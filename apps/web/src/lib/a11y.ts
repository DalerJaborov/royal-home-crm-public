import type { DraggableAttributes } from "@dnd-kit/core";

/**
 * Прокручиваемая вбок область (широкая таблица в `.tbl-wrap`).
 *
 * ЗАЧЕМ. `.tbl-wrap{overflow-x:auto}` прокручивается пальцем и колесом, но не
 * с клавиатуры: без `tabindex` в контейнер нельзя попасть, а значит содержимое
 * правее края экрана недостижимо вовсе — это WCAG 2.1.1 и axe
 * `scrollable-region-focusable`. `tabindex="0"` даёт остановку табуляции и
 * стрелки, `role="region"` с меткой объясняет диктору, куда человек попал
 * (без метки region не объявляется вообще и остановка выглядит пустой).
 *
 * Обёрток таких в приложении четырнадцать, поэтому набор атрибутов один на
 * всех: разъехаться им негде.
 */
export function scrollableRegion(label: string) {
  return { role: "region" as const, "aria-label": label, tabIndex: 0 };
}

/**
 * Доступные атрибуты перетаскиваемой карточки, внутри которой стоят кнопки.
 *
 * ЗАЧЕМ. `useDraggable().attributes` по умолчанию объявляет элемент
 * `role="button"` — это нужно ради клавиатурного перетаскивания: роль делает
 * элемент фокусируемым, и клавиатурный сенсор dnd-kit получает свои Space/Enter.
 * Но у ролей-кнопок не может быть фокусируемых потомков, а в карточках доски
 * сделок внутри лежат настоящие кнопки («вернуть на этап», «отменить»,
 * «продвинуть»). Итог — axe `nested-interactive`, 16 узлов на телефоне и 16 на
 * широком экране, и это не формальность: диктор объявляет карточку кнопкой и
 * прячет её содержимое как «подпись», то есть кнопок внутри для него нет вовсе.
 *
 * Кнопкой карточка при этом никогда и не была: с клавиатуры она ничего не
 * открывала (обработчика Enter у неё нет), роль стояла только ради
 * фокусируемости. Поэтому роль меняется на `group` — она разрешает
 * фокусируемых потомков, а `tabIndex` от dnd-kit остаётся, и клавиатурное
 * перетаскивание работает как работало.
 *
 * `aria-pressed` не переносится намеренно: он допустим только на кнопке, на
 * `group` это уже другое нарушение (`aria-allowed-attr`). dnd-kit ставит его
 * лишь на время перетаскивания, поэтому в покое проверка его и не видела —
 * ровно тот случай, когда починка одного правила молча заводит второе.
 *
 * `aria-roledescription` («перетаскиваемый») и `aria-describedby` (инструкция
 * для диктора) остаются: они и несут смысл, который давала роль кнопки.
 */
export function draggableGroupProps(attributes: DraggableAttributes) {
  return {
    role: "group" as const,
    tabIndex: attributes.tabIndex,
    "aria-disabled": attributes["aria-disabled"],
    "aria-roledescription": attributes["aria-roledescription"],
    "aria-describedby": attributes["aria-describedby"],
  };
}
