/**
 * Что сохранить из поля «Дата принятия объекта» (F11, 02.10.2026). Поле шлёт
 * запрос по уходу из него, а не на каждое изменение: при наборе года с
 * клавиатуры браузер отдаёт промежуточные даты (0002, 0020, 0202), и серия
 * запросов могла закончиться промежуточной. Сохраняем только правдоподобную
 * дату (год от 2000) и только если она отличается от уже сохранённой.
 * null — сохранять нечего.
 */
export function acceptedDateToSave(value: string, savedDayKey: string | null): string | null {
  const m = /^(\d{4})-\d{2}-\d{2}$/.exec(value);
  if (!m) return null;
  if (Number(m[1]) < 2000) return null;
  if (value === savedDayKey) return null;
  return value;
}
