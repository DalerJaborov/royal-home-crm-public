/**
 * СОСТОЯНИЕ ДАННЫХ ЭКРАНА ОДНИМ СЛОВОМ (17.11.2026, аудит интерфейса F2-1/F2-2).
 *
 * «Главная» агента писала «0 — на сегодня всё сделано», «Показов на сегодня нет»,
 * «Все дела сделаны», пока сводка ещё грузилась или если она не загрузилась
 * вовсе: каждый блок смотрел только на длину пустого массива `data?.x ?? []`.
 * Пустой массив из-за отказа сети и пустой массив «дел правда нет» выглядели
 * одинаково — и агент верил, что дел нет.
 *
 * Правило: тексты «всё сделано / пусто / нет» — только в состоянии "ready".
 *  - "ready"   — данные есть (в том числе прошлые, если фоновое обновление не
 *                удалось: TanStack держит прежние `data` и ставит `isError`);
 *  - "error"   — данных нет и запрос отказал: показать ошибку и «Повторить»;
 *  - "loading" — данных ещё нет (идёт загрузка или запрос пока выключен).
 */
export type ScreenState = "loading" | "error" | "ready";

export function screenState(query: { data: unknown; isError: boolean }): ScreenState {
  if (query.data !== undefined) return "ready";
  return query.isError ? "error" : "loading";
}
