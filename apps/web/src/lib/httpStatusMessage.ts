/**
 * ТЕКСТ ДЛЯ ЧЕЛОВЕКА ПО КОДУ ОТВЕТА СЕРВЕРА (ночная проверка 01.10.2026, №236).
 *
 * Раньше, когда сервер не прислал своего текста ошибки, на экране появлялось
 * «Ошибка запроса: 500» или «Ошибка 502» — цифра, по которой человек не может
 * понять, виноват ли он, сеть или сервер, и что делать. Здесь код превращается
 * в слова: чья это сторона и что можно сделать. Цифр в тексте нет.
 */
export function httpStatusMessage(status: number): string {
  if (status === 0) return "Нет связи с сервером. Проверьте интернет и повторите.";
  if (status === 401) return "Нужно войти заново.";
  if (status === 403) return "Недостаточно прав для этого действия.";
  if (status === 404) return "Не найдено — возможно, уже удалено.";
  if (status === 408 || status === 504) return "Сервер не ответил вовремя. Попробуйте ещё раз.";
  if (status === 409) return "Данные уже изменились. Обновите страницу и повторите.";
  if (status === 413) return "Файл слишком большой для отправки.";
  if (status === 429) return "Слишком много запросов подряд. Подождите немного.";
  if (status === 502 || status === 503) return "Сервер временно недоступен. Попробуйте через минуту.";
  if (status >= 500) return "Сбой на сервере. Попробуйте ещё раз чуть позже.";
  if (status >= 400) return "Сервер не принял запрос. Проверьте данные и повторите.";
  return "Не получилось. Попробуйте ещё раз.";
}
