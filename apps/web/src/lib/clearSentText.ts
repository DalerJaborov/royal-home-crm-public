/**
 * Что оставить в поле ввода после успешной отправки. Сервер мог отвечать
 * долго, а textarea всё это время редактируема: если агент уже набрал другой
 * текст, безусловный `setText("")` стирал его, хотя он не был отправлен.
 * Очищаем, только если поле всё ещё содержит ровно то, что ушло.
 */
export function clearIfUnchanged(current: string, sent: string): string {
  return current.trim() === sent ? "" : current;
}
