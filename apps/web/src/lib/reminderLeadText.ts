/**
 * За сколько до записи CRM напомнит агенту — для подписей в окнах.
 *
 * Подпись обязана совпадать с тем, что реально уходит (владелец 24.11.2026: окно
 * обещало «за 2 часа и за 40 минут», а приходит одно напоминание за 2 часа —
 * второе убрано 20.09.2026). Правило повторяет `stagesFor` из
 * apps/api/src/lib/meetingReminders.ts: показ и встреча — одно напоминание за
 * 2 часа, прочие задачи (звонок и т. п.) — за час. Меняется правило там —
 * меняется и здесь. Сторож — reminderLeadText.test.ts.
 */
export function reminderLeadText(type: string): string {
  return type === "SHOWING" || type === "MEETING" ? "за 2 часа" : "за час";
}
