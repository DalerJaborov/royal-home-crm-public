/**
 * Служебные подсказки модели, попавшие в переписку как слова клиента.
 *
 * ЗАЧЕМ. До 02.08.2026 подсказка про текущий ход («клиент ответил на нашу
 * историю — задай ОДИН вопрос…») дописывалась прямо в текст сообщения и уходила
 * в историю диалога. С тех пор она живёт отдельным полем и один ход
 * (см. turnHint в apps/api/src/messengers/conversation.ts), но СТАРЫЕ записи
 * остались в базе навсегда: 13.08.2026 в разделе «Сообщения» оператор всё ещё
 * видел вместо реплики человека абзац наших инструкций боту.
 *
 * Переписывать историю в базе нельзя — это то, что происходило на самом деле.
 * Поэтому прячем подсказки при показе.
 *
 * Список точный, а не «всё в квадратных скобках»: в переписке есть скобки,
 * которые оператору нужны, — «[🎤]», «[📎]», «[⛔ похоже на рассылку: … ]» и
 * описание присланного видео «[клиент прислал видео. Что там: …]». Их не трогаем.
 */
const HINT_OPENINGS = [
  "[клиент ответил на НАШУ историю",
  "[клиент переслал нашу публикацию",
  "[клиент прислал вложение, которое мы не умеем читать",
  "[клиент прислал геометку",
  "[клиент прислал контакт",
  "[клиент прислал видео —",
  "[клиент прислал файл.",
  "[клиент прислал документ.",
  "[клиент прислал стикер",
  "[в сообщении ссылка не на наш сайт",
];

/** Текст реплики клиента без служебных подсказок модели. */
export function stripBotHints(content: string): string {
  if (!content.includes("[")) return content;
  let out = content;
  for (const opening of HINT_OPENINGS) {
    let at = out.indexOf(opening);
    while (at !== -1) {
      const end = out.indexOf("]", at);
      if (end === -1) break;
      out = `${out.slice(0, at)}${out.slice(end + 1)}`;
      at = out.indexOf(opening);
    }
  }
  // Подсказка стояла отдельной строкой — убираем осиротевшие переводы строк.
  return out.replace(/\n{2,}/g, "\n").trim();
}

/**
 * ТЕХНИЧЕСКОЕ «[вложение: X]» — ПО-ЧЕЛОВЕЧЕСКИ (владелец 07.09.2026: «сделай так,
 * чтобы отображались template и так далее, чтобы агенты не думали три часа, что
 * это такое»).
 *
 * Строку пишет сервер (routes/webhooks.ts), когда у сообщения нет текста, а есть
 * вложение: в историю ложится `[вложение: image]`, `[вложение: template]` и т.п.
 * Тип приходит дословно от Meta и человеку не говорит ничего.
 *
 * Отдельный случай — `template`. Это НЕ вложение клиента: клиент такое отправить
 * физически не может. Это наша же карточка лид-магнита с кнопкой, вернувшаяся
 * эхом от Meta и записанная как реплика клиента (защита есть только в одной ветке
 * вебхука, см. разбор 07.09.2026). Показывать её как «вложение клиента» — врать,
 * поэтому у неё своя подпись.
 *
 * Правим ТОЛЬКО показ: в базе запись остаётся как есть — это то, что произошло на
 * самом деле, ровно та же причина, по которой не переписывается история в
 * stripBotHints выше.
 *
 * «НАША» — ТОЛЬКО У НАШЕЙ РЕПЛИКИ (25.09.2026). Клиент в Instagram всё-таки
 * прислал СВОЮ карточку с номером телефона — «клиент такое отправить не может»
 * оказалось неправдой, а подпись «наша карточка с кнопкой» у его реплики
 * убеждала агента, что клиент ничего не присылал. Поэтому по умолчанию подпись
 * нейтральная, а «наша» — только когда вызывающий знает, что реплика исходящая.
 */
const OWN_TEMPLATE_LABEL = "📋 наша карточка с кнопкой";
const ATTACHMENT_LABELS: Record<string, string> = {
  template: "📋 карточка",
  image: "🖼 фото",
  video: "🎬 видео",
  audio: "🎤 голосовое",
  file: "📎 файл",
  share: "🔗 пересланная публикация",
  story_mention: "📸 упоминание в истории",
  location: "📍 геометка",
  contact: "👤 контакт",
  sticker: "🙂 стикер",
  fallback: "📎 вложение",
};

/** `[вложение: image]` → `🖼 фото`. Неизвестный тип остаётся распознаваемым. */
export function humanizeAttachmentTags(content: string, opts: { outgoing?: boolean } = {}): string {
  if (!content.includes("[вложение:")) return content;
  return content.replace(/\[вложение:\s*([^\]]+)\]/g, (_all, rawType: string) => {
    const type = rawType.trim().toLowerCase();
    if (type === "template" && opts.outgoing) return OWN_TEMPLATE_LABEL;
    return ATTACHMENT_LABELS[type] ?? `📎 вложение (${type})`;
  });
}
