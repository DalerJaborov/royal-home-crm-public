function inside([lat, lng]: [number, number], ring: [number, number][]): boolean {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [yi, xi] = ring[i];
    const [yj, xj] = ring[j];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

describe("DISTRICT_COORDS — центр района лежит в своём районе", () => {
  for (const [name, center] of Object.entries(DISTRICT_COORDS)) {
    it(name, () => {
      const hits = Object.entries(BOUNDARIES)
        .filter(([, ring]) => inside(center, ring))
        .map(([n]) => n);
      expect(hits).toEqual([name]);
    });
  }

  it("все четыре района на месте", () => {
    expect(Object.keys(DISTRICT_COORDS).sort()).toEqual(Object.keys(BOUNDARIES).sort());
  });
});
