import { pluralizeRu } from "./format";

/**
 * Текст карточки «Горит сейчас» главной маркетолога, когда срочного объекта нет
 * (ни просрочки, ни ожидающих проверки). Раньше нет срочного читалось как «в
 * конвейере пусто», хотя плитки ниже показывали объекты на этапе фото, видео или
 * монтажа (FORMS09, аудит 04.10.2026). Один текст на обе главные: компьютерную и
 * мобильную.
 */
export function pipelineEmptyText(total: number | undefined): string {
  if (total && total > 0) {
    return `Срочного нет. В подготовке ${total} ${pluralizeRu(total, ["объект", "объекта", "объектов"])}, смотрите очередь ниже.`;
  }
  return "В конвейере подготовки пусто. Новые объекты появятся здесь сами.";
}
