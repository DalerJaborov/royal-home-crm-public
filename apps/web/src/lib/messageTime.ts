import { dushanbeTime } from "./date";

/**
 * Время сообщения в пузыре чата — ОДНО правило на три экрана (инбокс, чат на телефоне,
 * переписка в карточке клиента). Было три одинаковые копии, и все три писали под
 * пузырём без времени «Время сообщения неизвестно» — четыре строки на телефоне ради
 * того, чего нет (critic-uiux P1-14, пачка D1, 20.11.2026). Нет времени — пусто:
 * выдумывать его нельзя, а объяснять устройство системы агенту незачем.
 */
export function messageTimeText(at: string | null | undefined): string {
  return at ? dushanbeTime(at) : "";
}
