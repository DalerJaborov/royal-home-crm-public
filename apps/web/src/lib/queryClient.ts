import { MutationCache, QueryClient } from "@tanstack/react-query";
import { toast } from "../store/toast";
import { ApiError } from "./apiError";

/**
 * КОДЫ «СЕРВЕР СЕЙЧАС НЕ МОЖЕТ» — их повторяем, остальные нет.
 *
 * Зачем вообще (разбор 19.09.2026, жалоба владельца «то дашборд не грузится,
 * то чаты»). Выкат на проде пересоздаёт контейнеры, и на 20-40 секунд API не
 * отвечает вовсе. Умолчание react-query — три повтора с паузами 1/2/4 с, то
 * есть окно примерно в семь секунд: перезапуск в него не укладывается, запрос
 * окончательно падает, и экран показывает «не загрузилось» при живом сервере.
 * Здесь окно растянуто примерно до полуминуты — ровно на длину перезапуска.
 *
 * 429 в списке НЕТ намеренно. Общий лимитер (apps/api/src/app.ts) считает
 * запросы за пять минут, и повтор по нему — не спасение, а добавка к тому же
 * счётчику: четыре попытки вместо одной добивают окно до конца. Ответ отдаётся
 * экрану сразу, а экран показывает уже загруженные данные и текст сервера
 * («Слишком много запросов, подождите немного»), а не пустую ошибку.
 *
 * 4xx кроме перечисленных не повторяются никогда: 400/403/404 от повтора не
 * изменятся, а 401 обрабатывает сам lib/api.ts (обновляет токен и переспрашивает).
 */
const TRANSIENT_STATUSES = new Set([408, 425, 500, 502, 503, 504]);

/** Обрыв связи: fetch бросает TypeError, у которого нет ни статуса, ни тела.
 *  Экспортируется ради проверки в тестах — поведение тут важнее, чем кажется. */
export function isTransientFailure(error: unknown): boolean {
  if (error instanceof ApiError) return TRANSIENT_STATUSES.has(error.status);
  return error instanceof Error;
}

/**
 * ПОТОЛОК ПАУЗЫ ПЕРЕД ПОВТОРОМ 429 — 24.09.2026, ночная проверка (находка P1).
 *
 * `error.retryAfterMs` — это `Retry-After` сервера как есть, а он может быть
 * концом всего окна лимитера (у `brandingLimiter`, apps/api/src/routes/settings.ts,
 * окно 15 минут — то есть до 900 000 мс), а не «сколько ждать конкретно этому
 * запросу». Всё это время react-query держит запрос в статусе `pending`, и
 * экран честно крутит «Загружаем…», хотя это уже не загрузка, а долгая пауза
 * без единого слова пользователю. Дальше получаса ждать нет смысла: лучше
 * честная ошибка (`retryAfterMessage` в lib/api.ts уже формулирует её по-человечески),
 * чем бесконечная полоса загрузки.
 */
const MAX_429_RETRY_DELAY_MS = 30_000;

/** Вынесено отдельной функцией ради теста (`__tests__/retryDelay.test.ts`),
 *  как isTransientFailure выше. */
export function retryDelayFor(failureCount: number, error: unknown): number {
  if (error instanceof ApiError && error.status === 429) {
    return Math.min(error.retryAfterMs ?? 10_000, MAX_429_RETRY_DELAY_MS);
  }
  const base = Math.min(1_000 * 2 ** failureCount, 8_000);
  return base + Math.floor(Math.random() * base * 0.3);
}

// Single shared instance — imported by main.tsx (for QueryClientProvider) and
// by the auth store (to clear cached data on login/logout, see store/auth.ts).
//
// refetchInterval (история; глобальный интервал убран 06.10.2026, см. ниже): до этого в CRM ничего не обновлялось само (только смена фокуса
// вкладки или ручной F5) — новые сообщения/лиды/объекты не появлялись, пока
// кто-то не перезагрузит страницу. 25с — компромисс между «почти живым» видом
// и нагрузкой; только пока вкладка активна (refetchIntervalInBackground не
// включаем — свёрнутая/фоновая вкладка не должна долбить API).
//
// mutationCache: подтверждение «Сохранено» вешаем один раз здесь, а не на каждую
// мутацию отдельно. Половина действий в CRM сохраняется сама (перетащил сделку,
// поставил галочку, сменил статус), кнопки «Сохранить» там нет, и человек искал
// её глазами, не понимая, применилось ли изменение. Централизованный обработчик
// покрывает и те экраны, которые появятся потом.
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      // 12.09.2026: было 25 секунд на КАЖДЫЙ запрос в CRM. Живость горячих
      // мест (лиды, диалоги, сделки, уведомления, пульт) теперь держит поток
      // событий — lib/liveEvents.ts, — и общий таймер стал тем, чем должен
      // быть: страховкой. Не выключен совсем намеренно: экраны, которых поток
      // пока не касается (объекты, отчёты, звонки), обновляются только им.
      //
      // 06.10.2026 («CRM зависает»): общий refetchInterval УБРАН. Около 130
      // useQuery раз в минуту перезапрашивали всё открытое разом, хотя поток
      // событий уже инвалидирует clients, conversations, deals, notifications,
      // calls, properties, requests и mission-control, а полсотни хуков задают
      // свой интервал сами (useCalls, useActiveCall, useMissionControl,
      // useDashboard, useClients и др.). Экраны, которых не касается ни поток,
      // ни свой интервал (вакансии, безопасность, команда, телефония, отчёты,
      // финансы, архив), получили явный `refetchInterval: 120_000` в своём
      // хуке — страховка осталась, но реже и только там, где она нужна.
      // Новый хук без потока и без своего интервала сам не обновится: задавай
      // refetchInterval в хуке с комментарием «почему».
      // 22.09.2026: без staleTime КАЖДОЕ возвращение во вкладку (оператор
      // переключается CRM ↔ WhatsApp десятки раз в час) перезапрашивало все
      // открытые запросы разом — это и выбивало общий потолок API.
      // 06.10.2026: 20 → 30 секунд, по той же причине.
      staleTime: 30_000,
      // Повтор только того, что имеет смысл повторять (см. TRANSIENT_STATUSES).
      // 22.09.2026: 429 добавлен ОТДЕЛЬНОЙ веткой, не через TRANSIENT_STATUSES
      // (тот список остался как был) — ровно один повтор, не четыре: сервер
      // уже сказал, когда можно (retryAfterMs), тянуть его четыре раза подряд
      // незачем и добивало бы то же окно лимитера.
      retry: (failureCount, error) => {
        if (error instanceof ApiError && error.status === 429) return failureCount < 1;
        return isTransientFailure(error) && failureCount < 4;
      },
      // 1 → 2 → 4 → 8 секунд плюс разброс до 30%: без разброса полтора десятка
      // запросов одного экрана, упавших вместе на перезапуске, вместе же и
      // повторились бы — и добили бы только что поднявшийся API. Для 429 —
      // см. retryDelayFor и MAX_429_RETRY_DELAY_MS выше.
      retryDelay: retryDelayFor,
    },
  },
  mutationCache: new MutationCache({
    onSuccess: (_data, _vars, _ctx, mutation) => {
      // meta.silent — для мутаций со своей заметной обратной связью (форма
      // закрылась, экран сменился) или для служебных, вроде отметки «прочитано»:
      // там всплывающее «Сохранено» было бы шумом.
      const meta = mutation.meta as { silent?: boolean; successText?: string } | undefined;
      if (meta?.silent) return;
      toast.success(meta?.successText ?? "Сохранено");
    },
    onError: (error, _vars, _ctx, mutation) => {
      const meta = mutation.meta as { silent?: boolean } | undefined;
      if (meta?.silent) return;
      // Текст ошибки от API информативный (ApiError несёт сообщение сервера),
      // поэтому показываем его как есть, а не «что-то пошло не так».
      toast.error(error instanceof Error ? error.message : "Не удалось сохранить");
    },
  }),
});
