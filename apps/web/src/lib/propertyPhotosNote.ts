/**
 * Подпись над фотографиями в форме объекта (находка №185). Число берётся из
 * общей константы MIN_PROPERTY_PHOTOS: текст «не меньше шести» остался от старого
 * правила, а с 19.09.2026 достаточно одной фотографии.
 */
export function propertyPhotosNote(min: number): string {
  const need = min <= 1 ? "Нужна хотя бы одна фотография" : `Нужно не меньше ${min} фото`;
  return `${need}, иначе объект не пройдёт проверку. Первое фото главное.`;
}
