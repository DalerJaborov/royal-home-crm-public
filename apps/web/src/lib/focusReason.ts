import { dushanbeTime } from "./date";
import { daysSince, pluralizeRu } from "./format";
import type { Interaction } from "../types";

/**
 * Причина фокуса — единственное, что осталось от прежней карточки «Сначала
 * сделайте это».
 *
 * Сама карточка (компонент MobileFocusCard) и её классы кнопок
 * FOCUS_PRIMARY_BTN/FOCUS_SECONDARY_BTN сняты 09.09.2026 при добивании хвостов
 * старой разметки: обе Главные — MobileHome.tsx (агент) и Dashboard.tsx
 * (руководство) — при переносе на тему «Royal Home 2026» нарисовали фокус
 * блоками эталона у себя, а из этого файла продолжали брать только
 * `focusReason`. Компонент с 22.08.2026 не рендерился нигде: пятнадцать старых
 * утилитарных классов внутри жили в коде, который никто не открывал, и перенос
 * их на классы макета улучшил бы только счёт аудита, а не экран.
 *
 * Ключ localStorage закрытой карточки (FOCUS_DISMISSED_KEY) снят по той же
 * причине — им никто не пользовался: MobileHome держит признак в состоянии
 * компонента.
 *
 * ФАЙЛ ПЕРЕЕХАЛ СЮДА ИЗ components/mobile/MobileFocusCard.tsx (22.09.2026):
 * компонента в нём давно нет, а `focusReason` зовут ОБЕ Главные — и телефонная
 * (телефонная, слита в home/AgentHome.tsx 06.10.2026), и десктопная. Общая
 * формулировка, лежащая в папке телефона, читается как телефонная и рискует
 * разойтись ровно так, как расходились Oversight и MobileOversight.
 */

/**
 * Почему эта задача важнее остальных — сервер не присылает готовую формулировку
 * (нет такого поля у Interaction), а в макете она есть у каждой карточки
 * «Сначала это». Собираем короткую причину из того, что уже известно: тип
 * задачи и то, сколько она ждёт. Не выдумка — те же данные, что видны в подписи
 * строки, просто в развёрнутом виде. Одна на обе Главные, чтобы формулировки у
 * агента и у руководства не разошлись.
 */
export function focusReason(task: Interaction): string {
  if (task.type === "SHOWING" || task.type === "MEETING") {
    return task.nextActionDate
      ? `Показ сегодня в ${dushanbeTime(task.nextActionDate)} — клиент уже ждёт подтверждения`
      : "Показ назначен — клиент ждёт подтверждения";
  }
  if (task.type === "CALL") {
    return "Обещали перезвонить — чем дольше тишина, тем выше риск, что клиент уйдёт к другому агентству";
  }
  /**
   * Здесь нужна именно ДЛИТЕЛЬНОСТЬ, а не отметка времени: фраза объясняет, почему
   * задача попала в фокус, и «висит без ответа 20.08 14:32» её ломает. Общее
   * правило «везде точная дата» (см. exactDateTime в lib/format.ts) касается
   * подписей-меток; в связном предложении про ожидание считать дни должна CRM, а
   * не человек — ровно та работа, ради снятия которой правило и вводилось.
   */
  const days = daysSince(task.createdAt);
  const waited = days === 0 ? "с сегодняшнего дня" : `${days} ${pluralizeRu(days, ["день", "дня", "дней"])}`;
  return `Задача висит без ответа ${waited} — дальше она станет просрочкой`;
}
