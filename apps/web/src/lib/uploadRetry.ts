/**
 * ОДНО РАСПИСАНИЕ ПОВТОРОВ ДЛЯ ЗАГРУЗОК ФАЙЛОВ (25.11.2026).
 *
 * Было две очереди с разными правилами: карточка объекта (lib/uploadQueue.ts) —
 * 10 попыток, паузы 5 с … 5 мин, около 25 минут повторов; мастер нового объекта
 * (lib/draftUploads.ts) — 6 попыток, паузы 4 с … 60 с, сдавался через ~2 минуты.
 * Живой случай 23.11 (журнал ошибок, IMG_0461.mov 45,7 МБ и IMG_0452.mov 55,5 МБ):
 * мастер «сдался» на 6/6 и попросил нажать «Повторить», хотя части продолжали
 * уходить. Модуль без зависимостей — его зовут обе очереди и PropertyVideoFixCard.
 */

/** Пауза перед повтором: 5 с, 10 с, 20 с… но не длиннее пяти минут. */
export function retryDelayMs(attempts: number): number {
  return Math.min(5_000 * 2 ** Math.max(0, attempts - 1), 5 * 60_000);
}

/**
 * Потолок автоматических попыток для «повторяемого» отказа (обрыв, 5xx, 429).
 * 10 попыток — ~25 минут повторов с нарастающей паузой: с запасом покрывает
 * выкат (API недоступен ~10–15 с, замер 23.11 17:19:10–17:19:22 UTC) и сбой сети.
 * Подробный разбор — у MAX_RETRY_ATTEMPTS в lib/uploadQueue.ts (17.09.2026).
 */
export const MAX_RETRY_ATTEMPTS = 10;

/**
 * Что делать после повторяемого отказа сервера. Чистая функция.
 *
 * `progressed` — за этот заход сервер принял хоть одну часть ролика. Тогда счёт
 * начинается заново: попытки считают отказы ПОДРЯД БЕЗ ПРОДВИЖЕНИЯ, а не все
 * отказы за жизнь файла. Иначе ролик, у которого части уходят через раз (слабый
 * канал, 23.11: части 2→3→4 уходили между отказами), исчерпывал попытки, хотя
 * загрузка шла вперёд.
 *
 * `delayMs: null` — попытки кончились, ждём человека (кнопка «Повторить»).
 */
export function planServerRetry(prevAttempts: number, progressed: boolean): { attempts: number; delayMs: number | null } {
  const attempts = (progressed ? 0 : prevAttempts) + 1;
  return { attempts, delayMs: attempts < MAX_RETRY_ATTEMPTS ? retryDelayMs(attempts) : null };
}
