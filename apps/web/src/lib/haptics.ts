/**
 * Вибро-отклик — короткий ответ телефона на то, что действие принято.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ. В мобильном приложении палец получает подтверждение раньше,
 * чем глаз успевает прочитать экран: нажал — щёлкнуло — значит сработало. Без него
 * человек на секунду задерживается взглядом, проверяя, не зря ли нажал, и именно
 * эта задержка складывается в ощущение «сайт, а не приложение».
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Отклик уже был — но ровно в одном месте (переключение
 * вкладок нижнего меню) и своей функцией на четыре строки. Стоит добавить второе
 * место, и длительности начнут расходиться: где-то 8 мс, где-то 30, и вибрация из
 * подтверждения превращается в шум. Здесь их ровно три, и других не будет.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Вибрации на каждое касание. Телефон, дрожащий от любого нажатия,
 * раздражает сильнее, чем молчащий, и его выключают в системных настройках вместе с
 * полезными откликами. Отклик даётся только на СОБЫТИЕ: переход, сохранение, отказ.
 *
 * IPHONE. Safari `navigator.vibrate` не поддерживает вовсе — вызов просто вернёт
 * false, и ничего не произойдёт. Это не поломка и не повод писать обходной путь:
 * на iOS тактильный отклик доступен только настоящим приложениям.
 */

/** Есть ли вибромотор и разрешён ли он. */
function canVibrate(): boolean {
  return typeof navigator !== "undefined" && typeof navigator.vibrate === "function";
}

/**
 * Лёгкий щелчок: переключение вкладки, выбор в списке, раскрытие строки.
 * 8 мс — на границе ощущения: чувствуется как «щёлкнуло», а не как звонок.
 */
export function hapticTap(): void {
  if (canVibrate()) navigator.vibrate(8);
}

/**
 * Действие удалось: запись сохранена, лид принят, показ назначен.
 * Чуть длиннее щелчка, чтобы отличаться от него на ощупь, но всё ещё один импульс.
 */
export function hapticSuccess(): void {
  if (canVibrate()) navigator.vibrate(18);
}

/**
 * Не получилось: ошибка сохранения, отказ сервера.
 * Двойной короткий — единственный узнаваемый «отрицательный» рисунок, который
 * различается на ощупь без обучения. Пауза 60 мс: короче — сливается в один
 * импульс, длиннее — читается как две отдельные вибрации.
 */
export function hapticError(): void {
  if (canVibrate()) navigator.vibrate([14, 60, 14]);
}
