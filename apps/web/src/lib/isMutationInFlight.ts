import type { QueryClient } from "@tanstack/react-query";

/**
 * Второй, независимый сигнал «занят» рядом с isUserActivelyTyping.ts (ввод,
 * модалка, несохранённая форма, незавершённая загрузка файла).
 *
 * ЗАЧЕМ ОТДЕЛЬНО. Оптимистичная мутация (например, приём лида — useAcceptLead
 * в hooks/useClients.ts) не оставляет следа ни в одном из тех четырёх сигналов:
 * поле ввода тут ни при чём, а окно, из которого действие начато
 * (IncomingLeadWindow), может быть в этот момент свёрнуто — в свёрнутом виде
 * оно намеренно снимает `aria-modal` ради доступности (это верно для a11y и
 * трогать это не нужно), но тем самым и не совпадает с селектором диалога в
 * isUserActivelyTyping(). Раньше это означало: принудительное обновление PWA
 * (store/appUpdate.ts, lib/appUpdateReload.ts) могло сработать прямо посреди
 * такой мутации. `location.reload()`/жёсткий переход обрывает fetch БЕЗ
 * TypeError, поэтому `queueOffline` (lib/api.ts) его не подхватывает — принятый
 * лид просто исчезает без ошибки и без записи в офлайн-очередь.
 *
 * Проверяем через MutationCache напрямую (`client.isMutating()`), а не через
 * DOM: это единственный сигнал, который не зависит от того, свёрнуто ли окно,
 * из которого мутация запущена, и от того, какой компонент её вызвал.
 *
 * Принимает клиент параметром, а не тянет синглтон lib/queryClient.ts — тот же
 * приём, что и вынесение isUserActivelyTyping в свой модуль: тест строит свой
 * лёгкий QueryClient и не тащит toast/приложение целиком.
 */
export function isMutationInFlight(client: QueryClient): boolean {
  return client.isMutating() > 0;
}
