// Примерные координаты центров районов Душанбе — точка старта для карты, когда точный
// адрес объекта ещё не геокодирован. Используется и в общей карте объектов
// (PropertyMapView), и в выборе точки при создании/редактировании (LocationPicker).
//
// Точки взяты из справочника районов (`.data-geo/районы.json`, поля «Широта» и
// «Долгота»), каждая лежит внутри своей границы. До 28.09.2026 тут стояли точки
// «на глаз», и ни одна не попадала в свой район: «центр» Сино лежал в Исмоили
// Сомони, Шохмансура — в Фирдавси. Мастер объекта по ним подставлял район
// соседа, а метка желаемого места покупателя вставала в чужой район.
// Проверка — `lib/__tests__/districtCoords.test.ts`.
export const DISTRICT_COORDS: Record<string, [number, number]> = {
  Сино: [38.588, 68.748],
  "Исмоили Сомони": [38.636, 68.783],
  Фирдавси: [38.505, 68.752],
  Шохмансур: [38.546, 68.836],
};

export const CITY_CENTER: [number, number] = [38.5598, 68.787];

/** Центр района по имени, либо центр Душанбе, если район не в таблице. */
export function districtCenter(districtName?: string): [number, number] {
  return (districtName && DISTRICT_COORDS[districtName]) || CITY_CENTER;
}
