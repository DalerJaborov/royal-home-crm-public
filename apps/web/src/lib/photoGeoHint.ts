/**
 * ПОЧЕМУ ТОЧКА ПО ФОТО НЕ ПОЯВИЛАСЬ (владелец 27.11.2026, живой кадр с iPhone:
 * «геолокация не была определена» — и мастер молчал, агент не знал, что делать).
 *
 * Разбор снимка идёт в браузере по ИСХОДНОМУ файлу (lib/mediaGps.ts), ДО сжатия, так
 * что сжатие точку не теряет. Теряет её сам телефон: iPhone и Android отдают сайту
 * файл из «Фото» с уже вырезанной геометкой, если у браузера нет права на геопозицию
 * в «Фото». Ни код сайта, ни сервер вернуть её не могут — остаётся сказать агенту,
 * что произошло и как поставить точку.
 */
export interface PhotoGeoStatus {
  /** Снимки, разбор которых ещё идёт. */
  pending: number;
  /** Сколько снимков уже разобрано. */
  checked: number;
  /** Из них — с точкой внутри Душанбе. */
  found: number;
  /** Из них — с точкой за пределами Душанбе. */
  outside: number;
}

export const EMPTY_PHOTO_GEO_STATUS: PhotoGeoStatus = { pending: 0, checked: 0, found: 0, outside: 0 };

/** Текст под картой на шаге «Где»; null — подсказка не нужна. */
export function photoGeoHint(status: PhotoGeoStatus): string | null {
  if (status.pending > 0 || status.checked === 0 || status.found > 0) return null;
  if (status.outside > 0) {
    return "Фото снято не в Душанбе, поэтому точку по нему не ставлю. Найдите адрес в строке поиска или подвиньте карту.";
  }
  return "В выбранных фото нет геометки: телефон вырезает её, когда фото берут из галереи. Найдите адрес в строке поиска, подвиньте карту или нажмите «Определить мою позицию», если вы сейчас у объекта.";
}
