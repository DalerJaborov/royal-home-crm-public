/**
 * «Действует только последний запрос» — счётчик для разовых запросов по вводу
 * человека, где ответы могут прийти не в том порядке, в каком ушли (24.09.2026,
 * поиск на карте объектов, pages/PropertiesMap.tsx).
 *
 * Там было две гонки: поздний ответ «Найти» по старому слову переставлял метку
 * поиска поверх уже выбранной подсказки, а подсказки, запрошенные до отправки,
 * приходили после неё и снова раскрывали только что закрытый список. Каждый
 * запрос берёт номер `next()`, ответ применяется только если `isLatest(номер)`;
 * `invalidate()` обесценивает всё, что уже в пути, не заводя нового запроса.
 */
export function createLatestRequest() {
  let current = 0;
  return {
    next(): number {
      current += 1;
      return current;
    },
    isLatest(id: number): boolean {
      return id === current;
    },
    invalidate(): void {
      current += 1;
    },
  };
}
