/**
 * «Приложение обновлено» — тихая строка ПОСЛЕ подмены сборки.
 *
 * Полноэкранный экран обновления убран (владелец 10.09.2026): обновление
 * происходит молча, а человек узнаёт о нём постфактум одной строкой на две-три
 * секунды. Значит нужно пережить перезагрузку: перед подменой оставляем метку с
 * версией, из которой уходим, а новая сборка при старте её забирает.
 *
 * sessionStorage, а не localStorage: метка касается ровно этой вкладки и ровно
 * этой перезагрузки. localStorage показал бы строку и в соседней вкладке, и
 * завтра утром.
 *
 * Версия в метке нужна, чтобы отличить состоявшееся обновление от несостоявшегося:
 * если подмена не сработала (лестница попыток в appUpdateReload.ts сдалась) и
 * вкладка осталась на той же сборке, строки быть не должно — сообщать не о чем.
 */
const KEY = "rh:updated-from";

/** Вызывается прямо перед подменой: запомнить, из какой сборки уходим. */
export function markUpdateApplied(fromVersion: string): void {
  try {
    sessionStorage.setItem(KEY, fromVersion);
  } catch {
    // приватный режим/переполненное хранилище — обновление важнее строки о нём
  }
}

/**
 * Вызывается один раз при старте вкладки. Возвращает true, если обновление
 * действительно состоялось (метка есть и версия сборки сменилась) — тогда
 * показываем строку. Метку снимает в любом случае: несостоявшееся обновление
 * не должно всплыть строкой через час.
 */
export function consumeUpdateNotice(currentVersion: string): boolean {
  let from: string | null = null;
  try {
    from = sessionStorage.getItem(KEY);
    if (from !== null) sessionStorage.removeItem(KEY);
  } catch {
    return false;
  }
  return from !== null && from !== currentVersion;
}
