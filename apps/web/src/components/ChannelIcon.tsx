/** Каналы, у которых здесь есть свой знак. Всё остальное не рисуется вовсе. */
const GLYPHS = new Set([
  "INSTAGRAM",
  "WHATSAPP",
  "TELEGRAM",
  "FACEBOOK",
  "MESSENGER",
  "VIBER",
  "VK",
  "SITE",
  "PHONE",
  "YOUTUBE",
  "TIKTOK",
  "THREADS",
]);

/**
 * Как называется канал у нас — по значению с сервера. Сайт и телефон каналами
 * переписки не являются (это источники клиента), поэтому подпись для них своя.
 */
function labelOf(channel: string): string {
  if (channel === "SITE") return "Сайт";
  if (channel === "PHONE") return "Телефон";
  if (channel === "MESSENGER") return "Messenger";
  // YouTube/TikTok — каналы публикации роликов, не переписки: channelMeta их не
  // знает вовсе (её словарь — только мессенджеры) и отдала бы «Youtube»/«Tiktok»
  // через безопасный, но неточный автоматический разбор незнакомого значения.
  if (channel === "YOUTUBE") return "YouTube";
  if (channel === "TIKTOK") return "TikTok";
  if (channel === "THREADS") return "Threads";
  return channelMeta(channel).label;
}

/**
 * Есть ли у канала свой знак. Нужен вызывающим: уголок аватара — это белый
 * кружок ПОД значком, и без проверки он рисовался бы пустым там, где канал
 * скрыт правом `clients.viewOrigin` или просто неизвестен.
 */
export function hasChannelGlyph(channel: string | null | undefined): boolean {
  return GLYPHS.has((channel ?? "").toUpperCase());
}

/**
 * Источник клиента (ClientSource) → знак канала. Совпадающие имена берутся как
 * есть, сайт и звонок — свои знаки. Источники без своего знака (TikTok, реклама,
 * рекомендация, «пришёл в офис») возвращают null: у них нет узнаваемого силуэта,
 * и подписи в строке достаточно — рисовать вместо них универсальный кружок
 * значило бы обещать канал переписки, которого нет.
 */
export function sourceChannel(source: string | null | undefined): string | null {
  switch (source) {
    case "WEBSITE":
      return "SITE";
    case "PHONE_CALL":
      return "PHONE";
    case "INSTAGRAM":
    case "FACEBOOK":
    case "WHATSAPP":
    case "TELEGRAM":
      return source;
    default:
      return null;
  }
}

export function ChannelIcon({
  channel,
  size = 12,
  tone = "brand",
  className,
  title,
}: {
  /** Значение канала с сервера (INSTAGRAM/WHATSAPP/…) либо «SITE»/«PHONE». */
  channel: string | null | undefined;
  size?: number;
  tone?: ChannelIconTone;
  className?: string;
  /** Подпись для наведения; по умолчанию — название канала. */
  title?: string;
}) {
  const key = (channel ?? "").toUpperCase();
  /**
   * НЕИЗВЕСТНЫЙ КАНАЛ — НЕ РИСУЕМ НИЧЕГО.
   *
   * Не мелочь: у роли без права `clients.viewOrigin` сервер обнуляет и
   * `Client.source`, и `BotConversation.channel` (lib/clientOrigin.ts, решение
   * владельца 17.08 — по каналу клиента находят в обход агентства). Пока здесь
   * стоял запасной знак «телефон», агент видел в уголке каждого аватара
   * телефонную трубку — утверждение «пришёл звонком» там, где канал как раз
   * СКРЫТ. Выдуманный факт выглядит убедительнее пустоты, поэтому пусто.
   */
  if (!GLYPHS.has(key)) return null;
  const label = title ?? labelOf(key);
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      className={className}
      role="img"
      aria-label={`Канал: ${label}`}
      style={{ color: tone === "brand" ? (BRAND[key] ?? "currentColor") : "currentColor", flex: "none" }}
      fill="currentColor"
    >
      <title>{label}</title>
      <Glyph channel={key} />
    </svg>
  );
}
