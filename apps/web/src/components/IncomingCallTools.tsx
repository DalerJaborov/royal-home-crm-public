import { useBlockCaller } from "../hooks/useCalls";

/**
 * Инструменты журнала входящих. Жили внутри pages/Calls.tsx; вынесены при
 * мобильном редизайне 17.08.2026: их делят десктопный журнал и мобильный экран
 * «Звонки» (components/mobile/MobileCalls.tsx), а импорт страницы из компонента
 * дал бы цикл.
 *
 * 18.08.2026 отсюда удалён разбор звонка руками (QualifyIncomingForm): владелец
 * отменил роль оператора входящих целиком — звонки уходят прямо агентам, а тип
 * обращения и карточка заводятся автоматически из расшифровки разговора.
 * «Больше не звонить» осталось: оно про чёрный список станции, а не про разбор,
 * и одинаково нужно при любом устройстве приёма звонков.
 */

/**
 * «БОЛЬШЕ НЕ ЗВОНИТЬ» — реклама, автообзвон, ошиблись номером.
 *
 * Отбивает звонок сама станция, ещё до того как телефон оператора зазвонил: пометка
 * «не по делу» в CRM этого не умеет, человек всё равно снимает трубку.
 *
 * ЗНАКОМОМУ КЛИЕНТУ КНОПКИ НЕТ. Заблокировать номер из карточки — это отрезать
 * агентство от собственного клиента одним нажатием, причём молча: он будет звонить
 * и слышать сброс, а в CRM не появится ничего. Спам приходит с номеров, которых в
 * базе нет; для настойчивого «клиента» есть Корзина и пометка «не по делу».
 *
 * ПОДТВЕРЖДЕНИЕ ОБЯЗАТЕЛЬНО. Действие происходит на станции и из интерфейса не
 * видно: посмотреть, кто в чёрном списке, можно только на самой АТС. Случайное
 * нажатие означало бы потерянные звонки, которые никто не свяжет с этой кнопкой.
 */
export function BlockCallerButton({ callId, known }: { callId: string; known: boolean }) {
  const block = useBlockCaller();
  if (known) return null;
  return (
    <button
      type="button"
      onClick={() => {
        if (!window.confirm("Станция будет отбивать звонки с этого номера. Продолжить?")) return;
        block.mutate({ callId, blocked: true });
      }}
      disabled={block.isPending || block.isSuccess}
      title="Станция перестанет пропускать звонки с этого номера"
      // Кнопка живёт только в журналах входящих (десктопном и мобильном), а оба
      // переведены на эталон «Royal Home 2026» — отсюда прототипный `.pill`.
      className="pill ghost sm"
    >
      {block.isSuccess ? "Заблокирован" : block.isPending ? "Блокирую…" : "Больше не звонить"}
    </button>
  );
}
