import { useCan } from "../lib/permissions";
import { ScreenTabs, type ScreenTab } from "./ScreenTabs";

/**
 * ВТОРАЯ ЛЕНТА РАЗДЕЛА КЛИЕНТОВ — состояние внутри вида (21.09.2026).
 *
 * Владелец: «должно быть всего 2 раздела — Продавцы, Покупатели, — а когда в
 * них заходишь, потом уже неактивные, потерянные».
 *
 * Верхний уровень (ClientsTabs) отвечает на вопрос «кто это»: продавец или
 * покупатель. Здесь — «в каком он состоянии»: в работе, неактивен, потерян.
 * До этого состояния стояли вкладками ВЕРХНЕГО уровня, рядом с видами, и
 * читались как ещё три вида людей; продавцы и покупатели при этом лежали в них
 * вперемешку, потому что срез по виду там не передавался вовсе.
 *
 * ПОЧЕМУ СЕКЦИЯ ЕДЕТ ПАРАМЕТРОМ АДРЕСА, А НЕ СОСТОЯНИЕМ. «Неактивные» и
 * «Потерянные» — отдельные маршруты (/inactive-clients, /lost-clients), и без
 * `?kind=` они не знали бы, из какого раздела в них вошли: вернувшись на
 * «Продавцов», человек попадал бы к покупателям. Параметр же делает адрес
 * пригодным для закладки и для ссылки в уведомлении.
 *
 * ПОЧЕМУ БЕЗ СЧЁТЧИКОВ. `GET /clients/summary` отдаёт «неактивных» и
 * «потерянных» ОБЩИМ числом, без разбивки по виду. Показать это число у
 * «Продавцов» значило бы соврать; выдуманный ноль — тем более. Появится
 * разбивка в сводке — появятся и числа (тот же принцип, что в
 * mh/MhClientSections.tsx).
 *
 * «НЕ НА ВИДУ» — прежняя вкладка «Все мои» (18.09.2026, Р-2/Р-7
 * docs/audit/lead-ownership-17-09.md). Единственное место, где держатель без
 * `archive.view`/`clients.assign` находит свою карточку, молча уехавшую в
 * Корзину/OTHER/LOST. Видна только тому, у кого нет `clients.viewAll` — та же
 * граница, что у сервера (`scope=allMine`, routes/clients/list.ts); руководству
 * она ничего не добавляет. Название сменилось, потому что «Все мои» рядом с
 * «В работе» читалось как ещё один срез моих активных клиентов, а раздел про
 * ровно обратное — про то, чего в работе уже не видно.
 */
export type ClientsSection = "SELLER" | "BUYER";

export function ClientsSectionLane({ section }: { section: ClientsSection }) {
  const can = useCan();
  const inWork = section === "SELLER" ? "/sellers" : "/clients";
  const suffix = `?kind=${section}`;

  const tabs: ScreenTab[] = [
    { to: inWork, label: "В работе", end: section === "BUYER" },
    { to: `/inactive-clients${suffix}`, label: "Неактивные" },
    // Отложенные (23.09.2026): экран /deferred-clients существовал, но после
    // сокращения вкладок до двух на него не вела ни одна ссылка.
    { to: "/deferred-clients", label: "Отложенные" },
    { to: "/lead-funnel", label: "Воронка" },
    { to: `/lost-clients${suffix}`, label: "Потерянные", permission: "clients.assign" },
    { to: "/clients/all-mine", label: "Не на виду", when: !can("clients.viewAll") },
  ];

  /**
   * Подсветку ставит сам NavLink внутри ScreenTabs: у «Неактивных» и
   * «Потерянных» маршрут один на оба раздела, но в ленте каждого раздела такая
   * вкладка ровно одна — сравнивать `kind` руками не нужно, а из ДРУГОГО
   * раздела сюда просто не попасть, его лента ведёт на свой адрес.
   */
  return <ScreenTabs tabs={tabs} />;
}
