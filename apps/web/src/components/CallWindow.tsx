/**
 * ОКНО ЗВОНКА — ТОЛЬКО ИСХОДЯЩИЙ.
 *
 * До 15.08.2026 звонок в CRM показывался ТРЕМЯ независимыми плавающими панелями
 * сразу: `ActiveCallBar` (исходящий, по опросу АТС), `OperatorCallPanel` (входящий
 * с разбором обращения) и `BrowserPhoneBar` (кнопки трубки по своей SIP-сессии в
 * браузере). Их свели в одно окно — у одного разговора должен быть один источник
 * правды, иначе сброс трубки гасил и тут же зажигал карточку заново.
 *
 * 18.08.2026 механизм ужался ещё раз, по решению владельца: роль оператора
 * входящих отменена целиком, звонки уходят прямо агентам, а карточка заводится
 * автоматически из расшифровки разговора — человек в разборе больше не участвует.
 * Вместе с оператором ушла и браузерная трубка (WebRTC): она существовала ради
 * рабочего места оператора, а агенты и так говорят с обычного мобильного, куда
 * их дозванивает станция. Отдельная причина — фоновый опрос входящего звонка раз
 * в секунду в КАЖДОЙ открытой вкладке (включая фоновые): у владельца от него
 * подвисал браузер, дословно «чтобы даже фоново ничего не работало».
 *
 * Поэтому здесь остался ровно один случай: агент нажал «Позвонить», станция
 * дозванивается ему и клиенту, и окно показывает, на каком это шаге. Всё, что
 * жило вокруг живой SIP-сессии (ответить/сбросить/микрофон/громкая связь/
 * удержание/перевод/тональный набор/заметка в разговоре/«продолжить на моём
 * телефоне»), удалено вместе с самой трубкой — управлять из браузера нечем.
 *
 * ОБЛИК — ЭТАЛОН «ROYAL HOME 2026» (перенос 09.09.2026). Разметка и имена
 * классов взяты дословно из `docs/pult/theme-2026/screens/call-window-v2.html`
 * (ветка `docs/pult-theme-07-09`): шторка `.cw2` справа, шапка `.cw2-h`, тело
 * `.cw2-body` с аватаром `.cw2-av`, состояние `.cw2-state`, таймер `.cw2-timer`,
 * ряд `.cw2-controls` и тихая строка `.cw2-quiet`. Ни одна проверка и ни один
 * запрос не тронуты: поменялась только одёжка.
 *
 * ЧЕГО ИЗ МАКЕТА ЗДЕСЬ НЕТ И ПОЧЕМУ:
 *  · «Пауза / Динамик / Клавиатура» — в макете они помечены декоративными
 *    («браузер вызовом не управляет»), и сам макет выносит это вопросом
 *    владельцу. Три кнопки, которые нажимаются и ничего не делают, в рабочем
 *    интерфейсе — обман, поэтому они не перенесены до ответа владельца.
 *  · «Итог звонка» (`.cw2-outcome`, четыре исхода) — это окно владелец отменил
 *    18.08.2026 («никаких окон не надо»), PendingSummaryBanner их больше не
 *    рисует. Возвращать отменённое поверх переноса облика нельзя.
 *
 * ЧЕГО В МАКЕТЕ НЕТ, А ЗДЕСЬ ЕСТЬ (12.09.2026): крестик «закрыть» в шапке и
 * трёхсекундный отсчёт до самозакрытия после любого конца разговора. В макете
 * окно гасло само по событию станции; в жизни оно висело до сорока с лишним
 * секунд, и владелец назвал это «после отмены звонка карточка звонка долго
 * висит». Подробности — у `AUTO_CLOSE_MS` ниже.
 */
/**
 * СКОЛЬКО ОКНО ЖИВЁТ ПОСЛЕ КОНЦА ЗВОНКА — три секунды, любым исходом.
 *
 * Владелец 12.09.2026: «после отмены звонка карточка звонка долго висит,
 * возможно все такие». Это была правда, и виновата не одна причина, а три
 * подряд, каждая сама по себе разумная:
 *  1. сервер держит завершённый звонок в памяти 20 секунд, чтобы экран успел
 *     показать итог (KEEP_ENDED_MS в lib/telephony/callTracker.ts);
 *  2. опрос `/me/active-call` в состоянии «завершён» замедляется до 15 секунд,
 *     чтобы не дёргать сервер попусту (hooks/useActiveCall.ts);
 *  3. и только потом окно ещё семь секунд «догорало» здесь.
 * В сумме до сорока с лишним секунд шторки поверх работы после того, как агент
 * сам нажал «Отменить» — он уже знает, чем кончилось, а окно всё висит.
 *
 * Сервер и опрос трогать незачем: 20 секунд в памяти нужны на случай, если
 * вкладку открыли позже, а редкий опрос экономит запросы. Закрывать окно —
 * работа самого окна, и она не должна зависеть от того, когда сервер забудет
 * звонок: `ended` видно через секунду после отбоя (опрос идёт раз в секунду,
 * пока звонок жив), отсюда и отсчёт.
 */
const AUTO_CLOSE_MS = 3_000;

/**
 * Сколько окно ещё показывает итог, если запись АТС пропала, а состояния
 * «завершён» экран так и не увидел (вкладка спала, сервер перезапустился).
 * Тот же срок, что и у обычного исхода: иначе один и тот же конец разговора
 * гаснет то за три секунды, то за семь.
 */
const LINGER_MS = AUTO_CLOSE_MS;

/** Хвост тихой строки на всех завершённых исходах: человек должен понимать, что
 *  окно уходит само, а не ждать от него действия. Одной константой, чтобы четыре
 *  исхода не разъехались в формулировке. */
const CLOSES_ITSELF = "Окно закроется само через три секунды.";

/**
 * Держит последнее непустое значение ещё `LINGER_MS` после того, как источник
 * стал пустым — но НОВОЕ значение перекрывает паузу мгновенно (следующий звонок
 * не должен ждать, пока погаснет итог предыдущего).
 */
function useLingering<T>(value: T | null | undefined): T | null {
  const [snapshot, setSnapshot] = useState<T | null>(value ?? null);
  const timerRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  useEffect(() => {
    if (value) {
      if (timerRef.current) {
        clearTimeout(timerRef.current);
        timerRef.current = null;
      }
      setSnapshot(value);
      return;
    }
    setSnapshot((prev) => {
      if (prev == null) return prev;
      timerRef.current = setTimeout(() => setSnapshot(null), LINGER_MS);
      return prev;
    });
    return () => {
      if (timerRef.current) clearTimeout(timerRef.current);
    };
  }, [value]);

  return snapshot;
}

export function CallWindow() {
  const { data: outgoingLive } = useActiveCall();
  const outgoing = useLingering(outgoingLive);

  /**
   * Какой звонок уже закрыт на этом экране — по каналу, а не флагом «закрыто».
   *
   * Флаг пришлось бы снимать, и снимать его было бы нечем: следующий звонок
   * приходит тем же полем того же запроса. Ключ канала решает это сам собой —
   * у нового звонка он другой, и окно открывается чистым, даже если предыдущее
   * закрыли за секунду до этого.
   */
  const [closedChannelId, setClosedChannelId] = useState<string | null>(null);

  const channelId = outgoing?.channelId ?? null;
  const ended = outgoing?.state === "ended";

  /**
   * ОКНО ГАСНЕТ САМО ЧЕРЕЗ ТРИ СЕКУНДЫ ПОСЛЕ ЛЮБОГО КОНЦА.
   *
   * Исходов четыре, и все они приходят одним состоянием `ended` (см.
   * finishCall в lib/telephony/callTracker.ts): клиент не ответил, агент отменил
   * до дозвона, разговор состоялся и завершён, станция уронила канал. Поэтому и
   * отсчёт один — разбирать их по отдельности значит завести четыре места, где
   * можно забыть пятое.
   *
   * Отказ станции на «Отменить» сюда не попадает: вызов в этом случае ПРОДОЛЖАЕТ
   * идти, состояние не `ended`, и окно обязано остаться — иначе агент решит, что
   * отменил, а клиент возьмёт трубку. Ошибка показывается тихой строкой внизу.
   */
  useEffect(() => {
    if (!channelId || !ended) return;
    const timer = setTimeout(() => setClosedChannelId(channelId), AUTO_CLOSE_MS);
    return () => clearTimeout(timer);
  }, [channelId, ended]);

  // key по каналу: следующий звонок получает чистое окно, а не остатки
  // состояния предыдущего (свёрнутость, текст ошибки отмены).
  if (outgoing && outgoing.channelId !== closedChannelId) {
    return (
      <OutgoingCard
        key={outgoing.channelId}
        call={outgoing}
        onClose={() => setClosedChannelId(outgoing.channelId)}
      />
    );
  }

  // В покое — ничего. Раньше здесь висела плавающая чёрная кнопка набора поверх
  // ВСЕХ мобильных экранов (DialTrigger, решение от 16.08.2026) — владелец
  // 17.08.2026 вечером увидел её на новой мобильной Главной и назвал лишней:
  // набрать номер «прямо сейчас» и так есть на «Телефонии» (тот же уровень
  // прав, calls.transcripts), а плавать над каждым экраном ей незачем.
  return null;
}

/** Шторка исходящего звонка — экран вызова обычного телефона, облик `.cw2`. */
function OutgoingCard({ call, onClose }: { call: ActiveCall; onClose: () => void }) {
  const cancel = useCancelActiveCall();
  // Свёрнутое окно — та же мысль, что у `.cw.min` в эталоне: полоска остаётся,
  // работать не мешает. Звонок при этом продолжается, как и обещает подпись.
  const [minimized, setMinimized] = useState(false);
  const talking = call.state === "talking";
  const ended = call.state === "ended";
  // Отмена — ОТДЕЛЬНЫЙ исход, не «недозвон»: агент сам передумал, клиент тут ни при
  // чём. Раньше отмена попадала в ту же ветку, что и «клиент не ответил», и тихая
  // строка под ней врала — писала «клиент не взял трубку», хотя решение принял
  // агент (docs/ui-audit-07-09-2026.md, п.4).
  const cancelled = ended && call.cancelled;
  const missed = ended && !call.answeredAt && !cancelled;
  const canCancel = !talking && !ended;

  const stateTone = talking ? "talk" : cancelled ? "end" : missed ? "missed" : ended ? "end" : "";
  // Итог с сервера (`outcome`: «Поговорили 1:12», «Вызов отменён», «Клиент не
  // ответил») сильнее общей подписи макета и раньше стоял в первой строке полосы —
  // он и остаётся текстом состояния, чтобы при переносе облика не потерять
  // единственное место, где станция объясняет, чем всё кончилось.
  const stateText = talking
    ? "Разговор"
    : cancelled
      ? (call.outcome ?? "Вызов отменён")
      : missed
        ? (call.outcome ?? "Не ответил")
        : ended
          ? (call.outcome ?? "Завершён · запись уже в хронологии")
          : "Набираем…";
  const endLabel = cancel.isPending
    ? "Отменяем…"
    : talking
      ? "Идёт разговор"
      : cancelled
        ? "Отменён"
        : missed
          ? "Не ответил"
          : ended
            ? "Завершён"
            : "Отменить";
  /**
   * Тихая строка. Отказ станции показывается здесь же и первым: раньше он
   * занимал вторую строку полосы, и потерять его при переносе облика значило бы
   * молча съесть единственное объяснение неудавшейся отмены.
   */
  const quiet = cancel.isError
    ? cancel.error.message
    : talking
      ? "Разговор идёт через офисную станцию на вашем рабочем телефоне, из браузера его не завершить."
      : cancelled
        ? // Честно про след в истории: если телефон клиента успел зазвонить, запись
          // осталась в хронологии карточки; если нет — станция звонок не заводила,
          // и запись удалена (решение владельца 13.08.2026, см. callTracker.ts).
          call.clientRang
            ? `Вы отменили вызов — телефон клиента уже звонил, это отмечено в истории карточки. ${CLOSES_ITSELF}`
            : `Вы отменили вызов до того, как телефон клиента зазвонил. Следа в истории карточки не осталось. ${CLOSES_ITSELF}`
        : missed
          ? `Клиент не взял трубку. Исход зафиксирован сам, разговор уже в хронологии карточки. ${CLOSES_ITSELF}`
          : ended
            ? `Запись и разбор появятся в карточке клиента. ${CLOSES_ITSELF}`
            : `Станция звонит вам на ${call.dialingTo}, поднимите трубку. Окно можно свернуть, звонок продолжится.`;

  return (
    <Rh2Inline>
      <div className="cw2-stage live">
        <section
          className={`cw2${minimized ? " min" : ""}`}
          role="status"
          aria-live="polite"
          aria-label="Звонок клиенту"
        >
          <div className="cw2-h">
            <div>
              <b>{talking ? `Разговор с ${call.clientName}` : `Звонок клиенту: ${call.clientName}`}</b>
              <span>Карточка №{call.clientShortId}</span>
            </div>
            {/* Две кнопки в общей обёртке, а не подряд: `.cw2-h .close` несёт
                `margin-left:auto`, и у двух соседей подряд свободное место
                поделилось бы между ними — в шапке появилась бы дыра. */}
            <div style={{ marginLeft: "auto", display: "flex", gap: 8 }}>
              <button
                type="button"
                className="close"
                onClick={() => setMinimized((v) => !v)}
                aria-expanded={!minimized}
                aria-label={minimized ? "Развернуть окно звонка" : "Свернуть, звонок продолжится"}
              >
                <IconMinimize />
              </button>
              {/* Закрыть руками. Окно и так гаснет само через три секунды после
                  конца разговора, но ждать даже три секунды человек не обязан —
                  ровно на это владелец и пожаловался 12.09.2026. Пока звонок
                  идёт, кнопка закрывает только окно: сам вызов живёт на станции,
                  и «Отменить» ниже — отдельное действие. */}
              <button
                type="button"
                className="close"
                onClick={onClose}
                aria-label={ended ? "Закрыть окно звонка" : "Закрыть окно, звонок продолжится"}
                title={ended ? "Закрыть" : "Закрыть окно, звонок продолжится"}
              >
                <IconClose />
              </button>
            </div>
          </div>

          {!minimized && (
            <>
              <div className="cw2-body">
                <div className={`cw2-av${!ended && !talking ? " pulse" : ""}`}>{initials(call.clientName)}</div>
                <p className="cw2-name">{call.clientName}</p>
                <p className="cw2-prop">
                  {/* Карточка клиента ссылкой: в макете такого перехода нет, но он
                      был в старой полосе звонка и терять его нельзя. Оформлен
                      прототипным `.lk`, а не своим классом. */}
                  <Link className="lk mut" to={`/clients/${call.clientShortId}`}>
                    Открыть карточку клиента
                  </Link>
                </p>
                <p className={`cw2-state ${stateTone}`.trim()}>{stateText}</p>
                {call.talkSeconds > 0 && <p className="cw2-timer">{formatTalkTime(call.talkSeconds)}</p>}
              </div>

              <div className="cw2-controls" role="group" aria-label="Управление звонком">
                <button
                  type="button"
                  className="cw2-btn end"
                  onClick={() => cancel.mutate()}
                  disabled={!canCancel || cancel.isPending}
                >
                  <IconHangUp />
                  <span className="lbl">{endLabel}</span>
                </button>
              </div>

              <div className="cw2-quiet">
                <span className="dot" />
                <span>{quiet}</span>
              </div>
            </>
          )}
        </section>
      </div>
    </Rh2Inline>
  );
}
