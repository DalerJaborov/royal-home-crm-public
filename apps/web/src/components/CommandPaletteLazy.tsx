import { lazy, Suspense } from "react";

/**
 * ПОИСК ПО CRM, ЗАГРУЖАЕМЫЙ ПО НАЖАТИЮ.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Палитру поиска открывают из трёх мест оболочки —
 * боковое меню на компьютере (Sidebar, ⌘K), верхняя панель на телефоне (Topbar)
 * и своя шапка Главной на телефоне (MobileHomeHeader). Все три живут во входном
 * куске сборки, поэтому статический импорт хотя бы из ОДНОГО из них тянет туда и
 * саму палитру: телефон обязан скачать и разобрать её до первой отрисовки, хотя
 * до нажатия на поиск она не нужна. Ленивый импорт помогает только тогда, когда
 * его сделали ВО ВСЕХ трёх местах — поэтому обёртка живёт одним модулем, а не
 * тремя копиями `lazy(...)` (иначе следующее место снова подключит напрямую и
 * тихо вернёт палитру во входной кусок).
 *
 * ЗАГЛУШКА `null`. Палитра — поверхность поверх экрана, открывается по
 * намеренному нажатию. Мигнуть пустой шторкой хуже, чем открыться на кадр
 * позже; файл предзагружается service worker вместе с остальной сборкой, поэтому
 * и офлайн поиск открывается.
 *
 * Вызывать так же, как раньше: `{showSearch && <CommandPaletteLazy onClose={…} />}`
 * — условие вокруг обязательно, иначе файл скачается сразу.
 */
const CommandPalette = lazy(() =>
  import("./CommandPalette").then((m) => ({ default: m.CommandPalette })),
);

export function CommandPaletteLazy({ onClose }: { onClose: () => void }) {
  return (
    <Suspense fallback={null}>
      <CommandPalette onClose={onClose} />
    </Suspense>
  );
}
