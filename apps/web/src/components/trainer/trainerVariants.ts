/**
 * Какие варианты исправления показывать и принимать горячими клавишами A/B.
 * Запрос вариантов идёт секунды, и оператор успевает уйти на другую карточку
 * («Позже», выбор из очереди): ответ по старой карточке всё равно ложится в
 * состояние, и клавиша A/B применяла его к ТЕКУЩЕЙ, обучая бота чужой репликой,
 * притом варианты на экране не видны (CHAT02, аудит 04.10.2026). Поэтому
 * варианты привязаны к id карточки, для которой посчитаны, и действуют только
 * при открытом режиме «Неверно» на той же карточке.
 */
export function shownVariants(
  badMode: boolean,
  variants: string[] | null,
  variantsFor: string | null,
  currentId: string | null
): string[] | null {
  if (!badMode || !variants || !currentId || variantsFor !== currentId) return null;
  return variants;
}
