import { relativeTime } from "../lib/format";
import type { Client } from "../types";

/**
 * «Всё о клиенте» (до 29.09.2026 — «Коротко от ИИ») — сводка ИИ о клиенте одним
 * блоком. С 29.09.2026 это единственный рассказ о клиенте на карточке (ПК и
 * телефон): что ищет, откуда, кто вёл и ведёт, что было, что сейчас и дальше.
 *
 * ЗАЧЕМ (владелец 20.08.2026): «после принятия клиента нужно имя клиента и так
 * далее и короткий инсайт от ИИ, всё, не надо больше флудить и писать огромные
 * тексты; и всегда когда зайдёшь — в инсайте всё что происходило, коротко».
 *
 * Агент открывает карточку не читать, а вспомнить, на чём остановились. До этого
 * блока «вспомнить» означало пролистать хронологию и переписку — то есть прочесть
 * всё заново; единственная короткая строка на экране (aiScoreReason) объясняла
 * не это, а почему у клиента такая оценка.
 *
 * ЧТО ЗДЕСЬ НЕ ДЕЛАЕТСЯ. Ничего не выдумывается и не досочиняется: текст приходит
 * с сервера (ai/scoring.ts) и там же обрезан (300 → 650 знаков, 25.08.2026 — см.
 * MAX_INSIGHT_CHARS там же). Пусто — блока нет вовсе: строка «сводки пока нет»
 * занимала бы место ровно там, где человек ждёт сути. Возраст сводки подписан
 * всегда — устаревший пересказ, выданный за свежий, хуже отсутствующего.
 *
 * НА ТЕЛЕФОНЕ (владелец 25.08.2026) этот текст заменяет собой блоки «Требования»
 * и «Детали клиента» — раньше был добавкой поверх них, теперь единственное место,
 * где читаются бюджет/район/источник/агент/дата контакта. Отсюда и вид: без
 * рамки-карточки, крупнее и чуть жирнее (16.5px/500 вместо 15px/400) — обычный
 * текст на экране, а не ещё одна плашка среди прочих. Владелец явно отклонил
 * вариант с плашками-фактами («нет без карточки»). На десктопе, где «Требования»
 * никуда не делись, вид прежний (боксом) — стили ниже с lg: воспроизводят его
 * один в один.
 */
/**
 * ОБЛИК — тема «Royal Home 2026» (09.09.2026). Вкладка «Коротко» в прототипе
 * (screens/client-detail.html, `data-panel-id="short"`) — это абзац во всю
 * ширину 64ch с подписью `.note` под ним, без рамки-карточки: сама вкладка уже
 * лежит внутри `.card`. Ровно это здесь и собрано; отдельного «box на десктопе,
 * голый текст на телефоне» больше не нужно — вид один на обе ширины, как в
 * макете. Заголовок и оценка — `.sec-h`/`.chip`. Компонент рендерит только
 * карточка клиента, переключателя облика не требуется.
 */
export function ClientInsight({ client }: { client: Client }) {
  if (!client.aiInsight) return null;

  const score = client.aiScore;
  const tone = score == null ? "mute" : score >= 70 ? "ok" : score >= 40 ? "warn" : "crit";

  return (
    <section>
      <div className="sec-h">
        {/* «Коротко ИИ» вплотную к заголовку читалось как опечатка (аудит
            07.09.2026, ui-audit-07-09-2026.md п.5) — теперь это одна подпись,
            а не жирное слово и серый довесок встык. */}
        {/* «Всё о клиенте» (владелец 29.09.2026): не «коротко», а вся суть
            карточки — «Что просит» и «О карточке» убраны, их место здесь. */}
        <h2>Всё о клиенте</h2>
        {score != null && (
          // Число без подписи читается как попало: подписываем прямо в чипе,
          // а не только всплывающей подсказкой, которую на телефоне не видно.
          <span className={`chip ${tone}`} title="Насколько вероятна сделка по этому клиенту">
            вероятность сделки {score}%
          </span>
        )}
      </div>
      {/* Сводка приходит строками с подписью («Ищет: …», «Ведёт: …», «Что было: …») —
          каждая строка отдельным абзацем, подпись жирным: так длинный текст
          читается с одного взгляда, а не простынёй. Старые сводки абзацем
          без подписей показываются как были. */}
      <div style={{ fontSize: "var(--fs-15)", color: "var(--ink)", maxWidth: "72ch", lineHeight: 1.5 }}>
        {client.aiInsight
          .split("\n")
          .map((line) => line.trim())
          .filter(Boolean)
          .map((line, i) => {
            const m = /^([А-ЯЁ][а-яё ]{1,18}):\s+(.+)$/.exec(line);
            return (
              <p key={i} style={{ margin: i === 0 ? 0 : "6px 0 0" }}>
                {m ? (
                  <>
                    <b>{m[1]}:</b> {m[2]}
                  </>
                ) : (
                  line
                )}
              </p>
            );
          })}
      </div>
      {client.aiInsightAt && (
        <p className="note" style={{ fontSize: "var(--fs-13)", color: "var(--faint)", marginTop: 10 }}>
          Обновлено {relativeTime(client.aiInsightAt)}
        </p>
      )}
    </section>
  );
}
