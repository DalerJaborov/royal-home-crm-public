import { createPortal } from "react-dom";
import type { CSSProperties, ReactNode } from "react";

/**
 * ОБЛАСТЬ ТЕМЫ ДЛЯ ОКОН, МЕНЮ И ПАНЕЛЕЙ.
 *
 * Весь эталонный CSS (`theme-2026-proto.css`) ограничен классом-областью `.rh2`:
 * ни одно правило не действует за её пределами. Экраны включают область сами
 * (`Rh2Screen`), но окна уходят через `createPortal` в `document.body` — то есть
 * ВНЕ любой области экрана. Класс `.sheet` на таком окне не даёт ничего: элемент
 * рендерится, просто без единого правила. Ни сборка, ни типы, ни линтер об этом
 * не сообщают, и перенос выглядит сделанным, пока не откроешь окно глазами.
 *
 * Поэтому корень портала каждого окна оборачивается здесь. Побочная выгода:
 * облик окна перестаёт зависеть от того, перенесён ли экран-хозяин, — а
 * `ConfirmDialog` вызывается примерно из 35 мест, из них половина ещё старые.
 *
 * ПОЧЕМУ ФОН ПРОЗРАЧНЫЙ. Селектор `.rh2` задаёт `background:var(--page)`: это
 * правильно для экрана и вредно для обёртки, которая только открывает область.
 * У полноэкранного окна обёртка нулевой высоты и фона не видно, а вот у
 * встроенных случаев (`Rh2Inline`: очередь загрузки внутри формы, полоса «нет
 * соединения») серый прямоугольник появился бы прямо посреди чужой разметки.
 * Ставится инлайн-стилем, а не новым классом: `theme-2026-proto.css` собирается
 * скриптом `scripts/sync-proto-css.py` и руками не правится, а своих имён
 * классов тема не заводит (договор дизайна §3).
 *
 * ПОЧЕМУ ЗДЕСЬ ЖЕ `display:"block"` (13.09.2026, невидимые окна на «Главной»).
 * Эталон прячет `.rh2.screens` по умолчанию и показывает только при
 * `html[data-screen]` (theme-2026-proto.css: `.rh2.screens{display:none}` /
 * `html[data-screen] .rh2.screens{display:block}`). Пульт директора снимает
 * `html[data-screen]` нарочно (`usePultMode`), чтобы не показывать сам экран
 * пульта как отдельный `.scr` — но тем же правилом гасится ЛЮБОЕ окно/меню/тост,
 * которое рендерится через `Rh2Portal`/`Rh2Inline` поверх пульта: `ConfirmDialog`
 * (~35 мест), тосты, меню профиля, лайтбокс фото, панель ассистента, `Rh2Sheet`,
 * окно входящей заявки, полоса «нет соединения», подсказка PWA. Ни один из них
 * не является экраном пульта, поэтому им класс `.screens` вообще не нужен для
 * входа в область — им нужен только сам факт видимости. Инлайн-стиль имеет
 * больший вес, чем правило таблицы стилей (без `!important` его нет ни у одной
 * из веток), поэтому `display:"block"` здесь снимает зависимость от
 * `html[data-screen]` для ВСЕХ порталов разом, не трогая сам `theme-2026-proto.css`
 * (генерируется скриптом, руками не правится) и не заводя новых классов.
 */

/** `.rh2` без собственного фона: обёртка открывает область, а не рисует экран. */
const TRANSPARENT: CSSProperties = { background: "transparent", display: "block" };

/**
 * ПОЧЕМУ ВНУТРИ ОБЛАСТИ ЕСТЬ ЕЩЁ И `.scr` (10.09.2026, полный перенос артефакта).
 *
 * В артефакте стили экранов написаны как `.scr .card`, `.scr .sheet` — на
 * ступень строже стилей пульта — и перенесены в theme-2026-proto.css дословно:
 * `.rh2 .scr .sheet`. Потомковый селектор требует ДВУХ разных предков, поэтому
 * одного `<div class="rh2 scr">` мало: окно в портале без вложенного `.scr`
 * снова рендерилось бы голой разметкой, и снова молча.
 *
 * Сам `.scr` в артефакте — колонка экрана (поля, предел 1240 px, `margin:auto`).
 * Обёртке окна или встроенного куска эта колонка не нужна: у окна дети
 * `position:fixed`, у встроенного куска — чужая рамка вокруг. Поэтому колонка
 * обнулена инлайн-стилем, а не новым классом (theme-2026-proto.css собирается
 * скриптом и руками не правится). Экран же берёт колонку целиком — `Rh2Screen`.
 */
export const RH2_SCR_BARE: CSSProperties = { padding: 0, maxWidth: "none", margin: 0 };

/**
 * Строка `.row` эталона, сделанная КНОПКОЙ (пункт меню, результат поиска).
 *
 * В прототипе `.row` — это `<div>`, и правило выравнивания текста ему не нужно.
 * У `<button>` браузер по умолчанию ставит `text-align:center`, а `.rh2 button`
 * наследует только шрифт и цвет — в итоге имя клиента и подпись под ним
 * оказывались посередине строки. Сборка и проверки об этом молчат: разметка
 * верная, классы верные, кадр кривой (поймано кадрами 09.09.2026).
 *
 * Живёт одной константой, а не тремя копиями инлайн-стиля по файлам, и не новым
 * именем класса: `theme-2026-proto.css` собирается скриптом и руками не правится.
 */
export const RH2_ROW_BUTTON: CSSProperties = { textAlign: "left" };

/**
 * Счётчик непрочитанного в строке раздела («Комментарии 17», «Звонки 13»).
 *
 * Красным его рисовать нельзя: по договору дизайна §3 и §6.1 красная (розовая)
 * семья закреплена за «надо сделать», а счётчик непрочитанного ничего не требует
 * прямо сейчас — он сообщает. Ровно тот же разбор был у счётчика в шапке
 * приложения, и там он уже стал лавандовым (`[data-topbar] [data-unread-badge]`
 * в theme-royal-home-2026.css); здесь тот же смысл, значит тот же цвет.
 *
 * Инлайн-стилем, а не новым классом `.chip.lav`: пастельных вариантов у `.chip`
 * в макете нет (`ok`, `warn`, `crit`, `hot`, `mute`), а заводить своё имя класса
 * договор запрещает. Пара токенов `--lav`/`--lav-ink` переопределена для ночной
 * темы в theme-2026-proto.css, поэтому одна запись работает в обеих темах.
 */
export const RH2_UNREAD_CHIP: CSSProperties = {
  background: "var(--lav)",
  color: "var(--lav-ink)",
  borderColor: "transparent",
};

/**
 * Портал в `document.body`, обёрнутый в область темы.
 *
 * Дети должны позиционироваться сами (`.sheet`, `.sheet-back`, `.toast`, `.cw`
 * — все `position:fixed`): обёртка намеренно остаётся обычным блоком нулевой
 * высоты и ничего не перехватывает. Своего `transform`/`filter` у неё нет —
 * иначе она стала бы containing block и `position:fixed` внутри считался бы от
 * неё, а не от экрана (та же ловушка, из-за которой окна и уехали в портал).
 */
export function Rh2Portal({ children }: { children: ReactNode }) {
  return createPortal(
    <div className="rh2 screens" style={TRANSPARENT}>
      <div className="scr" style={RH2_SCR_BARE}>
        {children}
      </div>
    </div>,
    document.body
  );
}

/**
 * Область темы прямо на месте, без портала: для встроенных кусков, которые
 * живут внутри ещё не перенесённой разметки (очередь загрузки в форме объекта,
 * полоса «нет соединения» в рамке приложения, подсказка установки).
 *
 * `className` ставится на ВНЕШНЮЮ обёртку, а не на узел `.rh2` (24.10.2026,
 * перепись экранов, P0). Тема лежит в CSS БЕЗ слоя и задаёт `.rh2{position:
 * relative;margin:0}`, а утилиты Tailwind v4 — в слое `utilities`: бесслойное
 * правило бьёт слойное при любой специфичности. Поэтому `fixed`/`sticky`/
 * `absolute`/`inset-*`/`z-*`/`mt-*`/`mb-*` на самом узле `.rh2` молча
 * проигрывали: подсказка «Поставьте CRM на экран» на третьем заходе оставалась
 * в потоке и схлопывала приложение в колонку 32 px. Утилиты на внешнем узле
 * темой не перебиваются; `.scr .card` внутри остаются потомками обёртки, так что
 * семантические хуки вроде `cef-overview` (`.cef-overview .scr .card`) работают как раньше.
 */
export function Rh2Inline({ children, className }: { children: ReactNode; className?: string }) {
  const scope = (
    <div className="rh2 screens" style={TRANSPARENT}>
      <div className="scr" style={RH2_SCR_BARE}>
        {children}
      </div>
    </div>
  );
  return className ? <div className={className}>{scope}</div> : scope;
}
