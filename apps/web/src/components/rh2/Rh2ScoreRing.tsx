/**
 * КОЛЬЦО ОЦЕНКИ С РАДУЖНЫМИ ДЕЛЕНИЯМИ.
 *
 * Salesforce-кейс из брифа (docs/archive/agent-briefs/color-layer.md), блок «AI Scoring
 * 92»: венец из тонких делений лайм → аква → лаванда → розовый и крупное число
 * в центре. Вся отрисовка — CSS (`.ring-score` в theme-2026-color-layer.css),
 * здесь только доля счёта в градусах и доступная подпись.
 *
 * ПОЧЕМУ НЕ SVG. Радужные деления в SVG — это 72 отдельных `<line>` с
 * собственным градиентом на каждой; в CSS ровно тот же вид даёт один
 * `conic-gradient` под маской из повторяющегося конического градиента. Меньше
 * узлов в дереве, и цвет берётся токенами темы, а не атрибутами.
 *
 * ДОСТУПНОСТЬ. Кольцо — картинка поверх числа, поэтому у него `role="img"` с
 * подписью, а не `progressbar`: счёт не имеет твёрдого потолка (значение выше
 * ста возможно), и обещать диктору шкалу 0…100 было бы неправдой. Само число
 * продублировано текстом в центре, поэтому смысл не теряется и без цвета.
 */
export function Rh2ScoreRing({
  score,
  /** Значение, которое считается полным кольцом. По умолчанию сто — привычный
   *  потолок Royal Score; счёт выше потолка заполняет кольцо целиком, а не
   *  уходит на второй круг. */
  max = 100,
  label,
  caption,
}: {
  score: number;
  max?: number;
  /** Подпись для диктора: «Royal Score 78 из 100». */
  label: string;
  /** Мелкая подпись под числом внутри кольца. */
  caption?: string;
}) {
  const safeMax = max > 0 ? max : 100;
  const share = Math.min(1, Math.max(0, score / safeMax));
  // Ровно ноль оставил бы `--deg: 0deg`, и `conic-gradient` нарисовал бы всю
  // окружность цветом дорожки — это верно: нулевой счёт и есть пустое кольцо.
  const deg = `${(share * 360).toFixed(1)}deg`;

  return (
    <div className="ring-score" role="img" aria-label={label} style={{ ["--deg" as string]: deg }}>
      <span className="mid" aria-hidden="true">
        <b>{Math.round(score)}</b>
        {caption && <small>{caption}</small>}
      </span>
    </div>
  );
}
