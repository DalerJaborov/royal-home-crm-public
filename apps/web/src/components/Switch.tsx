/**
 * Тумблер настройки — один на все Настройки.
 *
 * Раньше копий было три (вкладки «Бот», «Каналы связи», «ИИ»), и вели они себя
 * по-разному: где-то тумблер, где-то кнопка со словом, где-то обычная галочка.
 * Разъехались и мелочи, которые владелец читает как поломку: тумблер оставался
 * в прежнем положении до ответа сервера, а все остальные тумблеры на экране на
 * это время гасли.
 *
 * Тема «Royal Home 2026»: разметка дословно из эталона
 * (docs/pult/theme-2026/screens/settings.html) — `<label class="tgl">` с
 * настоящим `<input type="checkbox">` внутри и рисованной ручкой `<i>`.
 * Собственная кнопка с `role="switch"` и ручной позицией ручки больше не нужна:
 * положение рисует CSS прототипа (.rh2 .tgl input:checked+i), а состояние
 * объявляет сам чекбокс — программе чтения с экрана этого достаточно.
 *
 * Два правила, которые пережили перенос:
 *
 * 1. Состояние объявлено, а не нарисовано: настоящий чекбокс с `aria-label`.
 * 2. Гасить тумблер только тогда, когда переключать НЕЧЕГО (нет ключей канала).
 *    Ожидание ответа сервера сюда не относится: положение меняется сразу
 *    (см. optimistic-обновление в useUpdateSettings), а отказ откатывает его назад.
 */
export function Switch({
  on,
  disabled = false,
  onToggle,
  label,
}: {
  on: boolean;
  /** Только «переключать нечего»: без ключей, без права. Не «идёт сохранение». */
  disabled?: boolean;
  onToggle: () => void;
  /** Название настройки — им тумблер представляется программе чтения с экрана. */
  label: string;
}) {
  return (
    <label className="tgl">
      <input
        type="checkbox"
        checked={on}
        disabled={disabled}
        aria-label={label}
        /* onChange, а не onClick: клавиатура (пробел) обязана переключать так же,
           как мышь. Обработчик читает только факт события — источник правды о
           положении остаётся снаружи, в настройках. */
        onChange={onToggle}
      />
      <i />
    </label>
  );
}

/**
 * Строка настройки с тумблером: название, слово состояния и пояснение.
 *
 * Слово «Включено/Выключено» стоит РЯДОМ С НАЗВАНИЕМ нарочно. До 11.08.2026
 * пояснения были написаны одним неизменным текстом «Выключено — бот присылает
 * только ссылку…», то есть описывали последствие выключения независимо от того,
 * включена настройка или нет. Владелец читал это как состояние: тумблер зелёный,
 * а под ним написано «Выключено» — значит настройка не работает. Отсюда правило:
 * состояние называется одним словом и меняется вместе с тумблером, а пояснение
 * говорит про ТЕКУЩЕЕ положение, а не про одно из двух.
 *
 * Разметка — строка настройки эталона: `.mod` с `.t` (название и пояснение) и
 * `.acts` (сам тумблер). Предупреждение — `.msg` под строкой.
 */
export function SwitchRow({
  title,
  hint,
  on,
  disabled = false,
  onToggle,
  warning = null,
  className = "",
}: {
  title: string;
  /** Что происходит ПРИ ТЕКУЩЕМ положении. Не «что будет, если выключить». */
  hint: React.ReactNode;
  on: boolean;
  disabled?: boolean;
  onToggle: () => void;
  warning?: React.ReactNode;
  className?: string;
}) {
  return (
    <div className={`mod${className ? ` ${className}` : ""}`}>
      <div className="t">
        <b style={{ display: "flex", alignItems: "center", gap: "8px", flexWrap: "wrap" }}>
          <span>{title}</span>
          <StateWord on={on} />
        </b>
        <span>{hint}</span>
      </div>
      <div className="acts">
        <Switch on={on} disabled={disabled} onToggle={onToggle} label={title} />
      </div>
      {warning && (
        <p className="msg" style={{ color: "var(--warn)" }}>
          {warning}
        </p>
      )}
    </div>
  );
}

/** Состояние одним словом — то же, что показывает тумблер, но текстом. */
export function StateWord({ on }: { on: boolean }) {
  return <span className={`chip ${on ? "ok" : "mute"}`}>{on ? "Включено" : "Выключено"}</span>;
}
