import type { ReactNode } from "react";
import { useCounters } from "../hooks/useCounters";
import { useCan } from "../lib/permissions";
import { ScreenTabs, type ScreenTab } from "./ScreenTabs";

/**
 * Вкладки раздела «Клиенты».
 *
 * ЗАЧЕМ. В меню было пять отдельных пунктов — «Клиенты», «Горячие клиенты»,
 * «Продавцы», «Прочие обращения», «Потерянные клиенты», — и все пять открывают
 * ОДИН И ТОТ ЖЕ экран, отличаясь фильтром выборки (четыре из них — буквально
 * компонент `<Clients>` с другим пропсом). Человек этого не знает: он ищет
 * Далера в «Клиентах», не находит и решает, что карточки нет, — а Далер
 * уехал в «Потерянные». Пять входов в один список превращали срез в отдельную
 * сущность.
 *
 * Вкладки говорят правду: это один список, у него есть срезы, и между ними
 * переключаются одним нажатием, не возвращаясь в меню.
 *
 * ВКЛАДКИ У ВСЕХ РОЛЕЙ, У АГЕНТА РОВНО ДВЕ (владелец 09.09.2026,
 * docs/theme-2026-missing.md §6). Это ОТМЕНЯЕТ решение от 18.08.2026, по
 * которому агенту вкладки убрали совсем и показывали один общий список с
 * плашкой категории в строке (`isAgentUnified` в pages/Clients.tsx). Тогда
 * причиной был «слишком длинный функционал» — пять вкладок; сейчас причина
 * обратная: общий список покупателей и продавцов читается как каша, и агенты
 * на неё жалуются. Двух вкладок «слишком длинным функционалом» уже не назвать,
 * а «потерять» клиента из-за не той вкладки не даёт поиск: он ищет по всем
 * разделам сразу (см. Clients.tsx, searchAcrossKinds).
 *
 * ВКЛАДКИ «ГОРЯЧИЕ» БОЛЬШЕ НЕТ (там же): «горячесть» определяет ИИ и она видна
 * плашкой прямо в строке списка — отдельный раздел под неё только путал.
 * Маршрут /hot-clients остался переходом на «Покупателей» (App.tsx), чтобы
 * старые ссылки в пушах и закладках не отдавали пустоту.
 *
 * Состав повторяет права из lib/navigation.ts: у кого раздела нет — нет и
 * вкладки, иначе она обещала бы то, что API не отдаст. У агента нет ни
 * `otherInquiries.view`, ни `clients.assign` (ROLE_PRESETS в
 * packages/shared/src/permissions.ts), поэтому у него остаются вкладки без
 * этих двух прав — без единой проверки роли здесь: правами занимается
 * `ScreenTabs` сам, тем же способом, что и меню.
 *
 * ПЕРЕНОС ИЗ МЕНЮ (15.09.2026, docs/archive/menu-flatten-brief-15-09.md). Сокращение
 * меню 34 → 19 пунктов забирает из бокового меню четыре отдельных пункта,
 * открывавших срезы того же списка «Клиенты»/«Сделки»: «Воронка лидов»
 * (/lead-funnel), «Отложенные» (/deferred-clients), «Потерянные»
 * (/lost-clients) и «Сделки» (/deals). Раньше «Потерянные» уже жили здесь
 * вкладкой — теперь это ОДИН набор, а не две ленты вкладок на одном экране:
 * старый список выше и новые четыре маршрута сведены в один массив `TABS`,
 * маршрут не повторяется. «Отложенные», «Воронка лидов» и «Сделки» без
 * `permission`: это те же роли, что уже видят сам компонент (сервер сам
 * скоупит по своему агенту), в отличие от «Прочих» и «Потерянных», которые
 * управленческие целиком.
 *
 * Вид один на все свёрнутые разделы — рисует `components/ScreenTabs.tsx`
 * (эталон `.seg-ai`), свои Tailwind-классы под вкладки здесь больше не
 * пишутся: раньше `ClientsTabs` рисовал их сам и вкладки «Клиентов» не
 * совпадали ни с одним другим элементом темы.
 */

/** Счётчики срезов из сводки экрана (артефакт: «Покупатели 212 · Продавцы 41 …»);
 *  без них в бейдже остаётся прежний счётчик непрочитанного. */
export interface ClientsTabCounts {
  clients: number;
  sellers: number;
  other: number | null;
  lost: number | null;
  inactive?: number | null;
}

export function ClientsTabs({
  counts,
  extra,
}: { counts?: ClientsTabCounts; extra?: ReactNode } = {}) {
  const { data: counters } = useCounters();
  const can = useCan();

  /**
   * ДВЕ ВКЛАДКИ ВЕРХНЕГО УРОВНЯ (21.09.2026).
   *
   * Владелец: «продавцы, покупатели — всё перемешано неправильно… горячие мы
   * же удалили, и новые удали, все мои — откуда столько разделов, всё
   * перепутано? Должно быть всего 2 раздела — Продавцы, Покупатели, — а когда
   * в них заходишь, потом уже неактивные, потерянные».
   *
   * Было пять: Продавцы, Покупатели, Неактивные, Потерянные, Все мои. Три
   * последние — это не отдельные виды людей, а СОСТОЯНИЯ того же продавца или
   * покупателя, и стоя рядом с видом они читались как пятый и шестой вид.
   * Теперь верхний уровень отвечает на вопрос «кто это», а состояние —
   * второй лентой внутри раздела (ClientsSectionLane ниже).
   *
   * «Все мои» не исчезла, а переехала туда же под именем «Не на виду»: это
   * единственное место, где держатель без archive.view/clients.assign находит
   * карточку, молча уехавшую в Корзину/OTHER/LOST (решение 18.09.2026,
   * docs/audit/lead-ownership-17-09.md Р-2/Р-7). Удалить её означало бы
   * вернуть ту самую тихую потерю.
   */
  const tabs: ScreenTab[] = [
    { to: "/sellers", label: "Продавцы", count: counts ? counts.sellers : (counters?.sellers ?? 0) },
    { to: "/clients", label: "Покупатели", count: counts ? counts.clients : (counters?.clients ?? 0), end: true },
  ];

  return <ScreenTabs tabs={tabs} right={extra} />;
}
