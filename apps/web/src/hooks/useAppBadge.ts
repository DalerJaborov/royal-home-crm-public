import { useEffect } from "react";
import { useNotifications } from "./useNotifications";
import { clearAppBadge, setAppBadge } from "../lib/appBadge";

/**
 * Число на иконке установленного приложения = НЕПРОЧИТАННЫЕ УВЕДОМЛЕНИЯ.
 *
 * ЧТО БЫЛО ДО 27.08.2026 И ПОЧЕМУ ЭТО НЕ РАБОТАЛО. Считалась сумма красных
 * значков меню: clients + sellers + otherInquiries + messages + comments. Каждый
 * из них означает «появилось нового с тех пор, как ты последний раз ОТКРЫВАЛ
 * ЭТОТ РАЗДЕЛ» (Agent.sectionsSeenAt). Пока человек в раздел не заходит, его
 * счётчик копится без предела — и значок на иконке не гаснет никогда.
 *
 * На проде это выглядело так: у Маъруфа раздел «Продавцы» не открывался с
 * 17 августа, у половины сотрудников не открывались «Сообщения» и «Прочие
 * обращения». Значок горел у всех, включая владельца, месяцами. Жалоба
 * 27.08.2026: «в приложении будто есть уведомления, их много, включая мой
 * телефон… пусть они исчезают».
 *
 * Дело не в арифметике, а в обещании. Значок на иконке человек читает как «мне
 * что-то пришло, открой и увидишь». Открыть «всё новое по пяти разделам» нельзя
 * ничем: чтобы его погасить, надо было обойти каждый раздел по очереди. Значок,
 * который невозможно погасить, перестают замечать — вместе с настоящими новостями.
 *
 * Теперь на иконке ровно то, что можно закрыть одним действием: непрочитанные
 * уведомления. Открыл ленту — она отмечается прочитанной сама
 * (useAutoReadNotifications), и значок гаснет.
 *
 * Красные кружки в меню остались как были: они про разделы, они и живут в
 * разделах, где рядом видно, о чём речь. Иконка приложения — про уведомления.
 *
 * Пока приложение закрыто, число ведёт service worker: он ставит на иконку
 * количество уведомлений, висящих в шторке (src/sw.ts). Это та же величина, и
 * расхождение снимается при первом же открытии.
 *
 * Вызывать один раз, в AppLayout: useNotifications уже опрашивается шапкой, и
 * второй подписчик того же запроса не добавляет обращений к серверу.
 */
export function useAppBadge() {
  const { data } = useNotifications();

  useEffect(() => {
    if (!data) return;
    setAppBadge(data.unreadCount);
  }, [data]);

  // Выход из системы уводит на /login, а с ним размонтируется и layout: значок
  // с чужими цифрами не должен пережить смену сотрудника на общем телефоне.
  useEffect(() => () => clearAppBadge(), []);
}
