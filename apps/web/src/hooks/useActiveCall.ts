/** Подпись состояния для человека. */
export function callStateLabel(call: ActiveCallView): string {
  switch (call.state) {
    case "ringing_agent":
      // Номер прямо в подписи: если вызов уходит не на тот телефон, это должно быть
      // видно сразу, а не после разбора журнала станции.
      return `Звоним вам на ${call.dialingTo} — поднимите трубку`;
    case "ringing_client":
      return `Набираем клиента: ${call.clientName}`;
    case "talking":
      return `Разговор с ${call.clientName}`;
    case "ended":
      return call.outcome ?? "Звонок завершён";
  }
}

/** мм:сс для таймера разговора. */
export function formatTalkTime(seconds: number): string {
  const m = Math.floor(seconds / 60);
  const s = seconds % 60;
  return `${m}:${String(s).padStart(2, "0")}`;
}

/**
 * ТО ЖЕ СОСТОЯНИЕ, НО БЕЗ СВОЕГО ТАЙМЕРА ОПРОСА (19.09.2026).
 *
 * `useActiveCall` живёт в КАЖДОЙ кнопке звонка, то есть в каждой строке списка
 * клиентов, а таймер опроса у react-query свой на каждого наблюдателя и
 * `staleTime` его не сдерживает вовсе. Список на сто строк давал сто таймеров:
 * во время разговора это опрос раз в секунду с каждой строки, и общий лимитер
 * (600 запросов на пять минут, apps/api/src/app.ts) выбирался за полминуты —
 * дальше 429 на случайных разделах, ровно то, с чего начался разбор 19.09
 * (docs/sections-not-loading-19-09.md). Частично это уже ловили 08.08.2026
 * через `staleTime`, но интервальный запрос его не спрашивает.
 *
 * Опрашивает сервер ровно один наблюдатель — `CallWindow`, он же софтфон, и он
 * смонтирован на всех экранах разом (layouts/AppLayout.tsx). Остальным нужно
 * только ЧИТАТЬ уже добытое: `enabled: false` подписывает наблюдателя на кэш,
 * не заводя ни запроса, ни таймера. Данные те же и приходят тем же тактом.
 */
export function useActiveCallValue() {
  return useQuery<ActiveCallView | null>({
    queryKey: ["active-call"],
    queryFn: () => api<ActiveCallView | null>("/me/active-call"),
    enabled: false,
    refetchInterval: false,
  });
}
