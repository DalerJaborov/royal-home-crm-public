import { useEffect } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import type { ActiveCallView } from "@royal-home/shared";
import { api } from "../lib/api";
import { playIncomingCall } from "../lib/aiSounds";

/**
 * Что сейчас со звонком этого сотрудника.
 *
 * Раньше после нажатия «Позвонить» интерфейс не показывал ничего: появлялось
 * «Сохранено», кнопка снова становилась активной, и человек не понимал, звонит ли
 * телефон, взял ли клиент трубку, идёт ли разговор. Теперь состояние приходит с
 * самой АТС (см. apps/api/src/lib/telephony/ariEvents.ts).
 *
 * Опрос раз в секунду, пока звонок идёт, и раз в 15 секунд, когда его нет: запрос
 * читает состояние из памяти процесса и в базу не ходит, а секундная точность нужна
 * для таймера разговора — иначе он дёргается.
 */

/**
 * Форма ответа описана один раз — в @royal-home/shared, её же держится сервер
 * (routes/me.ts). Пока тип был объявлен здесь своей копией, стороны успели
 * разъехаться, и пропажу поля обнаружил бы агент посреди разговора, а не сборка.
 */
export type { CallState, ActiveCallView as ActiveCall } from "@royal-home/shared";

/**
 * ЗВОНИТ ТЕЛЕФОН АГЕНТА — ЗВУК (владелец 12.09.2026: «все звуки, которых нет,
 * добавь и доработай, и там, где можно добавить»).
 *
 * Click-to-call устроен так, что станция сначала поднимает трубку У АГЕНТА
 * (`ringing_agent`) и только потом набирает клиента. Момент, когда человек
 * обязан взять свою трубку, до сих пор был виден только глазами — если экран
 * в этот момент смотрел в другую сторону, звонок просто срывался.
 *
 * Состояние отслеживается ПО ПЕРЕХОДУ, а не по значению: опрос идёт раз в
 * секунду, и без памяти о прошлом состоянии сигнал повторялся бы каждую
 * секунду, пока телефон звонит. Память модульная, а не в компоненте: хук
 * живёт в каждой кнопке звонка (то есть в каждой строке списка клиентов), и
 * ref компонента дал бы двадцать одновременных сигналов.
 *
 * Тихие часы на этот звук не действуют (playIncomingCall): звонок идёт прямо
 * сейчас — ровно то же исключение, что у пуша о входящем на сервере
 * (apps/api/src/lib/pushQuietHours.ts, `realtime`).
 */
let lastRingingCallId: string | null = null;

export function useActiveCall() {
  const query = useQuery<ActiveCallView | null>({
    queryKey: ["active-call"],
    queryFn: () => api<ActiveCallView | null>("/me/active-call"),
    refetchInterval: (query) => {
      const call = query.state.data;
      // 2 с, а не 1: секундный опрос за пятиминутный разговор съедал 300 из
      // 600 запросов общего потолка API, и чаты падали с 429 (22.09.2026).
      return call && call.state !== "ended" ? 2_000 : 15_000;
    },
    // Пока идёт звонок, состояние важнее экономии: показываем его и в фоновой вкладке,
    // иначе агент переключился на другое окно и вернулся к застывшему таймеру.
    refetchIntervalInBackground: true,
    // 900 мс, а не 0. Хук живёт в КАЖДОЙ кнопке звонка, то есть в каждой строке
    // списка клиентов: при staleTime 0 открытие списка из двадцати строк давало
    // всплеск из двадцати одинаковых запросов подряд (замечено в прогоне 08.08.2026 —
    // девять подряд только на главной). Секундной точности таймера это не мешает:
    // интервал опроса во время разговора всё равно 1000 мс.
    staleTime: 900,
  });

  const call = query.data;
  useEffect(() => {
    // Идентификатор звонка — channelId станции: он же отличает новый вызов от
    // того же самого, что звонит вторую секунду подряд.
    const id = call && call.state === "ringing_agent" ? call.channelId : null;
    if (id && id !== lastRingingCallId) {
      lastRingingCallId = id;
      playIncomingCall();
    }
    if (!call || call.state === "ended") lastRingingCallId = null;
  }, [call]);

  return query;
}

/**
 * «Отменить» на полосе звонка — просьба владельца 13.08.2026: «можно отменять звонки,
 * если они случайно пошли или я передумал».
 *
 * Доступна только до начала разговора; сервер это проверяет сам и на говорящий звонок
 * отвечает отказом (см. POST /me/active-call/cancel). Ответ сервера мы НЕ подменяем
 * оптимистично: пока станция не подтвердила сброс, вызов идёт, и убирать полосу с
 * экрана нельзя — агент решит, что отменил, а клиент возьмёт трубку.
 */
export function useCancelActiveCall() {
  const qc = useQueryClient();
  return useMutation<{ ok: boolean }, Error, void>({
    mutationFn: () => api<{ ok: boolean }>("/me/active-call/cancel", { method: "POST" }),
    onSuccess: () => qc.invalidateQueries({ queryKey: ["active-call"] }),
  });
}

