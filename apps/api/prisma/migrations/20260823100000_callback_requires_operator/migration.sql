-- Просьба «перезвоните мне» без дежурного оператора — обычная заявка агенту
-- (владелец 23.08.2026).
--
-- Рубильник botCanRequestCallback сменил СМЫСЛ: теперь он значит «у нас есть
-- дежурный оператор или колл-центр», а не «бот умеет принимать просьбу о звонке».
-- Просьбу бот слышит в обоих положениях; различается только то, кто звонит —
-- дежурный через АТС или агент, которому распределился обычный лид.
--
-- Умолчание становится false и singleton выключается явно: оператора сейчас нет,
-- и очередь висела перед глазами руководства неделями. Когда колл-центр появится,
-- владелец включит рубильник обратно в Настройки → Бот — механика авто-соединения
-- сохранена целиком и заработает без правок кода.
ALTER TABLE "Settings" ALTER COLUMN "botCanRequestCallback" SET DEFAULT false;
UPDATE "Settings" SET "botCanRequestCallback" = false WHERE "id" = 'singleton';
