-- Проверка дублей объекта на шаге «Где» (15.09.2026, решение владельца: «пусть
-- механизм будет быстрым и правильным, чтобы от себя не придумывал, что это
-- дубль» — только точное совпадение канонного адреса, без похожести «на глаз»).
--
-- Колонка со значением по умолчанию '' — существующие строки заполняются
-- разовым скриптом СРАЗУ ПОСЛЕ миграции (scripts/backfill-property-canonical-
-- address.ts), а не в этом SQL: канонизация — функция на TypeScript
-- (normalizePropertyAddress, routes/properties/shared.ts), а не выражение SQL,
-- и должна остаться ЕДИНСТВЕННЫМ источником правды для обеих сторон (запись
-- при создании/правке объекта и разовое заполнение старых строк) — дублировать
-- те же правила отдельно на SQL было бы вторым местом, которое можно забыть
-- обновить при следующей правке сокращений.
ALTER TABLE "Property" ADD COLUMN "canonicalAddress" TEXT NOT NULL DEFAULT '';

-- Точный поиск «этот адрес уже заведён» внутри района — без индекса это полный
-- перебор объектов на каждую напечатанную букву в шаге «Где».
CREATE INDEX "Property_districtId_canonicalAddress_idx" ON "Property"("districtId", "canonicalAddress");
