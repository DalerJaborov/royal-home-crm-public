-- Перенос существующих карточек на workStatus (ТЗ владельца 12.08.2026).
--
-- ЗАЧЕМ ОТДЕЛЬНОЙ МИГРАЦИЕЙ, А НЕ DEFAULT. Колонка добавлена со значением 'ACTIVE'
-- по умолчанию, и без этого шага в день выката поменялся бы смысл лимита активных
-- лидов у ЖИВЫХ карточек: раньше слот занимали только NEW/CONTACTED/HOT, теперь —
-- любой ACTIVE, кроме LOST/DEAL_CLOSED/ARCHIVED (см. lib/leadLimits.ts,
-- OCCUPIES_SLOT_WHERE). То есть агент, у которого лежат «Холодные» и «Не отвечает»,
-- утром обнаружил бы переполненный портфель и перестал получать новые лиды, ничего
-- при этом не сделав. Ошибка была бы тихой: ни падения, ни сообщения — просто
-- лиды перестают приходить.
--
-- ЧТО ДЕЛАЕМ. Клиентов, которые СЕГОДНЯ слот не занимают (COLD, UNRESPONSIVE),
-- переводим в INACTIVE — их положение не меняется ни на день выката, ни после.
-- Оба состояния и по смыслу ровно то, что ТЗ называет «Неактивным»: клиент
-- замолчал или остыл, работа приостановлена, но он не потерян.
--
-- Обратный путь есть: карточка сама вернётся в ACTIVE, как только клиент напишет
-- в любой канал (leads.ts::createLeadFromChannel), — «Неактивный» не дверь в один
-- конец. Дальше правило работает уже по-новому: слот освобождает только явное
-- решение агента.
--
-- Продавцов (kind='SELLER') и прочие обращения (kind='OTHER') не трогаем: у них
-- свой путь («Итог объекта»), workStatus для них не используется вовсе.
UPDATE "Client"
SET "workStatus" = 'INACTIVE'
WHERE "kind" = 'BUYER'
  AND "status" IN ('COLD', 'UNRESPONSIVE');
