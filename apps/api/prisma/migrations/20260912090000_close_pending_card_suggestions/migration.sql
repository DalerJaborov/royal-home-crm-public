-- Закрыть все неразобранные предложения ИИ по карточке — решение владельца 12.09.2026.
--
-- ПОЧЕМУ. Баннер «После разговора: проверьте, верно ли поняли клиента» отменён
-- целиком: «я уже сто раз убираю этот блок, чтобы он исчез у всех и больше не
-- появлялся. Я специально плачу за дорогую модель, чтобы она не переспрашивала».
-- Код баннер больше не рисует и маршрутов под него не держит, но в базе остаются
-- строки CardSuggestion со status='pending' и незакрытые окна PendingSummary
-- kind='card_fill'. Без этой миграции они пережили бы выкат и всплыли бы у
-- владельца снова — ровно то, на что он жалуется.
--
-- ПОЧЕМУ 'superseded', А НЕ 'applied'. Применять задним числом нельзя: эти строки
-- относятся к разговорам, которым уже дни или недели, и часть полей агент с тех
-- пор поправил руками. Тихо перезаписать его правку позавчерашним «услышал»
-- хуже, чем не записать ничего, и следа в хронологии у такой записи не будет.
-- 'superseded' — то же слово, которым код помечает предложение, устаревшее из-за
-- следующего звонка (lib/cardSuggestions.ts): смысл совпадает. Данные не теряются —
-- строки остаются целиком, с цитатами клиента, и видны в истории разборов
-- (GET /clients/:id/card-suggestions). Ближайший разговор с этим клиентом всё
-- услышанное запишет сам, уже молча и со следом в хронологии.
UPDATE "CardSuggestion"
SET "status" = 'superseded', "resolvedAt" = NOW()
WHERE "status" = 'pending';

-- Обязательные окна «Проверьте, верно ли поняли клиента» новых записей не получают
-- с 12.08.2026, но старые незакрытые могли дожить до сегодня и всплыли бы поверх
-- CRM. Закрываем их тем же способом, что и resolveCardSuggestion, — проставляя
-- doneAt; сами записи остаются для отчётности.
UPDATE "PendingSummary"
SET "doneAt" = NOW()
WHERE "kind" = 'card_fill' AND "doneAt" IS NULL;
