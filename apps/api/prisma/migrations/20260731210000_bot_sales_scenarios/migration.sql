-- Сравнение МАНЕР ПРОДАЖИ бота.
--
-- Сценарий закрепляется за диалогом при его создании и больше не меняется, поэтому
-- поле живёт у диалога, а не у сообщения. NULL допустим: все диалоги, начатые до
-- появления сравнения, остаются без сценария и в статистику не попадают — приписать
-- их задним числом какой-либо манере было бы враньём.
ALTER TABLE "BotConversation" ADD COLUMN "salesScenario" TEXT;

-- Свёртка «сколько диалогов и сколько заявок у каждого сценария» группирует именно
-- по этому полю.
CREATE INDEX "BotConversation_salesScenario_idx" ON "BotConversation"("salesScenario");

-- Рубильник сравнения. Выключен по умолчанию: пока тексты сценариев не написаны,
-- бот обязан работать ровно так, как работал до этой миграции.
ALTER TABLE "Settings" ADD COLUMN "salesScenarioTestEnabled" BOOLEAN NOT NULL DEFAULT false;
