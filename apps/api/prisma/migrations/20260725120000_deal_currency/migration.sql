-- Валюта сделки: снапшот валюты объекта в момент сделки.
-- До этой миграции комиссия хранилась «без единиц» и суммировалась 1:1 с сомони,
-- хотя считалась от цены объекта, которая может быть в долларах.
ALTER TABLE "Deal" ADD COLUMN "currency" "Currency" NOT NULL DEFAULT 'TJS';

-- Бэкфилл истории: у существующих сделок валюта — та, что стоит у их объекта.
-- Это восстанавливает единицы измерения уже закрытых сделок; курс к сомони
-- применяется на чтении (см. apps/api/src/lib/money.ts), в БД суммы остаются
-- в исходной валюте.
UPDATE "Deal" d
SET "currency" = p."currency"
FROM "Property" p
WHERE p."id" = d."propertyId";
