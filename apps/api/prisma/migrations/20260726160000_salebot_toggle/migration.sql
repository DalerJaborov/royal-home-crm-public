-- Ключ SALEBOT_API_KEY и секрет вебхука остаются на месте: включить обратно
-- можно галочкой в Настройках, без деплоя.

ALTER TABLE "Settings" ADD COLUMN "salebotEnabled" BOOLEAN NOT NULL DEFAULT false;
