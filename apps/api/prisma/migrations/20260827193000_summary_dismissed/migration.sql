-- «Показали один раз — и хватит» (решение владельца 27.08.2026).
-- Требование, закрытое агентом без заполнения, больше не всплывает окном, но и
-- не исчезает бесследно: невыполненное уходит задачей в список дел.
-- Отдельная колонка, а не doneAt: «закрыл, сделаю потом» и «записал итог» —
-- разные вещи, и путать их нельзя ни в отчётах, ни в Royal Score.
ALTER TABLE "PendingSummary" ADD COLUMN "dismissedAt" TIMESTAMP(3);

-- Выдача окна спрашивает «что показать этому агенту прямо сейчас» — путь по
-- агенту и обоим признакам закрытия.
CREATE INDEX "PendingSummary_agentId_doneAt_dismissedAt_idx"
    ON "PendingSummary" ("agentId", "doneAt", "dismissedAt");
