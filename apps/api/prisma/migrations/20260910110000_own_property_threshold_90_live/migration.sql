-- подтверждено 10.09.2026: «да, сделай порог 90»).
--
-- Миграция 20260910060917 подняла только DEFAULT колонки, а `ALTER COLUMN ... SET
-- DEFAULT` существующие строки не трогает. Settings — одна строка на всю базу, и
-- она была заведена задолго до правки: на проде порог так и оставался 85, то есть
-- решение существовало только в схеме. Подстраховки в коде (`?? 90` в
-- services/leads/assignment.ts и lib/clientTransfer.ts) срабатывают лишь когда
-- строки Settings нет вовсе — то есть никогда.
--
-- Условие `= 85` намеренное: если владелец к этому моменту выставил свой порог
-- руками (Настройки -> Лиды), эта миграция обязана пройти мимо, а не затереть его
-- решение задним числом.
UPDATE "Settings" SET "ownPropertyMatchThreshold" = 90 WHERE "ownPropertyMatchThreshold" = 85;
