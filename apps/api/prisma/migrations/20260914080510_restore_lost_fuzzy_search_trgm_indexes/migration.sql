CREATE INDEX IF NOT EXISTS "Property_title_trgm_idx" ON "Property" USING GIN ("title" gin_trgm_ops);

-- CreateIndex
CREATE INDEX IF NOT EXISTS "Property_address_trgm_idx" ON "Property" USING GIN ("address" gin_trgm_ops);
