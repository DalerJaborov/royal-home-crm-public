-- по не объявленным в schema.prisma триграммным индексам, тот самый повторяющийся
-- дрейф, который эта и предыдущие миграции этой ветки закрывают объявлением в
-- schema.prisma). Итог: ровно МЕСЯЦ поиск по имени клиента и по названию/адресу
-- объекта шёл полным перебором таблицы вместо GIN-индекса, никем не замеченный,
-- пока 14.09.2026 не сверили schema.prisma с `pg_indexes` на проде напрямую.
--
-- Физическое восстановление обычным CREATE INDEX (не CONCURRENTLY) признано
-- безопасным на момент правки: на проде (проверено psql 14.09.2026) Client —
-- 234 строки / 1168 kB, Property — 64 строки / 640 kB. Построение GIN на такой
-- Table Size — единицы миллисекунд, блокировка на запись неразличима. Если
-- читаешь это через год на выросшей на порядки базе — здесь обходились без
-- CONCURRENTLY именно поэтому, а не потому что это общее правило: на большой
-- таблице обычный CREATE INDEX держит ACCESS EXCLUSIVE на всё время построения
-- и его в миграции лучше не пускать, `CREATE INDEX CONCURRENTLY` Prisma в
-- транзакции миграции не умеет — такой индекс пришлось бы создавать вручную вне
-- `migrate deploy`.
--
-- Объявление всех трёх в schema.prisma (`@@index(...ops: raw("gin_trgm_ops")...)`,
-- тот же приём, что и для GeoAlias.normalized и Client.phone/whatsappPhone) —
-- чтобы дрейф не повторился: без него diff-движок Prisma снова счёл бы их
-- чужеродными и предложил DROP при первой же следующей миграции.

-- IF NOT EXISTS добавлено 14.09.2026 при сведении трёх параллельных веток
-- (#365, #368 закрыты в пользу этой). На базе, где индекс уцелел — стенд агента,
-- копия эталона, чья-то локальная — голый CREATE INDEX роняет всю миграцию.

