$json$::jsonb;
  cur_templates jsonb;
  cur_endings jsonb;
  next_templates jsonb;
  next_endings jsonb;
  kept text;
BEGIN
  SELECT "propertyNarrationConfig" INTO cfg FROM "Settings" WHERE "id" = 'singleton';
  IF NOT FOUND THEN RETURN; END IF;
  IF jsonb_typeof(cfg) IS DISTINCT FROM 'object' THEN cfg := '{}'::jsonb; END IF;
  cur_templates := CASE WHEN jsonb_typeof(cfg -> 'templates') = 'array' THEN cfg -> 'templates' ELSE '[]'::jsonb END;
  cur_endings := CASE WHEN jsonb_typeof(cfg -> 'endings') = 'array' THEN cfg -> 'endings' ELSE '[]'::jsonb END;

  -- Templates: replace known old texts in place, drop retired ones, keep everything else.
  SELECT COALESCE(jsonb_agg(CASE WHEN n.e IS NOT NULL AND COALESCE((lib -> 'knownOld' -> (t.e ->> 'id')) ? (t.e ->> 'text'), false) THEN n.e ELSE t.e END ORDER BY t.ord), '[]'::jsonb)
    INTO next_templates
    FROM jsonb_array_elements(cur_templates) WITH ORDINALITY AS t(e, ord)
    LEFT JOIN LATERAL (SELECT x AS e FROM jsonb_array_elements(lib -> 'templates') x WHERE x ->> 'id' = t.e ->> 'id' LIMIT 1) n ON true
    WHERE NOT (COALESCE((lib -> 'retire') ? (t.e ->> 'id'), false) AND COALESCE((lib -> 'knownOld' -> (t.e ->> 'id')) ? (t.e ->> 'text'), false));
  SELECT next_templates || COALESCE(jsonb_agg(n.e ORDER BY n.ord), '[]'::jsonb) INTO next_templates
    FROM jsonb_array_elements(lib -> 'templates') WITH ORDINALITY AS n(e, ord)
    WHERE NOT EXISTS (SELECT 1 FROM jsonb_array_elements(cur_templates) x WHERE x ->> 'id' = n.e ->> 'id');

  -- Endings: the same, without retiring.
  SELECT COALESCE(jsonb_agg(CASE WHEN n.e IS NOT NULL AND COALESCE((lib -> 'knownOld' -> (t.e ->> 'id')) ? (t.e ->> 'text'), false) THEN n.e ELSE t.e END ORDER BY t.ord), '[]'::jsonb)
    INTO next_endings
    FROM jsonb_array_elements(cur_endings) WITH ORDINALITY AS t(e, ord)
    LEFT JOIN LATERAL (SELECT x AS e FROM jsonb_array_elements(lib -> 'endings') x WHERE x ->> 'id' = t.e ->> 'id' LIMIT 1) n ON true;
  SELECT next_endings || COALESCE(jsonb_agg(n.e ORDER BY n.ord), '[]'::jsonb) INTO next_endings
    FROM jsonb_array_elements(lib -> 'endings') WITH ORDINALITY AS n(e, ord)
    WHERE NOT EXISTS (SELECT 1 FROM jsonb_array_elements(cur_endings) x WHERE x ->> 'id' = n.e ->> 'id');

  -- Which library ids were left as the owner edited them (visible in the deploy log).
  SELECT string_agg(t.e ->> 'id', ', ') INTO kept
    FROM jsonb_array_elements(cur_templates || cur_endings) t(e)
    WHERE EXISTS (SELECT 1 FROM jsonb_array_elements((lib -> 'templates') || (lib -> 'endings')) x WHERE x ->> 'id' = t.e ->> 'id' AND x ->> 'text' <> t.e ->> 'text')
      AND NOT COALESCE((lib -> 'knownOld' -> (t.e ->> 'id')) ? (t.e ->> 'text'), false);
  IF kept IS NOT NULL THEN RAISE NOTICE 'narration_templates_live: kept owner-edited texts: %', kept; END IF;

  cfg := jsonb_set(cfg, '{templates}', next_templates);
  cfg := jsonb_set(cfg, '{endings}', next_endings);
  UPDATE "Settings" SET "propertyNarrationConfig" = cfg WHERE "id" = 'singleton';
END
