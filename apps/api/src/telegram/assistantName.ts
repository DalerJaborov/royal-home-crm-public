import { BW, EW } from "../ai/wordBoundary.js";

/**
 * ИМЯ ПОМОЩНИЦЫ В ГРУППЕ — ОДНО МЕСТО (26.11.2026, жалоба владельца: «Шабнамчун хонахои заминира…»
 * осталось без ответа: имя с ласковым окончанием не считалось обращением).
 *
 * Как люди пишут имя в рабочих группах: «Шабнам», «Шабнамм» (опечатка), «Shabnam», «Сабнам»,
 * «Шебнам», «Шабнум», и ласково: «Шабнамҷон», «Шабнамчон», «Шабнам-чон», «Шабнам чун», «Шабнамчун»,
 * «шабнамджон», «Шабнамжон». «Мушовир» (советник) — второе имя-роль, им тоже зовут.
 *
 * Ласковая форма (-ҷон/-чон/-чун/-джон/-жон/-джан) — это всегда обращение: так о человеке не
 * говорят, так к нему зовут. Голое «Шабнам» в начале сообщения решает addressedToBot по прежнему
 * правилу (знак после имени или просьба).
 */
const NAME = "(?:ш[аеэ]бна+м+|шабнум|сабнам|shabna+m+|мушовир)";
/** Ласковое окончание: слитно, через дефис или пробел. «чун» в таджикском и «как», поэтому только сразу за именем. */
const VOCATIVE = "(?:[\\s-]?(?:ҷон(?:ам)?|чон(?:ам)?|чун|ҷун|джон|джун|жон|джан))";

/** Источник выражения «имя с необязательным ласковым окончанием», для сборки соседних выражений. */
export const ASSISTANT_NAME_SOURCE = `${NAME}${VOCATIVE}?`;

const NAME_AT_START = new RegExp(`^(${NAME})(${VOCATIVE})?(?=$|[\\s,:;.!?—–-])`, "iu");
/** Склонения внутри фразы: «Шабнаму», «у Шабнам», «Шабнамро», «ба Шабнам». */
const CASE_ENDING = "(?:у|е|ы|ой|ро|ба)";
const NAME_ANYWHERE = new RegExp(`${BW}${NAME}(?:${VOCATIVE}|${CASE_ENDING})?${EW}`, "iu");

export interface AssistantNameMatch {
  /** Длина обращения в начале текста (имя и окончание), чтобы отрезать его от просьбы. */
  length: number;
  /** Ласковая форма: обращение без сомнений. */
  vocative: boolean;
}

/** Имя в самом начале сообщения: «Шабнам, …», «Шабнамчун …», «Shabnam …». */
export function assistantNameAtStart(text: string): AssistantNameMatch | null {
  const match = NAME_AT_START.exec(text);
  if (!match) return null;
  return { length: match[0].length, vocative: Boolean(match[2]) };
}

/** Имя где угодно в тексте отдельным словом (не «шабнамро» как часть другого слова). */
export function mentionsAssistantName(text: string): boolean {
  return NAME_ANYWHERE.test(text);
}
