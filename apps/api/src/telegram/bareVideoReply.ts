import type { TelegramIncomingMessage } from "./api.js";
import { isVideoDocument } from "../lib/videoFileExtension.js";

export type BareVideoReason = "videoNote" | "forwarded" | "other";

/** Это видео (ролик, кружок или файл-видео)? null — не видео, ответ не нужен. */
export function bareVideoReason(msg: TelegramIncomingMessage): BareVideoReason | null {
  if (msg.video_note) return "videoNote";
  if (!msg.video && !isVideoDocument(msg.document)) return null;
  if (msg.forward_origin || msg.forward_from_message_id) return "forwarded";
  return "other";
}

