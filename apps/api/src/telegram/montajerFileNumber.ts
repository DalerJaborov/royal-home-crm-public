/**
 * НОМЕР ОБЪЕКТА В ФАЙЛЕ МОНТАЖЁРА (24.09.2026, проверка готового ролика по
 * классам). Бот отдаёт монтажёру исходники с именем «<номер объекта>.mp4» или
 * «<номер>_1из3.mp4» (lib/videoHandoff.ts::montajerFileName), и готовый ролик
 * обычно возвращается под тем же именем. До этой правки бот номер не читал и
 * клал любой файл на того, кто сейчас держит место монтажёра: исправленный или
 * поздний ролик №X, пришедший, когда место уже ушло №Y, публиковался на №Y.
 *
 * Номер берётся только из НАЧАЛА имени файла или подписи: «108.mp4»,
 * «108_1из3.mov», «№108 финал.mp4», подпись «объект 108». Цифры внутри имени
 * («IMG_1234.MOV») и длинные числа («20260924_видео.mp4» — дата съёмки) номером
 * не считаются. `\b` здесь не годится: между цифрой и кириллицей JS-граница
 * слова срабатывает не так, как ждёшь (CLAUDE.md, «Ловушки»), поэтому явное
 * «не цифра дальше».
 */
const LEADING_NUMBER = /^\s*(?:объект|об\.?)?\s*[№#]?\s*(\d{1,6})(?!\d)/i;

export function declaredObjectNumber(filename: string | undefined | null, caption: string | undefined | null): number | null {
  // Имя файла надёжнее: его выдал сам бот. Подпись — только если в имени номера нет.
  for (const source of [filename, caption]) {
    if (!source) continue;
    const match = source.match(LEADING_NUMBER);
    if (!match) continue;
    const n = Number(match[1]);
    if (Number.isSafeInteger(n) && n > 0) return n;
  }
  return null;
}
