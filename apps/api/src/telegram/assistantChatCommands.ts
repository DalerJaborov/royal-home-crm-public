/**
 * КОРОТКИЕ КОМАНДЫ ЛИЧКИ ШАБНАМ БЕЗ МОДЕЛИ: «повтори голосом» и «удали присланное» (17.11.2026).
 *
 * Журнал прода 10–17.11: «Овоз барор» (озвучь), «овозатро равон кун» (пришли голосом),
 * «Ки хомуш кард» (кто выключил [голос]) Шабнам не поняла — распознавание знало только
 * русские фразы; «удалить кун ҳамаи равон кардагиатро» (удали всё, что прислала) не умела.
 *
 * Сверка идёт по ВСЕЙ реплике после нормализации, а не поиском слова в тексте: «клиент
 * ответил голосом», «овоз нафирист» и «удали клиента» командами не становятся.
 * Таджикский пишут и со спецбуквами, и без них (ҳ→х, ӯ→у, ӣ→и, қ→к, ғ→г, ҷ→ч), и латиницей
 * («ovoz baror») — всё сводится к одной форме. `\w`/`\b` по кириллице не работают
 * (ai/wordBoundary.ts), поэтому границы — пробелы после нормализации и `\p{L}`.
 */

const TAJIK_LETTERS: Record<string, string> = { ӣ: "и", ӯ: "у", ҳ: "х", қ: "к", ғ: "г", ҷ: "ч", ё: "е" };
const LATIN_DIGRAPHS: [RegExp, string][] = [
  [/sh/g, "ш"], [/ch/g, "ч"], [/zh/g, "ж"], [/kh/g, "х"], [/gh/g, "г"], [/ya/g, "я"], [/yu/g, "ю"], [/yo/g, "е"],
];
const LATIN: Record<string, string> = {
  a: "а", b: "б", c: "к", d: "д", e: "е", f: "ф", g: "г", h: "х", i: "и", j: "ч", k: "к", l: "л", m: "м", n: "н",
  o: "о", p: "п", q: "к", r: "р", s: "с", t: "т", u: "у", v: "в", w: "в", x: "х", y: "й", z: "з",
};

const LEAD = /^(?:(?:шабнам|мушовир|лутфан|илтимос|пожалуйста|чон|чонам|ака|апа|хуб|ха|ну|а|слушай|слушайте|давай|давайте)\s+)+/u;
const TAIL = /(?:\s+(?:пожалуйста|мне|ба\s+ман|лутфан|илтимос|чон|чонам|шабнам|мушовир))+$/u;

/** Реплика в одной форме: строчные, без спецбукв таджикского, латиница → кириллица, без знаков. */
export function normalizeChatCommand(raw: string): string {
  let text = raw.toLocaleLowerCase("ru");
  if (/[a-z]/.test(text)) {
    for (const [from, to] of LATIN_DIGRAPHS) text = text.replace(from, to);
    text = text.replace(/[a-z]/g, (c) => LATIN[c] ?? c);
  }
  text = text.replace(/[ӣӯҳқғҷё]/g, (c) => TAJIK_LETTERS[c] ?? c);
  text = text.replace(/[^\p{L}\p{N}\s]+/gu, " ").replace(/\s+/gu, " ").trim();
  return text.replace(LEAD, "").replace(TAIL, "").trim();
}

// ───────────── «повтори голосом» ─────────────

/** Прежние русские формы (без изменений, по исходному тексту). */
const RU_REPLAY = /^(?:(?:озвучь|озвучьте|прочитай)(?:\s+(?:это|ответ|последний ответ))?|(?:отправь|отправьте|пришли|пришлите|ответь|ответьте)(?:\s+(?:мне|это|ответ|предыдущий ответ)){0,3}\s+(?:голосом|голсоом|голосовым)(?:\s+(?:это|мне|ответ))?)[?!.]*$/iu;

const TG_OBJECT = String.raw`(?:(?:ин|инро|инаша|инашро|чавоб(?:ат|атон)?(?:ро)?|чавоби\s+охир(?:ин)?(?:ро)?)\s+)?`;
const TG_VOICE = String.raw`овоз(?:ат|атон|и|ам)?(?:ро)?`;
/** «Выпусти / пришли / дай услышать» — повелительное, на «ту» и на «шумо». */
const TG_OUT = String.raw`(?:барор(?:ед)?|баровар(?:ед)?|(?:би)?фирист(?:ед|и)?|(?:равон|ирсол)\s+кун(?:ед|и)?|кун(?:ед)?|(?:би)?дех(?:ед)?|(?:би)?дих(?:ед)?|(?:би)?шунавон(?:ед)?)`;
/** «Скажи / прочитай / повтори / ответь» после «бо овоз». */
const TG_SAY = String.raw`(?:(?:би)?гу(?:й|ед)?|(?:би)?хон(?:ед)?|такрор\s+кун(?:ед|и)?|чавоб\s+(?:би)?(?:дех|дих)(?:ед)?|гап\s+зан(?:ед)?|(?:би)?фирист(?:ед)?|равон\s+кун(?:ед)?)`;

const VOICE_REPLAY = new RegExp([
  // «овоз барор», «овозатро равон кун», «инро бо овоз фирист», «ovoz baror»
  String.raw`^${TG_OBJECT}(?:бо\s+)?${TG_VOICE}\s+${TG_OUT}$`,
  // «бо овоз гӯ», «чавобро бо овоз хон», «бо овоз такрор кун»
  String.raw`^${TG_OBJECT}бо\s+овоз\s+${TG_SAY}$`,
  // «такрор кун бо овоз», «хон бо овоз»
  String.raw`^${TG_OBJECT}${TG_SAY}\s+бо\s+овоз$`,
  // «овозонӣ кун», «хонда деҳ»
  String.raw`^${TG_OBJECT}(?:овозони\s+кун(?:ед)?|хонда\s+(?:дех|дих)(?:ед)?)$`,
  // «Ки хомӯш кард?» — кто выключил (голос): ответ дублируется голосом. Владелец 17.11.2026.
  String.raw`^ки\s+(?:${TG_VOICE}\s+)?хомуш\s+кард(?:\s+${TG_VOICE})?$`,
  String.raw`^(?:чаро\s+)?${TG_VOICE}\s+(?:нест|хомуш(?:\s+аст)?|кучо(?:ст)?)$`,
  // Русские формы, которых не было: «повтори голосом», «скажи вслух», «кто выключил голос».
  String.raw`^(?:повтори|скажи|прочитай|прочти|расскажи)(?:те)?(?:\s+(?:это|ответ|мне))*\s+(?:голосом|вслух)$`,
  String.raw`^(?:голосом|вслух)\s+(?:повтори|скажи|прочитай|прочти)(?:те)?(?:\s+(?:это|ответ|мне))*$`,
  String.raw`^(?:кто\s+(?:выключил|отключил)\s+(?:голос|звук)|почему\s+(?:без\s+голоса|не\s+голосом)|где\s+(?:твой\s+)?голос)$`,
].join("|"), "u");

/** Просьба озвучить последний ответ помощницы — по-русски и по-таджикски, любым написанием. */
export function isVoiceReplayRequest(text: string): boolean {
  if (RU_REPLAY.test(text.trim())) return true;
  const normalized = normalizeChatCommand(text);
  return normalized.length > 0 && normalized.length <= 80 && VOICE_REPLAY.test(normalized);
}

// ───────────── «удали присланное» ─────────────

const DELETE_VERB = new RegExp(String.raw`(?:^|\s)(?:удали\p{L}*|сотри\p{L}*|убери\p{L}*|очисти\p{L}*|(?:нест|пок|тоза|хазф|удалит|удалить|удали)\s+кун(?:ед|и)?)(?=\s|$)`, "u");
const DELETE_OBJECT = new RegExp(String.raw`(?:^|\s)(?:равон\s+кардаги\p{L}*|фиристодаги\p{L}*|навиштаги\p{L}*|паем\p{L}*|сообщени\p{L}*|ответ\p{L}*|голосов\p{L}*|переписк\p{L}*|чат\p{L}*|прислал\p{L}*|отправил\p{L}*|написал\p{L}*|скинул\p{L}*)(?=\s|$)`, "u");
/** Про данные CRM — это работа инструментов, а не чистка чата: «удали сообщение клиенту». */
const CRM_SUBJECT = new RegExp(String.raw`(?:^|\s)(?:клиент|объект|об\s?\d|задач|показ|расход|сделк|фото|ролик|видео|мизоч|вазиф|хароч|уведомлен|заметк|карточк|сотрудник)\p{L}*`, "u");

/**
 * «Удали всё, что прислала», «удалить кун ҳамаи равон кардагиатро», «сообщенияҳоятро нест кун» —
 * просьба убрать СВОИ сообщения Шабнам в этом чате. Только короткая реплика (до 10 слов).
 */
export function isDeleteSentRequest(text: string): boolean {
  const normalized = normalizeChatCommand(text);
  if (!normalized || normalized.split(" ").length > 10) return false;
  if (CRM_SUBJECT.test(normalized) || !DELETE_VERB.test(normalized)) return false;
  return DELETE_OBJECT.test(normalized) || isBareScopeDelete(normalized);
}

/**
 * Подсказки из `deleteSentAsk` — «удали последнее», «удали всё», «охиринро нест кун», «ҳамаашро нест кун» —
 * без слова «сообщение». Слова «всё»/«последнее» сами по себе предметом не считаем («убери всё лишнее из
 * описания» — не про чат): принимаем, только когда кроме глагола и этого слова в реплике ничего нет.
 */
const SCOPE_WORD = /(?:^|\s)(?:последн\p{L}*|охирин\p{L}*|охир|все|всех|весь|всю|хама\p{L}*)(?=\s|$)/gu;
const DELETE_VERB_ALL = new RegExp(DELETE_VERB.source, "gu");
function isBareScopeDelete(normalized: string): boolean {
  if (!new RegExp(SCOPE_WORD.source, "u").test(normalized)) return false;
  return normalized.replace(DELETE_VERB_ALL, " ").replace(SCOPE_WORD, " ").trim() === "";
}

/**
 * Что стирать. «all» — только по явной фразе («удали всё», «весь чат», «всю переписку», «ҳамаи паёмҳо»)
 * и без сужения («голосовые», «для Нозы», фото…). «last» — «последнее» или одно «сообщение» в единственном
 * числе. Остальное — «ask»: ничего не стираем, спрашиваем (ревью волны 2: «убери голосовые ответы»
 * и «удали сообщение для Нозы» стирали двое суток переписки).
 */
export type DeleteScope = "last" | "all" | "ask";

const ALL_WORD = /(?:^|\s)(?:все|всех|весь|всю|хама\p{L}*)(?=\s|$)/u;
const NARROWING = /(?:^|\s)(?:голосов\p{L}*|озвуч\p{L}*|аудио|овоз\p{L}*|для|барои|фото|файл\p{L}*|ролик\p{L}*|карточ\p{L}*|корт\p{L}*|ссылк\p{L}*)(?=\s|$)/u;
const LAST_WORD = /(?:^|\s)(?:последн\p{L}*|охирин\p{L}*|охир)(?=\s|$)/u;
const SINGLE_MESSAGE = /(?:^|\s)(?:сообщение|ответ|паем|чавоб)(?=\s|$)/u;

export function deleteSentScope(text: string): DeleteScope {
  const normalized = normalizeChatCommand(text);
  if (LAST_WORD.test(normalized)) return "last";
  if (ALL_WORD.test(normalized) && !NARROWING.test(normalized)) return "all";
  if (/(?:^|\s)чат\p{L}*|(?:^|\s)переписк\p{L}*/u.test(normalized) && !NARROWING.test(normalized)) return "all";
  if (SINGLE_MESSAGE.test(normalized) && !NARROWING.test(normalized)) return "last";
  return "ask";
}

/** Вопрос вместо стирания: сказать словами, что именно убрать. */
export function deleteSentAsk(lang: "ru" | "tg"): string {
  return lang === "tg"
    ? "Кадомашро нест кунам? Нависед «охиринро нест кун» — танҳо паёми охирини ман, ё «ҳамаашро нест кун» — ҳамаи паёмҳои ман дар ин чат."
    : "Что убрать? Напишите «удали последнее» — уберу только моё последнее сообщение, или «удали всё» — все мои сообщения в этом чате за двое суток.";
}

/** Ответ на чистку: сколько удалила и почему не всё. Числа здесь — текст, не голос. */
export function deleteSentReply(lang: "ru" | "tg", deleted: number, total: number): string {
  if (total === 0) {
    return lang === "tg"
      ? "Нест кардан чизе нест: дар ду шабонарӯзи охир паёмҳои ман дар ин чат нестанд. Паёмҳои кӯҳнатарро Telegram нест карданро намемонад."
      : "Удалять нечего: за последние двое суток моих сообщений в этом чате нет. Старше двух суток Telegram удалить не даёт.";
  }
  if (deleted === total) {
    return lang === "tg" ? `Паёмҳои худро нест кардам: ${deleted}.` : `Удалила свои сообщения: ${deleted}.`;
  }
  return lang === "tg"
    ? `Аз ${total} паём ${deleted}-тоашро нест кардам, боқиро Telegram нагузошт.`
    : `Удалила ${deleted} из ${total}, остальные Telegram удалить не дал.`;
}
