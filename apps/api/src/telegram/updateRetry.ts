/**
 * ПОВТОР ПРИЁМА АПДЕЙТА TELEGRAM (JOB-06, аудит 04.10.2026).
 *
 * Обе дороги доставки (polling — telegram/poller.ts, вебхук — routes/webhooks.ts)
 * подтверждают апдейт Telegram'у раньше, чем сообщение гарантированно легло в
 * переписку: поллер двигает offset, вебхук отвечает 200 до разбора. Транзиентный
 * сбой (база моргнула, сеть) раньше выбрасывал апдейт навсегда: замок дубля снимался,
 * но повторной доставки уже не будет.
 *
 * Поэтому приём повторяется здесь же, ограниченное число раз с паузой. Лимит нужен,
 * чтобы один «ядовитый» апдейт не держал поллер (он разбирает чаты по одному) и не
 * крутился вечно: после последней попытки ошибку получает вызывающий — он пишет её в
 * журнал, снимает замок дубля и идёт дальше.
 *
 * Не durable: рестарт процесса посреди пауз (секунды) потеряет повтор вебхука; у
 * поллера offset к этому моменту ещё не подтверждён Telegram'у, и апдейт придёт сам.
 * Полноценная очередь заданий для вебхука потребовала бы хранить апдейт целиком, это
 * отдельное решение.
 */
export const telegramUpdateRetryPolicy = {
  /** Паузы перед 2-й и 3-й попыткой. Изменяемый объект, чтобы тест не ждал секунды. */
  delaysMs: [2_000, 5_000],
};

export async function withTelegramUpdateRetry<T>(run: () => Promise<T>): Promise<T> {
  for (let attempt = 0; ; attempt++) {
    try {
      return await run();
    } catch (err) {
      const delay = telegramUpdateRetryPolicy.delaysMs[attempt];
      if (delay === undefined) throw err;
      console.error(
        `[telegram] апдейт не принят (попытка ${attempt + 1}), повтор через ${delay} мс:`,
        err instanceof Error ? err.message : err
      );
      await new Promise((resolve) => setTimeout(resolve, delay));
    }
  }
}
