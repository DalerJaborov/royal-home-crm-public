/** Просьба привязать: «привяжи/подключи меня», «Манро пайваст кун», «как подключиться». */
export function asksToBeLinked(text: string): boolean {
  return /(?<![\p{L}])(?:привяж|привяз|подключ|пайваст|пайвас|link)/iu.test(text);
}

/**
 * Текст подсказки. attempt — какой это ответ человеку в этой группе (1, 2, …): каждый следующий другой фразой.
 * name — имя из Telegram (может быть пустым): «Бехруз, напишите…».
 */
export function newcomerLinkHint(opts: { language: HintLanguage; name: string; byPhone: boolean; asksToLink: boolean; attempt: number }): string {
  const kind = opts.byPhone ? "dm" : opts.asksToLink ? "howTo" : "profile";
  const variants = HINT_TEXTS[kind][opts.language];
  const pick = variants[(Math.max(1, Math.floor(opts.attempt)) - 1) % variants.length]!;
  const name = opts.name.trim();
  const text = pick(name ? `${name}, ` : "");
  return name ? text : text.charAt(0).toUpperCase() + text.slice(1);
}

