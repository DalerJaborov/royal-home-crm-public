import type { PushPayload } from "@royal-home/shared";
import { dushanbeNextOccurrence, isWithinDushanbeWindow } from "./dushanbeTime.js";

/**
 * ТИХИЕ ЧАСЫ ДЛЯ ПУШЕЙ (владелец 12.09.2026).
 *
 * Дословно: «ночью запрещено слать пуши всем пользователям, только в начале
 * рабочего дня».
 *
 * ПОЧЕМУ ГЕЙТ В ТРАНСПОРТЕ, А НЕ В ВЫЗЫВАЮЩЕМ КОДЕ. Окна в системе уже были —
 * lib/workingHours.ts: `isWithinWorkingHours` (09:30–18:00) стоит в девяти
 * местах, `isWithinAlarmHours` (09:50–14:45) — в одиннадцати. А прямых вызовов
 * sendPushToAgent(s) около ста тридцати пяти: девяносто с лишним путей уходили
 * в любой час ночи, и добавить им гейт по одному — значит гарантированно
 * забыть часть и забывать каждую новую. Поэтому правило живёт ровно там, где
 * его нельзя обойти, — в самом отправителе (apps/api/src/push.ts).
 *
 * ЧТО ПРОИСХОДИТ НОЧЬЮ:
 *  - ЗАПИСЬ В ЛЕНТЕ УВЕДОМЛЕНИЙ ПИШЕТСЯ ВСЕГДА. Тишина касается только звонка
 *    устройства; информация не теряется ни в одном из трёх исходов, и утром
 *    человек видит в колокольчике всё, что произошло за ночь.
 *  - "send"  — событие реального времени (`realtime`): телефон звонит прямо
 *    сейчас, через час это уведомление бессмысленно. Единственное исключение.
 *  - "defer" — уйдёт в 08:00 по Душанбе через очередь фоновых заданий.
 *  - "drop"  — к утру потеряет смысл, пуш не ставится вовсе (остаётся лента).
 *
 * ПОЧЕМУ НЕ ВСЁ ОТКЛАДЫВАЕТСЯ. Пуш в 08:00 про то, что уже неверно, хуже
 * молчания: у нового лида срок жизни короче ночи (не принял — ушёл другому,
 * см. services/leads/reassignment.ts), и утреннее «🔔 Новый лид» позвало бы
 * агента к чужой карточке. Royal Score и салют команде к утру — это к сведению,
 * и место им в ленте, а не в шторке поверх экрана.
 */

/** Начало тишины по Душанбе. */
export const QUIET_START = "21:00";
/** Конец тишины: «начало рабочего дня» из формулировки владельца. */
export const QUIET_END = "08:00";

export type QuietDecision = "send" | "defer" | "drop";

/** Ночь ли сейчас по Душанбе (окно перевалено через полночь — см. dushanbeTime). */
export function isQuietHour(at: Date = new Date()): boolean {
  return isWithinDushanbeWindow(QUIET_START, QUIET_END, at);
}

/** Ближайшие 08:00 по Душанбе — момент, на который откладывается пуш. */
export function quietHoursEndAfter(at: Date = new Date()): Date {
  return dushanbeNextOccurrence(QUIET_END, at);
}

/**
 * Виды, которые к утру теряют смысл и потому не откладываются, а отбрасываются.
 *
 * `lead` — у лида есть срок: к 08:00 он уже либо принят, либо передан дальше.
 * `score` и `celebration` — к сведению, им место в ленте.
 */
const DROP_KINDS: ReadonlySet<string> = new Set(["lead", "score", "celebration"]);

/**
 * Что делать с этим пушем прямо сейчас.
 *
 * Уведомление без `kind` (служебные сигналы: сбой интеграции, эскалация,
 * невозвращённый ключ) ОТКЛАДЫВАЕТСЯ, а не отбрасывается: оно не привязано к
 * сроку и утром по-прежнему требует действия.
 */
/**
 * ВЫКЛЮЧАТЕЛЬ ДЛЯ ТЕСТОВ (13.09.2026). Тесты 59 файлов зовут sendPushToAgent(s)
 * с реальными часами и ждут немедленной отправки. Прогон между 21:00 и 08:00
 * по Душанбе (CI на main 13.09 упал ровно в 21:00) откладывал пуш в очередь, и
 * тесты красились без единой правки в коде. `tests/setup.ts` ставит
 * PUSH_QUIET_HOURS=off на каждый файл; файл, проверяющий саму тишину,
 * возвращает `on`. В проде переменная не задана — правило действует.
 */
export function quietHoursDisabledByEnv(): boolean {
  return process.env.PUSH_QUIET_HOURS === "off";
}

export function quietDecision(payload: Pick<PushPayload, "kind" | "realtime" | "close">, at: Date = new Date()): QuietDecision {
  if (quietHoursDisabledByEnv()) return "send";
  // Закрытие уведомления на устройстве (`close`) — не звонок, а уборка уже
  // показанной карточки: задерживать её значит оставить на экране зов к
  // карточке, которая уже не твоя. Проходит всегда.
  if (payload.close) return "send";
  if (payload.realtime) return "send";
  if (!isQuietHour(at)) return "send";
  return payload.kind && DROP_KINDS.has(payload.kind) ? "drop" : "defer";
}
