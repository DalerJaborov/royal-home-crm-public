/**
 * «Звонок ждёт разбора человеком» — одно определение на всю CRM.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ. Это условие спрашивают три места: список «Только без
 * разбора» на странице «Звонки», счётчик на плитке телефонии и значок новизны на
 * дашборде. Пока оно было переписано в каждом из них руками, любое изменение
 * правила требовало вспомнить про все три — и 18.08.2026, когда к разбору
 * добавились сообщения автоответчика, два места из трёх продолжили бы показывать
 * старую цифру, а владелец увидел бы у одной и той же вещи два разных числа.
 *
 * ЧТО ВХОДИТ В РАЗБОР:
 *  — состоявшийся разговор: оператор поговорил, но тип обращения не указан;
 *  — сообщение на автоответчике, которое CRM не смогла разобрать сама.
 * Оба случая объединяет одно: о человеке есть что узнать, а CRM этого не знает.
 *
 * ЧЕГО НЕТ: пропущенных без сообщения (разбирать нечего — там задача перезвонить)
 * и СОСТОЯВШИХСЯ РАЗГОВОРОВ без карточки (их не с чем связать: автосоздание было
 * выключено).
 *
 * ПОЧЕМУ У АВТООТВЕТЧИКА КАРТОЧКА НЕ ТРЕБУЕТСЯ (30.08.2026). С этого дня сообщение
 * без расшифровки карточку не заводит вовсе (см. voicemailIngest.ts и ветку
 * «нет расшифровки» в autoLeadFromCall.ts): пустышки «Входящий +992…» по записям на
 * 13-26 секунд мусорили базу, их не мог разобрать ни человек, ни автоматика.
 * Но само сообщение разобрать МОЖНО — запись лежит и её слышно. Оставь мы здесь
 * общее требование `clientId != null`, такой звонок исчез бы из очереди человека
 * совсем: карточки нет, значит и в списке нет, — то есть, убрав мусор, мы бы
 * потеряли живое обращение. Для разговора условие прежнее: там разбирать нечего,
 * пока некого связывать.
 */
