import type { Prisma } from "../../generated/prisma/client.js";

/**
 * «Входящий звонок КАСАЕТСЯ ЛИЧНО МЕНЯ» — одно определение на всю CRM.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ — по той же причине, что и соседний awaitingReview.ts:
 * условие спрашивают ДВА места, и они уже разошлись. Лента звонков (routes/calls.ts,
 * GET /feed) сужала выборку до своего, а значок «Мои звонки» на дашборде
 * (routes/dashboard.ts, GET /counters) считал разговоры, ждущие разбора, по ВСЕМУ
 * агентству. Итог на проде: в меню горит красная «3», агент открывает раздел — там
 * пусто, потому что все три звонка чужие. Раздел выглядит сломанным, хотя сломан был
 * счётчик. Ровно тот же случай, что разбирали 03.09.2026 у вакансий, и то же правило,
 * записанное там же в dashboard.ts: счётчик обязан считать ровно то, что человек
 * увидит, открыв раздел.
 *
 * ЧТО СЧИТАЕТСЯ СВОИМ. Три способа оказаться причастным к входящему:
 *  — тебе назначено перезвонить (callbackAgentId);
 *  — звонил твой клиент (client.assignedAgentId);
 *  — ты сам снял трубку (answeredBy — станция пишет в звонок ВНУТРЕННИЙ НОМЕР,
 *    а не сотрудника, см. schema.prisma; поэтому номер приходит параметром).
 *
 * ВНУТРЕННЕГО НОМЕРА МОЖЕТ НЕ БЫТЬ (sipExtension = null у сотрудника без SIP):
 * тогда третье условие просто не добавляется. Пустую строку сюда пускать нельзя —
 * `answeredBy: ""` совпало бы со звонками, где станция номер не записала вовсе.
 */
export function ownIncomingCallsOr(
  agentId: string,
  sipExtension: string | null | undefined
): Prisma.IncomingCallWhereInput[] {
  return [
    { callbackAgentId: agentId },
    { client: { assignedAgentId: agentId } },
    ...(sipExtension ? [{ answeredBy: sipExtension }] : []),
  ];
}
