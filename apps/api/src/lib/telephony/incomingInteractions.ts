import { prisma } from "../../db.js";

/**
 * Какие записи хронологии на самом деле НЕ работа агента, а входящий звонок.
 *
 * ЗАЧЕМ. Устарело: до 17.09.2026 `Interaction` писался от имени ОТВЕТСТВЕННОГО
 * (assignedAgentId) агента карточки, хотя говорил с клиентом кто-то другой. С П-10
 * (17.09.2026, docs/audit/recon-17-09) автор — тот, кто реально ответил: оператор
 * (`operator.id`) или агент, которому звонок маршрутизирован (`routedAgentId`), см.
 * lib/telephony/incomingCalls.ts::agentAuthorId. Для истории клиента это правильно:
 * разговор был, и он должен быть виден. Для оценки работы ОТВЕТСТВЕННОГО агента — нет:
 * если ответил не он, а клиент позвонил сам, запись всё равно не его заслуга/недоработка.
 *
 * Пока правило жило внутри одной функции (`leads.ts::collectFirstCallFacts`), оно
 * действовало ровно в одном месте из четырёх: агенту засчитывалась «скорость первого
 * ответа» за то, что клиент сам позвонил в офис, — вплоть до полного балла за
 * звонок, на который агент не ответил вовсе. Та же ошибка в «Активности за месяц».
 * Это ровно тот случай, о котором предупреждает шапка `lib/clientPhone.ts`: правило,
 * записанное в одном маршруте, правилом не является.
 *
 * Пустой список на входе — пустое множество без обращения к базе: метрики считаются
 * по каждому агенту за каждый день, и лишний запрос здесь дорог.
 */
export async function incomingInteractionIds(interactionIds: string[]): Promise<Set<string>> {
  if (interactionIds.length === 0) return new Set();
  const rows = await prisma.incomingCall.findMany({
    where: { interactionId: { in: interactionIds } },
    select: { interactionId: true },
  });
  return new Set(rows.map((r) => r.interactionId).filter((id): id is string => !!id));
}
