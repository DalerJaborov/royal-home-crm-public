import { BW, EW } from "../ai/wordBoundary.js";

/**
 * Кому видно, ОТКУДА пришёл клиент — одно правило на всю CRM.
 *
 * Решение владельца 17.08.2026, дословно: «ник полностью скрыть от агентов
 * навсегда, пусть бот всегда записывает людей по имени, записывая их с номером
 * телефона, и агентам нельзя показывать нигде, откуда клиент пришёл, ватсап или
 * инстаграм — это только для руководителя и админа».
 *
 * ЗАЧЕМ. Ник соцсети — это способ найти клиента в обход агентства. По
 * «@tabarovmukhammadzoir» человек находится в Instagram за секунду; дальше ему
 * пишут напрямую, и ни разговора, ни следа в CRM не остаётся. Ровно та же беда, от
 * которой закрыт телефон (см. lib/clientPhone.ts), и закрывается так же.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПРОВЕРКА В МАРШРУТЕ. Урок уже дважды выучен на
 * телефоне и контактах собственников, и записан там же дословно: «правило,
 * записанное в одном маршруте, не является правилом». Источник клиента приходит в
 * список клиентов, в карточку, в инбокс «Сообщения», в дубликаты и в переписку —
 * закрыть его в одном месте значит оставить пять открытых.
 *
 * ЧТО ИМЕННО ЗАКРЫТО:
 *  - `source` карточки (INSTAGRAM / WHATSAPP / TELEGRAM / …) — заменяется на null;
 *  - `socialUsername` и `socialChannel` карточки — ник соцсети отдельным полем
 *    (появилось 30.08.2026). Оно заведено ради поиска для админа и директора
 *    («чтобы они с лёгкостью даже через поиск могли их искать»), и ровно поэтому
 *    агенту его нельзя показывать: ник — самая короткая дорога к клиенту в обход
 *    агентства. Скрывается ЗДЕСЬ, а не в маршрутах, — иначе поле, добавленное в
 *    шестой ответ, уедет агенту открытым;
 *  - ник вместо имени у старых карточек, заведённых до 17.08 (в новых ник в имя уже
 *    не пишется, см. cardName в messengers/conversation.ts) — заменяется нейтральной
 *    подписью;
 *  - `channel` и `name` диалога в инбоксе.
 *
 * ЧТО НЕ ЗАКРЫТО НАМЕРЕННО: сама переписка. Агент обязан видеть, о чём
 * договаривались с клиентом, иначе он не сможет с ним работать. Скрывается
 * подсказка, по которой человека находят снаружи, а не содержание разговора.
 */

/** Признак руководителя: право `clients.viewOrigin`. Роль не годится — директор
 *  может выдать или закрыть его конкретному сотруднику. */
export type CanSeeOrigin = boolean;

/** Нейтральная подпись вместо ника. Без канала в тексте: он сам по себе
 *  та подсказка, которую мы прячем, — «Клиент из Instagram» выдавала бы её. */
export const HIDDEN_ORIGIN_NAME = "Клиент";

/**
 * Похоже на ник соцсети, а не на имя? Ник узнаётся по «@» в начале — именно так их
 * писал resolveInstagramName. Отдельно перечислять «Клиент из Instagram» и прочие
 * прежние подписи каналов не нужно: они тоже выдают канал, и их ловит вторая
 * проверка ниже.
 */
function looksLikeHandle(name: string): boolean {
  const trimmed = name.trim();
  // Латинские названия ловились, а кириллические — нет: `\b` в JS считается по
  // латинице (см. ai/wordBoundary.ts). Подпись «инстаграм» проходила как имя
  // человека, и бот обращался к клиенту «Инстаграм».
  return (
    trimmed.startsWith("@") ||
    new RegExp(`${BW}(instagram|инстаграм|whatsapp|ватсап|вотсап|telegram|телеграм)${EW}`, "iu").test(
      trimmed
    )
  );
}

/**
 * СТРОКА — ЭТО НИК СОЦСЕТИ, А НЕ ИМЯ ЧЕЛОВЕКА?
 *
 * Признак взят слово в слово из lib/telephony/whisperText.ts (isSpeakablePiece,
 * шапка на строке 217): там его вывели на живом журнале прода — «имя в карточке
 * приходит из Instagram, а там вместо имени часто стоит ник (@nozil760) или логин
 * строчными латиницей (raxxmanzadee)». Третьей формулировки этого признака в
 * репозитории быть не должно: правило одно, место одно — здесь.
 *
 *  - «@что-то» — так их писал resolveInstagramName;
 *  - одно слово латиницей БЕЗ заглавной — так пишут логины, а имена люди пишут с
 *    заглавной. «Hokimshoh» и «Alex» не трогаем намеренно: это настоящие имена.
 *
 * Используется скриптом переноса ников из имени в поле socialUsername
 * (scripts/move-social-username-out-of-names.ts). В clientNameFor НЕ подставлен
 * намеренно: там задача обратная — не потерять настоящее имя, и лишняя строгость
 * превратила бы в «Клиент» человека, чьё имя просто записали строчными.
 */
const LATIN_LOGIN = /^[a-z][a-z0-9._-]*$/;

export function looksLikeSocialUsername(value: string): boolean {
  const trimmed = value.trim();
  // Ник — всегда одно слово: «Азиз Инстаграм» это имя с припиской, а не логин.
  if (!trimmed || /\s/.test(trimmed)) return false;
  return trimmed.startsWith("@") || LATIN_LOGIN.test(trimmed);
}

/** Имя клиента в том виде, в каком его можно показать этому сотруднику. */
export function clientNameFor(fullName: string, canSeeOrigin: CanSeeOrigin): string {
  if (canSeeOrigin) return fullName;
  return looksLikeHandle(fullName) ? HIDDEN_ORIGIN_NAME : fullName;
}

/**
 * Применяет правило к карточке клиента в любом ответе. Возвращает новый объект,
 * исходный не меняется — как withMaskedClient в lib/clientPhone.ts.
 *
 * Дженерик, а не конкретный тип: одни маршруты отдают карточку целиком, другие —
 * несколько полей, и требовать полный тип значило бы либо тянуть лишние поля из
 * базы, либо приводить типы руками в каждом месте.
 */
export function withHiddenOrigin<
  T extends {
    fullName?: string;
    source?: string | null;
    socialUsername?: string | null;
    socialChannel?: string | null;
  } | null | undefined,
>(entity: T, canSeeOrigin: CanSeeOrigin): T {
  if (!entity || canSeeOrigin) return entity;
  return {
    ...entity,
    ...(typeof entity.fullName === "string" ? { fullName: clientNameFor(entity.fullName, false) } : {}),
    // null, а не строка-заглушка: интерфейс уже умеет не рисовать пустой источник,
    // а «скрыто» пришлось бы отдельно переводить и объяснять в каждом месте.
    ...("source" in entity ? { source: null } : {}),
    // Ник и его сеть — там же и по той же причине. Обнуляем ОБА: один только канал
    // («Instagram») уже отвечает на вопрос «откуда пришёл», ради которого всё затевалось.
    ...("socialUsername" in entity ? { socialUsername: null } : {}),
    ...("socialChannel" in entity ? { socialChannel: null } : {}),
  };
}

/**
 * То же для диалога переписки: у него канал лежит своим полем, а ник — в `name`.
 *
 * `channel` обнуляем, потому что по нему интерфейс рисует значок мессенджера — а
 * значок и есть ответ на вопрос «откуда пришёл», ради которого всё затевалось.
 */
export function withHiddenConversationOrigin<
  T extends { channel?: string | null; name?: string | null } | null | undefined,
>(conversation: T, canSeeOrigin: CanSeeOrigin): T {
  if (!conversation || canSeeOrigin) return conversation;
  return {
    ...conversation,
    ...(typeof conversation.name === "string" ? { name: clientNameFor(conversation.name, false) } : {}),
    ...("channel" in conversation ? { channel: null } : {}),
  };
}
