import { timingSafeEqual } from "node:crypto";

/**
 * Сравнение общих секретов (X-Api-Key, служебный токен) без утечки по времени.
 *
 * Обычный `!==` выходит на первом несовпавшем байте: время ответа зависит от того,
 * сколько символов ключа угаданы, и ключ подбирается посимвольно. `timingSafeEqual`
 * этого не делает — но БРОСАЕТ при разной длине буферов, поэтому длину проверяем
 * отдельно (сама длина секретом не является: она известна из формата ключа).
 *
 * Один хелпер на весь API намеренно: раньше правильное сравнение было только у
 * служебного токена (routes/morningReport.ts) и подписи Meta (messengers/meta.ts),
 * а четыре вебхука сайта сравнивали ключ через `!==` — несогласованность со своим
 * же стандартом (аудит 12.08.2026, пункт Е).
 */
export function secretsMatch(a: string, b: string): boolean {
  const bufA = Buffer.from(a);
  const bufB = Buffer.from(b);
  return bufA.length === bufB.length && timingSafeEqual(bufA, bufB);
}
