export { foldTajikLetters, geoMatchKey, normalizeGeoText, transliterateLatin } from "@royal-home/shared";
import { foldTajikLetters } from "@royal-home/shared";

/**
 * ЗАПРОС БЕЗ ТАДЖИКСКОГО НАПИСАНИЯ (28.09.2026). Словарь синонимов хранит улицу
 * и по-русски («улица дехоти», «дехоти»), и по-таджикски («кӯчаи деҳотӣ»), но
 * так, как её пишут на самом деле, — «кучаи Дехоти 8», «хиёбони Рудаки 45»,
 * «Рӯдакӣ 45» — в словаре нет ни одной строки: вид улицы по-таджикски русскими
 * буквами или таджикские буквы без вида. Точный и префиксный поиск
 * промахивались, дом не находился.
 *
 * Здесь — второй вариант уже нормализованного запроса: таджикские буквы
 * свёрнуты, слово-вид впереди снято («дехоти 8», «рудаки 45») — короткое имя
 * улицы в словаре есть всегда. Базу не меняет (см. `foldTajikLetters`).
 * Возвращает строку, совпадающую со входом, если сводить нечего.
 */
const LEADING_STREET_KIND = /^(?:кучаи|куча|хиебони|хиёбони|гузаргохи|улица|ул|проспект|просп|пр т|пр|kuchai|khiyoboni|ulitsa|prospekt)\s+/;

export function plainStreetQuery(normalized: string): string {
  return foldTajikLetters(normalized).replace(LEADING_STREET_KIND, "").trim();
}
