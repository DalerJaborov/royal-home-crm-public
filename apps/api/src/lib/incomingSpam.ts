/**
 * Рассылки в директ — отсечка ДО вызова ИИ.
 *
 * ЗАЧЕМ. В Instagram Direct и WhatsApp приходит поток чужой рекламы: «заработок на
 * крипте», приглашения в телеграм-каналы, продвижение аккаунтов. Каждое такое
 * сообщение проходило весь путь настоящего клиента — скачивание вложений, разбор
 * видео, ход модели, — и стоило денег. Бот при этом честно и вежливо отвечал
 * спам-боту, что тоже не бесплатно: это сообщение в лимите переписок Meta.
 *
 * ГЛАВНОЕ ТРЕБОВАНИЕ — НЕ ЗАДЕТЬ ЖИВОГО. Ложно принятый за спам клиент не получает
 * ответа вовсе и уходит молча; мы даже не узнаем, что потеряли его. Поэтому правила
 * здесь заведомо трусливые: одного подозрительного слова НИКОГДА не хватает.
 *
 * Отдельно перечислено, что спамом НЕ является, хотя выглядит похоже. «Ипотека»,
 * «рассрочка», «кредит», «инвестиции», «доход» — обычные слова разговора о
 * недвижимости: человек спрашивает, можно ли купить в рассрочку, и это самый
 * желанный вопрос из всех. Ни одно из них не считается признаком само по себе.
 *
 * Известный клиент (у диалога есть карточка) не проверяется вовсе — вызывающий
 * решает это до обращения сюда.
 */

import { BW, EW, TAIL } from "../ai/wordBoundary.js";

export interface SpamVerdict {
  /** Короткая причина для инбокса: агент видит, почему бот промолчал. */
  reason: string;
}

/**
 * Приглашения на чужие площадки и сокращатели ссылок. Это самый сильный признак:
 * настоящему клиенту незачем звать агентство недвижимости в телеграм-канал, а
 * сокращатель в первом же сообщении незнакомого человека — почти всегда реклама.
 *
 * wa.me и обычный t.me/username сюда НЕ входят: первым делятся своим же номером,
 * вторым — личным аккаунтом, и оба встречаются у живых людей.
 */
const INVITE_LINKS = /(t\.me\/(joinchat|\+)|chat\.whatsapp\.com\/|bit\.ly\/|tinyurl\.com\/|cutt\.ly\/|is\.gd\/)/i;

/** Любая ссылка — сама по себе не признак, но усиливает остальные. */
const ANY_LINK = /https?:\/\/|www\./i;

/**
 * Словарь чужого бизнеса. Каждое слово подобрано так, чтобы не встречаться в
 * разговоре о квартире в Душанбе: заработок в интернете, ставки, криптовалюта,
 * продвижение аккаунтов.
 */
const SPAM_WORDS = [
  /крипт/i,
  /биткоин|bitcoin|usdt|binance/i,
  /майнинг/i,
  /трейдинг|трейдер/i,
  /казино|casino|1xbet|букмекер|ставки на спорт/i,
  /заработок|заработай|подработка на дому/i,
  /накрутк/i,
  /продвижение (аккаунт|страниц|инстаграм)/i,
  /подпишись|подписывайтесь на (наш|мой) канал/i,
  /пассивный доход/i,
  /работа на дому/i,
];

/**
 * НАКРУТКА ЛАЙКОВ И ПРОСМОТРОВ (замечание владельца 16.08.2026).
 *
 * Новый вид рассылки: человек присылает в директ ЧУЖОЙ ролик — обычно музыкальный
 * или развлекательный — и просит поставить лайк, подписаться или просто «посмотреть»
 * ради просмотров. Бот честно отвечал такому и даже пытался выяснить, сколько комнат
 * в квартире на видео.
 *
 * ОДНО СЛОВО ЗДЕСЬ ЗНАЧИТ БОЛЬШЕ, ЧЕМ В ОБЩЕМ СЛОВАРЕ, но всё равно не решает само:
 * «лайк» изредка встречается и в живом разговоре («видел ваш пост, лайк поставил»).
 * Решает СВЯЗКА со ПЕРЕСЛАННОЙ ПУБЛИКАЦИЕЙ: просьба про лайк вместе с чужим
 * роликом — это ровно накрутка, других объяснений у неё нет.
 */
const ENGAGEMENT_WORDS = [
  /лайк/i,
  /\blike\b/i,
  /подпис(ка|ку|аться|ись|ывайся|ываемся)|подпиш(ись|итесь|и)/i,
  /обуна шав|обуна шудан|обуна кун/i,
  // `взаимн[оа]\b` и `просмотр(ы|ов|а)?\b` не совпадали НИ С ЧЕМ: в JS `\b`
  // считается по латинице, и после кириллической буквы границы нет вовсе
  // (см. ai/wordBoundary.ts). Две строки словаря накрутки стояли мёртвыми —
  // «поставь просмотры» и «взаимно подпишемся» проходили как обычная реплика.
  new RegExp(`взаимн(ая|ую) подписк|${BW}взаимн[оа]${EW}`, "iu"),
  new RegExp(`${BW}просмотр(ы|ов|а|ами)?${EW}`, "iu"),
  /репост|шер кун/i,
  /поддержи (мой|наш)|дастгирӣ кун/i,
];

/**
 * ДЛЯ СВЯЗКИ «ЧУЖОЙ РОЛИК + ОДНО СЛОВО» — ТОЛЬКО ЯВНАЯ НАКРУТКА (QA 02.10.2026).
 * «Просмотр» в единственном здесь не годится: «можно на просмотр завтра?» после
 * присланного объявления — самый горячий клиент, а связка глушила его полностью.
 * «Накинь просмотры» (множественное) — накрутка и остаётся.
 */
const ATTACHMENT_ENGAGEMENT_WORDS = [
  ...ENGAGEMENT_WORDS.filter((re) => !re.source.includes("просмотр")),
  // Множественное — это «просмотры ролика» (накрути просмотры); «просмотр» и
  // «на просмотр» в единственном — осмотр квартиры.
  new RegExp(`${BW}просмотр(ы|ов|ами)${EW}`, "iu"),
];

/** Вопрос клиента про цену, жильё или встречу — с ним «лайк» не накрутка:
 *  «лайкнул ваш пост, сколько стоит?». Целыми словами (ai/wordBoundary.ts). */
const CLIENT_QUESTION = new RegExp(
  `${BW}(?:сколько|чанд|нарх${TAIL}|цен${TAIL}|стоит|хона${TAIL}|квартир${TAIL}|ҳавлӣ|просмотр(?:а|е|у)?|адрес${TAIL}|куҷо|кучо|где)${EW}`,
  "iu"
);

/**
 * ВЕЖЛИВОЕ «ПОСМОТРИТЕ, ПОЖАЛУЙСТА» — ОТДЕЛЬНО ОТ НАКРУТКИ (21.09.2026).
 *
 * «Бинед лутфан», «дидани кун», «посмотрите» стояли в одном списке с «поставь
 * лайк», а связка «пересланная публикация + одно слово оттуда» даёт ПОЛНОЕ
 * молчание. Но «посмотрите, пожалуйста» вместе с чужим объявлением — это самый
 * обычный горячий клиент: он переслал то, что нашёл, и просит посмотреть.
 * Отсечённый так человек не получает ответа вовсе и уходит молча, а мы даже не
 * узнаём, что его потеряли, — ровно то, чего этот модуль обещает не делать.
 *
 * Поэтому вежливая просьба посмотреть считается признаком только В ПАРЕ с другим:
 * «посмотрите и подпишитесь» — накрутка, «бинед лутфан» само по себе — клиент.
 */
const POLITE_LOOK_WORDS = [/дидан(и)? кун|бинед лутфан/i, /поделись/i];

/** Длина, после которой сообщение перестаёт быть похожим на реплику в переписке. */
const BLAST_LENGTH = 1200;

/** Что известно о сообщении помимо текста — нужно для накрутки (см. выше). */
export interface SpamContext {
  /** Клиент переслал публикацию или рилс (attachmentType share / ig_reel). */
  sharedPost?: boolean;
  /** Публикация опознана как НАША — тогда это горячий клиент, а не накрутка. */
  ourPost?: boolean;
  /**
   * Комментарий под НАШЕЙ публикацией (02.10.2026). Словарь писан для личных
   * сообщений от незнакомцев, а под нашим постом «Лайк и подписка, классно
   * снимаете! Цена?» — похвала, и «Можно оплатить криптой или USDT?» — вопрос
   * покупателя. Здесь не работает правило «лайк + подписка», а вопрос без
   * ссылки спамом не считается.
   */
  comment?: boolean;
}

/**
 * ЧТО СЧИТАТЬ «ПЕРЕСЛАЛИ ЧУЖОЕ», А ЧТО «ПОКАЗЫВАЮТ НА НАШЕ» — ОДНО МЕСТО.
 *
 * Решение жило строчкой в разборе вебхука, и в ней была дыра (жалоба владельца
 * 21.09.2026: «на спам отвечает, когда по рекламе нам отправляют своё видео»):
 * ЛЮБОЙ приход с рекламы выключал проверку на накрутку целиком — `sharedPost`
 * становился false, а `ourPost` true. Замысел был в том, что человек с нашей
 * рекламы пересылает нашу же публикацию. Но реклама — это ровно то, как нас
 * НАХОДЯТ рассылки: спамер кликает объявление и присылает свой ролик с
 * «подпишись, поставь лайк», а проверка на него не смотрела вовсе.
 *
 * Освобождение остаётся там, где мы ДЕЙСТВИТЕЛЬНО знаем, что показывают своё:
 * публикация опознана в нашей ленте, объявление сопоставлено с объектом, или это
 * пост вакансии. Сам факт прихода с рекламы таким знанием не является.
 */
export function sharedPostSpamContext(input: {
  /** Пересланная публикация или рилс (isSharedPost по типу вложения). */
  sharedPost: boolean;
  /** Публикация найдена в НАШЕЙ ленте (messengers/ownMedia.ts). */
  ownMedia: boolean;
  /** Объявление сопоставлено с конкретным объектом. */
  adProperty: boolean;
  /** Это пост вакансии (lib/vacancyPosts.ts). */
  vacancyPost: boolean;
  /** Объект по пересланному посту узнан в базе (findSharedProperty, sharedPostCard.ts):
   *  пост наш, даже если наша лента в этот момент не прочиталась (02.10.2026). */
  recognizedProperty?: boolean;
}): SpamContext {
  return {
    sharedPost: input.sharedPost,
    ourPost: input.ownMedia || input.adProperty || input.vacancyPost || Boolean(input.recognizedProperty),
  };
}

/**
 * Похоже ли сообщение на рассылку.
 *
 * Порог — ДВА очка. Приглашение на чужую площадку сразу даёт два: одного такого
 * признака достаточно. Слово из чужого словаря даёт одно, ссылка — одно, и вместе
 * они тоже дают два. Одно слово без ссылки не отсекается никогда: «крипта» в
 * разговоре про оплату квартиры звучит редко, но звучит.
 */
export function detectSpam(text: string, context: SpamContext = {}): SpamVerdict | null {
  const trimmed = text.trim();

  /**
   * НАКРУТКА: чужая публикация плюс просьба про лайк, подписку или просмотр.
   *
   * Проверяем ДО отсечки пустого текста? Нет: пустой текст тут ничего не решает.
   * Одно только пересланное чужое видео БЕЗ слов спамом не считаем никогда —
   * клиенты постоянно присылают чужие объявления с вопросом «а такое есть?», и
   * отсечь их значит потерять самых горячих.
   */
  if (
    context.sharedPost &&
    !context.ourPost &&
    ATTACHMENT_ENGAGEMENT_WORDS.some((re) => re.test(trimmed)) &&
    !CLIENT_QUESTION.test(trimmed)
  ) {
    return { reason: "накрутка лайков и просмотров: чужое видео с просьбой лайкнуть" };
  }

  if (!trimmed) return null;

  // Две просьбы про лайки/подписку в одном сообщении — накрутка и без вложения:
  // живому клиенту незачем просить агентство о взаимной подписке.
  const engagementHits =
    ENGAGEMENT_WORDS.filter((re) => re.test(trimmed)).length +
    POLITE_LOOK_WORDS.filter((re) => re.test(trimmed)).length;
  if (engagementHits >= 2 && !context.comment) {
    return { reason: "просьба о лайках и взаимной подписке" };
  }

  if (INVITE_LINKS.test(trimmed)) return { reason: "приглашение в чужой канал или сокращённая ссылка" };

  const words = SPAM_WORDS.filter((re) => re.test(trimmed));
  const hasLink = ANY_LINK.test(trimmed);
  if (context.comment && !hasLink && trimmed.includes("?")) return null;

  if (words.length >= 2) return { reason: "реклама чужого бизнеса" };
  if (words.length === 1 && hasLink) return { reason: "реклама со ссылкой" };

  // Простыня со ссылкой и без единого вопроса — это объявление, а не обращение.
  // Вопросительный знак важен: длинное письмо с вопросом пишет живой человек,
  // которому есть что рассказать о своей квартире.
  if (trimmed.length > BLAST_LENGTH && hasLink && !trimmed.includes("?")) {
    return { reason: "длинное рекламное сообщение со ссылкой" };
  }

  return null;
}
