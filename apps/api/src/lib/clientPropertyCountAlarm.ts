/** Выдержка продавцу, в РАБОЧИХ днях: первый заявленный объект — дороже остальных. */
export const SELLER_GRACE_WORKING_DAYS_FIRST = 3;
export const SELLER_GRACE_WORKING_DAYS_NEXT = 2;
export const BUYER_GRACE_DAYS_PER_UNIT = 5;

/** Сколько рабочих дней у агента на N заявленных продавцом объектов. */
export function sellerGraceWorkingDays(declared: number): number {
  if (declared <= 0) return 0;
  return SELLER_GRACE_WORKING_DAYS_FIRST + (declared - 1) * SELLER_GRACE_WORKING_DAYS_NEXT;
}

