/**
 * ЧАСТНОЕ ОБЪЯВЛЕНИЕ ПОД НАШИМ ПОСТОМ — ОТСЕЧКА КОДОМ, БЕЗ ХОДА МОДЕЛИ
 * (жалоба владельца 24.09.2026, снимок из Instagram).
 *
 * Под роликом royal.home.tj человек выложил своё объявление целиком: «Хона дорем
 * да Маладёжний… Хона 58квадрат… да 15 этаж доми 19 этажа. Нарх 580. Хазор сомон
 * номер 980001010 занг занед». Девять часов оно висело открытым. Спам-словарь
 * (lib/incomingSpam.ts) его не видит — там крипта и ставки, а не квартиры, — и
 * решение оставалось за моделью, у которой в промте стояли два правила сразу:
 * «продают свою квартиру — удаляй» и «человек предлагает свою квартиру — отвечай
 * как продавцу». Какое из них она выберет, от комментария к комментарию не
 * угадать; владелец видит результат — не скрыто.
 *
 * Отличать надо ОБЪЯВЛЕНИЕ ДЛЯ НАШИХ ЧИТАТЕЛЕЙ от ВОПРОСА К НАМ. «Хочу продать
 * квартиру, какие у вас условия?» — наш будущий продавец, ему отвечают. Объявление
 * другое: в нём подробности квартиры (цена числом, площадь, этаж, комнаты) и
 * номер, по которому звонить не нам, а ему. Поэтому правило трусливое, как и
 * спам-словарь: номер телефона ОБЯЗАТЕЛЕН, подробностей — не меньше двух, и одна
 * из них — цена числом либо «продаю / есть квартира». Всё, что не дотянуло,
 * по-прежнему решает модель.
 *
 * Покупатель, оставивший номер («нужна двушка до 500 тысяч, звоните»), похож на
 * объявление по всем признакам, кроме глагола, — отсюда слова покупателя, при
 * которых отсечка молчит.
 *
 * Кириллица: только BW/EW/TAIL из ai/wordBoundary.ts — `\b` и `\w` по русскому и
 * таджикскому тексту не срабатывают никогда (см. там же). Таджикские буквы
 * (ӯ ҳ қ ҷ ғ ӣ) люди в комментариях чаще пишут русскими (у х к ч г и) — каждое
 * слово ниже принимает оба написания.
 */

import { BW, EW, TAIL } from "../ai/wordBoundary.js";
import { extractAllPhones } from "../ai/leadQualifier.js";

export interface ListingAdVerdict {
  /** Какие признаки сошлись — для пометки в ленте комментариев. */
  reason: string;
  /** Найденные номера в формате +992…, первый — основной. */
  phones: string[];
}

const re = (source: string) => new RegExp(source, "iu");

/** «Продаю», «продаётся», «сдаю», «мефурӯшам», «фурӯш», «ба иҷора медиҳам». */
const SELL_VERB = re(
  `${BW}(прода[её]тся|продаю|продам|продажа|сда[её]тся|сдаю|мефур[уӯ]ш${TAIL}|фур[уӯ]ш${TAIL}|фур[уӯ]хта${TAIL}|ба\\s+и[чҷ]ора\\s+меди[хҳ]${TAIL})`
);

/** «Хона дорем», «хонаам дорам», «ҳавлӣ дорем», «есть квартира», «у меня квартира». */
const HAVE_FLAT = re(
  `${BW}((хона|[хҳ]авл[иӣ]|замин|квартира)${TAIL}\\s+(\\p{L}+\\s+){0,2}дор(ем|ам|ад)${EW}|(есть|у\\s+меня|у\\s+нас)\\s+(\\p{L}+\\s+){0,2}(квартир|дом|участ|хона)${TAIL})`
);

/** Цена числом: «Нарх 580», «цена: 45 000», «580 хазор», «600 000 сомон», «45000$». */
const PRICE = re(
  `(${BW}(нар[хҳ]${TAIL}|цена|стоимость)\\s*[:\\-–]?\\s*\\d)|(\\d[\\d\\s.,]*\\s*(сомон${TAIL}|смн|somoni|тыс${TAIL}|[хҳ]азор${TAIL}|доллар${TAIL}|\\$|usd))`
);

/** Площадь числом: «58квадрат», «60 м2», «60 кв.м», «80 метр». */
const AREA = re(`\\d+\\s*(квадрат${TAIL}|кв\\.?\\s*м|кв${EW}|м2|м²|метр${TAIL}|сотик${TAIL}|соток)`);

/** Этаж числом: «15 этаж», «5-ошёна», «9 қабата». */
const FLOOR = re(`\\d+\\s*-?\\s*(этаж${TAIL}|о[шщ][ьи]?[её]?на${TAIL}|[кқ]абат${TAIL})`);

/** Комнаты числом: «2 хонагӣ», «3-комнатная», «2 ком.». */
const ROOMS = re(`\\d+\\s*-?\\s*(хонаг${TAIL}|комнат${TAIL}|ком\\.|к\\.?\\s*кв)`);

/** Покупатель или съёмщик — не объявление, а запрос. */
//
// «бюджет», «интересует», «позвоните мне», «ба ман занг» (02.10.2026): покупатель,
// оставивший номер под нашим постом, принимался за объявление или рекламу
// агентства — комментарий удалялся, а ему писали «видим, вы продаёте».
const BUYER = re(
  `${BW}(куплю|покупаю|купить|ищу|ищем|нужн${TAIL}|сниму|снять|мехарам|бихарам|харидан${TAIL}|харид(ор|ан)${TAIL}|лозим|даркор|мехо[хҳ]ам\\s+бихарам|` +
    `бюджет${TAIL}|интересу${TAIL}|позвоните\\s+мне|перезвоните|свяжитесь\\s+со\\s+мной|ба\\s+ман\\s+занг${TAIL}|ба\\s+ман\\s+нависед)${EW}`
);

/** Вопрос — это обращение к нам, а не объявление для читателей и не реклама. */
const QUESTION = /\?/;

/** Похвала агентству — не реклама другого агентства. */
const PRAISE = re(
  `${BW}(хорош${TAIL}|отличн${TAIL}|лучш${TAIL}|рекоменду${TAIL}|спасибо|ра[хҳ]мат|офарин|молод(ец|цы)|з[уӯ]р|класс${TAIL}|супер)${EW}`
);

/** Наши же страницы: «подписывайтесь @royal.home.tj» — это реклама НАС. */
const OWN_HANDLE = /@royal[._]?home/iu;

/**
 * Частное объявление о продаже/сдаче под нашим постом — или null.
 * Порог нарочно высокий: ложное срабатывание прячет живого человека.
 */
export function detectListingAd(text: string): ListingAdVerdict | null {
  const phones = extractAllPhones(text);
  if (phones.length === 0) return null;
  if (BUYER.test(text) || QUESTION.test(text)) return null;

  const signs: string[] = [];
  const sellOrHave = SELL_VERB.test(text) || HAVE_FLAT.test(text);
  if (sellOrHave) signs.push("продаёт");
  const price = PRICE.test(text);
  if (price) signs.push("цена");
  if (AREA.test(text)) signs.push("площадь");
  if (FLOOR.test(text)) signs.push("этаж");
  if (ROOMS.test(text)) signs.push("комнаты");

  if (signs.length < 2) return null;
  if (!price && !sellOrHave) return null;
  return { reason: `объявление: ${signs.join(", ")}, номер`, phones };
}

/**
 * РЕКЛАМА АГЕНТСТВА ИЛИ РИЕЛТОРА ПОД НАШИМ ПОСТОМ (владелец 24.09.2026: «если это
 * рекламное агентство — удалить, если собственник — пообщаться»).
 *
 * Слово агентства само по себе не приговор: «агентствам не беспокоить», «без
 * посредников», «сам собственник» — это частник, который как раз отгораживается
 * от агентств. Такие слова выключают отсечку. Кроме слова нужен ещё один признак
 * рекламы: номер, ссылка, @страница или «звоните / пишите».
 */
const AGENCY_WORD = re(
  `${BW}(агентств${TAIL}|агенти[иӣ]\\s+(амвол|недвиж)${TAIL}|агентии${EW}|риел?т[оеэ]р${TAIL}|риэлт[оеэ]р${TAIL}|маклер${TAIL}|` +
    `услуг${TAIL}\\s+(риел|риэл|по\\s+(продаж|подбор))${TAIL}|подбер[её]м${EW}|подбор\\s+(квартир|недвиж|жиль)${TAIL}|` +
    `большой\\s+выбор|(база|каталог)\\s+(квартир|объект|недвиж)${TAIL}|все\\s+районы|` +
    `подписывайтесь|подпишитесь|переходите\\s+(в|на)\\s+(наш|профил|страниц)${TAIL}|` +
    `хизматрасон${TAIL}|вариант([хҳ]ои|ҳо|хо)?\\s+(зиёд|бисёр)|бис[её]р\\s+вариант${TAIL}|[хҳ]амаи\\s+но[хҳ]ия${TAIL}|` +
    `обуна\\s+шавед|ба\\s+са[хҳ]ифаи\\s+мо)`
);

/** Частник отгораживается от агентств — это собственник, а не реклама агентства. */
const OWNER_WORD = re(
  `(${BW}(собственник${TAIL}|без\\s+посредник${TAIL}|сам\\s+прода${TAIL}|свою\\s+квартир${TAIL}|свой\\s+дом|` +
    `агентствам\\s+не|риел?торам\\s+не|аз\\s+со[хҳ]иб${TAIL}|со[хҳ]иб${TAIL}|бе\\s+миёнарав${TAIL}|хонаи\\s+[хҳ]удам|` +
    `[хҳ]авлии\\s+[хҳ]удам))`
);

const AD_CONTACT = re(
  `(https?:\\/\\/|www\\.|t\\.me\\/|wa\\.me\\/|(?<![\\p{L}\\p{N}.])@[a-z0-9_.]{3,}|${BW}(звоните|пишите|обращайтесь|` +
    `занг\\s+зан${TAIL}|нависед|ватсап${TAIL}|вотсап${TAIL}|whatsapp|telegram|телеграм${TAIL}))`
);

export interface AgencyAdVerdict {
  reason: string;
  phones: string[];
}

/** Реклама агентства или риелтора — или null. */
export function detectAgencyAd(text: string): AgencyAdVerdict | null {
  if (!AGENCY_WORD.test(text)) return null;
  if (OWNER_WORD.test(text)) return null;
  // Удаление необратимо, поэтому сомнение решается в пользу человека
  // (02.10.2026): покупатель, вопрос к нам, похвала и наша же страница — решает
  // модель, а не отсечка.
  if (BUYER.test(text) || QUESTION.test(text) || PRAISE.test(text) || OWN_HANDLE.test(text)) return null;
  const phones = extractAllPhones(text);
  if (phones.length === 0 && !AD_CONTACT.test(text)) return null;
  return { reason: "реклама агентства или риелтора", phones };
}

/**
 * Язык для письма собственнику: таджикский, если в тексте есть таджикские буквы
 * или частые таджикские слова, иначе русский. Под постами Royal Home пишут
 * по-таджикски чаще, но русский текст таджикскими буквами не пишут никогда.
 */
export function looksTajik(text: string): boolean {
  if (/[ҳӯқҷғӣ]/iu.test(text)) return true;
  return re(`${BW}(хона${TAIL}|дорем|дорам|нар[хҳ]${TAIL}|занг|аст|барои|мефур${TAIL}|ман|шумо|[хҳ]аст|нависед|ва|да|сомон${TAIL})${EW}`).test(
    text
  ) && !re(`${BW}(и|в|на|с|продаю|квартир${TAIL}|звоните|цена)${EW}`).test(text);
}

/** Что про объект можно прочитать из объявления — для подбора покупателей. */
export interface ListingFacts {
  /** Цена целиком (580 хазор → 580 000). null — числом не названа. */
  price: number | null;
  currency: "TJS" | "USD";
  areaSqm: number | null;
  floor: number | null;
  totalFloors: number | null;
  rooms: number | null;
}

const num = (raw: string) => Number(raw.replace(/[\s.,](?=\d{3}(\D|$))/g, "").replace(",", "."));

/**
 * Цена, площадь, этаж, этажность и комнаты из текста объявления.
 *
 * ЦЕНА В ТЫСЯЧАХ — ПО ОБЫЧАЮ ДУШАНБЕ. «Нарх 580» под квартирой — это 580 тысяч, а
 * не 580 сомони: объявления почти всегда называют цену в тысячах, с «хазор» или
 * без. Поэтому число меньше 10 000 рядом со словом цены или «хазор/тыс» читается
 * как тысячи; «млн» — как миллионы. Доллар — по «$», «доллар», «usd».
 */
export function parseListingFacts(text: string): ListingFacts {
  const currency: "TJS" | "USD" = /\$|доллар|usd|долл/iu.test(text) ? "USD" : "TJS";

  let price: number | null = null;
  const priceMatch =
    re(`${BW}(?:нар[хҳ]${TAIL}|цена|стоимость)\\s*[:\\-–]?\\s*(\\d[\\d\\s.,]*)\\s*(?:[.,]?\\s*(млн|миллион|[хҳ]азор|тыс))?`).exec(text) ??
    re(`(\\d[\\d\\s.,]*)\\s*[.,]?\\s*(млн|миллион|[хҳ]азор|тыс|сомон|смн|\\$|доллар|usd)`).exec(text);
  if (priceMatch) {
    const value = num(priceMatch[1].trim().replace(/[.,]$/, ""));
    const unit = (priceMatch[2] ?? "").toLowerCase();
    // «Нарх 580. Хазор сомон»: множитель стоит после точки — ищем его рядом отдельно.
    const tail = text.slice(priceMatch.index + priceMatch[0].length, priceMatch.index + priceMatch[0].length + 12);
    const thousandNear = /[хҳ]азор|тыс/iu.test(unit) || /^[\s.,]*([хҳ]азор|тыс)/iu.test(tail);
    if (Number.isFinite(value) && value > 0) {
      if (/млн|миллион/iu.test(unit)) price = value * 1_000_000;
      // «До 10 000 это тысячи» это обычай объявлений в сомони. Явно названный доллар
      // («Цена 9000 USD») берётся как есть, иначе 9000 $ становились 9 000 000 $ (аудит
      // 04.10.2026, CRM-LISTING01); тысячи в долларах называются словом («120 тыс $»).
      else if (thousandNear || (value < 10_000 && currency === "TJS")) price = value * 1000;
      else price = value;
    }
  }

  const areaMatch = /(\d+(?:[.,]\d+)?)\s*(?:квадрат|кв\.?\s*м|кв(?![\p{L}])|м2|м²|метр)/iu.exec(text);
  const roomsMatch = /(\d)\s*-?\s*(?:хонаг|комнат|ком\.|к\.?\s*кв)/iu.exec(text);

  // Этаж и этажность: «15/19», «15 этаж доми 19 этажа», «5 этаж из 9», «9-этажный».
  let floor: number | null = null;
  let totalFloors: number | null = null;
  const slash = /(\d{1,2})\s*\/\s*(\d{1,2})\s*(?:этаж|о[шщ])/iu.exec(text);
  if (slash) {
    floor = Number(slash[1]);
    totalFloors = Number(slash[2]);
  } else {
    const floors = [...text.matchAll(/(\d{1,2})\s*-?\s*(?:этаж|о[шщ][ьи]?[её]?н|[кқ]абат)/giu)].map((m) => Number(m[1]));
    if (floors.length > 0) floor = floors[0];
    if (floors.length > 1 && floors[1] >= floors[0]) totalFloors = floors[1];
    const of = /из\s+(\d{1,2})/iu.exec(text);
    if (totalFloors == null && of && floor != null && Number(of[1]) >= floor) totalFloors = Number(of[1]);
  }

  return {
    price,
    currency,
    areaSqm: areaMatch ? num(areaMatch[1]) : null,
    floor,
    totalFloors,
    rooms: roomsMatch ? Number(roomsMatch[1]) : null,
  };
}
