/**
 * Список районов для модели, которая выбирает район карточки (карточка, черновик объекта, факты продавца,
 * разбор звонка). «Рудаки» в списке рядом с адресами вида «пр. Рудаки 45» модель легко примет за район —
 * поэтому имя района поясняется прямо в списке. Сам выбор сверяет код (districtPickAllowed).
 */
export function districtListForPrompt(names: readonly string[]): string {
  return names.map((n) => (n === RUDAKI_DISTRICT_NAME ? `${n} (район области вокруг города; проспект и улица Рудаки в Душанбе — НЕ этот район)` : n)).join(", ");
}

/**
 * Модель назвала район «Рудаки» — принять, только если сами слова источника говорят о районе Рудаки
 * («ноҳияи Рӯдакӣ», «район Рудаки», «Сомониён»), а не о проспекте. Остальные районы — как есть.
 */
export function districtPickAllowed(name: unknown, sourceText: string | null | undefined): boolean {
  if (typeof name !== "string" || name.trim().toLowerCase() !== RUDAKI_DISTRICT_NAME.toLowerCase()) return true;
  return mentionsRudakiDistrict(sourceText);
}

