/** Город компании из знаний (AGENCY_FACTS.city) → «где работаем» словами клиента. */
export function serviceAreaIn(city: string, language: "ru" | "tg"): string {
  if (city !== "Душанбе") return language === "tg" ? `дар ${city}` : `в городе ${city}`;
  return language === "tg" ? "дар Душанбе ва ноҳияи Рӯдакӣ" : "в Душанбе и районе Рудаки";
}

/** «Пока работаем только …» — отказ по объекту вне зоны. Без точки в конце: тексты продолжают фразу. */
export function serviceAreaOnly(language: "ru" | "tg", city = "Душанбе"): string {
  return language === "tg" ? `Ҳоло мо танҳо ${serviceAreaIn(city, "tg")} кор мекунем` : `Пока работаем только ${serviceAreaIn(city, "ru")}`;
}

/** «Записали, спасибо. Пока работаем только …» — продавцу объекта вне зоны, без обещания звонка (владелец 17.09.2026). */
export function outsideAreaAcceptedText(language: "ru" | "tg"): string {
  return language === "ru"
    ? `Записали, спасибо. ${serviceAreaOnly("ru")}; если начнём работать в вашем городе — напишем.`
    : `Сабт кардем, раҳмат. ${serviceAreaOnly("tg")}; агар дар шаҳри шумо сар кунем, менависем.`;
}

/**
 * Любое упоминание Рудаки — и район, и проспект Рудаки в самом городе: для зоны это
 * неважно, оба наши. Источник регулярки (без флагов) — для отсечки чужой географии.
 */
export const RUDAKI_ANY_SOURCE = "р[уӯ]да[кқ][иӣ]|rudaki|сомониён|сомониен|somoniyon";

/**
 * Именно РАЙОН Рудаки, а не проспект: «ноҳияи Рӯдакӣ», «н. Рудаки», «р-н Рудаки», «район Рудаки»,
 * «Рудаки, район», «Рудакинский», райцентр Сомониён. Голое «Рудаки» сюда нарочно
 * не входит — это главный проспект Душанбе; «мкр-н Рудаки» — микрорайон, не район (ревью #204, Н2).
 * Сверяется по ключу geoMatchKey (буквы свёрнуты, знаки сняты).
 */
const RUDAKI_DISTRICT_KEY =
  /(^| )(нохияи рудаки|(?<!мкр )н рудаки|рудакинск|район\p{L}* рудаки|рудаки район$|сомониен)/u;
/**
 * ПРОСПЕКТ ИЛИ УЛИЦА РУДАКИ И ДРУГОЙ РАЙОН ГОРОДА В ТОЙ ЖЕ СТРОКЕ — НЕ РАЙОН РУДАКИ (повторное ревью #204, Н-1).
 * «пр. Рудаки, район Сино», «Шохмансур район, Рудаки 30», «ул. Рудаки, районе Фирдавси» — адреса в центре города:
 * без этой проверки объект на главном проспекте становился «за городом» и выпадал из поиска по районам.
 */
const RUDAKI_AS_STREET = /(^| )(пр|пр т|просп|проспект\p{L}*|ул|улиц\p{L}*|кучаи|куча|хиебони|шохрохи) рудаки/u;
const CITY_DISTRICT_WORD = /(^| )(сино|фирдавс\p{L}*|шохмансур\p{L}*|исмоил\p{L}* сомон\p{L}*)( |$)/u;

function rudakiDistrictInKey(key: string): boolean {
  return RUDAKI_DISTRICT_KEY.test(key) && !RUDAKI_AS_STREET.test(key) && !CITY_DISTRICT_WORD.test(key);
}

/** Текст говорит о районе Рудаки (не о проспекте и не об адресе в другом районе города). */
export function mentionsRudakiDistrict(text: string | null | undefined): boolean {
  if (!text) return false;
  return rudakiDistrictInKey(geoMatchKey(text));
}

/** Те же слова района — вырезать из ключа поиска места, чтобы «район Рудаки» не нашёлся проспектом. Не район — ключ как есть. */
export function stripRudakiDistrictWords(key: string): string {
  return rudakiDistrictInKey(key) ? key.replace(new RegExp(RUDAKI_DISTRICT_KEY.source, "gu"), " ") : key;
}

