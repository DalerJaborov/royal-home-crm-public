import { geoMatchKey } from "./geoNormalize.js";

/**
 * ЗОНА РАБОТЫ АГЕНТСТВА — ОДНО МЕСТО НА ВСЕ КАНАЛЫ (16.11.2026).
 *
 * Душанбе и район Рудаки. Решение владельца 15.11.2026, дословно: «Да, Рудаки берём».
 * До этого модуля решение жило двумя копиями только у чат-бота (регулярка в
 * ai/coverageGuard.ts и строка в сценарии продавца ai/leadQualifier.ts), а общие
 * тексты, которые читают И чат-бот, И голосовой робот, по-прежнему говорили «только
 * Душанбе» (ai/salesPlaybook.ts «ГЕОГРАФИЯ РАБОТЫ», ai/agencyFacts.ts <company_info>).
 * Робот отказал бы продавцу из Рудаки, а чат-бот получал два противоречащих правила.
 *
 * Кто читает:
 *  - ai/coverageGuard.ts — отсечка чужой географии (RUDAKI_ANY_SOURCE снимает её, как Душанбе);
 *  - ai/leadQualifier.ts — сценарий продавца (RUDAKI_SELLER_RULE);
 *  - ai/salesPlaybook.ts и ai/agencyFacts.ts — общие тексты обоих ботов (SERVICE_AREA_*);
 *  - lib/suburbanProperty.ts — поиск: район Рудаки «за городом» (mentionsRudakiDistrict);
 *  - lib/telephony/liveVoiceClientTools.ts, liveVoicePropertyTools.ts — функции робота.
 *
 * ЗОНА — НЕ ГОРОД. Район Рудаки окружает Душанбе снаружи: в справочнике районов CRM
 * (таблица District — четыре района города) его нет, и для поиска объект там — «за
 * городом» (suburban), как и раньше. Решение владельца меняет, кому мы НЕ отказываем,
 * а не карту города. Строку District для Рудаки не заводим: её прочли бы карточки,
 * подбор и рынок во всех каналах, это отдельное решение с миграцией данных.
 */

export const SERVICE_AREA_DECIDED = "15.11.2026";

/** Зона одной фразой — для текстов ботов. */
export const SERVICE_AREA_RU = "Душанбе и район Рудаки";

/**
 * Любое упоминание Рудаки — и район, и проспект Рудаки в самом городе: для зоны это
 * неважно, оба наши. Источник регулярки (без флагов) — для отсечки чужой географии.
 */
export const RUDAKI_ANY_SOURCE = "р[уӯ]да[кқ][иӣ]|rudaki|сомониён|сомониен|somoniyon";

/**
 * Именно РАЙОН Рудаки, а не проспект: «ноҳияи Рӯдакӣ», «н. Рудаки», «район Рудаки»,
 * «Рудакинский», райцентр Сомониён. Голое «Рудаки» сюда нарочно не входит — это главный
 * проспект Душанбе. Сверяется по ключу geoMatchKey (буквы свёрнуты, знаки сняты).
 */
const RUDAKI_DISTRICT_KEY = /(^| )(нохияи рудаки|н рудаки|рудакинск|район рудаки|района рудаки|сомониен)/u;

/** Текст говорит о районе Рудаки (не о проспекте). */
export function mentionsRudakiDistrict(text: string | null | undefined): boolean {
  if (!text) return false;
  return RUDAKI_DISTRICT_KEY.test(geoMatchKey(text));
}

/** Общее правило обоих ботов: где работаем и что отвечать про другие места. */
