/**
 * Повторная доставка вебхука: одно сообщение клиента — один ответ бота.
 *
 * ПОЧЕМУ ЭТО НЕ ТЕОРИЯ. Meta повторяет доставку, если не получила 200 достаточно
 * быстро. Мы отвечаем ей сразу, до всякой работы (иначе не успеваем вовсе), но
 * «сразу» упирается в сеть: при задержке ответа то же самое сообщение приезжает
 * второй раз. Дальше всё идёт по второму кругу — клиент получает два ответа на
 * одну свою реплику, а сама реплика ложится в историю диалога дважды и остаётся
 * там как след «клиент повторяется».
 *
 * ЗАМОК — УНИКАЛЬНОСТЬ В БАЗЕ, А НЕ ПРОВЕРКА. Проверка «а нет ли уже такого»
 * закрывает только последовательные дубли: два обработчика, стартовавшие
 * одновременно (а именно так и приходит повтор при таймауте), оба увидят пустоту и
 * оба пойдут отвечать. Поэтому пишем сразу и смотрим, не упала ли запись на
 * ограничении — арбитром выступает сама БД.
 *
 * ОТКАЗ БАЗЫ ТРАКТУЕТСЯ КАК «НЕ ДУБЛЬ». Молча съеденное сообщение клиента хуже
 * второго ответа: второе видно и человеку, и в переписке, а пропавшее не видно
 * никому. Ровно то же решение принято у рубильников каналов и отметок показа.
 *
 * ОТМЕТКА — ЭТО «ОБРАБОТКА ИДЁТ», А НЕ «ОБРАБОТАНО» (21.09.2026).
 *
 * До этой правки строка в ProcessedMessage создавалась ДО обработки и означала
 * «обработано» сразу — снять её умел только `catch` при явном исключении.
 * Разбор ночи 20→21.09 («объект №114 принят, но не опубликован после рестарта»)
 * нашёл тот же класс потери опаснее рядом: если процесс умирает ЦЕЛИКОМ
 * (перезапуск контейнера, OOM, жёсткий выход по таймауту), исключения не
 * происходит — `catch` не срабатывает, отметка остаётся навсегда. Повторная
 * доставка того же сообщения от Telegram/Meta после рестарта отбрасывается как
 * «уже обработано», а на деле клиент ответа не получил и никогда не получит:
 * ни в переписке, ни в журнале ошибок следа не остаётся.
 *
 * Поэтому теперь строка несёт два состояния: `completedAt: null` — обработка
 * НАЧАТА (могла ещё идти, а могла оборваться вместе с процессом), `completedAt`
 * заполнено — обработка ЗАВЕРШИЛАСЬ успешно. Повторная доставка отбрасывается
 * только во втором случае или пока первая попытка совсем свежая (см.
 * `STALE_AFTER_MS` ниже) — иначе доставка подхватывается заново, а находка
 * пишется в журнал через `logSystemError` (см. `reportStaleDeliveryReclaimed`),
 * чтобы обрыв на полуслове не проходил бесследно, как раньше.
 *
 * Защита от ДВУХ ОДНОВРЕМЕННЫХ доставок сохранена целиком: первая создаёт
 * строку и получает `false`, вторая ловит нарушение уникальности, видит совсем
 * свежую (моложе `STALE_AFTER_MS`) отметку без `completedAt` и получает `true`
 * — то же исходное поведение, тем же способом.
 *
 * У ОТМЕТКИ ЕСТЬ ВЛАДЕЛЕЦ (24.09.2026, разбор потери ролика монтажёра при
 * рестарте контейнера в момент копирования файла).
 *
 * `STALE_AFTER_MS` защищало от гонки двух ЖИВЫХ доставок, но ничего не знало
 * о том, что процесс, поставивший отметку, уже мёртв — ждало полные 10 минут,
 * даже когда рестарт контейнера произошёл секунду назад и было известно точно.
 * Теперь каждая отметка несёт `claimedBy` — случайный идентификатор процесса
 * (`PROCESS_INSTANCE_ID`, один на весь процесс), и есть два независимых пути
 * узнать, что владелец мёртв, вместо одного таймера:
 *
 *  1. При СТАРТЕ процесса `resetIncompleteProcessedMessages` сбрасывает (удаляет)
 *     незавершённые отметки каналов, которые обслуживает именно этот процесс,
 *     КРОМЕ поставленных им самим — вызывается из index.ts (вебхуки, после bind,
 *     без await) и telegram/poller.ts (long polling, до первого опроса). Чужие
 *     отметки этого же канала однозначно принадлежат мёртвому предку.
 *  2. Внутри самой проверки: если у отметки `claimedBy` не совпадает с текущим
 *     `PROCESS_INSTANCE_ID`, она подхватывается НЕМЕДЛЕННО, не дожидаясь
 *     `STALE_AFTER_MS`, — это подчищает случаи, которые старт-ап сброс не
 *     видел (другой тип процесса, отметка появилась уже после сброса). Гонка
 *     двух ЖИВЫХ процессов по-прежнему исключена: подхват идёт условным
 *     обновлением (CAS) по прежним `createdAt`+`claimedBy`, выигрывает только
 *     один.
 *
 * `STALE_AFTER_MS` остаётся как было — единственная защита, когда `claimedBy`
 * СОВПАДАЕТ (тот же процесс поставил отметку и, возможно, всё ещё её
 * обрабатывает — тогда решает только возраст, а не владелец).
 */

import { randomUUID } from "node:crypto";
import { prisma } from "../db.js";
import { logSystemError, type SystemErrorSource } from "./systemError.js";

/** Один случайный идентификатор на весь процесс — вычисляется один раз при
 *  загрузке модуля. Не переживает рестарт нарочно: новый процесс обязан
 *  получить новый идентификатор, иначе владение отметками предыдущего
 *  процесса выглядело бы «своим», и startup-сброс/CAS ниже не сработали бы. */
export const PROCESS_INSTANCE_ID = randomUUID();

/** Ошибка уникального ограничения Prisma — «такая запись уже есть». */
const UNIQUE_VIOLATION = "P2002";

/**
 * Сколько разумно ждать, прежде чем считать отметку «зависшей» (обработка
 * началась, но неизвестно, идёт ли она ещё). Собрано из фактических потолков
 * самого дорогого пути одного входящего сообщения (голосовое/видео + ответ ИИ):
 *
 *   - скачивание вложения (messengers/attachments.ts, FETCH_TIMEOUT_MS)   —  60 с
 *   - разбор видео/фото через Gemini File API (ai/geminiMedia.ts,
 *     TOTAL_BUDGET_MS) — самый долгий шаг, уже включает загрузку и опрос —   180 с
 *   - расшифровка голосового при большом файле (ai/transcribe.ts,
 *     TIMEOUT_MAX_MS)                                                      —  180 с
 *   - сам ход ассистента, генерация ответа (ai/assistant.ts, TIMEOUT_MS)    —   60 с
 *
 * Сумма худшего случая — около 8 минут. Берём круглые 10 с запасом: короче —
 * рискуем подхватить ещё живую (просто медленную) обработку и ответить клиенту
 * дважды, длиннее — клиент после настоящего рестарта ждёт ответа лишние минуты
 * зря, пока Telegram/Meta не пришлют повтор сами.
 */
const STALE_AFTER_MS = 10 * 60 * 1000;

function systemErrorSourceFor(channel: string): SystemErrorSource {
  if (channel === "TELEGRAM") return "telegram";
  if (channel === "WHATSAPP" || channel === "INSTAGRAM" || channel === "FACEBOOK") return "meta";
  return "api";
}

/** Одна строка в журнал на каждый подхват — logSystemError уже дедуплицирует
 *  повторы того же текста в разумном окне и сам отличает гонку при остановке
 *  от настоящего сбоя (см. shutdownState.ts, isShuttingDown внутри logSystemError). */
async function reportStaleDeliveryReclaimed(
  channel: string,
  messageId: string,
  ageMs: number,
  ownerMismatch: boolean
): Promise<void> {
  const ageMin = Math.max(1, Math.round(ageMs / 60_000));
  const reason = ownerMismatch
    ? "отметку поставил другой экземпляр процесса, которого сейчас нет"
    : `началась ${ageMin} мин назад и не отмечена как готовая`;
  await logSystemError(
    systemErrorSourceFor(channel),
    `Повторная доставка принята: прошлая обработка сообщения ${channel}/${messageId} не завершилась ` +
      `(${reason}) — вероятно, процесс перезапустился посреди работы.`
  );
}

export async function isDuplicateDelivery(channel: string, messageId?: string | null): Promise<boolean> {
  // Без идентификатора отличить повтор не от чего: событие без mid (например, ответ
  // на историю) обрабатываем как раньше. Придумывать ключ из текста нельзя — клиент
  // имеет полное право написать «салом» дважды.
  if (!messageId) return false;
  try {
    await prisma.processedMessage.create({ data: { channel, messageId, claimedBy: PROCESS_INSTANCE_ID } });
    return false;
  } catch (err) {
    if ((err as { code?: string }).code !== UNIQUE_VIOLATION) {
      console.error("[webhook] отметка обработки не записана:", err instanceof Error ? err.message : err);
      return false;
    }
  }

  // Строка уже существует — решаем по её состоянию, а не по факту существования.
  const existing = await prisma.processedMessage.findUnique({
    where: { channel_messageId: { channel, messageId } },
  });
  if (!existing) {
    // Между нашим упавшим `create` и этим чтением кто-то снял замок
    // (releaseProcessedMessage после сбоя обработки) — доставка не дубль,
    // пробуем поставить отметку заново.
    return isDuplicateDelivery(channel, messageId);
  }
  if (existing.completedAt) return true; // обработано успешно — настоящий дубль

  // Владелец другой (и не null — «безымянные» отметки старых строк до этой
  // правки считаем как раньше, только по возрасту) — это либо мёртвый
  // предыдущий процесс, которого startup-сброс не увидел, либо другой тип
  // процесса на этот же канал. Ждать STALE_AFTER_MS незачем — известно точно.
  const ownerMismatch = existing.claimedBy !== null && existing.claimedBy !== PROCESS_INSTANCE_ID;
  const ageMs = Date.now() - existing.createdAt.getTime();
  if (!ownerMismatch && ageMs < STALE_AFTER_MS) return true; // ещё в работе (или только что упала) — гонка/дубль

  // Подхватываем: либо зависла дольше разумного окна (процесс, скорее всего,
  // умер посреди обработки), либо владелец точно не текущий процесс.
  // Условное обновление (WHERE ... createdAt = <прочитанное> AND claimedBy =
  // <прочитанный>) — компаре-энд-свап: если два подхвата столкнутся, выиграет
  // только тот, кто обновит первым, у второго `count` будет 0.
  const reclaimed = await prisma.processedMessage.updateMany({
    where: { channel, messageId, completedAt: null, createdAt: existing.createdAt, claimedBy: existing.claimedBy },
    data: { createdAt: new Date(), claimedBy: PROCESS_INSTANCE_ID },
  });
  if (reclaimed.count === 0) return true; // кто-то другой уже подхватил или успел завершить

  void reportStaleDeliveryReclaimed(channel, messageId, ageMs, ownerMismatch);
  return false;
}

/**
 * Отмечает обработку сообщения завершённой — с этого момента повторная доставка
 * того же (channel, messageId) отбрасывается как настоящий дубль, а не только
 * пока отметка свежая. Зовётся ПОСЛЕ успешной обработки, обычно из `finally`
 * рядом с обработчиком (см. routes/webhooks.ts) — так отметка ставится при
 * любом нормальном выходе, а не только в одной ветке кода.
 *
 * Если отметки уже нет (её снял releaseProcessedMessage после сбоя) — тихий
 * no-op: `updateMany` просто не находит что обновлять, воссоздавать строку
 * не нужно и незачем.
 */
export async function markProcessedMessageComplete(channel: string, messageId?: string | null): Promise<void> {
  if (!messageId) return;
  try {
    await prisma.processedMessage.updateMany({
      where: { channel, messageId },
      data: { completedAt: new Date() },
    });
  } catch (err) {
    console.error("[webhook] отметка завершения не записана:", err instanceof Error ? err.message : err);
  }
}

/**
 * Снимает замок после сорвавшейся обработки — чтобы повтор доставки от Meta мог
 * попробовать ещё раз НЕМЕДЛЕННО, не дожидаясь `STALE_AFTER_MS`.
 *
 * ЗАЧЕМ. isDuplicateDelivery ставит отметку ДО обработки, не после: иначе два
 * одновременных дубля оба увидели бы пустоту (см. комментарий у самой функции).
 * Но если между отметкой и ответом клиенту обработка упала — сеть до ИИ, отказ базы
 * при сохранении реплики, что угодно, — отметка остаётся, а ответа не было. Следующая
 * доставка увидит «уже обработано» и отступит молча: ровно тот исход, который весь
 * этот модуль призван предотвращать, только с другой стороны.
 */
export async function releaseProcessedMessage(channel: string, messageId?: string | null): Promise<void> {
  if (!messageId) return;
  try {
    await prisma.processedMessage.deleteMany({ where: { channel, messageId } });
  } catch (err) {
    console.error("[webhook] отметка обработки не снята после сбоя:", err instanceof Error ? err.message : err);
  }
}

/**
 * СБРОС НЕЗАВЕРШЁННЫХ ОТМЕТОК ПРИ СТАРТЕ ПРОЦЕССА (24.09.2026).
 *
 * Зовётся РОВНО ОДИН РАЗ при старте процесса — index.ts для каналов, что идут через HTTP-вебхуки
 * (routes/webhooks.ts, всегда живёт в api-процессе), telegram/poller.ts для
 * канала TELEGRAM, когда включён long polling (заменяет вебхук). Каждый
 * процесс вызывает это только для каналов, которые обслуживает САМ — иначе
 * можно снести отметку, за которой сейчас следит другой, живой процесс.
 *
 * В api-процессе вызов стартует внутри callback `app.listen`, то есть уже ПОСЛЕ
 * bind, без await: сервер может принять доставку раньше, чем сброс дойдёт до
 * базы (Meta повторяет доставку после 502 при деплое). Поэтому «до приёма
 * доставок» гарантировано только для поллера Telegram; для api защищает фильтр
 * по `claimedBy`: отметка, поставленная этим же процессом, живая и остаётся.
 *
 * Отметки этих каналов, оставшиеся незавершёнными (`completedAt: null`) и
 * принадлежащие другому `claimedBy` (или безымянные), принадлежат МЁРТВОМУ
 * предыдущему процессу: текущий процесс свои не сбрасывает. Удаляем
 * их целиком (а не просто снимаем владельца) — ровно тот же эффект, что у
 * `releaseProcessedMessage` после сбоя: следующая (или та же самая повторная)
 * доставка от Telegram/Meta обработается заново, а не отбросится как «в
 * работе», пока не истечёт `STALE_AFTER_MS`.
 *
 * Отказ глушим до предупреждения в консоль: не размётший стартовый набор —
 * не повод не поднимать процесс, отметки просто доживут свой век сами по
 * возрасту (`STALE_AFTER_MS`/`isDuplicateDelivery`) или по `claimedBy`-CAS.
 */
export async function resetIncompleteProcessedMessages(
  channels: string[],
  source: SystemErrorSource
): Promise<number> {
  if (channels.length === 0) return 0;
  let count = 0;
  try {
    ({ count } = await prisma.processedMessage.deleteMany({
      where: {
        channel: { in: channels },
        completedAt: null,
        // Отметки ЭТОГО процесса не трогаем: сброс идёт fire-and-forget ПОСЛЕ
        // bind, и новая доставка могла успеть поставить отметку за те
        // миллисекунды, что он стартует. `not` в SQL не видит NULL, поэтому
        // безымянные старые строки перечислены отдельной веткой.
        OR: [{ claimedBy: null }, { claimedBy: { not: PROCESS_INSTANCE_ID } }],
      },
    }));
  } catch (err) {
    console.error(
      "[webhook] сброс незавершённых отметок при старте не выполнен:",
      err instanceof Error ? err.message : err
    );
    return 0;
  }
  if (count > 0) {
    console.log(`[webhook] после перезапуска возвращено ${count} незавершённых сообщений (${channels.join(", ")})`);
    await logSystemError(
      source,
      `После перезапуска возвращено ${count} незавершённых сообщений (каналы: ${channels.join(", ")}) — повторная доставка обработает их заново.`
    ).catch(() => {});
  }
  return count;
}

/**
 * Сколько живут отметки. Три дня — с огромным запасом: Meta повторяет доставку
 * минутами, а не сутками. Держать дольше незачем, таблица растёт со скоростью всей
 * входящей переписки.
 */
const KEEP_DAYS = 3;

/** Уборка старых отметок — вызывается ночным кроном вместе с остальной. */
export async function cleanupProcessedMessages(): Promise<number> {
  const { count } = await prisma.processedMessage.deleteMany({
    where: { createdAt: { lt: new Date(Date.now() - KEEP_DAYS * 24 * 60 * 60 * 1000) } },
  });
  return count;
}
