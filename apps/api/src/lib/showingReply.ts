/**
 * Строка → " слово слово слово " (нижний регистр, ё→е, всё не-буквенное — пробел).
 * Обрамляющие пробелы обязательны: по ним работает поиск целого слова.
 */
function normalize(text: string): { padded: string; words: string[] } {
  const words = text
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim()
    .split(" ")
    .filter(Boolean);
  return { padded: ` ${words.join(" ")} `, words };
}

const hasPhrase = (padded: string, phrases: string[]) => phrases.some((p) => padded.includes(` ${p} `));
const hasStem = (words: string[], stems: string[]) => words.some((w) => stems.some((s) => w.startsWith(s)));

export function classifyShowingReply(text: string): ShowingReply {
  // Эмодзи ищем до токенизации, но решает оно ПОСЛЕ проверки отказа: «Не смогу
  // прийти 👍» это отказ, палец вверх тут вежливость (CRM-SHOWING01). Одинокое
  // эмодзи и эмодзи без слов отказа по-прежнему «да».
  const hasYesEmoji = YES_EMOJI.some((e) => text.includes(e));

  const { padded, words } = normalize(text);
  if (words.length === 0) return hasYesEmoji ? "yes" : "unclear";

  if (hasPhrase(padded, YES_DESPITE_NO)) return "yes";
  if (hasPhrase(padded, NO_PHRASES) || hasStem(words, NO_STEMS)) return "no";
  if (hasYesEmoji) return "yes";
  if (hasPhrase(padded, YES_PHRASES) || hasStem(words, YES_STEMS)) return "yes";
  return "unclear";
}
