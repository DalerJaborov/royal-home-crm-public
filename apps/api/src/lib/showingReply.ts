/**
 * Разбор ответа клиента на просьбу подтвердить показ.
 *
 * Три исхода, и третий здесь главный по смыслу:
 *  - "yes"     — человек явно сказал «приду» (по-русски, по-таджикски, эмодзи);
 *  - "no"      — человек явно сказал, что не сможет / просит перенести;
 *  - "unclear" — ответил что-то другое («а во сколько?», «адрес скиньте»).
 *
 * "unclear" НЕ равно отказу и вообще не равно молчанию: человек прочитал
 * сообщение и написал в ответ — значит он на связи и показ в силе. Вызывающий код
 * засчитывает "unclear" как подтверждение (см. showingConfirmation.ts), а
 * настоящий сигнал риска ровно один — тишина, и её здесь нет по определению:
 * этот модуль вызывается только когда сообщение пришло.
 *
 * ═══ ГРАБЛИ, на которых в этом проекте уже дважды теряли работающие правила ═══
 * В JavaScript `\b` — граница между [A-Za-z0-9_] и всем остальным. Кириллица в
 * этот класс НЕ входит, поэтому `/\bда\b/` на строке «да» не срабатывает ВООБЩЕ
 * НИКОГДА: перед «д» стоит начало строки, но и сама «д» для движка — не «слово».
 * Поэтому здесь нет ни одного `\b`. Вместо него — токенизация: строка режется по
 * всему, что не буква и не цифра (`\p{L}` с флагом u знает и русские буквы, и
 * таджикские ҳ/қ/ғ/ҷ/ӣ/ӯ), склеивается обратно через пробелы и обрамляется
 * пробелами. Проверка `includes(" да ")` — это и есть граница слова, честная для
 * любого алфавита.
 */

export type ShowingReply = "yes" | "no" | "unclear";

/**
 * Эмодзи проверяем ДО токенизации: она выкидывает всё, что не буква, а палец
 * вверх — самый частый способ ответить «да» в мессенджере, особенно в WhatsApp.
 */
const YES_EMOJI = ["👍", "✅", "👌", "🙌", "☑️", "✔️"];

/**
 * Отказ ищется ПЕРВЫМ. «Не приду» содержит слово «приду», и при обратном порядке
 * отказ засчитался бы как согласие — ошибка, которая стоит потерянного показа
 * (агент поехал, клиента нет).
 */
/**
 * «Нет проблем», «без проблем», «не вопрос» — это СОГЛАСИЕ, хотя внутри стоит
 * отрицание. Проверяются раньше отказов, иначе живой клиент, ответивший
 * «нет проблем, приду», попал бы в «не сможет» и агент отменил бы показ сам.
 */
const YES_DESPITE_NO = ["нет проблем", "нету проблем", "без проблем", "не вопрос", "почему нет", "нет вопросов"];

