import { prisma } from "../../db.js";

/**
 * Сколько объявлений автора мы видим в категории «Квартиры, продажа, Душанбе».
 *
 * Счёт ПО АВТОРУ: записи `SomonSeenAdvert` (и baseline, и новые) с тем же ключом.
 * Записи без ключа на счёт других авторов не влияют — иначе одна запись без автора
 * (объявление без `user.id` или запись до появления поля) обнуляла бы отправки всем.
 *
 * Записи до появления поля: baseline НЕ сбрасывается (монитор на проде уже активен).
 * Миграция `20261101190000_somon_seller_key` включает отдельный проход по выдаче
 * (`rekeySellerPage`), который только дописывает ключ объявлениям, ещё живым в выдаче.
 * Пока он идёт, `processSomonPending` пропускает собственником лишь автора с одним
 * объявлением на всём сайте, остальных откладывает. После прохода без ключа остаются
 * только исчезнувшие из выдачи объявления и объявления без автора в выдаче.
 * Допустимое занижение (решение 01.11.2026): объявление того же автора, у которого в
 * выдаче не было `user.id`, в счёт не попадёт. Такое объявление само по себе не уйдёт
 * агенту (ключа нет → счёт неизвестен).
 *
 * Почему не «активные в последнем полном обходе»: полного обхода после baseline нет —
 * обычный проход листает только верх выдачи, глубокие объявления повторно не видны.
 * Окно по времени дало бы ЗАНИЖЕНИЕ (живое старое объявление выпало бы, посредник
 * прошёл бы собственником). Поэтому исключаем только подтверждённо исчезнувшие
 * (`UNAVAILABLE` — карточка ответила 404). Известное ЗАВЫШЕНИЕ (не чиним): проданное,
 * но не перепроверенное объявление остаётся в счёте — baseline-записи чистка не удаляет
 * вовсе, прочие живут до 180 дней (`cleanupSomonReceipts`); перевыложенная квартира даёт 2.
 * Завышение уводит в «проверить», а не в «собственник».
 *
 * null — у самого объявления нет ключа автора: счёт неизвестен.
 */
export const SOMON_SELLER_GONE_STATUSES = ["UNAVAILABLE"];
/** Отложено: в выдаче не было автора. Возвращается в PENDING, когда автор появится. */
export const SOMON_SELLER_UNKNOWN = "SELLER_UNKNOWN";
/** Сколько ждать автора — столько же, сколько живёт PENDING в `processSomonPending`. */
export const SOMON_SELLER_UNKNOWN_DAYS = 3;

export async function countSomonSellerAdverts(sellerKey: string | null): Promise<number | null> {
  if (!sellerKey) return null;
  const count = await prisma.somonSeenAdvert.count({ where: { sellerKey, status: { notIn: SOMON_SELLER_GONE_STATUSES } } });
  return count < 1 ? null : count;
}
