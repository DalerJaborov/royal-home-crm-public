/**
 * Кому виден телефон клиента — одно правило на всю CRM.
 *
 * Решение владельца 07.08.2026: рядовой сотрудник не видит номера клиента ВООБЩЕ,
 * связь идёт только через кнопку «Позвонить» — набирает АТС. Иначе клиента уводили
 * из агентства в личный телефон: разговор не записывался, в хронологии не оставалось
 * следа, а при уходе сотрудника база оставалась в его записной книжке.
 *
 * Почему отдельный файл, а не функция внутри routes/clients.ts, где она жила раньше:
 * правило обходили ВСЕ остальные маршруты. Телефон приходил целиком в календаре,
 * сделках, инбоксе, на главной и в карточке сотрудника — то есть закрытым он был
 * ровно в одном разделе из шести, и это выглядело работающим ограничением. Тот же
 * урок уже был с контактами собственников (см. lib/ownerContact.ts): правило,
 * записанное в одном маршруте, не является правилом.
 *
 * Маска оставляет начало и две последние цифры (`+992•••••57`) намеренно: сотруднику
 * нужно отличать двух Мадин в списке и видеть, что номер вообще есть, а карточка не
 * пустая. Восстановить по ней номер нельзя.
 */

import { CLIENT_PHONE_MASK_CHAR } from "@royal-home/shared";

/** Признак руководителя: право видеть чужих клиентов целиком. Роль не годится —
 *  директор может закрыть чужие карточки конкретному сотруднику, и тогда телефоны
 *  всё равно приходили бы открытыми. */
export type CanSeeFullPhone = boolean;

export function maskClientPhone(phone: string): string {
  if (phone.length <= 6) return phone;
  // Символ маски — общий с @royal-home/shared: по нему и сервер, и форма
  // «Изменить клиента» узнаю́т закрытый номер и не принимают его за набранный.
  return phone.slice(0, 4) + CLIENT_PHONE_MASK_CHAR.repeat(5) + phone.slice(-2);
}

/** Телефон в том виде, в каком его можно показать этому сотруднику. */
export function clientPhoneFor(phone: string, canSeeFull: CanSeeFullPhone): string {
  return canSeeFull ? phone : maskClientPhone(phone);
}

/**
 * НОМЕР ВНУТРИ ТЕКСТА — ТА ЖЕ УТЕЧКА, ЧТО И ПОЛЕ `phone` (владелец 20.08.2026).
 *
 * Живой случай: агент открыл карточку и увидел «Входящий +992910001003» —
 * маскировка поля `phone` работала как задумано, но номер лежал В ИМЕНИ
 * карточки, которое CRM сама и составила при звонке с незнакомого номера
 * (lib/telephony/incomingCalls.ts и соседи). Правило «агент не видит номер»
 * обходилось не дырой в правиле, а тем, что номер оказался не в том поле.
 *
 * Сами карточки с тех пор заводятся уже с маской в имени (см. те же файлы), но
 * заведённые ДО этого живут в базе с открытым номером — эта функция закрывает
 * их на выдаче, и заодно ловит номер, вписанный в имя руками.
 *
 * ЧТО СЧИТАЕМ НОМЕРОМ — УЗКО, А НЕ «ЛЮБЫЕ ЦИФРЫ ПОДРЯД». Первая версия ловила
 * 7+ цифр в любом виде и на пробном прогоне (scripts/mask-phone-in-client-names.ts)
 * испортила бы имена вроде «Клиент ветвления показа 1786815047512» — это не
 * телефон, а метка времени. Портить настоящие подписи ради мнимой утечки нельзя,
 * поэтому берём два точных признака:
 *   · ведущий «+» — в этой CRM телефон ВСЕГДА хранится так (см. toCrmPhone
 *     в lib/telephony/incomingCalls.ts: любой вход нормализуется к +992…);
 *   · либо код страны 992 + 9 цифр — на случай номера, вписанного в имя руками
 *     без плюса.
 *
 * ТРЕТИЙ ПРИЗНАК — ГОЛЫЕ ДЕВЯТЬ ЦИФР, НАЧИНАЮЩИЕСЯ С 9 (30.08.2026).
 *
 * Живой пример с прода: «900001016». Ни плюса, ни кода страны — двух признаков
 * выше не хватало вовсе, и такой номер проходил насквозь везде, где текст
 * маскируется. В Таджикистане мобильный — ровно 9 цифр и начинается с 9, так что
 * признак узкий: суммы («450000», «1 200 000») и площади короче, а год, дата или
 * метка времени не начинаются с девятки при длине ровно 9.
 */
const PHONE_IN_TEXT_RE = /\+\d[\d\s()-]{5,}\d|\b992\d{9}\b|(?<![\d+])9\d{8}(?!\d)/g;

/**
 * ЦЕПОЧКА ЦИФР С РАЗДЕЛИТЕЛЯМИ — добивка для СВОБОДНОГО текста (см.
 * maskPhonesInFreeText ниже). Ровно та же мысль, что в sanitizeStyleText
 * (ai/styleLearning.ts): узкий разбор пропускает «910 00 10 03», а в пересказе
 * разговора номер недопустим.
 *
 * Порог — 9 цифр, а не 7 как у образцов стиля: сводка ИИ по решению владельца от
 * 25.08.2026 обязана нести бюджет («1 200 000 сомони» — семь цифр), и замазать
 * его ради мнимой утечки нельзя. Таджикский номер короче девяти не бывает.
 */
const DIGIT_RUN_IN_TEXT_RE = /(?<!\d)(?:\d[\s.()-]?){8,}\d(?!\d)/g;

/**
 * ССЫЛКИ И НИКИ — ТА ЖЕ ЛАЗЕЙКА, ЧТО И НОМЕР В ТЕКСТЕ (владелец 01.09.2026).
 *
 * Правило «сотрудник не видит контакт клиента в обход АТС» до сих пор ловило
 * только цифры номера. Ссылка t.me/username или wa.me/79161234567, а ник
 * @username в переписке (Telegram/Instagram) проходили насквозь — тот же обход,
 * что уже был с номером, спрятанным не в том поле (см. историю выше в файле),
 * только через другой канал контакта: договориться в обход АТС можно и без
 * цифр. Маскируем по тому же принципу — опознаваемо, что здесь была ссылка или
 * ник, но не сам контакт. Email сюда намеренно НЕ входит — вне задачи.
 *
 * `\b` перед `t.me`/`wa.me` — чтобы не задеть случайную подстроку внутри
 * другого домена вроде «start.me» (там перед «t.me» нет границы слова).
 */
const TG_LINK_RE = /\b(?:https?:\/\/)?(?:t(?:elegram)?\.me)\/(\+?[a-zA-Z0-9_]{3,32})\b/gi;
const WA_LINK_RE = /\b(?:https?:\/\/)?wa\.me\/(\+?\d{6,15})\b/gi;
// Отрицательный lookbehind исключает «@» внутри email (user@domain) — там перед
// «@» стоит буква/цифра/точка локальной части, а у ника перед «@» — пробел,
// начало строки или знак препинания.
const MENTION_RE = /(?<![\w@.])@([a-zA-Z0-9_]{3,32})\b/g;

function maskContactsInText(text: string): string {
  return text
    .replace(TG_LINK_RE, () => `t.me/${CLIENT_PHONE_MASK_CHAR.repeat(5)}`)
    .replace(WA_LINK_RE, (_match, digitsRaw: string) => {
      const digits = digitsRaw.replace(/\D/g, "");
      return `wa.me/${CLIENT_PHONE_MASK_CHAR.repeat(Math.max(digits.length, 6))}`;
    })
    .replace(MENTION_RE, () => `@${CLIENT_PHONE_MASK_CHAR.repeat(5)}`);
}

export function maskPhonesInText(text: string): string {
  return maskContactsInText(text).replace(PHONE_IN_TEXT_RE, (match) => {
    const digits = match.replace(/\D/g, "");
    if (digits.length < 9) return match;
    return maskClientPhone(match.trim().startsWith("+") ? `+${digits}` : digits);
  });
}

/**
 * НОМЕР В ПЕРЕСКАЗЕ — ТА ЖЕ УТЕЧКА, ЧТО И В ПОЛЕ (владелец 30.08.2026).
 *
 * Поле `phone` закрыто маской с 07.08.2026, а клиент между тем диктует номер в
 * переписку или голосом — и он всплывает открытым текстом там, куда правило не
 * заглядывало ни разу: в сводке «Коротко ИИ» (Client.aiInsight), в причине
 * оценки, в хронологии (Interaction.notes), в расшифровке разговора и в его
 * разборе. Право `clients.viewPhone` при этом обходится не дырой в правиле, а
 * тем, что номер лежит не в том поле — ровно как когда-то с именем карточки.
 *
 * Для таких текстов маскируем строже, чем имя: сначала узкий разбор, потом
 * добивка по цепочке из 9+ цифр с разделителями.
 */
export function maskPhonesInFreeText(text: string): string {
  // Порядок важен: узкий разбор оставляет после себя «•», и добивка уже не видит
  // в замаскированном номере длинную цепочку цифр.
  return maskPhonesInText(text).replace(DIGIT_RUN_IN_TEXT_RE, (match) =>
    maskClientPhone(match.replace(/\D/g, ""))
  );
}

/** Свободный текст в том виде, в каком его можно показать этому сотруднику.
 *  null/undefined проходят насквозь — чтобы вызов не обрастал проверками. */
export function phoneSafeText<T extends string | null | undefined>(text: T, canSeeFull: CanSeeFullPhone): T {
  if (canSeeFull || typeof text !== "string") return text;
  return maskPhonesInFreeText(text) as T;
}

/**
 * То же для разбора звонка (Interaction.callAnalysis) — это Json-колонка, номер
 * может лежать в любой её строке (совет агенту, цитата возражения). Обходим
 * дерево целиком: перечислять поля значило бы завести второе место, где можно
 * забыть про новое.
 */
export function maskPhonesDeep(value: unknown, canSeeFull: CanSeeFullPhone): unknown {
  if (canSeeFull || value === null || value === undefined) return value;
  if (typeof value === "string") return maskPhonesInFreeText(value);
  if (Array.isArray(value)) return value.map((item) => maskPhonesDeep(item, canSeeFull));
  if (typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>).map(([k, v]) => [k, maskPhonesDeep(v, canSeeFull)])
    );
  }
  return value;
}

/** Имя клиента в том виде, в каком его можно показать этому сотруднику: без
 *  номера телефона внутри, если права на номер нет. */
export function clientNamePhoneSafe(fullName: string, canSeeFull: CanSeeFullPhone): string {
  return canSeeFull ? fullName : maskPhonesInText(fullName);
}

/**
 * Применяет правило к вложенному клиенту в любой сущности — задаче календаря,
 * сделке, диалогу, строке дашборда. Возвращает новый объект, исходный не меняется.
 *
 * Работает и когда клиента нет (задача без клиента, диалог без карточки) — в таких
 * местах раньше приходилось писать проверку на null у каждого вызова.
 *
 * ИМЯ ЗАКРЫВАЕТСЯ ЗДЕСЬ ЖЕ, А НЕ ОТДЕЛЬНОЙ СТРОКОЙ В КАЖДОМ МАРШРУТЕ (22.09.2026).
 * Номер внутри `fullName` — та же утечка, что и поле `phone` (разбор в шапке
 * clientNamePhoneSafe ниже): карточку незнакомого звонившего CRM заводила с
 * ОТКРЫТЫМ номером в имени. Карточка клиента это учитывает (presentClient), а
 * вложенный клиент — нет: календарь (`GET /calendar/tasks`, до 500 задач) и
 * Главная отдавали `phone` замаскированным и тут же `fullName` вида
 * «Входящий +992910001003» рядом. Право `clients.viewPhone` обходилось не дырой в
 * правиле, а тем, что номер лежал в соседнем поле — ровно тот случай, ради
 * которого весь этот файл и заведён.
 *
 * Поля необязательны: вызов, выбравший только `fullName` (лента активности) или
 * только `phone`, проходит через ту же точку, а не заводит себе вторую.
 */
export function withMaskedClient<
  T extends { client?: { phone?: string; fullName?: string } | null } | null | undefined,
>(entity: T, canSeeFull: CanSeeFullPhone): T {
  if (!entity || canSeeFull || !entity.client) return entity;
  const { phone, fullName } = entity.client;
  return {
    ...entity,
    client: {
      ...entity.client,
      ...(typeof phone === "string" ? { phone: maskClientPhone(phone) } : {}),
      ...(typeof fullName === "string" ? { fullName: clientNamePhoneSafe(fullName, false) } : {}),
    },
  };
}
