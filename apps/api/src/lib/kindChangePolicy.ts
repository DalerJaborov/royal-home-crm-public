import type { ClientKind } from "@royal-home/shared";

/**
 * ЗАКОН: ТИП КАРТОЧКИ (BUYER/SELLER/OTHER) МЕНЯЕТ ЧЕЛОВЕК, ИИ ТОЛЬКО ПРЕДЛАГАЕТ
 * (владелец 21.09.2026, живой случай 18.09 — карточка продавца из WhatsApp-бота
 * стала покупателем молча, без единой строки в хронологии; второй случай — наоборот).
 *
 * ОДНА ТОЧКА РЕШЕНИЯ, а не условие, продублированное в трёх местах — тот же приём,
 * что у `describeRoleSwap`/`kindChangeUpdate` (services/leads/intake.ts) и у
 * `lib/timeline.ts`: разные писатели одного поля обязаны спрашивать одно и то же
 * место, иначе защита однажды окажется подключена не во всех каналах (ровно тот
 * класс бага, который уже дважды ловили в этом репозитории на других полях).
 *
 * ПРАВИЛО: пока карточка не принята (`acceptedAt === null`), автоматика вправе
 * сама уточнять/исправлять тип — никто ещё не подтвердил её руками, и это тот же
 * путь, каким лид вообще заводится (createLeadFromChannel/kindChangeUpdate искони
 * так себя вели для новых и ещё не принятых карточек). С МОМЕНТА ПРИЁМА
 * (`acceptedAt !== null`) карточка — рабочая, у неё есть ответственный человек,
 * и молчаливая смена типа стирает его понимание того, с кем он работает;
 * дальше automation тип не трогает и ничего о нём не пишет и не шлёт (владелец
 * 21.09.2026: «ии не должен ничего отправлять, пусть решает агент сам») — решает агент/руководитель
 * через PATCH /clients/:id (routes/clients/card.ts, там уже пишется хронология и
 * пуш — этот путь не трогаем).
 *
 * Смена на ТОТ ЖЕ САМЫЙ kind не входит в понятие «смена» вовсе — вызывающий код
 * обычно и так не зовёт эту функцию в таком случае, но результат симметричен:
 * менять нечего, значит менять можно (действие пустое).
 */
export function canAutomationChangeKind(input: {
  acceptedAt: Date | null;
  currentKind: ClientKind;
  nextKind: ClientKind;
}): boolean {
  if (input.nextKind === input.currentKind) return true;
  return input.acceptedAt === null;
}
