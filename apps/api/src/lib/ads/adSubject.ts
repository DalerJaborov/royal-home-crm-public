/**
 * ЧТО РЕКЛАМИРУЕТ ОБЪЯВЛЕНИЕ — конкретную квартиру или само агентство.
 *
 * Первая полная сверка кабинета (21.08.2026) показала то, чего не было видно ни
 * в одном отчёте: из 25 объявлений шесть продвигают не объект, а услуги Royal
 * Home — «доверьте продажу нам», «ищете жильё — обращайтесь», «у нас большая база
 * клиентов». На них ушла заметная часть бюджета, и раньше они лежали в общей куче
 * «без объекта» вместе с квартирами, которые привязать просто не успели.
 *
 * Это разные вещи, и путать их дорого. Непривязанная квартира — незакрытая
 * работа: расход есть, а на чьей карточке он должен быть, никто не сказал.
 * Реклама агентства — нормальная статья бюджета, у неё объекта нет и не будет, и
 * требовать привязки от неё бессмысленно. Пока они смешаны, список «без объекта»
 * никогда не станет пустым, и на него перестают смотреть.
 *
 * РАЗЛИЧАЕМ ПО ШАБЛОНУ ПОДПИСИ, а не по словарю тем. Агентство публикует объекты
 * по одной форме: «Продаётся/Фурӯш» плюс строка «Адрес»/«Суроға» — на русском и
 * на таджикском. Нет этой формы — значит пост не про конкретную квартиру.
 * Эвристика намеренно осторожна в одну сторону: сомнительное остаётся объектным
 * и попадает человеку в галерею. Ошибиться, спрятав квартиру в «рекламу бренда»,
 * хуже, чем показать лишнюю строку.
 */

/** Признак объектной публикации: продажа/аренда + адрес в подписи. */
const OFFER_WORDS = /продаётся|продается|продажа|сдаётся|сдается|фурӯш|фуруш|фурӯши|иҷора|ичора/i;
// «манзил» сюда НЕ входит, хотя выглядит подходяще: по-таджикски это «жильё», а
// не «адрес». Из-за него «Фурӯши манзилро ба Royal Home бовар кунед» («доверьте
// продажу жилья нам») читалось как объявление о конкретной квартире — реклама
// услуг агентства попадала в очередь на привязку. Адрес по-таджикски — «суроға».
const ADDRESS_WORDS = /адрес|суроға|сурога|ориентир|мкр|микрорайон|кӯча|куча|улица|ул\./i;

/**
 * true — объявление продвигает само агентство, а не квартиру.
 *
 * Пустой текст объектным не считаем и брендовым тоже: без подписи судить не о
 * чем, такое объявление идёт человеку в галерею как есть.
 */
export function looksLikeBrandAd(caption: string | null | undefined): boolean {
  const text = caption?.trim();
  if (!text) return false;
  return !(OFFER_WORDS.test(text) && ADDRESS_WORDS.test(text));
}

/** Первая содержательная строка текста — заголовок публикации без эмодзи-шапки. */
export function firstLine(caption: string | null): string | null {
  if (!caption) return null;
  for (const raw of caption.split(/\n+/)) {
    const line = raw.replace(/\s+/g, " ").trim();
    // Строка из одних значков (шапка вроде «🏛🏛🏛») заголовком быть не может.
    if (line.length >= 6 && /[a-zа-яё]/i.test(line)) return line.slice(0, 90);
  }
  return null;
}
