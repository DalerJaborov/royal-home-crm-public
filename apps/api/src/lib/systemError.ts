/**
 * Запись отказа интеграции в журнал ошибок.
 *
 * Раньше в ErrorLog попадали только необработанные исключения Express и JS-ошибки
 * браузера. Отказ ИИ, недоступный сайт, упавший Telegram, сбойный крон — всё это
 * уходило в console.error контейнера и не оставляло в системе никакого следа.
 * Экран «Здоровье системы» показывал зелёное «Всё разобрано», пока бот неделю не
 * отвечал клиентам, а утренняя сводка директору про это молчала.
 *
 * Дедупликация обязательна: сломанная интеграция повторяется каждым тиком крона и
 * каждым сообщением клиента. Без неё одна поломка за ночь даёт тысячи одинаковых
 * строк, в которых тонет всё остальное.
 */

/** Одну и ту же поломку не пишем чаще раза в 10 минут. */
const DEDUP_WINDOW_MS = 10 * 60 * 1000;

/**
 * Длина сравниваемого куска текста для дедупликации (28.08.2026).
 *
 * До этого «тот же вид поломки» сравнивался ПОЛНЫМ текстом: сообщения с
 * уникальными деталями внутри (имя файла голосового, ID канала звонка,
 * список объектов) никогда не совпадали друг с другом целиком, хотя по сути
 * были одной и той же повторяющейся проблемой. everSeen считал КАЖДОЕ такое
 * сообщение «первым в своём роде» и будил директора пушем на каждое — тот
 * самый повтор, которого п.18.08.2026 старался избежать. Тот же тег
 * `system-health-new-error` (push.ts) собирал их все в одну строку ленты,
 * которая от этого никогда не переставала быть непрочитанной.
 *
 * Число то же, каким утренний отчёт (.claude/hooks/morning-report.mjs) и
 * серверная группировка (routes/morningReport.ts, lib/errorLogClassify.ts)
 * группируют ошибки для директора — один источник правды на все стороны.
 * Помогает не всем источникам одинаково (уникальные детали не всегда в
 * хвосте сообщения), но безопасно и не требует различать формат по source.
 * Экспортирован, чтобы группировка по «стабильному типу» не заводила свою
 * копию числа (03.09.2026, разбор «377 неразобранных, 17 типов»).
 */
export const DEDUP_TEXT_LEN = 160;

export type SystemErrorSource =
  | "investigation"
  | "ai"
  | "site-sync"
  | "telegram"
  | "meta"
  | "cron"
  | "exchange-rate"
  /** Cloudflare R2 — хранилище сырого видео объектов (lib/r2Client.ts). */
  | "storage"
  /** Офисная АТС: связь с ARI, подписка на события звонков (lib/telephony). */
  | "telephony"
  /** Геокодирование адреса объекта через Nominatim (lib/geocode.ts). */
  | "geocode"
  /** Сам API: не внешний партнёр отказал, а мы упёрлись в собственный предел. */
  | "api"
  /** Рекламные кабинеты: чтение расходов Meta Ads и прочих систем (lib/ads). */
  | "ads"
  /** Очередь фоновых заданий (jobs/runner.ts): задание сдалось или тик упал. */
  | "background-jobs"
  /** YouTube Data API — публикация Shorts автомонтажа (lib/socialPublish.ts). */
  | "youtube"
  /** TikTok Content Posting API — OAuth и публикация видео (routes/tiktok.ts,
   *  lib/socialPublish.ts). */
  | "tiktok"
  /** Threads (Meta) — OAuth, продление токена и публикация постов
   *  (routes/threads.ts, lib/socialPublish.ts). */
  | "threads"
  /** Передача сырого видео монтажёру через Telegram и обратно (lib/videoHandoff.ts). */
  | "video-handoff"
  /** Единая точка записи хронологии (lib/timeline.ts) — вызывающий код передал
   *  задачу (nextAction) без subjectAgentId у не-агентского актора, П-10. */
  | "timeline"
  /** Автоподбор объектов (lib/propertyMatchFilter.ts) — пуш агенту о подходящем
   *  объекте не дошёл. До 18.09.2026 такой отказ уходил только в console.error и
   *  не попадал ни в журнал, ни в утренний отчёт: агент навсегда терял
   *  уведомление об уже отмеченном (дедуп) совпадении, и никто об этом не узнавал. */
  | "matching"
  /** Досье собеседника (lib/contactProfiles.ts) — не удалось завести или связать
   *  карточку написавшего. Молча терять это нельзя: без досье бот снова
   *  «не помнит» человека, а видно это только по жалобе владельца. */
  | "contact-profile"
  /** СМС через провайдера (lib/sms): код входа и рассылка объектов. Отказ
   *  провайдера (кончился баланс, IP не в белом списке) обязан быть виден —
   *  иначе сотрудники просто не могут войти, а причина нигде не записана. */
  | "sms";

export async function logSystemError(
  source: SystemErrorSource,
  message: string,
  context?: {
    url?: string;
    stack?: string;
    /**
     * СТАБИЛЬНЫЙ КЛЮЧ ДЕДУПЛИКАЦИИ ВМЕСТО ПЕРВЫХ `DEDUP_TEXT_LEN` СИМВОЛОВ
     * (найдено на проде 15.09.2026, `telephony`/ariEvents.ts: одна и та же
     * потеря связи приходила в журнал 15 раз за минуту).
     *
     * Дедуп по умолчанию сравнивает НАЧАЛО текста — правильное решение, пока
     * начало стабильно. Но `ariEvents.ts` кладёт туда же переменное число
     * секунд простоя (`${ALARM_MESSAGE_PREFIX} ${silentSec} с подряд: ...`), и
     * счётчик секунд растёт на каждом вызове раньше отметки `DEDUP_TEXT_LEN` —
     * каждый вызов получает СВОЙ ключ дедупликации и `everSeen`/`recent` не
     * находят друг друга никогда, хотя это один и тот же обрыв связи.
     *
     * Наименьшее вмешательство: вызывающий код передаёт свой стабильный
     * ключ явно, а не переносит переменную часть в конец сообщения силой —
     * это трогало бы только один вызов и оставляло бы тот же класс дыры для
     * следующего сообщения с числом или id в начале (см. отчёт: другие такие
     * места перечислены, не исправлены). Общий механизм (`DEDUP_TEXT_LEN`,
     * поведение по умолчанию) не меняется — параметр опциональный.
     */
    dedupKey?: string;
    /**
     * Не просить снимок пульта (23.10.2026). Только для отказов самой шины
     * живых событий (lib/eventBus.ts): иначе «публикация упала → запись ошибки
     * → снимок пульта → публикация упала…» крутится по кругу, пока лежит база.
     */
    quietPult?: boolean;
    /**
     * Окно дедупликации вместо общих 10 минут — для поломок, которые чинит
     * только человек и которые всё равно повторяются каждым тиком (нет права у
     * ключа YouTube: пока владелец не перевыпустит ключ, напоминать чаще раза в
     * сутки бессмысленно). Разобранная запись окно не сбрасывает: причина та же.
     */
    dedupWindowMs?: number;
    /**
     * ОБЛАСТЬ ДЕДУПА ВНУТРИ ОДНОГО КЛЮЧА (09.10.2026, аудит робота P1-1). Сторожа
     * ответа робота пишут с постоянным ключом («live-voice-off-catalog-claim»), чтобы
     * каждый звонок не будил директора пушем как новая поломка. Но окно дедупа по
     * одному ключу глотало находку ДРУГОГО звонка: два звонка за 10 минут с выдуманной
     * ценой — одна строка в журнале. С областью (обычно id канала звонка) повтор
     * считается повтором только в той же области: каждый звонок оставляет свою строку,
     * а пуш «Новая проблема» по-прежнему уходит только на первый раз за всю историю
     * ключа. Область дописывается в текст, если её там нет: по ней строка и ищется.
     */
    dedupScope?: string;
    /**
     * Не будить директоров пушем «Новая проблема» (E11 глубокой проверки
     * 02.10.2026): вызывающий уже оповестил их сам (сводная проверка
     * телефонии — stationHealth.ts::raiseAlert). Правило «одно событие — одно
     * уведомление»; запись в журнал при этом ложится как обычно.
     */
    silent?: boolean;
  }
): Promise<void> {
  if (isPrivateOperation()) source = "investigation";
  if (source === "investigation") context = { ...context, silent: true };
  // ОБЩИЙ МЕХАНИЗМ ОСТАНОВКИ (17.09.2026, shutdownState.ts). Фоновые задачи
  // зовут logSystemError из ~150 мест по всему проекту; во время мягкой
  // остановки пул Prisma уже закрыт или закрывается, и попытка записи здесь —
  // не баг интеграции, а ожидаемая гонка. Один флаг здесь закрывает
  // подавляющее большинство таких вызовов без правки каждого места отдельно.
  if (isShuttingDown()) {
    console.log(`[shutdown] запись в журнал ошибок пропущена при остановке (${source}): ${String(message).slice(0, 300)}`);
    return;
  }
  try {
    const scope = context?.dedupKey ? context.dedupScope?.trim().slice(0, 120) || null : null;
    const raw = String(message);
    const text = (scope && !raw.includes(scope) ? `${raw} [${scope}]` : raw).slice(0, 1000);
    // ЯВНЫЙ КЛЮЧ ХРАНИТСЯ В СВОЕЙ КОЛОНКЕ (25.09.2026). До этого ключ искался
    // как начало ТЕКСТА (`message startsWith dedupKey`) — работало только у тех
    // вызовов, чей ключ и есть начало текста (ariEvents.ts). У остальных ~80
    // («post-stats:YOUTUBE», «site-stats», «contact-profile-…») ключа в тексте нет
    // вовсе: повтор не узнавался никогда, на проде «Статистика роликов (YOUTUBE)»
    // легла четырьмя строками за минуту, и everSeen будил директора пушем на
    // каждую как на новую поломку. Старые записи без колонки по-прежнему
    // находятся по началу текста — переход без потери истории.
    const explicitKey = context?.dedupKey?.slice(0, DEDUP_TEXT_LEN) ?? null;
    const dedupKey = explicitKey ?? text.slice(0, DEDUP_TEXT_LEN);
    const sameKind = explicitKey
      ? { OR: [{ dedupKey: explicitKey }, { message: { startsWith: explicitKey } }] }
      : { message: { startsWith: dedupKey } };
    const recent = await prisma.errorLog.findFirst({
      where: {
        source,
        ...sameKind,
        ...(scope ? { message: { contains: scope } } : {}),
        createdAt: { gte: new Date(Date.now() - (context?.dedupWindowMs ?? DEDUP_WINDOW_MS)) },
      },
      select: { id: true },
    });
    if (recent) return;

    // Видели ли мы вообще когда-нибудь эту пару источник+текст (не только за
    // последние 10 минут)? Нужно ДО записи новой строки — иначе она сама себя
    // найдёт и «впервые» никогда не сработает.
    const everSeen = await prisma.errorLog.findFirst({
      where: { source, ...sameKind },
      select: { id: true },
    });

    await prisma.errorLog.create({
      data: {
        source,
        message: text,
        dedupKey: explicitKey,
        url: context?.url?.slice(0, 500) ?? null,
        stack: context?.stack?.slice(0, 4000) ?? null,
      },
    });

    if (!context?.quietPult) requestPultSnapshot(); // пульт: счётчик ошибок обновится за секунды

    // Директору — сразу, не дожидаясь утренней сводки, но только на ДЕЙСТВИТЕЛЬНО
    // новый вид поломки: повтор уже известной ошибки и так виден в счётчиках, а
    // будить пушем на каждый повтор — быстрый путь к тому, что пуш начнут
    // игнорировать (решение владельца 18.08.2026). `void` + собственный catch:
    // уведомление не должно сорвать запись самой ошибки.
    if (!everSeen && !context?.silent) {
      try {
        newErrorHook?.(source, text, context?.url);
      } catch {
        // Крючок не должен ронять запись самой ошибки — см. комментарий у onNewSystemError.
      }
    }
  } catch (err) {
    // Журнал ошибок не должен ломать то, об ошибке чего он пишет. Но и молчать
    // нельзя (G13, 02.10.2026): при недоступной базе сообщение пропадало даже из
    // лога контейнера — единственного места, где его тогда можно найти.
    console.error(`[systemError] ${source}: ${String(message).slice(0, 1000)} (запись в журнал не удалась: ${err instanceof Error ? err.message : String(err)})`);
  }
}

/**
 * КРЮЧОК ВМЕСТО ИМПОРТА push.ts — ЛОМАЕТ ЦИКЛ ИМПОРТОВ.
 *
 * push.ts сам импортирует logSystemError (запись отказа отправки push), поэтому
 * прямой (в т.ч. динамический) импорт push.ts отсюда создаёт цикл — его ловит
 * `no-circular` в CI (dependency-cruiser считает и динамические импорты рёбрами
 * графа, а не только статические). Вместо импорта systemError.ts просто зовёт
 * зарегистрированный извне колбэк, ничего не зная про push.ts. Регистрирует его
 * src/index.ts один раз при старте — там оба модуля встречаются без цикла.
 */
let newErrorHook: ((source: SystemErrorSource, message: string, url?: string) => void) | null = null;

export function onNewSystemError(hook: (source: SystemErrorSource, message: string, url?: string) => void): void {
  newErrorHook = hook;
}
