/**
 * Предел передач лида между агентами и статус «Потерянный».
 *
 * ЗАЧЕМ. Отказной лид ходил по агентам и после третьего отказа просто зависал у
 * последнего: статус оставался «горячий» или «холодный», карточка продолжала
 * считаться работой, но заниматься ею уже никто не собирался. Спецификация
 * владельца говорит прямо: после трёх передач это «Потерянный продавец» /
 * «Потерянный клиент», и распределять его дальше не нужно.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ СТАТУС, А НЕ АРХИВ. Архив — ручное решение человека («эту
 * карточку я закрыл»), и смешивать с ним автоматический вывод нельзя: в отчёте
 * «сколько мы потеряли из-за того, что никто не взял» это две разные цифры.
 * Холодный тоже не подходит — он вернётся в работу сам через месяц.
 *
 * ЧТО ОСТАЁТСЯ ВОЗМОЖНЫМ. Руководитель по-прежнему назначает такую карточку
 * вручную: «потерянный» — это про автоматику, а не про запрет работать с
 * человеком. Именно поэтому статус не трогает ни назначенного агента, ни историю.
 */

import { prisma } from "../db.js";

/** Запасное значение — ровно то, что стоит умолчанием колонки в схеме. */
const FALLBACK_MAX_TRANSFERS = 3;

export async function loadMaxTransfers(): Promise<number> {
  try {
    const s = await prisma.settings.findUnique({
      where: { id: "singleton" },
      select: { leadMaxTransfers: true },
    });
    return s?.leadMaxTransfers ?? FALLBACK_MAX_TRANSFERS;
  } catch {
    return FALLBACK_MAX_TRANSFERS;
  }
}

/**
 * Исчерпан ли предел передач.
 *
 * Сравнение «больше либо равно»: третья передача при пределе в три — последняя,
 * четвёртой не будет. Ноль и отрицательные значения выключают правило совсем —
 * это осмысленный выбор владельца «передавать сколько угодно», а не ошибка.
 */
export function transfersExhausted(transferCount: number, maxTransfers: number): boolean {
  if (maxTransfers <= 0) return false;
  return transferCount >= maxTransfers;
}
