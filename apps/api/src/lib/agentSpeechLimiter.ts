import rateLimit from "express-rate-limit";

/**
 * ОГРАНИЧИТЕЛЬ ПЛАТНОЙ РАССШИФРОВКИ РЕЧИ НА СОТРУДНИКА (находка №149, ночная
 * проверка 24.09.2026).
 *
 * `/transcribe`, `/me/voice-notes` и `/ai/parse-note` — платные вызовы модели, а
 * стояли только под общим потолком `apiLimiter` (1500 запросов за 5 минут на
 * сотрудника): зациклившаяся вкладка или скрипт с валидным токеном жёг бы
 * деньги почти без помех. Ключ — id сотрудника, не IP: весь офис сидит за одним
 * внешним адресом (та же причина, что у apiLimiter в app.ts). Ставится ПОСЛЕ
 * requireAuth, поэтому `req.agent` уже есть.
 *
 * Каждый маршрут берёт СВОЙ экземпляр: ведро у каждого своё, и диктовка заметки
 * не съедает запас разбора. Число — 30 за 5 минут, на глаз: живая диктовка столько
 * не производит (запись до минуты плюс разбор), зато цикл упирается за полминуты.
 */
export function agentSpeechLimiter(what: string) {
  return rateLimit({
    windowMs: 5 * 60 * 1000,
    limit: 30,
    standardHeaders: true,
    legacyHeaders: false,
    keyGenerator: (req) => `agent:${req.agent!.id}`,
    message: { error: `Слишком много запросов (${what}) за несколько минут — подождите немного и повторите` },
  });
}
