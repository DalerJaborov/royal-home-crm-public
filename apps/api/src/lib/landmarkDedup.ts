/**
 * Правило «два ориентира справочника — одно и то же место» для склейки дублей
 * при импорте (prisma/scripts/import-geo.ts). Вынесено из скрипта 02.10.2026,
 * чтобы его можно было проверить тестом: скрипт при импорте запускает загрузку.
 * Названия сюда приходят уже ключом geoMatchKey.
 */
import { geoMatchKey } from "./geoNormalize.js";
import { levenshteinDistance } from "./levenshtein.js";

/** Одна строка похожа на другую — точное совпадение, вхождение одной в
 *  другую (ловит «Bozori Korvon» ⊇ «Korvon» — латинская форма общая для
 *  разных языковых названий одного объекта в купленных данных) или одна
 *  опечатка в одном длинном слове. */
export function landmarkNamesLookAlike(a: string, b: string): boolean {
  if (!a || !b) return false;
  // Разные номера — разные места (02.10.2026, проба склейки на живых данных):
  // «Конечная маршрутки №12» и «№25», «Hospital №2» и «№9», «Неврологическое
  // отделение #1» и «#2» склеивались вхождением/Левенштейном — цифра в имени
  // отличается на один символ, а место другое.
  if (!sameNumbers(a, b)) return false;
  if (a === b || a.includes(b) || b.includes(a)) return true;
  // Опечатка — по словам, а не по всей строке (02.10.2026): расстояние на всю
  // строку склеивало «Вазорати адлия» с «Вазорати молия» (юстиция и финансы —
  // два слова из трёх общие, третье другое). Теперь слов столько же, и каждое
  // либо то же, либо отличается одной буквой в длинном слове («Бехзода» и
  // «Бехзод», «Шириншох» и «Шириншо»).
  const wa = a.split(" ").filter(Boolean);
  const wb = b.split(" ").filter(Boolean);
  if (wa.length !== wb.length) return false;
  let typos = 0;
  for (let i = 0; i < wa.length; i++) {
    if (wa[i] === wb[i]) continue;
    if (Math.max(wa[i].length, wb[i].length) < 5 || levenshteinDistance(wa[i], wb[i], 1) > 1) return false;
    typos++;
  }
  return typos <= 1;
}

/** Название из одного общего слова («Стадион», «Гостиница», «Рынок») — это не
 *  имя места, а его вид. Такие записи стоят в городе десятками, и вхождение
 *  в любое конкретное имя той же категории цепочкой склеивало их в одну
 *  (02.10.2026: 19 школьных стадионов ушли в «Стадион Истиклол», «Asia Grand
 *  Hotel» стал синонимом «Гостиницы»). Их не склеиваем ни с чем. */
const GENERIC_LANDMARK_NAMES = new Set(
  [
    "стадион", "спортплощадка", "гостиница", "отель", "хостел", "рынок", "базар", "бозор",
    "автовокзал", "вокзал", "торговый центр", "тц", "школа", "детский сад", "больница",
    "поликлиника", "аптека", "банк", "мечеть", "парк", "общежитие", "душанбе",
  ].map((s) => geoMatchKey(s)),
);

export function isGenericLandmarkName(name: string): boolean {
  return GENERIC_LANDMARK_NAMES.has(geoMatchKey(name.trim()));
}

/** Номера в двух названиях не противоречат друг другу: у обоих одни и те же
 *  числа, либо хотя бы у одного чисел нет вовсе («Школа» и «Школа №63» —
 *  решают расстояние и остальное правило). */
export function sameNumbers(a: string, b: string): boolean {
  const na = a.match(/\d+/g);
  const nb = b.match(/\d+/g);
  if (!na || !nb) return true;
  return [...new Set(na)].sort().join(",") === [...new Set(nb)].sort().join(",");
}
