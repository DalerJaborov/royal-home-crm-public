/**
 * МАТ И ОСКОРБЛЕНИЯ ПОД НАШИМ ПОСТОМ — УДАЛЯЮТСЯ СРАЗУ, БЕЗ МОДЕЛИ
 * (владелец 24.09.2026: «в комментариях может быть много хейта, плохих слов —
 * их сразу удалять»).
 *
 * Здесь только слова, у которых нет приличного значения: русский мат по корням и
 * таджикская брань. Всё, что может оказаться критикой по делу («обманщики»,
 * «дорого», «плохое агентство»), сюда НЕ входит — это решает модель, а на
 * претензию по делу бот отвечает вежливо (решение владельца, DEFAULT_COMMENT_PROMPT).
 *
 * Кириллица — только через BW/EW/TAIL (ai/wordBoundary.ts), `\b` здесь не работает.
 */

import { BW, EW, TAIL } from "../ai/wordBoundary.js";

const HATE = new RegExp(
  [
    // Русский мат: корни без приличных значений.
    `${BW}(на|по|ни|от|ох)?ху[йеёяию]${TAIL}`,
    `пизд`,
    `${BW}(за|вы|от|у|до|на|по|долбо|разъ|съ|при)?[её]б(ан|ат|ал|ут|уч|ну|лан|ись|ыр|аш|ёт|ет)${TAIL}`,
    `${BW}бля(д|т|ть)?${TAIL}`,
    `${BW}сук(а|и|ой|у|ин${TAIL})${EW}`,
    `${BW}муд(ак|ил|оз)${TAIL}`,
    `${BW}п[иеи]д[оа]р${TAIL}`,
    `${BW}гондон${TAIL}|${BW}гандон${TAIL}`,
    `${BW}шлю[хш]${TAIL}`,
    `${BW}мраз${TAIL}`,
    `${BW}чмо${TAIL}`,
    `${BW}тварь${EW}|${BW}твари${EW}`,
    // Таджикская брань.
    `${BW}кус(и|ат|ма|мо|мод${TAIL})?${EW}`,
    `${BW}кир(и|ат|ма)?${EW}`,
    `${BW}падарнала[тъ]${TAIL}`,
    `${BW}модар(ат|та|ша)(ро|)?${EW}`,
    `${BW}са[гк]бача${TAIL}`,
    `${BW}[чҷ]алаб${TAIL}`,
    `${BW}ландахур${TAIL}`,
    `${BW}харом(зода|и)${TAIL}`,
  ].join("|"),
  "iu"
);

/** Мат или брань — или null. */
export function detectHate(text: string): { reason: string } | null {
  return HATE.test(text) ? { reason: "мат или оскорбление" } : null;
}
