import { prisma } from "../db.js";

/**
 * Глобальный рубильник модуля Royal Score (Настройки → Команда).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ В scoreJournal.ts (15.09.2026). Рубильник нужен
 * обоим концам модуля сразу: журналу (не писать новое событие) и оповещению (не
 * слать push о счёте). Но журнал уже импортирует оповещение — и функция,
 * положенная в журнал, замкнула импорты в кольцо
 * scoreAlert → scoreJournal → scoreAlert. `audit:deps` такое кольцо запрещает
 * отдельным правилом, и не формально: именно так в этом репозитории вылезала
 * ошибка «Cannot access ... before initialization» — порядок инициализации
 * модулей становится неявным. Поймано на CI сразу после мержа PR #416.
 *
 * Отдельный лист, который не импортирует ничего из модуля, а только БД, —
 * штатный способ дать общую проверку обоим концам, не связывая их между собой.
 *
 * Выключен — новые события не пишутся, push о счёте не уходит, кабинет и
 * карточка в профиле не показываются. Уже накопленный журнал не трогаем: это
 * история, а не текущее поведение.
 */
export async function royalScoreEnabled(): Promise<boolean> {
  const settings = await prisma.settings.findUnique({
    where: { id: "singleton" },
    select: { royalScoreEnabled: true },
  });
  return settings?.royalScoreEnabled ?? true;
}
