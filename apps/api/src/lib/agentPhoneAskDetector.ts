/**
 * Детектор «агент спросил номер телефона» — требование 11 аудита 02.09.2026,
 * поведение переработано 07.09.2026 (владелец: «и то не нужно вмешиваться в
 * онлайн»).
 *
 * Раньше при срабатывании сразу уходил пуш директору — владелец решил, что
 * это лишнее: сам по себе вопрос о номере ещё ничего не доказывает (агенту
 * он мог понадобиться для показа, курьера и т.п.), а немедленный пуш будил
 * директора по пустякам. Теперь детектор МОЛЧА помечает карточку клиента
 * (Client.phoneAskFlaggedAt/ByAgentId) — это только факт-якорь. Настоящий
 * аларм уходит ОТДЕЛЬНЫМ модулем (lib/agentOffCrmAlarm.ts) и только если
 * ПОСЛЕ этого момента агент перестал вести клиента через CRM (тишина 2 дня
 * или брошенная договорённость) без объяснения со стороны самого клиента —
 * то есть похоже на увод сделки в обход компании, а не разовый вопрос.
 *
 * Этот модуль — дешёвый regex-детектор без вызова ИИ, работает синхронно, не
 * блокирует отправку сообщения (решение владельца в аудите §7 п.7: «сигналить
 * + маскировать, не блокировать»).
 */

import { prisma } from "../db.js";

// ─── Паттерны ────────────────────────────────────────────────────────────────

/**
 * Фразы, которыми агент просит номер. Порядок не важен — проверяем все.
 * Кириллица и латиница: агенты пишут и так и так, особенно в Telegram.
 *
 * НЕ ловим:
 *  - «мой номер» / «наш номер» — агент называет СВОЙ, а не просит чужой;
 *  - «номер объекта» / «номер заявки» — не телефон;
 *  - вопросы клиента («какой у вас номер?») — здесь проверяем только АГЕНТА.
 *
 * Границы слов: `\b` не работает с кириллицей в JS (см. ai/replyGuards.ts),
 * поэтому используем явные границы или обходимся без них там, где фраза
 * достаточно специфична.
 */
const PHONE_ASK_PATTERNS: RegExp[] = [
  // Прямые просьбы: «напишите номер», «оставьте телефон», «скиньте номерок»
  /(?:напиши(?:те)?|оставь(?:те)?|скинь(?:те)?|дай(?:те)?|пришли(?:те)?|отправь(?:те)?)\s+(?:ваш\s+)?(?:номер|телефон|тел\.?|контакт)/iu,
  // Вопросы: «какой у вас номер», «какой номер телефона»
  /какой\s+(?:у\s+(?:вас|тебя)\s+)?(?:номер|телефон)/iu,
  // «ваш телефон» в контексте вопроса/просьбы (не «ваш телефон заблокирован»)
  /(?:ваш|твой)\s+(?:телефон|номер)(?:\s*[?？]|$|\s+(?:для|чтобы))/iu,
  // «позвоните мне на этот номер» / «перезвоните на +992…» — агент даёт СВОЙ
  // номер, но это тоже попытка увести разговор в личный канал; по решению
  // владельца (§7 п.7) только сигналим, не блокируем. После «на» обязан идти
  // номер/телефон/цифры — иначе ловилось бытовое «перезвоните на следующей неделе».
  /(?:позвони(?:те)?|перезвони(?:те)?)\s+(?:мне\s+)?на\s+(?:этот\s+|мой\s+|данный\s+|вот\s+этот\s+)?(?:номер|телефон|\+?\d)/iu,
  // «можете дать номер» / «можно ваш номер»
  /(?:можете?\s+(?:ли\s+)?(?:дать|назвать)|можно\s+(?:ваш|твой))\s+(?:номер|телефон)/iu,
  // Номер в вопросе агента: «+992» или «+7» рядом с вопросительным знаком или
  // словом «номер». Ловим случаи «ваш номер +992...?» — агент диктует свой и
  // спрашивает подтверждение, либо просит клиента продиктовать.
  /(?:\+992|\+7)\s*\d[\d\s()-]{5,}\s*[?？]/iu,
  // Таджикские варианты (агенты часто пишут по-таджикски).
  // «рақаматонро нависед» = «напишите ваш номер»: корень рақам + любые суффиксы
  // притяжательности/падежа (-ат, -атон, -ро, -аш и т.д.) + глагол просьбы.
  // \S* вместо [а-я…]*: таджикская кириллица включает буквы вне диапазона а-я
  // (қ, ғ, ҳ, ҷ, ӣ, ӯ), и перечислять их все хрупко. \S* берёт любые непробельные
  // символы до первого пробела — ровно один словоформный хвост.
  /(?:рақам|телефон|номер)\S*\s*(?:навишт|гуфт|диҳед|бидеҳ|маълум|кунед|нависед)/iu,
  /шумо\s+(?:рақам|телефон)/iu,
];

/**
 * Проверяет текст на наличие просьбы о номере телефона.
 * Возвращает найденный паттерн (для отладки) или null.
 */
export function detectPhoneAsk(text: string): string | null {
  if (!text || text.length < 3) return null;
  for (const pattern of PHONE_ASK_PATTERNS) {
    if (pattern.test(text)) return pattern.source;
  }
  return null;
}

export type PhoneAskChannel = "text" | "voice" | "call" | "comment";

// ─── Точка входа ─────────────────────────────────────────────────────────────

interface CheckParams {
  agentId: string;
  agentName: string;
  clientId: string | null;
  clientName: string | null;
  channel: PhoneAskChannel;
  text: string;
}

/**
 * Проверяет текст агента на просьбу о номере и, если найдено, молча помечает
 * карточку клиента (Client.phoneAskFlaggedAt/ByAgentId) — без пуша директору,
 * см. комментарий в шапке файла. Вызывать ФОНОМ (void) — проверка не должна
 * задерживать основной поток (отправку сообщения, сохранение комментария,
 * разбор звонка).
 *
 * Без clientId (текст без карточки) помечать нечего — выходим сразу. Пишем
 * БЕЗ дедупа-по-24ч, который был нужен только push'у: повторный вопрос про
 * номер просто освежает дату — это и есть новый, более свежий якорь.
 */
export async function checkAgentPhoneAsk(params: CheckParams): Promise<void> {
  if (!params.clientId) return;
  const matched = detectPhoneAsk(params.text);
  if (!matched) return;
  try {
    await prisma.client.update({
      where: { id: params.clientId },
      data: { phoneAskFlaggedAt: new Date(), phoneAskFlaggedByAgentId: params.agentId },
    });
  } catch (err) {
    console.error("[agentPhoneAskDetector] не удалось пометить карточку:", err);
  }
}