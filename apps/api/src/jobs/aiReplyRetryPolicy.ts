/**
 * Лесенка повторов отложенного ответа ИИ — ОТДЕЛЬНЫМ файлом без импортов,
 * потому что её читают оба процесса: HTTP ставит задание (conversation.ts),
 * worker исполняет (jobs/aiReplyRetry.ts). Сам обработчик тянет за собой весь
 * messengers/*, и HTTP-процессу это ни к чему.
 *
 * Числа — те же, что жили в ai/aiRetryQueue.ts (решения владельца 03.08 и
 * 16.08.2026): быстрая фаза ~78 минут, затем хвост по 20 минут до ~13 часов —
 * ночной сбой поставщика переживается целиком, клиент из 22:00 получает ответ
 * к утру. Дальше 13 часов не тянем: отвечать на вчерашнее сообщение как ни в
 * чём не бывало хуже, чем честная тишина и агент.
 */

// 30с, 1м, 2м, 5м, 5м, 10м, 10м, 15м, 15м, 15м — сумма ≈ 78 минут.
const FAST_PHASE_MS = [30_000, 60_000, 120_000, 300_000, 300_000, 600_000, 600_000, 900_000, 900_000, 900_000];
const TRAILING_MS = 20 * 60_000;
const TRAILING_ATTEMPTS = 36; // ещё ~12 часов

export const AI_REPLY_RETRY_MAX_ATTEMPTS = FAST_PHASE_MS.length + TRAILING_ATTEMPTS;

/** Пауза после attempt-й неудачи (attempt считается с 1). */
export function aiReplyRetryBackoffMs(attempt: number): number {
  return FAST_PHASE_MS[attempt - 1] ?? TRAILING_MS;
}

