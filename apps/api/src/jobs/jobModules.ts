import type { PultModuleId } from "@royal-home/shared";

/**
 * Карта «тип фонового задания → модуль пульта» (аудит 02.09.2026 §4, гейт очереди).
 *
 * Выключенный модуль пульта не должен тратить ресурсы фоном — значит задание,
 * принадлежащее модулю, не ставится в очередь (enqueue → { skipped }), а уже
 * поставленное исполнитель переводит в SKIPPED, не в FAILED и не в DONE.
 *
 * В карту попадают ТОЛЬКО задания, которые логически живут ради плитки пульта.
 * Продуктовые задания — ответ бота клиенту (ai-reply-retry), расшифровка звонка,
 * монтаж и сжатие видео, геокодирование, синхронизация с сайтом — сюда НЕ входят
 * и исполняются всегда: тумблер плитки «Видео-конвейер» не имеет права остановить
 * монтаж ролика для клиента. На 04.09.2026 таких «пультовых» заданий в очереди
 * нет — карта пуста намеренно, механизм готов к первому (например, фоновая
 * генерация DirectorReport → модуль aiReport).
 */
export const JOB_PULT_MODULES: Readonly<Record<string, PultModuleId>> = {};

export function pultModuleOfJob(type: string): PultModuleId | null {
  return JOB_PULT_MODULES[type] ?? null;
}
