/**
 * КЛИЕНТ СВОИМИ СЛОВАМИ ГОВОРИТ О СДЕЛКЕ С ЖИЛЬЁМ — ЭТО СТАРШЕ ЛЮБОЙ РЕКЛАМЫ.
 *
 * Зачем нужно (найдено 20.09.2026 по выгрузке 775 живых переписок). С 17.09.2026
 * признак «человек пришёл по рекламе ВАКАНСИИ» (BotConversation.adTopic="job")
 * живёт весь разговор и на КАЖДОМ ходе подставляет модели подсказку
 * `vacancyTurnHint`, которая прямым текстом запрещает спрашивать про квартиру.
 * Правка была верной (до неё признак жил один ход, и кандидата со второго
 * сообщения вели как покупателя), но выхода из этого состояния не осталось
 * вовсе. В выгрузке видно, во что это обходится:
 *
 *   клиент: Хавлии фуруши дорам            («у меня дом на продажу»)
 *   бот:    Мо агентони фурӯшро ба кор қабул мекунем. Резюме доред?
 *   клиент: Бо кадом минтакахо кор мекунед
 *   бот:    …Оё резюме доред?
 *   клиент: Ма мегум хавлии фуруши дорм, мада кор ларкор нест
 *
 * Продавец пять ходов подряд объяснял боту, что ему не нужна работа. Такой же
 * случай в тот же день: человек продал разговор о даче до конца, а в хвосте
 * получил «руководство хочет поговорить с вами о работе, пришлите номер».
 *
 * Поэтому: как только клиент СВОИМИ словами сказал про сделку с жильём, подсказка
 * о вакансии молчит. Реклама — это догадка о человеке, его собственные слова —
 * факт, и факт сильнее.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ЕЩЁ ОДНА РЕГУЛЯРКА НА МЕСТЕ. Порог и словарь
 * «клиент говорит про покупку/продажу» в этом проекте уже лежат копиями в
 * ai/rentGuard.ts, ai/leadKind.ts и ai/intentDirectionGuard.ts, и починка в одной
 * копии не помогает в остальных (разбор — docs/bot-razbor-20-09.md). Четвёртую
 * копию рядом не заводим: здесь один вопрос — «человек говорит о своём жилье?» —
 * и одно место, где он задаётся.
 */

import { BW, EW, TAIL } from "./wordBoundary.js";

/**
 * ГРАНИЦЫ СЛОВ — BW/EW/TAIL (ai/wordBoundary.ts), А НЕ `\w` (02.10.2026, разбор
 * кандидатов в каналах). `хона\w*` без левой границы находило «хона» внутри
 * «хонадор» (женат), «хонанда» (учащийся), «корхона» (завод), «ошхона», «чойхона»;
 * а `\w` по кириллице вообще молчит, так что «окончание» на деле не добиралось.
 * Кандидат, написавший «25 сол дорам, хонадор», выглядел хозяином жилья: «хона» из
 * «хонадор» плюс «дорам» рядом — и уходил карточкой «прочего обращения» вместо
 * анкеты. Те же слова с левой границей: «задача»/«передача» больше не «дача».
 *
 * «хона» — с исключениями: хонадор/хонадон/хонавода (семья), хонашин (сидит дома),
 * хонанда (учащийся), хонагӣ (домашний) — это слова о человеке, а не о жилье.
 */
/**
 * Левая граница — только БУКВА, а не буква-или-цифра (доразбор 02.10.2026): общий
 * BW не пускает совпадение и после цифры, и «3хонаги мефурушам» переставал быть
 * продажей. Слитно с цифрой жильё пишут постоянно; внутри слова — нет.
 */
const LB = "(?<![\\p{L}])";

const HOUSING =
  `${LB}(?:кварт${TAIL}|хона(?!дор|дон|вод|шин|нда|гӣ)${TAIL}|ҳавл[иӣ]${TAIL}|хавл[иӣ]${TAIL}|манзил${TAIL}|` +
  `коттедж${TAIL}|таунхаус${TAIL}|сотих${TAIL}|сотик${TAIL}|сотка|соток|участок|қитъаи замин${TAIL}|китъаи замин${TAIL}|` +
  `дом|дача|дачу)${EW}`;

/** Глагол сделки — достаточно силён, чтобы склеиться с жильём через 40 знаков. */
const DEAL_STRONG =
  `${LB}(?:мефур[ӯу]ш${TAIL}|фур[ӯу]ш${TAIL}|фур[ӯу]хт${TAIL}|мехар${TAIL}|бихар${TAIL}|харид${TAIL}|` +
  `прода${TAIL}|куп(?:ить|лю|им|ите)|покупк${TAIL}|(?:и)?ҷора${TAIL}|ичора${TAIL}|аренд${TAIL}|снять|сдать|` +
  `мекоб${TAIL}|ищу|ищем|лозим|даркор|` +
  // «Шумо хона реклама мекунед?», «хонаамро эълон кунед» (владелец 25.09.2026):
  // хозяин хочет разместить у нас своё жильё — это продажа, а не отклик на вакансию.
  `реклам${TAIL}|эълон${TAIL})${EW}`;

/**
 * «ЕСТЬ / ДОРАМ» — СЛАБЫЙ ГЛАГОЛ: «хона дорам», «есть квартира» (владелец
 * 25.09.2026) — это хозяин жилья, но «дорам» в таджикском — ещё и «мне 25 лет»
 * («25 сол дорам»), а «есть» — что угодно. Поэтому слабый глагол склеивается с
 * жильём только ВПЛОТНУЮ (до 12 знаков) и не через запятую: «хона дорам» — да,
 * «25 сол дорам, дар хона нишастаам» — нет (02.10.2026).
 */
const DEAL_WEAK = `${LB}(?:дор(?:ам|ем|им|ум|ед|ад|а)|есть|имеется)${EW}`;

/**
 * В пределах одного предложения и не дальше 40 символов друг от друга: иначе
 * «квартира» из начала длинного рассказа склеивалась бы с «продаж» из конца.
 */
const NEAR = "[^.!?\\n]{0,40}";
const NEAR_TIGHT = "[^.!?,;\\n]{0,12}";

const HOUSING_DEAL = new RegExp(
  `(?:${HOUSING}${NEAR}${DEAL_STRONG}|${DEAL_STRONG}${NEAR}${HOUSING}|` +
    `${HOUSING}${NEAR_TIGHT}${DEAL_WEAK}|${DEAL_WEAK}${NEAR_TIGHT}${HOUSING})`,
  "iu"
);

/**
 * Человек описывает объект цифрами: «ду сотих хона дар калхоз», «2 хонага»,
 * «65кв», «340кв 2 юм этаж» (владелец 25.09.2026 — хозяйка рассказывала про свой
 * дом, а бот продолжал звать её в агенты: глагола сделки в её словах не было).
 * Кандидат о себе так не говорит; опыт работы с жильём ловит JOB_WORDS раньше.
 */
const PROPERTY_FACTS = new RegExp(
  "(?:\\d+|як|ду|се|чор|панҷ|панч|один|два|три|четыре)\\s*(?:-?\\s*)" +
    "(?:сотих|сотик|сотка|соток|сотки|кв(?![\\p{L}])|квадрат|м²|м2|хонага|ҳуҷрагӣ|хучраги|комнат|ошёна|ошиёна|этаж|юм\\s+этаж)",
  "iu"
);

/**
 * Слова САМОГО разговора о работе. Они гасят совпадение выше, потому что кандидат
 * законно говорит о жилье в рассказе о себе: «дар фурӯши хона таҷриба дорам» —
 * это опыт работы, а не его квартира.
 *
 * ТОЛЬКО ФРАЗЫ, НЕ ГОЛЫЕ СЛОВА (доразбор 02.10.2026). Голые «работа», «опыт»,
 * «кор ҳаст» гасили и продавцов: «Хочу продать дом. Звоните вечером, днём работа»,
 * «Продаю квартиру, у вас есть опыт продаж?». Поэтому здесь «нужна работа», «ищу
 * работу», «опыт работы/продаж», «кор лозим», «кор мекардам» и т. п., а явная
 * продажа своего жилья проверяется ещё раньше (EXPLICIT_DEAL ниже). «HR» — только
 * отдельным словом: внутри «Bahrom» его не было.
 */
const JOB_WORDS = new RegExp(
  `${BW}(?:ваканси${TAIL}|резюме|та[ҷч]риба${TAIL}|маош${TAIL}|музд${TAIL}|зарплат${TAIL}|` +
    `трудоустрой${TAIL}|собеседован${TAIL}|hr|` +
    `нужна\\s+работа|работа\\s+нужна|ищу\\s+работу|работу\\s+ищу|` +
    `(?:хочу|хотел${TAIL}|могу|готов${TAIL})\\s+работать|работать\\s+(?:у\\s+вас|агентом|риелтором|риэлтором)|` +
    `опыт${TAIL}\\s+(?:работы|продаж${TAIL}|в\\s+продажах|в\\s+недвижимости)|` +
    `кор\\s+(?:ҳаст|хаст|лозим|даркор|мекунам|мекардам|кардам|кардан|мехоҳам|мехохам))${EW}`,
  "iu"
);

/**
 * ЯВНАЯ СДЕЛКА СО СВОИМ ЖИЛЬЁМ — от первого лица, рядом со словом о жилье:
 * «продаю квартиру», «3хонаги мефурушам», «хочу продать дом», «квартира на
 * продажу». Сильнее любых слов о работе в том же тексте: «Хона мефурушам, кор
 * ҳаст?» — это продавец, который заодно спросил о работе. Рассказ кандидата о
 * прошлом («продавал квартиры», «дар фурӯши хона») сюда не попадает: там нет
 * глагола от первого лица в настоящем.
 */
const EXPLICIT_VERB =
  `${LB}(?:продаю|продам|продаём|продаем|(?:хочу|хотим)\\s+продать|на\\s+продажу|` +
  `мефур[ӯу]ш(?:ам|ем|ед|анд)|фур[ӯу]хтан(?:ӣ|и)?\\s+мехо[ҳх]${TAIL}|` +
  `куплю|(?:хочу|хотим)\\s+купить|мехарам|мехарем|харидан\\s+мехо[ҳх]${TAIL})${EW}`;
const EXPLICIT_DEAL = new RegExp(`(?:${EXPLICIT_VERB}${NEAR}${HOUSING}|${HOUSING}${NEAR}${EXPLICIT_VERB})`, "iu");

/**
 * Прямой отказ от вакансии. Перебивает всё, включая слова о работе рядом: человек
 * произносит их как раз для того, чтобы отказаться («мада кор ларкор нест»).
 */
const NOT_ABOUT_JOB =
  /(кор\s+(лозим|даркор|лар?кор)\s+нест|кор\s+намехо[ҳх]\w*|не\s+ищу\s+работу|работа\s+не\s+нужна|не\s+по\s+работе|не\s+насч[её]т\s+работы|кор\s+не\s+даркор)/iu;

/**
 * Клиент своими словами говорит о сделке со своим или нужным ему жильём?
 *
 * На вход — слова КЛИЕНТА (одна реплика или все его реплики разговора подряд),
 * никогда не ответы бота: бот сам произносит и «фурӯш», и «квартира» в каждом
 * втором сообщении.
 */
export function clientMeansHousingDeal(clientWords: string | null | undefined): boolean {
  // NFC (02.10.2026): часть клавиатур пишет «ӣ»/«ӯ» буквой с отдельным знаком, и
  // ни один шаблон ниже такую букву не узнаёт.
  const text = (clientWords ?? "").normalize("NFC").trim();
  if (!text) return false;
  if (NOT_ABOUT_JOB.test(text)) return true;
  if (EXPLICIT_DEAL.test(text)) return true;
  if (JOB_WORDS.test(text)) return false;
  return HOUSING_DEAL.test(text) || PROPERTY_FACTS.test(text);
}
