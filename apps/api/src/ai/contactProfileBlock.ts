import { CONTACT_CATEGORY_LABELS, contactCategoryLabel, type ContactCategory } from "@royal-home/shared";

/** Язык человека — подписи для промта, служебные. */
const LANGUAGE_LABELS: Record<string, string> = {
  tg: "по-таджикски",
  ru: "по-русски",
  en: "по-английски",
};

/** Одна прошлая роль человека: кем он был и когда. */
export interface PreviousCategory {
  category: string;
  /** Уже готовая человеческая дата («12 августа»), а не ISO: форматирует вызывающий. */
  when: string;
}

export interface ContactProfileForPrompt {
  category: ContactCategory;
  /** Прошлые роли, новее первыми, максимум две: длиннее не помогает решать. */
  previousCategories: PreviousCategory[];
  /** Имя, которое человек назвал САМ. Имя из профиля канала сюда не попадает. */
  selfName: string | null;
  /** Код языка, на котором человек пишет обычно: "tg" | "ru" | "en". */
  language: string | null;
  /** «пишет нам с 12 августа, 37 сообщений; последний раз 5 дней назад». */
  history: string | null;
  /** Чего ищет — только то, чего НЕТ в черновике текущего разговора. */
  buyer: string[];
  /** Что называл про свой объект в ПРОШЛЫХ разговорах. */
  seller: string[];
  /** Анкета кандидата. */
  job: string[];
  /** «ПК-000312, агент Умед» — без телефона. */
  crm: string | null;
}

/**
 * Собирает блок промта. Пустая строка означает «печатать нечего»: вызывающий
 * приклеивает результат как есть, без проверок на своей стороне.
 */
export function contactProfileBlock(
  profile: ContactProfileForPrompt | null | undefined,
  /**
   * withCrmCard: false — без строки «Карточка в CRM» (код карточки и агент).
   * Нужно голосу (02.10.2026): номер звонка подделывается, и служебный код
   * карточки — внутренний идентификатор CRM — не должен попадать туда, где модель
   * может произнести его вслух любому, кто позвонил с чужого номера. Агента
   * консультант и так знает отдельно (ConsultantCaller.agentName). Чат-бот
   * печатает блок как раньше.
   */
  opts: { withCrmCard?: boolean } = {}
): string {
  if (!profile) return "";
  const lines: string[] = [];

  if (profile.category !== "UNKNOWN") {
    const past = profile.previousCategories.length
      ? `; раньше: ${profile.previousCategories.map((p) => `${contactCategoryLabel(p.category)} (${p.when})`).join(", ")}`
      : "";
    lines.push(`Кто это: ${CONTACT_CATEGORY_LABELS[profile.category]}${past}.`);
  }
  if (profile.selfName) lines.push(`Имя, которое он называл сам: ${profile.selfName}.`);
  if (profile.language && LANGUAGE_LABELS[profile.language]) {
    lines.push(`Обычно пишет ${LANGUAGE_LABELS[profile.language]}.`);
  }
  if (profile.history) lines.push(`История: ${profile.history}.`);
  if (profile.buyer.length) lines.push(`Искал раньше: ${profile.buyer.join(", ")}.`);
  if (profile.seller.length) lines.push(`Про свой объект называл раньше: ${profile.seller.join(", ")}.`);
  if (profile.job.length) lines.push(`Анкета кандидата: ${profile.job.join("; ")}.`);
  if (profile.crm && opts.withCrmCard !== false) lines.push(`Карточка в CRM: ${profile.crm}.`);

  if (lines.length === 0) return "";
  return (
    `\n\nДОСЬЕ СОБЕСЕДНИКА (посчитано КОДОМ по всем его прошлым разговорам и звонкам в любом канале — ` +
    `это точнее твоей памяти о переписке): ${lines.join(" ")} ` +
    `Не переспрашивай то, что здесь уже есть, и не пересказывай досье человеку — он не просил отчёт о себе. ` +
    `Это знание о ПРОШЛЫХ обращениях: если сейчас он говорит иное, верь новому и уточни одной фразой. ` +
    `Номер телефона здесь не печатается никогда — не делай вид, что знаешь его.`
  );
}
