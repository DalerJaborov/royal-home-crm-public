import type { LeadIntent, ShowingRequest, WhoIsThis } from "./botContract.js";

/** Что нужно клиенту: купить / продать (разместить у нас) / устроиться на работу /
 * аренда (пока нет) / прочее. По этому агент в CRM сразу понимает суть заявки.
 * Persisted data only: no qualifier runtime or prompt-memory dependencies. */
export interface LeadDraft {
  stage: "chatting" | "awaiting_phone" | "done";
  intent?: LeadIntent;
  /**
   * КТО ПИШЕТ (21.09.2026) — шире, чем `intent`, и живёт дольше одного хода.
   *
   * Нужен тем, у кого намерения не будет никогда: рекламный агент, поставщик,
   * застройщик. У всех трёх `intent="other"`, и до этого поля код не мог
   * отличить их ни друг от друга, ни от покупателя, которого просто не успели
   * распознать, — а значит не мог ни дать им свой сценарий, ни снять права.
   * Заполняется моделью только при включённом тумблере «Бот-специалист по типу
   * обращения»; действует, лишь пока намерение не известно (см. mergeDraft).
   */
  whoIsThis?: WhoIsThis;
  /**
   * УВЕРЕНА ЛИ МОДЕЛЬ В ТИПЕ ОБРАЩЕНИЯ (добавлено 30.08.2026).
   *
   * Поля уверенности не было вовсе, и «не понял человека» на выходе выглядело
   * ровно как «покупатель»: intent оставался пустым, а карточка в
   * services/leads/intake.ts молча получала kind=BUYER и уходила живому агенту.
   * Теперь false означает «разбирать вручную» — карточка идёт в «Прочие
   * обращения» (см. ai/leadKind.ts). Образец поля — ai/incomingCallLead.ts,
   * там уверенность появилась раньше и по той же причине.
   */
  confident?: boolean;
  budgetMin?: number;
  budgetMax?: number;
  /**
   * СУММА, КОТОРУЮ КЛИЕНТ НАЗВАЛ, НО В БЮДЖЕТ ОНА НЕ ГОДИТСЯ (03.09.2026).
   *
   * mergeDraft отбрасывает вилку ниже MIN_REAL_PURCHASE_TJS — по ней нельзя
   * искать объекты, и в полях бюджета она мусор. Но эта же сумма — ГЛАВНАЯ улика
   * аренды без слова «аренда», и правило, которое её ждало (ai/leadKind.ts:
   * «🔑 ПОХОЖЕ НА АРЕНДУ»), получало уже пустой бюджет и молчало.
   *
   * Живой случай 03.09.2026: «2 хуҷрага бо нархи аз 3000 то 4500» — ни одного
   * слова про аренду, вилка стёрта как нереальная, intent=buy, и карточка
   * «Покупатель ПК-000250» ушла живому агенту. Два правильных правила погасили
   * друг друга, потому что одно стирало улику, которую ждало второе.
   *
   * Поэтому сумма не пропадает: в поля бюджета она не идёт, но остаётся здесь —
   * для решения о типе обращения и для агента в заметке.
   */
  budgetUnrealistic?: number;
  districtId?: string;
  districtName?: string;
  type?: string;
  rooms?: number;
  notes?: string;
  /** Продавец явно назвал объект в другом городе/районе Таджикистана (не Душанбе) —
   * такую заявку не даём агентам (у нас только Душанбе), она уходит в
   * «Прочие обращения» руководству, но телефон всё равно берём. */
  locationOutsideDushanbe?: boolean;
  /** Продавец назвал объект за пределами Таджикистана (Россия и т.п.) — такую заявку
   * не принимаем вообще: телефон не просим, карточку/лид не создаём, вежливо отказываем. */
  locationDifferentCountry?: boolean;
  /** Показ, о котором клиент уже договорился с ботом, но заявки ещё нет (телефон не
   * назван). Показ невозможно записать в CRM без карточки клиента — Interaction
   * требует clientId, — поэтому договорённость ждёт здесь и оформляется в тот же
   * миг, когда появляется телефон (см. acceptLead в messengers/conversation.ts). */
  pendingShowing?: ShowingRequest;
  /**
   * КОГО КЛИЕНТ НАЗВАЛ САМ («мне нужен Умед») — решение владельца 18.08.2026.
   * Проверенный по базе id сотрудника: имя распознаёт код (lib/requestedAgent.ts)
   * на том ходе, где оно прозвучало, а нужен он позже — в миг, когда клиент
   * назовёт телефон и появится заявка. Живёт в черновике, потому что это то же
   * самое «что мы уже знаем о клиенте», что бюджет и район, и переживать
   * перезапуск обязано вместе с ними.
   */
  requestedAgentId?: string;
  /** Пометка о названном имени для карточки — в том числе когда однозначно
   *  определить не вышло (тёзки) или сотрудник недоступен. */
  requestedAgentNote?: string;
  /**
   * КЛИЕНТ НАЗВАЛ НОМЕР ОБЪЕКТА («объект №112») — решение владельца 23.09.2026,
   * тот же приём, что requestedAgentId выше: номер распознаёт код
   * (ai/propertyMentionGuard.ts) на том ходе, где он прозвучал, id объекта
   * проверяется по базе (lib/telephony/resolveCallProperty.ts), а применяется
   * позже, в момент оформления заявки (см. acceptLead в
   * messengers/conversation.ts) — уходит в LeadAssignContext.propertyId той же
   * лесенки, что уже обслуживает ссылку с сайта и номер, названный в звонке.
   */
  requestedPropertyId?: string;
  /**
   * КЛИЕНТ ПРОСИЛ ПЕРЕЗВОНИТЬ, и дежурного оператора нет (рубильник «Соединять с
   * оператором» выключен) — тема звонка ждёт здесь до появления телефона, ровно как
   * pendingShowing ждёт карточки. В миг создания заявки она уезжает в требования
   * карточки, чтобы агент, которому лид достался, звонил зная о чём (acceptLead в
   * messengers/conversation.ts). При включённом рубильнике поле не заполняется:
   * там просьба живёт своей записью и очередью (lib/callbackRequests.ts).
   */
  callbackTopic?: string;
  /**
   * СКОЛЬКО РАЗ БОТ УЖЕ ПЕРЕСПРАШИВАЛ НЕЧИТАЕМЫЙ НОМЕР (03.09.2026).
   *
   * Переспрос помогает ровно первые два раза. Дальше это уже не помощь, а
   * препирательство: человек присылает одно и то же, бот отвечает одно и то же.
   * После предела разговор идёт обычным путём, а номер видит сторож
   * (lib/phoneLeadWatchdog.ts) и показывает его живому человеку.
   */
  phoneRetryCount?: number;
}
