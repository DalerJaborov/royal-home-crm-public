/**
 * НА КАКОМ ЯЗЫКЕ БРАТЬ ТРУБКУ (10.10.2026, владелец: «таджикский — в приоритете»).
 *  - "ru" — замок «только русский» или человек говорил с нами по-русски (досье);
 *  - "tg" — говорил по-таджикски: только по-таджикски;
 *  - "tg-first" — язык неизвестен: сначала по-таджикски, тут же коротко по-русски.
 * Одно решение и для правила в промте (greetingRule), и для служебной реплики-старта
 * (withGreetingLanguage): служебная реплика написана по-русски, и без явного указания
 * модель отвечала на неё по-русски — так незнакомец слышал «Здравствуйте» первым словом.
 */
export type ConsultantGreetingLanguage = "ru" | "tg" | "tg-first";

export function consultantGreetingLanguage(forceRussianOnly: boolean, callerLanguage: string | null | undefined): ConsultantGreetingLanguage {
  if (forceRussianOnly || callerLanguage === "ru") return "ru";
  return callerLanguage === "tg" ? "tg" : "tg-first";
}

