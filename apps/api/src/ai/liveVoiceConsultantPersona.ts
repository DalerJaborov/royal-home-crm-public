/** Служебная реплика-старт с указанием языка первой фразы (текст в скобках не озвучивается). */
export function withGreetingLanguage(trigger: string, language: ConsultantGreetingLanguage): string {
  if (language === "ru") return trigger;
  const tail =
    language === "tg"
      ? " Здоровайся по-таджикски: «Ассалому алайкум, Royal Home, гӯш мекунам»."
      : ` Поздоровайся на двух языках, коротко, таджикский первым: «Ассалому алайкум», тут же по-русски «здравствуйте» и Royal Home — одной фразой, например «${CONSULTANT_TAJIK_FIRST_GREETING}». Дальше говори на том языке, на котором ответит человек.`;
  return trigger.replace(/\)\s*$/u, `${tail})`);
}

