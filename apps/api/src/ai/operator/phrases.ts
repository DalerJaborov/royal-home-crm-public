/** «Когда позвонит агент» словами — из окна рабочих часов (ai/leadOnlyMode.ts::leadOnlyCallbackWhen). */
export function operatorWhenText(when: { kind: "soon" } | { kind: "today_from" | "tomorrow_from"; from: string }): { ru: string; tg: string } {
  if (when.kind === "soon") return { ru: "в ближайшее время", tg: "ба зудӣ" };
  if (when.kind === "today_from") return { ru: `сегодня с ${when.from}`, tg: `имрӯз аз соати ${when.from}` };
  return { ru: `завтра с ${when.from}`, tg: `пагоҳ аз соати ${when.from}` };
}

function joinList(items: readonly string[], language: OperatorLanguage): string {
  const clean = items.map(item => item.trim()).filter(Boolean);
  if (clean.length <= 1) return clean[0] ?? "";
  return `${clean.slice(0, -1).join(", ")} ${language === "tg" ? "ва" : "и"} ${clean.at(-1)}`;
}

/** Подстановка переменной: тире и переносы из данных не проходят в текст клиенту. */
function cleanValue(value: string): string {
  return value.replace(/\s*[—–]\s*/gu, ", ").replace(/\s+/gu, " ").trim();
}

function renderValue(name: string, value: PhraseVars[string], language: OperatorLanguage): string {
  if (name === "missing" && Array.isArray(value)) {
    return joinList((value as readonly string[]).map(field => DETAIL_WORDS[language][field as OperatorDetailField] ?? field), language);
  }
  if (name === "where") return value === "WHATSAPP" ? WHERE[language].whatsapp : WHERE[language].here;
  if (Array.isArray(value)) return joinList((value as readonly string[]).map(cleanValue), language);
  return cleanValue(String(value));
}

/** Текст одного шага. Неизвестная переменная в шаблоне — ошибка разработчика: бросаем, а не шлём «{price}» клиенту. */
export function renderOperatorStep(step: OperatorStepOut, language: OperatorLanguage): string {
  const variants = OPERATOR_PHRASES[step.key][language];
  const template = variants[((step.variant % variants.length) + variants.length) % variants.length]!;
  return template.replace(/\{(\w+)\}/gu, (_, name: string) => {
    const value = step.vars[name];
    if (value === undefined) throw new Error(`[operator-phrases] ${step.key}: нет переменной {${name}}`);
    return renderValue(name, value, language);
  });
}

/** Ответ целиком: шаги через пробел. Пусто — тишина. */
export function renderOperatorReply(steps: readonly OperatorStepOut[], language: OperatorLanguage): string {
  return steps.map(step => renderOperatorStep(step, language)).join(" ").trim();
}

/** Канал → значение переменной {where}. */
export function operatorWhereVar(channel: OperatorChannel): string { return channel === "WHATSAPP" ? "WHATSAPP" : "HERE"; }
