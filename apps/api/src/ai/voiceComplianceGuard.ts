import { maskPhones } from "@royal-home/shared";
import { callGemini } from "./geminiClient.js";

/**
 * Проверка голосового СОТРУДНИКА перед отправкой клиенту — тот же смысл, что у
 * маскировки телефонов в тексте (packages/shared/maskContacts.ts: «именно так
 * уходят клиенты — агент даёт свой номер, разговор переезжает в его WhatsApp, и
 * сделка проходит мимо агентства»), но текст можно замазать цифрами прямо в
 * строке, а голосовое — нет. Значит для голоса не «скрыть», а «не пропустить».
 *
 * ДВА РУБЕЖА, и оба обязательны — код, а не только промт («промт — просьба, а не
 * гарантия», см. ai/replyGuards.ts):
 *
 *  1) Детерминированный. Та же регулярка, что режет номера в тексте (maskPhones) —
 *     цифры не спрячешь фразировкой, поэтому это надёжный, но узкий рубеж: ловит
 *     только произнесённые ПОДРЯД цифры.
 *  2) Классификатор. Ловит то, что регулярка не видит: цифры по одной («восемь,
 *     ноль, ноль…»), приглашение писать в личный мессенджер без самого номера,
 *     «давайте договоримся без CRM» и подобное. Мягкий рубеж: при сбое модели НЕ
 *     блокируем — иначе агент теряет голосовые каждый раз, когда Gemini прилёг, а
 *     первый рубеж уже отработал.
 *
 * НА GEMINI, А НЕ НА CLAUDE (16.08.2026). До этой правки классификатор один во
 * всём проекте жёстко вызывал Anthropic (`callHaiku`), в обход переключателя
 * поставщика (`resolveTextProvider`) — владелец решил 02.08.2026 держать один
 * поставщик на всю CRM, но именно это место правило обошло. На проде это
 * вскрылось, когда у Anthropic кончился баланс: рубеж молча замолкал (мягкий
 * отказ и спас — голосовые уходили, просто без этой проверки), а Gemini в это
 * время работал как обычно. Раз второй поставщик всё равно не подключён нигде
 * больше, держать его здесь смысла не было — только лишняя точка отказа.
 */

export interface VoiceGuardResult {
  blocked: boolean;
  /** Короткая причина — уходит и агенту (почему не ушло), и в тревогу руководству. */
  reason?: string;
}

const CLASSIFIER_SYSTEM = `Ты проверяешь голосовое сообщение СОТРУДНИКА риелторского агентства клиенту —
уже расшифрованное в текст. Цель: поймать попытку увести сделку в обход CRM — сотрудник
получает комиссию только за сделки, оформленные через агентство, и заинтересован договориться
с клиентом напрямую, мимо системы.

Нарушение — если сотрудник:
 - называет номер телефона (свой личный или просит перезвонить на него), даже если произносит
   цифры по одной или словами («восемь, ноль, ноль, один…»);
 - предлагает писать/звонить в обход CRM: в личный WhatsApp/Telegram/Instagram, «спишемся
   отдельно», «давайте без агентства», «оформим сами»;
 - выманивает номер клиента для звонка НАПРЯМУЮ, в обход записи в CRM (не то же самое, что
   обычный рабочий вопрос «уточните, пожалуйста, номер для показа» — это штатная работа).

НЕ нарушение — рабочий разговор о квартире, цене, показе, документах, звонок ЧЕРЕЗ CRM.
При сомнении — не нарушение: агентов много, а ложная тревога уходит директору.

Ответь строго по схеме.`;

/**
 * `null` — классификатор недоступен (модель молчит/ошибка): для голоса это НЕ повод
 * блокировать, первый рубеж (телефон в цифрах) уже отработал раньше в вызывающем коде.
 */
async function classifyBypassAttempt(transcript: string): Promise<{ violation: boolean; reason: string } | null> {
  return callGemini<{ violation: boolean; reason: string }>({
    endpoint: "voice-compliance-guard",
    system: CLASSIFIER_SYSTEM,
    user: transcript.slice(0, 4000),
    maxTokens: 200,
    schema: {
      type: "object",
      properties: {
        violation: { type: "boolean" },
        reason: { type: "string", description: "Коротко, по-русски: что именно не так. Пусто, если нарушения нет." },
      },
      required: ["violation", "reason"],
    },
  });
}

export async function checkAgentVoiceMessage(transcript: string): Promise<VoiceGuardResult> {
  if (!transcript.trim()) return { blocked: false };

  // Рубеж 1: цифры подряд — тот же разбор, что режет номера в тексте.
  if (maskPhones(transcript).masked) {
    return { blocked: true, reason: "в голосовом произнесён номер телефона" };
  }

  // Рубеж 2: попытка обойти CRM без явных цифр подряд.
  const verdict = await classifyBypassAttempt(transcript);
  if (verdict?.violation) {
    return { blocked: true, reason: verdict.reason || "похоже на попытку договориться в обход CRM" };
  }

  return { blocked: false };
}
