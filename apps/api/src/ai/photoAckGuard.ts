/**
 * НА ОЧЕРЕДНУЮ ПАЧКУ ФОТО — НЕ БЛАГОДАРИТЬ ЗАНОВО (владелец 25.09.2026).
 *
 * Живой случай: продавец уже оставил номер и прислал 8 фото подряд. Бот ответил
 * на КАЖДОЕ («Раҳмат, аксҳоро гирифтем! Агенти мо…» восемь раз разными словами),
 * местами по два ответа на одно фото, — а потом щит исходящих остановил бота:
 * «написал 4 раза подряд, а человек не отвечал». Второй продавец так же получил
 * десяток «Раҳмат, аксро гирифтем. Хона чанд квадрат аст?».
 *
 * Главная причина — окно склейки (см. вызов debounceAndMerge в
 * messengers/conversation.ts): у принятой заявки оно было нулевым. Этот сторож —
 * второй слой: даже когда фото пришли двумя пачками с паузой больше окна, на
 * вторую пачку без единого слова бот молчит, если уже поблагодарил за фото
 * недавно. Фото при этом сохраняются в переписку как обычно — агент их видит.
 */

/** Сколько живёт «спасибо за фото»: дольше — это уже новый заход, ответить можно. */
export const PHOTO_ACK_WINDOW_MS = 15 * 60_000;

/** Реплика клиента — только фото, ни одного своего слова (склеенная пачка «[📷]\n[📷]…»). */
export function isPhotoOnlyTurn(merged: string | null | undefined): boolean {
  const lines = (merged ?? "")
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  return lines.length > 0 && lines.every((l) => l === "[📷]");
}

/**
 * Бот уже сказал «фото получили». Таджикский и русский, любые формы: «аксҳоро
 * гирифтем», «суратҳоро қабул кардем», «расмҳоро гирифтам», «фото получили».
 */
const PHOTO_ACK = new RegExp(
  "(?:акс|сурат|расм|фото|снимк)[\\p{L}]*[^.!?\\n]{0,40}(?:гирифт|қабул|кабул|омад|получил|получили|пришл)" +
    "|(?:получил|получили)[^.!?\\n]{0,20}(?:фото|снимк)",
  "iu"
);

export function isPhotoAck(botText: string | null | undefined): boolean {
  return PHOTO_ACK.test(botText ?? "");
}

/**
 * Молчать на эту пачку фото? Да, если в ней нет слов и последняя реплика бота —
 * недавнее «фото получили».
 */
export function photoAlreadyAcknowledged(
  merged: string | null | undefined,
  lastBot: { content?: string; at?: string } | null | undefined,
  now = Date.now()
): boolean {
  if (!isPhotoOnlyTurn(merged) || !lastBot || !isPhotoAck(lastBot.content)) return false;
  const at = lastBot.at ? Date.parse(lastBot.at) : NaN;
  // Без отметки времени (старые реплики) не молчим: не знаем, давно ли это было.
  return Number.isFinite(at) && now - at <= PHOTO_ACK_WINDOW_MS;
}
