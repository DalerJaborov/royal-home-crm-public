/**
 * Длина, после которой сообщение перестаёт быть репликой в переписке.
 *
 * Столько же, сколько у рассылок (lib/incomingSpam.ts): простыня в тысячу с
 * лишним знаков — это либо объявление, либо текст, который человек принёс нам
 * «обработать». Отсечка срабатывает, только если во всей простыне нет ни одного
 * слова ни про жильё, ни про работу у нас.
 */
const BLAST_LENGTH = 1200;

/**
 * О чём с нами вообще разговаривают: жильё или работа в агентстве.
 *
 * Нужно только длинной простыне: вакансии — законный повод написать длинно
 * (человек рассказывает о себе), и принять такое письмо за домашнее задание
 * значит потерять кандидата молча.
 */
