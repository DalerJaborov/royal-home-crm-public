import { BW, EW } from "./wordBoundary.js";

/**
 * КЛИЕНТ РАЗДРАЖЁН — СКАЗАТЬ МОДЕЛИ ДО ОТВЕТА (ревизия бота 02.10.2026, сравнение
 * с лучшими ассистентами: Intercom Fin и другие меняют тон и зовут человека по
 * признакам раздражения). До этой правки ловились только две частные жалобы
 * («мне не перезвонили», «файл не открылся»), а «вы меня не понимаете», «третий
 * раз пишу», капслок и «???» бот принимал за обычную реплику и отвечал бодрым
 * вопросом анкеты — ровно то, что выдаёт автомат.
 *
 * Словарь узкий нарочно: ложное срабатывание стоит дёшево (бот ответит чуть мягче
 * и короче), но «спасибо!!!» — не раздражение, поэтому восклицания не считаются,
 * а капслок — только длинный и без ссылок/кодов.
 */
const PHRASES = [
  // «не понимаю, какой район лучше» — растерянность, а не раздражение: только «вы не понимаете».
  `не\\s+понима(?:ете|ешь)`,
  `(?:третий|пятый|который|десятый)\\s+раз\\s+(?:пишу|спрашиваю|говорю|повторяю|объясняю)`,
  `сколько\\s+можно`,
  `бесполезн\\p{L}*`,
  `издева\\p{L}*`,
  `надоел\\p{L}*`,
  `достал\\p{L}*`,
  `(?:вы|ты)\\s+(?:что\\s+)?(?:тупо?й|тупые|глух\\p{L}*)`,
  `ответьте\\s+(?:уже|нормально|по\\s+делу)`,
  `я\\s+же\\s+(?:писал\\p{L}*|сказал\\p{L}*|спрашивал\\p{L}*)`,
  `намефаҳм\\p{L}*`,
  `нафаҳмидед`,
  `чанд\\s+бор\\s+(?:навис|навишт|гӯ|гу|пурс)\\p{L}*`,
  `безор\\s+шуд\\p{L}*`,
  `фоида\\s+надор\\p{L}*`,
  `ҷавоб\\s+диҳед\\s+дигар`,
];
const PHRASE_RX = new RegExp(`${BW}(?:${PHRASES.join("|")})${EW}`, "iu");
const MANY_QUESTION_MARKS = /\?{3,}/;

function shouting(text: string): boolean {
  const letters = text.replace(/https?:\/\/\S+/g, "").match(/\p{L}/gu) ?? [];
  if (letters.length < 12) return false;
  const upper = letters.filter((ch) => ch !== ch.toLowerCase()).length;
  return upper / letters.length > 0.8;
}

export function looksFrustrated(text: string | null | undefined): boolean {
  if (!text) return false;
  return PHRASE_RX.test(text) || MANY_QUESTION_MARKS.test(text) || shouting(text);
}

