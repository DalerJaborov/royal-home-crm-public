/**
 * «АГЕНТ НЕ ПОЗВОНИЛ» — ЭТО НЕ ПОВОД ДЛЯ ЕЩЁ ОДНОГО ИЗВИНЕНИЯ (разбор 30.08.2026).
 *
 * ЖИВОЙ СЛУЧАЙ. Клиент шесть раз подряд написал, что с ним никто не связался, и
 * шесть раз получил одну и ту же вежливую фразу «агент свяжется в ближайшее
 * время». Бот вёл себя ровно так, как ему велено после приёма заявки: коротко,
 * вежливо, ничего не обещая по существу. Беда в том, что вежливость здесь —
 * худший из возможных ответов: человеку нужен не текст, а звонок.
 *
 * РЕШЕНИЕ. Второе такое сообщение поднимает флаг руководителю (пуш + запись в
 * «Здоровье системы»), а не порождает новое извинение. Первое не поднимает
 * намеренно: агенту нужно дать нормальный срок, и дёргать руководство на каждое
 * «ну как там?» — верный способ приучить его не смотреть на уведомления.
 *
 * Модуль только распознаёт. Кого уведомлять и как — дело вызывающего.
 */

import { clientOwnWords } from "./untrustedContent.js";

const rx = (parts: string[]): RegExp => new RegExp(parts.join("|"), "iu");

/**
 * Жалуется и просит человека — САМ клиент. Пересланный документ, описание видео
 * или заметка агента лежат в той же реплике врезкой, и жалоба, найденная внутри
 * них, разбудила бы руководителя чужими словами (тот же класс, что находка 3.1
 * проверки 21.09.2026). Своё голосовое остаётся — см. clientOwnWords.
 */
function ownText(clientText: string): string {
  return clientOwnWords(clientText ?? "").trim();
}

/**
 * Жалоба на отсутствие связи. Слова подобраны так, чтобы не задеть обычное
 * «позвоните мне» (просьба, а не жалоба): нужен признак ОТРИЦАНИЯ или ожидания.
 */
const NO_CONTACT_COMPLAINT = rx([
  // Таджикский: «не позвонили», «никто не звонит», «сколько ждать»
  // ОТРИЦАНИЕ ОБЯЗАТЕЛЬНО (починено 20.09.2026). До этого группа «(на|не)?» была
  // необязательной, и УТВЕРДИТЕЛЬНОе «занг зада будед» («вы мне звонили») и «занг зада
  // метавонед?» («можете позвонить?») считались жалобой «мне не позвонили» — второе такое
  // сообщение будило руководителя пушем на ровном месте. В таджикском отрицание — приставка
  // к глаголу («назад», «намезананд», «назаданд»), иногда пишут раздельно — отсюда `\\s*`.
  "занг\\s*(?:на|не)\\s*(?:зад|мезан|зан)",
  "занг\\s+нест",
  "ҳеҷ кас\\s+занг|хеч кас\\s+занг",
  "касе тамос нагирифт|тамос нагирифтанд|тамос нагирифт",
  "чанд р[ӯу]з\\s+интизор|интизорам|мунтазирам",
  // Русский
  "никто (не )?(по)?звонил|не позвонили|так и не позвонил|не перезвонил",
  "не связал(ись|ся)|никто не связался|нет связи с агентом",
  "жду (звонка|уже)|сколько (мне )?ждать|когда позвонят|обещали позвонить",
  "агент не (звонит|позвонил|связал)",
]);

/**
 * Похоже ли сообщение на жалобу «со мной никто не связался».
 *
 * @param clientText одна реплика клиента.
 */
export function looksLikeNoContactComplaint(clientText: string): boolean {
  const text = ownText(clientText);
  if (!text) return false;
  return NO_CONTACT_COMPLAINT.test(text);
}

/**
 * Сколько раз клиент уже жаловался в этом разговоре — по его собственным репликам.
 */
export function countNoContactComplaints(clientMessages: string[]): number {
  return clientMessages.filter(looksLikeNoContactComplaint).length;
}

/**
 * КЛИЕНТ ПРЯМО ПРОСИТ ЖИВОГО ЧЕЛОВЕКА/АГЕНТА (владелец 18.09.2026).
 *
 * Отдельный сигнал от «жалобы на отсутствие связи» выше: там человек уже ждал
 * и недоволен, здесь — просто хочет поговорить с агентом прямо сейчас, часто
 * вежливо и без единой жалобы («можно с менеджером поговорить?»). Важен он
 * сильнее всего для клиента, которого агент реально забросил (LOST/ARCHIVED/
 * workStatus=INACTIVE, но карточка за ним всё ещё числится) — бот продолжает
 * вести разговор и знает всю историю, но такую просьбу нужно вынести из
 * общего потока сообщений отдельным пушем агенту, а не полагаться, что он
 * заметит её сам (см. `Client.agentAttentionRequestedAt`, prisma/schema.prisma).
 *
 * Обычную вежливую просьбу «позвоните мне» сюда не относим намеренно — это
 * просьба о звонке (её код и так слышит через сам факт заявки), а не просьба
 * СЕЙЧАС переключить на человека.
 */
const WANTS_HUMAN_AGENT = rx([
  // Русский
  "соедините (меня )?с (агентом|оператором|менеджером|человеком)",
  "переключите (меня )?на (агента|оператора|менеджера|человека)",
  "(хочу|можно|нужно) (ли )?поговорить с (агентом|человеком|менеджером|оператором)",
  "дайте (мне )?(живого )?(агента|человека|оператора)",
  "нужен (живой )?человек|нужен агент|позовите агента",
  "с (живым )?человеком (хочу )?(поговорить|пообщаться|связаться)",
  // Таджикский: «бо одам/агент гап занам», «маро бо агент пайваст кунед»
  "бо (одам|агент)[^.!?]{0,20}(гап зан|сӯҳбат|алоқа)",
  "маро бо агент[^.!?]{0,20}(пайваст|васл) кунед",
  "агентатонро[^.!?]{0,20}(диҳед|занг занонед)",
]);

/** Похоже ли сообщение на прямую просьбу переключить на живого агента/человека. */
export function looksLikeWantsHumanAgent(clientText: string): boolean {
  const text = ownText(clientText);
  if (!text) return false;
  return WANTS_HUMAN_AGENT.test(text);
}
