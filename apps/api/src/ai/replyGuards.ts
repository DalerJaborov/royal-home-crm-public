const EMOJI =
  /[\u{1F300}-\u{1FAFF}\u{1F000}-\u{1F2FF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE0F}\u{200D}\u{20E3}]/gu;

/**
 * Смайлики, которые значат не приветливость, а грубость. Разрешение 22.08.2026 их
 * не касается: «безобидные» — это про 🙂 и ❤️, а не про 🖕 и 🤬.
 *
 * Своя копия, а не импорт из messengers/comments.ts, — по той же причине, что и в
 * lib/leadMagnet.ts: comments.ts импортирует этот самый файл, и обратный импорт
 * замкнул бы модули в цикл, на котором падает сборка. Список держать одинаковым.
 */
/**
 * ПЕРЕЧИСЛЕНИЕМ, А НЕ КВАДРАТНЫМИ СКОБКАМИ (найдено тестом 22.08.2026).
 *
 * `☠️` — это ДВА символа: сам знак и модификатор начертания U+FE0F. Внутри
 * квадратных скобок модификатор становился ОТДЕЛЬНЫМ членом списка, то есть
 * «грубым» считался он сам по себе — а он стоит в конце почти каждого цветного
 * смайлика. Из-за этого `❤️` превращалось в `❤` (чёрно-белый значок вместо
 * сердца), и так у любого смайлика с модификатором. Перечисление через `|`
 * сравнивает последовательности целиком и такой ошибки не допускает.
 */
const RUDE_EMOJI = /🖕|💩|🤮|🤢|🤡|👿|😡|🤬|💀|☠️/gu;

/**
 * Смайлик из скобок: «дар кадомаш сухан меравад)», «хуб :)», «спасибо))».
 *
 * Запрет на смайлики модель поняла как запрет на КАРТИНКИ и тут же начала
 * ставить скобки — 01.08.2026 они появились в тот же день, когда убрали эмодзи.
 * Для читателя разницы нет никакой.
 *
 * Режем ТОЛЬКО в конце строки и ТОЛЬКО когда открывающей скобки в ней не было:
 * «(см. фото)» и «3-хонагӣ (95 м²)» — обычный текст, и трогать его нельзя.
 */
const TEXT_SMILEY = /[\s]*[:;=]?-?\)+\s*$/;

/**
 * Слова из программы, попавшие в речь: «дар база», «в базе», «в системе».
 *
 * Запрет стоял в промте с 01.08.2026 и не сработал дважды: «дар система ин
 * видеоро надорам», «Дар база вариантҳо дорем». Причина была рядом — прямо возле
 * списка объектов модель читала заголовок «ИЗ НАШЕЙ БАЗЫ» и повторяла за нами.
 * Заголовок переписан, но одного этого мало: слово всплывает и само по себе.
 *
 * Вырезается ПРЕДЛОГ С СУЩЕСТВИТЕЛЬНЫМ целиком, а не заменяется синонимом:
 * «Дар база вариантҳо дорем» → «Вариантҳо дорем», «В базе есть» → «Есть».
 * Фраза остаётся живой и не меняет смысла, а подстановка «у нас» вместо «в базе»
 * иногда давала бы «у нас у нас».
 */
// «в системе рассрочки», «в системе ипотеки» (02.10.2026) — это про деньги, а не
// про программу; без исключения клиенту уходило «Работаем рассрочки банка».
const MACHINE_PLACE =
  /(^|\s)(дар\s+(база|базаи мо|системаи мо|система|каталог)|в\s+(нашей\s+)?(базе|системе(?!\s+(?:рассрочк|ипотек|оплат|отоплен|водоснабж|безопасност|видеонаблюд|скид|бонус|лояльн))|каталоге)|по\s+базе|дар\s+базамон)([\s,]+|$)/giu;

function stripMachineWords(text: string): string {
  return text.replace(MACHINE_PLACE, (_m, left: string) => left || "");
}

/**
 * «У МЕНЯ СИСТЕМНЫЙ СБОЙ» — ПРИЗНАНИЕ, ЧТО КЛИЕНТ ПЕРЕПИСЫВАЕТСЯ С ПРОГРАММОЙ.
 *
 * Разбор переписки 14.08.2026 (WhatsApp): на вопросы про месяц и повторяющуюся фразу
 * бот отвечал «Узр, система хато кард», «с датой у меня просто системный сбой»,
 * «Парво накунед, ин як хатои техникӣ буд», «система хато карда истодааст». Запрет
 * называть себя ботом стоит в промте с 31.07 и здесь обходится с фланга: слова «бот»
 * нет, а смысл ровно тот же, да ещё и с извинением за неисправность.
 *
 * Режем ПРЕДЛОЖЕНИЕ ЦЕЛИКОМ, а не слово: «Узр, система хато кард» без «система» даёт
 * «Узр, хато кард» — фразу без подлежащего, которая читается ещё хуже. Остальные
 * предложения ответа остаются, и обычно среди них есть содержательное; если не
 * осталось ничего, вызывающий выбросит пустую реплику (см. cleanOutgoingReply).
 *
 * Ловим только связку «система/техника» + «ошибка/сбой»: отдельное слово «система»
 * уже вырезает MACHINE_PLACE, а «хато кардам» («я ошибся») — правильное человеческое
 * извинение, и трогать его нельзя.
 */
/**
 * Границы слова здесь свои, а не `\b`: в JS `\b` считает словом только ASCII, и
 * между пробелом и «с» в «система» границы для него нет вовсе — regexp с `\b`
 * не совпал бы ни с одной таджикской фразой (поймано тестом сразу же).
 */
const NOT_LETTER_LEFT = "(?<!\\p{L})";
const NOT_LETTER_RIGHT = "(?!\\p{L})";
// «Технический паспорт», «технический осмотр», «ҳуҷҷатҳои техникӣ» — документы
// объекта, а не поломка программы (02.10.2026): «Технический паспорт в порядке,
// ошибок нет» вырезалось целиком как признание сбоя.
const TECH = `${NOT_LETTER_LEFT}(?<!ҳуҷҷат\\p{L}*\\s+|хуҷҷат\\p{L}*\\s+)(систем\\p{L}*|system\\p{L}*|техник\\p{L}*|техническ\\p{L}*)${NOT_LETTER_RIGHT}(?!\\s+(?:паспорт|осмотр|характеристик|состояни|план|услови|этаж|помещени))`;
const BREAKAGE = `${NOT_LETTER_LEFT}(хато\\p{L}*|сбо[йя]\\p{L}*|носоз\\p{L}*|ошиб\\p{L}*|глюк\\p{L}*)${NOT_LETTER_RIGHT}`;
const SENTENCE_REST = "[^.!?\\n]*[.!?]*";
const SENTENCE_HEAD = "[^.!?\\n]*";

const SYSTEM_EXCUSE_SENTENCE = new RegExp(
  `${SENTENCE_HEAD}${TECH}[^.!?\\n]*${BREAKAGE}${SENTENCE_REST}`,
  "giu"
);

/** Та же связка в обратном порядке слов: «хатои техникӣ», «ошибка системы». */
const SYSTEM_EXCUSE_REVERSED = new RegExp(
  `${SENTENCE_HEAD}${BREAKAGE}[^.!?\\n]*${TECH}${SENTENCE_REST}`,
  "giu"
);

/** «ошибок нет», «без ошибок», «бе хато» — отрицание поломки, а не признание её. */
const NEGATED_BREAKAGE = /(?<!\p{L})(нет|без|бе|не\s+было|нест|надорад)(?!\p{L})/iu;

function dropExcuse(sentence: string): string {
  return NEGATED_BREAKAGE.test(sentence) ? sentence : "";
}

export function stripSystemExcuses(text: string): string {
  return text
    .replace(SYSTEM_EXCUSE_SENTENCE, dropExcuse)
    .replace(SYSTEM_EXCUSE_REVERSED, dropExcuse)
    .replace(/[ \t]{2,}/g, " ")
    .trim();
}

/**
 * ЧУЖИЕ ЯЗЫКИ В ТАДЖИКСКОМ ОТВЕТЕ (владелец 16.08.2026: «никаких узбекских слов,
 * „кизик“ и так далее, это бред»).
 *
 * Модель, которую просят писать по-таджикски, подмешивает соседние языки: узбекские
 * слова (их много в северном Таджикистане, и в обучающих текстах они рядом) и
 * персидские написания арабицей. Для клиента из Душанбе это звучит не «по-местному»,
 * а как машинный перевод — то есть ровно наоборот тому, ради чего писан весь стиль.
 *
 * Здесь ТОЛЬКО слова, которых в таджикском нет вовсе и которые нельзя спутать с
 * таджикскими: «яхши» (тадж. «хуб»), «керак» (тадж. «даркор»), «нима» (тадж. «чӣ»),
 * «қандай» (тадж. «чӣ хел»), «йўқ» (тадж. «не»), «қизиқ», «хўп», «борми», «бўлади».
 * Слова, общие у языков («майлӣ», «раҳмат», «ака»), сюда не входят намеренно:
 * фильтр, режущий правильную речь, хуже отсутствующего.
 *
 * Заменяем не на синоним, а вырезаем: подстановка перевода в чужую грамматику даёт
 * фразу хуже исходной. Ответ, потерявший слово, всё равно читается; ответ на
 * ломаном узбекском — нет.
 */
const FOREIGN_WORDS = new RegExp(
  `${LEFT}(қизиқ|кизик|яхши|керак|нима|қандай|кандай|йўқ|йук|хўп|хуп|борми|бўлади|булади|опа|синглим|укам)${RIGHT}`,
  "giu"
);

/**
 * ЧУЖОЙ ТЕЛЕФОН В ИСХОДЯЩЕМ (владелец 16.08.2026: «защиту установи, чтобы всякие
 * личные данные не давал»).
 *
 * Боту видны рабочие данные, среди которых телефон собственника — самая ценная и
 * самая чужая часть базы (см. lib/ownerContact.ts: она отдаётся не каждому даже
 * внутри компании). Запрет стоит в правилах промта, но запрет «никогда» на промте
 * не держится — об этом весь этот файл. Поэтому номер вырезается механически.
 *
 * Разрешены РОВНО ДВА случая: рабочий номер компании (его бот вправе назвать, когда
 * человек спросил, как с нами связаться) и номер, который клиент назвал сам, — его
 * повтор для подтверждения («Рақами шумо 900 123 456, дуруст?») это нормальная
 * работа оператора, и вырезать его нельзя. Всё остальное, похожее на телефон,
 * выкусывается: взяться ему в ответе неоткуда, кроме выдумки модели.
 *
 * ГЛАВНАЯ ЗАЩИТА ВСЁ РАВНО НЕ ЗДЕСЬ, а в том, что контакт собственника
 * (`Property.ownerContact`) не попадает в промт ни одним путём: ни подборка объектов,
 * ни география, ни узнавание пересланного поста его не выбирают. Данные, которых
 * модели не дали, она не разгласит. Этот фильтр — второй рубеж, на случай выдумки.
 *
 * Сравниваем по ПОСЛЕДНИМ 9 цифрам очищенного номера — тот же приём, что в
 * lib/whatsappPhone.ts: «+992 44 650 14 14», «992446501414» и «446501414» это один
 * и тот же телефон, и сравнение строк тут не работает.
 */
// Разделители — только пробел, таб, дефис и скобки, без перевода строки
// (02.10.2026): с `\s` «Цена 1 250 000\n120 м²» склеивалась через строку в
// «телефон» и уходила клиенту как «Цена м²».
const PHONE_LIKE = /\+?\d[\d \t\-()]{7,}\d/g;
/**
 * Номер, записанный через точки или косые: «938.887.766», «93/888/77/66»
 * (02.10.2026). Общий шаблон их не видел, и телефон собственника уходил
 * клиенту. Отдельный шаблон, а не точка в общем классе: с точкой в классе
 * «…120 000. 935 55 12 34» склеивалось в одно совпадение длиннее 13 цифр,
 * которое фильтр пропускает целиком, — то есть стало бы только хуже.
 */
const PHONE_DOTTED = /\+?\d{2,3}(?:[./]\d{2,4}){2,4}/g;
/** Ниже девяти цифр — это не телефон, а цена или площадь: «1 460 000» тоже подходит
 *  под шаблон, и без этого порога фильтр вырезал бы стоимость квартиры. */
const PHONE_MIN_DIGITS = 9;

function digitsOnly(value: string): string {
  return value.replace(/\D/g, "");
}

/** Телефон длиннее 13 цифр не бывает (E.164 — 15 максимум, у нас с кодом — 12):
 *  больше — это склеенные числа (диапазон цен, перечисление площадей), не номер. */
const PHONE_MAX_DIGITS = 13;

/** «320 000 - 350 000»: дефис делит совпадение на ДВА числа по ≥5 цифр — это вилка
 *  цены, не телефон (в номерах дефис делит группы по 2-3 цифры). До 26.08.2026
 *  фильтр вырезал такую вилку из ответа клиенту — бот называл бюджет пустотой. */
function looksLikeNumberRange(match: string): boolean {
  const parts = match.split(/[-–—]/);
  if (parts.length !== 2) return false;
  return parts.every((p) => digitsOnly(p).length >= 5);
}

/**
 * «85 000 (926 500 сомони)», «650 000 (59 600 $)» — цена и её пересчёт в скобках
 * (02.10.2026). Промт сам велит называть цену в обеих валютах, и это самая
 * естественная запись, а шаблон склеивал два числа через скобку в 11 цифр и
 * вырезал обе цены: клиенту уходило «Цена сомони)». У телефона в скобках только
 * код («(93) 555-12-34»), поэтому два куска по пять и больше цифр по разные
 * стороны скобки — это два числа, а не номер.
 */
function looksLikeBracketedPair(match: string): boolean {
  if (!/[()]/.test(match)) return false;
  return match.split(/[()]/).filter((p) => digitsOnly(p).length >= 5).length >= 2;
}

/**
 * Номер банковской карты (02.10.2026): 16 цифр длиннее любого телефона, и фильтр
 * их пропускал как «склеенные числа». Боту взять номер карты неоткуда, кроме
 * выдумки или чужого файла, а «отправьте на карту …» — ровно то, чем пользуются
 * мошенники. Вырезается всегда.
 */
const CARD_NUMBER = /(?<!\d)\d{4}(?:[ \t-]?\d{4}){3}(?:[ \t-]?\d{1,3})?(?!\d)/g;

function stripForeignPhones(text: string, clientText: string): string {
  const allowed = digitsOnly(clientText);
  return text.replace(CARD_NUMBER, (match) => {
    void logSystemError("ai", `Бот собрался отправить клиенту номер карты — вырезан: «${match}»`);
    return "";
  }).replace(PHONE_LIKE, (match) => {
    const digits = digitsOnly(match);
    if (digits.length < PHONE_MIN_DIGITS || digits.length > PHONE_MAX_DIGITS) return match;
    if (looksLikeNumberRange(match) || looksLikeBracketedPair(match)) return match;
    return isAllowedPhoneDigits(digits, allowed) ? match : "";
  }).replace(PHONE_DOTTED, (match) => {
    const digits = digitsOnly(match);
    if (digits.length < PHONE_MIN_DIGITS || digits.length > PHONE_MAX_DIGITS) return match;
    return isAllowedPhoneDigits(digits, allowed) ? match : "";
  });
}

/** Номер компании или номер самого клиента — их называть можно. Номер клиента
 *  ищем по последним 9 цифрам в слитной записи его же реплик: он мог написать
 *  «900-12-34-56», а бот повторить «900 123 456». */
function isAllowedPhoneDigits(digits: string, allowedDigits: string): boolean {
  if (isRetiredPublicAgencyPhone(digits)) return false;
  if (isPublicAgencyPhone(digits)) return true;
  return allowedDigits.includes(digits.slice(-PHONE_MIN_DIGITS));
}

/**
 * Ссылки-звонилки «viber://chat?number=%2B992…», «tel:+992…», «sms:…» (02.10.2026).
 * Под LINK_LIKE они не подходят (нет http и домена), и телефонный фильтр
 * выкусывал из них одни цифры: клиенту уходил обрубок «…number=%2B». Такая
 * ссылка целиком и есть телефон, поэтому проверяется как телефон и уходит
 * целиком или не уходит вовсе.
 */
const DIAL_LINK = /(?:viber|tel|sms|whatsapp|skype):(?:\/\/)?[^\s<>"'«»)\]]+/gi;

function stripForeignDialLinks(text: string, clientText: string): string {
  const allowed = digitsOnly(clientText);
  return text.replace(DIAL_LINK, (match) => {
    const digits = digitsOnly(decodeURIComponentSafe(match));
    const publicTelephoneOnly = !isPublicAgencyPhone(digits) || /^tel:/i.test(match);
    if (publicTelephoneOnly && digits.length >= PHONE_MIN_DIGITS && isAllowedPhoneDigits(digits, allowed)) return match;
    void logSystemError("ai", `Бот собрался отправить клиенту ссылку-звонилку — вырезана: «${match.slice(0, 200)}»`);
    return "";
  });
}

function decodeURIComponentSafe(value: string): string {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}

/**
 * ЧУЖАЯ ССЫЛКА В ИСХОДЯЩЕМ (найдено аудитом 22.08.2026).
 *
 * До этой правки ссылки не проверялись кодом ВООБЩЕ: ограничения жили только в
 * промте (BOT_CORE_RULES, LINKS_DISABLED_RULE в messengers/botCapabilities.ts), а
 * промт — просьба, а не гарантия; об этом весь этот файл. Модель, у которой в
 * контексте лежит содержимое присланного клиентом PDF или описание чужого поста,
 * охотно повторяет найденный там адрес — и клиент получает от «консультанта Royal
 * Home» ссылку на чужое объявление, чужой канал или прямо на фишинг из файла.
 *
 * ЗАПРЕТ ССЫЛОК ЦЕЛИКОМ ЗДЕСЬ БЫЛ БЫ ОШИБКОЙ. Бот законно даёт ссылку на объект
 * (leadQualifier.propertyLink → royalhome.tj или пост Instagram), а `t.me`
 * запрещать НЕЛЬЗЯ — это рабочий канал компании (половина карточек ссылается
 * туда). Поэтому фильтр не про ссылки, а про ЧУЖИЕ ссылки: свои домены и
 * мессенджеры остаются, незнакомый внешний адрес вырезается — ровно так же, как
 * уже вырезается чужой телефон.
 *
 * ⚠️ ПРОВЕРИТЬ С ВЛАДЕЛЬЦЕМ. Единого списка доменов компании в коде нет: он
 * собран чтением по репозиторию (royalhome.tj из lib/siteListingUrl.ts и
 * botCapabilities.LINKS_DISABLED_RULE, instagram.com из lib/instagramLink.ts,
 * t.me из Property.instagramUrl и telegram/bot.ts, wa.me/whatsapp — только допустимые
 * контакты клиента (публичный телефон агентства не WhatsApp), facebook — страница компании). Если у
 * агентства есть ещё домены (лендинги, короткие ссылки, карты) — дописать сюда,
 * иначе бот перестанет их отправлять молча.
 */
const ALLOWED_LINK_HOSTS = [
  "royalhome.tj",
  "instagram.com",
  "instagr.am",
  "facebook.com",
  "fb.me",
  "fb.com",
  "t.me",
  "telegram.me",
  "telegram.org",
  "wa.me",
  "whatsapp.com",
  // Геометка объекта: этот адрес собирает и отправляет КОД (messengers/
  // propertyShowcase.ts), но он остаётся в переписке, и модель законно повторяет
  // его следующим ходом («вот карта, которую я присылал»). Разрешён ровно
  // maps.google.com, а не google.com целиком: поиск и почта Google нам чужие.
  "maps.google.com",
];

/**
 * Адрес сайта берётся ещё и из настроек окружения (SITE_PUBLIC_URL): на проде он
 * может отличаться от значения по умолчанию, и тогда бот вырезал бы собственную
 * ссылку на объект. Читаем при каждом вызове, а не один раз при загрузке модуля:
 * тесты подменяют переменные окружения через stubEnv уже после импорта.
 */
function siteHostFromEnv(): string | null {
  const raw = process.env.SITE_PUBLIC_URL?.trim();
  if (!raw) return null;
  try {
    return new URL(raw.includes("://") ? raw : `https://${raw}`).hostname.replace(/^www\./i, "").toLowerCase();
  } catch {
    return null;
  }
}

/**
 * Что считается ссылкой. Два вида: с протоколом («https://…», «www.…») и голый
 * домен, как их и пишут в мессенджере («royalhome.tj/listing/12»).
 *
 * Список доменов верхнего уровня ЗАКРЫТЫЙ, и это не педантизм: без него «и.т.д»,
 * сокращения и обрывки фраз с точкой опознавались бы как адреса, и фильтр резал
 * бы обычный текст. Кириллица в шаблон не входит вовсе — таджикское слово с
 * точкой ссылкой не станет.
 */
const LINK_TLD = "tj|com|net|org|ru|uz|kz|kg|me|io|info|biz|app|dev|xyz|online|site|shop|store|link|club|top|pro";
const LINK_LIKE = new RegExp(
  `(?:https?:\\/\\/|www\\.)[^\\s<>"'«»)\\]]+|(?<![\\w@.])[a-z0-9-]+(?:\\.[a-z0-9-]+)*\\.(?:${LINK_TLD})(?![a-z])(?:\\/[^\\s<>"'«»)\\]]*)?`,
  "gi"
);

/** Домен из найденного адреса: без протокола, без «www.», без пути и параметров. */
function linkHost(match: string): string {
  return match
    .replace(/^https?:\/\//i, "")
    .replace(/^www\./i, "")
    .split(/[/?#]/)[0]
    .toLowerCase();
}

function isAllowedLinkHost(host: string): boolean {
  const site = siteHostFromEnv();
  const allowed = site ? [...ALLOWED_LINK_HOSTS, site] : ALLOWED_LINK_HOSTS;
  // Поддомены своих доменов тоже свои: «www.royalhome.tj», «m.facebook.com».
  return allowed.some((a) => host === a || host.endsWith(`.${a}`));
}

/**
 * Вырезает чужие ссылки. Свои остаются как есть — вместе с путём и параметрами:
 * ссылка на объект без хвоста ведёт не туда, а это хуже отсутствия ссылки.
 *
 * Вырезается АДРЕС, а не предложение целиком: фраза «вот эта квартира» без
 * ссылки остаётся осмысленной, а обрубок предложения — нет.
 */
function stripForeignLinksInner(text: string): string {
  const marked = text.replace(LINK_LIKE, (match) => {
    if (isAllowedLinkHost(linkHost(match))) return match;
    void logSystemError(
      "ai",
      `Бот собрался отправить клиенту чужую ссылку — вырезана: «${match.slice(0, 200)}»`
    );
    return CUT_LINK;
  });
  // Предлог или двоеточие перед вырезанным адресом уходят вместе с ним
  // (02.10.2026): «есть на somon.tj, но…» раньше давало «есть на, но…».
  return marked.replace(DANGLING_BEFORE_CUT, "").split(CUT_LINK).join("");
}

const CUT_LINK = "\u0002";
const DANGLING_BEFORE_CUT = /(?:[ \t]+(?:на|в|во|по|через|из|аз|дар|ба)|[ \t]*:)[ \t]*(?=\u0002)/giu;

/** Хосты, у которых сам адрес — чей-то телефон: адрес вида «wa.me/992…». */
// t.me/+992… — тоже телефон в адресе (02.10.2026): t.me разрешён целиком как
// рабочий канал компании, и номер собственника уходил клиенту рабочей ссылкой.
const PHONE_IN_PATH_HOSTS = ["wa.me", "whatsapp.com", "t.me", "telegram.me"];

/**
 * ССЫЛКА АГЕНТСТВА БОЛЬШЕ НЕ ОБКУСЫВАЕТСЯ ТЕЛЕФОННЫМ ФИЛЬТРОМ (20.09.2026).
 *
 * Ссылка на объект собирается как
 * `royalhome.tj/listing/by-crm/<id объекта>` (lib/siteListingUrl.ts), а id — это UUID.
 * В нём регулярно попадаются цифры через дефис — то есть ровно то, что PHONE_LIKE
 * считает телефоном: в `…/by-crm/66f40c0e-8959-40a6-bb8b-761427759093` хвост
 * `761427759093` — двенадцать цифр, и фильтр вырезал его из ссылки. Клиенту
 * уходил обрубок `…/by-crm/66f40c0e-8959-40a6-bb8b-`, который ведёт в никуда.
 * Замер на случайных UUID: ломалось каждая седьмая ссылка (~14 %), причём
 * молча: в журнал телефонный фильтр ничего не пишет, а бот считал себя
 * отправившим ссылку и второй раз её не давал.
 *
 * Порядок теперь такой: чужой адрес вырезается целиком (как и раньше — иначе
 * телефонный фильтр оставил бы от него читаемый огрызок), а СВОЙ подменяется
 * меткой на время поиска телефонов и возвращается нетронутым. Метка под PHONE_LIKE
 * не подходит сама: в ней одна-две цифры, а шаблон требует девять.
 *
 * ДЫРУ ЗАКРЫВАЕМ ТУТ ЖЕ. Раньше чужой номер в своём же адресе
 * (`wa.me/<номер конкурента>`) обезвреживался ПОБОЧНО — тем самым
 * обкусыванием цифр. Спрячет ссылку целиком — и контакт конкурента ушёл бы
 * клиенту рабочей ссылкой. Поэтому у адресов, где путь И ЕСТЬ телефон, номер
 * проверяется тем же правилом, что и в тексте (номер компании или номер самого
 * клиента — можно, любой другой — ссылка уходит целиком, с записью в журнал).
 */
function stripLinksAndForeignPhones(text: string, clientText: string): string {
  const allowedDigits = digitsOnly(clientText);
  const kept: string[] = [];
  const masked = stripForeignLinksInner(stripForeignDialLinks(text, clientText)).replace(LINK_LIKE, (match) => {
    const host = linkHost(match);
    if (PHONE_IN_PATH_HOSTS.some((h) => host === h || host.endsWith(`.${h}`))) {
      const digits = digitsOnly(match.slice(host.length));
      // The agency contact is telephone-only, even when the customer quotes it.
      const foreign = digits.length >= PHONE_MIN_DIGITS &&
        (isPublicAgencyPhone(digits) || !isAllowedPhoneDigits(digits, allowedDigits));
      if (foreign) {
        void logSystemError(
          "ai",
          `Бот собрался отправить клиенту чужой номер ссылкой — вырезана: «${match.slice(0, 200)}»`
        );
        return "";
      }
    }
    kept.push(match);
    return `\u0001L${kept.length - 1}\u0001`;
  });
  return stripForeignPhones(masked, clientText).replace(
    /\u0001L(\d+)\u0001/g,
    (whole, index: string) => kept[Number(index)] ?? whole
  );
}

/** Персидская и арабская графика: в переписке душанбинца её не бывает никогда. */
const ARABIC_SCRIPT = /[؀-ۿݐ-ݿ]+/g;

function stripForeignWords(text: string): string {
  // Проход повторяется, пока текст меняется: у соседних слов общий пробел, и за
  // один проход regexp съедает его вместе с первым словом — второе остаётся
  // («Сизга керак нима?» → «Сизга нима?»). Потолок в 4 прохода: чужих слов подряд
  // больше не бывает, а бесконечный цикл на странном вводе недопустим.
  let out = text.replace(ARABIC_SCRIPT, "");
  for (let pass = 0; pass < 4; pass += 1) {
    const next = out.replace(FOREIGN_WORDS, (_m, left: string, _word: string, right: string) => `${left}${right}`);
    if (next === out) break;
    out = next;
  }
  return out;
}

/**
 * Приветствие в середине разговора.
 *
 * Короткие реплики бота (напоминание молчащему, подтверждение заявки, просьба
 * подтвердить встречу) — это ВСЕГДА продолжение переписки, которая уже идёт.
 * Запрет здороваться заново стоит в промте с 31.07 и всё равно не держится:
 * 01.08 напоминание клиенту, разговор с которым шёл вторые сутки, началось с
 * «Ассалому алейкум!». Для человека это значит одно — с ним говорят как с
 * незнакомым, и всё сказанное раньше не в счёт.
 *
 * Режем ТОЛЬКО в начале и ТОЛЬКО у коротких реплик (см. stripGreeting в
 * shortAgentReply): первое сообщение диалога здоровается по праву, и трогать его
 * нельзя.
 */
// «салом(?!ат)» — не опечатка: «саломат бошед» это «будьте здоровы», прощание и
// пожелание, а вовсе не приветствие. Срезав у него первое слово, мы получили бы
// бессмысленное «Бошед!». Поймано собственным тестом.
//
// «(\s+(алейкум|алайкум|валейкум))?» добавлено 16.08.2026 и лечит ту же болезнь с
// другого конца. Обработана была только слитная форма «ассалом+У алейкум», а формы
// «Салом алейкум» и «Ассалом алейкум» (в Душанбе пишут и так, и так) под альтернативу
// не подходили целиком: срабатывало короткое «салом», и клиент получал сообщение,
// начинающееся со слова «алейкум». Второе слово приветствия обязано уходить вместе
// с первым.
//
// Правая граница слова «(?![\p{L}\p{N}])» (02.10.2026): без неё «Приветствую!»
// уходило клиенту как «Ствую!», а «Приветик» как «Ик!». Туда же «Доброе утро» и
// «Рӯзатон ба хайр» — шаблон приветствия из самого промта, который не срезался.
const LEADING_GREETING =
  /^(ассалому\s+алейкум|ассалом(?!ат)у?|салом(?!ат)|салам|ваалейкум\s+ассалом|здравствуйте|здравствуй|добрый\s+(день|вечер|утро)|доброе\s+утро|рӯзатон\s+ба\s+хайр|рузатон\s+ба\s+хайр|привет)(\s+(алейкум|алайкум|валейкум))?(?![\p{L}\p{N}])[!,.\s]*/iu;

/** Убирает приветствие из начала короткой реплики. Пустой результат — вызывающий
 *  обязан выбросить такую реплику: сообщение из одного «салом» бессмысленно. */
export function stripRepeatGreeting(text: string): string {
  const out = text.replace(LEADING_GREETING, "").trim();
  if (!out) return "";
  if (out === text) return out;
  // Счётчик (совет экспертов, п. 8): сколько раз промт не удержал правило и его
  // пришлось чинить кодом — прямая мера расхождения промта с поведением.
  guardFired("repeat_greeting");
  return out[0].toUpperCase() + out.slice(1);
}

/**
 * Отчёт о приёме данных в начале реплики: «Фаҳмо, дар Сино», «Хуб, 3-хонагӣ будааст».
 *
 * Владелец 02.08.2026: «не надо писать типа 2 квартира 129 квадрат дар Мехргон.
 * Фахмо. И далее следующий вопрос. Этот бред не нужен никому. Только по существу».
 *
 * Запрет стоял в промте с 01.08 и не держался по своей же вине: он запрещал
 * подтверждение ОТДЕЛЬНЫМ сообщением и прямо разрешал «хуб» в начале содержательной
 * фразы. Модель исполняла букву правила и начинала с «Фаҳмо,» каждый второй ответ.
 * Правило переписано, но одного промта здесь мало — слово короткое и лезет само.
 *
 * Режем ТОЛЬКО когда за словом идёт знак препинания: это и есть признак отдельной
 * вводной части. Без него слово живёт в обычной фразе и трогать его нельзя —
 * «Хуб мешавад» («будет хорошо»), «Фаҳмо шуд» — нормальная речь, а не отчёт.
 * Повтор параметров клиента («129 квадрат дар Меҳргон») здесь НЕ вычёркивается:
 * отличить отчёт от осмысленного упоминания («дар Меҳргон ҳозир надорем») можно
 * только по смыслу, и слепая правка испортила бы вторую фразу. Это остаётся на промте.
 */
// «(?!\s*(что|чтобы|ки)…)» (02.10.2026): «Хорошо, что вы написали!», «Хуб, ки
// навиштед!» — это не отчёт о приёме, а начало сложной фразы, и без своей
// первой половины она уходила клиенту как «Что вы написали!».
const LEADING_ACK =
  /^(фаҳмо|фахмо|фаҳмидам|фахмидам|аниқ\s+шуд|аник\s+шуд|хуб|хубааст|хуб\s+аст|понял|поняла|понятно|ясно|хорошо|ладно|ок|окей)[\s]*[,.!;:—–-]+(?!\s*(?:что|чтобы|ки|то)(?![\p{L}]))[\s]*/iu;

/** Убирает отчёт о приёме из начала реплики. Пустой результат — вызывающий обязан
 *  выбросить реплику: сообщение из одного «Фаҳмо» и есть то, что запретил владелец. */
export function stripLeadingAck(text: string): string {
  const out = text.replace(LEADING_ACK, "").trim();
  if (!out) return "";
  return out !== text ? out[0].toUpperCase() + out.slice(1) : out;
}

