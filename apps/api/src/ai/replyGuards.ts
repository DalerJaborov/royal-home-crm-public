/** Границы: имя из одного слова короче трёх букв — это «Jl» из профиля, а не имя. */
const NAME_MIN_WORD = 3;
const NAME_MAX_WORDS = 3;
const NAME_MAX_LENGTH = 40;

/**
 * Приводит строку к имени клиента или отвечает `null` — «это не имя».
 *
 * ЭТО ФИЛЬТР НА ЗАПИСЬ, А НЕ НА РЕПЛИКУ. Правило одно: не распознали имя — в карточке
 * остаётся заглушка. Произвольный текст в поле «Имя» хуже пустого поля: заглушку CRM
 * узнаёт (lib/placeholderName.ts) и однажды заменит настоящим именем, а «Чихели кунум»
 * она считает настоящим именем и не тронет больше никогда.
 *
 * Чистка перед проверкой (а не отказ сразу) — ради живых случаев с прода: «Наргиз
 * 900001014» это имя с прилипшим телефоном, «Ном Фозилшо» — имя с приставкой
 * «имя:», «Фаррух 🏠» — имя со значком. Отбрасывать их целиком значило бы терять ровно
 * то, ради чего всё это писалось.
 */
export function normalizeClientName(raw: string | null | undefined): string | null {
  if (!raw) return null;
  let value = raw
    // Значки, цифры и всё, что не буква: телефон рядом с именем, эмодзи из Instagram.
    .replace(/[^\p{L}\s'’-]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
  // Приставка представления могла остаться после чистки («Ном Фозилшо»), и она
  // бывает двойной («номи ман Фозилшо») — снимаем до двух раз.
  for (let pass = 0; pass < 2; pass += 1) {
    const stripped = value.replace(NAME_INTRO_PREFIX, "").trim();
    if (stripped === value) break;
    value = stripped;
  }
  if (!value || value.length > NAME_MAX_LENGTH) return null;

  const words = value.split(" ").filter(Boolean);
  if (words.length === 0 || words.length > NAME_MAX_WORDS) return null;
  for (const [index, word] of words.entries()) {
    // Слово из букв и только из них: дефис и апостроф внутри («Абдулло-Хон», «O'Neil»).
    if (!/^\p{L}[\p{L}'’-]*$/u.test(word)) return null;
    if (word.length < (index === 0 ? NAME_MIN_WORD : 2)) return null;
    if (NOT_A_NAME.has(foldTajik(word))) return null;
    // Латиница строчными — это логин («raxxmanzadee»), а не имя: тот же признак, что
    // в lib/telephony/whisperText.ts и lib/placeholderName.ts.
    if (/^[a-z]/.test(word)) return null;
  }

  // Кириллица со строчной («номам гулру») — имя настоящее, просто написано наспех.
  // Возвращаем его с заглавной: в карточке имя должно выглядеть именем.
  return words.map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");
}

/**
 * Слова-паразиты и канцелярит: то, что человек в переписке не пишет.
 *
 * Отдельно от «отчёта о приёме» (LEADING_ACK): тот стоит в начале фразы и режется
 * целиком, а эти лезут в середину — «в принципе», «как бы», «собственно». Директор
 * 02.08.2026 отдельно попросил их убрать: они делают речь бота узнаваемо машинной,
 * потому что живой человек в мессенджере экономит каждое слово.
 *
 * Режем вместе с прилипшей запятой, иначе остаётся «Да, , у нас есть».
 *
 * ГРАНИЦА СПРАВА ОБЯЗАТЕЛЬНА, и вот почему. Первая версия правила её не имела, и
 * «как бы» совпадало с началом «как быстро»: клиенту уходило «Стро вы хотите
 * заехать?» вместо «Как быстро вы хотите заехать?». Так же ломались «как быть» и
 * «собственность» → «сть». Слово-паразит вырезается ТОЛЬКО когда оно кончилось —
 * дальше пробел, знак препинания или конец строки.
 *
 * И ещё раз про кириллицу: `\w` в JavaScript это [A-Za-z0-9_], русский хвост слова
 * им не ловится. «как я уже говорил\w*» не находило «говорила», зато вырезало
 * «говорил» и оставляло висящую «а». Окончания перечислены явно.
 */
const FILLER_WORDS = [
  "в\\s+принципе",
  "собственно(?:\\s+говоря)?",
  "как\\s+бы",
  "так\\s+сказать",
  // «в общем-то» (02.10.2026): дефис раньше считался границей, и клиенту уходил «-то».
  "в\\s+общем(?:[\\s-]+то)?",
  "по\\s+сути",
  "честно\\s+говоря",
  "надо\\s+сказать",
  "не\\s+побоюсь\\s+этого\\s+слова",
  "хочу\\s+отметить",
  "стоит\\s+отметить",
  "хотелось\\s+бы\\s+отметить",
  "как\\s+я\\s+уже\\s+говорил(?:а|и)?",
  // «Рад сообщить, что квартира свободна» без «что» давало «Что квартира
  // свободна» — придаточное без главного (02.10.2026). Уходит вместе с «что».
  "рад(?:а|ы)?\\s+сообщить(?:\\s*,?\\s*что)?",
  "спешу\\s+сообщить(?:\\s*,?\\s*что)?",
];
const FILLER = new RegExp(
  `${LEFT}(?:${FILLER_WORDS.join("|")})(?=[\\s,.!?;:«»"'()\\-–—]|$)[ \\t]*,?[ \\t]*`,
  "giu"
);

export function stripFillerWords(text: string): string {
  return text.replace(FILLER, "$1").replace(/[ \t]{2,}/g, " ").replace(/[ \t]+([,.!?;:])/g, "$1");
}

/**
 * Клиент не сказал ничего — прислал одну реакцию: смайлик, сердечко, наклейку.
 *
 * Решение владельца 02.08.2026: на такое отвечать НЕ НАДО. Ответ на «🔥» это
 * разговор, которого человек не начинал: он щёлкнул реакцию на историю, как ставят
 * лайк, и вопрос в ответ выглядит навязчиво. Отвечаем только на слова и вопросы.
 *
 * ЗНАКИ ПРЕПИНАНИЯ — ЭТО РЕЧЬ, А НЕ РЕАКЦИЯ. Первая версия этого правила считала
 * пустышкой всё, что не содержит букв и цифр, — и заодно «+» (обычное «да» в наших
 * чатах) и «???» (нетерпеливое «ну что там»). Человек, ответивший «+» на вопрос
 * «показать варианты?», молчания в ответ не заслужил. Поэтому реакцией считается
 * только сообщение, в котором ЕСТЬ эмодзи и НЕТ ничего другого, кроме пробелов, —
 * либо пустая строка. «🔥» — реакция, «+» — ответ, «🔥 чанд?» — вопрос.
 *
 * ВАЖНО: вложения проверяются отдельно вызывающим. Фотография без подписи — это НЕ
 * пустая реакция: клиент прислал квартиру и ждёт ответа.
 */
/**
 * Знаки, которые выглядят как эмодзи, а значат речь: «❓» это «ну что там?», «➕» —
 * «да», «✅» — «согласен». Первая правка чинила ровно этот случай для ASCII («+»,
 * «???»), но такие же символы из набора эмодзи остались молчаливыми — человек,
 * ответивший «➕» вместо «+», ответа не получал.
 */
const SPEECH_SYMBOLS = /[❓❔❕❗➕✅✔❌✖]/u;

export function isReactionOnly(text: string): boolean {
  const trimmed = text.trim();
  if (!trimmed) return true;
  if (SPEECH_SYMBOLS.test(trimmed)) return false;
  const hasEmoji = EMOJI.test(trimmed) || TEXT_SMILEY.test(trimmed);
  // EMOJI объявлен с флагом g — у такого выражения test() запоминает позицию между
  // вызовами и через раз возвращает false на той же строке. Сбрасываем явно.
  EMOJI.lastIndex = 0;
  if (!hasEmoji) return false;
  const withoutEmoji = trimmed.replace(EMOJI, "").replace(TEXT_SMILEY, "").trim();
  EMOJI.lastIndex = 0;
  return withoutEmoji.length === 0;
}

/**
 * Приметы машинного текста: длинное тире и точка в конце короткого сообщения.
 *
 * Решение владельца 02.08.2026. В мессенджере живой человек не ставит «—» никогда:
 * его нет на телефонной клавиатуре, он берётся только из редактора или из модели.
 * Точка в конце единственной фразы — та же примета: «Ҳа, ҳаст.» пишет бот, человек
 * пишет «Ҳа, ҳаст». Обе мелочи по отдельности незаметны, вместе они и создают
 * ощущение робота, из-за которого разговор глохнет.
 *
 * ТОЧКУ УБИРАЕМ ТОЛЬКО ПОСЛЕДНЮЮ и только одну. Точки внутри текста нужны: без них
 * «Нархаш 320 000. Дар Сино» слипается в кашу. Многоточие тоже не трогаем — это
 * интонация, а не пунктуация.
 */
export function stripMachineTypography(text: string): string {
  const withoutDashes = text
    // Тире в начале строки (перечисление) убирается вместе с отступом. ПЕРВЫМ:
    // правило ниже с `\s` съедало перенос строки и склеивало список в одну строку,
    // и до этой замены дело просто не доходило.
    .replace(/^[ \t]*[—–][ \t]*/gm, "")
    // ВИЛКА ЦЕНЫ И МЕТРАЖА — это диапазон, а не два числа: «320 000 — 350 000»
    // превращалось в «320 000, 350 000», и клиент спрашивал, какая цена настоящая.
    .replace(/(\d)[ \t]*[—–][ \t]*(\d)/g, "$1-$2")
    // Тире между словами заменяется запятой: «Сино — 320 000» → «Сино, 320 000».
    // Пробелы только горизонтальные: `\s` захватывал перевод строки.
    .replace(/[ \t]+[—–][ \t]+/g, ", ")
    .replace(/[—–]/g, "-");
  return withoutDashes.replace(/(?<![.!?])\.[ \t]*$/, "").trimEnd();
}

/**
 * @param clientText реплики самого клиента, склеенные в одну строку. Нужны ровно для
 *   одного: отличить телефон, который клиент назвал сам (его повтор для подтверждения
 *   — нормальная работа оператора), от чужого номера, взявшегося из ниоткуда. Пустая
 *   строка — законное значение: тогда разрешён только номер компании.
 */
/**
 * НЕ БОЛЬШЕ ОДНОГО СМАЙЛИКА ПОД ПОСТОМ (владелец 16.08.2026, вечер).
 *
 * С 22.08.2026 смайлики разрешены везде, и это правило перестало быть послаблением
 * — оно стало ограничением, и только для комментариев: гирлянда «🔥🔥🔥» под
 * собственным постом читается как накрутка, а в личной переписке столько смайликов
 * подряд просто не бывает.
 *
 * Оставляем РОВНО ОДИН, первый; промт просит о том же — просьба и фильтр совпадают.
 */
function keepOneEmoji(text: string): string {
  let kept = false;
  return text.replace(EMOJI, (match) => {
    if (kept) return "";
    kept = true;
    return match;
  });
}

/**
 * БОТ СДЕЛАЛ ЧУЖУЮ РАБОТУ — ПОСЛЕДНИЙ РУБЕЖ НА ВЫХОДЕ (владелец 21.08.2026:
 * «люди пытаются использовать бота как бесплатный ChatGPT»).
 *
 * Входные сторожа (ai/offTopicGuard.ts) ловят прямые просьбы — «напиши код»,
 * «реши задачу», «переведи текст». Но они читают ФОРМУЛИРОВКУ, а её человек
 * подбирает: «а как бы ты на питоне посчитал ипотеку по нашей квартире» проходит
 * насквозь (там есть и «квартира», и «ипотека» — слова нашего дела), и модель
 * честно выдаёт тридцать строк кода. Промт это запрещает, но промт — просьба,
 * а не гарантия; об этом весь файл.
 *
 * Поэтому решение принимается по ТОМУ, ЧТО ПОЛУЧИЛОСЬ, а не по тому, о чём
 * попросили. Признак чужой работы не в теме, а в форме ответа: консультант по
 * недвижимости в мессенджере не присылает блоков кода, не пишет полторы страницы
 * и не нумерует десять пунктов.
 *
 * ПОЧЕМУ ЭТО НЕ БЬЁТ ПО ПОДБОРКЕ ОБЪЕКТОВ (проверено по коду, а не на глаз).
 * Объекты уходят клиенту НЕ текстом модели: фотографии отправляет код по номеру
 * объекта (showPropertyNumber, ai/photoOffer.ts), PDF-гид — отдельным файлом
 * (ai/guideOffer.ts), а сам ответ ограничен схемой в ДВА коротких сообщения
 * (maxItems: 2 в qualifySchema) при maxTokens 400–500 на весь JSON целиком.
 * Промт прямо велит назвать 1-2 варианта и дать не больше одной ссылки за ход,
 * а на вопрос «что смотреть при осмотре» — «назови ДВА-ТРИ пункта, списком не
 * заваливай». То есть законной реплики ни в 1200 знаков, ни в семь пунктов
 * попросту не бывает: весь бюджет хода — это примерно столько же знаков на ОБА
 * сообщения вместе.
 */

/** Огороженный блок кода — самый честный признак: живой человек так не пишет. */
const CODE_FENCE = /```|~~~/;

/**
 * Конструкции языков программирования — для кода без ограды.
 *
 * Список нарочно из однозначного: каждая строка здесь такова, что в разговоре о
 * квартире на русском, таджикском или английском не встречается вовсе. Голых
 * HTML-тегов тут НЕТ намеренно — одиночный «</p>», утёкший в текст, это известная
 * осечка модели (см. HTML_TAG выше), и её лечит вычёркивание, а не отмена всего
 * ответа. Ловим только разметку целой страницы.
 */
const CODE_CONSTRUCTS: RegExp[] = [
  /<\?php/i,
  /#include\s*[<"]/,
  /^#!\/(?:bin|usr)/m,
  /^[ \t]*import\s+\S/m,
  /^[ \t]*from\s+[\w.]+\s+import\s/m,
  /\b(?:function|def|class|interface|struct)\s+[A-Za-z_$][\w$]*\s*[({:]/,
  /\b(?:const|let|var)\s+[A-Za-z_$][\w$]*\s*=/,
  /\b(?:public|private|protected)\s+(?:static\s+)?[\w<>[\]]+\s+\w+\s*\(/,
  /\b(?:console\.log|System\.out\.print|printf|println|print|echo|alert)\s*\(/,
  /=>\s*[{(]/,
  /\b(?:if|for|while|switch|foreach)\s*\([^)\n]{0,80}\)\s*\{/,
  /\breturn\b[^\n]{0,80};/,
  // Закрывающая скобка отдельной строкой — то, чем кончается любой блок кода.
  /^[ \t]*[}\])];?[ \t]*$/m,
  /\b(?:select\s+\*|insert\s+into|update\s+\w+\s+set|delete\s+from|create\s+table|drop\s+table)\b/i,
  /<!DOCTYPE\s+html|<html[\s>]|<script[\s>]|<\/(?:html|body|script|style)>/i,
];

/**
 * Потолок длины ОДНОГО сообщения клиенту.
 *
 * 1200 знаков — это примерно вдвое больше самой длинной законной реплики: весь
 * бюджет хода (400–500 токенов на JSON целиком) на кириллице — это порядка тысячи
 * знаков на ОБА сообщения вместе со служебными полями. Дойти до 1200 в одном
 * пузыре модель может, только бросив разговор и начав писать сочинение. Порог
 * специально не занижен до «разумных» 400–500: ложное срабатывание здесь стоит
 * дороже пропуска — клиент получит шаблон вместо честного ответа про квартиру.
 */
const MAX_REPLY_CHARS = 1200;

/**
 * Пунктов в НУМЕРОВАННОМ списке. Больше шести — это уже инструкция, а не ответ
 * консультанта; промт и сам велит держаться двух-трёх пунктов.
 */
const MAX_LIST_ITEMS = 6;
const NUMBERED_ITEM = /^[ \t]*\d{1,2}[.)][ \t]+\S/gm;

/**
 * ПУНКТ СПИСКА — ЭТО ЛЮБОЙ МАРКЕР В НАЧАЛЕ СТРОКИ, А НЕ ТОЛЬКО ЦИФРА
 * (найдено аудитом 22.08.2026).
 *
 * До этой правки считались только строки вида «1. текст» / «2) текст», и весь
 * рубеж обходился сменой значка: ответ на десять пунктов через дефис или «•»
 * проходил насквозь, если укладывался в MAX_REPLY_CHARS. Форма маркера — не то,
 * по чему стоит принимать решение: чужая работа выглядит одинаково с любым.
 *
 * МАРКЕР ОПОЗНАЁТСЯ ТОЛЬКО В НАЧАЛЕ СТРОКИ И ТОЛЬКО С ПРОБЕЛОМ ПОСЛЕ НЕГО — иначе
 * фильтр начал бы считать пунктом обычную вилку цены («5000 - 7000 сомонӣ») и
 * тире между словами, которых в ответе бота полно. Ложное срабатывание здесь
 * стоит дороже пропуска: клиент получит шаблон вместо ответа про квартиру.
 */
const LIST_ITEM = /^[ \t]*(?:\d{1,2}[.)]|[-–—*•·‣▪●○]|[a-zа-яё]\))[ \t]+\S/gimu;

/**
 * Порог для маркеров ВООБЩЕ на единицу мягче нумерованного, и это не произвол.
 * Ровно шесть пунктов буллетами — законный ответ ПРОДАВЦУ: приём объекта прямо
 * велит перечислить одним сообщением комнаты, площадь, район, этаж, состояние и
 * цену, и сам образец в промте набран через «•» (ai/sellerIntake.ts,
 * SELLER_INTAKE_RULES). Отменить такую реплику шаблоном «давайте о жилье» —
 * потерять собственника, который уже согласился всё рассказать. Поэтому у
 * буллетов есть запас в один пункт, а нумерованный список — форма инструкции,
 * которой у нас законного применения нет, — остаётся на прежнем пороге.
 */
const MAX_MARKED_ITEMS = 7;

/**
 * Перечисление ВООБЩЕ БЕЗ МАРКЕРОВ — просто много строк подряд.
 *
 * Законная реплика — это 1-2 коротких предложения (правило 1 промта), и весь
 * бюджет хода — 400-500 токенов на оба сообщения вместе. Девять строк в одном
 * пузыре означают то же самое, что и нумерованный список: модель бросила
 * разговор и выдала чужую работу, только без значков. Порог намеренно выше
 * списочного: без маркера мы менее уверены, а перенос строки бот иногда ставит
 * законно (адрес, цена, ориентир отдельной строкой).
 */
const MAX_PLAIN_LINES = 8;
const KEY_VALUE_LINE = /^[ \t]*\p{L}[^:\n]{0,24}:[ \t]*\S/u;

/**
 * Похоже ли, что бот вместо разговора выполнил чужое задание. Возвращает короткую
 * причину для журнала или null.
 */
export function looksLikeOutsourcedWork(text: string): string | null {
  if (CODE_FENCE.test(text)) return "блок кода";
  if (CODE_CONSTRUCTS.some((re) => re.test(text))) return "конструкции языка программирования";
  if (text.length > MAX_REPLY_CHARS) return `${text.length} знаков — это не реплика, а сочинение`;
  // lastIndex сбрасывать не нужно: match() с флагом g возвращает все совпадения
  // сразу и позицию не запоминает (в отличие от test(), см. isReactionOnly).
  const numbered = text.match(NUMBERED_ITEM)?.length ?? 0;
  if (numbered > MAX_LIST_ITEMS) return `нумерованный список из ${numbered} пунктов`;
  const items = text.match(LIST_ITEM)?.length ?? 0;
  if (items > MAX_MARKED_ITEMS) return `список из ${items} пунктов`;
  // Строки вида «Район: Сино», «Цена: 85 000 $» не считаются (02.10.2026): это
  // сводка объекта, законный ответ покупателю, а не чужая работа. Девять строк
  // такой сводки раньше заменялись на «Тут не подскажу… Покупаете или продаёте?».
  const lines = text
    .split("\n")
    .filter((line) => line.trim().length > 0 && !KEY_VALUE_LINE.test(line)).length;
  if (lines > MAX_PLAIN_LINES) return `перечисление из ${lines} строк`;
  return null;
}

/**
 * РАЗМЕТКА ЧАТ-БОТА (ревизия 02.10.2026). Instagram, Messenger, WhatsApp и чат
 * сайта не рисуют markdown: «**2-хонага**», «## Варианты», `код` доходят до
 * клиента со звёздочками и решётками и сразу выдают автомат. Снимаем значки,
 * слова оставляем. Одиночная «*» снимается только парой вокруг слова: «5*» и
 * «*» как знак сноски не трогаем.
 */
export function stripMarkdown(text: string): string {
  return text
    .replace(/\*\*([^*\n]+?)\*\*/g, "$1")
    .replace(/__([^_\n]+?)__/g, "$1")
    .replace(/(^|[\s(«"])\*([^\s*][^*\n]*?)\*(?=$|[\s.,!?:;)»"])/gm, "$1$2")
    .replace(/`+/g, "")
    .replace(/^[ \t]{0,3}#{1,6}[ \t]+/gm, "");
}

export function cleanOutgoingReply(
  text: string,
  clientText = "",
  options: { allowOneEmoji?: boolean } = {}
): string {
  /**
   * ПРОВЕРЯЕМ ПЕРВЫМ ДЕЛОМ И ПО СЫРОМУ ТЕКСТУ — до всех вычёркиваний ниже.
   *
   * Они для того и написаны, чтобы менять текст: HTML_TAG снял бы теги страницы,
   * stripMachineTypography — тире и точки, и к моменту проверки код выглядел бы
   * уже не совсем кодом. Признак чужой работы надо искать в том, что вернула
   * модель, а не в том, что от него осталось.
   *
   * Каждое срабатывание — строка в журнал: рубеж, о котором не видно, работает ли
   * он и на чём, через месяц никто не поправит. Отправка при этом не ждёт записи
   * (`void`): журнал не должен задерживать ответ клиенту.
   */
  const outsourced = looksLikeOutsourcedWork(text);
  if (outsourced) {
    void logSystemError(
      "ai",
      `Бот сделал чужую работу вместо разговора о жилье (${outsourced}) — ответ заменён возвратом к теме: ` +
        `«${text.replace(/\s+/g, " ").slice(0, 200)}»`
    );
    /**
     * Язык берём из слов КЛИЕНТА, а из ответа — только если клиента нам не
     * передали (короткие реплики и комментарии зовут очистку без него). Ответ на
     * своём языке человек читает как ответ; шаблон на чужом — как второй сбой
     * подряд.
     */
    return guardReply("offtopic", detectClientLanguage(clientText.trim() || text));
  }

  /**
   * СМАЙЛИКИ ВЫРЕЗАЮТСЯ ИЗ ПЕРЕПИСКИ (решение владельца 22.08.2026, вечер:
   * «убери смайлики, они выдают бота»).
   *
   * ИСТОРИЯ, ЧТОБЫ НЕ ХОДИТЬ ПО КРУГУ ТРЕТИЙ РАЗ. 01.08 запрет ввели, 22.08 днём
   * сняли («современные безобидные смайлики всегда можно использовать»), 22.08
   * вечером вернули — и по другой причине, чем в первый раз. Дело не в
   * приличиях: одинаковый значок в конце ответов подряд читается как подпись
   * автомата. Живой человек ставит смайлик то так, то эдак, а бот — ровно и
   * всегда, и именно эта ровность выдаёт его вернее любой формулировки.
   *
   * ИСКЛЮЧЕНИЕ ОДНО — комментарии под постами (`allowOneEmoji`). Там смайлик
   * часто и есть весь ответ на «спасибо», а пустая строка вместо него выглядела
   * бы грубее, чем значок. Правило «не больше одного» (16.08.2026) продолжает
   * работать именно там.
   */
  const contactContextLanguage = detectClientLanguage(publicAgencyContactContext(text));
  const contactClientLanguage = detectClientLanguage(clientText);
  // Keep our inserted phrase coherent with the remaining bubble. If no language
  // is established, the trusted number alone avoids introducing a second one.
  const contactLanguage = contactContextLanguage === "ru" || contactContextLanguage === "tg"
    ? contactContextLanguage
    : contactClientLanguage === "ru" || contactClientLanguage === "tg" ? contactClientLanguage : undefined;
  const contactCorrected = renderPublicAgencyContact(text, contactLanguage);
  const withoutRude = contactCorrected.replace(RUDE_EMOJI, "");
  const emojiHandled = options.allowOneEmoji ? keepOneEmoji(withoutRude) : withoutRude.replace(EMOJI, "");
  // Ссылки и телефоны разбирает ОДИН проход: чужой адрес уходит целиком, свой
  // прячется от телефонного фильтра до конца разбора (см. stripLinksAndForeignPhones).
  // Признание сбоя режется ДО «в системе»/«дар база» (02.10.2026): иначе
  // stripMachineWords убирал слово «система», и «В системе произошёл сбой»
  // уходило клиенту как «Произошёл сбой» — фильтр признаний своего случая не видел.
  const withoutMarkup = stripMachineWords(
    stripSystemExcuses(stripLinksAndForeignPhones(
      stripTextSmileys(stripMarkdown(emojiHandled.replace(HTML_TAG, "").replace(HANDLE_ADDRESS, ""))),
      clientText
    ))
  );
  // Отчёт о приёме режется ПОСЛЕ обращений и разметки, но ДО чистки пробелов:
  // «@nick Фаҳмо, дар Сино» — сначала уходит ник, и только тогда «Фаҳмо,» видно
  // как начало строки. Порядок наоборот оставил бы отчёт нетронутым.
  const cleaned = stripMachineTypography(
    stripFillerWords(
      stripBannedWords(stripForeignWords(stripLeadingAck(stripGenderedAddress(stripSystemExcuses(withoutMarkup)))))
    )
  )
    .replace(/[ \t]{2,}/g, " ")
    .replace(/\s+([,.!?;:])/g, "$1")
    .trim();
  // Заглавная буква возвращается ЗДЕСЬ, а не в отдельных фильтрах: вырезали мы
  // начало фразы или нет, клиенту уходит одно сообщение, и начинаться со строчной
  // буквы оно не должно.
  if (cleaned && cleaned !== text) return cleaned[0].toUpperCase() + cleaned.slice(1);
  return cleaned;
}
