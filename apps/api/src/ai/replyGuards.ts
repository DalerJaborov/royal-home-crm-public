/**
 * Последний рубеж перед отправкой: то, что бот не должен говорить НИКОГДА.
 *
 * Запреты уже стоят в промте, и обычно этого хватает. Но промт — это просьба, а не
 * гарантия: он длинный, правил в нём десятки, и модель изредка проговаривается. Для
 * большинства правил такая осечка стоит дёшево. Для одного — нет.
 *
 * ОБРАЩЕНИЯ ПО ПОЛУ. Владелец запретил их полностью: пол собеседника мы не знаем и
 * знать не можем — ни ник, ни имя, ни манера письма его не определяют. Ошибка здесь
 * не «неточность», а личная обида в первом же сообщении, от которой разговор уже не
 * выправить. 01.08.2026 бот написал в Instagram «Фаҳмо, апаи Фарида» — при трёх
 * разных запретах в промте, включая поимённый список этих самых слов.
 *
 * Поэтому здесь не просьба, а вычёркивание: если слово всё же появилось, оно не
 * доедет до клиента. Проверка дешёвая (одна строка на сообщение), а цена пропуска —
 * весь разговор.
 *
 * ПРО КИРИЛЛИЦУ И `\b`: границы слова в регулярных выражениях JavaScript определены
 * через [A-Za-z0-9_], и с кириллицей `\b` НЕ РАБОТАЕТ вовсе — `/\bапаи/` не находит
 * ничего. В этом репозитории так молча умирали уже два правила. Поэтому границы
 * выписаны явно, символами.
 */

