/**
 * Слова, по которым нельзя узнать вопрос: они есть в любой фразе на обоих языках.
 * Без отсева «шумо» и «чӣ» совпадало бы что угодно, и повтор вопроса не дописывался
 * бы никогда — то есть гарантия молча превратилась бы обратно в пожелание.
 */
const QUESTION_STOP_WORDS = new Set([
  "шумо",
  "туро",
  "лутфан",
  "мешавад",
  "метавонед",
  "пожалуйста",
  "скажите",
  "можете",
  "какой",
  "какая",
  "какое",
  "какие",
  "сколько",
]);

/**
 * Значимые слова вопроса — по ним узнаём его в тексте ответа.
 *
 * Сравниваем НАЧАЛАМИ слов, а не целыми словами: таджикский лепит окончания к корню
 * («буҷет» → «буҷетатон» → «буҷеташ»), и точное совпадение промахивалось бы на каждой
 * второй форме. Пять букв — достаточно, чтобы «расм» и «раён» не слиплись, и коротко
 * достаточно, чтобы пережить окончание.
 */
const QUESTION_STEM_LENGTH = 5;

function questionStems(question: string): string[] {
  return question
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .split(/\s+/)
    .filter((w) => w.length >= 4 && !QUESTION_STOP_WORDS.has(w))
    .map((w) => w.slice(0, QUESTION_STEM_LENGTH));
}

/**
 * Прозвучал ли этот вопрос в тексте — пусть другими словами.
 *
 * Точного совпадения не требуем нарочно: модель почти всегда переформулирует, и
 * требование буквы приводило бы к тому, что код дописывал бы второй такой же вопрос
 * следом за первым. Половины значимых слов достаточно, чтобы отличить «а буҷетатон
 * то чӣ қадар?» от разговора про метро.
 */
export function repeatsQuestion(text: string, question: string): boolean {
  const stems = questionStems(question);
  // Вопрос из одних служебных слов («Кай?») узнать нечем — считаем, что вопросительный
  // знак в ответе и есть он: дописать второй вопрос хуже, чем не дописать.
  if (stems.length === 0) return text.includes("?");
  const haystack = text.toLowerCase();
  const hits = stems.filter((stem) => haystack.includes(stem)).length;
  return hits * 2 >= stems.length;
}

/**
 * НЕ ДАТЬ БОТУ ПОТЕРЯТЬ СВОЙ ЖЕ ВОПРОС, КОГДА КЛИЕНТ УШЁЛ С ТЕМЫ.
 *
 * Решение владельца 11.08.2026: клиент заговорил не по теме — бот потихоньку
 * возвращает его к последнему диалогу. Ровно то же требование уже стояло в промте про
 * номер телефона, было записано там трижды и всё равно не сработало на живом клиенте:
 * модель отвечает на ПОСЛЕДНЮЮ реплику и теряет висящую задачу. Общая инструкция
 * «мягко возвращай к теме» проверяема только глазами, а значит не проверяема вовсе.
 *
 * Здесь — последняя проверка: предписание на ход уже ушло в промт (ai/topicLock.ts), и
 * если модель его всё же не исполнила, вопрос дописывает код.
 *
 * ДОПИСЫВАЕМ В КОНЕЦ ПОСЛЕДНЕЙ реплики, а не в начало первой: вопрос должен закрывать
 * сообщение — так на него и отвечают. Место под отдельный пузырь используем, только
 * если оно есть: предел в две реплики держит вся отправка (см. normalizeReplyBubbles),
 * и третья была бы молча выброшена вместе с вопросом.
 */
export function ensureOpenQuestionKept(bubbles: string[], openQuestion: string | null, mustAsk: boolean): string[] {
  if (!mustAsk || !openQuestion) return bubbles;
  // Отвечать нечем — дописывать некуда: одинокий вопрос без ответа на реплику клиента
  // и есть то самое «неисправный автомат», которого владелец требовал избегать.
  if (bubbles.length === 0) return bubbles;
  if (bubbles.some((b) => repeatsQuestion(b, openQuestion))) return bubbles;

  if (bubbles.length < 2) return [...bubbles, openQuestion];
  const last = bubbles.length - 1;
  return bubbles.map((b, i) => (i === last ? `${b} ${openQuestion}` : b));
}

/**
 * НЕ ЗАДАВАТЬ КЛИЕНТУ ВОПРОС, КОТОРЫЙ ЕМУ УЖЕ ЗАДАВАЛИ.
 *
 * Живой случай 13.08.2026, разобранный владельцем по переписке клиента Жасмин
 * (WhatsApp): бот дописывал «Кадом тарафда хона кофта истодед ё фурӯхтаниед?»
 * ВТОРЫМ пузырём почти к каждому ответу — восемь раз подряд. Человек к тому
 * моменту давно сказал, что ищет, прислал фото конкретной квартиры и просил
 * позвонить; на его «ташаккур» и «тезтарак» бот отвечал одной и той же
 * стартовой анкетой. Со стороны это ровно то, чего владелец требовал избегать:
 * неисправный автомат.
 *
 * Промт тут не спасает и не спасал: запреты «не переспрашивай» стоят в нём в
 * трёх местах (правила 7, 9 и блок «НЕ КАЖДОЕ СООБЩЕНИЕ — ПРО КВАРТИРУ»).
 * Модель отвечает на последнюю реплику и не помнит, что спрашивала это же
 * пятнадцать сообщений назад — тот самый класс осечек, из-за которого в этом
 * проекте дорогие правила ставят фильтром в коде.
 *
 * ЧТО ИМЕННО РЕЖЕМ. Только вопросы (есть «?») и только те, что бот уже задавал
 * в этом разговоре — сравнение по значимым основам слов, тем же `repeatsQuestion`,
 * что уже используется для висящего вопроса. Не-вопросы не трогаем вовсе:
 * «Саломат бошед» повторяется в переписке законно, это вежливость, а не анкета.
 *
 * ПОЧЕМУ НЕ ВЕСЬ РАЗГОВОР, А ОКНО. Вопрос, заданный в самом начале и повторённый
 * через сотню сообщений и три месяца, — это нормально: обстоятельства меняются,
 * и спросить заново уместно. Отсекаем только повтор В ПРЕДЕЛАХ живой памяти
 * разговора.
 */
const REPEAT_QUESTION_WINDOW = 12;

export function dropRepeatedQuestions(
  bubbles: string[],
  botHistory: string[],
  /**
   * Вопрос, который вернуть РАЗРЕШЕНО, — незакрытый вопрос удержания темы
   * (ai/topicLock.ts). Его код возвращает осознанно и с пределом в три попытки:
   * без этого исключения фильтр вычёркивал бы ровно то, что сам же проект только
   * что дописал, и удержание темы перестало бы работать целиком.
   */
  allowedQuestion?: string | null
): string[] {
  const recent = botHistory.slice(-REPEAT_QUESTION_WINDOW);
  if (recent.length === 0) return bubbles;
  const kept = bubbles.filter((bubble) => {
    if (!bubble.includes("?")) return true;
    if (allowedQuestion && repeatsQuestion(bubble, allowedQuestion)) return true;
    return !recent.some((said) => said.includes("?") && repeatsQuestion(bubble, said));
  });
  // Если вычёркивание съело ВСЁ, оставляем как было: молчание в ответ на сообщение
  // клиента хуже повторного вопроса, а отправлять пустоту нельзя — на этом падает
  // следующий запрос к модели (см. cleanOutgoingReply).
  if (kept.length === 0) return bubbles;
  // Счётчик срабатываний (совет экспертов, п. 8): бот переспросил уже спрошенное.
  if (kept.length < bubbles.length) guardFired("repeated_question", bubbles.length - kept.length);
  return kept;
}

