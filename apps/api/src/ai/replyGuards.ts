/** Что считается краем слова слева и справа. Явно, потому что `\b` тут бесполезен. */
const LEFT = "(^|[\\s,.!?;:«»\"'()\\-–—])";
const RIGHT = "([\\s,.!?;:«»\"'()\\-–—]|$)";
/** Правый край БЕЗ пробела: «дальше знак препинания или конец фразы». Нужен там, где
 *  слово считается обращением только в конце реплики, а перед другим словом остаётся
 *  обычным существительным («акаи мо» — «наш брат»). */
const RIGHT_END = "([,.!?;:«»\"')\\-–—]|$)";

/**
 * Обращения, выдающие пол. Порядок важен: сначала «акаи Имя» (с именем), потом
 * голое «ака» — иначе первое правило никогда не сработает, имя останется висеть.
 *
 * Имя после приставки — это слово с заглавной буквы: «акаи Фарида». Строчное слово
 * не трогаем, потому что «акаи мо» («наш брат») к обращению отношения не имеет.
 */
/** Хвост таджикского слова: притяжательные и падежные суффиксы («акаҷонам»,
 *  «апаҷони»). ИМЕННО ТАК, А НЕ `\w*`: `\w` в JavaScript — это `[A-Za-z0-9_]`, и на
 *  кириллице он не ловит ничего. На этой грабле в репозитории уже умирали правила
 *  (стоп-слова напоминаний, определение непонимания), а 16.08.2026 выяснилось, что и
 *  это правило — тоже: «акаҷон» вырезалось, «акаҷонам» проходило насквозь. */
const TAIL = "[а-яёӣӯқғҳҷ]*";

/**
 * Родственные обращения, которые в Душанбе прямо указывают на пол собеседника.
 *
 * До 16.08.2026 фильтр знал ровно два корня, а промт запрещал «любые другие слова,
 * выдающие пол»: то есть половина запрета держалась на просьбе к модели, и
 * «додарҷон», «хоҳарам», «амак», «хола» проходили насквозь.
 * Список намеренно из ОБРАЩЕНИЙ, а не из всех терминов родства: «падар»/«модар» в
 * разговоре о квартире значат родителей клиента, а не обращение к нему.
 */
const KINSHIP = "ака|апа|додар|хоҳар|хохар|амак|тағо|таго|хола|амма|бародар";

/** Те же обращения латиницей. Промт велит отвечать кириллицей, но правило «никогда»
 *  на просьбе к модели не держится — ровно об этом весь этот файл. */
const KINSHIP_LATIN = "aka|apa|dodar|khohar|hohar|amak|tago|khola|hola|amma|barodar";

const PATTERNS: RegExp[] = [
  // акаҷон / апаҷон / додарҷон / ака ҷон — самая частая форма, с любым хвостом
  new RegExp(`${LEFT}(${KINSHIP})\\s?ҷон${TAIL}${RIGHT}`, "giu"),
  // тот же корень без «ҷ» — так пишут с клавиатуры без таджикских букв
  new RegExp(`${LEFT}(${KINSHIP})\\s?джон${TAIL}${RIGHT}`, "giu"),
  // акаи Фарида / апаи Фарида — приставка вместе с именем
  new RegExp(`${LEFT}(${KINSHIP})[иӣ]\\s+[А-ЯЁӢӮҚҒҲҶ][а-яёӣӯқғҳҷ]+${RIGHT}`, "gu"),
  // акаи / апаи / хоҳари без имени — ТОЛЬКО в конце фразы или перед знаком.
  // Перед другим словом не трогаем: «акаи мо» это «наш брат», а не обращение,
  // и вырезание превращало осмысленную фразу в «Ин мо».
  new RegExp(`${LEFT}(${KINSHIP})[иӣ]${RIGHT_END}`, "giu"),
  // ака Фарида / апа Фарида
  new RegExp(`${LEFT}(${KINSHIP})\\s+[А-ЯЁӢӮҚҒҲҶ][а-яёӣӯқғҳҷ]+${RIGHT}`, "gu"),
  // хоҳарам / додарам — обращение с притяжательным суффиксом, без «ҷон».
  // Суффикс НЕ захватывающей группой: разбор замены ждёт ровно три группы
  // (край-слово-край), и лишняя ломала его — «Хоҳарам, ин хона» превращалось
  // в «Ам ин хона». Поймано пробой на живых фразах, а не чтением.
  new RegExp(`${LEFT}(додар|хоҳар|хохар|бародар)(?:ам|ат|аш)${RIGHT}`, "giu"),
  // Звательное обращение без всяких суффиксов: «Рахмат, амак», «Хуб, хола».
  // Только после запятой или в самом начале фразы — там, где слово обращено к
  // человеку. «Хонаи хола» (дом тёти) под это не подходит и остаётся.
  new RegExp(`(,\\s*)(${KINSHIP})${RIGHT_END}`, "giu"),
  // латиница: akajon, apa jon, dodarjon
  new RegExp(`${LEFT}(${KINSHIP_LATIN})\\s?jon[a-z]*${RIGHT}`, "giu"),
];

/**
 * Убирает обращения по полу из текста, оставляя фразу читаемой.
 *
 * Вырезается ТОЛЬКО обращение; имя, если оно шло следом, уходит вместе с ним — иначе
 * из «Фаҳмо, апаи Фарида» получилось бы «Фаҳмо, Фарида», а это уже другое решение,
 * которое должен принимать не фильтр. Без обращения фраза звучит нормально и
 * по-таджикски: «Фаҳмо».
 *
 * Мусор после вырезания (двойные пробелы, запятая перед точкой, запятая в конце)
 * убирается здесь же: обрубок вроде «Фаҳмо, .» выдал бы правку не хуже самого
 * обращения.
 */
export function stripGenderedAddress(text: string): string {
  let out = text;
  for (const re of PATTERNS) {
    // Края (LEFT/RIGHT) возвращаем на место: они принадлежат соседним словам, а не
    // обращению, и съев их, мы склеили бы соседние слова.
    out = out.replace(re, (_m, left: string, _word: string, right: string) => `${left}${right}`);
  }
  out = out
    .replace(/[ \t]{2,}/g, " ")
    .replace(/\s+([,.!?;:])/g, "$1")
    .replace(/([,;:])\s*([.!?])/g, "$2")
    .replace(/^[\s,;:]+/, "")
    // Обращение стояло последним словом — от него осталась висящая запятая
    // («Ин вариант зӯр аст, акаҷон» → «Ин вариант зӯр аст,»).
    .replace(/[\s,;:]+$/, "")
    .replace(/[ \t]+$/gm, "")
    .trim();
  // Обращение стояло первым словом — фраза осталась со строчной буквы («апаи
  // Нигина, ин вариант зӯр аст» → «ин вариант...»). Само по себе это мелочь, но
  // именно из таких мелочей складывается ощущение, что писал не человек.
  if (out && out !== text) out = out[0].toUpperCase() + out.slice(1);
  return out;
}

