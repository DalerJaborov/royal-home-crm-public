/** Модель почти всегда возвращает массив, но на случай сбоя (одна строка вместо
 *  массива, пустые элементы, лишние пункты) приводим к 1-2 непустым «пузырям».
 *
 * `alreadyGreeted` — бот в этом диалоге уже здоровался. Тогда приветствие из начала
 * реплики вырезается: «Салом» в середине разговора означает, что бот забыл, с кем
 * говорит, и человек это читает именно так. Первое сообщение диалога здоровается по
 * праву, поэтому признак приходит снаружи, а не угадывается здесь. */
/**
 * ДОСЛОВНЫЙ ПОВТОР СОБСТВЕННОЙ ФРАЗЫ — ФИЛЬТРОМ В КОДЕ, А НЕ ПРОСЬБОЙ В ПРОМТЕ.
 *
 * Живой диалог 22.08.2026: клиент на вопрос про ремонт ответил «Бо ремонт», бот
 * попросил номер; клиент повторил «Бо таьмир» (то же самое другими словами) — и бот
 * СЛОВО В СЛОВО прислал ту же просьбу: «Рақами телефон ва номатонро нависед, то
 * агенти мо занг занад». Два одинаковых сообщения подряд — самая узнаваемая подпись
 * автомата, живой человек так не пишет никогда.
 *
 * Правило «не повторяй дословно» в промте УЖЕ ЕСТЬ. Оно не сработало — и это ровно
 * тот случай, ради которого в проекте заведено правило: дорогие запреты ставятся
 * фильтром, а промт остаётся просьбой (см. royal-home-prompt-is-not-a-guarantee).
 *
 * Сравниваем по «скелету» фразы: без знаков, регистра и лишних пробелов. «Рақами
 * телефон нависед.» и «Рақами телефон нависед» — один и тот же повтор, а точка
 * между ними ничего не меняет.
 */
function replySkeleton(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

/** Слишком короткие ответы («Хуб», «Бале») повторяются законно — это согласие, а
 *  не мысль. Порог отсекает их и оставляет настоящие фразы. */
const REPEAT_MIN_CHARS = 25;

export function isRepeatOfLastReply(text: string, lastAssistantText: string): boolean {
  if (!lastAssistantText) return false;
  const now = replySkeleton(text);
  if (now.length < REPEAT_MIN_CHARS) return false;
  /**
   * Сравниваем и с записью целиком, и с каждой её строкой (17.09.2026). Ход бота
   * уходит клиенту двумя сообщениями, а в историю ложится одной строкой через
   * перевод строки — и пузырь «Здравствуйте! Я консультант Royal Home.» никогда
   * не был равен «…\nПодскажите, как к Вам обращаться…». На двухпузырных ответах
   * проверка молча не срабатывала; ровно так бот и повторил себя дословно.
   */
  return [lastAssistantText, ...lastAssistantText.split("\n")].some((piece) => {
    const before = replySkeleton(piece);
    return before.length >= REPEAT_MIN_CHARS && now === before;
  });
}

export function normalizeReplyBubbles(
  reply: unknown,
  alreadyGreeted = false,
  clientText = "",
  lastAssistantText = ""
): string[] {
  const arr = Array.isArray(reply) ? reply : typeof reply === "string" ? [reply] : [];
  return (
    arr
      .filter((s): s is string => typeof s === "string" && s.trim().length > 0)
      // Безусловные запреты вычёркиваются здесь, а не только просятся в промте
      // (см. ai/replyGuards.ts). Фильтр стоит ДО обрезки до двух сообщений: реплика,
      // от которой после очистки ничего не осталось, не должна занимать место.
      // `clientText` — реплики самого клиента: по ним фильтр отличает его собственный
      // номер (повторить для подтверждения можно) от чужого (нельзя никогда).
      .map((s) => cleanOutgoingReply(s.trim(), clientText))
      /**
       * ПОВТОР ИЩЕМ ДО ОБРЕЗКИ ПРИВЕТСТВИЯ, А НЕ ПОСЛЕ (найдено 17.09.2026).
       *
       * stripRepeatGreeting меняет текст — и сочинённый моделью дословный повтор
       * прошлого хода переставал ему равняться: «Здравствуйте! Я консультант
       * Royal Home…» превращалось в «Я консультант Royal Home…», а в истории
       * лежало с приветствием. Порядок и был причиной того, что на «Саломалекм»
       * клиент получил прошлое сообщение бота слово в слово: обрезка молча
       * выключала защиту ровно в том случае, ради которого обе написаны.
       *
       * Сравнивать раньше ещё и точнее: слева то, что выдала модель, справа то,
       * что реально ушло клиенту, без наших правок посередине.
       */
      // Пустые — до проверки «первый ли пузырь» (02.10.2026): если очистка съела
      // первый («Хуб.»), повторное «Салом!» во втором становилось первым уже ПОСЛЕ
      // проверки и уходило клиенту.
      .filter((s) => s.length > 0)
      .filter((s) => !isRepeatOfLastReply(s, lastAssistantText))
      // После срезанного приветствия отчёт о приёме оказывается в начале строки:
      // «Ассалому алейкум! Фаҳмо, дар Сино…» → «Фаҳмо, дар Сино…». Срезаем и его.
      .map((s, i) => (i === 0 && alreadyGreeted ? stripLeadingAck(stripRepeatGreeting(s)) : s))
      .filter((s) => s.length > 0)
      .slice(0, 2)
  );
}

