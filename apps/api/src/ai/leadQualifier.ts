/**
 * Обязательные правила под конкретное намерение разговора.
 *
 * Экономия промта 23.08.2026: в каждый ход грузились сценарии покупателя,
 * продавца, арендатора и соискателя разом, а в разговоре нужен ровно один.
 *
 * @param intent намерение из черновика лида. `undefined` (первый ход) и `"other"`
 *   дают безопасный минимум: полных блоков нет вовсе, зато есть все четыре
 *   напоминания — по ним модель и выберет intent, а полный блок получит следующим
 *   ходом. Так же, а не «подать всё на всякий случай»: подать всё — это ровно то
 *   состояние, из-за которого промт и разросся.
 */
export function coreRulesForIntent(intent: LeadIntent | undefined, who?: WhoIsThis): string {
  // Порядок сценариев прежний (buy → sell → rent → job): подробный блок встаёт на
  // своё место, остальные три заменяются строкой. Так вариант префикса у каждого
  // намерения свой, но САМ ПО СЕБЕ устойчив между диалогами — кэш Anthropic делится
  // на пять веток вместо одной, а не рассыпается на диалог.
  // Направление ещё не известно — подаём ИНТЕЙК, а не четыре напоминания сразу.
  // Напоминания перечисляли сценарии, но не учили понимать человека: на «салом»
  // бот отвечал анкетой, а рекламному агенту начинал продавать квартиру.
  const body =
    intent && intent !== "other"
      ? SCENARIO_ORDER.map((key) => (key === intent ? SCENARIO_FULL[key] : SCENARIO_HINTS[key])).join("")
      : (NON_CLIENT_SCENARIOS[who ?? "UNKNOWN"] ?? SCENARIO_INTAKE);
  return CORE_RULES_HEAD + SCENARIOS_HEADER + body + SCENARIO_OTHER + CORE_RULES_TAIL;
}

