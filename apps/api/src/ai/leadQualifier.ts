/**
 * ДОСЬЕ ПОДСКАЗЫВАЕТ РОЛЬ, ПОКА ЭТОТ РАЗГОВОР ЕЩЁ НИЧЕГО НЕ СКАЗАЛ (§10.4 плана
 * от 20.09.2026). Без этого рекламщик, писавший месяц назад и получивший вежливый
 * отказ, при новом обращении снова проходит интейк с нуля: `draft.whoIsThis`
 * живёт только в рамках ОДНОГО разговора, а досье переживает их все.
 *
 * НАМЕРЕНИЕ ЭТОГО ХОДА ВСЕГДА СИЛЬНЕЕ. Подсказка из досье встаёт только когда в
 * разговоре ещё нет ни `whoIsThis`, ни `intent` — ровно первый ход(-ы) новой
 * переписки. Как только модель что-то классифицировала сама (в эту же секунду
 * или ходом позже), реальная классификация побеждает: продавец, заговоривший о
 * покупке, ведётся как покупатель с той же секунды, а не ждёт, пока досье
 * «согласится» (см. mergeDraft и тест «метка не отменяет намерения»).
 *
 * ТОЛЬКО НЕ-КЛИЕНТСКИЕ КАТЕГОРИИ (`isNonClientRole`), И НАМЕРЕННО. У BUYER/SELLER
 * из досье нет способа отличить «купить» от «снять» (categoryFromIntent сводит
 * оба intent="rent" и intent="buy" в одну BUYER) — подставить готовое намерение
 * значило бы рисковать: настоящему арендатору подставился бы сценарий покупки
 * вместо честного отказа. У рекламщика/застройщика такой развилки нет: сценарий
 * один и тот же независимо от повода, поэтому подсказка здесь безопасна, а
 * цена ошибки та же несимметричная, что и у всей этой системы ролей — лишний
 * вопрос стоит дешевле, чем плохо обслуженный клиент.
 */
export function resolveEffectiveWhoIsThis(
  draft: Pick<LeadDraft, "whoIsThis">,
  contactProfile: ContactProfileForPrompt | null | undefined,
  promptEconomyEnabled: boolean
): WhoIsThis | undefined {
  if (draft.whoIsThis) return draft.whoIsThis;
  if (!promptEconomyEnabled || !contactProfile) return undefined;
  const category = contactProfile.category;
  // `SPAM` — категория досье, но не входит в WHO_IS_THIS вовсе (см. botContract.ts):
  // спам не доходит досюда, вызов модели на него не делается никогда.
  return category !== "SPAM" && isNonClientRole(category as WhoIsThis) ? (category as WhoIsThis) : undefined;
}

export async function runQualifyTurn(
  history: ChatMessage[],
  draft: LeadDraft,
  // Умолчания `= {}` здесь больше нет намеренно: вместе с ним исчезала бы и
  // обязательность `abilities` (см. комментарий на месте бывшей ALL_ABILITIES).
  options: QualifyTurnOptions
): Promise<QualifyResult | null> {
  const memory = selectQualifierPromptMemory(history, draft, options);
  history = memory.history;
  draft = memory.draft;
  const scopedCustomer = options.customerContext !== undefined;
  const { images, scenarioId } = options;
  /**
   * ПРАВА ПО РОЛИ РАЗГОВОРА (ai/roleAbilities.ts). Только сужение и только при
   * включённом тумблере «Бот-специалист по типу обращения»: продавцу не уходит
   * поле показа и подборка чужих квартир, кандидату — фотографии объектов.
   * Тумблер выключен — права ровно те, что пришли, и схема прежняя побайтово.
   */
  // Подсказка из досье — только пока этот разговор ещё ничего не сказал сам
  // (resolveEffectiveWhoIsThis выше). Дальше везде вместо draft.whoIsThis.
  const effectiveWhoIsThis = resolveEffectiveWhoIsThis(draft, memory.contactProfile, options.abilities.promptEconomy);
  const { abilities, showcase } = abilitiesForIntent(
    options.abilities,
    options.showcase ?? NO_SHOWCASE,
    draft.intent,
    options.abilities.promptEconomy,
    effectiveWhoIsThis
  );
  // Рубильник темы: выключен или вовсе не передан — дальше ни одна строка промта и ни
  // одно поле схемы не меняются (регресс-щит проверяет это тестом).
  const topicSettings: TopicLockSettings = options.topic?.settings ?? { enabled: false, driftTurns: 1 };
  const topicState: TopicState = options.topic?.state ?? EMPTY_TOPIC_STATE;
  /**
   * ПРИЁМ ОБЪЕКТА: что продавец уже назвал — считает КОД, а не модель (ai/sellerIntake.ts).
   *
   * Только для продавца: покупателю блок ничего не сообщает, а токены стоит на каждом
   * сообщении. Черновик лида подмешивается к разбору реплик, потому что район и
   * комнатность модель уже разобрала в предыдущие ходы, и терять их здесь незачем;
   * этажа, состояния и цены собственника в черновике нет вовсе — они только отсюда.
   */
  const sellerFacts: SellerFacts | null =
    draft.intent === "sell"
      ? {
          ...collectSellerFacts(history),
          ...(draft.districtName ? { district: true as const } : {}),
          ...(draft.rooms ? { rooms: true as const } : {}),
        }
      : null;
  /**
   * ЧЕГО НЕ ХВАТАЕТ АНКЕТЕ КАНДИДАТА — тем же приёмом, что sellerFacts выше, но
   * источник другой: у продавца всё в истории чата, а у кандидата возраст/учёба/
   * работа/телефон копятся в JobApplication (lib/jobApplications.ts), не в
   * LeadDraft. Только для намерения job и только если рубильник «Вакансии»
   * включён — иначе запрос лишний: анкеты для этого диалога нет и не будет
   * (см. VACANCIES_DISABLED_RULE ниже).
   */
  // The live catalog is shared with CORE. Read failure is not "no vacancies";
  // let the normal turn failure handling report/retry the unavailable read.
  const recruitmentCatalog = abilities.vacancies ? await readCustomerOpenVacancies() : null;
  const recruitmentWords = history.filter(m => m.role === "user").slice(-3).map(m => m.content).join("\n");
  const recruitmentRole = recruitmentCatalog && selectedRecruitmentPosition(recruitmentCatalog.positions, recruitmentWords);
  const jobApplicationRow =
    memory.allowLegacyJobRead && draft.intent === "job" && abilities.vacancies && options.conversationId
      ? await prisma.jobApplication.findUnique({
          where: { conversationId: options.conversationId },
          select: { age: true, studyingNow: true, employedNow: true, phone: true },
        })
      : null;
  const jobIntakeBlock =
    draft.intent === "job" && abilities.vacancies && recruitmentRole?.key === "real-estate-agent"
      ? jobApplicationIntakeBlock(jobMissingFacts(jobApplicationRow ?? {}).filter(
          // A minimized current-inquiry flag needs no raw phone or old job row.
          // Legacy callers keep the original job missing-facts behavior.
          fact => memory.allowLegacyJobRead || !memory.phoneKnown || fact !== "телефон"
        ))
      : "";
  // Именем из профиля мессенджера (pushName) БОЛЬШЕ НЕ обращаемся — решение
  // владельца 18.08.2026 после жалобы клиента, который увидел в ответе бота своё
  // ФИО из профиля WhatsApp, хотя сам его боту не называл. Обращение разрешено
  // только тем именем, которое клиент САМ написал в переписке (см. replyGuards).
  const selfName = clientSelfStatedName(history);
  const nameLine = looksLikeRealName(selfName)
    ? `\n\nИмя клиента (сам назвал в переписке): ${selfName}. Имя можно назвать как есть, без родовых приставок; обращений по полу не используй.`
    : "";
  const lastClientText = [...history].reverse().find((m) => m.role === "user")?.content ?? "";
  /**
   * Места ищем не в одной последней реплике, а в трёх последних репликах клиента.
   * Причина — тот самый живой случай: клиентка назвала улицу Дехоти ОДИН раз, а
   * спрашивала про неё («кадом тарафда боша?») уже следующим сообщением, где
   * названия места нет вовсе. С 20.09.2026 список народных названий в промте
   * печатается только для мест, которых карта не знает (ai/folkPlaces.ts), и
   * узкое окно в одну реплику стало бы потерей знания, а не экономией.
   */
  const recentClientText = [...history]
    .filter((m) => m.role === "user")
    .slice(-3)
    .map((m) => m.content)
    .join("\n");
  const [propsBlock, learnedBlock, styleBlock, clientHours, money, geoBlock] = await Promise.all([
    // Подборка — по черновику, ДОПОЛНЕННОМУ разбором этой реплики (аудит поиска P0-2):
    // черновик модель обновит только в ответе, а «ищу двушку в Сино» в первом же
    // сообщении обязано дать варианты в этом же ходе. Разбор не удался — черновик как был.
    buyerQueryForTurn(draft, lastClientText)
      .catch(() => draft)
      .then((turnQuery) =>
        searchMatchingProperties(
          { ...draft, ...turnQuery },
          showcase,
          abilities.links,
          options.channel,
          abilities.promptEconomy && isNonClientRole(effectiveWhoIsThis),
          scopedCustomer
        )
      ),
    // Legacy learned text/examples can contain another customer's names or
    // exact addresses. Scoped input uses static rules until curated projection.
    scopedCustomer ? Promise.resolve("") : learnedRulesBlock(),
    // Образцы манеры живых агентов (просьба владельца 22.08.2026, см.
    // ai/styleLearning.ts). Отбираются по близости к тому, что клиент спросил
    // СЕЙЧАС, — поэтому блок переменный и уходит в изменяемую часть промта рядом
    // с выученными правилами, а не в кэшируемый префикс.
    scopedCustomer ? Promise.resolve("") : buildStyleBlock(lastClientText),
    // Часы для клиентов — один источник с голосом (ai/agencyFacts.ts::CLIENT_HOURS): по
    // ним и строка «часы работы», и срок обещанного звонка (callbackPromise).
    loadClientHours(),
    // Курс — ЖИВОЙ, из Настроек (ночью обновляется с alif.tj). В промте раньше
    // стояло «~11.3» литералом, и бюджет, записанный ботом в карточку, расходился
    // с бюджетом, по которому потом ищутся объекты (priceRangeBranches считает по
    // настоящему курсу): при 11,9 клиент с $50 000 получал 565 000 вместо 595 000
    // и не видел подходящие варианты. Идёт в переменную часть промта, а не в
    // кэшируемую: курс меняется раз в сутки, и ломать им кэш «личности» незачем.
    loadMoneyContext(),
    // Улица/ориентир/микрорайон, названные клиентом ИМЕННО СЕЙЧАС, — по
    // лицензированной карте города (ai/geoMentions.ts). Блок переменный по
    // построению: он про последнюю реплику, и в кэшируемую часть ему нельзя.
    geoMentionBlock(recentClientText, abilities.links),
  ]);
  // Промт разрезан на две части намеренно: стабильная «личность» бота уходит
  // кэшируемым блоком и переиспользуется между ВСЕМИ диалогами, а имя клиента,
  // черновик лида и подборка объектов меняются каждый ход — внутри кэш-блока они
  // ломали бы побайтовое совпадение префикса и делали кэш дороже его отсутствия.
  // Обязательные правила и география приклеиваются ПОВЕРХ промта из Настроек: если
  // владелец перепишет «личность» бота там, зашитые правила молча перестанут
  // действовать, а терять запрет на обращения по полу и умение узнавать жилые
  // комплексы нельзя. Оба блока стабильны — уходят в кэшируемую часть, а не в
  // переменную: платить за них на каждом ходе незачем.
  const [botPersona, baseGeography, sellerRules, folkGeography] = await Promise.all([
    resolveBotPersona(options.accountId),
    // Retain public city/folk geography, never the global private property list.
    scopedCustomer ? Promise.resolve("") : propertyGeographyBlock(),
    resolveSellerRules(),
    folkGeographyBlock(),
  ]);
  // Манера продажи — тоже стабильный блок: у диалога она одна на всю его жизнь, а
  // у сценария одна на все его диалоги. Значит платить за неё на каждом сообщении
  // незачем, и место ей рядом с «личностью» и географией, в кэшируемой части.
  // Приклеиваем в САМЫЙ конец стабильного блока, всегда одинаково: кэш Anthropic —
  // побайтовое совпадение префикса, и вставка в середину сбрасывала бы кэш всему,
  // что идёт после неё.
  // Порядок не случаен: сначала «личность» из Настроек, затем обязательные правила и
  // география, затем условия сделки, и последним — манера продажи из сравнения
  // сценариев. Манера может менять КАК бот говорит, но не может отменить условия
  // агентства: то, что идёт позже, не переписывает факты, а надстраивается над ними.
  const systemStable = buildStableSystem({
    botPersona,
    baseGeography,
    sellerRules,
    folkGeography,
    canSendGuide: showcase.canSendGuide,
    canBookShowings: abilities.showings,
    askOwner: abilities.askOwner,
    scenarioId,
    intent: draft.intent,
    whoIsThis: effectiveWhoIsThis,
    economy: abilities.promptEconomy,
  });
  /**
   * ЗАПОМИНАЕМ ОТДЕЛЬНОЙ ПЕРЕМЕННОЙ (14.09.2026, живая отладка голосовых
   * ответов) — печатается ДВАЖДЫ в этом же ходе, см. вторую вставку перед
   * topicDirective ниже.
   *
   * ЖИВОЙ СЛУЧАЙ: клиент трижды подряд писал явно по-русски (расшифровка
   * голосового подтверждала: детектор honestly отдавал "ru"), а модель всё
   * равно отвечала на таджикском. Причина — не код (языковой детектор
   * проверен отдельно и работает верно), а место в промте: инструкция стояла
   * здесь, у самого начала, а `styleBlock` (образцы живых агентов, почти
   * всегда таджикские) читается НАМНОГО позже — и по собственному комментарию
   * автора этого файла (см. styleBlock ниже: «всё, что читается ниже,
   * остаётся сильнее его») модель тянется к тому, что прочитала последним.
   * Решение — не переписывать architecture, а повторить короткую версию
   * инструкции ТАМ ЖЕ, где уже стоит topicDirective: единственное место в
   * этом промте, официально признанное «последним словом».
   */
  const languageDirective = languageLine(history);
  const system =
    nameLine +
    // Часы бота — ВНЕ любых рубильников (см. ai/conversationTime.ts): раньше дата
    // стояла только внутри блока показов, показы выключили, и бот начал называть
    // клиенту месяц из своего обучения.
    nowBlock(dushanbeWallClock()) +
    // Номер спрашиваем ВЕЗДЕ, включая WhatsApp (решение владельца 01.08.2026). С 31.07
    // здесь стоял запрет просить телефон у того, кто пишет со своего же номера, — и
    // рассуждение было верным ровно наполовину. Номер, С КОТОРОГО человек пишет, и
    // номер, ПО КОТОРОМУ он просит перезвонить, совпадают не всегда: пишут с рабочего,
    // просят звонить на личный, пишут с своего за родственника. Молча забрав wa_id, мы
    // отдавали агенту телефон, по которому клиента может не оказаться. Плюс сам вопрос
    // был единственным согласием на звонок — раньше его давал набранный номер.
    languageDirective +
    TIME_AWARENESS_RULE +
    // Часы работы — та же фраза, что у голоса (ai/agencyFacts.ts::clientHoursSentence, P1-2).
    chatHoursBlock(clientHours) +
    `\n\nКУРС ДОЛЛАРА: 1 USD = ${money.usdToTjs} TJS. Пересчитывай долларовые суммы в сомони только по нему.` +
    `\n\nТЕКУЩЕЕ СОСТОЯНИЕ ДИАЛОГА (что уже собрано, НЕ переспрашивай): ${JSON.stringify(draft)}` +
    // Телефона в состоянии диалога нет вовсе (см. phoneKnown в QualifyTurnOptions),
    // поэтому про него говорим отдельной строкой — иначе модель просит номер,
    // который человек дал час назад.
    (memory.phoneKnown
      ? "\nРАҚАМИ ТЕЛЕФОН АЛЛАКАЙ ДАР МО ҲАСТ. Телефон клиента У НАС УЖЕ ЕСТЬ: просить номер снова " +
        "СТРОГО ЗАПРЕЩЕНО, даже если разговор начался заново. Отвечай по существу того, что он спросил, и " +
        "не приписывай к ответу дежурную фразу про звонок агента."
      : "") +
    // Досье собеседника — СРАЗУ за состоянием текущего диалога: сначала «что уже
    // собрано сейчас», потом «что мы знаем о нём вообще». Обратный порядок читался
    // бы как «вот его бюджет», и модель брала бы прошлый бюджет за нынешний.
    contactProfileBlock(memory.contactProfile) +
    // Что продавец уже назвал про свой объект — посчитано КОДОМ по его репликам, а не
    // взято из памяти модели: ровно на этом бот и спотыкался, переспрашивая площадь и
    // этаж следом за сообщением «2 етаж, 360 квадрат» (см. ai/sellerIntake.ts).
    // Покупателю блок не печатается: ему он ничего не значит, а токены стоит.
    (sellerFacts ? sellerIntakeBlock(sellerFacts) : "") +
    // Чего не хватает анкете кандидата — посчитано кодом по JobApplication, не по
    // памяти модели (см. jobApplicationRow/jobIntakeBlock выше). Пусто, если
    // намерение не job или анкета уже полная — печатать тогда нечего.
    jobIntakeBlock +
    // Тема и незакрытый вопрос — рядом с состоянием диалога и строго здесь, в
    // ИЗМЕНЯЕМОЙ части: они меняются каждый ход, и внутри кэшируемого префикса
    // ломали бы побайтовое совпадение (см. ai/topicLock.ts).
    topicStateBlock(topicState, topicSettings) +
    propsBlock +
    // Правила показа — сразу ПОСЛЕ подборки объектов: в них ссылки на «№N» из
    // этого блока, и порядок «сначала объекты, потом что с ними делать» читается
    // моделью так же, как человеком. Выключенные показы убирают блок целиком и
    // ставят вместо него объяснение, что этим займётся агент: без объяснения
    // модель всё равно спрашивает «когда вам удобно приехать».
    // Второй аргумент — тот самый `leadAccepted` (см. showingPromptBlock): с ним
    // блок показов перестаёт безусловно требовать номер у того, чей телефон уже
    // наш. До 22.09.2026 сюда не передавалось ничего, и запрет внутри блока был
    // мёртвым кодом — он не мог сработать ни при каких настройках.
    (abilities.showings ? showingPromptBlock(new Date(), memory.phoneKnown) : SHOWINGS_DISABLED_RULE) +
    // Ползунки владельца: каждый убирает/добавляет и действие, и кусок промта —
    // флаг, который гасит действие, но оставляет обещание, хуже отсутствия флага.
    // Рубильник выбирает не наличие правила, а его содержание: с дежурным оператором
    // бот вправе обещать звонок сию минуту, без него — честное «агент свяжется» плюс
    // вопрос по теме, из которого выйдет обычная заявка (см. ai/callbackRequest.ts).
    // Срок звонка — одно решение с голосом (ai/agencyFacts.ts::callbackPromise, 10.10.2026).
    (abilities.callback
      ? callbackPromptRule(callbackPromise(new Date(), clientHours))
      : callbackAsLeadPromptRule(callbackPromise(new Date(), clientHours))) +
    (abilities.vacancies ? "" : VACANCIES_DISABLED_RULE) +
    (abilities.links ? "" : LINKS_DISABLED_RULE) +
    // Выводы из случаев, где бот уже ошибался (см. lib/botLessons.ts). Идут в
    // изменяемую часть промта, а не в кэшируемую: список пополняется каждую ночь,
    // и внутри кэш-блока он ломал бы побайтовое совпадение префикса.
    // Карта города про место из последней реплики — ВЫШЕ образцов манеры и
    // правил тона: это факты, и спорить с ними тону не о чем.
    geoBlock +
    learnedBlock +
    // Образцы живых агентов — сразу за выученными правилами и ДО режима запуска:
    // это тон, а не правило, и всё, что читается ниже, остаётся сильнее его.
    styleBlock +
    // Живой сотрудник уже отвечал в этом разговоре — бот обязан это видеть
    // (владелец 22.08.2026, см. HUMAN_REPLY_AWARENESS_RULE). Печатается только
    // когда такие реплики в истории есть.
    (hasHumanReplies(history) ? HUMAN_REPLY_AWARENESS_RULE : "") +
    // Режим запуска — ПОСЛЕ выученных правил и ПЕРЕД заданием на ход: он объявляет
    // себя сильнее правил тона, и стоять должен ниже их, чтобы модель прочла его
    // последним из общих правил.
    (abilities.cautious ? CAUTIOUS_MODE_RULE : "") +
    // «Не могу открыть видео» говорится ОДИН раз (см. ai/mediaApology.ts). Предписание
    // на этот ход, поэтому стоит рядом с заданием темы, а не среди общих правил.
    mediaApologyDirective(history) +
    // ПОВТОР языковой инструкции — здесь, а не только у начала промта (см.
    // докстринг у languageDirective выше): это самое сильное место в промте
    // по собственному признанию автора файла (topicDirective ниже — «иначе
    // тонет среди сотни строк»), а язык ответа важнее темы разговора.
    languageDirective +
    // САМЫМ ПОСЛЕДНИМ — распоряжение про этот конкретный ход: вернуть клиента к
    // незакрытому вопросу. Общие правила выше, задание на ход внизу, иначе оно тонет
    // среди сотни строк ровно так же, как тонула просьба «держи тему».
    topicDirective(topicState, topicSettings) +
    // Поправка повторного хода — ещё ниже задания темы: она про этот же ход и
    // отменяет только что отвергнутый вариант (см. retryDirective в опциях).
    (options.retryDirective ?? "") +
    (recruitmentCatalog ? legacyRecruitmentCatalogBlock(recruitmentCatalog, recruitmentWords) : "");

  const rawResult = await callAiText<unknown>({
    endpoint: "lead-qualify",
    systemStable,
    system,
    // Разрывы во времени подмешиваются в текст реплик: без них разговор
    // трёхмесячной давности неотличим от начатого минуту назад (conversationTime.ts).
    messages: withTimeGaps(markHumanRepliesForModel(maskHistoryForModel(history.slice(-MAX_HISTORY_TO_MODEL)))),
    images,
    maxTokens: 500,
    schema: qualifySchema(showcase.canSendPhotos, showcase.canSendGuide, abilities, topicSettings.enabled),
    conversationId: options.conversationId,
  });
  // Validate the whole external result before guards, state merges or actions.
  // The shared boundary preserves string-to-bubbles compatibility without
  // silently dropping invalid members or coercing action flags and numbers.
  if (rawResult == null) return null;
  const parsedResult = submitReplySchema({
    ...abilities, canSendPhotos: showcase.canSendPhotos,
    canSendGuide: showcase.canSendGuide, topicLock: topicSettings.enabled,
  }).safeParse(rawResult);
  traceModelValidation(rawResult, parsedResult.success ? [] : parsedResult.error.issues);
  if (!parsedResult.success) {
    // Only schema codes and known field paths; never log model values or unknown key names.
    const issues = parsedResult.error.issues.slice(0, 8)
      .map((issue) => `${issue.path.join(".") || "root"}:${issue.code}`).join(", ");
    void logSystemError("ai", `submit_reply: invalid result (${issues})`);
    return null; // All channels already persist/retry provider failures before applying actions.
  }
  const result = parsedResult.data;

  /**
   * СВЕРКА ЦЕН — здесь, а не в диалоговом слое: только тут в руках одновременно
   * блок объектов из промта, вся история и курс. Названная клиенту цена обязана
   * существовать в одном из источников (подробности — ai/priceGuard.ts); выдумка
   * вырезается предложением и попадает в журнал, чтобы её видели люди.
   *
   * Историю отдаём целиком: цены, вычитанные ВНУТРИ присланных клиентом файлов,
   * щит выбросит из белого списка сам — он же и знает про границы недоверенного
   * содержимого (ai/untrustedContent.ts).
   */
  if (result?.reply?.length) {
    let traceBefore = result.reply.join("\n");
    const guarded = guardPrices({
      bubbles: result.reply,
      allowedText:
        propsBlock +
        (recruitmentCatalog ? "\n" + JSON.stringify(recruitmentCatalog.positions.map(row => ({ detailsRu: row.detailsRu, detailsTg: row.detailsTg }))) : "") +
        "\n" +
        history.map((m) => m.content).join("\n") +
        "\n" +
        JSON.stringify(draft ?? {}),
      usdToTjs: money.usdToTjs,
    });
    if (guarded.invented.length > 0) {
      void logSystemError(
        "ai",
        guarded.keptDespiteViolation
          ? `Бот назвал цену, которой нет в данных (${guarded.invented.join(", ")}), и вычистить её без потери ответа не вышло — клиенту ушла безопасная заглушка вместо выдумки. Проверьте диалог глазами.`
          : `Бот выдумал цену (${guarded.invented.join(", ")}) — предложение с ней вырезано из ответа клиенту.`
      );
    }
    // Сумма совпала с каталогом, а валюта нет («1 000 000 сомони» → «1 000 000
    // долларов»). Пока ТОЛЬКО НАБЛЮДЕНИЕ (AI-GUARD02): ответ не режем, чтобы замерить
    // ложные срабатывания; вырезание включается флагом enforceCurrency в guardPrices.
    if (guarded.currencyMismatch.length > 0) {
      void logSystemError(
        "ai",
        `[щит цены, наблюдение] В ответе бота сумма (${guarded.currencyMismatch.join(", ")}) совпала с данными, ` +
          `но валюта названа другая. Ответ ушёл как есть — проверьте диалог глазами.`
      );
    }
    // keptDespiteViolation значит «чистка съела весь ответ, щит вернул исходный
    // текст» — а в исходном тексте живёт цена, которой нет ни в одном источнике.
    // Отправлять её клиенту как факт нельзя (прод-инцидент 16.09.2026, см.
    // priceGuardFallbackReply выше): подставляем заглушку вместо неё.
    result.reply = guarded.keptDespiteViolation ? priceGuardFallbackReply(lastClientLanguage(history)) : guarded.bubbles;
    traceFilterDelta("qualifier_guards", traceBefore, result.reply.join("\n"), "price");
    traceBefore = result.reply.join("\n");

    // Та же сверка, но для размера скидки: SALES_PLAYBOOK запрещает называть
    // процент торга, а промт — просьба, а не гарантия (см. ai/priceGuard.ts).
    const discountGuarded = guardDiscounts(result.reply);
    if (discountGuarded.invented.length > 0) {
      void logSystemError(
        "ai",
        discountGuarded.keptDespiteViolation
          ? `Бот назвал размер скидки (${discountGuarded.invented.join(", ")}%), хотя это запрещено, и вычистить без потери ответа не вышло — клиенту ушла безопасная заглушка вместо выдумки. Проверьте диалог глазами.`
          : `Бот назвал запрещённый размер скидки (${discountGuarded.invented.join(", ")}%) — предложение с ней вырезано из ответа клиенту.`
      );
    }
    result.reply = discountGuarded.keptDespiteViolation
      ? priceGuardFallbackReply(lastClientLanguage(history))
      : discountGuarded.bubbles;
    traceFilterDelta("qualifier_guards", traceBefore, result.reply.join("\n"), "discount");
    traceBefore = result.reply.join("\n");

    /**
     * УЛИЦА, ПЛОЩАДЬ, ЭТАЖ ВНЕ ПОДБОРКИ — ТОТ ЖЕ СТОРОЖ, ЧТО У ГОЛОСА (ai/catalogClaimsGuard.ts,
     * аудит 10.10.2026, P1-6). Раньше чат сверял одни цены, и «87 м², 15 этаж» из головы
     * модели в WhatsApp не ловились. Пока ТОЛЬКО ЖУРНАЛ, как у голоса: вырезать площадь или
     * этаж из фразы без потери смысла щит не умеет, а ложные срабатывания сначала надо
     * замерить. Цены здесь не повторяем — их уже снял guardPrices выше. Продавцу и
     * кандидату подборки нет: он называет свой объект, сверять не с чем.
     */
    if (draft.intent !== "sell" && draft.intent !== "job") {
      const claims = findOffCatalogClaims({
        text: result.reply.join("\n"),
        allowedText: propsBlock + "\n" + history.map((m) => m.content).join("\n"),
        catalogText: `${propsBlock}\n${geoBlock}\n${folkGeography}`,
        clientText: history
          .filter((m) => m.role === "user")
          .map((m) => m.content)
          .join("\n"),
        usdToTjs: money.usdToTjs,
      });
      const what = [
        claims.streets.length > 0 ? `улицы/ориентиры ${claims.streets.join(", ")}` : "",
        claims.areas.length > 0 ? `площадь ${claims.areas.join(", ")} м²` : "",
        claims.floors.length > 0 ? `этаж ${claims.floors.join(", ")}` : "",
      ].filter(Boolean);
      if (what.length > 0) {
        void logSystemError(
          "ai",
          `Бот назвал вне подборки: ${what.join("; ")} — этого нет ни в подборке объектов, ни в словах клиента. ` +
            "Ответ ушёл как есть — проверьте диалог глазами.",
          { dedupKey: "chat-off-catalog-claim", dedupScope: options.conversationId ?? undefined }
        );
      }
    }

    /**
     * ОБЕЩАНИЕ ВАРИАНТОВ ПРИ ПУСТОЙ ПОДБОРКЕ — ТРЕТИЙ РУБЕЖ, ВКЛЮЧЁН 22.08.2026.
     *
     * Сам щит написан 15.08.2026 под живой случай первого дня трафика (подробности
     * и разбор — в шапке ai/availabilityGuard.ts: «в этом бюджете есть отличные
     * варианты» при полном отсутствии блока объектов), у него был свой тест — а
     * вызова не появилось НИ ОДНОГО: аудит 22.08.2026 нашёл `applyAvailabilityGuard`
     * импортированным в этом файле и не вызванным нигде во всём проекте. Семь дней
     * самая дорогая ложь из возможных держалась только на просьбе в промте, ровно
     * там, где промт уже один раз не сработал.
     *
     * Признак наличия — БЫЛ ЛИ БЛОК ОБЪЕКТОВ В ПРОМТЕ, а не «есть ли что-то в базе
     * вообще»: пустой propsBlock значит, что перед глазами у модели не было ни
     * одного объекта, и любое «подберём»/«вариантҳо дорем» она взяла из воздуха.
     */
    //
    // Продавцу и кандидату подборку не строят вовсе (searchMatchingProperties), и
    // щит на них срабатывал всегда: «Ҳуҷҷатҳои хона ҳаст?» продавцу уходило как
    // «Ҳоло вариантҳои мувофиқ надорем» (02.10.2026). Обещать им варианты бот и
    // не может — разговор не о подборке.
    const noCatalogTalk = draft.intent === "sell" || draft.intent === "job";
    result.reply = applyAvailabilityGuard(
      result.reply,
      propsBlock.trim().length > 0 || noCatalogTalk,
      lastClientLanguage(history)
    );
    traceFilterDelta("qualifier_guards", traceBefore, result.reply.join("\n"), "availability");
    traceBefore = result.reply.join("\n");

    // Повторное «не открылось» вырезаем ПОСЛЕ сверки цен: обе правки работают с
    // готовыми пузырями, порядок между ними безразличен (см. ai/mediaApology.ts).
    result.reply = stripRepeatedMediaApology(result.reply, history);
    traceFilterDelta("qualifier_guards", traceBefore, result.reply.join("\n"), "media_apology");
  }

  /**
   * ВОПРОС ПРО УЖЕ НАЗВАННОЕ СНИМАЕТСЯ КОДОМ.
   *
   * openQuestion — это не только подсказка модели: код сам дописывает его клиенту
   * (ensureOpenQuestionKept в ai/replyGuards.ts) и держит тему вокруг него. Значит
   * вопрос про этаж, заданный после «2 етаж», вернулся бы к человеку ещё дважды уже
   * нашими руками. Проще всего не дать ему стать незакрытым вопросом вовсе.
   */
  if (result && sellerFacts && topicSettings.enabled) {
    const raw = (result as { openQuestion?: unknown }).openQuestion;
    if (typeof raw === "string" && asksKnownSellerFact(raw, sellerFacts)) {
      (result as { openQuestion?: string }).openQuestion = "";
    }
  }

  // Номер объекта приходит от модели, то есть снаружи: приводим к числу или к null
  // здесь, чтобы дальше по ходу его никто не проверял заново (см. ai/photoOffer.ts).
  return result
    ? {
        ...result,
        showPropertyNumber: parsePhotoOffer(result.showPropertyNumber),
        askOwner: abilities.askOwner ? parseAskOwner((result as { askOwner?: unknown }).askOwner) : null,
        callbackRequest: parseCallbackRequest((result as { callbackRequest?: unknown }).callbackRequest),
        jobApplication: abilities.vacancies
          ? parseJobApplication((result as { jobApplication?: unknown }).jobApplication)
          : null,
        // Тема разбирается здесь по той же причине: за пределами этой функции никто
        // не должен гадать, что именно вернула модель в topic/openQuestion.
        sendGuide: parseGuideOffer((result as { sendGuide?: unknown }).sendGuide),
        topicAnswer: topicSettings.enabled ? parseTopicAnswer(result) : null,
      }
    : null;
}

