/**
 * «Соедините с оператором» / «пусть мне позвонят» — поле инструмента и правило промта.
 *
 * Тот же приём, что у «уточню у собственника» (ai/askOwner.ts): обещание клиенту
 * превращается в ПОЛЕ СХЕМЫ, а не остаётся фразой. Поле модель либо заполнила, либо
 * нет — «почти выполнить» его нельзя, и просьба о звонке больше не может утонуть в
 * переписке.
 *
 * ДВА РЕЖИМА, ОДНО ПОЛЕ (владелец 23.08.2026). Поле в схеме есть ВСЕГДА — сам факт
 * «человек просит звонок» ценен независимо от того, кто будет звонить. Различается
 * только то, что с ним делает код (см. messengers/conversation.ts):
 *
 *  • Рубильник Настройки → Бот → «Соединять с оператором» ВКЛЮЧЁН — есть колл-центр
 *    или дежурный оператор: запрос живёт отдельной записью (lib/callbackRequests.ts),
 *    АТС набирает дежурного и соединяет с клиентом, очередь видна баннером.
 *  • ВЫКЛЮЧЕН (так сейчас) — отдельного оператора нет, и просьба о звонке это
 *    ОБЫЧНЫЙ ЛИД: бот выясняет, по какому вопросу звонить, берёт номер и оформляет
 *    заявку общим порядком — с распределением на агента, кнопкой «Принять» и
 *    пометкой в карточке. Никакой параллельной очереди и никакого баннера.
 *
 * Почему не удалили выключённую половину: оператор появится (владелец 23.08.2026 —
 * «будет колл-центр, и с сайта кнопка „перезвоните мне“ пойдёт по этой же системе»),
 * а построенное авто-соединение работает. Рубильник дешевле, чем написать это заново.
 *
 * ОПЕРАТОРУ — ТОЛЬКО ВХОДЯЩИЕ АТС (владелец 22.09.2026). Дежурный оператор получает
 * лишь прямые входящие незнакомых номеров на городской. Всё из соцсетей и
 * мессенджеров — агентам: при включённом рубильнике просьба из переписки уходит
 * назначенному агенту клиента (запись + пуш, без автодозвона через АТС), а без
 * агента — обычной заявкой в раздачу, как при выключенном.
 */

