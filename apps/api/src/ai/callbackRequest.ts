/**
 * Правило для промта. Как и у askOwner, главное — вторая половина: обещание должно
 * прозвучать в том же сообщении, где заполнено поле, иначе клиент ждёт неизвестно чего.
 *
 * ОБЕЩАНИЕ ЗАВИСИТ ОТ ВРЕМЕНИ (владелец 16.08.2026) — и с 10.10.2026 решается ОДНОЙ
 * функцией на чат и голос (ai/agencyFacts.ts::callbackPromise, аудит «одно окно», P1-1):
 * «сегодня», «сегодня после …», «завтра после …», «в понедельник после …» с учётом
 * выходных из Настроек (с 11.10.2026; до этого — зашитого воскресенья). «Прямо сейчас» больше не обещаем: с 22.09 просьба из переписки идёт
 * агенту пушем, без автодозвона через АТС, и «в ближайшие минуты» не держалось.
 */
export function callbackPromptRule(promise: CallbackPromise): string {
  return (
    "\n\nПРОСЯТ ЖИВОГО ЧЕЛОВЕКА ИЛИ ЗВОНОК — СРАЗУ СОГЛАШАЙСЯ. Клиент пишет «соедините с оператором», " +
    "«позвоните мне», «занг занед», «оператор ҳаст?» — не отговаривай и не продолжай переписку сам. " +
    "Заполни поле callbackRequest (по какому вопросу звонить) И в том же сообщении скажи, когда позвонит агент. " +
    callbackPromiseLine(promise) +
    " Если номера клиента ещё нет — попроси его в этом же сообщении: без номера звонить некуда."
  );
}

/**
 * ТО ЖЕ, НО БЕЗ ДЕЖУРНОГО ОПЕРАТОРА — просьба о звонке становится обычной заявкой.
 *
 * Разница с callbackPromptRule — вопрос, ПО КАКОМУ ВОПРОСУ, если это ещё не ясно из
 * разговора. Агенту достаётся карточка, а не строчка «просил перезвонить»: без темы он
 * звонит вслепую и начинает разговор с «а вы по какому вопросу?» — ровно того, что
 * клиент уже написал боту. Срок звонка — то же общее решение (callbackPromiseLine).
 *
 * Один вопрос, не анкета: тема + номер. Всё остальное агент выяснит голосом — за
 * этим человек и просил звонок.
 */
export function callbackAsLeadPromptRule(promise: CallbackPromise): string {
  return (
    "\n\nПРОСЯТ ЖИВОГО ЧЕЛОВЕКА ИЛИ ЗВОНОК — СРАЗУ СОГЛАШАЙСЯ. Клиент пишет «соедините с оператором», " +
    "«позвоните мне», «занг занед», «оператор ҳаст?» — не отговаривай и не продолжай переписку сам. " +
    "Заполни поле callbackRequest (по какому вопросу звонить) и в том же сообщении скажи, когда позвонит агент. " +
    callbackPromiseLine(promise) +
    " Звонит живой агент. " +
    "Если из разговора ЕЩЁ НЕ ЯСНО, по какому вопросу звонить, — одной короткой фразой спроси об этом " +
    "(«Дар бораи чӣ занг занем: харид, фурӯш ё оид ба хонаи мушаххас?»). Если вопрос уже понятен — " +
    "второй раз не переспрашивай. " +
    "Если номера клиента ещё нет — попроси его в этом же сообщении: без номера звонить некуда. " +
    /**
     * ПОРЯДОК ВАЖНЕЕ ПОЛНОТЫ (проверено на проде 23.08.2026). Общее правило требует
     * просить номер И имя одной фразой — вместе с вопросом о теме это три просьбы в
     * одном сообщении, и модель молча выкидывала как раз тему. Имя при этом НЕ
     * теряется: код переспросит его отдельным ходом в момент приёма заявки (см.
     * acceptLead в messengers/conversation.ts).
     */
    "ПОРЯДОК, ЕСЛИ ТЕМА НЕЯСНА: в этом сообщении спроси ТОЛЬКО тему и номер, а имя НЕ спрашивай — " +
    "три просьбы в одной фразе читаются как анкета, и имя мы всё равно уточним следующим шагом. " +
    "Тема звонка важнее имени: без неё агент звонит вслепую."
  );
}

/**
 * Просьба из ответа модели или null. Пустяки («да», пробелы) отсекаются: пустая
 * карточка звонка тратит время агента и приучает не читать очередь.
 */
export function parseCallbackRequest(value: unknown): string | null {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  if (trimmed.length < 5) return null;
  return trimmed.slice(0, 500);
}

/**
 * ЯВНАЯ ПРОСЬБА О ЗВОНКЕ В СЛОВАХ САМОГО КЛИЕНТА (22.09.2026, баг на проде).
 *
 * Модель засчитывала просьбой о звонке ЛЮБОЙ оставленный номер: за день 14 ложных
 * срабатываний (продажа дачи, ролик, спам веб-студии, вакансия), и каждое набирало
 * оператора через АТС. Поле модели теперь только кандидат: засчитываем его, лишь
 * если в реплике клиента есть явный маркер (ру/тадж). Сам номер маркером НЕ является.
 * Границы слов — через ai/wordBoundary.ts: `\b` по кириллице молчит.
 */
const EXPLICIT_CALLBACK_MARKERS: readonly RegExp[] = [
  // позвоните / перезвоните / звоните / позвонят / наберите / свяжитесь
  new RegExp(`${BW}(пере|по)?звон(и|ите|ить|ят|ю)${EW}`, "iu"),
  new RegExp(`${BW}набер(и|ите)${EW}`, "iu"),
  new RegExp(`${BW}свяжи(те)?сь${EW}`, "iu"),
  // живой человек / оператор / менеджер
  new RegExp(`${BW}(оператор|менеджер)${TAIL}`, "iu"),
  new RegExp(`${BW}(жив${TAIL}|реальн${TAIL})\\s+(человек|сотрудник|агент)${TAIL}`, "iu"),
  new RegExp(`${BW}(ты|вы|это)\\s+бот${EW}`, "iu"),
  new RegExp(`${BW}(шумо|ту)\\s+бот${TAIL}`, "iu"),
  // таджикский: занг занед / занг занад / занг занам / занг мезанед / занг кунед
  new RegExp(`${BW}занг\\s+(зан|мезан|кун|задан)${TAIL}`, "iu"),
  new RegExp(`${BW}zang\\s+(zan|mezan|kun)${TAIL}`, "iu"),
  new RegExp(`${BW}одам(и|ӣ)?\\s+зинда${EW}`, "iu"),
  new RegExp(`${BW}(call\\s+me|operator|manager)${EW}`, "iu"),
];

export function hasExplicitCallbackAsk(clientText: string | null | undefined): boolean {
  if (!clientText) return false;
  const text = clientText.normalize("NFC");
  // Два набора маркеров, и оба нужны: здешний ловит «свяжитесь», «ты бот?»,
  // латиницу («zang zaned»); ai/operatorHandoff.ts — «тамос гиред», «соедините»,
  // и он же снимает врезки из присланных файлов и заметок CRM, чтобы просьбой не
  // считалось то, что клиент не писал. Объединение строго безопаснее любого из
  // них по отдельности: оставленный номер не проходит ни там, ни там.
  return (
    EXPLICIT_CALLBACK_MARKERS.some((re) => re.test(text)) || clientAskedForCallback([text])
  );
}

/**
 * Итог хода: поле модели засчитывается только при явной просьбе в реплике клиента
 * и никогда — в разговоре кандидата на вакансию (там свой путь, lib/jobApplications.ts).
 */
export function acceptCallbackRequest(
  modelTopic: string | null | undefined,
  clientText: string | null | undefined,
  opts: { isJobApplication?: boolean } = {}
): string | null {
  if (!modelTopic || opts.isJobApplication) return null;
  return hasExplicitCallbackAsk(clientText) ? modelTopic : null;
}
