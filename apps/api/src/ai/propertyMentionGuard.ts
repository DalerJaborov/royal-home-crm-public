import { BW, EW } from "./wordBoundary.js";

/**
 * КЛИЕНТ НАЗВАЛ НОМЕР ОБЪЕКТА — РАСПОЗНАЁТ КОД, В ЧАТЕ (23.09.2026, пункт 8
 * списка владельца после публикаций, реализуется по факту решения владельца:
 * «код агента не надо, код объекта ставить номер типа объект номе 112, а не
 * 00112»). Подписи под постами теперь несут простой номер объекта — тот же
 * shortId, что виден в самой карточке («/properties/112») — а бот в переписке
 * ни разу этот номер из слов клиента не читал: BotConversation.adPropertyId
 * (клик по конкретному посту) используется ТОЛЬКО как подсказка модели
 * (ai/leadQualifier.ts propertyLink), а не как сигнал для лесенки назначения агента
 * (services/leads/assignment.ts::pickByExplicitProperty). Со звонка и с сайта
 * (по ссылке страницы, `resolveCallPropertyHint`) правило «объект назван явно»
 * уже есть — здесь тот же путь для чата: слова клиента → номер → propertyId.
 *
 * ПОЧЕМУ НУЖЕН ПОВОД, А НЕ ГОЛОЕ ЧИСЛО. Число в переписке о квартире встречается
 * почти в каждой реплике («3 хона», «700 хазор», «5 этаж», «82 мкр») — если ловить
 * любую цифру, клиент, назвавший этаж или бюджет, уйдёт агенту чужого объекта.
 * Поводом служит слово «объект»/«обьект» рядом с числом или знак «№» — именно
 * так подписаны посты, и именно так, скорее всего, скопирует его клиент.
 *
 * ПОЧЕМУ НЕ «112-Й». Порядковая форма («3-й этаж», «5-й микрорайон») в переписке
 * о квартире звучит намного чаще, чем номер объекта, и с тем же самым «-й» —
 * ловить её значило бы путать этаж с номером карточки почти на каждом ходе.
 * Владелец назвал только «объект/номер/№» как реальный формат подписи — этого
 * и придерживаемся.
 */

/** «Объект» и типичные опечатки/варианты написания того же слова. */
const OBJECT_WORD = `${BW}(?:объект|обьект|обект)\\p{L}*`;
/** Необязательное «№»/«номер»/«ном.» между словом «объект» и самим числом. */
// «под номером», «рақами» (таджикское «номер») — тоже повод (ревизия 02.10.2026).
const NUMBER_CUE = "(?:№|н[оа]мер\\p{L}*|ном\\.?|под\\s+номером|рақам\\p{L}*)?";
const NUMBER = `${BW}(\\d{1,7})${EW}`;
/** Код с карточки сторис и карточки объекта: «ОБ-000118» (lib/video/storyCard.ts). */
const OB_CODE = `${BW}(?:об|ob)-?(\\d{3,7})${EW}`; // «об 3-комнатной» — предлог, не код

const RX = new RegExp(
  `${OBJECT_WORD}\\s*${NUMBER_CUE}\\s*${NUMBER}` + `|` + `№\\s*${NUMBER}` + `|` + OB_CODE,
  "iu"
);

/**
 * «№» В АДРЕСЕ — НЕ НОМЕР ОБЪЕКТА (ревизия 02.10.2026). «Продаю квартиру в доме №25»,
 * «ул. Рудаки 45, кв. №12» читались как объект 25 и 12: заявка уходила агенту чужого
 * объекта и запиралась за ним. Голый «№» засчитываем, только если перед ним нет
 * адресного слова.
 */
// «квартира №N» — это как раз наш объект («интересует квартира №118»), поэтому
// здесь только адресные слова и их сокращения: «кв. №12», «д. №5», «ул.».
const ADDRESS_BEFORE = new RegExp(
  `(?:${BW}(?:дом|улиц|микрорайон|корпус|подъезд|школ|гимназ|бино|кӯча|куча|маҳалл)\\p{L}*|${BW}(?:д|кв|ул|мкр|корп)${EW}\\.?)\\s*$`,
  "iu"
);

/**
 * Номер объекта, если клиент назвал его своими словами («объект 112», «объект
 * №112», «№112», «объект номер 112»). `null`, если повода нет — тогда решение
 * остаётся обычной лесенке (services/leads/assignment.ts).
 */
export function extractMentionedPropertyNumber(clientText: string): string | null {
  const text = clientText.trim();
  if (!text) return null;
  const match = RX.exec(text);
  if (!match) return null;
  if (match[2] && ADDRESS_BEFORE.test(text.slice(0, match.index))) return null;
  const digits = match[1] ?? match[2] ?? match[3] ?? null;
  // «ОБ-000118» — это объект 118: ведущие нули не часть номера.
  return digits ? String(Number(digits)) : null;
}
