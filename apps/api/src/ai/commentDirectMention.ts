/**
 * «НАПИСАЛИ ВАМ В ДИРЕКТ» — ТОЛЬКО КОГДА ЛИЧНОЕ ПРАВДА УШЛО (разбор суток 23.11.2026, K8: под постом Facebook бот написал
 * «Ба директ навиштем 📩 Чандхонагӣ ва дар кадом тарафи шаҳр меҷӯед?», а личное не ушло — `dm_failed`, 7 из 7 за сутки).
 *
 * Публичный ответ модели часто начинается с «написали вам в директ». Порядок теперь такой: сначала личное, потом публичный
 * ответ (messengers/comments.ts); личное не ушло (или его и не было) — из публичного ответа вырезаются куски о директе, а
 * если от ответа ничего не осталось — вызывающий берёт нейтральный текст без директа. Чистые функции.
 */
/** Упоминание личных сообщений: «директ», «в личку», «в личные», «написали вам», «ба директ», «паёми шахсӣ», латиница. */
const DIRECT_MENTION = /(?<![\p{L}])(?:директ\p{L}*|дайрект\p{L}*|direct\p{L}*|dm|лс|личк\p{L}*|личн(?:ые|ое|ых|ом|ым|ую)(?:\s+сообщ\p{L}*)?|в\s+личн\p{L}*|написал[аи]?\s+вам|ответил[аи]?\s+вам\s+в|паём(?:и)?\s+шахс\p{L}*|шахсӣ|шахси)(?![\p{L}])/iu;
/** Значок письма — граница смысловой части («Ба директ навиштем 📩 Чандхонагӣ…» — без точки между частями). */
const SEGMENT_SPLIT = /(?<=[.!?…])\s+|\s*[📩📨✉️💌📬📥]️?\s*/u;

export function mentionsDirect(text: string): boolean {
  return DIRECT_MENTION.test(text);
}

/** Публичный ответ без кусков о личных сообщениях; пусто — от ответа ничего не осталось. */
export function withoutDirectMention(text: string): string {
  return text.split(SEGMENT_SPLIT).map(part => part.trim()).filter(part => part && !DIRECT_MENTION.test(part)).join(" ")
    .replace(/\s{2,}/gu, " ").trim();
}
