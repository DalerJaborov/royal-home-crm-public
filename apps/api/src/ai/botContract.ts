/**
 * ФОРМА ДОГОВОРА КВАЛИФИКАТОРА — что боту разрешено и о чём идёт разговор.
 *
 * Жило в `ai/leadQualifier.ts`, откуда эти два описания читали все подряд.
 * Вынесено 21.09.2026, когда права стали сужаться по роли собеседника
 * (`ai/roleAbilities.ts`): тот модуль обязан знать форму прав, а квалификатор —
 * знать про роли, и оставь описания на месте, получился бы цикл импортов,
 * который сторож зависимостей заворачивает (и правильно делает: порядок
 * инициализации в цикле неявен).
 *
 * `leadQualifier` вывозит оба имени дальше, поэтому ни один прежний импорт не
 * тронут.
 */

export interface ShowcaseAbility {
  /** Канал умеет отправить снимки объекта прямо в чат И это разрешено ползунком. */
  canSendPhotos: boolean;
  /** Объекты, фотографии которых этот собеседник уже получал (повторно не уйдут). */
  alreadyShownShortIds: number[];
  /** Сколько снимков уйдёт за показ — число из Настроек. Промт называет его клиенту
   *  («до N штук»), поэтому обещание и отправка обязаны идти от одного значения. */
  photosPerOffer: number;
  /** Канал умеет отправить файл-документ (гид покупателя) — см. guideOffer.ts.
   *  Те же Meta-каналы, что и фото; в Telegram файл не уходит вовсе. */
  canSendGuide: boolean;
}

/**
 * Что боту разрешено делать (Настройки → Бот → «Что бот умеет»).
 *
 * Приходит сюда готовым признаком, а не читается из базы: квалификатор не должен
 * ходить в настройки — он вызывается и из вебхука, и из крона, и из тестов, и
 * лишний запрос на каждом ходе не нужен.
 */
export interface BotAbilities {
  /** Назначать, переносить и отменять показы самому. */
  showings: boolean;
  /** «Соедините с оператором»: поле callbackRequest и правило в промте. */
  callback: boolean;
  /** «Уточню у собственника»: поле askOwner и очередь вопросов. Выключено —
   *  бот берёт номер, отвечает агент по звонку (владелец 16.08.2026). */
  askOwner: boolean;
  /** Разговор с кандидатом на вакансию: поле jobApplication и сценарий JOB. */
  vacancies: boolean;
  /** Ссылки на объекты в переписке. Выключено — параметры словами, ссылку даст агент. */
  links: boolean;
  /** Режим запуска: отвечать строго на спрошенное (см. CAUTIOUS_MODE_RULE). */
  cautious: boolean;
  /** БОТ-СПЕЦИАЛИСТ ПО ТИПУ ОБРАЩЕНИЯ (Настройки → Бот; по умолчанию ВЫКЛЮЧЕНО).
   *  Включено — пока направление не известно, бот получает ИНТЕЙК (SCENARIO_INTAKE:
   *  разобраться, кто пишет и что нужно), а как только намерение понятно —
   *  подробности только своего сценария, чужие строкой-напоминанием (см.
   *  buildStableSystem). Выключено — промт собирается ровно как раньше, побайтово.
   *  Имя поля осталось прежним (`promptEconomy`, в базе `botPromptIntentEconomy`):
   *  экономия токенов — побочный эффект, а не смысл тумблера. */
  promptEconomy: boolean;
}

/**
 * Направление разговора — то, что модель определила в ЭТОМ ходе. Не то же самое,
 * что категория собеседника в досье: сегодня человек продаёт, завтра покупает.
 */
export type LeadIntent = "buy" | "sell" | "job" | "rent" | "other";

/**
 * КТО ПИШЕТ — шире, чем направление разговора.
 *
 * `LeadIntent` отвечает на вопрос «о чём речь» и знает только четыре наши темы;
 * всё остальное человечество попадает в `"other"`. Из-за этого рекламный агент,
 * застройщик и человек, ошибшийся номером, были для кода неотличимы друг от
 * друга и от покупателя, которого бот просто не успел распознать: у всех
 * четверых `intent="other"`, а значит интейк на каждом ходе и полный набор прав.
 * Живой итог — бот по третьему разу спрашивает у рекламщика, что тот хочет
 * купить.
 *
 * Коды намеренно те же, что у категорий досье (`CONTACT_CATEGORIES` в
 * `@royal-home/shared`): второй словарь про одно и то же разъехался бы с первым,
 * а так перевод — это `categoryFromWhoIsThis`, таблица из одной строки на код.
 *
 * `SPAM` в список НЕ входит, хотя в категориях досье он есть: спам ловится кодом
 * до вызова модели (стражи накрутки и рассылок), и спрашивать у модели «это спам?»
 * значило бы дать ей повод замолчать в ответ живому человеку.
 *
 * Поле подчинено тумблеру «Бот-специалист по типу обращения»: выключен — его нет
 * ни в схеме, ни в промте, и обе строки собираются побайтово как раньше.
 */
export const WHO_IS_THIS = [
  "BUYER",
  "SELLER",
  "JOB",
  "PARTNER",
  "CLIENT_CARE",
  "VENDOR",
  "OTHER",
  "UNKNOWN",
] as const;
export type WhoIsThis = (typeof WHO_IS_THIS)[number];

/**
 * Что клиент делает с показом: договаривается впервые, переносит уже назначенный
 * или отказывается совсем.
 *
 * Для ОДНОГО И ТОГО ЖЕ объекта "book" и "reschedule" код различает САМ, по базе
 * (см. bookShowing): если у клиента уже есть непрошедший показ этого объекта —
 * время меняется у него, что бы ни прислала модель. А вот отмену по одному лишь
 * тексту не отличить от переноса без времени, и назвать её может только модель.
 *
 * Для ДРУГОГО объекта слово модели, наоборот, единственный сигнал — см.
 * isReplacementOfOtherShowing.
 */
export type ShowingAction = "book" | "reschedule" | "cancel";

/** Что бот вытащил из разговора: какой объект и на когда клиент согласился приехать. */
export interface ShowingRequest {
  /** Отсутствует — считаем "book": так приходили ходы до появления переноса. */
  action?: ShowingAction | null;
  /** Код объекта из блока подобранных объектов (Property.shortId) либо его uuid. */
  propertyCode?: number | string | null;
  /** "today" | "tomorrow" | "after_tomorrow" | "YYYY-MM-DD" (плюс те же слова по-русски/таджикски). */
  day?: string | null;
  /** "HH:MM" либо часть суток: morning / afternoon / evening (и синонимы). */
  time?: string | null;
}
