  "цифры: выпиши те цифры, которые действительно расслышал, а неразобранные обозначь символом «?» " +
  "на их месте, но не превращай номер во что-то другое. " +
  // Найдено 19.08.2026: тишина/фоновый шум/дыхание без слов иногда получали
  // придуманную модель фразу вместо честной пустой строки — в интерфейсе это
  // выглядело так, будто человек «сам» что-то сказал, хотя он молчал. Прежний
  // запрет («неразборчиво → пусто») касался ИСКАЖЁННОЙ речи, а не её ПОЛНОГО
  // отсутствия — уточняем оба случая раздельно и явно запрещаем угадывать.
  "Если в записи вообще НЕТ человеческой речи (тишина, шум, дыхание, шорох, гудки) — " +
  "тоже ответь пустой строкой. НИКОГДА не придумывай и не угадывай слова, которых не было " +
  "в записи, даже одно короткое — лучше пустой ответ, чем выдуманный текст.";

/**
 * КОНТЕКСТ РАСШИФРОВКИ — ЗВОНОК ИЛИ ГОЛОСОВОЕ (24.09.2026).
 *
 * ЗАЧЕМ. GEMINI_INSTRUCTION выше писалась для голосового сообщения клиента: там
 * говорит один человек, и делить текст по репликам нечего. Телефонный разговор
 * (lib/telephony/callRecordings.ts) — это ВСЕГДА двое, и разбор (ai/callAnalysis.ts)
 * и перевод (ai/translateTranscript.ts) читают текст построчно именно затем, чтобы
 * понять, кто что сказал, — сплошной текст без разметки лишает их этой возможности
 * так же, как лишал бы человека, слушающего запись без подписей.
 *
 * `kind` по умолчанию не задан — это старое поведение (голосовое), ни одного
 * вызывающего места менять не пришлось.
 */
export interface TranscribeContext {
  /** "call" — телефонный разговор (реплики с префиксами); не задано/"voice" —
   *  голосовое сообщение клиента, инструкция не меняется вовсе. */
  kind?: "call" | "voice";
  /** Известный номер этого клиента — ТОЛЬКО для сверки цифр, которые модель и так
   *  расслышала (см. callerPhoneInstruction ниже); откуда берётся — см.
   *  clientForMasking в lib/telephony/callRecordings.ts (тот же Client.phone). */
  callerPhone?: string | null;
  /** Имя сотрудника, который вёл разговор — чтобы модель не исказила обращение к
   *  нему по имени. */
  agentName?: string | null;
  /**
   * Внутренний номер сотрудника (Agent.sipExtension). В текст инструкции не идёт —
   * в разговоре его никто вслух не называет, полю просто некуда попасть. Поле
   * оставлено в контексте ради симметрии с остальными («кто вёл разговор») и на
   * случай, если модели в будущем понадобится маршрутный признак, а не текстовая
   * подсказка — например, чтобы отличать несколько параллельных линий одного
   * разговора. Сегодня используется только для журнала на стороне вызывающего.
   */
  agentExtension?: string | null;
}

/**
 * ДОПОЛНЕНИЕ ДЛЯ ЗВОНКОВ — РЕПЛИКАМИ, А НЕ СПЛОШНЫМ ТЕКСТОМ.
 *
 * Отдельная константа, а не переписанная GEMINI_INSTRUCTION: голосовое сообщение
 * клиента инструкцию не меняет вовсе, а дублировать весь текст ради одной вставки
 * («пиши репликами») значило бы держать две копии одних и тех же правил про
 * цифры и тишину — именно то дублирование, которого CLAUDE.md просит избегать.
 */
const CALL_DIALOGUE_INSTRUCTION =
  "Это запись телефонного разговора сотрудника агентства недвижимости с клиентом. " +
  "Пиши РЕПЛИКАМИ: каждая реплика — с новой строки, с префиксом «Агент:» или «Клиент:». " +
  "Агент — тот, кто представляется агентством или ведёт разговор от лица компании; если по " +
  "репликам нельзя понять, кто есть кто, используй префикс «Говорящий:». ";

/** Тот же запрет на додумывание, что уже есть в GEMINI_INSTRUCTION для цифр номера —
 *  здесь он распространяется на ЛЮБОЕ неразобранное слово звонка, не только на цифры:
 *  в разговоре двоих неразборчивое слово легко спутать с осмысленной репликой другой
 *  стороны, и додумывание там дороже, чем в одиночном голосовом. */
const CALL_UNCLEAR_WORD_INSTRUCTION =
  "Любое неразобранное слово в разговоре, не только цифру, помечай знаком «?» вместо того, " +
  "чтобы додумывать его по смыслу или похожему звучанию. ";

/** Отдельная функция, а не строка в константе: имя сотрудника известно только на
 *  момент вызова (lib/telephony/callRecordings.ts передаёт его из Agent.fullName). */
function agentNameInstruction(agentName: string): string {
  return `Сотрудника, который ведёт разговор, зовут ${agentName} — обращения к нему по имени не искажай. `;
}

/**
 * ЗНАЕМ НОМЕР — НО ТОЛЬКО ДЛЯ СВЕРКИ, НЕ ДЛЯ ПОДСТАНОВКИ.
 *
 * Живой риск: если просто сказать модели «номер клиента такой-то», она может
 * ПОДСТАВИТЬ его в расшифровку целиком, даже если в записи клиент называл только
 * часть цифр или не называл номер вовсе, — это та же подмена «неразобранного
 * похожим», которую GEMINI_INSTRUCTION уже запрещает для одиночного голосового, и
 * запрет здесь сформулирован так же явно, а не понадеявшись на общий смысл.
 */
function callerPhoneInstruction(callerPhone: string): string {
  return (
    `Известный номер этого клиента: ${callerPhone}. Используй его ТОЛЬКО для сверки цифр, которые ` +
    `ты реально слышишь в записи — НИКОГДА не вписывай этот номер в расшифровку, если его не ` +
    `произносили в разговоре. `
  );
}

/** Собирает инструкцию по контексту: для звонка — база плюс блок про реплики,
 *  имя агента (если известно) и известный номер (если известен); для голосового
 *  (kind не "call") — ровно GEMINI_INSTRUCTION без изменений, как было раньше. */
function instructionFor(context?: TranscribeContext): string {
  if (context?.kind !== "call") return GEMINI_INSTRUCTION;
  let extra = CALL_DIALOGUE_INSTRUCTION;
  if (context.agentName) extra += agentNameInstruction(context.agentName);
  if (context.callerPhone) extra += callerPhoneInstruction(context.callerPhone);
  extra += CALL_UNCLEAR_WORD_INSTRUCTION;
  return `${GEMINI_INSTRUCTION} ${extra}`;
}

export async function isTranscriptionEnabled(): Promise<boolean> {
  return !!(await resolveGeminiKey());
}

/**
 * Модель ответила НЕ расшифровкой, а разговором с нами: «предоставьте аудиозапись»,
 * «файл не прикреплён», «я не могу это сделать».
 *
 * ЗАЧЕМ ЭТО НУЖНО. 13.08.2026 в карточке клиента оказался «разговор» с текстом
 * «Пожалуйста, предоставьте голосовое сообщение или аудиозапись, так как файл для
 * расшифровки не был прикреплён» — звонок, где никто не поднял трубку, дал запись
 * из одних гудков, Gemini честно ответил, что расшифровывать нечего, а CRM сохранила
 * этот ответ как содержание беседы. Дальше по конвейеру он ушёл в разбор качества и
 * в предложение по карточке: разбор написал «запись отсутствует», и всё это увидел
 * агент. Одна пустая запись — три испорченных места в CRM и два платных запроса.
 *
 * ПОЧЕМУ ЭВРИСТИКОЙ, А НЕ ЗАПРЕТОМ В ПРОМТЕ. Промт — просьба, а не гарантия: он уже
 * велит «если речь неразборчива, ответь пустой строкой», и модель это иногда
 * игнорирует. Фильтр на выходе не зависит от того, послушалась ли модель сегодня.
 *
 * ПОЧЕМУ ОГРАНИЧЕНО ДЛИНОЙ. Живая речь клиента тоже может начинаться со слова
 * «пожалуйста» — но мета-ответ модели всегда короткий и всегда про сам файл. Порог
 * в 300 знаков (это примерно полминуты речи) оставляет настоящий разговор в покое:
 * потерять расшифровку страшнее, чем пропустить одну служебную фразу.
 */
const MODEL_REFUSAL_PATTERNS = [
  /предостав(ьте|те)\s+(мне\s+)?(голосов|аудио|запис|файл)/i,
  /(файл|запис\w*|аудио|сообщени\w*)[^.]{0,40}(не\s+был\w*\s+)?(прикреплен|прикреплён|приложен|предоставлен)/i,
  /(загрузите|прикрепите|отправьте)\s+(аудио|голосов|запис|файл)/i,
  /(не\s+могу|невозможно)\s+[^.]{0,40}(расшифровать|прослушать|обработать|распознать)/i,
  /^(i'?m\s+sorry|i\s+cannot|i\s+can'?t|unable\s+to)\b/i,
  /(no|missing)\s+(audio|file|recording)\b[^.]{0,30}(provided|attached|uploaded)/i,
];

const MAX_REFUSAL_LENGTH = 300;

export function looksLikeModelRefusal(text: string): boolean {
  const trimmed = text.trim();
  if (!trimmed || trimmed.length > MAX_REFUSAL_LENGTH) return false;
  return MODEL_REFUSAL_PATTERNS.some((pattern) => pattern.test(trimmed));
}

/**
 * Итог расшифровки — с ответом на вопрос «это тишина или это отказ».
 *
 * ЗАЧЕМ РАЗЛИЧАТЬ (15.08.2026). Раньше функция на оба случая возвращала `null`, и
 * вызывающий код не мог их развести: пустая запись (никто не поднял трубку, гудки)
 * и полный отказ поставщика выглядели одинаково. Из-за этого разговор, который
 * Gemini не осилил, оставался «не расшифрован» навсегда — повторить было некому,
 * потому что повторять решают именно по этому признаку (см. lib/telephony/
 * transcriptionRetry.ts).
 */
/**
 * ГОЛОСОВОЕ КЛИЕНТА НЕ ПОНЯТО — ВИДНО В ЖУРНАЛЕ (25.09.2026).
 *
 * Живой случай в WhatsApp: бот дважды ответил «паёми овозиро кушода
 * наметавонам», а в журнале ошибок не было ни строки — пустой ответ модели и
 * ответ «про файл» (looksLikeModelRefusal) считались штатной тишиной и молчали.
 * Владелец не мог узнать, почему голосовое не поняли.
 *
 * Пишем ТОЛЬКО для голосовых сообщений (context.kind не "call"): у записей
 * звонков тишина и правда штатна и частна, их повтор ведёт
 * scheduleTranscriptionRetry. Шум держит дедупликация: начало текста
 * постоянное и совпадает с dedupKey (logSystemError сравнивает начало), так что
 * за десять минут ложится одна строка на каждый из двух исходов.
 */
export const VOICE_EMPTY_LOG_PREFIX = "Голосовое клиента не понято: модель вернула пустую расшифровку";
export const VOICE_REFUSAL_LOG_PREFIX = "Голосовое клиента не понято: модель ответила про файл, а не расшифровкой";

function noteVoiceNotUnderstood(context: TranscribeContext | undefined, prefix: string, detail: string): void {
  if (context?.kind === "call") return;
  void logSystemError("ai", `${prefix} (${detail})`, { dedupKey: prefix });
}

export interface TranscriptionResult {
  /** Текст расшифровки. null — модель ничего внятного не вернула. */
  text: string | null;
  /** Поставщик не ответил (сеть, лимит, таймаут) — есть смысл повторить позже. */
  failed: boolean;
  /** Причина отказа для журнала. */
  detail?: string;
}

/**
 * `filename` остался в сигнатуре, хотя Gemini имя файла не смотрит (тип берётся из
 * mime_type). Убирать его — значит править все вызывающие места ради ничего; здесь
 * же он остаётся полезен в журнале, когда расшифровка не удалась.
 */
export async function transcribeAudioResult(
  buffer: Buffer,
  filename: string,
  mediaType: string,
  /** Не задан — голосовое, поведение как раньше. См. TranscribeContext выше. */
  context?: TranscribeContext
): Promise<TranscriptionResult> {
  // Ключи и модели — одним запросом к Настройкам (см. ai/geminiSettings.ts).
  const runtime = await resolveGeminiRuntime();
  const apiKeys = runtime.keys;
  if (apiKeys.length === 0) return { text: null, failed: true, detail: "ключ Gemini не задан" };
  const expensiveModels = runtime.transcribeModels;
  const primaryModel = expensiveModels[0];
  // Дешёвые — то же, чем пользуется весь остальной ИИ: последний рубеж, чтобы
  // голосовое не потерялось насовсем, если ВСЕ дорогие модели разом недоступны.
  const cheapModels = [runtime.model, ...runtime.fallbackModels];

  const fail = (detail: string): TranscriptionResult => {
    console.error("[transcribe]", detail);
    void logSystemError("ai", `Голосовое (${filename}) не расшифровано: ${detail}`);
    return { text: null, failed: true, detail };
  };

  /**
   * ТЕЛО ЗАПРОСА — СВОЁ ДЛЯ КАЖДОЙ МОДЕЛИ: ДОРОГАЯ РАЗМЫШЛЯЕТ, ДЕШЁВАЯ — НЕТ (24.09.2026).
   *
   * Дорогой модели thinkingConfig НЕ шлём — она думает над речью так, как решит сама,
   * и это не расточительство, а то самое качество на таджикском, ради которого её
   * поставили первой (19.08). Проверено живой пробой на записях звонков 24.09: с
   * "low" pro отвечает втрое быстрее, но текст на шумной записи хуже и цена «350000»
   * теряется; "medium" может вовсе не думать. Успевать ей дают не урезанные
   * размышления, а срок попытки (см. EXPENSIVE_TIMEOUT_BASE_MS).
   *
   * Дешёвая модель — последний рубеж «хоть что-то вместо ничего», и ей, как и всем
   * текстовым вызовам, уходит «не размышляй» (geminiThinkingConfig: у 3.x —
   * thinkingLevel, у 2.x — thinkingBudget 0): на голосовом 97 КБ Flash без блока думала
   * 1233 токена и отвечала 8 с — резерву спешить важнее, чем размышлять. Форма зависит
   * от модели, поэтому тело собирается по модели; base64 считается один раз — на
   * 15-мегабайтном разговоре это заметные миллисекунды на каждую попытку. Отвергнутый
   * блок (400 «Thinking level … not supported») снимается для этой модели до конца
   * жизни процесса — тот же приём, что thinkingConfigRejected в geminiClient.
   */
  // Для звонка (kind: "call") инструкция дополняется блоком про реплики, имя
  // агента и известный номер клиента — см. instructionFor/TranscribeContext выше.
  // Для голосового (context не задан) — ровно GEMINI_INSTRUCTION, как и раньше.
  const audioParts = [
    { inline_data: { mime_type: mediaType, data: buffer.toString("base64") } },
    { text: instructionFor(context) },
  ];
  const bodyCache = new Map<string, string>();
  const bodyFor = (model: string): string => {
    const withThinking = !expensiveModels.includes(model) && !thinkingConfigRejected.has(model);
    const key = `${model}:${withThinking ? "no-thinking-block" : "plain"}`;
    let cached = bodyCache.get(key);
    if (!cached) {
      cached = JSON.stringify({
        contents: [{ parts: audioParts }],
        ...(withThinking ? { generationConfig: { thinkingConfig: geminiThinkingConfig(model) } } : {}),
      });
      bodyCache.set(key, cached);
    }
    return cached;
  };

  const allModels = [...expensiveModels, ...cheapModels];
  const signature = keysSignature(apiKeys);
  // Модели, у которых квота уже выжжена, из перебора выпадают целиком: именно
  // хождение по ним «на всякий случай» и размножало один эпизод деградации на
  // каждое голосовое (см. TRANSCRIBE_QUOTA_PAUSE_STEPS_MS).
  const modelsToTry = allModels.filter((m) => !modelPausedUntil(m, signature));
  if (modelsToTry.length === 0) {
    const until = quotaPause.get(allModels[0])?.until;
    return fail(
      `все модели расшифровки на паузе по исчерпанной квоте Gemini${until ? ` (до ${untilLabel(until)})` : ""} — ` +
        `поможет ключ из ДРУГОГО проекта Google: Настройки → ИИ → дополнительные ключи`
    );
  }

  /**
   * Учёт «модель ответила 429» по каждой модели: сколькими ключами её пробовали и
   * сколько из них уткнулись в квоту. Пауза ставится только если ВСЕ опробованные
   * ключи дали 429 — если хоть один ключ (из другого проекта Google) на этой модели
   * прошёл, квота не кончилась и молчать не о чем.
   */
  const modelTriedWith = new Map<string, Set<string>>();
  const modelQuotaWith = new Map<string, Set<string>>();
  const noteAttempt = (map: Map<string, Set<string>>, model: string, key: string): void => {
    const set = map.get(model) ?? new Set<string>();
    set.add(key);
    map.set(model, set);
  };
  /**
   * ПОЧЕМУ ИМЕННО ЭТА МОДЕЛЬ НЕ ОТВЕТИЛА — HTTP-КОД, А НЕ СЛОВО «НЕДОСТУПНА»
   * (22.08.2026).
   *
   * До сегодняшнего дня запись в журнале звучала «основная gemini-2.5-pro недоступна»
   * и молчала о причине. За этим словом могло стоять что угодно: перегрузка Google
   * (503, пройдёт сама), кончившаяся квота (429, лечится деньгами) или закрытая
   * модель (404, не лечится ничем, кроме правки кода). Отличить их было нельзя — и
   * 404 закрытой модели прожил незамеченным трое суток, обходясь нам в двойную цену
   * на каждом голосовом. Одной строки «HTTP 404» хватило бы в первый же день.
   *
   * Храним причину ПЕРВОГО отказа модели: следующие — это обычно те же грабли
   * другим ключом, а первая ближе всего к настоящей причине.
   */
  const modelFailure = new Map<string, string>();
  const noteFailure = (model: string, reason: string): void => {
    if (!modelFailure.has(model)) modelFailure.set(model, reason);
  };
  /** Приписка «(HTTP 404: ...)» для журнала; пусто, если причина не известна. */
  const failureNote = (model: string): string => {
    const reason = modelFailure.get(model);
    return reason ? ` (${reason})` : "";
  };
  /**
   * Итог перебора переносится в паузы. Зовётся ПЕРЕД КАЖДЫМ выходом, включая
   * удачный: главный случай как раз удачный — расшифровку вытянула резервная
   * модель, а основная всю дорогу отвечала 429, и без этой записи следующее
   * голосовое снова начнёт с неё (ровно те «7 раз за час» 22.08.2026).
   */
  const rememberQuotaPauses = (): void => {
    for (const [model, quotaKeys] of modelQuotaWith) {
      const tried = modelTriedWith.get(model);
      if (!tried || quotaKeys.size === 0 || quotaKeys.size !== tried.size) continue;
      const previous = quotaPause.get(model);
      // Подряд — только если беда та же и ключи те же; иначе счёт начинается заново.
      const strikes =
        previous && previous.signature === signature
          ? Math.min(previous.strikes + 1, TRANSCRIBE_QUOTA_PAUSE_STEPS_MS.length - 1)
          : 0;
      const until = Date.now() + TRANSCRIBE_QUOTA_PAUSE_STEPS_MS[strikes];
      quotaPause.set(model, { signature, until, strikes });
      console.error(`[transcribe] квота ${model} исчерпана на всех ${tried.size} ключах — пауза до ${untilLabel(until)}`);
      void logSystemError(
        "ai",
        `Расшифровка не будет обращаться к модели ${model} до ${untilLabel(until)}: квота Gemini исчерпана на всех ` +
          `${tried.size} ключах. Голосовые продолжат расшифровываться остальными моделями цепочки. Квота считается ` +
          `на ПРОЕКТ Google, поэтому поможет ключ из ДРУГОГО проекта: Настройки → ИИ → дополнительные ключи — ` +
          `он снимет паузу сразу, ждать её конца не нужно.`
      );
    }
  };

  let lastDetail = "нет доступных ключей";
  const startedAt = Date.now();
  // Общий дедлайн на весь перебор — см. TRANSCRIBE_TOTAL_BUDGET_MS.
  const deadline = startedAt + TRANSCRIBE_TOTAL_BUDGET_MS;
  // Дорогим моделям отдаётся не весь бюджет: хвост забронирован под дешёвые, чтобы
  // одна зависшая попытка не съедала их окно (см. TRANSCRIBE_FALLBACK_RESERVE_MS).
  const expensiveDeadline = deadline - TRANSCRIBE_FALLBACK_RESERVE_MS;
  // Резерв действует, только пока в цепочке ЕСТЬ кому его отдать. Дешёвых моделей
  // может не остаться вовсе — они тоже уходят на паузу по квоте, а основную модель
  // владелец волен задать тем же именем, что и дорогую. Бронировать время не для
  // кого — значит просто выбросить четверть бюджета в никуда.
  const hasCheapModels = modelsToTry.some((m) => !expensiveModels.includes(m));
  let outOfTime = false;
  /**
   * МОДЕЛЬ СНАРУЖИ, КЛЮЧ ВНУТРИ (24.09.2026) — А НЕ НАОБОРОТ.
   *
   * ЧТО БЫЛО НЕ ТАК. Перебор шёл «ключи × модели»: для первого ключа пробовались
   * ВСЕ модели (обе дорогие, если их несколько, затем дешёвые), и только когда они
   * все отказали — перебор переходил ко второму ключу и начинал заново с первой
   * дорогой. На практике с одной дорогой моделью в цепочке это означало: если pro
   * молчит на первом ключе, до второго ключа ДЛЯ НЕЁ ЖЕ дело не доходит никогда —
   * перебор соскальзывает на дешёвую модель первым же ключом, хотя второй ключ (из
   * другого проекта Google, со своей квотой) мог ответить.
   *
   * ЧТО ДЕЛАЕМ. Модель — внешний цикл, ключ — внутренний: для КАЖДОЙ модели по
   * очереди пробуются ВСЕ ключи, и только когда модель отказала на всех ключах,
   * перебор переходит к следующей модели (дорогая → дорогая → … → дешёвая →
   * дешёвая). Дорогие модели по-прежнему пробуются раньше дешёвых — modelsToTry
   * начинается с expensiveModels, порядок списка не менялся.
   *
   * Бюджеты фаз (expensiveDeadline/deadline), outOfTime, память об отказах
   * (modelFailure/noteFailure) и пауза по квоте (modelQuotaWith/rememberQuotaPauses)
   * не зависят от того, какой цикл внешний, — они и раньше считались по модели и
   * по ключу отдельно, а не по паре «текущий виток», так что перестановка их не
   * трогает.
   */
  models: for (const model of modelsToTry) {
    const isExpensive = expensiveModels.includes(model);
    const phaseDeadline = isExpensive && hasCheapModels ? expensiveDeadline : deadline;
    // Полный набор попыток — КАЖДОМУ ключу на этой модели (перегружена с одним
    // ключом — пробуем следующий ключ той же модели, не проваливаемся сразу на
    // дешёвую); у дешёвой — по одной попытке на ключ (тот же расклад, что у
    // geminiClient.ts): ждать четыре секунды ради уже перегруженной резервной
    // модели смысла нет.
    const attempts = isExpensive ? GEMINI_RETRY_DELAYS_MS.length + 1 : 1;
    for (const apiKey of apiKeys) {
      for (let attempt = 0; attempt < attempts; attempt++) {
        // Пауза перед повтором тоже укладывается в бюджет своей фазы: ждать четыре
        // секунды, когда до потолка осталась одна, значит отдать их впустую.
        if (attempt > 0) {
          await sleep(Math.min(GEMINI_RETRY_DELAYS_MS[attempt - 1], Math.max(0, phaseDeadline - Date.now())));
        }
        // Общий бюджет исчерпан — дальше не пробуем ни этой моделью, ни следующим
        // ключом: очередь расшифровок общая, и держать её ради заведомо мёртвого
        // перебора дороже, чем честно признать отказ и отдать место следующему.
        if (deadline - Date.now() <= 0) {
          outOfTime = true;
          break models;
        }
        // Фаза дорогих моделей закончилась, а общий бюджет ещё нет — это и есть
        // забронированный хвост: уступаем его следующим (дешёвым) моделям, а не
        // доедаем очередной попыткой той, что и так не отвечает.
        const left = phaseDeadline - Date.now();
        if (left <= 0) break;
        noteAttempt(modelTriedWith, model, apiKey);
        // ВРЕМЯ УДАЧНОЙ ПОПЫТКИ, А НЕ ВСЕЙ ФУНКЦИИ (24.09.2026, для logAiCall ниже).
        // startedAt считает от первого похода в сеть, а перебор — это ключи×модели×
        // попытки: если основная модель дважды провисела таймаутом (90 с каждая), а
        // резервная ответила с первой, «время вызова» в Финансах показывало бы три
        // минуты вместо честных секунд ОТВЕТИВШЕЙ попытки — цифра врала бы именно
        // там, где по ней считают, дорого ли обходится расшифровка. Секундомер
        // ставится заново перед каждым fetch и меряет только его.
        const attemptStartedAt = Date.now();
        try {
          const res = await fetch(geminiGenerateUrlFor(model), {
            method: "POST",
            headers: { "Content-Type": "application/json", "x-goog-api-key": apiKey, ...geminiProxyHeaders() },
            body: bodyFor(model),
            // Срок — по размеру записи (transcribeTimeoutFor), но не длиннее остатка
            // общего бюджета: последняя попытка не имеет права его перебрать.
            signal: AbortSignal.timeout(Math.min(transcribeTimeoutFor(buffer.length, isExpensive), left)),
          });
          if (!res.ok) {
            const detail = (await res.text()).slice(0, 300);
            // Поставщик отверг не запрос, а блок thinkingConfig: снимаем его для этой
            // модели и повторяем ТУ ЖЕ попытку сразу — это не сбой модели, и счёт
            // попыток и паузу перед повтором он тратить не должен.
            if (!thinkingConfigRejected.has(model) && isThinkingConfigRejection(res.status, detail)) {
              thinkingConfigRejected.add(model);
              console.warn(`[transcribe] ${model} не приняла thinkingConfig — дальше без него: ${detail.slice(0, 120)}`);
              attempt -= 1;
              continue;
            }
            lastDetail = `Gemini HTTP ${res.status} (${model}): ${detail}`;
            // Причина попадёт в журнал рядом со словом «недоступна» — см. modelFailure.
            noteFailure(model, `HTTP ${res.status}: ${detail.replace(/\s+/g, " ").slice(0, 160)}`);
            /**
             * 429 НЕ ПОВТОРЯЕМ ЭТИМ ЖЕ КЛЮЧОМ (22.08.2026) — тот же вывод, что уже
             * сделан для озвучки (ai/tts.ts). Общий перебор считает 429 временной
             * помехой и ждёт 1+2+4 секунды; для предела «запросов в минуту» это
             * разумно, а для исчерпанной квоты — четыре заведомо пустых запроса и
             * семь секунд простоя НА КАЖДОЕ голосовое. Ключ кончился — берём
             * следующий (он из другого проекта Google и со своей квотой), а если
             * кончились все, модель уйдёт на паузу (rememberQuotaPauses).
             */
            if (res.status === 429) {
              noteAttempt(modelQuotaWith, model, apiKey);
              break;
            }
            if (!isRetryableGeminiStatus(res.status)) break;
            continue;
          }
          const data = (await res.json()) as {
            candidates?: { content?: { parts?: { text?: string }[] } }[];
            usageMetadata?: { promptTokenCount?: number; candidatesTokenCount?: number };
          };
          /**
           * РАСШИФРОВКА ТОЖЕ СТОИТ ДЕНЕГ, и до 20.08.2026 её вызовы не попадали в
           * журнал ИИ вовсе — то есть месячная строка «расходы на ИИ» в Финансах
           * не видела ни одного голосового, а их сотни. Пишем вызов сюда же, где
           * его пишут оба остальных клиента (ai/shared.ts).
           */
          void logAiCall({
            endpoint: "transcribe",
            model,
            spent: {
              inputTokens: data.usageMetadata?.promptTokenCount ?? 0,
              outputTokens: data.usageMetadata?.candidatesTokenCount ?? 0,
              cacheWriteTokens: 0,
              cacheReadTokens: 0,
            },
            ms: Date.now() - attemptStartedAt,
            ok: true,
          });
          const text = (data.candidates?.[0]?.content?.parts ?? [])
            .map((p) => p.text ?? "")
            .join("")
            .trim();
          // Пустой ответ — это «речь неразборчива» по нашей же инструкции, штатный исход.
          // У звонков в журнал он не пишется (шум был бы ежедневным); у голосового
          // клиента — одной строкой за десять минут (noteVoiceNotUnderstood, 25.09.2026).
          // И повторять его не надо: тишину не расшифрует и десятая попытка.
          //
          // ЕСЛИ ЖЕ ЭТО ОТВЕТИЛА ДЕШЁВАЯ МОДЕЛЬ, А ХОТЯ БЫ ОДНА ДОРОГАЯ ДО НЕЁ НЕ
          // ОТВЕТИЛА (24.09.2026) — ЭТО НЕ ТИШИНА, А НЕДОСМОТРЕННАЯ РАСШИФРОВКА.
          //
          // ЧТО БЫЛО НЕ ТАК. Пустой ответ Flash после того, как pro провисела
          // таймаутом (524 через прокси, см. isRetryableGeminiStatus), выглядел
          // снаружи ровно как «в записи тишина» — штатный исход, без записи в журнал
          // и без повтора. На деле дорогая модель эту запись даже не дослушала:
          // Flash получает ТУ ЖЕ речь и просто хуже её разбирает (та же причина, по
          // которой её не ставят первой, — 19.08.2026), и молчание Flash после
          // отказа pro — не «неразборчиво», а «не справилась, потому что дорогая не
          // успела». Разговор в этом случае тихо считался расшифрованным (пустой
          // текст — валидный штатный исход) и повторной попытки не получал никогда.
          //
          // ЧТО ДЕЛАЕМ. Дешёвая модель молчит одновременно с тем, что хотя бы одна
          // дорогая в ЭТОМ ЖЕ вызове зафиксирована в modelFailure (таймаут/5xx/524 —
          // именно отказ поставщика, а не штатный 400 на thinkingConfig, который в
          // modelFailure не попадает, см. noteFailure) — это failed:true с понятной
          // причиной, чтобы для звонков сработал scheduleTranscriptionRetry (см.
          // lib/telephony/callRecordings.ts), а не «расшифровано пустотой навсегда».
          // Пустой ответ ДОРОГОЙ модели такой проверке не подвергается — это
          // по-прежнему штатная тишина, ей после себя проверять больше некого.
          if (!text) {
            rememberQuotaPauses();
            const expensiveFailedModels = expensiveModels.filter((m) => modelFailure.has(m));
            if (!isExpensive && expensiveFailedModels.length > 0) {
              return fail(
                `дешёвая модель ${model} ответила пустой строкой, но это не тишина в записи — ` +
                  `до неё отказали все опробованные дорогие: ` +
                  expensiveFailedModels.map((m) => `${m}${failureNote(m)}`).join("; ")
              );
            }
            noteVoiceNotUnderstood(context, VOICE_EMPTY_LOG_PREFIX, `${filename}, модель ${model}`);
            return { text: null, failed: false };
          }
          // Модель ответила про сам файл, а не про то, что в нём сказано (см.
          // looksLikeModelRefusal). Это то же «расшифровывать нечего»: в консоль —
          // чтобы было по чему разбирать; в журнал — только у голосового клиента и
          // одной строкой за десять минут (noteVoiceNotUnderstood, 25.09.2026).
          if (looksLikeModelRefusal(text)) {
            console.warn(`[transcribe] ${filename}: модель ответила про файл, а не расшифровкой — «${text.slice(0, 120)}»`);
            rememberQuotaPauses();
            noteVoiceNotUnderstood(context, VOICE_REFUSAL_LOG_PREFIX, `${filename}, модель ${model}: «${text.slice(0, 120)}»`);
            return { text: null, failed: false };
          }
          /**
           * ЖАЛУЕМСЯ НА ОТКАТ ТОЛЬКО ЕСЛИ ДОРОГУЮ МОДЕЛЬ СЕГОДНЯ ДЕЙСТВИТЕЛЬНО
           * ПРОБОВАЛИ (22.08.2026). Пока паузы не было, эта строка честно значила
           * «сходили к основной и получили отказ». С паузой основная в перебор не
           * попадает вовсе — и та же строка стала бы писаться на КАЖДОЕ голосовое
           * заново, то есть ровно тем потоком одинаковых записей («7 раз за час»),
           * ради устранения которого пауза и заведена. Причина паузы уже описана
           * ОДНОЙ записью в rememberQuotaPauses — второй раз объяснять нечего.
           */
          const triedPrimary = modelTriedWith.has(primaryModel);
          const triedAnyExpensive = expensiveModels.some((m) => modelTriedWith.has(m));
          if (!isExpensive) {
            if (triedAnyExpensive) {
              void logSystemError(
                "ai",
                `Голосовое (${filename}) расшифровано ДЕШЁВОЙ моделью ${model} — все дорогие не ответили/отказали: ` +
                  expensiveModels.map((m) => `${m}${failureNote(m)}`).join("; ")
              );
            }
          } else if (model !== primaryModel && triedPrimary) {
            void logSystemError(
              "ai",
              `Голосовое (${filename}) расшифровано резервной дорогой моделью ${model} — основная ` +
                `${primaryModel} недоступна${failureNote(primaryModel)}.`
            );
          }
          rememberQuotaPauses();
          return { text, failed: false };
        } catch (err) {
          /**
           * «НЕ ОТВЕТИЛА ЗА N с» ВМЕСТО СЫРОГО ТЕКСТА ИСКЛЮЧЕНИЯ (24.09.2026).
           *
           * describeError на таймауте отдаёт что-то вроде «The operation was
           * aborted due to timeout» — техническое сообщение самого рантайма, из
           * которого не видно ни какой это был срок, ни что цифра посчитана по
           * transcribeTimeoutFor (bytes, isExpensive). Для журнала это два разных
           * вопроса — «отказал сервер» (HTTP-код, см. noteFailure выше) и «сервер
           * молчал, пока мы не устали ждать» (этот блок) — и вторая причина должна
           * называть срок, который реально стоял, а не голое имя ошибки рантайма.
           */
          const raw = describeError(err);
          const isTimeout =
            (err instanceof Error && (err.name === "AbortError" || err.name === "TimeoutError")) ||
            /aborted due to timeout/i.test(raw);
          lastDetail = isTimeout
            ? `не ответила за ${Math.round(transcribeTimeoutFor(buffer.length, isExpensive) / 1000)} с`
            : raw;
          noteFailure(model, lastDetail);
        }
      }
    }
  }
  /**
   * ПРИЧИНЫ ПО ВСЕМ МОДЕЛЯМ, А НЕ ОДНА lastDetail (24.09.2026).
   *
   * ЧТО БЫЛО НЕ ТАК. lastDetail — это причина ПОСЛЕДНЕЙ попытки последней модели в
   * переборе (обычно дешёвой, она идёт последней). Если дорогая модель отказала
   * HTTP 404 (мёртвое имя, чинится правкой кода), а дешёвая следом честно ответила
   * 429 (кончилась квота, чинится ключом), в журнал уходил только второй отказ —
   * и разбирающий видел «кончилась квота», хотя первопричина серьёзнее и совсем
   * другая. С момента, когда каждая модель разбирается своим ключом (см. models:
   * выше), таких независимых причин в одном вызове стало по определению больше.
   *
   * ЧТО ДЕЛАЕМ. modelFailure уже хранит ПЕРВУЮ причину каждой опрошенной модели
   * (см. noteFailure) — просто перечисляем их все. lastDetail добавляется отдельно,
   * только если он не совпадает ни с одной уже перечисленной причиной: обычно он
   * совпадает (это причина последней попытки последней модели, которая уже есть в
   * modelFailure), но исключения бывают — например, «нет доступных ключей», когда
   * до самого перебора не дошло ни разу и modelFailure остался пустым.
   */
  const perModelReasons = Array.from(modelFailure.entries()).map(([m, reason]) => `${m}: ${reason}`);
  const lastDetailListed = Array.from(modelFailure.values()).includes(lastDetail);
  const causes = !lastDetailListed && lastDetail
    ? [...perModelReasons, lastDetail].join("; ")
    : perModelReasons.join("; ") || lastDetail;
  // Одна понятная строка на весь исчерпанный бюджет: без неё «не расшифровано» с
  // последней сетевой причиной не отличить от «перебор оборвали по времени», а это
  // разные болезни — вторая лечится не повтором, а разбором с поставщиком.
  rememberQuotaPauses();
  if (outOfTime) {
    return fail(
      `перебор ключей и моделей прерван — не уложились в отведённые ` +
        `${Math.round(TRANSCRIBE_TOTAL_BUDGET_MS / 1000)} с; причины по моделям: ${causes}`
    );
  }
  return fail(causes);
}

/**
 * Короткая форма для тех, кому разница «тишина или отказ» не нужна: голосовые
 * клиентов в переписке, автоответчик, диктовка задачи в браузере. Им всё равно
 * нечего повторять — сообщение уже обработано, и второй попытки не будет.
 */
export async function transcribeAudio(buffer: Buffer, filename: string, mediaType: string): Promise<string | null> {
  return traceMeasured("asr", async () => (await transcribeAudioResult(buffer, filename, mediaType)).text);
}
