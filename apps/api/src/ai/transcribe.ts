/**
 * Модели, отвергшие блок thinkingConfig (400 «Thinking level … not supported»):
 * им тело уходит без него до конца жизни процесса. Память процесса, а не база —
 * как thinkingConfigRejected в geminiClient.ts: после перезапуска пробуем снова,
 * одного лишнего 400 на модель это стоит.
 */
const thinkingConfigRejected = new Set<string>();

/** Отказ именно из-за thinkingConfig, а не из-за самого запроса. */
function isThinkingConfigRejection(status: number, detail: string): boolean {
  return status === 400 && /thinking/i.test(detail);
}

/** Отпечаток набора ключей: только хвосты, чтобы сам ключ нигде не осел (как в tts.ts). */
function keysSignature(keys: string[]): string {
  return keys.map((k) => k.slice(-4)).join("|");
}

const quotaPause = new Map<string, { signature: string; until: number; strikes: number }>();

/**
 * Стоит ли модель на паузе ПРИ ЭТОМ наборе ключей. Синхронная — набор ключей уже
 * прочитан вызывающим, второй поход в БД на горячем пути расшифровки не нужен.
 */
function modelPausedUntil(model: string, signature: string): number | null {
  const paused = quotaPause.get(model);
  if (!paused) return null;
  if (Date.now() >= paused.until) {
    quotaPause.delete(model);
    return null;
  }
  // Ключи сменились — прежняя пауза больше ни о чём не говорит (см. комментарий выше).
  if (paused.signature !== signature) {
    quotaPause.delete(model);
    return null;
  }
  return paused.until;
}

/**
 * То же самое для внешнего мира (например, для диагностики в Настройках) — парная
 * функция к `ttsQuotaPausedUntil` из ai/tts.ts. Модель по умолчанию берётся из
 * Настроек, а не из константы: с 22.08.2026 её имя задаёт владелец с экрана.
 */
export async function transcribeQuotaPausedUntil(model?: string): Promise<number | null> {
  const runtime = await resolveGeminiRuntime();
  const target = model ?? runtime.transcribeModels[0];
  if (!target) return null;
  return modelPausedUntil(target, keysSignature(runtime.keys));
}

/** Время окончания паузы человеческим часом — для записи в журнал (как в tts.ts). */
function untilLabel(until: number): string {
  return new Date(until).toLocaleTimeString("ru-RU", { timeZone: "Asia/Dushanbe", hour: "2-digit", minute: "2-digit" });
}

