/**
 * СРОК ОЖИДАНИЯ СЧИТАЕТСЯ ОТ РАЗМЕРА ЗАПИСИ, А НЕ ОДИН НА ВСЁ (15.08.2026).
 *
 * Тридцать секунд ставились под голосовое клиента — это сотни килобайт. Потом той
 * же функцией начали расшифровывать телефонные разговоры, а их куски доходят до
 * 15 МБ, и в запрос они уходят в base64, то есть примерно 20 МБ тела. Чтобы успеть,
 * канал до Gemini (через прокси, из Душанбе) должен держать больше 5 Мбит/с ровно
 * все тридцать секунд — на длинных разговорах это выливалось в «AbortError: timeout»
 * с первой же попытки, три повтора подряд и «Разговор не расшифрован» в карточке.
 *
 * Отсюда: тот же базовый срок для мелочи и запас на каждый мегабайт сверху.
 * Потолок в три минуты — это дольше, чем разумно ждать ответа модели, но короче,
 * чем висеть вечно, если прокси проглотил запрос.
 */
const TIMEOUT_BASE_MS = 30_000;
const TIMEOUT_PER_MB_MS = 10_000;
const TIMEOUT_MAX_MS = 180_000;

/**
 * ДОРОГОЙ МОДЕЛИ — БАЗОВЫЙ СРОК ВТРОЕ ДЛИННЕЕ (24.09.2026).
 *
 * Тридцать секунд считались от размера файла, а дорогая модель тратит время не на
 * приём байтов, а на РАЗМЫШЛЕНИЕ над речью — и именно оно даёт качество на
 * таджикском. Живая проба на проде 24.09 двумя записями звонков, которые в тот день
 * ушли на Flash по таймауту (mp3 162 и 393 КБ → срок попытки 31–34 с):
 * gemini-3.1-pro-preview со своими размышлениями отвечает за 42 и 49 с и даёт
 * чистый текст с ценой «350000»; с thinkingLevel "low" — за 12–21 с, но текст на
 * шумной записи заметно хуже (фонетическая каша, цена потеряна). Уровень "medium"
 * не гарантирует размышлений вовсе (0 токенов на той же записи). Значит выбор не
 * между быстро и медленно, а между «pro успевает» и «pro не успевает, отвечает Flash»:
 * за неделю 17–24.09 второе случалось с каждым пятым голосовым (62 отказа из 69 —
 * timeout, не квота), а медиана удачного ответа pro была ровно 30 с — на самой грани.
 *
 * Девяносто секунд: с запасом над измеренными 42–49 с, и две такие попытки всё ещё
 * укладываются в фазу дорогих моделей (TRANSCRIBE_TOTAL_BUDGET_MS минус резерв под
 * дешёвые). Потолок в три минуты общий; прокси Cloudflare режет ответ дольше ~100 с
 * (HTTP 524) — на записях в мегабайты это по-прежнему ведёт к Flash, отдельная тема.
 */
const EXPENSIVE_TIMEOUT_BASE_MS = 90_000;

export function transcribeTimeoutFor(bytes: number, expensive = false): number {
  const megabytes = Math.max(0, bytes) / (1024 * 1024);
  const base = expensive ? EXPENSIVE_TIMEOUT_BASE_MS : TIMEOUT_BASE_MS;
  return Math.min(TIMEOUT_MAX_MS, Math.round(base + megabytes * TIMEOUT_PER_MB_MS));
}

