import { numberToWords, spokenArea, spokenPrice } from "@royal-home/shared";

/**
 * КАК РОБОТ ГОВОРИТ ПО-ТАДЖИКСКИ ПО ТЕЛЕФОНУ — ОДИН ИСТОЧНИК (11.11.2026).
 *
 * Отсюда берут оба пути голоса — ElevenLabs и Gemini Live: блок вставляется в
 * таджикские части промта (ai/liveVoicePersona.ts: исходящие и консультант на
 * входящих), а те собирают промт для любого поставщика. Пока включён замок
 * «только русский», блока в промте нет вовсе (как и прочих таджикских образцов).
 *
 * Откуда фразы:
 *  - скилл владельца tajik-phrasebook (живые фразы операторов и бота, «как не
 *    говорить», числа и время) — фразы, помеченные там проверенными;
 *  - правки владельца таджикских текстов (tajik_ui_edits: узбекизмы «қулай»,
 *    «қизиқ», «бор»; пропущенное «аст» после «мумкин»/«лозим»; «мудир» вместо
 *    «менеҷер»);
 *  - замер 11.11.2026: синтез ElevenLabs читает таджикские ЦИФРЫ с ошибками
 *    («80» распознано как «82» и «800», «1 380 000» — как «1 382 000»), а те же
 *    числа словами — верно. Поэтому числа только словами, и примеры ниже
 *    собраны той же функцией, что сервер отдаёт роботу (packages/shared/spokenNumber).
 *
 * Слова-запреты здесь же продублированы в коде: bannedWordsGuard.ts вырезает
 * «лутфан»/«безаҳмат» из текста бота; в голосе ElevenLabs текст модели до
 * синтеза CRM не видит, поэтому для голоса это правило держит только промт.
 */

const price = spokenPrice(1_380_000, "TJS", "tg");
const priceUsd = spokenPrice(45_000, "USD", "tg");
const perMeter = spokenPrice(850, "USD", "tg");
const area = spokenArea(80, "tg");

/** Числа, цены, время, даты голосом. */
export const TAJIK_PHONE_NUMBERS_RULE =
  `ЧИСЛА ПО-ТАДЖИКСКИ — ТОЛЬКО СЛОВАМИ, НИКОГДА ЦИФРАМИ: синтезатор читает таджикские цифры с ошибками и называет человеку не ту цену. ` +
  `Цена: «${price}», «${priceUsd}», «${perMeter} барои як метр». Площадь: «${area}» или «${numberToWords(80, "tg")} квадрат». ` +
  `Этаж: «ошёнаи ҳафтум аз ${numberToWords(16, "tg")}», «ошёнаи якум». Комнаты: «сеҳуҷрагӣ», «дуҳуҷрагӣ». ` +
  `Время: «соати даҳ», «соати даҳу сӣ», «соати сеи рӯз», «соати шаши бегоҳ». Дата: «понздаҳуми ноябр», день недели словом: «рӯзи панҷшанбе». ` +
  `«Душанбе» — это и город, и понедельник: про день говори «рӯзи душанбе». ` +
  `Номер телефона повторяй группами, как его продиктовали, каждую группу словами.`;

/** Как говорить по-таджикски по телефону: короткие живые фразы. */
export const TAJIK_PHONE_SPEECH_RULES = `ТАДЖИКСКАЯ РЕЧЬ ПО ТЕЛЕФОНУ (одно место для всех звонков, 11.11.2026):
- Только «Шумо» и глаголы во множественном числе: «мехоҳед», «гӯед», «метавонед». «Ту» — никогда.
- Реплика короткая: одна мысль и один вопрос. Не пересказывай человеку то, что он сам сказал.
- Ответ на салом: «Ваалайкум ассалом!». Прощание одно: «Ташаккур, саломат бошед!» — без «агар савол бошад, занг занед» и без приглашения перезвонить.
- Согласие и «понял»: «Ҳа», «Хуб», «Ҳа, фаҳмидам», «Қайд кардам». Благодарность: «Раҳмат» или «Ташаккур».
- Не расслышал: «Бубахшед, хуб нашунидам. Як бори дигар гӯед». Второй раз не вышло — спроси одно слово: «Кадом ноҳия?», «Чанд ҳуҷра?».
- Извиниться: «Бубахшед». За ожидание: «Бубахшед барои таъхир».
- Подождать: «Як дақиқа». Не молчи дольше пары секунд без этих слов.
- Не знаешь или нет в данных: «Инро аниқ агенти мо мегӯяд». Не выдумывай и не обещай срок звонка.
- Просьба — без вежливого слова: «Рақамро гӯед», «Номи худро гӯед». Нельзя: «лутфан», «безаҳмат», «илтимос», «хоҳиш мекунам».
- Нельзя узбекских слов и кальки: «қулай» (говори «мувофиқ» или «хуб»), «қизиқ», «бор», «яхши», «керак», «мудир» про менеджера (говори «менеҷер»). После «мумкин» и «лозим» — «аст»: «мумкин аст», «лозим аст».
- Человек вставляет русские слова — это нормально, отвечай по-таджикски; слова рынка (квартира, этаж, ремонт, коробка, навостройка) говори как он. На русский переходи, только когда он сам заговорил по-русски целыми фразами.
- ${TAJIK_PHONE_NUMBERS_RULE}`;
