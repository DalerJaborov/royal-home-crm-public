/**
 * ЭМОДЗИ ТОЛЬКО В НАЧАЛЕ ФРАЗЫ (решение владельца 20.09.2026: «смайлики надо
 * ставить в начале предложения, а ты везде в подписях ставишь в конце»).
 *
 * Промт об этом просит, но промт — просьба, а не гарантия: модель регулярно
 * заканчивает хук эмодзи, и подпись уходит в Instagram без второй проверки
 * (её у этого генератора нет по решению владельца от 16.09.2026). Поэтому
 * порядок наводится детерминированно, уже после ответа модели.
 *
 * Правится КАЖДАЯ строка отдельно: hook — одна фраза, а closing бывает из двух,
 * и эмодзи в хвосте второй строки так же лишний. Строка, где эмодзи уже стоит
 * в начале, не трогается вовсе — второй эмодзи ей не дописывается.
 */
export function moveTrailingEmojiToStart(text: string): string {
  const TRAILING = /\s*([\p{Extended_Pictographic}\uFE0F\u200D\u{1F3FB}-\u{1F3FF}]+)\s*$/u;
  const LEADING = /^[\p{Extended_Pictographic}\uFE0F\u200D]/u;
  return text
    .split("\n")
    .map((line) => {
      const trimmed = line.trim();
      if (!trimmed || LEADING.test(trimmed)) return line;
      const match = trimmed.match(TRAILING);
      if (!match || match.index === undefined) return line;
      const rest = trimmed.slice(0, match.index).trim();
      // Строка из одного эмодзи: переносить нечего, оставляем как есть.
      return rest ? match[1] + " " + rest : line;
    })
    .join("\n");
}

function factsBlock(v: ReelsCaptionValues): string {
  // Один шаблон с lib/reelsCaptionTemplate.ts: по нему же блок находят и
  // переписывают, когда объект правят после публикации (rewriteCaptionFacts).
  return fillReelsCaptionTemplate(REELS_FACTS_TEMPLATE, v);
}

/**
 * Живой текст на каждую публикацию — hook и closing от Gemini, факты и номера
 * агентства детерминированы. Отказ/пустой ответ модели → прежний шаблонный
 * генератор (бесплатный и не может отказать), чтобы объект НИКОГДА не остался
 * без подписи и не ждал ничьей проверки.
 */
export async function generateReelsCaptionWithAi(
  values: ReelsCaptionValues,
  templatesRaw: string | null | undefined
): Promise<string> {
  const facts = factsBlock(values);
  const result = await callGemini<{ hook?: string; closing?: string }>({
    endpoint: "reels-caption-ai",
    simple: true,
    system: buildCaptionSystemPrompt(),
    user: facts ? `Факты объекта (только контекст, не повторяй их в ответе):\n${facts}` : "Фактов для объекта пока мало.",
    maxTokens: 300,
    schema: HOOK_CLOSING_SCHEMA,
  });

  const hook = result?.hook?.trim();
  const closing = result?.closing?.trim();
  if (!hook || !closing) {
    return generateReelsCaptionFromTemplates(values, templatesRaw);
  }

  const body = [
    moveTrailingEmojiToStart(stripDashes(hook)),
    "",
    facts,
    "",
    moveTrailingEmojiToStart(stripDashes(closing)),
  ]
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return applyContactFooter(body, { fullName: values.agentName, phone: values.phone });
}
