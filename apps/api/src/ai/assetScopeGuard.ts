/**
 * ЗЕМЛЯ И КОММЕРЦИЯ — НЕ НАШЕ ДЕЛО, И РЕШАЕТ ЭТО КОД (разбор 30.08.2026).
 *
 * Агентство продаёт ЖИЛЬЁ в Душанбе: квартиры и дома. Участками, цехами,
 * магазинами, складами, чайхонами и фермами оно не занимается.
 *
 * ЖИВЫЕ СЛУЧАИ. За две недели: участок/замин — три карточки; цех 2000 м²,
 * магазин 13 м², вулканизация, чайхона, ферма, склад, ангар — ещё четыре. И
 * почерк ровно тот же, что с арендой и географией: бот САМ отвечал «участками мы
 * не занимаемся» — и следом заводил лид, который уходил живому агенту.
 *
 * ЧТО ДЕЛАЕМ. Карточка типа OTHER («Прочие обращения», агентам не раздаётся —
 * services/leads/intake.ts). Не полный отказ, как с арендой: владелец такого
 * решения не принимал, а обращение может оказаться поводом для руководства.
 *
 * ПОРОГ — ДВА СИГНАЛА, как в lib/incomingSpam.ts, и по той же причине: одного
 * слова мало. «Магазин» и «мактаб» сплошь и рядом звучат как ОРИЕНТИР («хона
 * наздики магазин» — дом рядом с магазином), и отсечь по одному слову значило бы
 * терять живых покупателей квартир. Нужен объект ИЗ ЧУЖОГО СПИСКА плюс явное
 * намерение по нему (куплю / продам / нужен / сдаётся).
 *
 * ЖИЛЬЁ РЯДОМ СНИМАЕТ ОТСЕЧКУ. «Дом с участком», «хона бо замин» — это обычная
 * продажа дома, наш профиль. Поэтому слова про квартиру/дом отменяют вердикт.
 *
 * Смотрим ТОЛЬКО слова клиента (то же правило, что в ai/rentGuard.ts).
 */

import { BW, EW, TAIL } from "./wordBoundary.js";

const rx = (parts: string[]): RegExp => new RegExp(parts.join("|"), "iu");

/** Участок земли во всех обиходных написаниях. */
const LAND = rx([`${BW}замин`, "қитъаи замин|китъаи замин", `участ(ок|ка|ки)${EW}|уч-?ток`, "сотих|сотка|соток"]);

/** Коммерческая недвижимость и производство. */
const COMMERCIAL = rx([
  `${BW}цех${EW}|производствен`,
  "магазин|мағоза|магоза|дукон|дӯкон",
  `склад|анбор|ангар|${BW}бокс${EW}`,
  "вулканизаци",
  `чойхона|чайхана|ресторан|${BW}кафе${EW}|ошхона`,
  "ферма|молхона|мурғпарвар|мургпарвар",
  `офис${TAIL}\\s+(харид|мехар|мефур|фур[ӯу]ш|лозим|даркор|куп|прода|нужен|ищу)`,
  // «СТО» — автосервис, но так же пишется русское «сто»: «куплю за сто тысяч»
  // уезжало в «коммерческий объект» (разбор 22.09.2026). Берём только запись
  // заглавными или с точками, как её и пишут про автосервис.
  `автомойка|шиномонтаж|заправк|${BW}(СТО|с\\.т\\.о\\.?)${EW}`,
  `салон${TAIL}\\s+(зебо|красот)`,
  `бизнес${TAIL}\\s+(омода|готов)|готовый бизнес`,
]);

/** Намерение по объекту: без него слово из списка — просто ориентир на местности. */
const INTENT = rx([
  "харид|мехар|бихар|мефур|фур[ӯу]ш|мефурӯшам|лозим|даркор|мехоҳам",
  "куп(ить|лю|им|ите)|прода(ть|м|ю|жа|ём|ем)|нужен|нужна|нужно|ищу|ищем|сдаётся|продаётся",
  "\\d+\\s*(м2|м²|кв\\.?\\s*м|квадрат|метр)",
]);

/** Жильё в том же разговоре — отсечки нет: «дом с участком» это дом. */
const HOUSING = rx([
  `кварт(ир|ер)|хонаи истиқомат|${BW}хона|апартамент|манзил`,
  `${BW}дом${EW}|коттедж|таунхаус|ҳавлӣ|хавли`,
  "\\d\\s*(хона|комнат|otoq)|студи[яи]",
]);

export interface AssetScopeVerdict {
  /** Что именно клиент назвал — уходит в требования карточки для руководства. */
  asset: string;
  reason: string;
}

/**
 * Клиент говорит про землю или коммерцию — по его собственным словам.
 *
 * @param clientText только реплики клиента, без ответов бота.
 */
export function detectOutOfScopeAsset(clientText: string): AssetScopeVerdict | null {
  const text = clientText.trim();
  if (!text) return null;
  if (HOUSING.test(text)) return null;
  if (!INTENT.test(text)) return null;

  const land = LAND.exec(text);
  if (land) return { asset: land[0], reason: "участок земли — мы землёй не занимаемся" };

  const commercial = COMMERCIAL.exec(text);
  if (commercial) return { asset: commercial[0], reason: "коммерческий объект — мы коммерцией не занимаемся" };

  return null;
}
