/**
 * ПРАВА БОТА ПО РОЛИ СОБЕСЕДНИКА — гарантия кодом, а не текстом промта.
 *
 * Промт уже подаётся по направлению разговора (buildStableSystem), но ПРАВА от
 * него не зависели вовсе: кандидату на вакансию бот мог предложить назначить
 * показ, а собственнику — выслать подборку квартир, потому что поля схемы и
 * блоки правил выдавались всем одинаково. Просьба «не делай так» в тексте
 * промта — не гарантия: модель её нарушит ровно тогда, когда разговор пошёл
 * необычно, то есть в самом неудобном случае.
 *
 * ФУНКЦИЯ ТОЛЬКО СУЖАЕТ. Она никогда не включает то, что владелец выключил в
 * Настройках: вход — уже готовые права, выход — их подмножество. Иначе роль
 * стала бы вторым местом, где решается, что боту можно, и два места разъехались
 * бы на первой правке.
 *
 * Подчиняется тому же тумблеру «Бот-специалист по типу обращения»: выключен —
 * права ровно те, что пришли, и ни одно поле схемы не меняется.
 */

import type { BotAbilities, LeadIntent, ShowcaseAbility, WhoIsThis } from "./botContract.js";

export interface RoleAbilities {
  abilities: BotAbilities;
  showcase: ShowcaseAbility;
}

/**
 * Что каждой роли НЕ положено. Перечисляем запреты, а не разрешения: список
 * разрешений пришлось бы дополнять при каждом новом умении бота, и забытое
 * умение молча досталось бы всем.
 */
const DENIED: Record<Exclude<LeadIntent, "other">, Partial<Record<keyof BotAbilities | "photos", true>>> = {
  // Покупатель — ради него всё и работает: ничего не снимаем.
  buy: {},
  // Собственнику подборка чужих квартир не нужна ни строкой: он пришёл отдать
  // свою. Показы назначает агент после осмотра, а не бот в переписке.
  sell: { showings: true, links: true, photos: true },
  // Аренда — отказ одной фразой. Любое умение здесь означает продолжение
  // разговора, которого не будет.
  rent: { showings: true, links: true, photos: true, askOwner: true, vacancies: true },
  // Кандидату на вакансию квартиры не показывают. Обратный звонок оставляем:
  // «соедините с человеком» — законная просьба и от кандидата тоже.
  job: { showings: true, links: true, photos: true, askOwner: true },
};

/**
 * ЧЕГО НЕ ПОЛОЖЕНО ТЕМ, КТО ВООБЩЕ НЕ КЛИЕНТ.
 *
 * Рекламный агент, поставщик и застройщик не покупают и не продают жильё, а
 * значит `intent` у них навсегда `"other"` — таблица DENIED выше про них не
 * знает ничего, и до этой второй таблицы они сохраняли ПОЛНЫЙ набор прав. Бот
 * мог отправить рекламщику подборку квартир и предложить ему показ, потому что
 * запрет жил только словами в промте.
 *
 * `callback` («соедините с человеком») остаётся и здесь, как и у всех остальных
 * ролей: это единственное умение, которое не продаёт, а доносит просьбу до
 * живого сотрудника. План от 20.09 пишет для застройщика «всё false», но убрать
 * обратный звонок значило бы потерять просьбу поговорить с руководством — ровно
 * ту, ради которой такой человек и написал.
 */
const NON_CLIENT_DENIED: Partial<Record<WhoIsThis, Partial<Record<keyof BotAbilities | "photos", true>>>> = {
  // Предлагает нам услуги, товары или рекламу.
  VENDOR: { showings: true, links: true, photos: true, askOwner: true, vacancies: true },
  // Застройщик или агентство про сотрудничество: объекты в работу принимает
  // руководство, а не бот в переписке.
  PARTNER: { showings: true, links: true, photos: true, askOwner: true, vacancies: true },
};

/**
 * ЭТО РОЛЬ ЧЕЛОВЕКА, КОТОРОМУ КВАРТИРЫ НЕ ПРЕДЛАГАЮТ?
 *
 * Читается по той же таблице, что снимает права: два списка «кто не клиент» —
 * один для прав, другой для всего остального — разъехались бы на первой правке,
 * и разъезд был бы тихим (бот перестал бы предлагать показ, но продолжил бы
 * присылать подборку). Отвечает на вопрос и тем местам, которые не про права:
 * подборка объектов, например, собирается ДО прав и своим условием.
 */
export function isNonClientRole(who: WhoIsThis | undefined): boolean {
  return !!who && who in NON_CLIENT_DENIED;
}

/**
 * Сузить права под роль разговора.
 *
 * @param intent направление из черновика. `undefined`/`"other"` — направление
 *   ещё не известно (идёт интейк): прав не снимаем, потому что снять их у
 *   покупателя, которого мы просто не успели распознать, дороже, чем лишнее
 *   умение у того, кто им не воспользуется.
 * @param enabled тумблер «Бот-специалист по типу обращения». Выключен — вход
 *   возвращается как есть, побайтово.
 * @param who кто пишет, если модель это поняла (см. WhoIsThis). Смотрим на него
 *   ТОЛЬКО пока намерения нет: у покупателя, один раз помеченного рекламщиком,
 *   намерение перевесит метку — иначе одна ошибка модели выпроводила бы живого
 *   клиента из переписки до конца разговора.
 */
export function abilitiesForIntent(
  base: BotAbilities,
  showcase: ShowcaseAbility,
  intent: LeadIntent | undefined,
  enabled: boolean,
  who?: WhoIsThis
): RoleAbilities {
  if (!enabled) return { abilities: base, showcase };
  const denied = intent && intent !== "other" ? DENIED[intent] : who ? NON_CLIENT_DENIED[who] : undefined;
  if (!denied) return { abilities: base, showcase };
  return {
    abilities: {
      ...base,
      showings: base.showings && !denied.showings,
      links: base.links && !denied.links,
      askOwner: base.askOwner && !denied.askOwner,
      vacancies: base.vacancies && !denied.vacancies,
    },
    showcase: { ...showcase, canSendPhotos: showcase.canSendPhotos && !denied.photos },
  };
}
