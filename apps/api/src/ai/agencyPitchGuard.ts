/**
 * НАМ ПИШУТ КАК АГЕНТСТВУ, А НЕ КАК АГЕНТСТВУ КЛИЕНТ (разбор 30.08.2026).
 *
 * ЖИВОЙ СЛУЧАЙ. В директ пришла реклама конкурирующей площадки объявлений,
 * адресованная нам самим: «даём первым агентам бесплатный месяц PRO, пришлите
 * 2-3 ваших объекта». Существующий фильтр рассылок (lib/incomingSpam.ts) её не
 * увидел: там словарь чужого бизнеса — крипта, ставки, накрутка, — а здесь текст
 * составлен вежливо и по-деловому, ссылки может не быть вовсе. Карточка стала
 * BUYER и ушла живому агенту.
 *
 * ПРИЗНАК, КОТОРОГО НЕ БЫЛО НИ У ОДНОГО ФИЛЬТРА: обращаются к нам КАК К
 * АГЕНТСТВУ. Клиент говорит о себе и своей квартире; коммерческое предложение
 * говорит О НАС — «вашим агентам», «разместите ваши объекты», «для агентств
 * недвижимости», «тариф», «PRO», «бесплатный месяц», «партнёрство».
 *
 * ПОРОГ — ДВА ОЧКА, как в lib/incomingSpam.ts, и по той же причине: ложно
 * принятый за рекламу живой человек уходит молча, и мы даже не узнаем, что его
 * потеряли. Одно слово не решает никогда.
 *
 * ЧТО ДЕЛАЕМ. Полное молчание и никакой карточки — так же, как с рассылкой:
 * решение принимает канал, здесь только вердикт.
 */

import { TAIL } from "./wordBoundary.js";

const rx = (parts: string[]): RegExp => new RegExp(parts.join("|"), "iu");

/** Обращение к нам как к бизнесу, а не разговор о своей квартире. */
const ADDRESSED_TO_AGENCY = rx([
  "ваш(им|его|ему|и)? (агент|риелтор|компани|агентств)",
  "для агентств|агентствам|риелторам|для риелтор",
  `ваш${TAIL}\\s+(объект|объявлен)|разместите (ваши|свои|у нас)`,
  /**
   * «Агентам»/«агентствам» — обращение к цеху, а НЕ голое «агентство»
   * (найдено 20.09.2026 по выгрузке живых переписок, docs/bot-razbor-20-09.md).
   *
   * «Агентство» без предлога адресата — это то, как нас называет обычный
   * человек: «хочу через ваше агентство», «ваше агентство занимается
   * продажей?». Голая основа `агентств` давала первое очко любому такому
   * сообщению, и вместе со вторым очком за «продвижение объявления» продавец
   * получал полное молчание и не получал карточки. Настоящее предложение
   * площадки обращается к цеху во множественном числе — «для агентств»,
   * «агентствам», «вашим агентам», — и это покрыто строками выше и этой.
   *
   * Без `\\b` намеренно: в JS граница слова считается по латинице, и после
   * кириллической «м» её нет вовсе — с ней выражение не совпало бы никогда.
   */
  "агентам",
  "сотрудничеств|партн[её]рств|коллаборац",
  "барои агентӣ|барои агентҳо",
]);

/** Коммерческое предложение площадки: тарифы, доступы, бесплатные периоды. */
const PITCH = rx([
  `тариф|подписк${TAIL} (на|для)|\\bPRO\\b|премиум-?доступ`,
  "бесплатн(ый|о|ая)\\s+(месяц|период|доступ|размещен)",
  "перв(ым|ые)\\s+\\d*\\s*(агент|клиент|пользовател)",
  "наша (платформ|площадк|сайт|биржа)|нашей платформ|новая площадк",
  `регистрац${TAIL} на (сайт|платформ)|зарегистрируйтесь`,
  `продвижен${TAIL} объявлен|реклам${TAIL} объявлен`,
  "пришлите\\s+\\d+[-–]?\\d*\\s*(ваш|объект|объявлен)",
]);

/**
 * СЛОВА СВОЕГО ЧЕЛОВЕКА — ПОЛНАЯ АМНИСТИЯ, СКОЛЬКО БЫ ОЧКОВ НИ НАБРАЛОСЬ
 * (20.09.2026, разбор 775 живых переписок).
 *
 * Живой случай: «хочу продвижение объявления через ваше агентство». Это обычный
 * продавец, который просит нас о работе, — а страж давал ему два очка
 * («агентство» + «продвижение объявления») и отвечал полным молчанием, без
 * карточки. Цена такой ошибки несимметрична: чужую рекламу, принятую за клиента,
 * агент закроет одним движением, а потерянного продавца мы не увидим никогда.
 *
 * Отличает их первое лицо: площадка говорит О НАС и предлагает НАМ, а клиент
 * говорит О СЕБЕ и о своей квартире. Поэтому ищем разговор о собственном жилье
 * или о собственном поиске — на русском и на таджикском.
 */
const SPEAKS_ABOUT_OWN_PROPERTY = rx([
  /**
   * Своя квартира — ТОЛЬКО от первого лица: «моя квартира», «мою трёшку».
   * «Свой» сюда нарочно не входит: в предложении площадки «разместите свой
   * объект» это слово обращено к НАМ, и амнистия по нему отменила бы строку
   * `разместите (ваши|свои|у нас)` выше. Клиент со своей квартирой почти всегда
   * скажет «моя» или «продаю» — и то и другое ловится здесь же.
   */
  "мо(й|я|ю|его|ей|им)\\s+(кварт|дом|хон|участок|земл|коммерц|офис|объект|объявлен)",
  // «у меня есть квартира», «у меня двухкомнатная»
  "у\\s+мен[яи]\\s+(есть\\s+)?(кварт|дом|хон|участок|земл|\\d|одно|двух|трёх|трех|четыр)",
  // Прямое действие от первого лица: продаю/хочу продать/сдаю через вас
  `(хочу|хотел[аи]?\\s*бы|надо|нужно|планиру${TAIL})\\s+(продать|прода[тю]|выставить|разместить\\s+сво)`,
  "прода(ю|ём|ем)\\s|продаётся\\s+мо|выставля(ю|ем)\\s",
  // Свой поиск: «ищу квартиру», «хочу купить»
  `(ищу|подыскива${TAIL}|смотрю)\\s+(кварт|дом|хон|участок|земл)`,
  "(хочу|хотел[аи]?\\s*бы)\\s+(купить|приобрести|посмотреть\\s+кварт)",
  // Таджикский: «хонаи ман», «мехоҳам фурӯшам», «хона мекобам»
  "хона(и|ям)?\\s+(ман|худам)|хонаи\\s+ман",
  "мехоҳам\\s+(фур[ӯу]ш|хар|бифур[ӯу]ш)|мефур[ӯу]ш|мехар",
  `хона\\s+мекоб|кварт${TAIL}\\s+мекоб`,
]);

export interface AgencyPitchVerdict {
  reason: string;
}

/**
 * Похоже ли сообщение на коммерческое предложение, адресованное нашему агентству.
 *
 * @param clientText слова собеседника; известного клиента вызывающий сюда не
 *   ведёт вовсе — своего человека принять за рекламу страшнее (то же правило,
 *   что у detectSpam в lib/incomingSpam.ts).
 */
export function detectAgencyPitch(clientText: string): AgencyPitchVerdict | null {
  const text = clientText.trim();
  if (!text) return null;
  // Человек говорит о СВОЕЙ квартире или о своём поиске — это наш клиент, и
  // никакие очки выше его не отменяют (тот же приём, что BUY_OR_SELL в
  // ai/rentGuard.ts: ложно отсечённый живой человек уходит молча).
  if (SPEAKS_ABOUT_OWN_PROPERTY.test(text)) return null;
  const score = (ADDRESSED_TO_AGENCY.test(text) ? 1 : 0) + (PITCH.test(text) ? 1 : 0);
  if (score < 2) return null;
  return { reason: "коммерческое предложение нашему агентству" };
}
