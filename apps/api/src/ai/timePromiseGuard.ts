import { BW, EW } from "./wordBoundary.js";

/**
 * СРОК ПЕРЕЗВОНА, КОТОРОГО НИКТО НЕ ОБЕЩАЛ (11.11.2026, симуляции робозвонка ElevenLabs).
 * Робот говорил «агент наберёт в течение получаса» — срок взялся из головы модели. Агенты
 * на связи в рабочие часы, и обещание «через полчаса» на деле уходит к человеку как нарушенное.
 *
 * Ловит только ОТНОСИТЕЛЬНЫЙ срок рядом со словом о звонке: «через пять минут», «через
 * полчаса», «в течение часа», «прямо сейчас перезвонит», «буквально через …». Абсолютные
 * слова («сегодня», «завтра после девяти», «в субботу в десять») не трогает: их даёт
 * инструкция звонка (callbackPromiseLine) и функция request_callback.
 *
 * Звук уже в линии: вызывающий (LiveVoiceReplyGuard) только фиксирует находку и отправляет
 * модели поправку; вырезать сказанное нельзя. Тот же приём, что у запрещённых слов.
 */

const CALL_WORD = `${BW}(?:перезвон|набер|набр|позвон|звонок|звонить|свяж|передам|передаю|тамос)\\p{L}*`;
const NUMBER_WORD = `(?:\\d+|пол${BW}|одну|одну|две|двух|три|трёх|трех|четыре|пять|шесть|семь|восемь|девять|десять|пятнадцать|двадцать|тридцать|сорок|пол-?часа|полчаса)`;
const RELATIVE_TIME = [
  // «через пять минут», «через час», «через полчаса», «через 10 минут»
  `${BW}через${EW}\\s+(?:${NUMBER_WORD}\\s+)?(?:минут\\p{L}*|мин${EW}|час\\p{L}*|полчаса|секунд\\p{L}*)`,
  // «в течение получаса / часа / пяти минут»
  `${BW}в${EW}\\s+течени\\p{L}*\\s+(?:${NUMBER_WORD}\\s+)?(?:получаса|полчаса|минут\\p{L}*|час\\p{L}*)`,
  // «прямо сейчас перезвонит», «сию минуту наберёт», «буквально через …»
  `${BW}прямо${EW}\\s+сейчас`,
  `${BW}сию${EW}\\s+минуту`,
  `${BW}буквально${EW}\\s+(?:через|в${EW}\\s+течени)`,
  // таджикский: «баъди ним соат», «дар муддати як соат», «баъд аз панҷ дақиқа»
  `${BW}баъд(?:и|\\s+аз)${EW}\\s+(?:${NUMBER_WORD}\\s+)?(?:дақиқа\\p{L}*|соат\\p{L}*|ним${EW}\\s+соат)`,
  `${BW}дар${EW}\\s+муддати\\s+(?:${NUMBER_WORD}\\s+)?(?:дақиқа\\p{L}*|соат\\p{L}*)`,
];
const RELATIVE_RE = new RegExp(RELATIVE_TIME.join("|"), "giu");
const CALL_RE = new RegExp(CALL_WORD, "iu");
/** «Через две минуты» от самого клиента повторять нельзя тоже, но слово о звонке рядом обязательно. */
const SENTENCE_SPLIT = /[.!?…]+|\n+/u;

/**
 * Относительные сроки перезвона в реплике робота, в порядке появления, без повторов.
 * Пусто — реплика чистая. Срок засчитывается, только если в той же фразе есть слово о звонке.
 */
export function findTimePromises(text: string): string[] {
  const found: string[] = [];
  for (const sentence of text.split(SENTENCE_SPLIT)) {
    if (!sentence.trim() || !CALL_RE.test(sentence)) continue;
    for (const m of sentence.matchAll(RELATIVE_RE)) {
      const phrase = m[0].trim().toLowerCase();
      if (!found.includes(phrase)) found.push(phrase);
    }
  }
  return found;
}

/** Служебная поправка модели (без рода: род вешает мост по голосу). */
export function timePromiseCorrectionText(phrases: readonly string[]): string {
  return `срок «${phrases.join("», «")}» ты не обещал(а) и обещать не вправе: одной фразой поправься — агент свяжется, как только сможет, или в то время, что назвала функция; минуты и «прямо сейчас» не называй`;
}
