/**
 * ГРАНИЦЫ СЛОВА И ОКОНЧАНИЯ — ДЛЯ КИРИЛЛИЦЫ, А НЕ ДЛЯ ЛАТИНИЦЫ
 * (найдено 20.09.2026 при разборе 775 живых переписок, docs/bot-razbor-20-09.md).
 *
 * В JavaScript `\w` и `\b` считаются ПО ЛАТИНИЦЕ даже с флагом `u`: `\w` — это
 * `[A-Za-z0-9_]`, а `\b` — граница между таким символом и любым другим. Для
 * русского и таджикского текста отсюда следуют два молчаливых провала:
 *
 *  · `дом\b` не совпадает НИКОГДА: ни «м», ни пробел после неё не латинская
 *    буква, значит границы между ними нет вовсе. Правило выглядит написанным, а
 *    не работает ни на одном сообщении;
 *  · `продвижен\w* объявлен` не совпадает с «продвижение объявления»: `\w*`
 *    съедает ноль символов, и дальше выражение требует пробел там, где стоит
 *    «и». То есть правило ловит ТОЛЬКО ту форму слова, где окончания нет
 *    совсем, а все остальные — а в наших языках это почти все — пропускает.
 *
 * Стражи из-за этого тихо не срабатывали: в `ai/*Guard.ts` таких правил нашлось
 * семь. Ловушка ровно того рода, о которой предупреждает CLAUDE.md, — код
 * ничего не сообщает, тесты на живых формах слов никто не писал, а поведение
 * отличается от написанного.
 *
 * Здесь лежат три куска выражений, которыми это лечится. `BW`/`EW` уже были
 * написаны дважды — в ai/coverageGuard.ts и ai/assetScopeGuard.ts, — и вынесены
 * сюда, чтобы копии не разошлись (правило «копия логики вместо самой логики» из
 * CLAUDE.md). `TAIL` появился здесь же: та же ошибка, только про окончания.
 */

/** Начало слова: перед ним нет буквы или цифры ЛЮБОГО алфавита. */
export const BW = "(?<![\\p{L}\\p{N}])";

/** Конец слова: за ним нет буквы или цифры ЛЮБОГО алфавита. */
export const EW = "(?![\\p{L}\\p{N}])";

/**
 * Окончание слова любой длины — замена `\w*` там, где основа кириллическая.
 * «офис» + `TAIL` покрывает «офиса», «офисҳо», «офисы», а не только «офис».
 */
export const TAIL = "\\p{L}*";
