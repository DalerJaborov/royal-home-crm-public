/**
 * ЗВОНОК ОПЕРАТОРА — ТОЛЬКО ПО ПРОСЬБЕ САМОГО КЛИЕНТА (владелец 22.09.2026).
 *
 * ЖИВОЙ СЛУЧАЙ. Продавец дачи (WhatsApp, 22.09, карточка «Шахбоз Б.») спокойно
 * рассказал об объекте, БОТ САМ попросил «Рақами телефонатон ва номатонро
 * нависед, то агенти мо занг занад» — и человек прислал номер с именем. Модель
 * прочла свой же вопрос как просьбу клиента и заполнила `callbackRequest`: в
 * карточке первой строкой встало «📞 ПРОСИТ ПЕРЕЗВОНИТЬ», а при назначенном
 * дежурном оператор получил бы пуш «📞 Клиент просит звонок» и автодозвон
 * (lib/callbackRequests.ts). Владелец: «я отвечаю только неизвестным входящим
 * звонкам и тем, кто прямо просит поговорить с оператором лично; продавец,
 * который просто оставил свой номер, — обычный лид агенту».
 *
 * ПОЧЕМУ НЕ ЛЕЧИТСЯ ПРОМТОМ. Описание поля и так говорит «заполняй ТОЛЬКО когда
 * клиент прямо просит живого человека или звонок» (ai/callbackRequest.ts) — и
 * ровно так же, как с географией и арендой, модель исполнила правило наполовину:
 * после собственной просьбы бота «напишите номер, чтобы агент позвонил» любой
 * присланный номер выглядит для неё просьбой о звонке. Значит решает КОД, по
 * СЛОВАМ КЛИЕНТА — тот же приём, что в ai/coverageGuard.ts и ai/rentGuard.ts.
 *
 * ДВА РАЗНЫХ ПОРОГА, И ЭТО НЕ ПРИДИРКА:
 *
 *  · `clientAskedForCallback` — «перезвоните мне», «занг занед». Человек прямо
 *    попросил звонок: пометка «📞 ПРОСИТ ПЕРЕЗВОНИТЬ» в карточке уместна, и
 *    звонит обычный агент обычным порядком.
 *  · `clientAskedForOperator` — «соедините с оператором», «бо одами зинда гап
 *    занам». Только это поднимает дежурного оператора (отдельная запись, пуш,
 *    автодозвон): по решению владельца оператор — не второй агент, а последняя
 *    инстанция для тех, кто именно человека и просил.
 *
 * Ничего не теряется ни в одном случае: просьба, не дошедшая до порога, остаётся
 * обычной заявкой агенту (распределение, «Принять», отчёты) — то же поведение,
 * что при выключенном рубильнике «Соединять с оператором».
 *
 * СМОТРИМ ТОЛЬКО СЛОВА КЛИЕНТА — как в coverageGuard: бот сам произносит «агенти
 * мо занг мезанад» почти в каждом ходе, и по всей переписке подряд любой разговор
 * пометился бы задним числом. Цитата, на которую клиент отвечает, в его реплику
 * не попадает (хранится ссылкой `replyToMid`, см. messengers/conversation.ts), так
 * что процитированный вопрос бота сюда не просачивается.
 */

import { BW, EW, TAIL } from "./wordBoundary.js";
import { stripUntrusted } from "./untrustedContent.js";

const rx = (parts: string[]): RegExp => new RegExp(parts.join("|"), "iu");

/**
 * ПРЯМАЯ ПРОСЬБА О ЖИВОМ ЧЕЛОВЕКЕ. Шире, чем `looksLikeWantsHumanAgent`
 * (ai/complaintGuard.ts, там задача другая — пуш закреплённому агенту): здесь
 * достаточно САМОГО СЛОВА «оператор»/«менеджер» в реплике клиента. Человек,
 * напечатавший боту «оператор», ничего другого этим сказать не может, а
 * ошибиться в эту сторону дёшево — это ровно тот случай, для которого дежурный и
 * заведён.
 */
const WANTS_OPERATOR = rx([
  `${BW}оператор${TAIL}${EW}`,
  `${BW}менеджер${TAIL}${EW}|${BW}мудир${TAIL}${EW}`,
  // Любой падеж: «с живым человеком», «живому человеку» (24.09.2026 — прежняя форма
  // знала только «живой/живого» и пропускала самое частое «с живым человеком»).
  `${BW}(жив|настоящ|реальн)${TAIL}\\s+(человек|сотрудник)${TAIL}|человеком поговорить|с человеком`,
  "соедини(те)?|переключите|передайте (меня )?(живому )?человек",
  "бо (одам|агент|оператор)[^.!?]{0,20}(гап зан|сӯҳбат|сухбат|алоқа|алока)",
  "одами зинда|шахси зинда",
  "маро бо (агент|оператор)[^.!?]{0,20}(пайваст|васл)",
]);

/**
 * ПРЯМАЯ ПРОСЬБА О ЗВОНКЕ. Отрицание сюда попасть не должно: «занг назадед» —
 * это жалоба (ai/complaintGuard.ts), а не просьба, и разбирается она отдельным
 * путём. Поэтому у таджикских форм явно перечислены утвердительные окончания, а
 * не `${TAIL}`: приставка отрицания в таджикском стоит ПЕРЕД корнем («назанед»,
 * «намезанад»), и `зан${TAIL}` поймал бы и её.
 */
const WANTS_CALL = rx([
  // Русский: просьба, а не констатация. «позвоните», «перезвоните», «наберите».
  "(по|пере)?звоните( мне| пожалуйста)?|наберите меня|набери(те)? мне|перезвон(ите|и)",
  "(хочу|можно|нужно|давайте) (по)?говорить по телефону|(хочу|можно) звонок",
  // Таджикский: «занг занед», «занг занен», «занг мезанед?», «тамос гиред».
  "занг\\s+(зан(ед|ен|ет|и)|мезан(ед|ен|ет))",
  "тамос\\s+(гиред|гир|мегиред)",
  "занг\\s+кун(ед|ен|ӣ|и)",
]);

/** Слова самого клиента — без врезок из присланных файлов и заметок CRM.
 *  Расшифровка голосового остаётся: ею человек и диктует просьбу. */
const own = (text: string): string => stripUntrusted(text, ["document", "video", "crm_note"]).trim();

/** Клиент сам, своими словами, попросил звонок (или живого человека: кто просит
 *  человека, тот тем более согласен на звонок). */
export function clientAskedForCallback(clientMessages: string[]): boolean {
  return clientMessages.some((message) => {
    const text = own(message ?? "");
    if (!text) return false;
    return WANTS_CALL.test(text) || WANTS_OPERATOR.test(text);
  });
}

/** Клиент сам попросил ЧЕЛОВЕКА/ОПЕРАТОРА — только это поднимает дежурного. */
export function clientAskedForOperator(clientMessages: string[]): boolean {
  return clientMessages.some((message) => {
    const text = own(message ?? "");
    if (!text) return false;
    return WANTS_OPERATOR.test(text);
  });
}
