/** Чистая: публичный ответ номер `turn` (счётчик таких ответов), по кругу. */
export function commentPhonePublicReply(language: SelfLang, turn: number): string {
  const index = ((Math.trunc(turn) % COMMENT_PHONE_PUBLIC.length) + COMMENT_PHONE_PUBLIC.length) % COMMENT_PHONE_PUBLIC.length;
  return COMMENT_PHONE_PUBLIC[index]![language];
}

