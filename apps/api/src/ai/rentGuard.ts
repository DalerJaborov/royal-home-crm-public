/**
 * АРЕНДА — ПОЛНЫЙ ЗАПРЕТ, РЕШАЕТ КОД, А НЕ МОДЕЛЬ (владелец 21.08.2026).
 *
 * ЖИВОЙ СЛУЧАЙ. В промте квалификатора запрет на аренду стоял с самого начала
 * («RENT: вежливо откажи»), и в шести разговорах из девяти он сработал. А в
 * седьмом человек написал бюджет «3000–5000 сомонӣ» — сумму, за которую квартиру
 * не купить ни в одном районе, и которая очевидна как месячная плата. Модель сама
 * ответила ему «за эти деньги квартир на продажу нет, если вы про аренду, то мы
 * ей не занимаемся» — и тут же выставила intent=buy. Карточка ушла живому агенту
 * как обычный покупатель (клиент №27 на проде).
 *
 * Это ровно тот случай, ради которого в проекте появился offTopicGuard: запрет,
 * который модель нарушает не по глупости, а когда формулировка достаточно
 * необычна. Промт — просьба, а не гарантия. Поэтому «аренду не берём» проверяет
 * код, и его решение сильнее решения модели.
 *
 * ЧТО ЗДЕСЬ НЕ ЛОВИТСЯ, И ЭТО НАРОЧНО. Покупка квартиры, чтобы потом сдавать её,
 * — это ПОКУПКА, наш обычный клиент с деньгами, и терять его нельзя. Поэтому
 * слово про аренду рядом со словом про покупку/продажу отсечку снимает: разбор
 * такого разговора остаётся за моделью.
 *
 * Смотрим ТОЛЬКО слова клиента. Бот сам произносит «иҷора надорем» в каждом
 * отказе — если читать всю переписку подряд, любой корректно отказанный разговор
 * помечался бы арендой задним числом.
 */

import { detectClientLanguage } from "./clientLanguage.js";
import { MIN_MONTHLY_RENT_TJS, MIN_REAL_PURCHASE_TJS } from "./moneyThresholds.js";

const rx = (parts: string[]): RegExp => new RegExp(parts.join("|"), "iu");

/**
 * Человек ищет жильё внаём или сам сдаёт. Оба направления одинаково не наше дело.
 *
 * «кира»/«кироя» и «иҷора»/«ижора» — таджикское «аренда» в двух написаниях,
 * встречаются и кириллицей без диакритики (ҷ→ж, ӣ→и): люди печатают как придётся.
 */
const RENT_WANTED = rx([
  // Таджикский: иҷора/ижора/кироя + глаголы «взять/дать/нужна»
  "и[ҷж]ора|кироя|кирова|кира\\s+(хона|кварт)",
  // Русский: аренда во всех падежах, «снять/сдать» именно жильё
  "аренд(а|ы|у|е|ой|овать|уем|ую)",
  "сн(ять|иму|имаю|имаем)\\s+(кварт|дом|жиль|хон|комнат|квадрат)",
  "сда(ть|ю|ём|ем|ется)\\s+(кварт|дом|жиль|хон|комнат|в\\s+аренду)",
  "кварт(иру|ира)\\s+(на|в)\\s+(месяц|сутки|день|аренду)",
  "посуточн|помесячн",
]);

/**
 * Слова, при которых разговор всё-таки про куплю-продажу: покупка «под сдачу» —
 * законный покупатель, и отсекать его нельзя. Здесь же «фурӯш» (продажа) — хозяин,
 * который сдаёт СЕЙЧАС, но хочет продать, наш продавец, а не арендодатель.
 */
const BUY_OR_SELL = rx([
  "харид|мехар|хоҳам\\s+гир|бихар",
  "куп(ить|лю|им|ит|ите|ля)|покупк|приобрет",
  "фур[ӯу]ш|мефур|прода(ть|м|ю|жа|ём|ем)|на\\s+продаж",
  "ипотек|рассрочк|мортг",
]);

/**
 * Спрашивает ли клиент про аренду — по его собственным словам.
 *
 * @param clientText только реплики клиента, без ответов бота.
 */
export function looksLikeRentRequest(clientText: string): boolean {
  const text = clientText.trim();
  if (!text) return false;
  // Разговор про покупку/продажу с упоминанием аренды разбирает модель: «куплю,
  // чтобы сдавать» — это покупатель, и отсечка здесь сделала бы только хуже.
  if (BUY_OR_SELL.test(text)) return false;
  return RENT_WANTED.test(text);
}

/**
 * Клиент явно заговорил о покупке/продаже — единственный сигнал, которым можно
 * снять уже выставленную метку «аренда» (см. `stickyRentIntent` в
 * ai/leadQualifier.ts). Без этой функции отметка о «купле-продаже» была видна
 * только внутри `looksLikeRentRequest` и наружу не отдавалась.
 */
export function looksLikeBuyOrSellRequest(clientText: string): boolean {
  return BUY_OR_SELL.test(clientText.trim());
}

/**
 * АРЕНДА, НАЗВАННАЯ СУММОЙ, А НЕ СЛОВОМ (решение владельца 03.09.2026).
 *
 * Живой случай, карточка ПК-000250: «2 хуҷрага бо нархи аз 3000 то 4500». Слова
 * «иҷора» нет ни в одном сообщении, а 3000–4500 сомонӣ — это очевидная месячная
 * плата: за эти деньги в Душанбе не купить ничего. Раньше такой разговор шёл
 * дальше как обычная покупка и заканчивался карточкой у живого агента.
 *
 * Владелец выбрал ПОЛНЫЙ ОТКАЗ — тот же, что по слову «иҷора»: ни карточки, ни
 * номера. Отсюда узость правила, потому что цена ошибки здесь — потерянный
 * покупатель:
 *  · сумма должна попадать в вилку месячной платы (500 … 50 000 сомонӣ);
 *  · любое слово о купле-продаже («мехарам», «ипотека», «продаю») отсечку
 *    снимает — покупка «под сдачу» это покупка;
 *  · сумму сюда передаёт ТОЛЬКО черновик, где она уже признана негодной для
 *    бюджета (budgetUnrealistic), — то есть после того, как бот переспросил
 *    «ин ба доллар аст ё ҳазор сомонӣ?» и человек остался при своём.
 */
export function looksLikeRentBudget(budget: number | undefined, clientText: string): boolean {
  if (typeof budget !== "number" || !Number.isFinite(budget)) return false;
  if (budget < MIN_MONTHLY_RENT_TJS || budget >= MIN_REAL_PURCHASE_TJS) return false;
  return !looksLikeBuyOrSellRequest(clientText);
}

/**
 * ОТКАЗ ПО АРЕНДЕ — НА ЯЗЫКЕ КЛИЕНТА И В ОДНОМ МЕСТЕ.
 *
 * Фраза была зашита таджикским текстом сразу в трёх файлах
 * (messengers/conversation.ts, messengers/telegramDirectMessages.ts,
 * telegram/bot.ts) и в промте квалификатора. В выгрузке 775 живых переписок
 * (20.09.2026, docs/bot-razbor-20-09.md) она 11 раз ушла людям, писавшим
 * по-русски: человек спрашивает «сдаёте квартиры?» и получает ответ, которого не
 * понимает. Язык клиента у нас определяется кодом (ai/clientLanguage.ts) — здесь
 * он просто не был применён.
 *
 * Текст таджикского варианта оставлен дословно прежним: его же предписывает промт
 * (ai/leadQualifier.ts), и расхождение между кодом и промтом было бы хуже, чем
 * любая шероховатость формулировки.
 */
export function rentRefusalReply(clientWords: string | null | undefined): string {
  return detectClientLanguage(clientWords ?? "") === "ru"
    ? "Извините, мы занимаемся только покупкой и продажей жилья, аренды у нас нет."
    : "Мутаассифона, мо фақат бо хариду фурӯши хона машғулем ва иҷора надорем.";
}
