import { guardFired } from "./guardMetrics.js";
/**
 * Когда бот сам показывает объект — фотографиями, а не одной ссылкой.
 *
 * Владелец про бота: «как будто отправляет сам лично фотографии». Живой риелтор пишет
 * «зараз расмҳояшро мефиристам» и скидывает снимки; бот же до сих пор умел только дать
 * ссылку — по ней ещё надо перейти, а фото видно сразу. Именно это и выдавало в нём
 * не-человека: он разговаривает, но ничего не ДЕЛАЕТ.
 *
 * Решение «пора показать» принимает модель, а не код: сыпать фотографиями в каждом
 * сообщении — спам, от которого Meta ограничивает отправку, а зашитое правило вроде
 * «после третьего сообщения» одинаково промахивается и на «просто смотрю», и на
 * «дар кучост? расмаша фиристед». Поэтому у инструмента появляется одно поле: номер
 * объекта, который уместно показать ПРЯМО СЕЙЧАС.
 *
 * ЧЕМ именно показать, модель не решает — это зависит от канала и решается кодом
 * (messengers/propertyShowcase.ts). Модуль намеренно не знает ни про Meta, ни про базу:
 * здесь только текст промта и разбор ответа, и это можно проверить тестом без транспорта.
 */

/**
 * Сколько снимков уходит за один раз, если в Настройках ничего не выбрано.
 *
 * Два-три — столько отправляет человек: общий вид, комната, кухня. Двадцать фотографий
 * подряд — это уже не «как человек», а рассылка: клиент получает пачку уведомлений, а
 * Meta считает такое поведение поводом ограничить номер.
 *
 * Само число с 02.08.2026 живёт в Настройках (решение владельца: ни одна цифра не
 * остаётся в коде), а здесь — только значение по умолчанию и запасное на случай
 * недоступной базы. Риск при увеличении не в самой цифре: каждая фотография уходит
 * ОТДЕЛЬНЫМ сообщением, и жалобы на «спам» приходят раньше, чем ограничения Meta.
 */
export const DEFAULT_PHOTOS_PER_OFFER = 3;

/**
 * Поле инструмента submit_reply. Отдаётся куском схемы, а не строкой в промте: так
 * модель не может «почти» выполнить просьбу — она либо назвала номер объекта, либо нет.
 *
 * В канале, куда снимки не уходят, поля НЕТ ВОВСЕ. Оставить его «на всякий случай»
 * означало бы дать модели способ пообещать то, чего код не сделает: она заполнила бы
 * номер, написала «ана расмҳояш», а клиент не получил бы ничего.
 */
export function photoOfferSchemaField(canSendPhotos: boolean): Record<string, unknown> {
  if (!canSendPhotos) return {};
  return {
    showPropertyNumber: {
      type: "number",
      description:
        "Номер объекта из блока «РЕАЛЬНЫЕ ПОДХОДЯЩИЕ ОБЪЕКТЫ» (число после №), который нужно показать клиенту " +
        "прямо сейчас: ему уйдут фотографии этого объекта и ссылка. Заполняй ТОЛЬКО когда клиент " +
        "заинтересовался этим конкретным объектом: спросил про него, попросил фото, отреагировал на присланную " +
        "ссылку. В остальных случаях поле не заполняй вовсе.",
    },
  };
}

/**
 * Правило для промта. Клеится к блоку с подборкой объектов — там же, где модель видит
 * номера, — чтобы «№1042» и «показать объект №» не разъехались по разным углам промта.
 *
 * Про порядок сказано прямо: показ уходит клиенту РАНЬШЕ текста этого же хода (отправку
 * делает сам ход диалога, а текст доставляется после него). Без этой строчки бот писал
 * бы «зараз мефиристам» уже после того, как снимки пришли, и выглядел бы невнимательным.
 *
 * ПОЧЕМУ ПРАВИЛО ЗАВИСИТ ОТ КАНАЛА. Отправлять снимки умеют только каналы Meta (см.
 * messengers/propertyShowcase.ts). В Telegram показа нет вообще, а
 * правило до 01.08.2026 было одно на всех и безусловно велело писать «ана расмҳояш».
 * Там бот сообщал клиенту, что отправил фотографии, и не отправлял ничего — молча,
 * без единой записи в журнале, потому что с точки зрения кода ничего и не произошло.
 */
export function photoOfferPromptRule(
  canSendPhotos: boolean,
  photosPerOffer = DEFAULT_PHOTOS_PER_OFFER,
  /**
   * Рубильник ссылок (Настройки → Бот). Раньше это правило о нём не знало и при
   * выключенных ссылках велело «дай ССЫЛКУ» ровно там, где другое правило
   * (`LINKS_DISABLED_RULE`) запрещает ссылки и обещания прислать их позже.
   * Адресов в блоке объектов при этом нет вовсе — модели оставалось их выдумать
   * (разбор 22.09.2026).
   */
  canSendLinks = true
): string {
  if (!canSendPhotos) {
    const base =
      "\n\nФОТОГРАФИИ В ЭТОТ КАНАЛ ОТПРАВИТЬ НЕЛЬЗЯ. Здесь ты не можешь прислать снимки объекта — такой " +
      "возможности у тебя нет. Поэтому НИКОГДА не пиши «ана расмҳояш», «вот фото», «зараз расмҳояшро " +
      "мефиристам», «сейчас отправлю фотографии» и подобное: клиент не получит ничего, а это выглядит как " +
      "обман. ";
    return canSendLinks
      ? base +
          "Вместо этого дай ССЫЛКУ на объект из списка выше — по ней он увидит и фотографии, и " +
          "подробности. Просят именно фото — так и отвечай: «Ҳамаи расмҳояш ана ин ҷо» и ссылка."
      : base +
          "Ссылку тоже НЕ давай и не обещай прислать её позже — в этом разговоре ссылок у тебя нет. " +
          "Просят именно фото — скажи честно: фотографии покажет агент, и переходи к его словам: " +
          "«Расмҳоро агенти мо нишон медиҳад» / «Фотографии покажет агент». Описывай объект словами: " +
          "район, площадь, этаж, состояние, цена — всё это у тебя есть."
    ;
  }
  return (
    "\n\nПОКАЗАТЬ ОБЪЕКТ. Ты можешь показать объект сам, как живой риелтор: поставь в showPropertyNumber номер " +
    `объекта (число после №) — клиенту уйдут его фотографии (до ${photosPerOffer} штук)${canSendLinks ? " и ссылка" : ""}. Делай ` +
    "это ТОЛЬКО когда клиент заинтересовался КОНКРЕТНЫМ объектом (спросил про него, попросил фото, отозвался на " +
    "ссылку) и не больше одного объекта за ход: пачка снимков в каждом сообщении выглядит рассылкой, а не " +
    "разговором. Всё это клиент получит РАНЬШЕ этого твоего сообщения, поэтому пиши так, будто уже отправил " +
    "(«ана расмҳояш», «вот фото»), а не «сейчас пришлю». " +
    (canSendLinks
      ? "Ссылку на ЭТОТ ЖЕ объект в своём тексте не повторяй — она уже ушла отдельным сообщением; ссылки на " +
        "ДРУГИЕ объекты давай как обычно. "
      : "Ссылок в этом разговоре у тебя нет: никакие ссылки не давай и не обещай. ") +
    "Если фото не просят и разговор ещё об общем — поле не заполняй."
  );
}

/**
 * Пометка про объекты, снимки которых этому собеседнику уже уходили.
 *
 * Предохранитель от повторного показа стоит в коде (messengers/propertyShowcase.ts) и
 * работает молча: модель называет номер, код видит недельную отметку и не отправляет
 * ничего. Текст при этом уже написан — «ана расмҳояш», — и клиент получает обещание
 * без фотографий. Поэтому список уходит модели заранее: пусть она сама не предлагает
 * второй раз то, что код всё равно не отправит.
 */
export function alreadyShownPromptNote(shortIds: number[]): string {
  if (shortIds.length === 0) return "";
  return (
    "\n\nЭТИ ОБЪЕКТЫ ТЫ ЭТОМУ ЧЕЛОВЕКУ УЖЕ ПОКАЗЫВАЛ (фотографии ушли): " +
    shortIds.map((id) => `№${id}`).join(", ") +
    ". Второй раз их снимки отправить нельзя — в showPropertyNumber эти номера не ставь и не пиши про них " +
    "«вот фото». Говорить о самих объектах можно как обычно, и ссылку дать тоже можно."
  );
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * ВТОРОЙ РУБЕЖ поверх словесного запрета выше («ссылку не повторяй») — модель всё
 * равно иногда его нарушает (живой баг 23.08.2026, чат на сайте: карточка объекта
 * ушла ОТДЕЛЬНЫМ сообщением, а бот всё равно продублировал тот же адрес и ту же
 * ссылку в своём тексте). Промт — просьба, а не гарантия; там, где повтор виден
 * КОДУ (siteUrl совпадает с уже показанной карточкой), вырезаем его напрямую,
 * не полагаясь на то, что модель послушается во второй раз.
 */
export function stripDuplicatedCardLink(text: string, siteUrl: string): string {
  if (!text.includes(siteUrl)) return text;
  // Счётчик (совет экспертов, п. 8): модель продублировала ссылку вопреки прямому
  // запрету в промте — считаем, чтобы видеть, насколько промт не держится.
  guardFired("duplicate_card_link");
  return text
    .replace(new RegExp(`[:\\-—]?\\s*${escapeRegExp(siteUrl)}`, "g"), "")
    .replace(/[ \t]{2,}/g, " ")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

/**
 * Номер объекта из ответа модели или null.
 *
 * Ответ модели — внешние данные, и доверять их форме нельзя: строка «1042», ноль,
 * дробь и отрицательное число здесь равно «объекта не назвали». Иначе такой номер
 * доехал бы до запроса в базу и до отправки.
 */
export function parsePhotoOffer(value: unknown): number | null {
  if (typeof value !== "number" || !Number.isInteger(value) || value <= 0) return null;
  return value;
}
