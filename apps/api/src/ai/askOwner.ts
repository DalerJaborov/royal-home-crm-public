/**
 * Вопрос из ответа модели или null.
 *
 * Ответ модели — внешние данные: пустая строка, пробелы и «нет» здесь означают
 * «спрашивать нечего». Без этой проверки в список живых людей падали бы пустые
 * карточки, и его перестали бы читать.
 */
export function parseAskOwner(value: unknown): string | null {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  if (trimmed.length < 5) return null;
  return trimmed.slice(0, 1000);
}
