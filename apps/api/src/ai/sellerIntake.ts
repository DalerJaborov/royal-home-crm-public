/**
 * ПРИЁМ ОБЪЕКТА У ПРОДАВЦА — ОДНИМ ВОПРОСОМ, А НЕ ДОПРОСОМ (решение владельца 18.08.2026).
 *
 * Дословно: «мне надо чтобы ИИ отвечал продавцам сразу вопросы про квартиру которую
 * продают, а не по очереди типа сколько квадратов отдельно а потом район и так далее —
 * все можно сразу отдать информацию спросить и все».
 *
 * ЧТО БЫЛО. Общее правило проекта «ОДИН ВОПРОС ЗА РАЗ» (ai/salesPlaybook.ts и «личность»
 * бота) распространялось и на продавца. Для ПОКУПАТЕЛЯ оно верное: человек ещё сам не
 * знает, чего хочет, и анкета его отпугивает. Для ПРОДАВЦА оно вредное — он про свою
 * квартиру знает всё и готов рассказать разом, а бот вытягивал по одному параметру за
 * реплику. Живая переписка 18.08 (@suhroboqilov0): район → комнаты → ремонт → цена,
 * четырьмя отдельными вопросами, между ними человек успел написать «Интернетон сустай».
 *
 * ПОЧЕМУ ЭТО НЕ ОДНА СТРОЧКА В ПРОМТЕ. В этом проекте промт — просьба, а не гарантия
 * (см. шапку ai/topicLock.ts). Поэтому здесь три части:
 *  1. ТЕКСТ ПРАВИЛА (SELLER_INTAKE_RULES) — приклеивается КОДОМ поверх «личности» из
 *     Настроек, как условия сделки и география. Правка промта владельцем не может его
 *     отменить: иначе правило умерло бы в тот день, когда владелец перепишет промт.
 *  2. КОД СЧИТАЕТ, ЧТО УЖЕ НАЗВАНО (collectSellerFacts) — по всем сообщениям клиента,
 *     а не по памяти модели. Список известного и список недостающего уходят в промт
 *     готовыми, модели остаётся только сформулировать.
 *  3. ФИЛЬТР (asksKnownSellerFact) — вопрос про уже названный параметр снимается кодом
 *     с незакрытого вопроса, чтобы удержание темы (ai/topicLock.ts) не задало его снова.
 *     Ровно на этом в живой переписке бот и споткнулся: клиент написал «2 етаж 8 дар
 *     хона / 360 квадрат», а бот продолжил допрос по своему списку.
 *
 * Модуль намеренно ничего не знает ни про базу, ни про транспорт: разбор текста и текст
 * для модели, всё проверяется тестом без поднятого стенда.
 */

import type { ChatMessage } from "./client.js";
import { clientOwnWords } from "./untrustedContent.js";
import { BW, EW } from "./wordBoundary.js";

/** Что агенту нужно знать об объекте, чтобы не выспрашивать заново. */
export type SellerFactKey = "district" | "rooms" | "area" | "floor" | "condition" | "price";

/** Порядок — тот, в котором параметры перечисляются клиенту одной строкой. */
export const SELLER_FACT_ORDER: SellerFactKey[] = ["rooms", "area", "district", "floor", "condition", "price"];

/** Подписи для промта. Служебные, клиенту не уходят: живую фразу даёт модель на языке клиента. */
const FACT_LABELS: Record<SellerFactKey, string> = {
  district: "район или ориентир",
  rooms: "количество комнат",
  area: "площадь",
  floor: "этаж",
  condition: "состояние (каробка / с ремонтом)",
  price: "цена",
};

export type SellerFacts = Partial<Record<SellerFactKey, true>>;

/**
 * ЧТО СЧИТАЕТСЯ НАЗВАННЫМ.
 *
 * Число рядом с единицей измерения, а не число само по себе: «3200000 Сомони» — цена,
 * а голая «2» в «2 етаж 8 дар хона» ценой не является. Ошибка в эту сторону дешевле
 * обратной: лишний раз не спросим — параметр возьмёт агент по телефону; спросим уже
 * названное — человек решит, что его не читают, и это ровно та жалоба, из-за которой
 * модуль написан.
 */
const FACT_PATTERNS: Record<SellerFactKey, RegExp[]> = {
  // Комнатность: «2-хонага», «3 ҳуҷра», «двухкомнатная», «2 комнаты». Голое «хона»
  // (дом/квартира) сюда не годится — этим словом в таджикском начинается почти любая
  // фраза о жилье, и оно означало бы «комнатность названа всегда».
  // `комн\b` не совпадало НИ С ЧЕМ: `\b` в JS считается по латинице (см.
  // ai/wordBoundary.ts), поэтому «2 комн» и «2 комн.» комнатностью не считались и
  // бот переспрашивал уже названное — ровно та жалоба, из-за которой модуль написан.
  rooms: [
    new RegExp(`\\d\\s*-?\\s*(хонаг|хонаҳ|хуҷра|ҳуҷра|хучра|комнат|комн${EW}|room)`, "iu"),
    /(одно|двух|трёх|трех|четырёх|четырех)комнат/i,
  ],
  // Площадь: «360 квадрат», «54 м2», «120 кв.м», «масоҳаташ 80».
  area: [/\d{2,4}\s*(квадрат|кв\.?\s?м|м\s?2|м²|метр|масоҳат|масохат)/i, /(масоҳат|масохат|площад)\D{0,10}\d{2,4}/i],
  // Этаж: «2 етаж», «5 этаж», «ошёнаи 3», «қабати 4».
  floor: [/\d{1,2}\s*-?\s*(етаж|этаж|ошён|ошиён|қабат|qabat|kabat)/i, /(етаж|этаж|ошён|қабат)\D{0,6}\d{1,2}/i],
  // Состояние: слова, а не числа. «каробка», «бо ремонт», «евроремонт», «под обои».
  // `евро` здесь стояло голым и ловило ВАЛЮТУ: «нархаш 50 000 евро» помечалось
  // названным состоянием, и бот больше не спрашивал «каробка ё бо ремонт?»
  // (разбор 22.09.2026). Ремонт называют «евроремонт» или «евро таъмир» — именно
  // эти формы и берём.
  condition: [
    new RegExp(
      `каробка|коробка|ремонт|таъмир|евро\\s*(ремонт|таъмир)|под\\s*обо|обой|нимтайёр|бе\\s*таъмир`,
      "iu"
    ),
  ],
  // Цена: сумма рядом с валютой либо словом «нарх/цена». Валюта обязательна — иначе
  // площадь «360» и цена «360000» неразличимы.
  price: [
    // `евро\b` тоже было мёртвым: «50 000 евро» ценой не считалось.
    new RegExp(`\\d[\\d\\s.,]{2,}\\s*(сомонӣ|сомони|somoni|доллар|dollar|usd|\\$|евро${EW})`, "iu"),
    /(нарх|цена|стоимост)\D{0,15}\d[\d\s.,]{2,}/i,
  ],
  // Район/ориентир: четыре района Душанбе, слова «тараф/назди/ориентир» и адресные слова.
  // «Дар тарафи политехникум» — это и есть ориентир, и переспрашивать район после него
  // нельзя: человек уже ответил, просто не словарным названием района.
  district: [
    // `сино\b` и `жк\b` не совпадали ни с чем — район «Сино», названный
    // словарным именем, не признавался названным вовсе.
    new RegExp(`исмоил|сомони|${BW}сино${EW}|фирдавс|шохмансур|шоҳмансур`, "iu"),
    new RegExp(
      `тараф|назди|ориентир|кӯча|куча|улиц|маҳалл|махалл|мкр|микрорайон|ҷойгир|чойгир|${BW}жк${EW}`,
      "iu"
    ),
  ],
};

/** Что названо в ОДНОМ сообщении. */
export function extractSellerFacts(text: string): SellerFacts {
  const facts: SellerFacts = {};
  if (!text) return facts;
  /**
   * ЧУЖОЙ ФАЙЛ — НЕ «ПРОДАВЕЦ УЖЕ НАЗВАЛ» (находка 3.1 проверки 21.09.2026).
   *
   * Продавец пересылает скрин чужого объявления и пишет «Ман ҳам мефурӯшам» —
   * из врезки разобранного файла вычитывались комнаты, площадь и цена ЧУЖОЙ
   * квартиры, в промт уходило «названо всё, больше про объект не спрашивай», и
   * про его собственную квартиру мы не узнавали ничего. Свою речь голосом
   * (`voice`) фильтр оставляет: она — его слова (см. clientOwnWords).
   */
  const own = clientOwnWords(text);
  for (const key of SELLER_FACT_ORDER) {
    if (FACT_PATTERNS[key].some((re) => re.test(own))) facts[key] = true;
  }
  return facts;
}

/**
 * Что названо за ВЕСЬ разговор.
 *
 * Только реплики клиента: слова бота — это его вопросы, и считать их ответами значит
 * закрыть все параметры первым же вопросом. Черновик лида (LeadDraft) подмешивает
 * вызывающий: там уже разобранные моделью район и комнаты, а здесь — то, чего в
 * черновике нет вовсе (этаж, состояние, площадь, цена собственника).
 */
export function collectSellerFacts(history: ChatMessage[]): SellerFacts {
  const facts: SellerFacts = {};
  for (const message of history) {
    if (message.role !== "user") continue;
    Object.assign(facts, extractSellerFacts(message.content));
  }
  return facts;
}

/** Чего ещё не хватает — в том порядке, в котором это перечисляется клиенту. */
export function missingSellerFacts(facts: SellerFacts): SellerFactKey[] {
  return SELLER_FACT_ORDER.filter((key) => !facts[key]);
}

/**
 * ПРАВИЛО ПРИЁМА — стабильный текст, уходит в кэшируемую часть промта и приклеивается
 * ПОВЕРХ «личности» из Настроек. Стоять обязано ПОСЛЕ ai/salesPlaybook.ts: там общее
 * «ОДИН ВОПРОС ЗА РАЗ», и отменить его для продавца может только правило, прочитанное
 * позже.
 */
export const SELLER_INTAKE_RULES = `

<приём_объекта_у_продавца>
ЭТО ПРАВИЛО СИЛЬНЕЕ ОБЩЕГО «ОДИН ВОПРОС ЗА РАЗ» И СИЛЬНЕЕ ПРАВИЛА «1-2 КОРОТКИХ ПРЕДЛОЖЕНИЯ». Оно действует ТОЛЬКО с продавцом — с тем, кто предлагает нам свою квартиру или дом (intent=sell). С покупателем всё по-прежнему: по одному вопросу за раз.

ПОЧЕМУ ТАК. Покупатель сам не знает, чего хочет, и анкета его отпугивает. Продавец про свою квартиру знает всё и готов рассказать разом. Вытягивать из него по одному параметру за сообщение — это допрос: он отвечает односложно, раздражается и уходит. Решение владельца 18.08.2026.

КАК СПРАШИВАТЬ. Один раз, ОДНИМ сообщением, попроси перечислить всё сразу — списком, в свободной форме, как ему удобно:
• сколько комнат;
• площадь;
• район или ориентир;
• этаж и этажность дома;
• состояние: каробка или с ремонтом;
• цена, которую хочет собственник.
Так и скажи: «напишите одним сообщением, как вам удобно». Пример по-таджикски: «Барои ҳамин ҳама маълумотро якбора нависед: чандҳуҷрагӣ, чанд метр, кадом тараф, кадом ошёна, бо таъмир ё каробка ва нархаш чанд. Дар як паём нависед, ҳамин кифоя.» По-русски: «Напишите одним сообщением: сколько комнат, площадь, район или ориентир, этаж, состояние и цену. Больше ничего спрашивать не буду.»

ДАЛЬШЕ — ТОЛЬКО ПРО НЕДОСТАЮЩЕЕ И ТОЖЕ ОДНИМ СООБЩЕНИЕМ. Человек ответил не по всем пунктам — не начинай допрос заново по одному. Спроси разом всё, чего не хватает, одной короткой фразой: «Осталось два: этаж и цена». Ниже в промте есть блок «ПРИЁМ ОБЪЕКТА» — в нём КОД уже посчитал, что названо, а что нет. Верь ему, а не своей памяти.

ЧТО НАЗВАНО — ПЕРЕСПРАШИВАТЬ ЗАПРЕЩЕНО. Если человек написал «2 етаж, 360 квадрат», значит этаж и площадь у тебя ЕСТЬ. Спросить их снова — прямая ошибка: он видит на экране, что уже написал это, и делает единственный вывод — его не читают.

СПИСОК ПАРАМЕТРОВ — ЭТО ОДИН ВОПРОС, А НЕ ШЕСТЬ. В Настройках задан предел вопросов за разговор (блок «про_нас»); просьба перечислить всё сразу считается ОДНИМ вопросом, добор недостающего — ВТОРЫМ. Иначе предел исчерпывался бы первой же фразой, и бот замолкал бы, ничего не спросив.

НЕ ДОЖИМАЙ ДО ПОСЛЕДНЕГО ПУНКТА. Один раз спросил всё, один раз добрал недостающее — и хватит. Дальше бери номер и передавай агенту с тем, что есть: неполная карточка лучше потерянного собственника.
</приём_объекта_у_продавца>`;

/**
 * ЧТО УЖЕ СОБРАНО — переменная часть промта (меняется каждый ход, в кэшируемый
 * префикс её класть нельзя: сломает побайтовое совпадение, см. ai/client.ts).
 *
 * Печатается только продавцу: покупателю этот блок стоит токенов на каждом сообщении
 * и не значит ничего.
 */
export function sellerIntakeBlock(facts: SellerFacts): string {
  const known = SELLER_FACT_ORDER.filter((key) => facts[key]);
  const missing = missingSellerFacts(facts);
  const lines: string[] = [];
  if (known.length > 0) {
    lines.push(
      `УЖЕ НАЗВАНО СОБСТВЕННИКОМ (переспрашивать ЗАПРЕЩЕНО): ${known.map((k) => FACT_LABELS[k]).join(", ")}.`
    );
  }
  lines.push(
    missing.length > 0
      ? `ЕЩЁ НЕ НАЗВАНО: ${missing.map((k) => FACT_LABELS[k]).join(", ")}. Спроси это ОДНИМ сообщением, всё сразу.`
      : "НАЗВАНО ВСЁ. Больше про объект не спрашивай — бери номер и имя и передавай агенту."
  );
  return `\n\nПРИЁМ ОБЪЕКТА (посчитано кодом по сообщениям клиента, это точнее твоей памяти): ${lines.join(" ")}`;
}

/**
 * Слова, по которым видно, что вопрос — про этот параметр.
 *
 * Нужны отдельно от FACT_PATTERNS: там ищется ОТВЕТ («360 квадрат»), а здесь ВОПРОС
 * («Чанд метр аст?»), и чисел в нём нет вовсе.
 */
const QUESTION_WORDS: Record<SellerFactKey, RegExp> = {
  rooms: /(чандҳуҷраг|чанд ҳуҷра|чанд хуҷра|чандхонаг|чанд хонаг|сколько комнат|комнатност)/i,
  area: /(чанд метр|чанд квадрат|масоҳат|масохат|площад|квадратур|метраж)/i,
  floor: /(кадом ошён|чанд ошён|кадом қабат|чанд қабат|этаж|етаж)/i,
  condition: /(каробка|коробка|ремонт|таъмир|состояни|ҳолати хона)/i,
  price: /(нарх|чанд доллар|чанд сомон|цен[аыу]|сколько хотите|сколько просите|стоимост)/i,
  district: /(кадом тараф|кадом район|куҷо ҷойгир|куҷо аст|какой район|где находится|ориентир)/i,
};

/**
 * Вопрос спрашивает то, что клиент УЖЕ назвал?
 *
 * Этим кодом снимается незакрытый вопрос удержания темы: без такой проверки код сам
 * дописывал бы клиенту вопрос про этаж после того, как тот написал «2 етаж». Возвращаем
 * ключ параметра, а не просто true, — по нему видно в журнале, что именно сняли.
 */
export function asksKnownSellerFact(question: string | null, facts: SellerFacts): SellerFactKey | null {
  if (!question) return null;
  for (const key of SELLER_FACT_ORDER) {
    if (facts[key] && QUESTION_WORDS[key].test(question)) return key;
  }
  return null;
}
