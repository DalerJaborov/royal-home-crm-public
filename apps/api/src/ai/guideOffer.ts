/** Ответ модели — внешние данные: строку "true" и число 1 признаком не считаем. */
export function parseGuideOffer(value: unknown): boolean {
  return value === true;
}

/**
 * Слова об уже ИЗРАСХОДОВАННОЙ отправке: «отправил», «выслал», «скинул», «прикрепил»,
 * «фиристодам». Будущее («пришлю после подписки») сюда не входит: оно честно.
 */
const SENT_CLAIM = /(?:^|[^\p{L}])(?:отправил|выслал|скинул|прикрепил|фиристод)/iu;

const GUIDE_NOT_SENT_REPLY: Record<"ru" | "tg", string> = {
  ru: "Файл сейчас отправить не получается, но могу рассказать главное словами.",
  tg: "Ҳозир файлро ирсол карда наметавонам, аммо чизи асосиро бо калима мегӯям.",
};

/**
 * ОТВЕТ НЕ ДОЛЖЕН ГОВОРИТЬ «ОТПРАВИЛ», КОГДА ФАЙЛ НЕ УШЁЛ (CHANNEL-NEW-27, аудит 04.10.2026).
 *
 * Промт велит модели при sendGuide=true написать «Отправил, там всё подробно», а сам
 * файл отправляет код и вправе не отправить: Instagram без подписки получает только
 * просьбу подписаться, файл мог не загрузиться, транспорт мог отказать. Разговор шёл
 * дальше с текстом модели как есть, и клиент читал «подпишитесь, пришлю» и «отправил»
 * в одном ответе. Промт тут просьба, а не гарантия: итог отправки известен коду, и
 * он вырезает предложения о совершённой отправке, оставляя ответ по существу. Если от
 * ответа ничего не осталось, а клиенту код сам ничего не сказал, уходит нейтральная
 * фраза: не обман и не пустота.
 *
 * Не трогаем: файл ушёл, файл не просили, файл уходил раньше (тогда повтор «отправил»
 * не ложь, а лишь лишнее слово).
 */
export function reconcileGuideClaim(
  replies: { reply?: string; reply2?: string },
  state: {
    sendRequested: boolean;
    guideSent: boolean;
    alreadySentBefore: boolean;
    language: "ru" | "tg" | "mixed" | "unknown";
    /** Код сам что-то сказал клиенту (просьба подписаться): пустой ответ допустим. */
    codeSpokeToClient?: boolean;
  }
): { reply?: string; reply2?: string } {
  if (!state.sendRequested || state.guideSent || state.alreadySentBefore) return replies;

  const clean = (text: string | undefined): string | undefined => {
    if (!text || !SENT_CLAIM.test(text)) return text;
    // Предложения режем той же функцией, что и щит цены: строки сохраняются.
    const kept = keepSentences(text, (sentence) => !SENT_CLAIM.test(sentence));
    return kept || undefined;
  };

  const reply = clean(replies.reply);
  const reply2 = clean(replies.reply2);
  if (!reply && !reply2 && !state.codeSpokeToClient) {
    const lang = state.language === "tg" || state.language === "mixed" ? "tg" : "ru";
    return { reply: GUIDE_NOT_SENT_REPLY[lang], reply2: undefined };
  }
  return { reply, reply2 };
}
