/**
 * МОДЕЛЬ ПЕРЕПУТАЛА, КТО ПОКУПАЕТ, А КТО ПРОДАЁТ — ЭТО ТОЖЕ ПРОВЕРЯЕТ КОД (разбор
 * 18.09.2026, жалоба агента Нозы: «покупатель приходит как продавец, продавец —
 * как покупатель», подтверждено и на лиде из переписки, не только по звонку).
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ОСТАЛЬНЫХ ОТСЕЧЕК В ЭТОЙ ПАПКЕ. coverageGuard/
 * serviceOfferGuard/assetScopeGuard/rentGuard ловят обращение, которое модель по
 * ошибке считает покупателем/продавцом, хотя оно вообще НЕ про куплю-продажу
 * жилья (чужой город, услуги, земля, аренда). Здесь другой случай: разговор
 * ПРО куплю-продажу жилья, но модель перепутала НАПРАВЛЕНИЕ — «хочу купить
 * квартиру» ушло как intent=sell, или наоборот. Ни одна из старых отсечек этого
 * не ловит: они не проверяют, СОВПАДАЕТ ЛИ заявленное намерение со словами
 * клиента, только не относится ли обращение к другой теме вовсе.
 *
 * ПОЧЕМУ ПОРОГ — ЯВНЫЙ СИГНАЛ ОДНОЙ СТОРОНЫ И ПОЛНОЕ ОТСУТСТВИЕ ДРУГОЙ. Разговор
 * часто содержит оба слова сразу («куплю квартиру, чтобы потом продать старую»,
 * ответ бота повторяет за клиентом «купить/продать») — отсекать по одному
 * найденному слову значило бы ложно снимать обычных покупателей и продавцов
 * пачками. Спорным считается только разговор, где сторона клиента говорит ровно
 * ОДНО направление, а модель классифицировала ПРОТИВОПОЛОЖНОЕ.
 *
 * ЧТО ДЕЛАЕМ С ПРОТИВОРЕЧИЕМ. Не выбираем сторону сами (код не умнее модели в
 * том, ЧТО сказал человек, — умнее только в том, что заявленное направление ему
 * противоречит): решение кода — «не уверены», а не «переставить местами».
 * Возвращаем причину, вызывающая сторона превращает её в OTHER/на разбор
 * человеку — тот же приём, что у остальных отсечек (см. ai/leadKind.ts).
 *
 * ВТОРАЯ ДЫРА ТОГО ЖЕ КЛАССА (разбор 21.09.2026, живой случай карточка №104,
 * Instagram): клиент прислал ТОЛЬКО описание квартиры («Гардиш Ленинград, 1
 * этаж, 51 кв.м, 2-хонага») — не сказал ни «покупаю», ни «продаю». Бот сам
 * спросил наводящим вопросом «Шумо ин хонаро мефурӯшед?» («Вы её продаёте?»),
 * клиент ответил ценой (не подтверждая направление, просто отвечая на заданный
 * вопрос) — и карточка стала SELLER, хотя человек был покупателем. Мismatch-
 * проверка выше здесь МОЛЧИТ: `saysBuy === saysSell === false`, противоречия нет,
 * потому что нет вообще никакого сигнала — ни один единственный. То есть дыра не
 * в «модель перепутала направление», а в «модель угадала направление там, где
 * клиент его не называл вовсе», и виноват в этом не только промт, а и сам
 * наводящий вопрос бота, подсказывающий клиенту одну сторону.
 *
 * Лечится это в двух местах, оба — код, а не только текст промта:
 *  1. `clientStatedDirection` ниже — то же самое различение сигналов, что и в
 *     detectIntentDirectionMismatch, но как отдельная проверка «направление
 *     подтверждено словами клиента» (используется в ai/leadKind.ts при заводе
 *     карточки — там даже отсутствие противоречия не значит согласие);
 *  2. `detectOneSidedDirectionQuestion`/`guardDirectionQuestion` ниже — сам
 *     наводящий вопрос бота ловится и подменяется ДО того, как клиент успеет на
 *     него ответить (см. вызов в messengers/conversation.ts).
 */

const rx = (parts: string[]): RegExp => new RegExp(parts.join("|"), "iu");

/**
 * СЛОВА, КОТОРЫЕ НЕ ГОВОРЯТ НИ О КАКОМ НАПРАВЛЕНИИ, И ИХ НАДО УБРАТЬ ДО ПРОВЕРКИ
 * (правка 22.09.2026).
 *
 * «Хариду фурӯш» — это «купля-продажа» одним словом, название нашего же занятия:
 * его произносит и бот в каждом отказе, и клиент, повторяя за ним. Оно зажигает
 * СРАЗУ ОБА сигнала, а два сигнала — это «направление не названо» (см.
 * `clientStatedDirection`), то есть карточка живого продавца уходит в «Прочие
 * обращения» мимо агентов. То же самое делает русская «купля-продажа».
 *
 * Убираем ровно эти обороты и только их: решать за человека, что перевешивает,
 * по-прежнему не дело кода.
 */
const NEUTRAL_DIRECTION = new RegExp(
  ["хар[иі]ду\\s*фур[ӯу]ш" + TAIL, "купл[яи][\\s-]*продаж" + TAIL].join("|"),
  "giu"
);

/**
 * «У ВАС ЕСТЬ НА ПРОДАЖУ?» — ВОПРОС ПОКУПАТЕЛЯ, А НЕ ЗАЯВЛЕНИЕ ПРОДАВЦА (28.09.2026).
 *
 * Живой случай (WhatsApp, 26.09): «Салом Да 112 мкр хонаи фуруши дорен? ...
 * суратоша партое» — «есть дома на продажу в 112 мкр? пришлите фото». Модель
 * верно назвала покупателем, а SELL_SIGNAL зажёгся на «фуруши», и отсечка
 * увела живого покупателя в «Прочие» мимо агентов. «Хонаи фурӯшӣ дорам/дорем»
 * (у меня/у нас есть дом на продажу) — продавец; «доред/дорен/дорет/дорӣ» —
 * второе лицо, то есть вопрос к НАМ. По-русски тот же класс: «у вас есть
 * квартиры на продажу?», «есть ли в продаже…», «что есть в продаже».
 */
const ASKS_OUR_LISTINGS = new RegExp(
  [
    "фур[ӯу]ш[иӣ]?\\s+(?:ҳам\\s+|хам\\s+)?дор(?:ед|ен|ет|ин|ӣ|и|етон|едон)" + EW,
    "у\\s+вас[^.!?\\n]{0,40}?[нв]а?\\s+продаж" + TAIL,
    "есть\\s+ли[^.!?\\n]{0,40}?[нв]а?\\s+продаж" + TAIL,
    "что\\s+(?:у\\s+вас\\s+)?есть\\s+[нв]а?\\s+продаж" + TAIL,
  ].join("|"),
  "giu"
);

/**
 * Человек хочет ПРИОБРЕСТИ жильё — как для себя, так и через агентство.
 *
 * `хар[иі]д(?!ор|о${EW})`: «харидор» — это «покупатель», СУЩЕСТВИТЕЛЬНОЕ, и чаще
 * всего его говорит как раз продавец («харидор ёбед» — найдите покупателя).
 * Считать его признаком покупки значит снимать с агентов продавцов. Настоящий
 * покупатель называет себя отдельным оборотом ниже («харидор ҳастам»).
 *
 * `|о${EW}` добавлено 22.09.2026 (живой случай ПО-000431, голосовое: «...ягон
 * харидо дошба бошен, ёрдам кунед»): «харидо» — усечённое разговорное «харидор»,
 * без конечного «р», и без этого исключения ловилось той же строкой как будто
 * продавец сам заявил о покупке — рядом с явным «хонаи фуруши» (дом на продажу),
 * из-за чего оба направления зажигались одновременно и clientStatedDirection()
 * возвращал null вместо однозначного «продаю».
 */
const BUY_SIGNAL = rx([
  `хар[иі]д(?!ор|о${EW})|мехар|бихар|мехоҳам\\s+гир`,
  // «харам»/«харем» — «куплю»/«купим» без приставки: «Мехоҳам хона харам».
  // Отдельной строкой и с границами слова, потому что «хар» само по себе в
  // таджикском значит совсем другое.
  BW + "хар[ае]м" + EW,
  "харидор\\s+(ҳастам|мебошам|шудан)",
  "куп(ить|лю|им|ит|ите|ля)|покупк|приобрет",
  // Опечатки без «ь» и через «а»: «купит», «кпить», «пакупаю» (22.09.2026).
  // «покупатель» нарочно не ловим: «ищу покупателя» — слова продавца.
  BW + "(кп[иі]ть?|п[ао]купа(ю|ть|ем))" + EW,
  "ищ[ую]\\s+(кварт|дом|жиль|хон)|нужна?\\s+кварт|подбер(ите|и|у)\\s+кварт",
  "ипотек|рассрочк",
]);

/**
 * Человек хочет РАЗМЕСТИТЬ/ПРОДАТЬ СВОЙ объект через агентство.
 *
 * ПЕРЕПИСАНО 22.09.2026: прежние правила не совпадали с самыми обычными русскими
 * фразами продавца. `моя\s+кварт\w*\s+…` было мертво целиком (`\w*` после
 * кириллицы съедает ноль символов, а дальше требуется пробел — на его месте «и»
 * из «квартира»), а перечисление окончаний `прода(ть|м|ю|жа|ём|ем|ется)` не
 * покрывало ни «продажу», ни «продаётся» через «ё». Проверено прогоном: «Моя
 * квартира на продажу», «Квартира на продажу, 3 комнаты», «Продаётся квартира»
 * и «Хочу выставить квартиру» не распознавались НИ ОДНОЙ формой — а с 21.09.2026
 * нераспознанное направление означает карточку в «Прочих» мимо агента.
 *
 * Поэтому здесь основы с `TAIL`, а не списки окончаний: в наших языках окончание
 * есть почти всегда, и перечислить их все никто не успевает.
 */
/**
 * «Я СОБСТВЕННИК» — ТОЖЕ ПРОДАВЕЦ, ХОТЯ ГЛАГОЛА «ПРОДАЮ» НЕТ (28.09.2026).
 *
 * Живой случай (Facebook, скриншот владельца): под постом объекта человек написал
 * «Ман сохибхона))», затем «Ман сохибхона, мегум дар эълон нархаша арзотар монем»
 * (я хозяин, давайте в объявлении цену пониже). Ни одной формы «фурӯш» — и бот
 * отвечал ему как покупателю: «торг после показа с собственником», «оставьте
 * номер». Ловим только слова о СЕБЕ: «рақами соҳиби хонаро диҳед» (дайте номер
 * хозяина) говорит покупатель, и это не сигнал. «х» вместо «ҳ» — обычное
 * написание с телефона, поэтому `[хҳ]` везде.
 */
// Основы слова «хозяин/собственник» во всех написаниях, что встречаются с телефона:
// таджикское соҳиб через «ҳ», «х», «h», «ҳ» пропущено («соиб»), «а» вместо «о»;
// русское с опечатками (собствиник, сабственик, хазяин, владелиц-); латиница.
const OWNER_ROOT =
  "(?:с[оа](?:[хҳh]|х[ьъ])?иб|sa?o?[hx]i?b|с[оа]бств\\p{L}{0,3}?ни[кц]|х[оа]зя[ие]|х[оа]зяйк|владел[еи]ц|владелиц|" +
  "sobstvenni[kc]|xoz[yj]a|hoz[yj]a|мулкдор|mulkdor)";
const ME = "(?:ман|манам|мана|худам|худи\\s+ман|я|ya|man|manam|xudam)";
export const OWNER_CLAIM = rx([
  // «ман соҳиб…», «ман худам сохибаш», «я собственник», «я сама хозяйка», «man sohibi»
  BW + ME + "\\s+(?:(?:худам|худи|сам[аи]?|и\\s+есть|же|xudam)\\s+)?" + OWNER_ROOT + TAIL,
  // «соҳиби хона ман(ам)», «сохибхона манам», «хозяин это я», «собственник — я»
  BW + OWNER_ROOT + TAIL + "(?:\\s*(?:и\\s*)?хона" + TAIL + ")?(?:\\s+ин)?\\s*[-—,:]?\\s*(?:это\\s+|ин\\s+)?" + ME + EW,
  // «хонаи худам», «хонаи ман», «хонаамро фурӯш…» — жильё о себе
  BW + "(?:хона|ҳавли|хавли|квартира|дом)" + TAIL + "\\s+(?:ман|худам|худи\\s+ман)" + EW,
  BW + "(?:хонаам|ҳавлиям|хавлиям)" + TAIL,
  // «моя квартира», «это мой дом», «квартира моя», «наша квартира»
  BW + "(?:мо[яйю]|наш[аиу]?)\\s+(?:кварт|дом|хат|участ|объект)" + TAIL,
  BW + "(?:кварт|дом|хат)" + TAIL + "\\s+(?:мо[яйё]|наш[аи]?)" + EW,
  // «продаю сам», «без посредников», «от собственника» — как в lib/listingAd.ts
  BW + "(?:прода[юё]\\s+сам|без\\s+посредник|бе\\s+миёнарав|от\\s+собственник|аз\\s+со[хҳ]иб)" + TAIL,
]);

const SELL_SIGNAL = rx([
  OWNER_CLAIM.source,
  "фур[ӯу]ш(?!анда" + TAIL + "|гоҳ" + TAIL + "|гар" + TAIL + ")|мефур(ушам)?",
  "прода(ть|м|ю|[её]т|[её]м|ём|ем|вец|вца)" + TAIL,
  "прода[её]тся|на\\s+продаж" + TAIL + "|в\\s+продаж" + TAIL,
  "выставит[ья]?" + TAIL + "\\s+(на\\s+продаж|объект|кварт|дом|хон)",
  "разместит[ья]?" + TAIL + "\\s+(объект|кварт|дом|хон)",
  "хочу\\s+продать|решил[аи]?\\s+продать|собира(юсь|емся)\\s+продать",
  // Живые опечатки и формы (прод 21-22.09.2026): «Хачу продат сваю квартиру»,
  // «Прадат», «дар хона Мефрушум», «фурӯхтан мехоҳам» (прошедшая основа «фурӯхт»).
  BW + "пр[ао]д[ао]т" + TAIL,
  "мефр[уӯ]?ш" + TAIL + "|фур[ӯу]хт" + TAIL,
]);

export interface IntentDirectionMismatch {
  /** Короткая причина для метки карточки и журнала. */
  reason: string;
}

/**
 * Направление, которое клиент назвал СВОИМИ словами (buy/sell), или `null`, если
 * ни разу не сказал ни того, ни другого — либо сказал ОБА сразу (тогда решать,
 * что перевешивает, — не дело кода, см. заголовок файла).
 *
 * Общая основа для `detectIntentDirectionMismatch` (там «не совпадает с
 * заявленным») и для ai/leadKind.ts (там «вообще подтверждено хоть чем-то»)
 * — тот же регэксп, два разных вопроса поверх него, без копии паттернов
 * (правило «копия логики вместо самой логики» из CLAUDE.md).
 */
export function clientStatedDirection(clientText: string): "buy" | "sell" | null {
  const raw = clientText?.trim();
  if (!raw) return null;
  // Нейтральные обороты убираются ДО проверки, иначе «хариду фурӯш» зажигает оба
  // сигнала и направление считается неназванным (см. NEUTRAL_DIRECTION).
  // Вопрос «что у вас есть на продажу» — слова ПОКУПАТЕЛЯ, хотя в нём «продажа»
  // (см. ASKS_OUR_LISTINGS): вырезается до проверки продажи и сам засчитывается покупкой.
  const neutral = raw.replace(NEUTRAL_DIRECTION, " ");
  const asksListings = new RegExp(ASKS_OUR_LISTINGS.source, "iu").test(neutral);
  const text = neutral.replace(ASKS_OUR_LISTINGS, " ");
  const saysBuy = asksListings || BUY_SIGNAL.test(text);
  const saysSell = SELL_SIGNAL.test(text);
  if (saysBuy === saysSell) return null;
  return saysBuy ? "buy" : "sell";
}

/**
 * Заявленное направление (BUYER — модель считает покупателем, SELLER — продавцом)
 * противоречит словам клиента: он явно говорил про ОБРАТНОЕ и ни разу — про
 * заявленное.
 *
 * @param clientText только слова клиента (сообщения в переписке либо пересказ
 *   разговора для звонка — модель сама формулирует его по-русски, поэтому здесь
 *   те же паттерны работают для обоих каналов).
 */
export function detectIntentDirectionMismatch(
  clientText: string,
  claimedKind: "BUYER" | "SELLER"
): IntentDirectionMismatch | null {
  const stated = clientStatedDirection(clientText);
  if (!stated) return null;

  if (claimedKind === "SELLER" && stated === "buy") {
    return { reason: "модель назвала продавцом, а клиент говорил только о покупке" };
  }
  if (claimedKind === "BUYER" && stated === "sell") {
    return { reason: "модель назвала покупателем, а клиент говорил только о продаже своего объекта" };
  }
  return null;
}

/**
 * НАВОДЯЩИЙ ВОПРОС БОТА — ОТДЕЛЬНЫЙ НАБОР СИГНАЛОВ, А НЕ BUY_SIGNAL/SELL_SIGNAL
 * (владелец 21.09.2026, уточнение к задаче про карточку №104).
 *
 * BUY_SIGNAL/SELL_SIGNAL выше настроены на слова КЛИЕНТА О СЕБЕ — от первого
 * лица или в повелительном/инфинитивном виде («хочу купить», «продаю», «ищу
 * квартиру»). Наводящий вопрос бота — это ВТОРОЕ лицо («вы продаёте?», «вы
 * покупаете?»), и это разные формы: «продаёте» не совпадает ни с одной формой
 * из SELL_SIGNAL («прода(ть|м|ю|жа|ём|ем|ется)» — «ёте» там нет), а значит
 * дублировать эти регэкспы для другой задачи означало бы либо молчать на ровно
 * тех фразах, которые владелец назвал примером, либо незаметно разъехаться с
 * BUY_SIGNAL/SELL_SIGNAL при следующей правке одного из двух списков. Поэтому
 * это осознанно отдельный, маленький набор — под конкретную, другую роль
 * говорящего (бот про клиента, а не клиент про себя).
 */
/**
 * «Продать» и «купить» голыми инфинитивами добавлены НАРОЧНО (а не только
 * составными «хотите продать»/«продавать хотите»): нейтральный двусторонний
 * вопрос вида «вы хотите купить или продать?» иначе ловился бы только с одной
 * стороны («хотите купить» есть рядом, а «продать» после «или» — само по себе,
 * без «хотите» вплотную) и считался бы наводящим там, где он уже нейтральный.
 * Голый инфинитив реже встретится в вопросе клиенту случайно, чем в обычном
 * ответе о делах агентства, — цена ложного срабатывания здесь низкая: лишняя
 * подмена на нейтральный вопрос никого не отталкивает.
 */
const SELL_QUESTION_SIGNAL = rx(["мефур[ӯу]шед", "фур[ӯу]хтан\\s+мехоҳед", "продаёте", "продавать\\s+хотите", "хотите\\s+продать", "продать"]);

const BUY_QUESTION_SIGNAL = rx(["мехаред", "харидан\\s+мехоҳед", "покупаете", "купить\\s+хотите", "хотите\\s+купить", "купить"]);

export interface OneSidedDirectionQuestion {
  /** Какую сторону наводящий вопрос предполагает — её и заменяем на нейтральную. */
  assumedSide: "BUYER" | "SELLER";
}

/**
 * Реплика бота — вопрос, предполагающий ОДНУ сторону («мефурӯшед?», «продаёте?»
 * либо «мехаред?», «покупаете?»), без второго варианта в том же тексте. Если
 * прозвучали ОБА варианта («покупаете или продаёте?») — вопрос уже нейтральный,
 * подменять нечего; вернём `null`, как и когда не прозвучало ни одного.
 */
export function detectOneSidedDirectionQuestion(botText: string): OneSidedDirectionQuestion | null {
  const text = botText?.trim();
  if (!text || !text.includes("?")) return null;
  // Смотрим только сами ВОПРОСЫ (02.10.2026). Раньше признак искался по всему
  // пузырю: «Квартира стоит 85 000 $. Если решите купить, оформим ипотеку. Когда
  // удобно посмотреть?» — «купить» в утверждении плюс «?» в другом предложении —
  // и весь ответ с ценой заменялся на «Вы хотите купить или продать?».
  const questions = questionSentences(text).join(" ");
  if (!questions) return null;
  const asksSell = SELL_QUESTION_SIGNAL.test(questions);
  const asksBuy = BUY_QUESTION_SIGNAL.test(questions);
  if (asksSell === asksBuy) return null;
  return { assumedSide: asksSell ? "SELLER" : "BUYER" };
}

/** Предложения, кончающиеся вопросительным знаком. */
function questionSentences(text: string): string[] {
  return (text.match(/[^.!?\n]*\?+/g) ?? []).map((q) => q.trim()).filter(Boolean);
}

/** Пузырь без наводящих вопросов; пустая строка — если ничего другого в нём не было. */
function withoutOneSidedQuestions(bubble: string): string {
  return bubble
    // Уходят ВСЕ вопросы пузыря, а не только наводящий: соседний («Нархаш чанд
    // аст?» после «мефурӯшед?») стоит на той же догадке о стороне, и два вопроса
    // подряд — уже не разговор. Утверждения (цена, факты) остаются.
    .replace(/[^.!?\n]*\?+/g, "")
    .replace(/[ \t]{2,}/g, " ")
    .replace(/[ \t]*\n[ \t]*/g, "\n")
    .trim();
}

/** Нейтральная замена наводящему вопросу — по языку клиента (см. ai/clientLanguage.ts). */
interface NeutralPhrase {
  tg: string;
  ru: string;
}

/**
 * САМЫЙ ПЕРВЫЙ ОТВЕТ БОТА В РАЗГОВОРЕ (уточнение владельца 21.09.2026): ни слова
 * про направление, даже нейтрального «покупаете или продаёте?» — просто
 * приветствие и открытый вопрос «чем помочь». Направление угадывать нельзя НИ
 * ОДНИМ способом, включая «предложить оба варианта сразу»: клиент мог написать
 * вообще не про покупку-продажу (см. SCENARIO_OTHER в ai/leadQualifier.ts).
 */
export const NEUTRAL_FIRST_REPLY: NeutralPhrase = {
  tg: "Ассалому алейкум! Чӣ хизмат карда метавонем?",
  ru: "Здравствуйте! Чем можем помочь?",
};

/**
 * РАЗГОВОР УЖЕ ИДЁТ, а направление всё ещё не ясно — нейтральный вопрос с ОБОИМИ
 * вариантами сразу, вместо наводящего с одним.
 */
export const NEUTRAL_DIRECTION_QUESTION: NeutralPhrase = {
  tg: "Шумо хона мехаред ё мефурӯшед?",
  ru: "Вы хотите купить или продать?",
};

export interface DirectionQuestionGuardInput {
  /** Сырые пузыри ответа модели — до прочих проверок (см. заголовок файла: этот
   *  фильтр должен стоять РАНО, как и ai/oneQuestionGuard.ts). */
  bubbles: string[];
  /** Слова КЛИЕНТА за весь разговор (тот же смысл, что у clientText выше:
   *  реплики бота и недоверенные вложения исключены вызывающим кодом). */
  clientText: string;
  /** Бот уже отвечал в этом разговоре раньше (см. botSpokeBefore в
   *  messengers/conversation.ts) — решает, приветствие это или уже нет. */
  botSpokeBefore: boolean;
  language: ClientLanguage;
}

/**
 * КОДОВАЯ СТРАХОВКА ПОВЕРХ ЗАПРЕТА В ПРОМТЕ (см. заголовок файла и
 * royal-home-prompt-is-not-a-guarantee): пока направление не названо клиентом,
 * наводящий вопрос бота в исходящей реплике подменяется, а не улетает клиенту.
 *
 * Направление уже названо клиентом (`clientStatedDirection` вернул значение) —
 * подмены нет вовсе, даже если бот зачем-то всё равно спросил: спрашивать в этом
 * случае можно, вопрос не наводящий, а уточняющий.
 */
export function guardDirectionQuestion(input: DirectionQuestionGuardInput): string[] {
  if (clientStatedDirection(input.clientText)) return input.bubbles;
  const triggered = input.bubbles.some((b) => detectOneSidedDirectionQuestion(b) != null);
  if (!triggered) return input.bubbles;
  guardFired("direction_question");

  if (!input.botSpokeBefore) {
    /**
     * ПЕРВЫЙ ОТВЕТ БОТА — ТОЛЬКО ПРИВЕТСТВИЕ (уточнение владельца 21.09.2026).
     * Остальные пузыри модели (в том числе сам наводящий вопрос и всё, что
     * модель успела дописать рядом с ним) выбрасываем целиком, а не оставляем
     * вперемешку с приветствием: «чем помочь» — это весь первый ответ.
     */
    return [input.language === "ru" ? NEUTRAL_FIRST_REPLY.ru : NEUTRAL_FIRST_REPLY.tg];
  }

  // Разговор уже идёт — подменяем ТОЛЬКО сам наводящий вопрос, остальной текст
  // пузыря (факты, цена, что угодно ещё) остаётся на месте (02.10.2026: раньше
  // уходил весь пузырь вместе с ценой).
  const neutral = input.language === "ru" ? NEUTRAL_DIRECTION_QUESTION.ru : NEUTRAL_DIRECTION_QUESTION.tg;
  let replacedOnce = false;
  return input.bubbles
    .map((bubble) => {
      if (!detectOneSidedDirectionQuestion(bubble)) return bubble;
      const rest = withoutOneSidedQuestions(bubble);
      // Второй такой пузырь в одном ответе — редкость; не дублируем нейтральный
      // вопрос дважды.
      if (replacedOnce) return rest;
      replacedOnce = true;
      return rest ? `${rest} ${neutral}` : neutral;
    })
    .filter((b) => b.trim().length > 0);
}

/**
 * СОБСТВЕННИКУ НЕ ГОВОРЯТ «ТОРГ С СОБСТВЕННИКОМ» (28.09.2026, скриншот владельца).
 *
 * Человек дважды написал «Ман сохибхона», а бот отвечал ему как покупателю:
 * «Савдо аслан баъди хонаро дидан бо соҳиби хона карда мешавад» и «агенти мо …
 * ҳамаашро бо соҳиби хона мебинад». Промт теперь это запрещает, но промт —
 * просьба, а не гарантия. Пока клиент назвал себя хозяином (OWNER_CLAIM), пузырь,
 * говорящий о собственнике как о третьем лице, подменяется одной фразой «понял,
 * передам агенту вашего объекта», остальные такие пузыри убираются.
 */
const OWNER_AS_THIRD_PARTY = rx([
  "(?:бо|ба|аз|с|у)\\s+" + OWNER_ROOT + TAIL,
  OWNER_ROOT + TAIL + "(?:\\s*(?:и\\s*)?хона" + TAIL + ")?\\s+(?:розӣ|рози|мегӯяд|мегуяд|медонад|ҳал|хал|решает|скажет|согласит|договор)" + TAIL,
  "(?:савдо|торг)" + TAIL + "[^.!?\\n]{0,60}?(?:после\\s+показ|баъди|пас\\s+аз|дидан)",
]);

export const OWNER_ACK: NeutralPhrase = {
  tg: "Фаҳмидам, Шумо соҳиби хона ҳастед. Гапи Шуморо ба агенти мо, ки хонаатонро мебарад, мерасонам, ӯ бо Шумо тамос мегирад.",
  ru: "Понял, вы собственник. Передам ваши слова агенту, который ведёт ваш объект, он с вами свяжется.",
};

/** Реплика бота говорит о собственнике как о третьем лице (см. выше). */
export function ownerAsThirdParty(text: string): boolean {
  return OWNER_AS_THIRD_PARTY.test(text);
}

export function guardOwnerAsThirdParty(input: { bubbles: string[]; clientText: string; language: ClientLanguage }): string[] {
  if (!OWNER_CLAIM.test(input.clientText ?? "")) return input.bubbles;
  if (!input.bubbles.some((b) => OWNER_AS_THIRD_PARTY.test(b))) return input.bubbles;
  guardFired("owner_as_third_party");
  const ack = input.language === "ru" ? OWNER_ACK.ru : OWNER_ACK.tg;
  let replaced = false;
  return input.bubbles
    .map((b) => {
      if (!OWNER_AS_THIRD_PARTY.test(b)) return b;
      if (replaced) return "";
      replaced = true;
      return ack;
    })
    .filter((b) => b.trim().length > 0);
}
