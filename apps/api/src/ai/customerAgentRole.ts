/** Фраза кончается отрицанием: «Мефурӯшам не», «продаю нет» (слепое ревью #345). Только в самом конце: «продаю не дорого» — продаёт. */
const NEGATED_AFTER = /^ (?:не|нет|нест)$/u;
/** True when at least one match is not negated: "не"/"намехоҳам" before (one filler word, not a role verb), "не" at the very end. */
function plain(norm: string, patterns: RegExp | readonly RegExp[]): boolean {
  for (const pattern of Array.isArray(patterns) ? patterns : [patterns]) {
    for (const match of norm.matchAll(pattern)) {
      if (NEGATED_BEFORE.test(norm.slice(Math.max(0, match.index - 30), match.index))) continue;
      if (NEGATED_AFTER.test(norm.slice(match.index + match[0].length))) continue;
      return true;
    }
  }
  return false;
}

/**
 * «Хона мехоҳам, пул дорам» — «хочу дом, деньги есть» (аудит 14.11.2026): покупатель, а не «у меня есть дом» (OWN_HOUSING).
 * Не покупатель, если жильё СВОЁ (притяжательное -ам/-амро: «хонаамро», «хонаи худам») или в сообщении слово продажи
 * («Хонаамро мехоҳам фурӯшам» — «свой дом хочу продать», ревью 14.11).
 */
const HOUSING_WISH = re(`${BW}(${HOUSING})${EW}( (?:ман|худам)${EW})? мехо(?:х|ст)\\p{L}*${EW}`);
const POSSESSIVE_HOUSING = /(?:ам|амро|ем|емро|имро)$/u;
const SELL_WORD = /фур[уо]ш|фурух|продат|прод[ао]ват|прадат|прадаю|прадам|продаю|продам|продаж|сдам|сдаю|сдат|ичора ме/u;
function housingWish(norm: string): boolean {
  if (SELL_WORD.test(norm)) return false;
  for (const match of norm.matchAll(HOUSING_WISH)) {
    if (POSSESSIVE_HOUSING.test(match[1] ?? "") || match[2]) continue;
    if (!NEGATED_BEFORE.test(norm.slice(Math.max(0, match.index - 30), match.index))) return true;
  }
  return false;
}

export type CustomerRoleSignals = { buyStrong: boolean; buyWeak: boolean; sell: boolean; landlord: boolean; rent: boolean;
  /** И продать своё, и купить другое — в одном сообщении. */ both: boolean;
  /**
   * Роль по СИЛЬНЫМ явным словам («мефурӯшам», «продаю», «хочу продать», «харидан мехоҳам», «куплю», «нужен покупатель»):
   * только она решает роль поверх модели (слепое ревью #345). Остальное (вопрос о цене и месте, «хона дорам», «пул дорам»,
   * «… даркор», «бо савдо») — подсказка: при споре с моделью бот спрашивает «купить или продать?». И продать, и купить —
   * «seller» (заявка продавца, покупка в заметке).
   */
  strong: "buyer" | "seller" | null;
  /** Говорит о СВОЁМ жилье («хонаам», «хонаи ман», «моя квартира», «у меня есть дом»). */
  ownHouse: boolean;
  /** Нужна услуга, а не жильё: «хона реклама / агент / харидор даркор» — не покупатель (слепое ревью #345). */
  serviceWanted: boolean };
export function customerRoleSignals(text: string): CustomerRoleSignals {
  const norm = foldCustomerTextForRole(text);
  const asked = /[?؟]/u.test(text);
  const question = asked || ASKING.test(norm);
  const passive = plain(norm, SELL_PASSIVE);
  const landlord = plain(norm, LANDLORD_TG) ||
    (plain(norm, LANDLORD_ACTIVE) || (plain(norm, LANDLORD_PASSIVE) && !question)) && (RENT_HINT.test(norm) || HOUSING_WORD.test(norm));
  // Сильные слова продажи перекрывают вопрос о цене и месте: «Хонаамро мефурӯшам, нархаш чанд мешавад?» — продавец спрашивает
  // о СВОЁМ (слепое ревью #345). Своё жильё («хонаам», «хонаи ман») вопрос о цене тоже не делает покупательским.
  const ownHouse = plain(norm, OWN_HOUSE);
  const sellStrong = plain(norm, SELL_LISTING) || plain(norm, SELL_ACTIVE) || plain(norm, SELL_TG) || plain(norm, SELL_OWN) || plain(norm, BUYER_WANTED) ||
    (ownHouse && plain(norm, SELL_YOU));
  const buyExplicit = plain(norm, BUY_EXPLICIT) || housingWish(norm);
  const converb = !asked && plain(norm, SELL_CONVERB);
  const buyerAsk = !sellStrong && !ownHouse && (plain(norm, BUYER_ASK) || (passive && question) || (question && plain(norm, FOR_SALE)) ||
    plain(norm, BARGAIN_ASK) || (asked && plain(norm, FOR_SALE_EXISTS)) || (asked && plain(norm, SAVDO_ANY)) || (asked && [...norm.matchAll(SELL_STATUS_ASK)].length > 0));
  const buyWeak = plain(norm, BUY_WEAK);
  // «Хона дорам» (своё есть) рядом с «хона меҷӯям» (ищу) — покупатель: слабое «есть» не перекрывает поиск.
  // «Хона дорам, иваз мекунед?» — обмен своего на наш объект: это интерес покупателя, а не продажа агентству.
  const exchange = EXCHANGE.test(norm);
  const sellWeak = (plain(norm, OWN_HOUSING) && !buyWeak && !exchange) || (!asked && plain(norm, SELL_PRICE_BARGAIN)) ||
    (passive && !question && !buyerAsk) || (!question && !buyerAsk && plain(norm, FOR_SALE_TG)) || (!question && !buyerAsk && plain(norm, ON_SALE)) ||
    (!buyExplicit && plain(norm, SELL_OWN_WEAK)) || (!asked && !buyerAsk && plain(norm, SELL_BARE)) || converb;
  const sell = sellStrong || sellWeak;
  const buySoft = !sellStrong && plain(norm, BUY_SOFT);
  // «Продать и купить», «Хонаамро фурӯхта, хонаи калонтар харидан мехоҳам» — две роли сразу (экзамен 21.11.2026): отдельный исход.
  // Только явные слова: «… пулашро нақд мегирам» у продавца — деньги за своё, не покупка (слепое ревью #345).
  const both = (sellStrong || converb) && (buyExplicit || /(?:^|\s)купить(?:\s|$)/u.test(norm));
  const strong = sellStrong || both ? "seller" as const : buyExplicit ? "buyer" as const : null;
  return { buyStrong: buyerAsk || buyExplicit || buySoft, buyWeak, sell, landlord, rent: plain(norm, RENT_TENANT), both, strong, ownHouse,
    serviceWanted: SERVICE_WANTED.test(norm) };
}

/** Topic-level reading (job wins over buy/sell; a landlord offers property, so it is a seller). */
export function customerTextRole(text: string, jobRequested: boolean): "job" | "buyer" | "seller" | "rent" | null {
  if (jobRequested) return "job";
  const signals = customerRoleSignals(text);
  if (signals.buyStrong) return "buyer";
  if (signals.sell || signals.landlord) return "seller";
  if (signals.rent) return "rent";
  return signals.buyWeak ? "buyer" : null;
}
