/**
 * На каком языке написал клиент — определяется КОДОМ, а не просьбой к модели.
 *
 * В промте правило «отвечай строго на языке клиента» стоит трижды, в трёх разных
 * режимах, и всё равно нарушается. 01.08.2026 человек написал из рекламы по-русски
 * «Сколько стоят ваши услуги?» — бот ответил на таджикском. Для клиента это не
 * «мелочь стиля»: он спросил на своём языке и получил ответ на чужом.
 *
 * Правило, растворённое среди сотни других строк промта, слабее короткой строки,
 * прижатой к самому сообщению. Поэтому язык считается здесь, а в промт уходит
 * прямое указание про КОНКРЕТНО ЭТО сообщение.
 *
 * ПОЧЕМУ НЕ БИБЛИОТЕКА: русский и таджикский пишутся одной кириллицей и делят
 * половину служебных слов, а таджикский вдобавок часто пишут латиницей. Готовые
 * определители на коротком «салом, чанд пул?» ошибаются чаще, чем шесть букв,
 * которых в русском нет вовсе.
 */

import { stripUntrusted, unwrapUntrusted } from "./untrustedContent.js";


/**
 * Частые таджикские слова кириллицей — на случай, когда особых букв не попалось
 * («ман хона мехохам»). Список короткий и намеренно из служебных слов: они есть
 * почти в любой фразе и не совпадают с русскими.
 *
 * «НЕ» И «ОН» ОТСЮДА УБРАНЫ (16.08.2026) и переехали в русский список. Они стояли
 * здесь как таджикские служебные слова, но в русской переписке встречаются на
 * порядок чаще: «Не подходит», «Он дорогой», «Пока не решил» определялись как
 * таджикский, и модель получала ПРИКАЗ отвечать по-таджикски. Модуль писался ровно
 * против обратного случая (01.08: спросили по-русски — ответили по-таджикски) и
 * воспроизводил его принудительно. В таджикской фразе эти слова почти всегда идут
 * рядом с другими маркерами, поэтому потеря невелика; в русской они решают всё.
 */
const TAJIK_WORDS =
  /(?<![а-яёҳҷӣӯқғ])(ман|шумо|мо|хона|хонаи|мехохам|мехоҳам|мехаред|дорем|доред|даркор|аст|ҳаст|хаст|чанд|кучо|куҷо|нест|лозим|бошад|мешавад|мешава|кадом|барои|бале|ки|ва|бо|аз|дар|ин|намефамум|намефахмам|намефаҳмам|намефаҳмум|намедонам|наметавонам|уруси|урус|русӣ|маош|кор|нарх(?:аш|и|ат|ро)?|чанпул|чи|ака|апа|хуб|мешид|мегрифти|хавли|мефурӯш(?:ам|ем)?|мефуруш(?:ам|ем)?|мефурош(?:ам|ем)?|фурӯшам|фуруш(?:ам|ем)?|дорам|доштам|доштм)(?![а-яёҳҷӣӯқғ])/giu;

/**
 * ПРИВЕТСТВИЕ И «СПАСИБО» ЯЗЫКА НЕ ЗАДАЮТ (03.10.2026, живой сбой в Instagram).
 * «Салом можно окончательную цену и когда можно посмотреть?» — русская фраза с
 * таджикским приветствием, так в Душанбе здороваются и русскоязычные. Раньше
 * «салом» стоял в TAJIK_WORDS наравне с «хона» и «чанд», фраза выходила «смесью»,
 * и бот отвечал по-таджикски человеку, который писал по-русски. Теперь такие
 * слова решают язык, только когда больше в сообщении ничего нет («Салом!»).
 */
const TAJIK_GREETINGS =
  /(?<![а-яёҳҷӣӯқғ])(салом|саломалейкум|асалом|асаломалейкум|ассалом|ассалому|ассаломуалейкум|алейкум|алайкум|рахмат|раҳмат|ташаккур)(?![а-яёҳҷӣӯқғ])/giu;

/** Частые русские слова. Тоже служебные: в короткой фразе они попадаются почти всегда. */
const RUSSIAN_WORDS =
  /(?<![а-яёҳҷӣӯқғ])(сколько|стоят|стоит|услуги|ваши|ваш|ваша|что|как|где|когда|почему|можно|хочу|нужно|есть|нет|не|это|он|она|они|вы|мне|меня|для|или|тоже|ещё|еще|пожалуйста|здравствуйте|добрый|спасибо|квартиру|квартира|дом|цена|цену|район|купить|продать|привет|посмотреть|окончательную|скажите|подскажите|интересует|какой|какая|какие|сейчас|будет|звоните|позвоните|номер)(?![а-яёҳҷӣӯқғ])/giu;

/** Слова с буквой, которой в русском нет (ҳ, ҷ, ӣ, ӯ, қ, ғ): одна такая — уже таджикский. */
const TAJIK_LETTER_WORDS = /[а-яёҳҷӣӯқғ]*[ҳҷӣӯқғ][а-яёҳҷӣӯқғ]*/giu;

const count = (re: RegExp, text: string): number => (text.match(re) ?? []).length;

/** Латиница таджикского («salom, chand pul») — латинские буквы без кириллицы вовсе. */
const HAS_CYRILLIC = /[а-яёҳҷӣӯқғ]/i;
const HAS_LATIN = /[a-z]/i;

/**
 * Английские слова-маркеры: латиница латинице рознь.
 *
 * До 16.08.2026 ЛЮБАЯ латиница считалась таджикской, и «Hello, do you have
 * apartments in the center?» получал приказ «отвечай на таджикском кириллицей».
 * Пишут нам по-английски редко, но такой ответ — гарантированный конфуз, а цена
 * ошибки в другую сторону нулевая: не опознали — просто не навязываем язык, и
 * модель отвечает сама (см. languageInstruction, «unknown» → пустая строка).
 *
 * Список из служебных слов, которых нет в таджикской латинице: артикли,
 * вспомогательные глаголы, местоимения.
 */
const ENGLISH_WORDS =
  /(^|[^a-z])(the|and|you|your|are|is|do|does|have|has|can|could|would|want|need|price|how|much|many|what|where|when|hello|hi|please|thanks|thank|apartment|apartments|house|buy|sell|rent|for|with|about|in|of|to)([^a-z]|$)/i;

export type ClientLanguage = "ru" | "tg" | "mixed" | "unknown";

/**
 * Язык последнего сообщения клиента.
 *
 * «mixed» — не отговорка, а нормальный случай Душанбе: люди свободно мешают
 * русский с таджикским в одной фразе, и отвечать им такой же смесью правильнее,
 * чем выбирать что-то одно.
 */
/**
 * Служебные пометки кодом — «[📎 файл не открылся]», «[🎤 не расслышал]» и прочие
 * квадратные скобки — вырезаются ДО определения языка (описание присланного файла
 * вырезается отдельно, по своим границам, — см. detectClientLanguage ниже).
 *
 * Живой случай 17.08.2026: продавец писал строго на таджикском, документ не
 * открылся, код дописал «[📎 файл не открылся]» в конец реплики для модели — и
 * слово «не» из этой ЖЕ пометки попало в RUSSIAN_WORDS. Определитель решил, что
 * клиент написал по-русски, и STRICT-инструкция «Ответь ПО-РУССКИ» перебила
 * весь таджикский разговор. Отличие от ONE_LANGUAGE_RULE ниже: тот учит МОДЕЛЬ
 * игнорировать язык вложения, а здесь ошибался сам определитель ДО модели —
 * инструкция «отвечай по-русски» уже стояла в промте, не оставляя модели выбора.
 */
const SYSTEM_MARKER = /\[[^\]]*\]/g;

/**
 * Не язык клиента: ссылки, e-mail, @ники и телефоны. Голая ссылка на рилс
 * (латиница без кириллицы) считалась таджикской, а ссылка с «/to/» — английской;
 * это переключало язык диалога без единого слова клиента (23.10.2026).
 */
const NON_LANGUAGE = [
  /[\w.+-]+@[\w-]+(?:\.[\w-]+)+/gu,
  /(?:https?:\/\/|www\.)\S+/giu,
  /(?<![\p{L}\p{N}])[a-z0-9-]+(?:\.[a-z0-9-]+)*\.(?:com|net|org|tj|ru|me|ly|io|co|uz|kg|kz|info|app)(?:\/\S*)?/giu,
  /(?<![\p{L}\p{N}_.])@[\w.]{2,}/gu,
  /\+?\d[\d\s().-]{6,}\d/gu,
];
export function stripNonLanguage(text: string): string {
  return NON_LANGUAGE.reduce((acc, pattern) => acc.replace(pattern, " "), text).replace(/\s+/gu, " ").trim();
}

export type ClientLanguageScores = { tajik: number; russian: number; greetings: number };
/** Word counts behind detectClientLanguage, for callers that must break a "mixed" tie themselves. */
export function clientLanguageScores(text: string): ClientLanguageScores {
  const trimmed = prepare(text);
  return { tajik: count(TAJIK_LETTER_WORDS, trimmed) + count(TAJIK_WORDS, trimmed), russian: count(RUSSIAN_WORDS, trimmed),
    greetings: count(TAJIK_GREETINGS, trimmed) };
}

function prepare(text: string): string {
  /**
   * Присланное клиентом содержимое размечено границами (см. ai/untrustedContent.ts),
   * и для языка эти два вида разметки значат ПРОТИВОПОЛОЖНОЕ:
   *  - описание видео и документа пишем МЫ и всегда по-русски — считать его языком
   *    клиента нельзя, иначе таджикоязычный продавец, приславший видео квартиры,
   *    получит строгое «Ответь ПО-РУССКИ» (та же ошибка, что с «[📎 файл не открылся]»
   *    выше, только дороже: описание длинное и русских слов в нём много);
   *  - расшифровка голосового — это собственная речь клиента, и она язык как раз
   *    задаёт: голосовое часто приходит вообще без подписи, и без неё определять
   *    было бы не по чему. Поэтому у неё снимаются только границы, а текст остаётся.
   */
  const withoutFiles = stripUntrusted(text, ["video", "document"]);
  return stripNonLanguage(unwrapUntrusted(withoutFiles).replace(SYSTEM_MARKER, " "));
}

export function detectClientLanguage(text: string): ClientLanguage {
  const trimmed = prepare(text);
  // Слишком коротко («ок», «👍», «[📷]») — по такому языка не определить, и
  // навязывать модели язык на основании двух букв опаснее, чем не навязывать.
  if (trimmed.length < 4) {
    // Три буквы — уже слово, если это однозначно таджикское («Кор», «Ман»); голое «нет»/«ок» язык не задаёт.
    const long = (re: RegExp) => (trimmed.match(re) ?? []).filter(word => word.length >= 3).length;
    return long(TAJIK_LETTER_WORDS) + long(TAJIK_WORDS) > 0 && count(RUSSIAN_WORDS, trimmed) === 0 ? "tg" : "unknown";
  }

  /**
   * СЧЁТ, А НЕ «ЕСТЬ ЛИ ХОТЬ ОДНО» (03.10.2026). Одно таджикское слово в русской
   * фразе делало её «смесью», а смесь бот отвечал по-таджикски. Язык решает то,
   * чего в сообщении больше; «смесь» — только когда обоих поровну по-честному.
   */
  const greetings = count(TAJIK_GREETINGS, trimmed);
  const tajik = count(TAJIK_LETTER_WORDS, trimmed) + count(TAJIK_WORDS, trimmed);
  const russian = count(RUSSIAN_WORDS, trimmed);

  if (tajik > 0 && russian > 0) {
    if (russian >= tajik * 2) return "ru";
    if (tajik >= russian * 2) return "tg";
    return "mixed";
  }
  if (tajik > 0) return "tg";
  if (russian > 0) return "ru";
  // Одно приветствие или «рахмат» без других слов — таджикский, как и раньше.
  if (greetings > 0) return "tg";
  // Латиница без кириллицы у нашей публики — это почти всегда таджикский
  // («salom, hona darkor»), а не английский. Но если в тексте есть английские
  // служебные слова, язык не навязываем вовсе: пусть решает модель по переписке.
  if (!HAS_CYRILLIC.test(trimmed) && HAS_LATIN.test(trimmed)) {
    return ENGLISH_WORDS.test(trimmed) ? "unknown" : "tg";
  }
  return "unknown";
}

/**
 * Строка для промта — короткая, прижатая к самому сообщению.
 *
 * Пусто при «unknown»: если код языка не понял, пусть решает модель по всей
 * переписке. Выдуманное указание хуже отсутствующего.
 */
/**
 * Общий хвост ко всем указаниям о языке (16.08.2026, первый день живого трафика;
 * усилено 14.09.2026 — голосовые ответы сделали видимой вторую, более узкую
 * дыру в этом же правиле).
 *
 * Клиент прислал скриншот объявления и спросил по-таджикски «Ҳами хона арзон
 * мешавад?». Бот ответил ДВУМЯ сообщениями: первым по-русски (описал скриншот,
 * который сам был русским), вторым по-таджикски. Для человека это выглядит так,
 * будто с ним говорят двое разных людей.
 *
 * Причина не в определителе языка — он отработал верно и сказал «таджикский».
 * Причина в том, что модель взяла язык КАРТИНКИ. Поэтому оговорка нужна явная:
 * язык вложения не решает ничего, и все пузыри одного ответа — на одном языке.
 *
 * ВТОРАЯ ДЫРА (14.09.2026, живая отладка голосовых ответов). Клиент написал
 * ЧИСТО по-русски, языковой определитель верно отдал «ru», а модель ответила
 * ОДНОЙ репликой, где русский текст заканчивался приклеенной ТАДЖИКСКОЙ
 * фразой — дословной цитатой одного из примеров-образцов из этого же промта
 * («Рақаматонро нависед, агенти мо занг зада, ҳамаашро мегӯяд» и т.п., см.
 * секцию про передачу агенту). Прежняя формулировка запрещала смешивать языки
 * МЕЖДУ пузырями ответа, но не внутри ОДНОГО пузыря — и не предупреждала, что
 * примеры фраз в промте — это ОБРАЗЕЦ СТРУКТУРЫ, а не готовый текст для
 * копирования не на том языке. Для голосового ответа это особенно заметно:
 * Gemini TTS не озвучивает таджикский вообще, и склеенная фраза либо совсем
 * не озвучивалась, либо звучала оборванной на середине.
 */
const ONE_LANGUAGE_RULE =
  "\nВСЕ сообщения одного ответа — на ОДНОМ языке, БЕЗ ИСКЛЮЧЕНИЙ, включая ВНУТРИ " +
  "одной реплики: нельзя начать по-русски и закончить таджикской фразой (или наоборот) " +
  "в одном и том же пузыре. Язык КАРТИНКИ, документа или пересланного объявления НЕ " +
  "определяет язык ответа: скриншот бывает русским, а спросили по-таджикски. Смотри " +
  "только на слова клиента. Примеры фраз в этой инструкции (в кавычках, на любом языке) " +
  "— образец СТРУКТУРЫ и смысла, а не готовый текст: скажи ту же мысль на языке клиента " +
  "СВОИМИ словами, не копируй пример дословно, если его язык не совпадает с языком ответа.";

export function languageInstruction(language: ClientLanguage): string {
  switch (language) {
    case "ru":
      return (
        "\n\nЯЗЫК ПОСЛЕДНЕГО СООБЩЕНИЯ КЛИЕНТА: РУССКИЙ. Ответь ПО-РУССКИ. Не переходи на таджикский, " +
        "даже если раньше в переписке он был: человек только что написал по-русски." +
        ONE_LANGUAGE_RULE
      );
    case "tg":
      return (
        "\n\nЯЗЫК ПОСЛЕДНЕГО СООБЩЕНИЯ КЛИЕНТА: ТАДЖИКСКИЙ. Ответь на таджикском КИРИЛЛИЦЕЙ, " +
        "даже если он написал латиницей. Не переходи на русский." +
        ONE_LANGUAGE_RULE
      );
    case "mixed":
      return (
        // Правило «один язык внутри реплики» здесь НЕ ставится (ревизия 02.10.2026):
        // рядом с «отвечай смешанно» оно противоречило само себе, и модель
        // выбирала то одно, то другое. Смесь — это таджикская речь с русскими
        // словами, как пишет сам клиент, а не две готовые фразы встык.
        // Без перекоса в таджикский (03.10.2026): прежнее «таджикская речь с русскими
        // словами» отвечало по-таджикски людям, писавшим по-русски с «салом».
        "\n\nЯЗЫК ПОСЛЕДНЕГО СООБЩЕНИЯ КЛИЕНТА: СМЕСЬ русского и таджикского. Пиши так же, как он: " +
        "на том языке, которого в его сообщении больше; если поровну — по-русски с его же таджикскими словами. " +
        "Все сообщения ответа — на ОДНОМ языке, и этот язык — та же смесь: не склеивай целую " +
        "русскую фразу с целой таджикской и не копируй примеры из этой инструкции дословно, " +
        "скажи мысль своими словами. Язык КАРТИНКИ, документа или пересланного объявления " +
        "язык ответа не определяет."
      );
    default:
      // Языка не поняли — не навязываем НИЧЕГО, включая правило про один язык:
      // указание, придуманное кодом, хуже отсутствующего (тем же принципом живёт
      // весь модуль). Разнобой в ответе случился при ИЗВЕСТНОМ языке, и оговорка
      // нужна там, где язык известен.
      return "";
  }
}
