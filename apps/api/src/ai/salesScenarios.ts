import { prisma } from "../db.js";

/**
 * СЦЕНАРИИ ПРОДАЖ бота — разные манеры продавать, которые сравниваются между собой
 * на живых клиентах.
 *
 * ПОЧЕМУ НЕ «КАЖДЫЙ ДЕНЬ НОВЫЙ СЦЕНАРИЙ», как предлагалось изначально.
 * Дни между собой несопоставимы. В субботу пишут одни люди, в среду другие; запустили
 * рекламу — приходит поток холодных любопытных, кончился бюджет — остаются те, кто
 * искал сам; Навруз, Рамазан, конец месяца, дождь. Разброс МЕЖДУ днями заведомо больше,
 * чем разница между двумя манерами разговора. Померив понедельник против вторника, мы
 * померим понедельник и вторник, а не сценарии: любой вывод оттуда — про погоду.
 * Плюс ждать пришлось бы месяцами, потому что каждый день даёт ровно одну точку.
 *
 * ПОЭТОМУ: сценарий выбирается СЛУЧАЙНО на КАЖДЫЙ НОВЫЙ ДИАЛОГ. Тогда все сценарии
 * живут в одних и тех же сутках, в одной и той же рекламной кампании, с одной и той же
 * публикой — всё, что мешает, распределяется между ними поровну и взаимно вычитается.
 * Разница, которая останется, и есть разница манер. Данные при этом копятся не по одной
 * точке в день, а по одной на каждый диалог: ответ приходит в разы быстрее.
 *
 * И ГЛАВНОЕ: назначенный сценарий закрепляется за диалогом НАВСЕГДА (см.
 * ensureConversationScenario). Перевыбирать его на каждом сообщении нельзя — бот
 * менял бы характер посреди разговора, клиент разговаривал бы с тремя разными людьми
 * подряд, и приписать исход какому-то одному сценарию стало бы невозможно.
 */

export interface SalesScenario {
  /** Короткий код. Лежит в БД у каждого диалога — переименовывать его нельзя,
   *  иначе уже собранная статистика отвяжется от сценария. */
  id: string;
  /** Человеческое название — то, что владелец видит в Настройках. Его менять можно. */
  name: string;
  /** Одной строкой: в чём суть этой манеры. Показывается рядом с числами, чтобы
   *  через неделю было понятно, что именно выиграло. */
  summary: string;
  /**
   * Блок, который приклеивается к системному промту бота. Пусто — бот работает
   * ровно так, как работал до сравнения.
   */
  prompt: string;
}

/**
 * Сценарий по умолчанию: когда сравнение выключено, все диалоги идут на нём.
 * Он же контрольная группа — «как сейчас», без добавок к промту. Без контроля
 * сравнение отвечает только на вопрос «какая из новых манер лучше остальных
 * новых», но не на главный: «стало ли вообще лучше, чем было».
 */
export const DEFAULT_SCENARIO_ID = "baseline";

/**
 * ЗДЕСЬ ВЛАДЕЛЕЦ ВПИСЫВАЕТ ТЕКСТЫ СЦЕНАРИЕВ.
 *
 * Менять нужно ТОЛЬКО поле `prompt` (и при желании `name`/`summary`). Поле `id`
 * не трогать: по нему в базе лежат уже проведённые диалоги.
 *
 * Как писать текст. Это ДОБАВКА к основному промту, а не замена: география, запрет
 * обращений по полу, правила языка и формат ответа уже действуют и повторять их не
 * надо. Пишите только то, чем ЭТА манера отличается от остальных — темп выхода на
 * телефон, что предлагать первым, сколько давить, чем закрывать. Абзаца-двух хватает;
 * длинный текст размывает отличие, и сценарии перестанут отличаться друг от друга,
 * а значит и сравнивать станет нечего.
 *
 * Сколько сценариев держать. Сейчас три (контроль + две манеры). Четвёртый добавляется
 * одной строкой в этот массив, но каждый лишний сценарий делит поток клиентов на
 * лишнюю часть и отодвигает вывод примерно на треть. Две новые манеры против текущей —
 * то, на что реально хватит трафика.
 */
export const SALES_SCENARIOS: SalesScenario[] = [
  {
    id: DEFAULT_SCENARIO_ID,
    name: "Как сейчас",
    summary: "Текущий промт без добавок — то, с чем сравниваем остальные.",
    // Контрольная группа. Пусто НАРОЧНО: любой текст здесь превратил бы контроль
    // в третью манеру, и «стало ли лучше, чем было» стало бы не с чем сверить.
    prompt: "",
  },
  {
    id: "warm_consultant",
    name: "Сначала разобраться",
    summary: "Два-три вопроса до объектов, показ предлагает после понимания задачи. Ставка на доверие.",
    prompt: `
<манера_продажи>
Ты работаешь как консультант, который сначала понимает задачу, а потом предлагает.

Прежде чем называть объекты, задай два-три коротких вопроса по одному за сообщение: что ищет, в каком районе, на какую сумму рассчитывает. Спрашивай по-человечески, а не анкетой. Не вываливай варианты в первом же ответе, даже если подходящие уже видишь.

Когда картина ясна — покажи ОДИН, максимум два самых подходящих варианта и объясни, почему именно они: «беру этот, потому что вы говорили про Сино и до сорока пяти». Объяснённый выбор ценится выше длинного списка.

Показ предлагай после того, как клиент отозвался на конкретный объект, а не сразу. Если он сомневается — не подталкивай, спроси, что смущает.

Твоя сила — в том, что человек чувствует: его выслушали, а не обработали.
</манера_продажи>`,
  },
  {
    id: "fast_closer",
    name: "Сразу по делу",
    summary: "Объекты в первых репликах, показ предлагает рано. Ставка на скорость и конкретику.",
    prompt: `
<манера_продажи>
Ты работаешь быстро и предметно: человек пришёл смотреть квартиры, а не беседовать.

Уже во втором-третьем сообщении показывай конкретные варианты из базы, с ценой и районом. Хватит одного уточнения (район или сумма) — дальше показывай то, что есть, и уточняй по ходу, отталкиваясь от реакции. Реакция на живой объект говорит о человеке больше, чем три вопроса подряд.

Предлагай посмотреть рано — как только клиент задержался на каком-то варианте: «есть время завтра после шести или в субботу утром?». Не жди, пока он сам созреет: чаще всего он не созревает, а уходит смотреть дальше.

Если вариант не подошёл — не расспрашивай долго, предложи следующий. Три показанных объекта лучше трёх заданных вопросов.

Твоя сила — в скорости: клиент получает конкретику там, где другие агентства ещё выясняют.
</манера_продажи>`,
  },
];

/** Сценарий по коду. undefined — код из базы, которого в реестре больше нет
 *  (сценарий удалили после того, как по нему уже прошли диалоги). */
export function scenarioById(id: string | null | undefined): SalesScenario | undefined {
  if (!id) return undefined;
  return SALES_SCENARIOS.find((s) => s.id === id);
}

/**
 * Название для экрана. Для кода, которого в реестре нет, возвращаем сам код: врать
 * «Как сейчас» про удалённый сценарий нельзя — числа под ним настоящие, и владелец
 * должен видеть, что они относятся к чему-то, чего в коде уже не осталось.
 */
export function scenarioName(id: string): string {
  return scenarioById(id)?.name ?? `${id} (удалён из кода)`;
}

/**
 * Блок сценария для системного промта.
 *
 * Уходит в КЭШИРУЕМУЮ часть (systemStable), рядом с «личностью» бота и географией:
 * текст стабильный, один и тот же во всех диалогах этого сценария, и платить за него
 * на каждом сообщении незачем. Кэш Anthropic — совпадение префикса побайтово, поэтому
 * блок приклеивается ВСЕГДА в одном и том же месте, в конец стабильной части.
 *
 * Обратная сторона: у каждого сценария получается свой префикс, то есть свой кэш.
 * Это нормально — сценариев единицы, и каждый прогревается первым же диалогом.
 */
export function scenarioPromptBlock(id: string | null | undefined): string {
  const prompt = scenarioById(id)?.prompt ?? "";
  if (!prompt) return "";
  /**
   * ЯВНЫЙ ПРИОРИТЕТ ПРАВИЛ (26.08.2026). Блок сценария приклеивается к промту
   * ПОСЛЕДНИМ — ниже обязательных правил, а их оговорка «если текст ВЫШЕ
   * противоречит…» на текст ниже не распространяется. fast_closer («предлагай
   * посмотреть рано, не жди») прямо противоречил правилу 8 («не дави на показ»),
   * и какую инструкцию исполнит модель, было не определено. Строка ниже снимает
   * неопределённость для ЛЮБОГО сценария, не переписывая манеры по одной.
   */
  return `${prompt}\n\nЕсли эта манера противоречит обязательным правилам выше — действуют правила, манера лишь окрашивает тон.`;
}

/** Включено ли сравнение. Выключено — все диалоги идут на сценарии по умолчанию.
 *  При недоступной базе считаем выключенным: молча раздавать клиентам непроверенные
 *  манеры разговора из-за сбоя запроса — худший из вариантов. */
export async function isScenarioTestEnabled(): Promise<boolean> {
  try {
    const s = await prisma.settings.findUnique({
      where: { id: "singleton" },
      select: { salesScenarioTestEnabled: true },
    });
    return s?.salesScenarioTestEnabled === true;
  } catch {
    return false;
  }
}

/**
 * Какой сценарий достанется новому диалогу.
 *
 * Равномерный жребий по всем сценариям реестра, включая контроль. Именно
 * равномерный, а не «поумнее»: подкручивать доли в пользу того, кто пока лидирует,
 * — верный способ получить лидера из шума, потому что ранний перевес почти всегда
 * случаен, а перекос долей потом уже не разгрести.
 */
export function pickScenarioId(testEnabled: boolean): string {
  if (!testEnabled || SALES_SCENARIOS.length === 0) return DEFAULT_SCENARIO_ID;
  return SALES_SCENARIOS[Math.floor(Math.random() * SALES_SCENARIOS.length)].id;
}

/**
 * Закрепляет сценарий за диалогом — один раз и навсегда.
 *
 * Если сценарий уже проставлен, возвращаем его как есть и НИЧЕГО не пишем: в этом
 * весь смысл. Даже если сравнение успели выключить, а диалог начался при включённом,
 * он доживает на своём сценарии — иначе бот сменил бы характер посреди разговора,
 * а исход стало бы не к чему отнести.
 *
 * Запись через updateMany с условием "salesScenario IS NULL", а не через update:
 * два сообщения клиента приходят почти одновременно, оба хода видят пустое поле, и
 * обычный update дал бы разным ходам разные сценарии — последний победил бы, а первый
 * уже успел бы ответить своим. Условие в WHERE делает назначение однократным на
 * стороне БД; проигравший ход просто перечитывает то, что записал победитель.
 */
export async function ensureConversationScenario(conversation: {
  id: string;
  salesScenario: string | null;
}): Promise<string> {
  if (conversation.salesScenario) return conversation.salesScenario;

  const picked = pickScenarioId(await isScenarioTestEnabled());
  const claimed = await prisma.botConversation.updateMany({
    where: { id: conversation.id, salesScenario: null },
    data: { salesScenario: picked },
  });
  if (claimed.count === 1) return picked;

  // Нас опередил параллельный ход — берём его выбор, а не свой.
  const current = await prisma.botConversation.findUnique({
    where: { id: conversation.id },
    select: { salesScenario: true },
  });
  return current?.salesScenario ?? picked;
}
