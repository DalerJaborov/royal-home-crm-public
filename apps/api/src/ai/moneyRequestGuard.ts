/**
 * ПРОСЬБА О ДЕНЬГАХ — ПОЛНОЕ МОЛЧАНИЕ, ДАЖЕ БЕЗ ГАЛОЧКИ «ПРОЧИТАНО» (владелец
 * 21.08.2026, живой случай: женщина написала в директ агентства с просьбой
 * помочь деньгами).
 *
 * ПОЧЕМУ НЕ ПРОСТО «ОТКАЗАТЬ ВЕЖЛИВО», КАК С АРЕНДОЙ. У аренды и разведки про
 * бота есть готовый вежливый шаблон-отказ — там человек ждёт ответа по делу,
 * просто не по нашему. Здесь по делу ответа нет вообще: агентство недвижимости
 * не может ни помочь, ни отказать так, чтобы это не выглядело холодно или
 * поучительно. Разбор чужой беды сообщением от бота задевает больше, чем полное
 * молчание, — как в жизни: на такое обращение в личку незнакомой компании
 * никто не отвечает, а не отвечает вежливым отказом.
 *
 * ПОЧЕМУ БЕЗ ГАЛОЧКИ «ПРОЧИТАНО». Это ровно то же решение, применённое до
 * конца: если отвечать нельзя, то и показывать, что сообщение увидели и
 * прочитали (mark_seen), тоже не стоит — это уже маленький ответ, тот самый
 * «увидели и промолчали», который читается как отказ. Полная тишина —
 * единственный вариант, который не требует объяснений с нашей стороны. В CRM
 * при этом сообщение всё равно сохраняется (см. processMessengerTurn: silent),
 * чтобы владелец мог увидеть, что обращение было, а не потерялось незаметно.
 *
 * АМНИСТИЯ ПО НАШЕЙ ТЕМЕ. «Можно ли купить в рассрочку, у меня сейчас туго с
 * деньгами» — законный покупатель, а не просьба о помощи. СВОЯ амнистия, а не
 * OUR_BUSINESS из offTopicGuard.ts: та широкая амнистия включает слова про
 * цену и валюту («сомони», «доллар») — а именно с суммой прошения о деньгах
 * обычно и приходят («дайте в долг тысячу сомони»). Здесь смотрим только на
 * прямой признак сделки: жильё, показ, ипотека, рассрочка — а не на то, что в
 * тексте вообще упомянуты деньги.
 */

import { EW } from "./wordBoundary.js";

const rx = (parts: string[]): RegExp => new RegExp(parts.join("|"), "iu");

const PROPERTY_CONTEXT = rx([
  `хона|квартир|дом${EW}|ҳавлӣ|хавли|участок|замин|офис|магазин`,
  "ипотек|рассрочк|показ|дидорбин|объект|нархи\\s+хона",
]);

/**
 * Прямая просьба о деньгах, помощи материально или в долг — не про недвижимость.
 *
 * «Садақа»/«хайр» — исламская благотворительность, «кӯмаки молиявӣ»/«маблағ
 * кӯмак» — таджикское «материальная помощь», встречаются и кириллицей без
 * диакритики (ғ→г, қ→к): пишут как придётся, как и с арендой (rentGuard.ts).
 */
const MONEY_REQUEST = rx([
  // Русский: прямая просьба о деньгах/помощи материально, без слова "жильё" рядом
  "помог(ите|и)\\s+(мне\\s+)?(деньга|материальн|финансов)",
  "нужна\\s+(материальн|финансов)\\p{L}*\\s+помощь",
  "дайте?\\s+(в\\s+)?долг|займите?\\s+(мне\\s+)?денег|одолж(ите|и)\\s+денег",
  "переве?д(ите|и)те?\\s+(мне\\s+)?(денег|деньги|сумму|на\\s+карт)",
  "нечем\\s+(кормить|платить)|нет\\s+денег\\s+на\\s+(еду|лечени|лекарств)",
  "милостын|подайте?,?\\s+кто\\s+чем",
  "сложн(ая|ое)\\s+(жизненн\\p{L}*\\s+)?ситуаци.{0,20}(помог|деньг)",
  // Таджикский
  "маблағ\\s+кӯмак|кӯмаки\\s+молиявӣ|пул\\s+кӯмак\\s+кун",
  "садақа|садака|хайр\\s+кун(ед)?",
  "қарз\\s+диҳед|карз\\s+диҳед|қарз\\s+гирам",
  /**
   * ЁРДАМ/КӮМАК («помощь») + ПРИЧИНА, БЕЗ СЛОВ ПРО ДЕНЬГИ НАПРЯМУЮ (17.09.2026,
   * живой случай ПК-000330: «Ёрдами шумоҳо даркор… лечение ребёнка»). Просьба
   * не называет ни суммы, ни слова «пул»/«деньги» — MONEY_REQUEST её не ловил, и
   * карточка ушла агентам как покупатель. «Ёрдам»/«кӯмак» сами по себе слишком
   * широки (человек может попросить помочь ПОДОБРАТЬ квартиру — PROPERTY_CONTEXT
   * ниже такое уже снимает), поэтому здесь порог — «помощь» РЯДОМ с причиной, не
   * связанной с недвижимостью: лечение, болезнь, ребёнок в беде.
   */
  /**
   * `\\b` ЗДЕСЬ БЫЛ МЁРТВЫМ (починено 20.09.2026). До этого стояло `бемор\\b`, а в
   * JavaScript `\\b` — граница между [A-Za-z0-9_] и всем остальным, даже с флагом `u`.
   * После таджикской «р» такой границы нет никогда, и `бемор\\b` не совпадал НИ С
   * ОДНИМ сообщением: «Кӯмак кунед, модарам бемор» проходило как обычный
   * покупатель. Работала только форма с окончанием («беморӣ»), то есть решение владельца
   * от 21.08.2026 молча не выполнялось в половине случаев. Берём `EW` из ai/wordBoundary.ts —
   * тот же разбор, что у семи мёртвых правил, найденных в тот же день (правка #579).
   */
  `(ёрдам|кӯмак|кумак)\\p{L}*.{0,40}(лечени|духтур|беморӣ|бемор${EW}|операци|фарзанд)`,
  `(лечени|духтур|беморӣ|бемор${EW}|операци|фарзанд).{0,40}(ёрдам|кӯмак|кумак)`,
]);

/**
 * Просьба о деньгах ли это, по словам клиента — тем же приёмом, что и
 * looksLikeRentRequest (rentGuard.ts): слово о жилье рядом снимает подозрение.
 */
export function looksLikeMoneyRequest(clientText: string): boolean {
  const text = clientText.trim();
  if (!text) return false;
  if (PROPERTY_CONTEXT.test(text)) return false;
  return MONEY_REQUEST.test(text);
}
