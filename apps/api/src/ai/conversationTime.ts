import type { ChatMessage } from "./shared.js";

/**
 * Сколько времени прошло между репликами — чтобы модель это ВИДЕЛА.
 *
 * До 01.08.2026 в модель уходили только роль и текст. Разговор трёхмесячной
 * давности выглядел для неё в точности как начатый пять минут назад, и она
 * продолжала его с того же места: «можете посмотреть квартиру сегодня?» в
 * переписке, оборвавшейся в январе. Директор увидел это и справедливо спросил,
 * почему бот сразу предлагает квартиру.
 *
 * Дело было не в напоре. Дело в том, что у бота не было часов.
 *
 * Разрывы вставляются В ТЕКСТ реплики, а не отдельным полем, нарочно: вызовы
 * пересобирают сообщение по role/content (Anthropic отвергает объект с
 * незнакомыми ключами), и любое служебное поле до модели просто не доедет.
 */

const MINUTE = 60_000;
const HOUR = 60 * MINUTE;
const DAY = 24 * HOUR;

/**
 * С какого разрыва он вообще заслуживает упоминания.
 *
 * Шесть часов, а не «любая пауза»: люди отвечают через час-два, и помечать это
 * значит засорить историю пометками, среди которых настоящий разрыв потеряется.
 * А вот пауза с вечера до утра уже меняет разговор: «завтра в 18» вчерашнее и
 * «завтра в 18» сегодняшнее — разные дни.
 */
const NOTABLE_GAP_MS = 6 * HOUR;

/** «3 месяца», «5 дней», «14 часов» — по-русски, без точности до минуты. */
export function humanGap(ms: number): string {
  if (ms >= 60 * DAY) return `${Math.round(ms / (30 * DAY))} мес.`;
  if (ms >= 2 * DAY) return `${Math.round(ms / DAY)} дн.`;
  if (ms >= DAY) return "сутки";
  return `${Math.round(ms / HOUR)} ч`;
}

/**
 * Дописывает к репликам пометки о разрывах во времени.
 *
 * Пометка ставится перед репликой, ПОСЛЕ которой был перерыв, — то есть перед
 * той, что начинает новый заход. Так модель видит не «где-то была пауза», а
 * «вот отсюда идёт другой разговор».
 *
 * Возвращает новый массив; исходный не трогаем — он же уходит в запись истории.
 */
export function withTimeGaps(history: ChatMessage[], now: Date = new Date()): ChatMessage[] {
  const out: ChatMessage[] = [];
  for (let i = 0; i < history.length; i++) {
    const message = history[i];
    const previous = history[i - 1];
    const at = message.at ? Date.parse(message.at) : NaN;
    const previousAt = previous?.at ? Date.parse(previous.at) : NaN;

    // Разрыв считается только когда известны обе даты: у старых реплик их нет,
    // и выдумывать паузу по их отсутствию нельзя.
    if (Number.isFinite(at) && Number.isFinite(previousAt) && at - previousAt >= NOTABLE_GAP_MS) {
      out.push({ ...message, content: `[перерыв ${humanGap(at - previousAt)}]\n${message.content}` });
      continue;
    }
    out.push(message);
  }

  // И отдельно — сколько прошло с последней реплики до СЕЙЧАС. Это важнее всех
  // остальных разрывов: именно здесь бот решает, продолжает он разговор или
  // начинает новый.
  const last = out[out.length - 1];
  const lastAt = last?.at ? Date.parse(last.at) : NaN;
  if (last && Number.isFinite(lastAt) && now.getTime() - lastAt >= NOTABLE_GAP_MS) {
    out[out.length - 1] = { ...last, content: `${last.content}\n[с этого момента прошло ${humanGap(now.getTime() - lastAt)}]` };
  }
  return out;
}

/** Дни недели по-русски: без них «сегодня» для модели безымянный день. */
const WEEKDAYS = ["воскресенье", "понедельник", "вторник", "среда", "четверг", "пятница", "суббота"];
const MONTHS = [
  "января",
  "февраля",
  "марта",
  "апреля",
  "мая",
  "июня",
  "июля",
  "августа",
  "сентября",
  "октября",
  "ноября",
  "декабря",
];

/**
 * КАКОЙ СЕГОДНЯ ДЕНЬ — БЕЗУСЛОВНО, В КАЖДОМ ХОДЕ.
 *
 * Живой случай 14.08.2026 (WhatsApp, разбор владельца): клиент спросил «Какой сейчас
 * месяц?» и получил «Сейчас март 2026 года», потом «мы в Душанбе, а с датой у меня
 * системный сбой». Ни сбоя, ни системы не было: у бота просто не было часов. Дата
 * стояла ровно в одном месте промта — внутри блока назначения показов
 * (`showingPromptBlock`), а показы владелец 16.08.2026 выключил. Вместе с блоком
 * исчезли и часы, и модель начала называть дату своего обучения.
 *
 * Отсюда правило: время в промте не может зависеть ни от одного рубильника. Строка
 * короткая и уходит в ИЗМЕНЯЕМУЮ часть системного промта — внутри кэшируемого
 * префикса она ломала бы побайтовое совпадение на каждой минуте.
 *
 * `at` — уже настенное время Душанбе (`dushanbeWallClock`), поэтому читаем его
 * через getUTC*: контейнер живёт в UTC, и локальные геттеры дали бы сдвиг обратно.
 */
export function nowBlock(wall: Date): string {
  const stamp =
    `${WEEKDAYS[wall.getUTCDay()]}, ${wall.getUTCDate()} ${MONTHS[wall.getUTCMonth()]} ${wall.getUTCFullYear()} г., ` +
    `${String(wall.getUTCHours()).padStart(2, "0")}:${String(wall.getUTCMinutes()).padStart(2, "0")}`;
  return (
    `\n\nСЕЙЧАС В ДУШАНБЕ: ${stamp}. Это настоящее время, считай дни, месяцы и годы только от него. ` +
    "Спросили, какое сегодня число, месяц, год или день недели — назови отсюда, без оговорок и без сомнений. " +
    "Свои внутренние представления о дате не используй: они устаревшие, и названный по ним месяц — прямая ложь клиенту."
  );
}

