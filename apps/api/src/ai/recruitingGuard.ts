/**
 * ПРО НАЙМ АГЕНТОВ — ТОЛЬКО В РАЗГОВОРЕ О РАБОТЕ (владелец 25.09.2026).
 *
 * Живой случай: хозяйка пришла с рекламы и спросила «Шумо хона реклама
 * [мекунед]?» — то есть хочет разместить свой дом. Бот ответил «Бале, мо
 * агентони фурӯшро ба кор қабул мекунем. Оё резюме доред?» и дописывал
 * «Мо инчунин агентони фурӯшро ба кор қабул мекунем… резюме» к КАЖДОМУ
 * следующему ответу, пока она рассказывала про «ду сотих хона». Другой продавец
 * после принятой заявки получил отдельное «Барои қабули дархости кор рақами
 * телефони худро бинависед». Владелец: «разговор не клеится, она спрашивала про
 * рекламу своего объекта, а не кандидат».
 *
 * Промт это и так запрещает — но промт просьба, а не гарантия (тот же приём,
 * что ai/intentDirectionGuard.ts). Здесь код: когда разговор НЕ о работе
 * (намерение не job и нет признака рекламы вакансии), предложения про найм,
 * резюме и «заявку на работу» из ответа вычёркиваются. Остальное предложение
 * пузыря остаётся — «Реклама для хозяев бесплатна» без хвоста про найм.
 *
 * `\w`/`\b` не используются: по кириллице они молчат (ai/wordBoundary.ts).
 */

const RECRUITING = new RegExp(
  [
    // «агентони фурӯшро ба кор қабул мекунем», «агентҳои фурӯш қабул мекунем»
    "агент\\p{L}*\\s+(?:и\\s+)?фур[ӯу]ш\\p{L}*[^.!?\\n]{0,40}(?:қабул|кабул)",
    "ба\\s+кор\\s+(?:қабул|кабул)",
    "қабули\\s+дархости\\s+кор|кабули\\s+дархости\\s+кор|дархости\\s+кор(?![\\p{L}])",
    "резюме",
    "та[ҷч]рибаи\\s+кор",
    "ваканси",
    // русские формулировки найма
    "(?:набира|нанима|приглаша|ищем)\\p{L}*\\s+(?:\\p{L}+\\s+)?(?:агент|сотрудник|менеджер)",
    "(?:агент\\p{L}*|менеджер\\p{L}*)\\s+по\\s+продаж\\p{L}*[^.!?\\n]{0,40}(?:работ|команд)",
    // «ищете квартиру или вас интересует работа?» / «…ё кор?»
    //
    // Нужен сам вопрос о работе — «вас интересует», «ищете», «лозим» (02.10.2026):
    // голое «для жизни или работы?», «барои зиндагӣ ё кор?» — законный вопрос
    // покупателю, зачем ему квартира, и вычеркивался как вербовка.
    "(?:или|ё)\\s+(?:вас\\s+)?интересует\\s+работ\\p{L}*",
    "(?:или|ё)\\s+(?:ищете|ищите)\\s+работ\\p{L}*",
    "(?:или|ё)\\s+кор\\s+(?:лозим|мехоҳед|мехохед|мекобед)",
  ].join("|"),
  "iu"
);

export function mentionsRecruiting(text: string | null | undefined): boolean {
  return RECRUITING.test(text ?? "");
}

/** Предложения внутри пузыря — по концу предложения или переносу строки. */
//
// Точка считается концом предложения, только когда за ней пробел или конец
// (02.10.2026): иначе «royalhome.tj» рвалось на «royalhome.» и «tj». Перевод
// строки остаётся в куске — склеиваем без потерь, строки не сливаются.
function sentences(bubble: string): string[] {
  return bubble.match(/(?:[^.!?\n]|[.!?](?![\s]|$))+(?:[.!?]+(?=\s|$))?\s*/g) ?? [bubble];
}

/**
 * Вычеркнуть предложения про найм. Пузырь, от которого ничего не осталось,
 * уходит целиком. Если не осталось ни одного пузыря — вместо тишины короткое
 * «чем могу помочь»: вычеркнули мы сами, а человек ждёт ответа.
 */
export function stripRecruiting(
  bubbles: string[],
  language: "ru" | "tg" | "mixed" | "unknown"
): { bubbles: string[]; stripped: number } {
  let stripped = 0;
  const kept: string[] = [];
  for (const bubble of bubbles) {
    if (!mentionsRecruiting(bubble)) {
      kept.push(bubble);
      continue;
    }
    const rest = sentences(bubble)
      .filter((s) => {
        if (!mentionsRecruiting(s)) return true;
        stripped++;
        return false;
      })
      .join("")
      .replace(/[ \t]+/g, " ")
      .replace(/[ \t]*\n[ \t]*/g, "\n")
      .trim();
    // Обрубок вроде «Бале,» — не ответ.
    if (rest.replace(/[\p{P}\s]/gu, "").length >= 3) kept.push(rest);
  }
  if (kept.length === 0 && bubbles.length > 0) {
    kept.push(language === "ru" ? "Чем могу помочь?" : "Чӣ хизмат карда метавонам?");
  }
  return { bubbles: kept, stripped };
}
