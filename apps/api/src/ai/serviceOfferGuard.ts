/**
 * «ШУМОДА ЭЛЕКТРИК ЛОЗИМ БОША ЗАНГ ЗАНЕН» — ЭТО НЕ ПОКУПАТЕЛЬ (разбор 30.08.2026).
 *
 * ЖИВОЙ СЛУЧАЙ. Человек написал в директ агентства: «нужен электрик — звоните».
 * Он не покупает и не продаёт квартиру, он предлагает СВОИ УСЛУГИ. Бот ответил
 * ему по-человечески, а карточка ушла живому агенту с типом BUYER — агент звонил
 * электрику, чтобы предложить квартиру.
 *
 * Отсечки не было вовсе: в промте есть сценарий JOB (кандидат в агенты), но
 * «делаю ремонт под ключ», «мы бригада», «доставка», «реклама» под него не
 * подходят — это не соискатель, это встречное коммерческое предложение.
 *
 * ЧТО ДЕЛАЕМ. Карточка типа OTHER: руководство видит обращение в «Прочих», агенту
 * оно не назначается (services/leads/intake.ts). Отказа не пишем — человек ничего
 * плохого не сделал, а решать, нужен ли нам подрядчик, руководству, а не боту.
 *
 * СМОТРИМ ТОЛЬКО СЛОВА КЛИЕНТА (то же правило, что в ai/rentGuard.ts).
 *
 * ЧЕГО ЗДЕСЬ НЕ ЛОВИТСЯ, И ЭТО НАРОЧНО. Слово «ремонт» само по себе — самое
 * обычное слово разговора о квартире («хонаи таъмиршуда», «с ремонтом», «нужен
 * ремонт?»). Оно засчитывается ТОЛЬКО в связке с предложением услуги («таъмир
 * мекунем», «делаем ремонт под ключ»). Ровно так же «усто» — мастер: клиент может
 * спросить, есть ли у нас знакомый усто, и это ещё не подрядчик.
 */

import { TAIL } from "./wordBoundary.js";

const rx = (parts: string[]): RegExp => new RegExp(parts.join("|"), "iu");

/**
 * Рабочие профессии и бригады. Эти слова в разговоре о ПОКУПКЕ квартиры не
 * звучат почти никогда: человек, назвавший себя электриком или сварщиком в
 * первом же сообщении агентству, предлагает работу, а не ищет жильё.
 */
const TRADE = rx([
  "электрик|барқчӣ|барқчи",
  "сантехник|обгузар",
  "сварщик|кафшергар|сварка",
  "плиточник|кафелчӣ|кафелчи|кафелкор",
  "маляр|штукатур|шпаклёвк|шпаклевк",
  "натяжн(ые|ой) потолк|потолки натяжн",
  "гипсокартон|евроремонт",
  "грузчик|боркаш",
  "мебел(ь|и) на заказ|мебел бо фармоиш",
  `кондиционер${TAIL}\\s+(насб|монтаж|устанавлива)`,
]);

/** Предложение услуги словами: «мы делаем», «принимаем под ключ», «оказываем». */
const OFFER = rx([
  "хизматрасон|хизмат мерасонем|хизмат пешниҳод",
  "қабул мекунем|кабул мекунем|қабул менамоем",
  "кор мекунем|кор карда медиҳем|мекунем ба шумо",
  "под\\s*ключ|подключ|калид ба даст",
  `таъмир${TAIL}\\s+мекунем|таъмири хона мекунем`,
  "делаем (ремонт|отделк)|выполняем (ремонт|работы)|оказываем услуги",
  "предлага(ю|ем) (свои )?услуг|услуги (по )?ремонт",
  `реклама${TAIL}\\s+(мекунем|пешниҳод)|предлагаем рекламу`,
  `доставка${TAIL}\\s+(мекунем|дорем)|осуществляем доставку`,
  "бригада",
]);

/**
 * ВТОРОЙ ПРИЗНАК ДЛЯ ПРОФЕССИИ (починено 20.09.2026, docs/bot-razbor-20-09.md,
 * класс 4 п. 7).
 *
 * Одного упоминания профессии было достаточно для вердикта «предлагает услуги» — и
 * покупатель, написавший «потом нужен будет электрик» или «без гипсокартона лучше»,
 * уезжал в «Прочие обращения»: агенту его не раздают, то есть живой лид терялся
 * молча. Амнистия BUY_OR_SELL его не спасала: в том самом сообщении слова «купить»
 * нет, оно было десять реплик назад.
 *
 * Теперь профессия считается только в связке со вторым признаком — тот же приём, что
 * уже стоит здесь у слова «ремонт» и в ai/agencyPitchGuard.ts:
 *   • предложение себя (OFFER или SELF_OFFER): «звоните», «мы», «мекунем», «арзон»,
 *     «опыт» — так говорит тот, кто продаёт свой труд;
 *   • обращение к НАМ как к нуждающемуся (YOU_NEED): «шумода … лозим боша»,
 *     «если нужен» — именно так был сформулирован живой случай 30.08.2026.
 */
const SELF_OFFER = rx([
  "занг зан|звоните|пишите|нависед",
  "мекунем|мекунам|мерасонем|мо \\S+ ҳастем",
  "арзон|недорого|качественно|гаранти|сола таҷриба|опыта? работ",
  "услуг|хизмат|бригад|мастера? есть",
]);

const YOU_NEED = rx([
  "шумода|шуморо|агар лозим|лозим бош",
  "если (нуж|надо|понадоб)|вам нужен|вашим клиентам",
]);

/**
 * ВЕБ/IT/МАРКЕТИНГ-УСЛУГИ (23.09.2026, живой случай: «Предложение
 * веб-разработки (вебсайт)» через Instagram осталось в очереди «просит звонок»
 * на дашборде — TRADE/OFFER выше знают только про физические ремёсла и
 * общую формулу «мы делаем/предлагаем услуги», а слово «Предложение»
 * (существительное, не «предлагаю») под OFFER не попадает вовсе.
 *
 * В отличие от TRADE, второй признак не нужен: «веб-разработка», «SMM»,
 * «продвижение сайта», «IT-услуги» в переписке агентства недвижимости не
 * звучат почти никогда как слова обычного покупателя/продавца жилья.
 */
const WEB_SERVICE = rx([
  "веб-?разработ|разработ\\S*\\s+сайт|созда(ём|ем|ние)\\s+сайт|сайт\\S*\\s+под\\s+ключ",
  "smm|смм|таргет(инг|olog)?|seo[\\s-]?продвижен|продвижени\\S*\\s+(сайт|аккаунт|инстаграм)",
  "it[\\s-]?услуг|ит[\\s-]?услуг|digital[\\s-]?агентств|диджитал[\\s-]?агентств",
  "мобильн\\S*\\s+приложени|разработк\\S*\\s+приложени",
]);

/** Прямая просьба о работе своими словами — это тот же JOB, только без анкеты. */
const WANTS_JOB = rx([
  "кор мекобам|кор кофта истода|кор даркор|ҷои кор",
  "ищу работу|нужна работа|хочу устроиться|есть ли вакансии|вакансия",
]);

/**
 * Разговор всё-таки про куплю-продажу жилья — отсечку снимаем: подрядчик,
 * который САМ покупает квартиру, наш обычный клиент (тот же приём, что
 * BUY_OR_SELL в ai/rentGuard.ts).
 */
const BUY_OR_SELL = rx([
  "харид|мехар|бихар|мехоҳам гирам",
  "куп(ить|лю|им|ит|ите|ля)|покупк|приобрет",
  "фур[ӯу]ш|мефур|прода(ть|м|ю|жа|ём|ем)|на продаж",
  "ипотек|рассрочк",
]);

export interface ServiceOfferVerdict {
  /** Короткая причина для карточки и инбокса. */
  reason: string;
}

/**
 * Человек предлагает услуги или ищет работу — по его собственным словам.
 *
 * Порог: явное предложение услуги ИЛИ профессия СО ВТОРЫМ признаком. Одинокого «занг занен»
 * («звоните») в списках НЕТ намеренно: этими словами заканчивает сообщение и
 * обычный клиент, оставляющий свой номер, — живой случай ловится по слову
 * «электрик», а не по просьбе перезвонить.
 */
export function detectServiceOffer(clientText: string): ServiceOfferVerdict | null {
  const text = clientText.trim();
  if (!text) return null;
  if (BUY_OR_SELL.test(text)) return null;

  if (WANTS_JOB.test(text)) return { reason: "ищет работу" };
  if (WEB_SERVICE.test(text)) return { reason: "предлагает веб/IT/маркетинг-услуги" };
  // Профессия — только со вторым признаком (разбор выше у SELF_OFFER/YOU_NEED).
  if (TRADE.test(text) && (OFFER.test(text) || SELF_OFFER.test(text) || YOU_NEED.test(text))) {
    return { reason: "предлагает услуги мастера или бригады" };
  }
  if (OFFER.test(text)) return { reason: "встречное коммерческое предложение (услуги)" };
  return null;
}
