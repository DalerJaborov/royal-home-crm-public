/**
 * «У нас есть варианты» — сверка обещания с тем, что реально есть.
 *
 * САМАЯ ДОРОГАЯ ЛОЖЬ ИЗ ВОЗМОЖНЫХ, и промт называет её так дословно. Человек
 * слышит «в этом бюджете есть отличные варианты», оставляет номер, ждёт звонка —
 * а агенту предложить нечего. Потерян не диалог, потеряно доверие: второй раз он
 * не напишет.
 *
 * ЖИВОЙ СЛУЧАЙ 16.08.2026, первый день трафика. Клиент искал трёшку в центре до
 * 200 тысяч долларов. Район «центр» в карточку не пишется (он делится на два
 * официальных, см. dushanbeGeography), тип клиент не назвал — значит подборка не
 * строилась вовсе, и блока объектов в промте НЕ БЫЛО. Бот всё равно ответил:
 * «В этом бюджете в центре есть отличные варианты. Напишите ваш номер телефона».
 * Человек тут же спросил «Какие варианты у вас есть?» — и не получил ни одного.
 *
 * ПОЧЕМУ ФИЛЬТРОМ, А НЕ ПРОСЬБОЙ. Запрет стоит в промте прямым текстом, крупными
 * буквами, с объяснением цены ошибки — и всё равно нарушен в первый же день. Это
 * ровно тот класс правил, который в этом репозитории ставят кодом (см.
 * royal-home-prompt-is-not-a-guarantee и соседний ai/priceGuard.ts, откуда взят и
 * подход, и осторожность).
 *
 * ФИЛЬТР ТРУСЛИВ ПО ПОСТРОЕНИЮ. Ложное срабатывание вырезает честную фразу и
 * оставляет клиента без ответа, поэтому:
 *   - работает ТОЛЬКО когда подборка пуста (есть объекты — молчим совсем);
 *   - ловит узкий список утверждений о наличии, а не любое слово «вариант»;
 *   - режет предложение, а не слово: обрубок хуже самой лжи;
 *   - если после чистки не осталось ничего — отдаёт исходный текст и громко пишет
 *     в журнал: пусть лучше соврёт один раз и мы это увидим, чем клиент получит
 *     пустоту.
 */

import { logSystemError } from "../lib/systemError.js";
import type { ClientLanguage } from "./clientLanguage.js";

/**
 * Утверждения «у нас это есть». Списком, а не одним широким правилом: слово
 * «вариант» само по себе законно («ҳозир чунин вариант надорем» — это ОТКАЗ, и
 * трогать его нельзя ни в коем случае).
 *
 * Отрицания отсекаются отдельно (см. DENIAL): «надорем», «нест», «нет» рядом
 * превращают утверждение в честный отказ.
 */
/**
 * ГРАНИЦЫ СЛОВА ВЫПИСАНЫ ЯВНО. `\b` в JavaScript определён через [A-Za-z0-9_] и
 * с кириллицей НЕ РАБОТАЕТ вовсе: `/\bесть/` не находит «есть» ни разу, потому
 * что между пробелом и «е» границы для движка нет. В этом репозитории на этом
 * молча умерли уже четыре правила, и пятое чуть не умерло здесь же — первый
 * прогон на живой фразе «В этом бюджете есть отличные варианты» не сработал.
 */
const L = "(^|[^а-яёa-zA-Zа-ёӣӯқғҳҷ])";

/**
 * ОПРЕДЕЛЕНИЯ МЕЖДУ «ЕСТЬ» И ПРЕДМЕТОМ (починено 20.09.2026).
 *
 * Раньше правило требовало предмет СРАЗУ после «есть», а список прилагательных был
 * закрытым из пяти слов. Поэтому «У нас есть отличная трёшка» при пустой подборке
 * проходило насквозь — ровно то обещание, от которого написан весь этот файл, и даже
 * теми же словами, что в живом случае 16.08.2026 (docs/bot-razbor-20-09.md, класс 4 п. 5).
 *
 * Вместо списка прилагательных — до двух ЛЮБЫХ слов перед предметом: их может
 * быть сколько угодно («две хорошие квартиры», «очень уютная двушка»), а выписывать их
 * поимённо — значит возвращаться сюда после каждой новой живой фразы.
 */
const GAP = "(?:[\u0430-\u044f\u0451\u04ef\u04e3\u049b\u0493\u04b3\u04b7\\d]+\\s+){0,2}";

const AVAILABILITY_CLAIMS = [
  // русский
  new RegExp(`${L}есть\\s+${GAP}вариант`, "i"),
  new RegExp(`${L}имеются\\s+вариант`, "i"),
  // «Подберём удобное время для показа» — не обещание объектов (02.10.2026):
  // обещанием «подберём» становится только рядом с самим предметом.
  new RegExp(`${L}подбер[её]м\\s+(?:вам\\s+)?(?:[^\\s.!?]+\\s+){0,2}(вариант|квартир|жиль|дом|хона|ҳавл)`, "iu"),
  new RegExp(`${L}подыщ`, "i"),
  new RegExp(`${L}найд[её]тся`, "i"),
  new RegExp(`${L}найд[её]м\\s+(?:[^\\s.!?]+\\s+){0,3}(квартир|жиль|вариант|дом)`, "iu"),
  new RegExp(`${L}у\\s+нас\\s+есть\\s+${GAP}(квартир|тр[её]шк|двушк|однушк|дом|участок|хавл)`, "i"),
  new RegExp(`${L}найд[её]м\\s+(вам\\s+)?(подходящ|вариант)`, "i"),
  // таджикский
  /вариант\S*\s+(зӯр\s+)?дорем/i,
  /вариантҳои\s+\S+\s+дорем/i,
  /чанд\s+варианти\s+\S+\s+(ҳаст|дорем)/i,
  /мувофиқ\S*\s+дорем/i,
  /**
   * ТИП ЖИЛЬЯ ВМЕСТО СЛОВА «ВАРИАНТ» (20.09.2026, живой случай).
   *
   * Клиентка просила ҳавлӣ до 1 200 000 сомони; подборки в промте не было, и бот
   * ответил «Шохмансурда ҳавлӣ дорем» — то самое обещание, ради которого написан
   * этот файл, только другими словами. Список ловил «вариант … дорем» и
   * «мувофиқ … дорем», а самый естественный способ это сказать — назвать сам
   * предмет: ҳавлӣ, хона, квартира, манзил, ҳуҷра, замин.
   */
  //
  // До трёх слов между предметом и «ҳаст» (02.10.2026): «Ҳавлӣ дар Шоҳмансур ҳаст»
  // проходило, потому что между ними допускалось только «зӯр». «Ҳуҷҷатҳои хона» —
  // документы на дом, а не дом, их не трогаем.
  /(?<!ҳуҷҷат\S*\s|хуҷҷат\S*\s)(ҳавлӣ|хавлӣ|хавли|хона|хонаҳо|квартира|квартираҳо|манзил|ҳуҷра|замин|участок)\S*\s+(?:[^\s.!?]+\s+){0,3}(ҳаст|дорем|доранд)/iu,
];

/** «Есть варианты оплаты», «варианти пардохт» — про деньги, а не про объекты. */
const NOT_ABOUT_LISTINGS = /вариант\S*\s+(оплат|расч[её]т|расср|ипотек|пардохт|показ)/iu;

/** Отрицание рядом — предложение честное, это отказ, а не обещание. */
const DENIAL = new RegExp(
  `${L}(надорем|нест|надоранд|не\\s+имеем|нет\\s+вариант|не\\s+нашлось)`,
  "i"
);

export interface AvailabilityGuardResult {
  bubbles: string[];
  /** Вырезанные предложения — для журнала, чтобы люди видели, что именно бот обещал. */
  removed: string[];
  /** Чистка съела ответ целиком — отдали как есть, но факт надо увидеть. */
  keptDespiteViolation: boolean;
}

/** Разбивка на предложения — та же, что у обрезки приглашений в комментариях:
 *  границей считается и перевод строки, иначе весь пузырь читается как одно
 *  предложение и вырезается целиком. */
function sentences(text: string): string[] {
  return text.split(/(?<=[.!?])[ \t]+|\n+/);
}

/**
 * @param bubbles ответ модели как есть
 * @param hasProperties была ли подборка объектов в промте. false — обещать нечего
 */
export function guardAvailability(bubbles: string[], hasProperties: boolean): AvailabilityGuardResult {
  // Объекты есть — обещание правдиво, проверять нечего. Самый частый случай, и он
  // не должен стоить ни одного регулярного выражения.
  if (hasProperties) return { bubbles, removed: [], keptDespiteViolation: false };

  const removed: string[] = [];
  const cleaned = bubbles.map((bubble) => {
    const kept = sentences(bubble.normalize("NFC")).filter((s) => {
      // Вопрос — не обещание (02.10.2026): «Ҳуҷҷатҳои хона ҳаст?», «Хона ҳаст?»
      // спрашивают клиента, а не сообщают ему о наличии.
      if (/\?\s*$/.test(s)) return true;
      if (NOT_ABOUT_LISTINGS.test(s)) return true;
      const claim = AVAILABILITY_CLAIMS.some((p) => p.test(s));
      if (!claim || DENIAL.test(s)) return true;
      removed.push(s.trim());
      return false;
    });
    return kept.join(" ").replace(/[ \t]{2,}/g, " ").trim();
  });

  if (removed.length === 0) return { bubbles, removed: [], keptDespiteViolation: false };

  const survivors = cleaned.filter((b) => b.length > 0);
  // От ответа ничего не осталось: отдаём исходный. Пустое сообщение клиенту хуже
  // неточного, а факт лжи всё равно попадёт в журнал — его увидит человек.
  if (survivors.length === 0) return { bubbles, removed, keptDespiteViolation: true };

  return { bubbles: survivors, removed, keptDespiteViolation: false };
}

/**
 * ЗАГЛУШКА НА МЕСТО ОБЕЩАНИЯ ВАРИАНТОВ, КОТОРОЕ НЕ УДАЛОСЬ ВЫЧИСТИТЬ.
 *
 * Тот же класс дыры, что чинили priceGuardFallbackReply в ai/leadQualifier.ts (PR
 * #431, 16.09.2026): когда чистка съедает ответ целиком, guardAvailability отдаёт
 * keptDespiteViolation: true и ИСХОДНЫЕ bubbles — решение, принятое на случай
 * пустоты, а не на случай «отправить клиенту ложное обещание как факт». Ревью
 * того PR нашло, что applyAvailabilityGuard эту заглушку не подставлял вовсе:
 * если ответ модели целиком состоял из фраз про наличие при пустой подборке,
 * клиент получал «в этом бюджете есть отличные варианты» без единого объекта
 * за спиной.
 *
 * Текст не про цену — про варианты, которых сейчас нет: не годится реплика про
 * «точную цифру» из priceGuardFallbackReply.
 */
export function availabilityGuardFallbackReply(language: ClientLanguage): string[] {
  // Ревизия 02.10.2026: без «вернусь с ответом» (обещание, которого никто не
  // помнит) и без двух языков встык для смеси — см. priceGuardFallbackReply.
  const ru = "Подходящих вариантов сейчас нет. Наш агент подскажет, что есть похожего.";
  const tg = "Ҳоло вариантҳои мувофиқ надорем. Агенти мо мегӯяд, ки чӣ монанд ҳаст.";
  if (language === "tg" || language === "mixed") return [tg];
  return [ru];
}

/** Обёртка с записью в журнал — чтобы вызывающий не повторял текст сообщения.
 *  Подставляет безопасную заглушку сама, когда чистка съедает ответ целиком:
 *  вызывающий получает готовый безопасный текст, а не исходное обещание. */
export function applyAvailabilityGuard(
  bubbles: string[],
  hasProperties: boolean,
  language: ClientLanguage
): string[] {
  const guarded = guardAvailability(bubbles, hasProperties);
  if (guarded.removed.length > 0) {
    void logSystemError(
      "ai",
      guarded.keptDespiteViolation
        ? `Бот обещал варианты, которых нет («${guarded.removed[0]}»), и вычистить это без потери ответа не вышло — клиенту ушла безопасная заглушка вместо выдумки. Посмотрите диалог.`
        : `Бот обещал варианты при пустой подборке — вырезано: «${guarded.removed.join(" | ")}»`
    );
  }
  return guarded.keptDespiteViolation ? availabilityGuardFallbackReply(language) : guarded.bubbles;
}
