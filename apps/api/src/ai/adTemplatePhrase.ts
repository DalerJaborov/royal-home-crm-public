/**
 * К сравнимому виду: нижний регистр, ё→е, без эмодзи и знаков препинания,
 * одиночные пробелы. Латиница и кириллица остаются как есть — таджикский пишут
 * и так, и так, а нормализовать одно в другое значило бы склеивать разные слова.
 */
function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, "е")
    // Апостроф СКЛЕИВАЕТ, а не разделяет: «I'm» — одно слово, и превратив его в
    // «i m», мы перестали бы узнавать английский шаблон Meta.
    .replace(/['’`ʼʻ‘]/g, "")
    .replace(/[^\p{L}\p{N}\s]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** Убирает приветствия и вежливые обороты — по краям и внутри фразы. */
function stripGreetings(normalized: string): string {
  return normalized
    .split(" ")
    .filter((w) => w && !GREETING_WORDS.includes(w))
    .join(" ")
    .trim();
}

/**
 * Человек не сказал НИЧЕГО СВОЕГО: пусто, одно приветствие или ровно шаблон
 * рекламы (возможно, с приветствием).
 *
 * `text` — слова КЛИЕНТА за весь разговор (реплики бота исключает вызывающий
 * код, см. clientWords в messengers/conversation.ts).
 */
export function clientSaidNothingSubstantive(text: string | null | undefined): boolean {
  // Пересланный файл своими словами не считается: «он ещё ничего не написал»
  // должно оставаться правдой, если человек прислал только скрин чужого
  // объявления (тот же класс, что находка 3.1 проверки 21.09.2026).
  const rest = stripGreetings(normalize(clientOwnWords(text ?? "")));
  if (!rest) return true;
  return TEMPLATE_OPENERS.some((tpl) => {
    const t = normalize(tpl);
    // Полное совпадение или шаблон с обеих сторон обрамлён только пробелами:
    // «можно узнать об этом подробнее про 3 комнаты» — это уже СВОИ слова.
    return rest === t;
  });
}

/** Только шаблон кнопки (с приветствием или без): клиент не написал ни одной своей буквы. */
export function isAdTemplateOpener(text: string | null | undefined): boolean {
  const rest = stripGreetings(normalize(clientOwnWords(text ?? "")));
  return !!rest && TEMPLATE_OPENERS.some(template => rest === normalize(template));
}
/** Язык самой кнопки — слабая подсказка «на каком языке шла реклама», а не язык клиента:
 *  берётся только когда никаких слов клиента ещё нет. Узбекская кнопка — русский (узбекских шаблонов у бота нет). */
export function adTemplateLanguage(text: string | null | undefined): "ru" | "tg" {
  const rest = stripGreetings(normalize(clientOwnWords(text ?? "")));
  return /[ҳҷӣӯқғ]|маълумот|бештар|донам/u.test(rest) ? "tg" : "ru";
}
