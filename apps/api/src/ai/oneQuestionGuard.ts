/**
 * ОДИН ВОПРОС — ОДНО СООБЩЕНИЕ (разбор находок судьи 30.08.2026: 25 находок
 * репетиции + 8+ находок tone/other прямо называют причиной «задал два вопроса
 * в одной реплике», например: «Чӣ гуна кӯмак карда метавонам?» и «Хона мехаред
 * ё мефурӯшед?» одним сообщением, или «Дар кадом тарафи шаҳр?» и «Чандҳонагӣ?»
 * вместе).
 *
 * Правило прямо в промте (ai/leadQualifier.ts, правило 2: «Темп: только 1 вопрос
 * в 1 сообщении... Это правило БЕЗ исключений»). Промт для него не гарантия (см.
 * шапку ai/replyRepeatGuard.ts — тот же диагноз, другое правило): модель то и
 * дело формулирует два вопроса подряд одной репликой, несмотря на прямой запрет.
 *
 * ЗДЕСЬ — грубая и дешёвая проверка поверх промта, тем же приёмом, что и
 * dropRepeatedBubbles/dropPhoneAsks: если в пузыре два и больше НАСТОЯЩИХ
 * вопросительных знака (конец фразы, а не «?» посреди ссылки — `?id=7` не
 * считается), оставляем первый вопрос, а лишние вопросительные предложения
 * вырезаем — не задевая фактов между ними (см. collapseToOneQuestion). Второй вопрос
 * лучше не задать вовсе, чем задать вместе с первым: человек отвечает на
 * последний и молча теряет первый — та же логика, что и у остальных правил
 * этого файла.
 *
 * ИСКЛЮЧЕНИЕ — приём объекта у ПРОДАВЦА (ai/sellerIntake.ts, решение владельца
 * 18.08.2026): там сбор всех фактов объекта нарочно идёт одним сообщением с
 * несколькими вопросами сразу. Проверку гасит вызывающий код через intent
 * черновика, а не эта функция угадыванием по тексту.
 *
 * ПОЧЕМУ ЭТО НЕ ПОСЛЕДНИЙ РУБЕЖ, А РАННИЙ (см. вызов в messengers/conversation.ts,
 * до ensureOpenQuestionKept/ensurePhoneAskKept). Ниже по конвейеру topicLock и
 * напоминание о номере сознательно ДОПИСЫВАЮТ текст в конец уже готовой реплики —
 * это их собственная, отдельно обоснованная гарантия «не потерять важный вопрос»
 * (topicLock даже считает свои повторы отдельным пределом, MAX_OPEN_QUESTION_PRESSES
 * в ai/topicLock.ts). Резать их дописку этим фильтром значило бы сломать то, ради
 * чего они написаны. Здесь ловится только то, что вопросом сформулировала САМА
 * модель, — источник почти всех находок судьи по этому типу.
 */

/**
 * «?» на конце фразы: за ним пробел, конец строки, кавычка или скобка.
 * Без этого условия `?` внутри `somon.tj/adv/12345?ref=7` тоже считался бы
 * вопросом — знак там есть, а вопроса нет.
 */
const SENTENCE_QUESTION = /\?(?=[\s"'»)\]]|$)/gu;

/** Сколько настоящих вопросов в тексте — по границе, описанной выше. */
export function countSentenceQuestions(text: string): number {
  const matches = text.match(SENTENCE_QUESTION);
  return matches ? matches.length : 0;
}

/**
 * Конец НЕВОПРОСИТЕЛЬНОГО предложения: знак и за ним пробел или конец строки.
 *  Пробел после знака обязателен: иначе границей считалась бы точка внутри числа («54.5 метр»).
 *  Перенос строки — граница сам по себе: модель сплошь пишет ссылку или факт
 *  отдельной строкой без точки в конце. */
const SENTENCE_END = /(?:[.!\u2026](?=\s|$)|\n)/gu;

/**
 * Один пузырь, два и больше вопроса → остаётся ПЕРВЫЙ вопрос и ВСЕ факты.
 * Меньше двух вопросов — текст не трогаем вовсе.
 *
 * ДО 20.09.2026 ТЕКСТ РЕЗАЛСЯ ПО ПЕРВОМУ «?» ЦЕЛИКОМ — и вместе со вторым
 * вопросом молча терялось всё, что стояло МЕЖДУ вопросами: цена, район, площадь,
 * ссылка на объект. То есть правило против лишнего вопроса съедало ответ на
 * заданный — именно то, от чего бот читается «не слушает и переспрашивает» (жалоба
 * владельца 20.09.2026, разбор docs/bot-razbor-20-09.md, класс 4 п. 4).
 *
 * Теперь вырезается РОВНО вопросительное предложение, а не всё после него: у каждого
 * куска после первого вопроса отбрасывается последнее предложение (оно и есть сам
 * вопрос), а факты перед ним остаются. Границы предложения в куске нет — значит
 * весь кусок и был вопросом, и он уходит целиком, как и раньше.
 */
export function collapseToOneQuestion(text: string): string {
  const matches = [...text.matchAll(SENTENCE_QUESTION)];
  if (matches.length < 2) return text;
  // Вырезаем именно куски текста, а не собираем остаток заново: так переносы строк
  // и абзацы остаются ровно такими, какими их сделала модель.
  const cuts: [number, number][] = [];
  for (let i = 1; i < matches.length; i++) {
    const from = (matches[i - 1].index ?? 0) + 1;
    const to = (matches[i].index ?? 0) + 1;
    const chunk = text.slice(from, to);
    const ends = [...chunk.matchAll(SENTENCE_END)];
    const lastEnd = ends.length ? (ends[ends.length - 1].index ?? 0) + 1 : 0;
    cuts.push([from + lastEnd, to]);
  }
  let out = text;
  for (const [from, to] of cuts.reverse()) out = `${out.slice(0, from)}${out.slice(to)}`;
  return out
    .replace(/[ \t]{2,}/g, " ")
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

/**
 * Применяет правило ко всем пузырям хода разом.
 *
 * @param allowMultiQuestion — истина только для приёма объекта у продавца
 *   (см. заголовок файла); во всех остальных сценариях правило без исключений.
 */
export function enforceOneQuestionPerBubble(bubbles: string[], allowMultiQuestion = false): string[] {
  if (allowMultiQuestion) return bubbles;
  let trimmedCount = 0;
  const result = bubbles.map((b) => {
    const collapsed = collapseToOneQuestion(b);
    if (collapsed !== b) trimmedCount++;
    return collapsed;
  });
  // Считаем ПУЗЫРИ, где текст обрезан, а не сам факт срабатывания — как и у
  // bot_repeat в ai/replyRepeatGuard.ts: масштаб важнее факта.
  if (trimmedCount > 0) guardFired("two_questions", trimmedCount);
  return result;
}
