/** Сколько адресов из своей базы отдаём модели: список для ориентировки, не каталог. */
const MAX_BASE_ADDRESSES = 60;

/**
 * Строки справочника «адрес — район» из карточек объектов: чистая функция, чтобы
 * порядок и отсев проверялись тестом без базы.
 *
 * СНАЧАЛА ТО, ЧТО В ПРОДАЖЕ (20.09.2026, разбор живых переписок, класс 6 п. 3).
 * Проданные и снятые объекты из справочника НЕ выбрасываем: адрес дома и его район
 * от продажи квартиры не меняются, а справочник тем и ценен, что знает как можно
 * больше домов Душанбе — отсев по статусу выкинул бы верное знание («Бустон Сити —
 * Шохмансур») и вернул бы боту тот самый вопрос «а это какой район?», который
 * владелец запретил 16.08.2026. Но мест в справочнике всего MAX_BASE_ADDRESSES, и
 * занимать их проданным, пока непоказанными остаются дома в продаже, неправильно:
 * адреса живых объектов идут первыми. Сортировка стабильная (ES2019) — внутри каждой
 * группы прежний порядок «сначала новые» сохраняется.
 */
export function geographyAddressLines(
  rows: { address: string | null; status: string; district: { name: string } | null }[],
  max = MAX_BASE_ADDRESSES
): string[] {
  const ordered = [...rows].sort(
    (a, b) => (a.status === "AVAILABLE" ? 0 : 1) - (b.status === "AVAILABLE" ? 0 : 1)
  );
  // Один адрес может повторяться у нескольких квартир в одном доме — показываем
  // каждый дом один раз, иначе список раздувается копиями и вытесняет полезное.
  const seen = new Map<string, string>();
  for (const r of ordered) {
    // Закрытый объект (offSite) может остаться без адреса/района вовсе — такой
    // строке в справочнике ориентиров взяться неоткуда, пропускаем её здесь же.
    if (!r.address || !r.district) continue;
    const key = r.address.trim().toLowerCase();
    if (key && !seen.has(key)) seen.set(key, `${r.address.trim()} — ${r.district.name}`);
    if (seen.size >= max) break;
  }
  return [...seen.values()];
}

/**
 * География из НАШЕЙ базы объектов.
 *
 * Самый надёжный источник и единственный, который пополняется сам: у каждого объекта
 * район уже проставлен агентом, а адрес написан живым языком, с названиями комплексов.
 * Если клиент называет дом, который у нас есть в продаже, район определяется точно —
 * спрашивать незачем. Ровно это имел в виду владелец: "сверяя всё с нашей базой".
 */
export async function propertyGeographyBlock(): Promise<string> {
  try {
    const rows = await prisma.property.findMany({
      where: { deletedAt: null },
      select: { address: true, status: true, district: { select: { name: true } } },
      orderBy: { createdAt: "desc" },
      take: 300,
    });
    const lines = geographyAddressLines(rows);
    if (lines.length === 0) return "";
    return (
      // Без слова «база» в заголовке — по той же причине, что и у списка объектов
      // (см. leadQualifier.ts): клиенту это слово говорить запрещено, а модель охотно
      // повторяет то, что читает рядом с данными. Убрать подсказку надёжнее, чем запрещать.
      // ЯВНО НЕ СПИСОК НАЛИЧИЯ (20.09.2026, класс 6 п. 3). Заголовок «дома, которые
      // мы ведём» рядом с живыми адресами читается как ассортимент, а в списке есть
      // и проданные дома (см. geographyAddressLines выше) — модель могла назвать такой адрес
      // как вариант в продаже. Наличие живёт в отдельном блоке с ценами и ссылками
      // (leadQualifier.ts::searchMatchingProperties, только status=AVAILABLE), и
      // здесь об этом сказано прямо.
      "\n\nАДРЕСА ДОМОВ, ПО КОТОРЫМ РАЙОН ИЗВЕСТЕН ТОЧНО (справочник для определения района: " +
      "если клиент назвал что-то из этого, район бери отсюда и НЕ переспрашивай). " +
      "ЭТО НЕ СПИСОК ТОГО, ЧТО ЕСТЬ В ПРОДАЖЕ — часть этих домов уже продана; " +
      "про наличие и цены говори ТОЛЬКО по блоку с вариантами:\n" +
      lines.map((v) => `- ${v}`).join("\n")
    );
  } catch (err) {
    // Молчал (правка 22.09.2026): справочник адресов исчезал из промта, и бот
    // начинал переспрашивать район у людей, назвавших известный дом. Внешне
    // неотличимо от «модель поглупела», в журнале — ни строки.
    void logSystemError("ai", `Справочник адресов для промта не прочитан: ${describeError(err)}`, {
      dedupKey: "bot-geography-addresses",
    });
    return "";
  }
}
