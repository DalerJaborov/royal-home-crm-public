import { guardFired } from "./guardMetrics.js";

/**
 * СЛОВА, ЗАПРЕЩЁННЫЕ ПОИМЁННО В <language_and_slang> (ai/leadQualifier.ts,
 * AGENCY_VOICE) — А ПРОМТ ИХ ВСЁ РАВНО ИНОГДА ПИШЕТ.
 *
 * Список в AGENCY_VOICE длиннее этого файла: там ещё «манзур», «илтимос»,
 * «пешниҳод намудан», «хабарҳои шахсӣ» и другие. Здесь — НЕ весь список, а
 * только два слова, у которых есть ОБА условия разом: живая находка судьи
 * 30.08.2026 (BotAuditFinding, тип tone) И безопасная механическая замена, не
 * рискующая задеть постороннее значение того же слова.
 *
 * «ПЕШНИҲОД» СЮДА НАРОЧНО НЕ ВОШЁЛ, ХОТЯ ТОЖЕ БЫЛ В НАХОДКЕ СУДЬИ. Первая
 * версия этого файла резала его как отдельное слово (по правилу «пешниҳод
 * намудан» → «нишон медиҳем») и тут же сломала боевой тест reply-guards.test.ts:
 * «Чи шуд бо пешниҳоди ҳамкорӣ?» («что с предложением о сотрудничестве?») —
 * здесь «пешниҳод» обычное существительное «предложение», а не запрещённый
 * канцелярский оборот «предлагать/представлять», и вырезание украло смысл
 * фразы целиком. Правило языка говорит о ГЛАГОЛЬНОМ обороте («пешниҳод намудан/
 * мекунем»), а не о слове вообще, — различить это надёжно регуляркой нельзя,
 * и гадать вместо разбора живого случая означало бы менять чужой смысл. Тот же
 * риск — у «манзур», «илтимос», «баррасӣ мекунем» и остальных слов списка:
 * без единого проверенного случая на каждое трогать их здесь не стоит.
 *
 * ХВОСТ СЛОВА НЕ ФИКСИРОВАН НАРОЧНО (`\p{L}*` после корня). Таджикский лепит
 * окончания и изафет к корню слитно («мутахассис» → «мутахассиси мо» — «наш
 * специалист»), и точное совпадение промахивалось бы на каждой второй форме —
 * тот же приём и та же причина, что и у questionStems в ai/replyGuards.ts.
 *
 * «МУТАХАССИС» ЗАМЕНЯЕТСЯ, А НЕ ВЫРЕЗАЕТСЯ: в правилах прямая замена на «агент»
 * («агенти мо занг мезанад»), и вырезание оставило бы фразу без подлежащего.
 * Хвост (изафет/суффикс) переносится на замену: «мутахассиси» → «агенти», а не
 * «агент» — иначе «мутахассиси мо» превратилось бы в «агент мо».
 *
 * «ЛУТФАН» ВЫРЕЗАЕТСЯ ЦЕЛИКОМ — по тому же принципу, что и stripForeignWords
 * (ai/replyGuards.ts): это вежливая частица («пожалуйста»), у неё нет второго
 * значения, которое можно случайно задеть, а подмена синонимом («бемалол») в
 * чужом месте предложения рискует испортить фразу больше, чем её отсутствие.
 */

/** Левая и правая граница слова — своя, не `\b`: в JS `\b` не совпадает с
 *  кириллицей вовсе (те же грабли уже разобраны в ai/replyGuards.ts). */
const LEFT = "(^|[\\s,.!?;:«»\"'()\\-–—])";
const RIGHT = "([\\s,.!?;:«»\"'()\\-–—]|$)";

/** Заменяется на «агент» — без подстановки предложение остаётся без подлежащего.
 *  Хвост (группа 2) переносится на замену: «мутахассиси» → «агенти». */
const MUTAKHASSIS_RE = new RegExp(`${LEFT}мутахассис(\\p{L}*)${RIGHT}`, "giu");

/** Вырезается целиком, соседние границы схлопываются в одну (см. stripForeignWords). */
const LUTFAN_RE = new RegExp(`${LEFT}лутфан${RIGHT}`, "giu");

export function stripBannedWords(text: string): string {
  let out = text.replace(MUTAKHASSIS_RE, (_m, left: string, tail: string, right: string) => `${left}агент${tail}${right}`);
  // Проход повторяется, пока текст меняется — та же причина, что у
  // stripForeignWords: у соседних запрещённых слов общая граница, и один проход
  // съедает её только у первого совпадения.
  for (let pass = 0; pass < 3; pass += 1) {
    const next = out.replace(LUTFAN_RE, (_m, left: string, right: string) => `${left}${right}`);
    if (next === out) break;
    out = next;
  }
  // Слово могло стоять первым в реплике («Лутфан, рақами...») — вырезание
  // оставляет висящую запятую в начале строки (та же чистка, что и у
  // stripGenderedAddress в ai/replyGuards.ts).
  // «Рақаматонро, лутфан, нависед» → «Рақаматонро,, нависед», «нависед, лутфан!» →
  // «нависед,!» (02.10.2026): у слова между запятыми обе границы — запятые, и они
  // возвращались обе. Схлопываем двойную и висящую перед концом фразы.
  out = out
    .replace(/,[ \t]*,/g, ",")
    .replace(/,[ \t]*([!?.])/g, "$1")
    .replace(/[ \t]{2,}/g, " ")
    .replace(/^[\s,;:]+/, "")
    .replace(/[\s,;:]+$/, "")
    .trim();
  const changed = out !== text.trim();
  // Заглавная буква возвращается ТОЛЬКО если реплика реально изменилась: вырезанное
  // первое слово могло оставить фразу со строчной буквы.
  if (changed && out) out = out[0].toUpperCase() + out.slice(1);
  if (changed) guardFired("banned_word");
  return out;
}

/**
 * Какие запрещённые слова есть в тексте — без правки текста (10.10.2026, аудит «одно
 * окно», P1-6). Голосу вырезать сказанное нельзя: звук уже ушёл в линию, — поэтому
 * сторож голоса (lib/telephony/liveVoiceGuards.ts) только сообщает находку и поправляет
 * следующую реплику. Те же регулярки, что у stripBannedWords: одно место.
 */
export function findBannedWords(text: string): string[] {
  const found: string[] = [];
  for (const re of [MUTAKHASSIS_RE, LUTFAN_RE]) {
    for (const m of text.matchAll(re)) {
      const word = m[0].replace(/^[\s,.!?;:«»"'()\-–—]+|[\s,.!?;:«»"'()\-–—]+$/g, "").toLowerCase();
      if (word && !found.includes(word)) found.push(word);
    }
  }
  return found;
}
