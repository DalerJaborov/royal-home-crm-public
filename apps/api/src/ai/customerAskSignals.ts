/** Слова самого клиента, свёрнутые, без цитат и упоминаний роли. */
export function customerAskText(text: string): string {
  return foldCustomerText(withoutQuotes(clientOwnWords(text ?? ""))).replace(ROLE_MENTION, " ");
}

/** customerAskText без отказов от звонка и от человека — для старых списков
 * слов, которые сами отрицания не различают (ai/operatorHandoff.ts). Вопрос о
 * роли или вакансии («кто такой оператор?», «вам нужен менеджер?») — пустая строка. */
export function customerAskTextWithoutRefusals(text: string): string {
  const own = customerAskText(text);
  if (HUMAN_NOT_REQUEST.test(own)) return "";
  return own.replace(new RegExp(HUMAN_REFUSAL.source, "giu"), " ")
    .replace(new RegExp(CALL_REFUSAL.source, "giu"), " ").replace(/\s+/gu, " ").trim();
}

/** Отказ от звонка в словах клиента («не звоните», «занг назанед»). */
export function customerRefusesCall(text: string): boolean {
  return CALL_REFUSAL.test(customerAskText(text));
}

/** Явная просьба о звонке: отрицания и цитаты вырезаны, номер сам по себе — не просьба. */
export function customerAsksForCall(text: string): boolean {
  const own = customerAskText(text).replace(new RegExp(CALL_REFUSAL.source, "giu"), " ");
  return CALL_ASK.test(own);
}

/** Отказ от человека («не нужен оператор», «корманд лозим нест»). */
export function customerRefusesHuman(text: string): boolean {
  return HUMAN_REFUSAL.test(customerAskText(text));
}

/** Явная просьба о живом человеке. Вопрос о роли/вакансии и отказ («не нужен оператор») — нет. */
export function customerAsksForHuman(text: string): boolean {
  const own = customerAskText(text);
  if (!own || HUMAN_NOT_REQUEST.test(own)) return false;
  const kept = own.replace(new RegExp(HUMAN_REFUSAL.source, "giu"), " ").trim();
  // Голое слово — только когда отказа не было: «корманд намехоҳам» без отказа стало бы «корманд».
  return HUMAN_ASK.test(kept) || (BARE_HUMAN.test(own) && !HUMAN_REFUSAL.test(own));
}

/** Жалоба «со мной никто не связался». Обычное «позвоните мне» сюда не попадает. */
export function customerComplainsNoContact(text: string): boolean {
  const own = customerAskText(text);
  return !!own && NO_CONTACT.test(own);
}

/**
 * Тема разговора касается людей или связи — слово «человек/агент/оператор…»
 * или «звон/связ/ответ/занг/тамос». Это ЯКОРЬ для решения модели о передаче:
 * модель решает, код только проверяет, что сообщение вообще о связи с людьми и
 * не отказ. Отказы и упоминания роли к этому моменту уже вырезаны.
 */
const CONTACT_ANCHOR = rx([
  HUMAN_NOUN,
  // «Связь» само по себе — не о людях («связь плохая»): только «связаться», «свяжитесь», «на связь».
  `${BW}(?:пере|по|до)?звон${TAIL}`, `${BW}связал${TAIL}`, `${BW}связать${TAIL}`, `${BW}свяж${TAIL}`, `${BW}на\\s+связь${EW}`,
  `${BW}(?:корманд|одам|занг|тамос|мутахассис)${TAIL}`,
  `${BW}(?:human|person|operator|manager|agent|zang|tamos|odam|kormand)${TAIL}`,
]);
export function customerTalksAboutContact(text: string): boolean {
  const own = customerAskText(text);
  // Любой отказ («оператор не нужен», «корманд намехоҳам», «не звоните») снимает
  // свободу модели: тогда передать можно только по явной просьбе выше.
  if (!own || HUMAN_NOT_REQUEST.test(own) || HUMAN_REFUSAL.test(own) || CALL_REFUSAL.test(own)) return false;
  return CONTACT_ANCHOR.test(own);
}

/**
 * КОРОТКОЕ «ДА» НА СОБСТВЕННЫЙ ВОПРОС БОТА О ЗВОНКЕ. Само по себе это ничего не
 * разрешает: засчитывается только вместе с доказательством, что ПРЕДЫДУЩИМ
 * ходом бот сам спросил о звонке и вопрос доставлен (lib/customerAcceptedCallbackQuestion.ts).
 *
 * Принимает: «Да, конечно», «Да, пожалуйста», «Хорошо», «Давайте», «Ага», «Бале»,
 * «Хуб», «Ҳа, албатта», «ха», «да, звоните». Не принимает: вопрос («Да?»),
 * отрицание («Да, но не звоните», «Ҳа не»), цитату (««Да»»), пересказ («Он
 * сказал: да»), смайлик и всё, где есть слово вне короткого словаря.
 */
const AFFIRM_WORDS = "да|ха|ага|угу|ок|окей|окэй|ok|okay|хорошо|хоп|ладно|давайте|давай|конечно|разумеется|можно|согласен|согласна|согласны|бале|албатта|хуб|майлаш|майли|рози|розиям|yes|ha|xa|da|bale|xub|hub|mayli|maylash|albatta|звоните|позвоните|наберите|занг\\s+занед";
const AFFIRM_HEAD = `(?:${AFFIRM_WORDS})`;
const AFFIRM_TAIL = `(?:${AFFIRM_WORDS}|пожалуйста|пж|плиз|please|илтимос|лутфан|спасибо|рахмат|ташаккур|буду\\s+рад|буду\\s+рада|буду\\s+ждать|жду|жду\\s+звонка|в\\s+любое\\s+время|можно\\s+звонить|звоните\\s+пожалуйста|мне|сейчас|сегодня|завтра|мезанед|занг\\s+занед|тамос\\s+гиред|конечно\\s+можно)`;
const AFFIRMATIVE = new RegExp(`^${AFFIRM_HEAD}(?:[\\s,.!;:)-]+${AFFIRM_TAIL})*[\\s.!)]*$`, "u");
/** Номер (9–15 цифр) с именем или парой связок: «Алишер 927123456», «Вот мой номер …». */
const PHONE_RUN = /\+?\d[\d\s().-]{7,22}\d/gu;
const NEGATION_WORD = new RegExp(`${BW}(?:не|нет|ни|нельзя|не\\s+надо|no|not|na)${EW}`, "u");

export function isCustomerShortCallbackYes(text: string): boolean {
  const raw = (text ?? "").normalize("NFC").trim();
  if (!raw || raw.length > 200 || /[?？«»"“”„<>]/u.test(raw)) return false;
  const folded = foldCustomerText(raw);
  if (AFFIRMATIVE.test(folded)) return true;
  // Ответ номером (с именем) на вопрос бота о звонке — тоже согласие.
  const phones = folded.match(PHONE_RUN) ?? [];
  if (phones.length !== 1 || !/^\d{9,15}$/.test(phones[0].replace(/\D/g, ""))) return false;
  const rest = folded.replace(PHONE_RUN, " ").replace(/[,.:;!()\-–—+]/gu, " ").trim();
  if (NEGATION_WORD.test(rest)) return false;
  const words = rest ? rest.split(/\s+/u) : [];
  return words.length <= 6 && words.every(word => /^\p{L}+$/u.test(word));
}
