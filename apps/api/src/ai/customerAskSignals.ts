/**
 * ЧТО КЛИЕНТ ПРОСИТ: ЗВОНОК, ЖИВОГО ЧЕЛОВЕКА, ИЛИ ЖАЛУЕТСЯ, ЧТО НЕ ПОЗВОНИЛИ
 * (одна дверь, 14.11.2026).
 *
 * ЖИВОЙ СЛУЧАЙ (аудит 14.11.2026). Модель клиента понимала, а решал код — узким
 * списком фраз, разным в пяти местах (согласие на звонок, передача сотруднику,
 * жалоба «не позвонили», просьба оператора, тема звонка). Модель отвечала
 * «передам агенту», код отказывал, клиент повторял, и сторож исходящих
 * (lib/outboundShield.ts, правило `repeat`) после третьего одинакового ответа
 * ставил разговор на паузу 6 часов — заявка терялась. Срабатывали не «Да», а
 * «Да, конечно»; не «соедините с оператором», а «Можно с менеджером?»; не «мне
 * не перезвонили», а «Мне никто не звонит».
 *
 * Поэтому словарь теперь ОДИН, здесь, и его зовут все пять мест. Каждое место
 * оставляет свой порог (оператор ≠ звонок ≠ передача), но слова берёт отсюда.
 *
 * Как устроено распознавание:
 *  1. Слова самого клиента: врезки из файлов/видео/заметок CRM снимаются
 *     (clientOwnWords), расшифровка голосового остаётся.
 *  2. Свёртка: регистр, «ё→е», таджикские буквы → русские двойники
 *     (ҳ→х, ӯ→у, ҷ→ч, ӣ→и, қ→к, ғ→г) — люди пишут и так, и так.
 *  3. Цитаты «…» / "…" вырезаются: процитированная чужая фраза — не просьба. Но
 *     «я вам написал» без кавычек больше НЕ отменяет просьбу (раньше отменяло).
 *  4. Отрицания («не звоните», «оператор не нужен», «занг назанед») вырезаются
 *     ДО поиска просьбы — тогда «не звоните завтра, позвоните в пятницу» остаётся
 *     просьбой, а «не звоните» — нет.
 *  5. Упоминание роли («я работаю оператором», «у меня оператор Билайн», «я
 *     менеджер по продажам») вырезается: это не просьба позвать человека.
 *
 * Границы слов — только через ai/wordBoundary.ts: `\b` и `\w` по кириллице молчат.
 */

import { BW, EW, TAIL } from "./wordBoundary.js";
import { clientOwnWords } from "./untrustedContent.js";

const rx = (parts: readonly string[], flags = "iu"): RegExp => new RegExp(parts.join("|"), flags);

/** Регистр, «ё», таджикские буквы — к одному виду; пробелы схлопнуты. */
export function foldCustomerText(text: string): string {
  return (text ?? "").normalize("NFC").toLowerCase()
    .replace(/ё/g, "е").replace(/ҳ/g, "х").replace(/ӯ/g, "у").replace(/ҷ/g, "ч")
    .replace(/ӣ/g, "и").replace(/қ/g, "к").replace(/ғ/g, "г")
    .replace(/[’‘`]/g, "'").replace(/\s+/g, " ").trim();
}

/** Процитированное — чужие слова, не просьба клиента. */
const QUOTED = /«[^»]*»|"[^"]*"|“[^”]*”|„[^“”]*[“”]/gu;
export function withoutQuotes(text: string): string {
  return text.replace(QUOTED, " ");
}

