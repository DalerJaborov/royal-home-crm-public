import { guardFired } from "./guardMetrics.js";

/**
 * СРОК ЗВОНКА АГЕНТА В ОТВЕТЕ БОТА — ВЫРЕЗАЕТСЯ КОДОМ (владелец 22.11.2026: «срок
 * звонка агента («через N минут») не называть никогда — только «агент свяжется»»).
 *
 * Промт это уже запрещает, но модель продолжает писать («он позвонит вам завтра с
 * 10:00», проверено на проде 22.11 08:59 и 23.11 23:38): рабочие часы агентства
 * лежат у неё в фактах, и она сама строит из них обещание. Бот не знает, когда
 * агент освободится, и невыполненный срок хуже отсутствия срока. Поэтому, как и
 * у остальных запретов (ai/bannedWordsGuard.ts), правило стоит и в промте, и в коде.
 *
 * ЧТО РЕЖЕТСЯ — только срок, а не сам смысл «агент свяжется»: «завтра с 10:00»,
 * «сегодня», «через 5 минут», «в течение часа», «пагоҳ аз соати 10:00», «баъди 5
 * дақиқа». Режется ТОЛЬКО в предложении, где есть глагол связи (позвонит, свяжется,
 * занг мезанад, тамос мегирад): «Показ завтра в 10:00» этой правки не касается.
 * Границы слов свои, не `\b`: в JS `\b` не видит кириллицу (см. ai/wordBoundary.ts).
 */

/** Слово связи в предложении: без него предложение не про звонок агента. */
const CONTACT_VERB = /(?<![\p{L}\d])(?:позвон|перезвон|свяж|связ|звонок|звонк|занг|тамос|алоқа)/iu;

const L = "(?<![\\p{L}\\d])";
const R = "(?![\\p{L}\\d])";
const CLOCK = "\\d{1,2}(?:[:.]\\d{2})?";

/** Порядок важен: длинные формы раньше коротких, иначе «завтра» срежется отдельно от времени. */
const TIME_PHRASES: RegExp[] = [
  // «сегодня/завтра (с|после|до|около|к) 10:00 (до 18:00)»
  new RegExp(
    `${L}(?:(?:сегодня|завтра|послезавтра)\\s*)?(?:с|после|до|около|ближе\\s+к|к|в)\\s+${CLOCK}(?:\\s*(?:ч|час\\p{L}*|утра|вечера))?(?:\\s*(?:-|–|до)\\s*${CLOCK})?${R}`,
    "giu"
  ),
  // «через 5 минут», «через час», «через пару часов»
  new RegExp(`${L}через\\s+(?:\\d+|пару|несколько|полчаса|час|минуту)(?:\\s*(?:минут\\p{L}*|мин\\.?|час\\p{L}*|секунд\\p{L}*))?${R}`, "giu"),
  // «в течение 10 минут / часа / дня», «в ближайшие 15 минут»
  new RegExp(`${L}в\\s+течени[ие]\\s+(?:\\d+\\s*)?(?:минут\\p{L}*|мин\\.?|час\\p{L}*|дн\\p{L}*|суток|рабоч\\p{L}+\\s+\\p{L}+)${R}`, "giu"),
  new RegExp(`${L}в\\s+ближайш\\p{L}+\\s+\\d+\\s*(?:минут\\p{L}*|мин\\.?|час\\p{L}*)${R}`, "giu"),
  // таджикский: «пагоҳ аз соати 10:00», «имрӯз то соати 18:00», «аз соати 10:00 то 18:00»
  // «имрӯз баъд аз соати 10:00» (прод 24.11.2026, 7d0df9a4: «баъд аз» прежний шаблон не брал, и от фразы оставался обрывок).
  new RegExp(`${L}(?:(?:имрӯз|имруз|пагоҳ|пагох|пасфардо)\\s*)?(?:баъд\\p{L}*\\s+аз|аз|то|баъд\\p{L}*)?\\s*соати\\s+${CLOCK}(?:\\s*(?:то|-|–)\\s*${CLOCK})?${R}`, "giu"),
  // «баъди 5 дақиқа», «дар давоми 10 дақиқа», «дар 10 дақиқа»
  new RegExp(`${L}(?:баъд\\p{L}*|дар\\s+давоми|дар)\\s+(?:\\d+|чанд|як)\\s*(?:дақиқа|соат|рӯз)\\p{L}*${R}`, "giu"),
  // одинокие слова дня
  new RegExp(`${L}(?:сегодня|завтра|послезавтра|имрӯз|имруз|пагоҳ|пагох|пасфардо)${R}`, "giu"),
];

/** Предложение: заканчивается . ! ? или переводом строки; точка внутри «10.00» не конец. */
const SENTENCE_END = /([.!?]+(?=\s|$)|\n)/;

function stripFromSentence(sentence: string): string {
  if (!CONTACT_VERB.test(sentence)) return sentence;
  let out = sentence;
  for (const re of TIME_PHRASES) out = out.replace(re, "");
  return out
    .replace(/[ \t]{2,}/g, " ")
    .replace(/\s+([,;:])/g, "$1")
    .replace(/,\s*,/g, ",")
    .replace(/,(\s*)$/g, "$1")
    .replace(/[ \t]+$/, "");
}

export function stripCallTimePromise(text: string): string {
  if (!text) return text;
  const parts = text.split(SENTENCE_END);
  const out = parts.map((part, i) => (i % 2 === 0 ? stripFromSentence(part) : part)).join("");
  const cleaned = out.replace(/[ \t]+\n/g, "\n").replace(/[ \t]{2,}/g, " ").trim();
  if (cleaned === text.trim()) return text;
  guardFired("call_time_promise");
  return cleaned;
}

/** Есть ли в тексте срок звонка — без правки (для сторожей и проверок). */
export function hasCallTimePromise(text: string): boolean {
  return stripCallTimePromiseSilently(text) !== text.trim();
}

function stripCallTimePromiseSilently(text: string): string {
  const parts = text.split(SENTENCE_END);
  return parts
    .map((part, i) => (i % 2 === 0 ? stripFromSentence(part) : part))
    .join("")
    .replace(/[ \t]+\n/g, "\n")
    .replace(/[ \t]{2,}/g, " ")
    .trim();
}
