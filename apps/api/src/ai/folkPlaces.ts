const DISTRICT_ORDER: OfficialDistrict[] = ["Сино", "Фирдавси", "Шохмансур", "Исмоили Сомони"];

/** Справочник меняется разовым импортом и ручной правкой — читать его на каждый
 *  ход бота незачем. Тот же потолок, что у словаря мест в ai/geoMentions.ts. */
const COVERAGE_TTL_MS = 5 * 60_000;

export interface FolkCoverage {
  place: FolkPlace;
  /** Карта знает это название (нашлось в словаре синонимов). */
  onMap: boolean;
  /** Район, который карта называет для этой точки — null, если не определила. */
  mapDistrict: string | null;
}

let coverageCache: { at: number; rows: FolkCoverage[] } | null = null;

/** Сбросить разбор покрытия — для тестов и после правки справочника. */
export function resetFolkCoverageCache(): void {
  coverageCache = null;
}

type TargetKey = string;

async function targetCoordinates(): Promise<Map<TargetKey, { lat: number; lng: number }>> {
  const [streets, landmarks, microdistricts, livingAreas] = await Promise.all([
    prisma.street.findMany({ select: { id: true, lat: true, lng: true } }),
    prisma.landmark.findMany({ where: { enabled: true }, select: { id: true, lat: true, lng: true } }),
    prisma.microdistrict.findMany({ select: { id: true, lat: true, lng: true } }),
    prisma.livingArea.findMany({ select: { id: true, lat: true, lng: true } }),
  ]);
  const out = new Map<TargetKey, { lat: number; lng: number }>();
  for (const s of streets) out.set(`street:${s.id}`, { lat: Number(s.lat), lng: Number(s.lng) });
  for (const l of landmarks) out.set(`landmark:${l.id}`, { lat: Number(l.lat), lng: Number(l.lng) });
  for (const m of microdistricts) out.set(`microdistrict:${m.id}`, { lat: Number(m.lat), lng: Number(m.lng) });
  for (const a of livingAreas) out.set(`livingArea:${a.id}`, { lat: Number(a.lat), lng: Number(a.lng) });
  return out;
}

/**
 * Что карта знает про каждое народное название. Пустой справочник (стенд, тесты)
 * даёт «карта не знает ничего» — и список печатается целиком, как до правки.
 */
export async function folkCoverage(): Promise<FolkCoverage[]> {
  if (coverageCache && Date.now() - coverageCache.at < COVERAGE_TTL_MS) return coverageCache.rows;
  const normalized = FOLK_PLACES.map((p) => geoMatchKey(p.name));
  const [aliases, coords] = await Promise.all([
    prisma.geoAlias.findMany({
      where: {
        // Свёртку таджикских букв база не знает (она в памяти, см. geoNormalize.ts),
        // поэтому тут выбираем шире — по типу цели — и сверяем ключи уже у себя.
        targetType: { in: ["street", "landmark", "microdistrict", "livingArea"] },
      },
      select: { normalized: true, targetType: true, targetId: true },
    }),
    targetCoordinates(),
  ]);
  const byNormalized = new Map<string, { lat: number; lng: number }>();
  const wanted = new Set(normalized);
  for (const a of aliases) {
    const key = foldTajikLetters(a.normalized);
    if (!wanted.has(key)) continue;
    const point = coords.get(`${a.targetType}:${a.targetId}`);
    // Синоним может вести на выключенный ориентир — такой точки в карте нет.
    if (!point || byNormalized.has(key)) continue;
    byNormalized.set(key, point);
  }
  const rows: FolkCoverage[] = [];
  for (const [i, place] of FOLK_PLACES.entries()) {
    const point = byNormalized.get(normalized[i]);
    if (!point) {
      rows.push({ place, onMap: false, mapDistrict: null });
      continue;
    }
    const district = await districtByPoint(point.lat, point.lng);
    rows.push({ place, onMap: true, mapDistrict: district?.name ?? null });
  }
  coverageCache = { at: Date.now(), rows };
  return rows;
}

/** Названия, которых карта не знает вовсе, — их заводят руками в справочнике. */
export async function folkPlacesMissingOnMap(): Promise<FolkPlace[]> {
  return (await folkCoverage()).filter((r) => !r.onMap).map((r) => r.place);
}

/** Печатаем название, только если карта его не знает или отвечает другим районом. */
function keepInPrompt(row: FolkCoverage): boolean {
  if (!row.onMap) return true;
  if (!row.mapDistrict) return true;
  return row.mapDistrict !== row.place.district;
}

