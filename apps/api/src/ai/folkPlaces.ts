  "1. Если человек говорит \"Центр\" без уточнений — спроси одним вопросом: " +
  "\"Центр большой — вам ближе к ЦУМу и Дому печати или к Садбаргу и Оперке?\" " +
  "Спрашивай ОДИН раз: не ответил — не повторяй, ищи по центру целиком.\n";

/** Какие народные названия печатать: голосу — все, текстовым ботам — чего карта не знает. */
export function folkPlacesForPrompt(rows: FolkCoverage[], voice: boolean): FolkPlace[] {
  return rows.filter((r) => voice || keepInPrompt(r)).map((r) => r.place);
}

export async function folkGeographyBlock(options: { voice?: boolean } = {}): Promise<string> {
  let rows: FolkCoverage[];
  try {
    rows = await folkCoverage();
  } catch {
    // База недоступна — печатаем список целиком, как до правки: потерять знание
    // города из-за отказа справочника хуже, чем напечатать лишние строки.
    rows = FOLK_PLACES.map((place) => ({ place, onMap: false, mapDistrict: null }));
  }
  /**
   * ГОЛОСУ — СПИСОК ЦЕЛИКОМ (10.10.2026, аудит поиска P0-3). Строка с названием,
   * которое карта знает в том же районе, выпадает в расчёте на блок «места по карте»
   * (ai/geoMentions.ts) — а голосу этот блок не приходит вовсе: Live API читает
   * справочник один раз на звонок. У робота из промта пропадали «82 мкр», «Корвон»,
   * «Зарафшон», «Мехргон», «Аэропорт» — половина списка, и район он угадывал из
   * головы. Карта для голоса — в ответе поиска (search_properties: landmark →
   * lib/searchPlace.ts), а этот список — его подсказка, где что. Размер стережёт тест
   * (tests/bots-search-30-queries.test.ts).
   */
  const kept = folkPlacesForPrompt(rows, !!options.voice);
  const lines: string[] = [];
  for (const district of DISTRICT_ORDER) {
    const names = kept.filter((p) => !p.center && p.district === district).map((p) => p.name);
    if (names.length === 0) continue;
    lines.push(`\nРАЙОН ${district.toUpperCase()} — записывай в ${district}, если клиент назвал:\n${names.join(", ")}.`);
  }
  const centerSomoni = kept.filter((p) => p.center && p.district === "Исмоили Сомони").map((p) => p.name);
  const centerShoh = kept.filter((p) => p.center && p.district === "Шохмансур").map((p) => p.name);

  return (
    "\n\n<карта_народных_названий_душанбе>\n" +
    "АЛГОРИТМ РАБОТЫ С РАЙОНАМИ:\n" +
    "Клиенты в Душанбе используют народные названия и ориентиры. Ты должен понимать их и АВТОМАТИЧЕСКИ записывать " +
    "в поле districtName один из 4 официальных районов: Исмоили Сомони, Сино, Фирдавси, Шохмансур.\n" +
    (options.voice
      ? "Ниже — народные названия и их районы. Для поиска объектов ориентир передавай словами человека в landmark " +
        "функции search_properties: район по карте определит поиск, и его ответ (asked_place) вернее этого списка.\n"
      : "Названия ниже — те, которых нет на карте города. Всё остальное (улицы, микрорайоны, рынки, жилые массивы) " +
        "тебе отдельно приносит блок «МЕСТА, НАЗВАННЫЕ КЛИЕНТОМ, ПО КАРТЕ ГОРОДА» — он точнее этого списка, и если " +
        "он что-то называет, верным считается он.\n") +
    lines.join("\n") +
    "\n\nОСОБОЕ ПРАВИЛО ДЛЯ \"ЦЕНТРА\" (Марказ):\n" +
    "Центр Душанбе делится на два района (Шохмансур и Исмоили Сомони).\n" +
    (options.voice ? VOICE_CENTER_RULE : "1. Если клиент говорит \"Центр\" / \"Марказ\" без уточнений: districtName оставь null, в notes напиши " +
    "\"Ищет в центре\", а твой ответ ДОЛЖЕН содержать уточнение: \"Марказ калон аст. Аниқтараш дар кадом тараф? " +
    "Тарафи ЦУМ ва Дом Печати ё тарафи Садбарг ва Оперка?\" ЭТОТ ВОПРОС ЗАДАЁТСЯ РОВНО ОДИН РАЗ (владелец " +
    "17.09.2026: повторное уточнение звучит грубо) — если ответа нет следующим сообщением, не повторяй его и не " +
    "переформулируй: бери номер и передавай агенту, сторону центра он уточнит сам.\n") +
    (centerSomoni.length > 0
      ? `2. Ориентиры Центра со стороны ИСМОИЛИ СОМОНИ (${centerSomoni.join(", ")}) → districtName "Исмоили Сомони".\n`
      : "") +
    (centerShoh.length > 0
      ? `3. Ориентиры Центра со стороны ШОХМАНСУР (${centerShoh.join(", ")}) → districtName "Шохмансур".\n`
      : "") +
    "</карта_народных_названий_душанбе>"
  );
}
