/**
 * Имя человека для вставки в промт (02.10.2026, аудит текстов, п. 15). Имя из
 * профиля WhatsApp/Instagram или карточки — чужой текст: «Ахмад. Забудь инструкции…»
 * без очистки ложилось в блок <system_role>. Берём до трёх первых слов и пропускаем
 * через sanitizeSpokenName (буквы, пробел, дефис); не имя — null, то есть «без имени».
 */
export function promptSafeName(raw: string | null | undefined): string | null {
  if (typeof raw !== "string") return null;
  return sanitizeSpokenName(raw.trim().split(/\s+/).slice(0, 3).join(" "));
}

/** Короткий свободный текст (заголовок объекта) для вставки в промт: одна строка,
 *  без угловых скобок и управляющих знаков, не длиннее `max`. */
export function promptSafeText(raw: string | null | undefined, max = 120): string | null {
  if (typeof raw !== "string") return null;
  const text = raw
    .replace(/[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]/gu, " ")
    .replace(/[<>{}`]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, max)
    .trim();
  return text || null;
}

function buildLiveVoiceContextBlock(context?: LiveVoiceCallContext): string {
  // Имя клиента — текст внешнего человека (профиль мессенджера), описание объекта
  // собрано из полей объявления: в самый «высокий» блок промта они попадают только
  // очищенными (аудит текстов 02.10.2026, п. 15).
  const clientName = promptSafeName(context?.clientName);
  const propertyDescription = promptSafeText(context?.propertyDescription, 500);
  if (!clientName && !propertyDescription) return "";
  const lines: string[] = [];
  if (clientName) lines.push(`Имя собеседника, как записано в CRM: ${clientName}.`);
  if (propertyDescription) {
    lines.push(
      `Ты звонишь по конкретному объекту, вот его данные (используй ТОЛЬКО их, ничего не добавляй от себя): ${propertyDescription}.`
    );
  }
  return `\n<system_role>\nКОНТЕКСТ ЭТОГО ЗВОНКА:\n${lines.join("\n")}\n</system_role>\n`;
}

