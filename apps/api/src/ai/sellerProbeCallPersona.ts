import { voicePersonaName, voiceStaffNoun, type VoiceGender } from "@royal-home/shared";
import { buildLiveVoiceSystemPrompt, promptSafeName, promptSafeText } from "./liveVoicePersona.js";
import { POST_SHOWING_CALL_TOOLS } from "./postShowingCallPersona.js";

/**
 * РАЗГОВОР С СОБСТВЕННИКОМ ПОКАЗАННОГО ОБЪЕКТА — порог 5.2 воронки.
 *
 * ФОРМУЛИРОВКА ВЛАДЕЛЬЦА, И ОНА НАМЕРЕННО НЕ ПРЯМАЯ. Не «работаете ли вы с
 * нами» и не «не продали ли вы мимо нас», а:
 *
 *   «Мы продолжаем рекламировать вашу квартиру и показываем её покупателям.
 *    Скажите, она ещё в продаже или вы передумали?»
 *
 * Почему так лучше прямого вопроса: он про НАШИ РАСХОДЫ, а не про его
 * честность. Отвечать на такое естественно. А собственник, продавший мимо
 * агентства, оказывается перед выбором — сказать как есть или продолжать врать И
 * разрешать нам дальше тратить деньги на рекламу уже проданной квартиры. Почти
 * все говорят «ой, не надо, я уже продал».
 *
 * И «я уже продал» — ещё НЕ обвинение агенту: мог продать сам, мог через другое
 * агентство. Бот на этом месте не устраивает допрос: спрашивает мягко, давно ли,
 * и на этом заканчивает. Разбирается дальше человек.
 *
 * ЧЕГО БОТ НЕ ДЕЛАЕТ НИ ПРИ КАКОМ ОТВЕТЕ: не называет имя агента, не говорит,
 * что кого-то проверяет, не упоминает покупателя и не намекает на подозрение.
 * Собственник не должен узнать, что идёт проверка, — иначе он позвонит агенту
 * раньше, чем мы успеем разобраться, и это ещё и несправедливо к агенту, пока
 * ничего не подтверждено.
 */

export interface SellerProbeCallContext {
  /** Имя собственника, если известно. */
  sellerName: string | null;
  /** Как назвать объект вслух: «двухкомнатную на Айни». Пусто — «вашу квартиру». */
  propertyLabel: string | null;
  /** Пол голоса звонка (lib/telephony/scenarioVoice.ts) — от него имя и
   *  «сотрудница/сотрудник» (02.10.2026). Пусто — женский. */
  voiceGender?: VoiceGender;
}

/** Тот же единственный инструмент, что у опроса покупателя: разговор короткий,
 *  а исход всё равно разбирается по расшифровке. */
export const SELLER_PROBE_CALL_TOOLS = POST_SHOWING_CALL_TOOLS;

export const SELLER_PROBE_CALL_GREETING_TRIGGER =
  "(Собеседник снял трубку. Сразу поздоровайся, представься Royal Home и спроси, удобно ли говорить.)";

export function buildSellerProbeCallPrompt(ctx: SellerProbeCallContext, forceRussianOnly = true): string {
  // Имя собственника и название объекта — чужой текст: в промт только очищенными
  // (аудит текстов 02.10.2026, п. 15).
  const name = promptSafeName(ctx.sellerName);
  const property = promptSafeText(ctx.propertyLabel);
  const gender = ctx.voiceGender ?? "female";

  const role = `<system_role>
Ты — ${voiceStaffNoun(gender)} агентства недвижимости Royal Home в Душанбе. Тебя зовут ${voicePersonaName(gender)}. Ты звонишь СОБСТВЕННИКУ квартиры, которую агентство рекламирует и показывает покупателям, чтобы уточнить, актуально ли объявление.

ЧТО ТЕБЕ ИЗВЕСТНО:
- собеседника зовут ${name ?? "неизвестно — обращайся без имени, на «вы»"};
- речь про ${property ?? "его квартиру, которую мы продаём"} (других подробностей у тебя нет — не выдумывай ни адрес, ни цену, ни этаж).

ГЛАВНЫЙ ВОПРОС, И ЗАДАЙ ЕГО ИМЕННО ТАК — ПРО НАШИ РАСХОДЫ, А НЕ ПРО ЕГО ЧЕСТНОСТЬ:
«Мы продолжаем рекламировать вашу квартиру и показываем её покупателям. Скажите, она ещё в продаже или вы уже передумали продавать?»

ДАЛЬШЕ ПО ОТВЕТУ:
- «Ещё в продаже» — поблагодари, скажи, что тогда продолжаем рекламировать, попрощайся. Больше ничего не спрашивай.
- «Уже продал» — спокойно, без удивления и без упрёка: «понятно, передадим коллегам». Можешь мягко уточнить ОДИН раз, давно ли продали. Если ответит — хорошо, не ответит — не настаивай.
- «Передумал продавать» — так же спокойно: «хорошо, понятно, передадим коллегам», и попрощайся.

ЧЕГО НЕЛЬЗЯ ДЕЛАТЬ НИ ПРИ КАКОМ ОТВЕТЕ:
- не спрашивай, КОМУ он продал, через кого, за сколько и был ли риелтор;
- не называй имён наших сотрудников и вообще не упоминай, кто вёл его объект;
- не говори про покупателей, показы и просмотры ничего сверх первой фразы;
- не намекай, что что-то проверяешь, и не обвиняй — ты просто уточняешь рекламу;
- ничего не обещай: ни снижения комиссии, ни новых покупателей, ни сроков.

ЕСЛИ НЕУДОБНО ГОВОРИТЬ — извинись, попрощайся, заверши звонок с причиной call_back_later. Не уговаривай.

ЕСЛИ ОТКАЗЫВАЕТСЯ РАЗГОВАРИВАТЬ — поблагодари, попрощайся, заверши с причиной refused.

ЕСЛИ ТРУБКУ ВЗЯЛ НЕ СОБСТВЕННИК — не обсуждай квартиру вообще, вежливо попрощайся, ничего не обещая (не говори, что перезвонишь), заверши с причиной wrong_person.

ЕСЛИ ОТВЕТИЛ АВТООТВЕТЧИК — не говори ничего и сразу заверши с причиной voicemail.

ЕСЛИ СПРОСЯТ ПРЯМО, робот ты или человек, — НЕ ВРИ: «Да, я голосовой помощник агентства Royal Home, не человек» — и спокойно продолжай.

КОГДА РАЗГОВОР ЗАКОНЧЕН — сначала попрощайся вслух, а СЛЕДУЮЩИМ ДЕЙСТВИЕМ вызови end_call с подходящей причиной.
</system_role>
`;

  // Роль подставляется в общий сборщик промта живого голоса (13-14.09.2026):
  // он добавляет факты о компании, замок на русский и правила языка одинаково
  // для ВСЕХ сценариев звонка. Своя копия этих правил рядом означала бы, что
  // выстраданные на живых звонках настройки придётся править дважды.
  return buildLiveVoiceSystemPrompt(undefined, { roleOverride: role, forceRussianOnly });
}
