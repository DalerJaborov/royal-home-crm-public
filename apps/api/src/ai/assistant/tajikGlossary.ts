export function tajikGlossaryFor(question: string): string {
  const normalized = question.toLocaleLowerCase();
  const selected = TAJIK_GLOSSARY.filter((row) => [row.ru, row.tg].some((phrase) =>
    phrase.toLocaleLowerCase().split(/[^\p{L}]+/u).filter((word) => word.length >= 4).some((word) => normalized.includes(word)))).slice(0, 8);
  const examples = selected.length ? selected : TAJIK_GLOSSARY.filter((row) => ["Нашла клиента", "Уточните имя или номер карточки", "Подтвердить", "Изменение выполнено"].includes(row.ru));
  return `\nПРОСТОЙ ТАДЖИКСКИЙ (только если отвечаешь по-таджикски): короткие фразы, обращение на шумо, без книжного официоза.\n` +
    `Не меняй имена, номера, суммы, даты и ссылки. Пользователь системы не равен клиенту; квартира не равна любому дому; комиссия бывает фиксированной, не только процентом.\n` +
    `Это ориентиры смысла, не автоматические замены и не готовые утверждения о выполнении:\n` +
    examples.map((row) => `${row.ru} → ${row.tg}`).join("\n");
}
