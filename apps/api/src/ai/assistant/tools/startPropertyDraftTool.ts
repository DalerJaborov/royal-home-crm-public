import { z } from "zod";
import { openPropertyDraft } from "../../../telegram/propertyDraftOpener.js";
import type { AssistantReadToolPlugin } from "./types.js";

/**
 * start_property_draft — «ДОБАВЬ ОБЪЕКТ» ЛЮБЫМИ СЛОВАМИ (21.11.2026, владелец: «Бот мушовир Шабнам
 * почему не может добавить объект… Исправь, чтобы любые похожие все можно было использовать»).
 *
 * Было: мастер объекта в Telegram (telegram/assistantPropertyDraft.ts) открывала только регулярка по
 * началу сообщения. Голосовое, «Шабнам, добавь…», «можешь добавить объект?», сообщение в группе —
 * всё уходило в общий ответ модели, у которой не было инструмента, и помощница честно отвечала
 * «не могу добавить объект», хотя права у сотрудника есть.
 * Теперь просьбу узнаёт модель, а мастер открывается тем же входом, что у «/new_property»: права,
 * рубильник помощницы и черновик — одни и те же. Объект этим НЕ создаётся: открывается черновик с
 * карточкой проверки, создаёт его сотрудник кнопкой — поэтому уровень A.
 * Мастер живёт в личке Telegram, поэтому из группы и из чата CRM карточка приходит туда.
 */
const argsSchema = z.object({
  details: z.preprocess(value => (value === null ? undefined : value), z.string().max(3000).optional()),
});

export const startPropertyDraftTool: AssistantReadToolPlugin = {
  name: "start_property_draft",
  level: "A",
  description:
    "Открыть МАСТЕР ДОБАВЛЕНИЯ НОВОГО ОБЪЕКТА (квартира, дом, участок, коммерция) в личке Telegram сотрудника. " +
    "Звать, когда сотрудник любыми словами просит добавить, внести, завести, записать, оформить новый объект или объявление, " +
    "или говорит, что у него новый объект на продажу и его надо внести: «добавь объект», «можешь внести квартиру?», " +
    "«есть новая хата, занеси», «оформим двушку», «объект илова кунед», «хонаи нав дорам, илова кун». " +
    "Если в той же просьбе уже названы данные объекта (район, комнаты, площадь, этаж, цена, продавец, ремонт), передай их " +
    "дословно в details — мастер разберёт их сам; ничего не додумывай. " +
    "НЕ звать: для поиска объектов, вопросов о существующем объекте по номеру ОБ-…, смены цены или статуса, подборки клиенту. " +
    "Сам объект этим не создаётся: в личке придёт карточка черновика, дальше сотрудник отвечает там. " +
    "Без вызова этого инструмента НЕ говори «не могу добавить объект». После вызова скажи одной короткой фразой, что мастер открыт " +
    "(в группе или в CRM — что карточка пришла в личку Telegram).",
  parameters: {
    type: "object",
    properties: {
      details: { type: "string", description: "Данные объекта, которые сотрудник уже назвал, его словами. Пусто, если не называл." },
    },
  },
  statusPhrase: "Открываю мастер объекта…",
  async run(raw, ctx) {
    const parsed = argsSchema.safeParse(raw);
    if (!parsed.success) return { error: "details — текст до 3000 знаков" };
    const result = await openPropertyDraft(ctx.actor.id, parsed.data.details ?? "");
    if (result.opened) {
      return {
        opened: true,
        where: ctx.actor.surface === "telegram-private" ? "этот чат" : "личка сотрудника с помощницей в Telegram",
        message: "Мастер объекта открыт: карточка черновика отправлена, дальше сотрудник отвечает в ней",
      };
    }
    if (result.reason === "denied") return { error: result.text ?? "Нет прав на создание объекта" };
    if (result.reason === "no_telegram") {
      return { error: "Telegram сотрудника не привязан к CRM: объект можно добавить в CRM (Объекты → Добавить объект) или сначала привязать Telegram в профиле" };
    }
    if (result.reason === "unavailable") return { error: "Мастер объекта сейчас недоступен: объект можно добавить в CRM (Объекты → Добавить объект)" };
    return { error: "Учётная запись сотрудника отключена" };
  },
};
