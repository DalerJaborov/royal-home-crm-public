/**
 * Загрузка .env — ЕДИНСТВЕННАЯ точка входа для dotenv в apps/api.
 *
 * Почему отдельный модуль, а не `import "dotenv/config"` (как было до
 * dotenv 17): в 17.0.0 опция `quiet` сменила значение по умолчанию с `true`
 * на `false`, и теперь при каждом старте dotenv печатает в поток строку вида
 * «[dotenv@17.x] injecting env (N) from .env». В журнале прода это шум на
 * каждый рестарт api и worker, а в выводе vitest — лишняя строка перед
 * каждым файлом тестов. Через `import "dotenv/config"` опции не передать,
 * поэтому вызов вынесен сюда.
 *
 * ВАЖНО: этот файл обязан импортироваться ПЕРВЫМ в точке входа. Импорты в
 * ES-модулях вычисляются раньше тела модуля, поэтому написать
 * `import { config } from "dotenv"; config()` прямо в index.ts нельзя —
 * config() выполнился бы уже ПОСЛЕ вычисления всех остальных импортов, то
 * есть после того, как модули прочитали process.env на верхнем уровне.
 * Отдельный модуль с побочным эффектом сохраняет прежний порядок.
 */
import { config } from "dotenv";

config({ quiet: true });
