/**
 * Паузы, из-за которых бот читается как человек, а не как рассылка.
 *
 * Живой агент не отвечает мгновенно и не вываливает три фотографии одним залпом:
 * он читает сообщение, набирает текст, прикладывает снимок, потом второй. Мгновенная
 * очередь сообщений выдаёт робота сильнее любой формулировки — и в мессенджерах это
 * ещё и признак рассылки, за которую Meta придерживает отправку.
 *
 * Собрано в один модуль нарочно: одни и те же значения нужны и вебхуку (там пауза
 * перед текстовым ответом), и показу объекта (пауза между фотографиями). Пока
 * `sleep` и `typingDelayMs` жили копиями внутри routes/webhooks.ts, у показа
 * фотографий не было ни одной паузы вовсе.
 *
 * Все значения со случайным разбросом: ровно одинаковые интервалы — та же
 * машинная подпись, что и полное их отсутствие.
 */

export const sleep = (ms: number): Promise<void> => new Promise<void>((resolve) => setTimeout(resolve, ms));

/**
 * Сколько «набирать» сообщение: примерно по длине текста, но не мгновенно и не
 * дольше двенадцати секунд — за ними клиент решает, что ему не ответят.
 */
export function typingDelayMs(text: string, minMs = 3000): number {
  const base = Math.min(12_000, Math.max(minMs, text.length * 90));
  return Math.round(base * (0.75 + Math.random() * 0.5));
}

/**
 * Пауза «набора» перед пузырём ответа в Telegram (03.10.2026, «один мозг»): та же
 * typingDelayMs, что у каналов Meta. Под тестами (process.env.VITEST) — ноль, тот
 * же приём, что lib/dailyStories.ts: сотни тестов Telegram гоняют живой ход бота,
 * и 3–12 секунд на пузырь сделали бы прогон часовым, ничего не проверив.
 */
export function chatTypingPauseMs(text: string, minMs = 3000): number {
  return process.env.VITEST ? 0 : typingDelayMs(text, minMs);
}

/**
 * Пауза между двумя фотографиями объекта.
 *
 * Верхняя граница выбрана из общего срока показа: снимков не больше трёх
 * (MAX_PHOTOS_PER_OFFER), значит пауз не больше трёх вместе со ссылкой на карточку,
 * и весь показ укладывается примерно в восемь секунд. Это ровно та задержка, за
 * которую человек успевает выбрать и приложить следующий файл, — но текстовый ответ
 * следом за показом она не отодвигает на минуты.
 */
export function photoGapMs(): number {
  return Math.round(1200 + Math.random() * 1400);
}
