import { prisma } from "../db.js";

/**
 * ЗАБРАТЬ ПРАВО ПЕРЕСПРОСИТЬ НЕЧИТАЕМЫЙ НОМЕР — РОВНО СТОЛЬКО РАЗ, СКОЛЬКО МОЖНО.
 *
 * Клиент присылает номер, который не разобрать («985», «номер тот же»), и бот
 * переспрашивает — но не больше разрешённого числа раз.
 *
 * Раньше это считалось по `leadDraft`, прочитанному в начале хода, а счётчик
 * писался ПЕРЕЗАПИСЬЮ ВСЕГО черновика (`{ ...draft, phoneRetryCount: n + 1 }`).
 * Две поломки разом, обе бьют по жалобе владельца «он опять спрашивает по 35 раз»
 * (docs/bot-razbor-20-09.md, класс 7 п. 4):
 *
 *  • ПОТЕРЯ СОБРАННОГО. Человек часто пишет очередью, и соседний ход того же
 *    разговора успевает дописать в черновик бюджет, район или тип жилья.
 *    Перезапись возвращала черновик к тому, каким он был в начале ЭТОГО хода, и
 *    бот спрашивал заново то, на что уже получил ответ.
 *  • СЧЁТЧИК СТОЯЛ НА МЕСТЕ. Оба хода читали одну цифру и оба писали её же плюс
 *    один, так что предел не наступал и переспросов уходило больше разрешённого.
 *
 * Лечится тем же приёмом, что и захват заявки (`claimed` в conversation.ts):
 * атомарный UPDATE с условием по СВЕЖЕМУ значению в базе и точечной правкой
 * ОДНОГО ключа через `jsonb_set`. Возвращает false, когда предел уже исчерпан —
 * своим же прошлым переспросом или соседним ходом; тогда переспроса нет и ход
 * идёт обычным путём, к модели.
 *
 * Отдельным модулем, а не строкой внутри хода, — чтобы гонку можно было проверить
 * тестом напрямую: `tests/phone-retry-claim.test.ts` зовёт её параллельно.
 *
 * ПРОВЕРКА ТИПА ВМЕСТО `COALESCE`. Пустой черновик Prisma сохраняет как
 * jsonb-значение `null`, а не как SQL NULL: `COALESCE` его не подменяет, и
 * `jsonb_set` падает с «cannot set path in scalar». Поэтому здесь `jsonb_typeof`
 * — он закрывает оба случая сразу. Поймано тестом «черновика нет вовсе».
 */
export async function claimUnreadablePhoneAsk(conversationId: string, max: number): Promise<boolean> {
  const changed = await prisma.$executeRaw`
    UPDATE "BotConversation"
    SET "leadDraft" = jsonb_set(
          CASE WHEN jsonb_typeof("leadDraft") = 'object' THEN "leadDraft" ELSE '{}'::jsonb END,
          '{phoneRetryCount}',
          to_jsonb(COALESCE(("leadDraft"->>'phoneRetryCount')::int, 0) + 1)
        )
    WHERE "id" = ${conversationId}
      AND COALESCE(("leadDraft"->>'phoneRetryCount')::int, 0) < ${max}`;
  return changed > 0;
}
