/**
 * Текст подтверждения заявки. null — модель не ответила; канал берёт
 * FALLBACK_ACCEPTED на языке клиента.
 *
 * НИКАКОГО «АГЕНТ СВЯЖЕТСЯ» ДЛЯ ЛЮБОГО kind=OTHER (владелец 17.09.2026): у
 * «Прочих обращений» агента нет вообще, значит и обещание не годится. «Другой
 * город» получает свою фразу с упоминанием Душанбе, остальные причины —
 * нейтральный текст. Для обычной заявки — короткая фраза модели на языке
 * клиента с именем агента и реальным сроком звонка (решение Dan 02.10.2026,
 * lib/handoffPromise.ts): ночью — «завтра после 9:30», а не ложное «скоро».
 */
export async function leadAcceptedReply(input: {
  kind: string;
  /** Причина «другой город» (ai/leadKind.ts::isOtherCityReason). */
  otherCity: boolean;
  /** Карточка заведена сейчас, а не найдена уже существующая. */
  created: boolean;
  clientId: string;
  /** Переписка ДО этого хода. */
  history: ChatMessage[];
  /** Что клиент сказал этим ходом (с номером). */
  saidText: string;
  /** Слова клиента за весь разговор — по ним язык готовой фразы. */
  clientWords: string;
  name?: string;
  draft: LeadDraft;
  conversationId: string;
  /** Имя клиенту неизвестно — спросить его последней фразой. */
  askName: boolean;
  /** Спросить про запасной номер (только там, где канал умеет его принять). */
  askExtraPhones: boolean;
}): Promise<string | null> {
  const { kind, otherCity, created, clientId, history, saidText, clientWords, name, draft, conversationId } = input;
  if (kind === "OTHER") {
    return otherCity
      ? otherCityAcceptedReply(detectClientLanguage(clientWords || saidText))
      : otherInquiryAcceptedReply(detectClientLanguage(clientWords || saidText));
  }
  return shortAgentReply(
    [...history, { role: "user", content: saidText }],
    (created
      ? "Клиент только что оставил номер телефона, заявка оформлена. Тепло поблагодари. " +
        (await handoffInstruction(clientId)) +
        " Больше ничего не проси."
      : "У клиента уже была заявка. Тепло скажи об этом. " + (await handoffInstruction(clientId))) +
      (input.askName
        ? " Клиент не назвал своё имя. Одной короткой фразой, тем же тёплым тоном, уточни, как его зовут " +
          "(например: «Айнан кӣ мешавед?» / «Кстати, как вас зовут?») — без давления, вопрос последний."
        : "") +
      (input.askExtraPhones
        ? " Также одной короткой фразой спроси, есть ли у клиента ещё номера телефона, по которым с ним " +
          "можно связаться (например: «Ва боз рақами дигаре доред, ки бо шумо тамос гирем?» / «И ещё — " +
          "есть другой номер, на который можно позвонить?») — не давить, просто уточнить."
        : ""),
    { name, draft },
    conversationId
  );
}

