/**
 * Честный ответ для «другой город»: клиент сам оставил номер или прислал данные
 * объекта, заявка заведена (kind=OTHER, без агента), но звонка не будет — и
 * обещать его нельзя (владелец 17.09.2026). Одна формулировка на все поверхности:
 * та же строка, что в ai/leadQualifier.ts (SCENARIO_SELL) и messengers/comments.ts
 * (COMMENT_SCENARIO_RULES).
 */
export function otherCityAcceptedReply(language: ReturnType<typeof detectClientLanguage>): string {
  return language === "ru"
    ? "Записали, спасибо. Пока работаем только по Душанбе; если начнём работать в вашем городе — напишем."
    : "Сабт кардем, раҳмат. Ҳоло танҳо дар Душанбе кор мекунем; агар дар шаҳри шумо сар кунем, менависем.";
}

/**
 * ОБЩЕЕ ПРАВИЛО ДЛЯ ЛЮБОЙ ПРИЧИНЫ "ПРОЧЕГО ОБРАЩЕНИЯ" (владелец 17.09.2026,
 * доразбор того же дня: нашли, что то же самое обещание звонка уходило и
 * электрику, и продавцу участка, и любому другому kind=OTHER — не только
 * «другому городу»). Раз агент этой заявке не назначается вообще, обещать
 * звонок нельзя ни для какой причины — нейтральный честный ответ вместо
 * "агент скоро свяжется". Причина по-прежнему пишется в заметку заявки
 * (requirementsNotes/label, decision.label выше по стеку) — меняется только
 * то, что говорится КЛИЕНТУ, а не то, что видит руководство в карточке.
 *
 * intent=job ("работа") сюда не попадает вообще: ветка кандидата во всех
 * каналах возвращает результат раньше, до этого места.
 */
export function otherInquiryAcceptedReply(language: ReturnType<typeof detectClientLanguage>): string {
  return language === "ru"
    ? "Записали, спасибо. Если сможем помочь — напишем."
    : "Сабт кардем, раҳмат. Агар кӯмак карда тавонем, менависем.";
}

