import { prisma } from "../db.js";
import { DEFAULT_PHOTOS_PER_OFFER } from "../ai/photoOffer.js";

/**
 * ЧТО БОТ УМЕЕТ — ползунки в Настройках, а не удалённый код.
 *
 * Решение владельца 01.08.2026 после разговора с заказчиком: пока компанию мало
 * знают, показ должен назначать живой агент по телефону — голос закрывает встречу
 * лучше переписки. Но логику показов просить удалить нельзя: назначение, перенос,
 * отмена, подтверждение обеими сторонами, календарь и напоминания — это связка,
 * которую потом пришлось бы собирать заново неделю ради флага, который ставится
 * за час.
 *
 * ГЛАВНОЕ ПРАВИЛО ЭТОГО МОДУЛЯ: выключенная возможность обязана исчезнуть И ИЗ
 * КОДА, И ИЗ ПРОМТА. Ровно на этом мы обожглись с фотографиями: отправки не было
 * ни в Telegram, а промт всё равно велел писать «ана расмҳояш» — и
 * бот честно обещал клиенту снимки, которых тот не получал. Флаг, который гасит
 * действие, но оставляет обещание, хуже отсутствия флага.
 *
 * Поэтому каждая возможность здесь — это пара: признак для кода и кусок промта,
 * который либо есть, либо заменён на объяснение, что делать вместо.
 */

export interface BotCapabilities {
  /** Отправлять фотографии объекта прямо в переписку. */
  photos: boolean;
  /** Сколько снимков уходит за один показ (Настройки → Бот). */
  photosPerOffer: number;
  /** Назначать, переносить и отменять показы самому, не спрашивая агента. */
  showings: boolean;
  /** Просить у клиента и собственника подтверждение назначенной встречи. */
  showingConfirmations: boolean;
  /** Напоминать о себе клиенту, который перестал отвечать. */
  followUps: boolean;
  /** Отвечать на комментарии под публикациями Instagram. */
  comments: boolean;
  /** «Соедините с оператором»: записывать запрос звонка и звать агентов. */
  callback: boolean;
  /** «Уточню у собственника и вернусь»: очередь вопросов живым людям. Выключено —
   *  бот берёт номер, и агент отвечает по звонку (решение владельца 16.08.2026). */
  askOwner: boolean;
  /** Разговаривать с кандидатами на вакансии и собирать анкету. */
  vacancies: boolean;
  /** Отправлять ссылки на объекты в переписку. */
  links: boolean;
  /** Режим запуска: отвечать ровно на спрошенное, ничего не предлагать сверх. */
  cautious: boolean;
  /** Экономия промта по намерению: подробности сценария — только своему намерению
   *  (см. buildStableSystem в ai/leadQualifier.ts). По умолчанию выключено. */
  promptEconomy: boolean;
  /** Озвучивать ответ бота, если клиент сам прислал голосовое в этом ходе
   *  (см. messengers/conversation.ts::finishQualifyTurn). Владелец 13.09.2026:
   *  «создай, но выключи — сам протестирую». */
  voiceReplies: boolean;
}

/** Всё включено — то, как система работала до появления ползунков.
 *  cautious здесь false: это не возможность, а намордник, и по умолчанию его нет.
 *  showings/showingConfirmations — ИСКЛЮЧЕНИЕ из «всё включено» (20.08.2026): раньше
 *  здесь стояло true, но это давно разошлось с реальным решением владельца
 *  (01.08.2026, показы назначает агент по звонку) и было структурным риском — при
 *  отказе базы бот молча получал два взаимоисключающих указания сразу (SALES_ROLE
 *  говорит «не назначаешь встречи», showingPromptBlock() — «назначаешь сам»,
 *  см. ai/leadQualifier.ts). Здесь единственное поле, где «отказ базы = как было
 *  задумано изначально» опаснее, чем «отказ базы = текущее решение владельца». */
const ALL_ENABLED: BotCapabilities = {
  photos: true,
  photosPerOffer: DEFAULT_PHOTOS_PER_OFFER,
  showings: false,
  showingConfirmations: false,
  followUps: true,
  comments: true,
  // ОТКАЗ БАЗЫ = «ОПЕРАТОРА НЕТ» (23.08.2026), в отличие от остальных рубильников.
  // Включённый callback означает не «бот разговорчивее», а «дежурного наберёт АТС и
  // клиенту обещан звонок сию минуту». Обещать это вслепую, когда настройки не
  // прочитались, нельзя: набирать может быть некому. Просьба о звонке при этом не
  // теряется — она уедет обычной заявкой к агенту (см. ai/callbackRequest.ts).
  callback: false,
  // Отказ базы возвращает поведение «как раньше» — а раньше вопросы собственнику
  // работали. Настоящее умолчание (выключено) живёт в колонке Settings.
  askOwner: true,
  vacancies: true,
  links: true,
  cautious: false,
  // Отказ базы обязан вернуть ПРЕЖНИЙ промт целиком: экономия — намеренный выбор
  // владельца, а не поведение при сбое. Та же логика, что у cautious.
  promptEconomy: false,
  // Новая возможность (13.09.2026), ещё не проверенная живым звонком/чатом —
  // тот же принцип, что у showings/showingConfirmations выше: «всё включено»
  // не значит «включить то, чего раньше не было и что владелец явно попросил
  // держать выключенным».
  voiceReplies: false,
};

/**
 * Состояние ползунков.
 *
 * Отказ базы трактуется как «всё включено» — так же, как у рубильников каналов:
 * молча онемевший бот страшнее лишнего действия, и разбираться в тишине сложнее,
 * чем в лишнем сообщении.
 */
export async function loadBotCapabilities(): Promise<BotCapabilities> {
  try {
    const s = await prisma.settings.findUnique({
      where: { id: "singleton" },
      select: {
        botCanSendPhotos: true,
        botPhotosPerOffer: true,
        botCanBookShowings: true,
        botCanConfirmShowings: true,
        botCanFollowUp: true,
        botCanAnswerComments: true,
        botCanRequestCallback: true,
        botCanAskOwner: true,
        botCanHandleVacancies: true,
        botCanSendLinks: true,
        botCautiousMode: true,
        botPromptIntentEconomy: true,
        botCanSendVoiceReplies: true,
      },
    });
    if (!s) return ALL_ENABLED;
    return {
      photos: s.botCanSendPhotos,
      photosPerOffer: s.botPhotosPerOffer,
      showings: s.botCanBookShowings,
      // Подтверждение встречи без самой встречи бессмысленно: если показы
      // назначает агент, спрашивать о них бот не должен тем более.
      showingConfirmations: s.botCanBookShowings && s.botCanConfirmShowings,
      followUps: s.botCanFollowUp,
      comments: s.botCanAnswerComments,
      callback: s.botCanRequestCallback,
      askOwner: s.botCanAskOwner,
      vacancies: s.botCanHandleVacancies,
      links: s.botCanSendLinks,
      // Отказ базы даёт ALL_ENABLED, где cautious=false: осторожность — намеренный
      // выбор владельца, а не поведение при сбое.
      cautious: s.botCautiousMode,
      promptEconomy: s.botPromptIntentEconomy,
      voiceReplies: s.botCanSendVoiceReplies,
    };
  } catch {
    return ALL_ENABLED;
  }
}

/**
 * Срез ползунков для «мозга» бота (BotAbilities в ai/leadQualifier.ts).
 *
 * Отдельной функцией, а не разбросанными литералами: когда появлялся новый ползунок,
 * литерал `{ showings: ... }` в трёх местах conversation.ts и двух местах telegram
 * молча оставлял новую возможность включённой навсегда — тип совпадал, ошибки не было.
 * Форма совпадает с BotAbilities структурно; импортировать тип отсюда нельзя —
 * получился бы цикл (leadQualifier уже импортирует этот модуль).
 */
export function botAbilitiesOf(c: BotCapabilities): {
  showings: boolean;
  callback: boolean;
  askOwner: boolean;
  vacancies: boolean;
  links: boolean;
  cautious: boolean;
  promptEconomy: boolean;
} {
  return {
    showings: c.showings,
    callback: c.callback,
    askOwner: c.askOwner,
    vacancies: c.vacancies,
    links: c.links,
    cautious: c.cautious,
    promptEconomy: c.promptEconomy,
  };
}

