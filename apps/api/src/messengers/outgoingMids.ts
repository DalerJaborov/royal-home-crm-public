/**
 * Память о ТОЛЬКО ЧТО отправленных нами сообщениях — защита от гонки с эхом Meta.
 *
 * ЗАЧЕМ. На каждое наше исходящее Meta присылает вебхук-эхо (is_echo). Отличать
 * своё от ручного ответа сотрудника из приложения мы умели только по `mid`,
 * записанному в переписке (см. handleOutgoingEcho в routes/webhooks.ts). Но
 * переписка пишется НЕ в момент отправки, а после того, как отправлена вся пачка:
 * воронка сперва шлёт текст, потом PDF, и только затем одним махом кладёт обе
 * реплики с их mid (lib/leadMagnet.ts, recordInConversation).
 *
 * Эхо первого сообщения успевает прийти в эту щель. 18.08.2026, диалог
 * @farruhruz_: текст отправлен в 09:11:17, эхо пришло в ту же секунду, а mid'ы
 * легли в переписку только в 09:11:20 — три секунды, которых хватило, чтобы CRM
 * приняла собственное сообщение воронки за ответ сотрудника: дописала вторую
 * копию в переписку (владелец видел «отправляется два сообщения») и поставила
 * бота на десятиминутную паузу («бот в паузе»). Клиенту при этом уходила ОДНА
 * копия — дублировалось только отображение, но пауза была настоящей и глушила
 * бота на живом лиде.
 *
 * ПОЧЕМУ ЗДЕСЬ, А НЕ ПОЧИНКОЙ ПОРЯДКА ЗАПИСИ В ВОРОНКЕ. Щель между «отправили» и
 * «записали mid» есть у каждого, кто шлёт пачкой: воронка, гид покупателя,
 * показ объекта, ответ бота двумя пузырями. Латать их по одному — значит
 * возвращаться сюда после каждой новой ветки отправки; отметка в момент отправки
 * закрывает их все разом и не зависит от того, когда и как вызывающий пишет историю.
 *
 * ПАМЯТЬ + БАЗА (переделано 27.08.2026 по аудиту №4). Раньше отметка жила только
 * в памяти процесса — «контейнер API один», и это было верно ровно до появления
 * второго процесса. Теперь напоминания молчащим и задания очереди шлёт worker, а
 * эхо-вебхук обрабатывает api: отметка, поставленная в памяти worker'а, для api
 * не существует, и собственная реплика бота ДЕТЕРМИНИРОВАННО сходила за ручной
 * ответ сотрудника — бот ставил себе паузу на 10 минут на живом лиде и дописывал
 * вторую копию в переписку (реинкарнация бага 18.08).
 *
 * Память остаётся быстрым путём (эхо на своё же сообщение в том же процессе —
 * самый частый случай), база — общей правдой для обоих процессов. Пишем в ту же
 * таблицу ProcessedMessage, что и дедуп входящих: у неё уже есть уникальность
 * (channel, messageId) и ночная чистка. Канал помечается префиксом `out:`, чтобы
 * исходящие отметки не столкнулись с входящими (mid у Meta уникален, но полагаться
 * на это в чужом пространстве имён нельзя).
 */

import { prisma } from "../db.js";

/** Сколько помним. С запасом к реальной задержке эха (секунды) — на случай, если
 *  Meta придержит вебхук под нагрузкой. */
const TTL_MS = 15 * 60 * 1000;

/** Потолок на случай всплеска рассылок: не даём множеству расти без предела, даже
 *  если чистка почему-то не поспевает. */
const MAX_ENTRIES = 5000;

const sentAt = new Map<string, number>();

function sweep(now: number): void {
  for (const [mid, at] of sentAt) {
    if (now - at > TTL_MS) sentAt.delete(mid);
  }
  // Всё ещё великовато — выкидываем самые старые: Map хранит порядок вставки,
  // а вставляем мы по времени отправки.
  while (sentAt.size > MAX_ENTRIES) {
    const oldest = sentAt.keys().next();
    if (oldest.done) break;
    sentAt.delete(oldest.value);
  }
}

/** Пространство имён исходящих отметок в общей таблице ProcessedMessage. */
const OUT_CHANNEL = "out:meta";

/**
 * Отметить: это сообщение отправили мы. Вызывается сразу после ответа Meta.
 *
 * ЗАПИСЬ В БАЗУ ДОЖИДАЕТСЯ (20.09.2026). Раньше она была fire-and-forget с
 * доводом «эхо идёт через сеть Meta, а мы пишем в локальный Postgres — успеем».
 * Довод неверен дважды:
 *
 *  • это ГОНКА, а не порядок. Пул соединений Postgres под нагрузкой (ночные
 *    рассылки, очередь заданий) держит вставку в очереди столько же, сколько
 *    идёт вебхук от Meta, — и тогда эхо доходит до api раньше отметки worker'а;
 *  • отказ записи не замечает никто. Соединение мигнуло — отметка не появится
 *    НИКОГДА, и для этого сообщения поломка становится не случайной, а верной:
 *    собственная реплика бота сходит за ручной ответ сотрудника, бот ставит себе
 *    паузу на 10 минут на живом лиде и дописывает вторую копию в переписку.
 *    Владелец видит это как «отправляется два сообщения» и «бот завис».
 *
 * Ждать тут нечего бояться: клиенту сообщение уже ушло, остаётся одна вставка в
 * локальную базу. Ошибки по-прежнему не выбрасываются наружу — отправка
 * состоялась, и ронять из-за отметки вызывающего нельзя.
 */
export async function rememberOutgoingMid(mid: string | null | undefined): Promise<void> {
  if (!mid) return;
  const now = Date.now();
  sentAt.set(mid, now);
  sweep(now);
  try {
    await prisma.processedMessage.create({ data: { channel: OUT_CHANNEL, messageId: mid } });
  } catch (err) {
    // P2002 — тот же mid уже отмечен (повторная отправка/гонка): это норма.
    if ((err as { code?: string }).code === "P2002") return;
    console.error("[эхо] отметка исходящего не записана:", err instanceof Error ? err.message : err);
  }
}

/**
 * Наше ли это сообщение вернулось эхом.
 *
 * Асинхронна с 27.08.2026: память процесса больше не полная правда — сообщение мог
 * отправить worker, а эхо разбирает api. Отказ базы трактуется как «не наше», то
 * есть по-старому: молча съесть ответ сотрудника хуже, чем лишний раз записать
 * своё сообщение (второй слой защиты — mid в истории диалога — при этом работает).
 */
export async function wasSentByUs(mid: string | null | undefined): Promise<boolean> {
  if (!mid) return false;
  const at = sentAt.get(mid);
  if (at !== undefined) {
    if (Date.now() - at <= TTL_MS) return true;
    sentAt.delete(mid);
  }
  try {
    const row = await prisma.processedMessage.findUnique({
      where: { channel_messageId: { channel: OUT_CHANNEL, messageId: mid } },
      select: { createdAt: true },
    });
    if (!row) return false;
    return Date.now() - row.createdAt.getTime() <= TTL_MS;
  } catch (err) {
    console.error("[эхо] проверка исходящего в базе:", err instanceof Error ? err.message : err);
    return false;
  }
}

/** Только для тестов: очистить память между сценариями. */
export function resetOutgoingMids(): void {
  sentAt.clear();
}
