import { isAckOnlyMessage } from "../ai/ackOnly.js";

/**
 * ПОКА БОТ ДУМАЛ, КЛИЕНТ НАПИСАЛ ЕЩЁ (16.11.2026, аудит tone.md п.15 / facts.md Ф4).
 *
 * Живые случаи старого бота: «Алфемо» → бот думает → «60 квадрата» → два ответа, первый уже
 * устарел («Буҷетатон то чанд?»), а следом тот же вопрос ещё раз; «Ака ватсап дорен» получило
 * два разных ответа за 4 секунды. Окно склейки (5 с) закрылось раньше, чем модель ответила,
 * и следующее сообщение начало свой ход параллельно.
 *
 * Если в буфере склейки уже ждёт НОВОЕ содержательное сообщение клиента, этот ответ не
 * уходит: победитель того окна ответит за всё сразу, по истории, где лежат обе реплики
 * (сообщение этого хода сохранено в историю до вызова модели).
 *  - «Ок», «👍», «Рахмат» в буфере не в счёт: их ход может промолчать (silentTurnReason),
 *    и вопрос остался бы без ответа.
 *  - Повтор уже сохранённого хода (skipSaveIncoming) не трогаем: он ничего в буфер не кладёт.
 * Остаётся риск (ревью #207, С5): следующий ход может промолчать по своей причине (пауза
 * сотрудника, бюджет ИИ). Тогда сообщение клиента без ответа видит сторож «клиент ждёт»
 * (lib/clientWaitingAlert.ts) и фоновый повтор ответа.
 */
export function newerClientMessagePending(
  row: { pendingSince: Date | null; pendingMessages: unknown } | null | undefined,
  skipSaveIncoming: boolean
): boolean {
  if (skipSaveIncoming || !row?.pendingSince || !Array.isArray(row.pendingMessages)) return false;
  return (row.pendingMessages as unknown[]).some(
    (t) => typeof t === "string" && t.trim().length > 0 && !isAckOnlyMessage(t)
  );
}
