import type { LeadRequirements } from "../../lib/propertyTypeRule.js";
/**
 * Типы маршрутизации лидов, вынесенные отдельно: их импортируют крючки
 * телефонии (lib/telephony/assignAgentForLeadHook.ts, qualifyIncoming.ts), и
 * импорт самого assignment.ts оттуда замыкал цикл через selection.ts →
 * agentOccupancyShield.ts → callTracker.ts (audit:deps, 11.09.2026). Здесь —
 * ни одного импорта, только типы.
 */
export type LeadAssignReason =
  /**
   * КЛИЕНТ ПРИСЛАЛ ССЫЛКУ НА ПОСТ (владелец 09.09.2026) — он прямо показал, какой
   * объект ему нужен. Это не догадка, в отличие от совпадения по описанию, поэтому
   * стоит в лесенке первым и уступает только просьбе назвать сотрудника.
   */
  | "instagram_post_link"
  /**
   * ОБЪЕКТ НАЗВАН ЯВНО (Пачка 1 п.5, 11.09.2026): форма сайта или разбор звонка
   * уже нашли конкретную карточку (`ctx.propertyId`) — самое прямое основание,
   * сильнее и показа боту, и ссылки на пост: там объект узнаём по следу, здесь
   * он назван кодом ещё до входа в assignAgentForLead.
   */
  | "own_property_explicit"
  | "own_property_shown"
  | "own_property_match"
  /**
   * КЛИЕНТ САМ НАЗВАЛ СОТРУДНИКА (решение владельца 18.08.2026): «мне нужен Умед»,
   * «я работаю с Нозой». Прямое указание человека сильнее любой нашей догадки —
   * ни очередь по KPI, ни правило «свой объект» его не перебивают. Кого именно
   * назвали, решает код по списку сотрудников из базы (lib/requestedAgent.ts), а
   * не текст модели.
   */
  | "requested_by_client"
  | "queue";

/** Что известно о лиде в момент выбора агента. Всё необязательно: у лида,
 *  созданного руками в CRM, нет канала, а у лида из переписки может ещё не быть
 *  карточки — объекты ему показывали раньше, чем он назвал телефон. */
export interface LeadAssignContext {
  clientId?: string;
  channel?: string;
  recipientId?: string;
  /** Strict customer bridge uses account-bound transport evidence only. */
  endpointScopeId?: string | null;
  /** Текст обращения клиента — из него достаём ссылку на пост Instagram. */
  inquiryText?: string | null;
  /** Покупатель или продавец. Лимит активных лидов действует только на
   *  покупателей (владелец 20.08.2026) — см. OCCUPIES_SLOT_WHERE в
   *  lib/leadLimits.ts. Не задан — считаем покупателем, как было раньше. */
  kind?: "BUYER" | "SELLER";
  /**
   * ОБЪЕКТ НАЗВАН ЯВНО (Пачка 1 п.5, 11.09.2026): форма сайта прислала ссылку
   * на конкретную карточку (`pageUrl`), звонок ИИ распознал в расшифровке адрес,
   * ЖК или номер объекта — в обоих случаях объект уже найден вызывающим кодом
   * существующим поиском, здесь остаётся только отдать лид его хозяину. Это
   * самое прямое основание из всех: клиент не просто заинтересовался похожим —
   * он смотрит именно эту карточку. Стоит выше и показа боту, и совпадения по
   * описанию; уступает только просьбе назвать сотрудника (она разбирается вне
   * assignAgentForLead, см. requestedAgentId в services/leads/intake.ts).
   */
  propertyId?: string;
  /**
   * Запрос, который ещё не лёг в карточку (разбор звонка выбирает агента раньше,
   * чем записывает бюджет/район/комнаты) — для шага «запрос совпал с объектом».
   */
  requirements?: LeadRequirements;
}

export interface LeadAssignment {
  agentId: string | null;
  reason: LeadAssignReason;
  /** Объект, из-за которого лид ушёл мимо очереди (для записи в карточку). */
  propertyId?: string;
  propertyShortId?: number;
  score?: number;
  /** Готовая строка для хронологии — у «назвал сам» она составляется по имени
   *  сотрудника ещё в lib/requestedAgent.ts, дублировать её здесь незачем. */
  note?: string;
}
