import { describe, expect, it } from "vitest";
import { ASKED_FOR_NAME, PHONE_CORRECTION } from "../src/messengers/conversation.js";
import { isRepeatOfLastReply, normalizeReplyBubbles } from "../src/ai/leadQualifier.js";

/**
 * КЛИЕНТ ИСПРАВЛЯЕТ НОМЕР — верный обязан стать ОСНОВНЫМ.
 *
 * Живой диалог 22.08.2026, стоивший лида:
 *
 *   бот:    Рақами телефон ва номатонро нависед
 *   клиент: 980001027
 *   бот:    Ташаккури зиёд, маълумотро қабул кардем
 *   клиент: Бахшиш хато шуд          ← «извините, ошибся»
 *   клиент: 980001019                ← правильный номер
 *
 * В карточку верный номер лёг ЗАПАСНЫМ, а звонит агент по основному — то есть по
 * ошибочному. Реклама оплачена, человек ждёт звонка, звонка не будет.
 *
 * Общее правило «номера дописываем, а не перетираем» остаётся в силе: клиент часто
 * даёт второй номер просто так («вот ещё рабочий»), и затирать первый нельзя.
 * Поэтому местами меняем ТОЛЬКО когда он прямо сказал, что ошибся. Отсюда и две
 * половины теста: узнать исправление и не принять за него обычную добавку.
 */
describe("исправление номера клиентом", () => {
  it("узнаёт таджикское «хато шуд» — тот самый случай", () => {
    expect(PHONE_CORRECTION.test("Бахшиш хато шуд")).toBe(true);
    expect(PHONE_CORRECTION.test("хато кардам, ин рақам дуруст")).toBe(true);
    expect(PHONE_CORRECTION.test("мебахшед, нодуруст навиштам")).toBe(true);
  });

  it("узнаёт русские формулировки", () => {
    expect(PHONE_CORRECTION.test("ошибся, вот правильный")).toBe(true);
    expect(PHONE_CORRECTION.test("извините, неверный номер")).toBe(true);
    expect(PHONE_CORRECTION.test("не тот номер написал")).toBe(true);
    expect(PHONE_CORRECTION.test("исправляю: 980001019")).toBe(true);
  });

  it("обычная добавка второго номера исправлением НЕ считается", () => {
    // Затереть основной номер здесь — та же потеря, только наоборот.
    expect(PHONE_CORRECTION.test("вот ещё мой рабочий 980001019")).toBe(false);
    expect(PHONE_CORRECTION.test("980001019")).toBe(false);
    expect(PHONE_CORRECTION.test("это номер мужа")).toBe(false);
    expect(PHONE_CORRECTION.test("можно и на этот звонить")).toBe(false);
  });
});

/**
 * ИМЯ, НАЗВАННОЕ В ОТВЕТ НА ПРОСЬБУ БЕЗ «?».
 *
 * Тот же диалог 22.08.2026: бот написал «Рақами телефон ва номатонро нависед, то
 * агенти мо занг занад» — просьба прямая, вопросительного знака в ней нет. Клиент
 * ответил «Давлат», и имя пролетело мимо карточки: признаком служил один лишь «?».
 * Агент звонит «Продавцу №…», не зная, как обратиться к человеку.
 */
describe("просьба назвать имя без вопросительного знака", () => {
  it("узнаёт таджикскую просьбу — тот самый случай", () => {
    expect(ASKED_FOR_NAME.test("Рақами телефон ва номатонро нависед, то агенти мо занг занад")).toBe(true);
    expect(ASKED_FOR_NAME.test("Номатонро нависед")).toBe(true);
  });

  it("узнаёт русскую просьбу", () => {
    expect(ASKED_FOR_NAME.test("Напишите ваше имя и номер")).toBe(true);
    expect(ASKED_FOR_NAME.test("Скажите имя, пожалуйста")).toBe(true);
  });

  it("обычную реплику за просьбу об имени не принимает", () => {
    // Иначе в карточку вместо имени ляжет случайное слово из ответа клиента.
    expect(ASKED_FOR_NAME.test("Чи хизмат намоям")).toBe(false);
    expect(ASKED_FOR_NAME.test("Хона бо таъмир аст ё каробка")).toBe(false);
    expect(ASKED_FOR_NAME.test("Ташаккури зиёд, маълумотро қабул кардем")).toBe(false);
  });
});

/**
 * ДОСЛОВНЫЙ ПОВТОР СВОЕЙ ЖЕ ФРАЗЫ ДО КЛИЕНТА НЕ ДОХОДИТ.
 *
 * Тот же диалог 22.08.2026: клиент повторил ответ другими словами («Бо ремонт» →
 * «Бо таьмир»), и бот слово в слово прислал ту же просьбу о номере. Два одинаковых
 * сообщения подряд — самая узнаваемая подпись автомата.
 *
 * Правило «не повторяй дословно» в промте уже было и не сработало: промт — просьба,
 * а не гарантия. Поэтому фильтр стоит в коде.
 */
describe("повтор собственной фразы", () => {
  const asked = "Рақами телефон ва номатонро нависед, то агенти мо занг занад";

  it("узнаёт повтор, даже если изменились знаки и регистр", () => {
    expect(isRepeatOfLastReply(asked, asked)).toBe(true);
    expect(isRepeatOfLastReply(asked + ".", asked)).toBe(true);
    expect(isRepeatOfLastReply(asked.toUpperCase(), asked)).toBe(true);
  });

  it("короткие согласия повторять можно — это не мысль, а «да»", () => {
    expect(isRepeatOfLastReply("Хуб", "Хуб")).toBe(false);
    expect(isRepeatOfLastReply("Бале", "Бале")).toBe(false);
  });

  it("другая фраза повтором не считается", () => {
    expect(isRepeatOfLastReply("Хона бо таъмир аст ё каробка?", asked)).toBe(false);
  });

  it("повтор вырезается из ответа целиком", () => {
    expect(normalizeReplyBubbles([asked], true, "", asked)).toEqual([]);
    // А новая фраза проходит — фильтр не должен глушить разговор.
    const fresh = "Кадом ошёна ва чанд метр?";
    expect(normalizeReplyBubbles([fresh], true, "", asked)).toEqual([fresh]);
  });
});
