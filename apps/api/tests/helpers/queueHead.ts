/**
 * СВОЁ ЗАДАНИЕ — В ГОЛОВУ ОЧЕРЕДИ, БЕЗ УДАЛЕНИЯ ЧУЖИХ СТРОК.
 *
 * Очередь `BackgroundJob` одна на базу, а `claimBatch` (jobs/runner.ts) берёт
 * партию `ORDER BY "runAt" LIMIT 10` по ВСЕЙ таблице, не разбирая типов. Своё
 * задание — самое молодое, то есть последнее в очереди, и тик может до него не
 * дойти. Для HEAVY_TYPES хуже: тяжёлое задание тик берёт ровно одно, и любая
 * чужая строка постарше занимает единственный слот.
 *
 * КТО ТАКИЕ «ЧУЖИЕ» (уточнено 24.09.2026 — прежнее объяснение здесь было
 * НЕВЕРНЫМ). Тут было написано «тесты идут в два процесса на одной базе
 * (#608), и чужие строки — живые задания соседнего шарда». Это не так:
 * `tests/dbPerWorker.ts` даёт КАЖДОМУ процессу vitest СВОЮ базу (копию
 * шаблона), а внутри процесса файлы идут строго последовательно
 * (`singleFork`, `fileParallelism: false`). Соседнего шарда в твоей базе нет
 * вовсе. Чужие строки — это брошенные задания ПРОШЕДШИХ файлов твоего же
 * процесса: их владельцы уже отработали, но `deleteMany` по ним всё равно
 * плохая привычка (сносит и то, что чинит позднее, и маскирует настоящую
 * причину), а главное — сам по себе снос НЕ РЕШАЕТ задачу, см. ниже.
 *
 * ОДНОГО СДВИГА МАЛО. Брошенная строка прошедшего файла может быть СТАРШЕ
 * твоего сдвига и занять тяжёлый слот. Сдвиг ставит своё задание в голову
 * очереди, но не гарантирует, что ОДИН тик его исполнит. Поэтому тикать надо,
 * пока своё задание не уйдёт из `PENDING`/`RUNNING`, а не ровно один раз
 * (образец — `tickUntilOwnJobRan` в `video-handoff.test.ts`). На этом файл
 * покраснел в полном прогоне 24.09.2026 при исправном коде.
 *
 * ПОЧЕМУ НЕ `new Date(0)`. В конце КАЖДОГО тика runner подчищает
 * `DONE`/`SKIPPED` со сроком старше `KEEP_DONE_DAYS = 7`. Задание с `runAt` в
 * 1970-м попадает под эту чистку в том же тике, который его исполнил:
 * обработчик отработал, а строки в таблице уже нет — тест падает
 * «expected undefined to be DONE», хотя код исправен. Поэтому сдвиг —
 * заведомо больше возраста строк одного прогона и заведомо меньше недели.
 */
const HEAD_OF_QUEUE_SHIFT_MS = 60 * 60_000;

/** `runAt`, ставящий задание в голову очереди и не попадающий под чистку DONE. */
export function headOfQueueRunAt(): Date {
  return new Date(Date.now() - HEAD_OF_QUEUE_SHIFT_MS);
}
