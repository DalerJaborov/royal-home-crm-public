import { prisma } from "../../src/db.js";

/**
 * СВОБОДНЫЙ УЧАСТОК ПУЛА ВНУТРЕННИХ НОМЕРОВ.
 *
 * Тесты телефонии брали основание номера как `Math.random() * 9000 + 1000` —
 * четыре цифры, никакой проверки. На пустой базе CI это всегда работало, а на
 * стенде и на проде номер вполне мог оказаться уже закреплённым за живым
 * сотрудником: `pickFreeExtension` его пропускала, и «первый свободный»
 * оказывался вторым (замер 11.09.2026: ждали 1002, получили 1003). Тест при
 * этом проверял ровно то, что должен, — просто исходил из пустого пула.
 *
 * Здесь основание подбирается по базе: возвращается такое число, что все
 * `count` номеров подряд начиная с него в Agent.sipExtension не встречаются.
 * Читает, ничего не меняет и ничего чужого не трогает.
 *
 * ПОЛОСА 1000-1099 НЕ ВЫДАЁТСЯ НИКОГДА (20.09.2026). Проверки по базе мало:
 * она смотрит на сотрудников, которые есть В ЭТУ СЕКУНДУ, а соседние файлы
 * набора заводят своих ПОЗЖЕ — и ровно там лежат номера, вписанные в тесты
 * буквами: `1001` и `1002` в incoming-operator.test.ts, `1003`, `1005`, `1007`,
 * `1009`, `1012` в requested-agent.test.ts. Живое падение 20.09.2026 в CI:
 * `Math.random()` дал основание 1000, участок занял 1001-1006, к моменту
 * проверки эти номера уже были за сотрудниками соседнего файла — «первый
 * свободный» оказался 1003, а второй тест не нашёл свободных вовсе.
 *
 * Поэтому договорённость такая: 1000-1099 — полоса номеров, написанных в тестах
 * буквами, случайные участки начинаются с 1100. Новый номер буквами писать
 * только в этой полосе.
 */
const LITERAL_BAND_END = 1100;

export async function reserveExtensionBase(count = 6): Promise<number> {
  for (let attempt = 0; attempt < 60; attempt++) {
    const base = LITERAL_BAND_END + Math.floor(Math.random() * (9000 - LITERAL_BAND_END));
    const wanted = Array.from({ length: count + 1 }, (_, i) => `${base + i}`);
    const taken = await prisma.agent.count({ where: { sipExtension: { in: wanted } } });
    if (taken === 0) return base;
  }
  throw new Error(`Не нашлось свободного участка пула из ${count} номеров подряд за 60 попыток`);
}
