import { prisma } from "../../src/db.js";

/**
 * УДАЛЕНИЕ ТЕСТОВЫХ АГЕНТОВ, КОТОРОЕ НЕ ПАДАЕТ НА ЧУЖОМ СЛЕДЕ.
 *
 * Обычная уборка выглядит так: удалить взаимодействия СВОИХ клиентов, удалить
 * своих клиентов, удалить своих агентов. Пока агент связан только со своими
 * клиентами, это работает.
 *
 * Но агент — общий ресурс базы. Раздача лидов выбирает исполнителя среди ВСЕХ
 * активных агентов (см. комментарий в vitest.config.ts), и заведённый тестом
 * агент может получить карточку, которую этот тест не заводил: лид, созданный
 * маршрутом по ходу проверки, или карточку соседнего прогона на общем стенде.
 * По такой карточке пишется Interaction с нашим agentId — и `agent.deleteMany`
 * падает на `Interaction_agentId_fkey`. Тесты при этом все зелёные, а файл
 * красный: уборка уронила то, что уже прошло (замер 11.09.2026 — так упали
 * access-control и lead-training-mode-toggles).
 *
 * Здесь след агента стирается ПО САМОМУ АГЕНТУ, а не по списку его клиентов, —
 * и только по нашим id, ничего чужого.
 */
export async function deleteAgentsWithTraces(agentIds: string[]): Promise<void> {
  const ids = agentIds.filter(Boolean);
  if (ids.length === 0) return;
  await prisma.interaction.deleteMany({ where: { agentId: { in: ids } } });
  await prisma.agent.deleteMany({ where: { id: { in: ids } } });
}
