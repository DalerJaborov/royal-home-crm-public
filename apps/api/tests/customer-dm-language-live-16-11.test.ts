describe("кнопка рекламы — признак, а не язык", () => {
  const RU_AD = "Привет! Можно узнать об этом подробнее?";
  const UZ_AD = "Assalomu alaykum! Bu haqida yana maʼlumot olsam boʻladimi?";
  it("узнаёт русскую, узбекскую и набранную руками без фактов", () => {
    for (const text of [RU_AD, "Здравствуйте! Можно узнать об этом подробнее?", UZ_AD, "Здравствуйте можно по подробнее пожалуйста"]) {
      expect(isAdTemplateOpener(text)).toBe(true);
    }
    expect(isAdTemplateOpener("Можно узнать подробнее об этой вакансии")).toBe(false);
    expect(clientSaidNothingSubstantive("Салом")).toBe(true);
  });
  it("«Салом» после русской кнопки — таджикский (WhatsApp 16680508, 15.11 21:19)", () => {
    expect(resolveCustomerDmLanguage("Салом", [RU_AD])).toBe("tg");
    expect(resolveCustomerDmLanguage("Оиди вакансия маъоумот медоден", [RU_AD, "Салом"])).toBe("tg");
  });
  it("сама кнопка: язык рекламы только как последний запасной", () => {
    expect(resolveCustomerDmLanguage(RU_AD)).toBe("ru");
    expect(resolveCustomerDmLanguage(UZ_AD)).toBe("ru");
    expect(adTemplateLanguage("Мехоҳам дар бораи ин бештар донам")).toBe("tg");
    expect(resolveCustomerDmLanguage(RU_AD, ["Хонаи фуруши дорам"])).toBe("tg");
  });
  it("узбекская латиница не считается таджикской (7e3d0a3d, 12.11)", () => {
    expect(detectClientLanguage("Bu haqida yana maʼlumot olsam boʻladimi?")).toBe("unknown");
  });
});

describe("язык диалога помнится дальше окна в 6 реплик (5a5de705, 5e961b62)", () => {
  it("таджикский чат → точка → номер → фото: последний решающий язык — таджикский", () => {
    const history = ["Привет! Можно узнать об этом подробнее?", "Ман хонаи фуруши дорам дар Душанбе", "3 хонага 82 мкр", ".",
      "935 00 00 00", "{\"incomingAttachments\":[\"image\"]}"];
    expect(customerDmDialogueLanguage(history)).toBe("tg");
    // В окне памяти ничего решающего: только точка, номер и заглушки фото.
    expect(resolveCustomerDmLanguage(".", [".", "935 00 00 00"], customerDmDialogueLanguage(history) ?? undefined)).toBe("tg");
  });
  it("ничего решающего — null, язык не выдумывается", () => {
    expect(customerDmDialogueLanguage(["Привет! Можно узнать об этом подробнее?", "Салом", "."])).toBeNull();
  });
  it("клиент перешёл на русский — помнится русский", () => {
    expect(customerDmDialogueLanguage(["Хона мехарам", "Можно на русском? Я ищу квартиру в Сино"])).toBe("ru");
  });
});
