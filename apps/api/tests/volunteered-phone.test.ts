import { describe, expect, it } from "vitest";
import { extractAllPhones, extractTypedPhone, extractVolunteeredPhone } from "../src/ai/leadQualifier.js";
import { replyWaitMs } from "../src/messengers/conversation.js";

/**
 * Номер, который клиент дал сам, не дожидаясь вопроса.
 *
 * 31.07 такой клиент потерялся: он написал «мада занг занен 880001007», бот
 * вежливо поблагодарил, а заявки не возникло — номер искали только в стадии
 * «жду телефон». Обратная опасность не меньше: в переписке полно чисел, и
 * бюджет не должен превращаться в телефон.
 */
describe("extractVolunteeredPhone — телефон посреди разговора", () => {
  it("берёт местный девятизначный номер из фразы", () => {
    expect(extractVolunteeredPhone("мада занг занен 880001007")).toBe("+992880001007");
  });

  it("понимает номер с кодом страны и разделителями", () => {
    expect(extractVolunteeredPhone("мой +992 93 700 11 22, звоните после 18")).toBe("+992937001122");
  });

  it("берёт российский номер", () => {
    expect(extractVolunteeredPhone("звоните 89161234567")).toBe("+79161234567");
  });

  it("НЕ принимает бюджет за телефон", () => {
    expect(extractVolunteeredPhone("то 150 000 доллар")).toBeNull();
    expect(extractVolunteeredPhone("бюджет 1 100 000 сомони")).toBeNull();
    expect(extractVolunteeredPhone("цена 149 000$")).toBeNull();
  });

  it("НЕ принимает девятизначную сумму — рядом стоит слово о деньгах", () => {
    // Раньше здесь была проверка «цены начинаются не с кода оператора» (1 или 2),
    // но код оператора не бывает известен заранее (владелец 03.09.2026: у MegaFon
    // нашёлся код «01», а разбор гадал по цифрам). Девятизначную сумму отличает от
    // номера не первая цифра, а слово клиента о деньгах рядом — см. тест ниже про
    // «сомони» и «настоящий номер в том же сообщении».
    expect(extractVolunteeredPhone("хочу за 100000000 сомони")).toBeNull();
  });

  it("НЕ принимает площадь, этаж и год", () => {
    expect(extractVolunteeredPhone("96 кв/м, 6 этаж, 2024 год")).toBeNull();
  });

  it("на тексте без чисел молчит", () => {
    expect(extractVolunteeredPhone("салом, хона даркор")).toBeNull();
  });

  /**
   * 18.08.2026: спам со ссылкой wa.me/992880001013 (номер поддержки спамера, не
   * клиента) бот принял за оставленный контакт — цифры после слэша совпали с
   * формой «таджикский номер с кодом страны». Номера внутри ссылок — не то, что
   * клиент оставил как свой.
   */
  it("НЕ принимает номер, спрятанный в ссылке (wa.me, t.me, домен)", () => {
    expect(extractVolunteeredPhone("Поддержка: WhatsApp: https://wa.me/992880001013")).toBeNull();
    expect(extractVolunteeredPhone("пишите t.me/992937001122")).toBeNull();
    expect(extractVolunteeredPhone("сайт domtj.ru/992880001013/page")).toBeNull();
  });

  it("но настоящий номер рядом со ссылкой всё ещё берётся", () => {
    expect(extractVolunteeredPhone("сайт domtj.ru, звоните 992880001013")).toBe("+992880001013");
  });
});

/**
 * Пауза перед ответом: ждём тишины, продлеваем, пока клиент дописывает, но не
 * дольше потолка — иначе человек, пишущий каждые 20 секунд, откладывал бы ответ
 * бесконечно.
 */
describe("replyWaitMs — сколько ждать перед ответом", () => {
  const delay = 25_000;
  const cap = 90_000;

  it("первое сообщение пачки — полная пауза", () => {
    expect(replyWaitMs(1_000_000, 1_000_000, delay, cap)).toBe(delay);
  });

  it("клиент дописывает — снова полная пауза, пока есть запас", () => {
    expect(replyWaitMs(1_030_000, 1_000_000, delay, cap)).toBe(delay);
  });

  it("у потолка ждём только остаток", () => {
    expect(replyWaitMs(1_080_000, 1_000_000, delay, cap)).toBe(10_000);
  });

  it("потолок исчерпан — отвечаем немедленно", () => {
    expect(replyWaitMs(1_090_000, 1_000_000, delay, cap)).toBe(0);
    expect(replyWaitMs(1_200_000, 1_000_000, delay, cap)).toBe(0);
  });
});

describe("Номера столбиком и числа рядом с ними", () => {
  /**
   * 18.08.2026, @shoga7820: продавец дома в Дарёободе за 1 050 000 сомонӣ прислал
   * четыре своих номера, каждый с новой строки. Класс символов внутри номера
   * содержал \s, который матчит и перенос строки, — регулярка жадно слепила первые
   * два в «030001023000001018», 18 цифр не прошли проверку длины, и extractTypedPhone
   * вернул null. Карточка НЕ СОЗДАЛАСЬ, хотя бот ответил «маълумотатонро ба агент
   * додам». Лид исчез вместе с домом за миллион.
   */
  const CTOLBIK = ["030001023", "000001018", "940001011", "200001022", "Номам Навруз"].join("\n");

  /**
   * ПОЧЕМУ ПЕРВЫЙ ПО ПОРЯДКУ, А НЕ «НАСТОЯЩИЙ МОБИЛЬНЫЙ» (владелец 03.09.2026).
   *
   * До сегодня здесь стояло правило «"030001023" начинается с нуля — значит не
   * мобильный» и extractTypedPhone намеренно пропускал его в пользу «940001011».
   * Правило было основано на догадке о том, какие коды операторов существуют, а
   * владелец поправил: коды МЕНЯЮТСЯ и появляются новые, начиная хоть с нуля (у
   * MegaFon есть «01») — отличить «настоящий код с нуля» от «настоящего мобильного»
   * по одним цифрам нельзя. Значит, среди нескольких девятизначных кандидатов в
   * столбике решает порядок (кто первый, тот и номер), а не догадка по первой
   * цифре — так же, как решает первый попавшийся кандидат в любом другом месте
   * этого файла.
   */
  it("четыре номера столбиком не склеиваются — берётся первый по порядку", () => {
    expect(extractTypedPhone(CTOLBIK)).toBe("+992030001023");
    expect(extractVolunteeredPhone(CTOLBIK)).toBe("+992030001023");
  });

  it("но ВСЕ номера столбика сохраняются, не только первый", () => {
    // Первым в extractTypedPhone/extractVolunteeredPhone уходит только ОДИН номер
    // (в Client.phone), а extractAllPhones — для запасных (см. её же комментарий
    // в leadQualifier.ts) — находит все четыре, включая тот, что начинается с нуля.
    expect(extractAllPhones(CTOLBIK)).toEqual([
      "+992030001023",
      "+992000001018",
      "+992940001011",
      "+992200001022",
    ]);
  });

  it("цена перед номером не мешает найти номер", () => {
    expect(extractTypedPhone("3 сотих, 1050000 сомонӣ, занг занед 910001044")).toBe("+992910001044");
  });

  it("одна лишь цена телефоном не становится", () => {
    // Бот СПРОСИЛ номер, человек ответил ценой — мягкое правило раньше заводило
    // карточку с телефоном «+1050000», по которому не позвонить.
    expect(extractTypedPhone("Нарх 1050000 сомонӣ")).toBeNull();
  });

  it("номер с комментарием разбирается по-прежнему", () => {
    expect(extractTypedPhone("+992 93 700 11 22, звоните после 18")).toBe("+992937001122");
  });
});
