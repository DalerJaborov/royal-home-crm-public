import { describe, expect, it } from "vitest";
import { classifyAdTopic, foldTajikLetters, isJobAdRef, isSellerAdRef } from "../src/ai/adTemplateOpener.js";

/**
 * Живой случай 14–15.11.2026 (аудит рекламы, отчёт ads-2026-11-15): буст рилса
 * для собственников «Фуруши манзил». Строка `Ad` на проде — ниже дословно
 * (название, кампания и группа у буста одинаковые). Бот записал все 4 переписки
 * как вакансию (`adTopic = job`) и спрашивал продавца «информация или работа?».
 * Две причины, обе — класс «таджикский текст на русской раскладке и бытовое
 * слово как признак»:
 *  1. «Фуруши» написано обычной «у», а признак собственников ждал «фурӯш»;
 *  2. в тексте рилса «бокимондааш — кори мост» («остальное — наша работа»),
 *     а голое «кори» считалось признаком вакансии.
 */
const CAPTION =
  "Фуруши манзилро ба Royal Home бовар кунед.🏡\n\nШумо вакти худро сарфа кунед, бокимондааш - кори мост.\n" +
  "Аз аксбардории касби то анчоми\nмуомила, хамеша дар пахлуи шумоем.\n\n📩Барои машварати ройгон ба мо мурочиат\nкунед.\n" +
  "#недвижимость #душанбе #royalhome";
const BOOST = 'Публикация: "Фуруши манзилро ба Royal Home бовар кунед.🏡"';

describe("реклама для собственников не становится вакансией", () => {
  it("буст рилса «Фуруши манзил» — собственники", () => {
    expect(classifyAdTopic({ name: BOOST, campaignName: BOOST, groupName: BOOST, caption: CAPTION })).toBe("seller");
  });

  it("текст объявления из referral (WhatsApp/Instagram) — не вакансия и узнаётся как собственники", () => {
    expect(isJobAdRef(CAPTION)).toBe(false);
    expect(isSellerAdRef(CAPTION)).toBe(true);
  });

  it("«кори мост» / «кори хуб» — не признак вакансии", () => {
    expect(isJobAdRef("бокимондааш - кори мост")).toBe(false);
    expect(isJobAdRef("Кори хуб мекунем")).toBe(false);
  });

  it("таджикские буквы и русская раскладка значат одно и то же", () => {
    expect(foldTajikLetters("Фурӯши ҶОИ кор, қабул, ҳамеша, ғайриманқул, ӣ")).toBe("фуруши чои кор, кабул, хамеша, гайриманкул, и");
    // «ӯ» как «у» + комбинируемый макрон (U+0304) — так её иногда шлют телефоны.
    expect(foldTajikLetters("фуӯш")).toBe("фууш");
    expect(isSellerAdRef("Мехохед амволи худро фурушед?")).toBe(true);
    expect(isSellerAdRef("Мехоҳед амволи худро фурӯшед?")).toBe(true);
  });
});

describe("настоящая вакансия по-прежнему вакансия", () => {
  it.each(["Ҷои кор — менеджер", "чои кор барои менечер", "Ҷойи кор", "кор лозим", "кор", "Вакансия: агент", "работа в офисе", "job"])(
    "%s",
    (ref) => expect(isJobAdRef(ref)).toBe(true)
  );

  it("вакансия менеджера по продажам с «фурӯш» в тексте — вакансия, не собственники", () => {
    expect(classifyAdTopic({ name: "Недвижимость", caption: "ВАКАНСИЯ. Менеджери фурӯши амволи ғайриманқул" })).toBe("job");
    expect(classifyAdTopic({ name: "Менеджери ба фурӯши амволи ғайриманқул — ҷои кор" })).toBe("job");
    expect(classifyAdTopic({ name: "x", caption: "Ба кор қабул мекунем" })).toBe("job");
    expect(classifyAdTopic({ name: "x", caption: "Ба кор кабул мекунем" })).toBe("job");
  });

  it("«мы работаем без комиссии» в рекламе квартиры — не вакансия", () => {
    expect(isJobAdRef("Мы работаем без комиссии")).toBe(false);
  });
});
