import { describe, expect, it } from "vitest";
import { parseAskOwner } from "../src/ai/askOwner.js";

/**
 * «Уточню у собственника» — механика вместо фразы.
 *
 * Раньше бот говорил «уточню и вернусь» и не возвращался: фраза никуда не
 * записывалась. Теперь обещание становится записью — но только если модель
 * действительно назвала вопрос. Разбор её ответа и стережёт эту границу: пустые
 * карточки в списке живых людей быстро приучают этот список не читать.
 */

describe("Что считается вопросом к собственнику", () => {
  it("нормальный вопрос принимается", () => {
    expect(parseAskOwner("Готов ли собственник торговаться и насколько?")).toBe(
      "Готов ли собственник торговаться и насколько?"
    );
  });

  it("пробелы по краям срезаются", () => {
    expect(parseAskOwner("  Остаётся ли мебель?  ")).toBe("Остаётся ли мебель?");
  });

  /** Модель охотно возвращает пустую строку вместо отсутствия поля. */
  it("пустое и слишком короткое — это «спрашивать нечего»", () => {
    expect(parseAskOwner("")).toBeNull();
    expect(parseAskOwner("   ")).toBeNull();
    expect(parseAskOwner("нет")).toBeNull();
  });

  it("не строка — тоже ничего", () => {
    expect(parseAskOwner(undefined)).toBeNull();
    expect(parseAskOwner(null)).toBeNull();
    expect(parseAskOwner(42)).toBeNull();
    expect(parseAskOwner({ question: "торг?" })).toBeNull();
  });

  /** Вопрос уходит человеку в интерфейс и в базу: простыня на два экрана там не
   *  читается, а колонка не бесконечна. */
  it("длинный вопрос обрезается", () => {
    const long = "а".repeat(2000);
    expect(parseAskOwner(long)!.length).toBe(1000);
  });
});
