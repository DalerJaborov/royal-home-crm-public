import { describe, expect, it } from "vitest";
import { SHOWINGS_DISABLED_RULE } from "../src/messengers/botCapabilities.js";
import { showingPromptBlock } from "../src/ai/leadQualifier.js";

/**
 * Выключенная способность обязана исчезнуть И ИЗ ДЕЙСТВИЙ, И ИЗ ОБЕЩАНИЙ.
 *
 * Это не педантизм, а разбор конкретной поломки: отправки фотографий не было ни в
 * Telegram, ни в других каналах вне Meta, а промт всё равно велел писать «ана расмҳояш» — и бот
 * честно обещал клиенту снимки, которых тот не получал. Флаг, который гасит
 * действие, но оставляет обещание, хуже отсутствия флага.
 */
describe("показы выключены", () => {
  it("вместо блока про назначение времени идёт объяснение, что этим займётся агент", () => {
    // Просто «молчи» не работает: спросить «когда вам удобно приехать» — это
    // естественный следующий шаг модели в разговоре о квартире.
    expect(SHOWINGS_DISABLED_RULE).toContain("ПОКАЗЫ ТЫ НЕ НАЗНАЧАЕШЬ");
    expect(SHOWINGS_DISABLED_RULE).toContain("агент");
  });

  it("клиента, который сам просится посмотреть, не теряем — берём номер", () => {
    // Формулировка правки таджикского 16.08.2026: вежливое «Безаҳмат» вместо
    // книжного «лутфан», слово после него со строчной буквы.
    expect(SHOWINGS_DISABLED_RULE).toContain("рақаматонро нависед");
  });

  it("предлагать конкретное время прямо запрещено", () => {
    expect(SHOWINGS_DISABLED_RULE).toContain("запрещено");
    expect(SHOWINGS_DISABLED_RULE).toContain("имрӯз ё пагоҳ");
  });
});

describe("показы включены", () => {
  it("блок назначения на месте — правило остаётся обратимым", () => {
    const block = showingPromptBlock(new Date("2026-08-01T09:00:00.000Z"));
    expect(block).toContain("action=book");
    expect(block).not.toContain("ПОКАЗЫ ТЫ НЕ НАЗНАЧАЕШЬ");
  });
});
