import { describe, expect, it } from "vitest";

import { MOBILE_LEG_RE, memberHasLiveLeg } from "../src/lib/telephony/stationHealth.js";

/**
 * ДОСТУПНОСТЬ УЧАСТНИКА ОЧЕРЕДИ СЧИТАЕТСЯ ПО ОБОИМ ПЛЕЧАМ (21.09.2026).
 *
 * Поломка, ради которой написан этот файл: проверка «Очередь приёма:
 * доступность» считала участника готовым принять звонок только при
 * зарегистрированной настольной SIP-трубке. Настольных трубок в агентстве нет
 * ни у кого с 18.08.2026 — `sip show registry` отдаёт ноль регистраций, все
 * работают с мобильных, и звонок доходит вторым плечом
 * `Local/<девять цифр>@from-internal` в строке набора (agentMobileFallback.ts).
 *
 * Значит проверка обязана была докладывать поломку КАЖДЫЙ день и навсегда —
 * при исправной очереди. Замер 21.09.2026: станция отвечает `Status: 1,
 * Paused: 0`, очередь накануне приняла 4 звонка, а проверка писала «ни один из
 * участников не на связи». Ежедневная ложная тревога на самой важной проверке
 * хуже её отсутствия: она приучает пролистывать ровно ту строку, которой
 * однажды скажут правду.
 */
describe("мобильное плечо в строке набора", () => {
  it("узнаёт плечо, которое ставит CRM", () => {
    expect(MOBILE_LEG_RE.test("SIP/1009&Local/880001007@from-internal/n")).toBe(true);
  });

  it("узнаёт плечо, стоящее первым и единственным", () => {
    expect(MOBILE_LEG_RE.test("Local/900001042@from-internal/n")).toBe(true);
  });

  it("узнаёт плечо рядом с мёртвыми PJSIP-плечами эксперимента 14.08", () => {
    expect(MOBILE_LEG_RE.test("PJSIP/rh-mobile-1003&PJSIP/rh-web-1003&Local/777700555@from-internal/n")).toBe(true);
  });

  it("не принимает голый SIP за живое плечо", () => {
    expect(MOBILE_LEG_RE.test("SIP/1008")).toBe(false);
  });

  it("не принимает ВНУТРЕННИЙ номер за выход наружу", () => {
    // Ровно та ошибка, ради которой в выражении стоит \d{7,}: `Local/1009@…` —
    // это внутренний аппарат, до которого без регистрации не дозвониться, а не
    // мобильный. Считать его живым плечом значило бы вернуть ту же ложь, только
    // с обратным знаком.
    expect(MOBILE_LEG_RE.test("SIP/1009&Local/1009@from-queue/n")).toBe(false);
  });

  it("не принимает пустую строку набора", () => {
    expect(MOBILE_LEG_RE.test("")).toBe(false);
  });
});

describe("до участника очереди доходит звонок", () => {
  it("настольный аппарат на связи — достижим, строку набора спрашивать незачем", () => {
    expect(memberHasLiveLeg(true, null, false)).toBe(true);
  });

  it("аппарата нет, но есть мобильное плечо — достижим (тот самый случай)", () => {
    expect(memberHasLiveLeg(false, "SIP/1009&Local/880001007@from-internal/n", true)).toBe(true);
  });

  it("аппарата нет и плеча нет — недостижим", () => {
    expect(memberHasLiveLeg(false, "SIP/1008", true)).toBe(false);
  });

  it("станция не отдала строку набора — это незнание, а не «мёртв»", () => {
    // Отличие от `false` существенное: по `null` проверка говорит «судить
    // нельзя» и НЕ копит срок мёртвой трубки, иначе каждая заминка туннеля до
    // станции через сутки превращалась бы в поломку, которой не было.
    expect(memberHasLiveLeg(false, null, false)).toBe(null);
  });

  it("аппарат неизвестен ARI и строка набора не прочитана — тоже незнание", () => {
    expect(memberHasLiveLeg(undefined, undefined, false)).toBe(null);
  });
});
