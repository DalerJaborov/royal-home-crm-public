import { describe, expect, it } from "vitest";
import { clientMeansHousingDeal } from "../src/ai/housingIntent.js";
import { jobPriority } from "../src/ai/jobApplication.js";
import { normalizeCandidatePhone } from "../src/lib/candidatePhone.js";

/**
 * СЛОВА КАНДИДАТА НЕ ДОЛЖНЫ ПРЕВРАЩАТЬ ЕГО В ХОЗЯИНА ЖИЛЬЯ, А ЦВЕТ — ВРАТЬ
 * (02.10.2026, разбор приёма кандидатов в каналах).
 *
 * Чистые функции, база не нужна. Фразы — дословно из разбора.
 */

describe("clientMeansHousingDeal: рассказ кандидата о себе — не сделка с жильём", () => {
  it.each([
    // «хона» внутри «хонадор» (женат) + «дорам» рядом — раньше «хозяин жилья».
    "25 сол дорам, хонадор",
    // «продавал квартиры» — опыт работы, «нужна работа» раньше не гасило совпадение.
    "Нужна работа, раньше продавал квартиры",
    // «корхона» (завод) — не «хона».
    "Дар корхона кор мекардам, 26 сол дорам",
    // «хонанда» (учащийся).
    "Ман хонанда ҳастам, кор лозим",
    "Кор ҳаст? 25 сол дорам, хонадор, фурӯш кардам",
    // «дорам» про возраст не склеивается с «хона» через запятую.
    "25 сол дорам, дар хона нишастаам",
    "Задача — продавать",
  ])("«%s» — не жильё", (t) => {
    expect(clientMeansHousingDeal(t)).toBe(false);
  });

  it.each([
    "Хона дорам",
    "Шумо хона реклама мекунед",
    "Салом хонай фуруши дорам",
    "Продаю квартиру в Сино",
    "у меня есть дача",
    // «hr» внутри латинского имени — не слово о работе, жильё остаётся жильём.
    "Bahrom, хона дорам",
    // Продавцы, которых голые «работа/опыт/кор ҳаст» и граница по цифре гасили
    // (доразбор 02.10.2026): явная продажа своего жилья сильнее слов о работе.
    "3хонаги мефурушам",
    "Продаю квартиру, у вас есть опыт продаж?",
    "Хочу продать дом. Звоните вечером, днём работа",
    "Хона мефурушам, кор ҳаст?",
    "Квартира на продажу, работа агентов сколько стоит?",
  ])("«%s» — разговор о жилье", (t) => {
    expect(clientMeansHousingDeal(t)).toBe(true);
  });
});

describe("jobPriority: запасной разбор цвета по словам", () => {
  it("«без» про недвижимость не гасит продажи, названные в том же поле", () => {
    expect(jobPriority({ experience: "Продавец 3 года, без опыта в недвижимости" })).toBe("GREEN");
  });

  it("отрицание рядом со словом по-прежнему не даёт зелёного", () => {
    expect(jobPriority({ experience: "Опыта продаж нет" })).toBe("RED");
    expect(jobPriority({ experience: "Не работал в продажах" })).toBe("RED");
    // Вопрос и ответ, «поле: значение» — отрицание относится к слову (доразбор 02.10.2026).
    expect(jobPriority({ experience: "Опыт продаж: нет" })).toBe("RED");
    expect(jobPriority({ experience: "Работал в продажах? Нет." })).toBe("RED");
    expect(jobPriority({ experience: "Работал в продажах. Нет" })).toBe("RED");
  });

  it("«айти» внутри «найти» — не айти", () => {
    expect(jobPriority({ education: "Учился на повара, хочу найти себя в продажах" })).toBe("RED");
    expect(jobPriority({ education: "айти, программист" })).toBe("YELLOW");
  });

  it("«фурӯшгоҳ» (магазин) — не опыт продаж, «фурӯш» — опыт", () => {
    expect(jobPriority({ experience: "дар фурӯшгоҳ кор мекардам" })).toBe("RED");
    expect(jobPriority({ experience: "дар фурӯши телефон кор кардам" })).toBe("GREEN");
  });
});

describe("normalizeCandidatePhone: запасной разбор не выдаёт мусор за номер", () => {
  it("9–10 цифр, не похожие на таджикский номер, — не номер", () => {
    expect(normalizeCandidatePhone("012345678")).toBeUndefined();
    expect(normalizeCandidatePhone("9001112223")).toBeUndefined();
    expect(normalizeCandidatePhone("1234567890")).toBeUndefined();
  });

  it("иностранный номер без «+» по-прежнему принимается", () => {
    expect(normalizeCandidatePhone("998901234567")).toBe("+998901234567");
    expect(normalizeCandidatePhone("905321234567")).toBe("+905321234567");
  });

  it("настоящие таджикские записи не задеты", () => {
    expect(normalizeCandidatePhone("910001044")).toBe("+992910001044");
    expect(normalizeCandidatePhone("0910001044")).toBe("+992910001044");
    expect(normalizeCandidatePhone("992910001044")).toBe("+992910001044");
  });
});
