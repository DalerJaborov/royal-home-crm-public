import { describe, expect, it } from "vitest";
import { hasCallTimePromise, stripCallTimePromise } from "../src/ai/callTimePromiseGuard.js";

/**
 * Срок звонка агента не называется никогда (владелец 22.11.2026). Живые фразы бота
 * с прода: 22.11 08:59 «он позвонит вам на этот номер сегодня с 10:00» и 23.11
 * 23:38 «он позвонит вам завтра с 10:00, а пока можете рассказать…».
 */
describe("stripCallTimePromise — русский", () => {
  it("живая фраза 22.11: срок режется, смысл остаётся", () => {
    expect(stripCallTimePromise("Спасибо, передаю агенту, он позвонит вам на этот номер сегодня с 10:00.")).toBe(
      "Спасибо, передаю агенту, он позвонит вам на этот номер."
    );
  });

  it("живая фраза 23.11: запятая после срока не остаётся двойной", () => {
    expect(
      stripCallTimePromise("Спасибо, передаю агенту, он позвонит вам завтра с 10:00, а пока можете рассказать, что ищете.")
    ).toBe("Спасибо, передаю агенту, он позвонит вам, а пока можете рассказать, что ищете.");
  });

  it("«через N минут» и «в течение часа»", () => {
    expect(stripCallTimePromise("Агент свяжется с вами через 5 минут.")).toBe("Агент свяжется с вами.");
    expect(stripCallTimePromise("Агент позвонит в течение часа.")).toBe("Агент позвонит.");
  });

  it("одинокое «сегодня» в предложении про связь тоже убирается", () => {
    expect(stripCallTimePromise("Записали, с вами свяжутся сегодня.")).toBe("Записали, с вами свяжутся.");
  });

  it("предложение без глагола связи не трогается: время показа остаётся", () => {
    const text = "Показ завтра в 10:00 у подъезда.";
    expect(stripCallTimePromise(text)).toBe(text);
  });

  it("точка внутри времени «10.00» не рвёт предложение", () => {
    expect(stripCallTimePromise("Агент позвонит завтра с 10.00 до 12.00.")).toBe("Агент позвонит.");
  });

  it("два предложения: режется только то, где обещание звонка", () => {
    expect(stripCallTimePromise("Встреча завтра в 15:00. Агент позвонит завтра.")).toBe("Встреча завтра в 15:00. Агент позвонит.");
  });

  it("обычный текст без срока возвращается как есть", () => {
    const text = "Агент свяжется с вами и расскажет подробнее.";
    expect(stripCallTimePromise(text)).toBe(text);
  });
});

describe("stripCallTimePromise — таджикский", () => {
  it("«пагоҳ аз соати 10:00 занг мезанад»", () => {
    expect(stripCallTimePromise("Ташаккур, агент пагоҳ аз соати 10:00 занг мезанад.")).toBe("Ташаккур, агент занг мезанад.");
  });

  it("«баъди 5 дақиқа тамос мегирад»", () => {
    expect(stripCallTimePromise("Агент баъди 5 дақиқа бо шумо тамос мегирад.")).toBe("Агент бо шумо тамос мегирад.");
  });

  it("таджикский текст без срока не меняется", () => {
    const text = "Дархостатон назди агент аст, ӯ бо шумо тамос мегирад.";
    expect(stripCallTimePromise(text)).toBe(text);
  });
});

describe("hasCallTimePromise", () => {
  it("видит срок и не видит там, где его нет", () => {
    expect(hasCallTimePromise("Он позвонит вам завтра с 10:00.")).toBe(true);
    expect(hasCallTimePromise("Он свяжется с вами.")).toBe(false);
  });
});
