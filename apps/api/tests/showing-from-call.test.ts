import { describe, expect, it } from "vitest";
import { parseShowingAt } from "../src/ai/callAnalysis.js";
import { DUSHANBE_OFFSET_MS, dushanbeInputToDate } from "../src/lib/dushanbeTime.js";

/**
 * «Встретимся сегодня в шесть» → показ в календаре агента.
 *
 * Владелец 10.08.2026: «по телефону сказали, что надо сегодня встретиться в 18:00,
 * а показ автоматически не назначился». Теперь разбор разговора вытаскивает время
 * встречи, и по нему заводится обязательное окно «Назначьте показ».
 *
 * Проверяется здесь именно разбор ответа модели — единственное место, где чужой
 * текст превращается в момент времени в календаре живого человека. Цена ошибки
 * несимметрична: показ на неверную дату агент увидит только когда клиент позвонит
 * и спросит, где он.
 */

/** Момент разговора для всех проверок: 10 августа 2026, 15:00 по Душанбе. */
const CALL_AT = dushanbeInputToDate("2026-08-10", "15:00");

describe("Разбор договорённости о показе из разговора", () => {
  it("«сегодня в 18:00» становится 18:00 ПО ДУШАНБЕ, а не по UTC контейнера", () => {
    const at = parseShowingAt("2026-08-10T18:00", CALL_AT);
    expect(at).not.toBeNull();
    // Контейнер живёт в UTC, поэтому 18:00 по Душанбе — это 13:00 UTC. Без явного
    // сдвига показ уехал бы на пять часов вперёд: та же ловушка, что однажды
    // сдвинула все напоминания о встречах (аудит 06.08.2026).
    expect(at!.getUTCHours()).toBe(13);
    expect(new Date(at!.getTime() + DUSHANBE_OFFSET_MS).getUTCHours()).toBe(18);
  });

  it("пустой ответ модели — договорённости не было", () => {
    expect(parseShowingAt(null, CALL_AT)).toBeNull();
    expect(parseShowingAt(undefined, CALL_AT)).toBeNull();
    expect(parseShowingAt("", CALL_AT)).toBeNull();
  });

  it("модель ответила словами вместо даты — окно не заводим", () => {
    // Модель может вернуть «сегодня вечером» вместо формата: превращать это в
    // Invalid Date и класть в календарь нельзя.
    expect(parseShowingAt("сегодня вечером", CALL_AT)).toBeNull();
    expect(parseShowingAt("2026-08-10", CALL_AT)).toBeNull();
    expect(parseShowingAt("2026-08-10 18:00", CALL_AT)).toBeNull();
  });

  it("встреча в прошлом — это пересказ, а не будущий показ", () => {
    // «Мы вчера встречались» модель может принять за договорённость.
    expect(parseShowingAt("2026-08-09T18:00", CALL_AT)).toBeNull();
  });

  it("час до звонка допускается — разбор идёт уже после разговора", () => {
    // Расшифровка и разбор занимают минуты, и «через полчаса» не должно отсекаться
    // тем, что к моменту разбора это время почти наступило.
    const at = parseShowingAt("2026-08-10T14:30", CALL_AT);
    expect(at).not.toBeNull();
  });

  it("ошибка в годе не ставит встречу через год", () => {
    // «2027» вместо «2026» — самая вероятная ошибка модели, и найти такой показ
    // в календаре можно было бы только случайно.
    expect(parseShowingAt("2027-08-10T18:00", CALL_AT)).toBeNull();
  });

  it("три месяца вперёд — предел, дальше не верим", () => {
    const withinLimit = parseShowingAt("2026-10-01T12:00", CALL_AT);
    expect(withinLimit).not.toBeNull();
    const beyondLimit = parseShowingAt("2026-12-01T12:00", CALL_AT);
    expect(beyondLimit).toBeNull();
  });
});
