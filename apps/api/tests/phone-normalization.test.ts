import { describe, expect, it } from "vitest";
import { extractTypedPhone, normalizeDigits } from "../src/ai/leadQualifier.js";

/**
 * Клиент, которого бот явно спросил про телефон (стадия awaiting_phone), набирает
 * номер так, как принято внутри страны — с ведущим нулём («0937001122»), а не с
 * кодом страны. `normalizeDigits` эту запись не знал (только 9-значный местный без
 * нуля, 11-значный российский с восьмёрки и явный «+»), поэтому десять цифр с нулём
 * падали в общий случай и превращались в «+0937001122» — телефон, по которому нельзя
 * позвонить. Zod это пропускает: схема считает цифры, а не проверяет формат, — и
 * испорченный номер уходил прямо в карточку клиента.
 *
 * Тот же случай уже был решён для номеров со станции (`toCrmPhone` в
 * telephony/incomingCalls.ts); здесь то же правило для ботов и формы сайта.
 */
describe("normalizeDigits — местный номер с ведущим нулём", () => {
  it("10 цифр с ведущим нулём — местный номер, ноль отбрасывается", () => {
    expect(normalizeDigits("0937001122")).toBe("+992937001122");
  });

  it("9 цифр без нуля — как раньше", () => {
    expect(normalizeDigits("937001122")).toBe("+992937001122");
  });

  it("11 цифр с восьмёрки — российский номер, как раньше", () => {
    expect(normalizeDigits("89161234567")).toBe("+79161234567");
  });

  it("уже полный номер — просто плюс спереди, как раньше", () => {
    expect(normalizeDigits("992937001122")).toBe("+992937001122");
  });
});

describe("extractTypedPhone — стадия awaiting_phone", () => {
  it("номер с ведущим нулём приводится к местному формату, а не ломается", () => {
    expect(extractTypedPhone("0937001122")).toBe("+992937001122");
  });

  it("номер с ведущим нулём и разделителями посреди фразы", () => {
    expect(extractTypedPhone("мой номер 093 700 11 22, звоните вечером")).toBe("+992937001122");
  });

  it("номер без нуля продолжает работать как раньше", () => {
    expect(extractTypedPhone("937001122")).toBe("+992937001122");
  });
});
