import { describe, expect, it } from "vitest";
import { FALLBACK_USD_TO_TJS, convertToTjs, fromCents, toCents } from "@royal-home/shared";

import { toTjs } from "../src/lib/money.js";

/**
 * ОДНО ПРАВИЛО ПЕРЕВОДА В СОМОНИ — ОДНО МЕСТО.
 *
 * Тест сторожит не арифметику, а границу. До 22.09.2026 перевод суммы в сомони
 * был написан дважды под одним именем `toTjs`: на сервере — через целые сотые с
 * округлением до копейки, во фронте (`apps/web/src/lib/format.ts`) — простым
 * `n * курс`. Серверное округление сделано намеренно: без него 9.53 × 11.27
 * даёт 107.40310000000001, и этот хвост складывается, сравнивается и уезжает в
 * выгрузку. То есть на доске сделок сумма могла не сойтись с отчётом по тем же
 * деньгам.
 *
 * Тестов у фронта отсюда не видно, поэтому проверяем то, что видно: серверный
 * `toTjs` обязан быть тонкой обёрткой над общим `convertToTjs`. Пока это так,
 * разойтись двум сторонам не на чем — обе зовут одну функцию.
 *
 * Если кто-то снова напишет во фронте своё вычисление, тест не покраснеет. Но
 * он покраснеет на попытке вернуть своё вычисление НА СЕРВЕР, а комментарии в
 * обоих файлах называют причину — этого достаточно, чтобы правка не прошла
 * молча.
 */
describe("перевод в сомони: правило общее для сервера и фронта", () => {
  const RATE = 11.27;

  it("серверный toTjs считает ровно то же, что общий convertToTjs", () => {
    const cases: Array<[unknown, string]> = [
      [9.53, "USD"],
      [9.53, "TJS"],
      [0, "USD"],
      [1234.56, "USD"],
      [1234.56, "TJS"],
      ["1234.56", "USD"],
      [null, "USD"],
      [undefined, "TJS"],
      [Number.NaN, "USD"],
      [-15.005, "USD"],
    ];
    for (const [amount, currency] of cases) {
      expect(toTjs(amount, currency, { usdToTjs: RATE })).toBe(convertToTjs(amount, currency, RATE));
    }
  });

  it("хвост плавающей точки не выходит наружу — ровно две цифры после запятой", () => {
    // Тот самый пример из комментария в money.ts: без округления здесь было бы
    // 107.40310000000001.
    const value = convertToTjs(9.53, "USD", RATE);
    expect(value).toBe(107.4);
    expect(Number.isInteger(Math.round(value * 100))).toBe(true);
    expect(String(value)).not.toMatch(/\.\d{3,}/);
  });

  it("сумма не в долларах округляется до копейки, а не проходит как есть", () => {
    expect(convertToTjs(10.004, "TJS", RATE)).toBe(10);
    expect(convertToTjs(10.005, "TJS", RATE)).toBe(10.01);
  });

  it("нечисловое даёт ноль, а не NaN в отчёте", () => {
    expect(convertToTjs("не число", "USD", RATE)).toBe(0);
    expect(convertToTjs(null, "TJS", RATE)).toBe(0);
    expect(convertToTjs(Number.POSITIVE_INFINITY, "USD", RATE)).toBe(0);
  });

  it("запасной курс объявлен один раз и остаётся прежним", () => {
    // Значение проверяется не ради самого числа, а чтобы вторая копия константы
    // не завелась снова: расхождение курса между экраном и отчётом — это разные
    // деньги у директора и у агента.
    expect(FALLBACK_USD_TO_TJS).toBe(11);
  });

  it("сотые и обратно — без потерь на типичных суммах", () => {
    for (const v of [0, 1, 10.5, 1234.56, 99999.99]) {
      expect(fromCents(toCents(v))).toBe(v);
    }
  });
});
