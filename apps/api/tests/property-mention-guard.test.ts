import { describe, expect, it } from "vitest";

/**
 * КЛИЕНТ НАЗВАЛ НОМЕР ОБЪЕКТА («объект №112») — решение владельца 23.09.2026
 * (пункт 8 списка после публикаций: «код агента не надо, код объекта ставить
 * номер типа объект номе 112, а не 00112»).
 *
 * Здесь — только распознавание номера по словам клиента (без базы). Что номер
 * действительно уводит лид хозяину объекта, проверено на уровне лесенки в
 * tests/lead-own-property-priority.test.ts («Объект назван явно»); здесь
 * важно, что число НЕ путается с этажом, бюджетом, комнатами и микрорайоном —
 * они звучат почти в каждой реплике о квартире.
 */

const { extractMentionedPropertyNumber } = await import("../src/ai/propertyMentionGuard.js");

describe("извлечение номера объекта из слов клиента", () => {
  it.each([
    ["простое упоминание", "объект 112", "112"],
    ["со знаком №", "объект №112", "112"],
    ["словом «номер»", "объект номер 112", "112"],
    ["опечатка «обьект»", "обьект 112", "112"],
    ["без слова «объект», только №", "интересует №112", "112"],
    ["№ перед текстом", "№112 квартира, ещё доступна?", "112"],
    ["с падежным окончанием слова «объект»", "по объекту 112 расскажите подробнее", "112"],
  ])("%s (%s)", (_label, text, expected) => {
    expect(extractMentionedPropertyNumber(text)).toBe(expected);
  });

  it.each([
    ["количество комнат", "3 хона, 700 хазор"],
    ["этаж и микрорайон", "5 этаж, 82 мкр"],
    ["порядковая форма этажа", "3-й этаж, угловая"],
    ["голый бюджет", "бюджет 700000"],
    ["пустая строка", ""],
  ])("не путает с обычными числами разговора о квартире (%s)", (_label, text) => {
    expect(extractMentionedPropertyNumber(text)).toBeNull();
  });
});
