/**
 * МЁРТВЫЕ ПРАВИЛА СТРАЖЕЙ: КИРИЛЛИЦА И `\b` / `\w` (найдено 21.09.2026).
 *
 * В JavaScript `\w` — это `[A-Za-z0-9_]`, а `\b` — граница между таким символом и
 * любым другим, даже с флагом `u`. Поэтому `рус\b` не совпадает НИ С ЧЕМ, а
 * `улиц\w*\s+` не совпадает с «улица Варзоб»: `\w*` съедает ноль символов и
 * выражение требует пробел там, где стоит окончание.
 *
 * Ловушка задокументирована в CLAUDE.md, и 20.09 по ней вылечили семь правил в
 * стражах. Проверка кода 21.09 нашла ещё одиннадцать в девяти файлах — правила
 * выглядели написанными и не срабатывали ни на одном сообщении. Ни один тест
 * этого не показывал, потому что тесты писались на ту форму слова, которая в
 * выражение попадала.
 *
 * Этот файл закрывает класс целиком: каждый случай проверяется на ЖИВОЙ форме
 * слова, а не на основе без окончания. Границы брать из `ai/wordBoundary.ts`
 * (`BW`/`EW`/`TAIL`), а не `\b`/`\w`.
 */

describe("границы слова в кириллице: правила должны срабатывать на живых формах", () => {
  it("определитель таджикского текста видит характерные слова без особых букв", () => {
    // До правки выражение `/\b(ман|шумо|…)\b/` не совпадало ни с чем вовсе, и
    // таджикским признавался только текст с буквами ӯғқҳҷӣ.
    expect(looksTajik("ман хона мехоҳам")).toBe(true);
    expect(looksTajik("чанд сомони")).toBe(true);
    expect(looksTajik("барои шумо")).toBe(true);
    // Русский текст таджикским не становится.
    expect(looksTajik("хочу купить квартиру")).toBe(false);
    // Слово внутри другого слова не считается: иначе «команда» дала бы «ман».
    expect(looksTajik("наша команда работает")).toBe(false);
  });

  it("метка «кор» в объявлении читается как вакансия", () => {
    expect(isJobAdRef("кор")).toBe(true);
    expect(isJobAdRef("кор лозим")).toBe(true);
    expect(isJobAdRef("ҷои кор")).toBe(true);
    // Объявление про объект вакансией не становится.
    expect(isJobAdRef("2 хонагӣ Сино")).toBe(false);
  });

  it("накрутка просмотров и взаимной подписки распознаётся", () => {
    // Два признака накрутки в одном сообщении — этого достаточно без вложения.
    expect(detectSpam("взаимно подпишемся, поставь лайк")).not.toBeNull();
    // Чужой ролик плюс просьба про просмотры.
    expect(
      detectSpam("накинь просмотры пожалуйста", { sharedPost: true, ourPost: false })
    ).not.toBeNull();
    // ГЛАВНОЕ: живого клиента не задеть. «Просмотрел» — обычное слово, и одного
    // его мало даже вместе с чужой публикацией.
    expect(detectSpam("просмотрел ваши объявления, есть что-то в Сино?")).toBeNull();
    expect(
      detectSpam("посмотрите, такая квартира есть?", { sharedPost: true, ourPost: false })
    ).toBeNull();
  });

  it("вежливое «посмотрите, пожалуйста» с чужим объявлением — это клиент, а не накрутка", () => {
    // Человек переслал то, что нашёл, и просит посмотреть. Раньше связка
    // «пересылка + одно слово из словаря» глушила ответ полностью, и такой клиент
    // уходил молча.
    expect(detectSpam("бинед лутфан", { sharedPost: true, ourPost: false })).toBeNull();
    expect(
      detectSpam("дидани кун, ин хона ҳаст?", { sharedPost: true, ourPost: false })
    ).toBeNull();
    // А вот просьба посмотреть ВМЕСТЕ с просьбой подписаться — накрутка.
    expect(
      detectSpam("бинед лутфан ва обуна кунед", { sharedPost: true, ourPost: false })
    ).not.toBeNull();
    // Чужой ролик с прямой просьбой про лайк — накрутка, как и было.
    expect(detectSpam("поставь лайк", { sharedPost: true, ourPost: false })).not.toBeNull();
  });

  it("подпись «инстаграм» вместо имени не выдаёт канал сотруднику без права", () => {
    // clientNameFor скрывает подписи, выдающие канал. Латинские ловились, а
    // кириллические — нет, и «Клиент из телеграм» показывался как есть.
    expect(clientNameFor("инстаграм", false)).toBe(HIDDEN_ORIGIN_NAME);
    expect(clientNameFor("Клиент из телеграм", false)).toBe(HIDDEN_ORIGIN_NAME);
    expect(clientNameFor("instagram", false)).toBe(HIDDEN_ORIGIN_NAME);
    // Настоящее имя остаётся именем.
    expect(clientNameFor("Далер Джабборов", false)).toBe("Далер Джабборов");
  });

  it("продавец назвал комнатность, цену и район — бот не переспрашивает названное", () => {
    // Все три правила («комн», «евро», «сино») стояли мёртвыми, и бот переспрашивал
    // уже сказанное — ровно та жалоба, из-за которой модуль sellerIntake написан.
    expect(extractSellerFacts("2 комн").rooms).toBe(true);
    expect(extractSellerFacts("продаю, 2 комн.").rooms).toBe(true);
    expect(extractSellerFacts("50 000 евро").price).toBe(true);
    expect(extractSellerFacts("район Сино").district).toBe(true);
    expect(extractSellerFacts("ЖК Ватан").district).toBe(true);
    // Пустое сообщение фактов не даёт.
    expect(extractSellerFacts("здравствуйте")).toEqual({});
  });
});

/**
 * ВТОРОЙ ЗАХОД ПО ТОМУ ЖЕ КЛАССУ (22.09.2026).
 *
 * Сплошная проверка бота нашла ещё восемь правил той же природы — мёртвых либо,
 * наоборот, слишком широких. Дороже всех первое: с 21.09.2026 карточка, в которой
 * направление не подтверждено словами клиента, уходит в «Прочие обращения» мимо
 * агентов, а самые обычные русские фразы продавца («Моя квартира на продажу»,
 * «Продаётся квартира») не распознавались НИ ОДНОЙ формой.
 *
 * Каждая проверка ниже — на той форме слова, которой пишут живые люди, и на паре
 * к ней: правило обязано срабатывать там, где надо, и молчать там, где не надо.
 */
describe("направление сделки и стражи: живые формы слов", () => {
  it("русский продавец называет направление самыми обычными фразами", () => {
    expect(clientStatedDirection("Моя квартира на продажу")).toBe("sell");
    expect(clientStatedDirection("Квартира на продажу, 3 комнаты, Сино")).toBe("sell");
    expect(clientStatedDirection("Продаётся квартира")).toBe("sell");
    expect(clientStatedDirection("Продается квартира")).toBe("sell");
    expect(clientStatedDirection("Хочу выставить квартиру")).toBe("sell");
    expect(clientStatedDirection("Выставить на продажу свой дом")).toBe("sell");
  });

  it("покупатель остаётся покупателем", () => {
    expect(clientStatedDirection("Куплю квартиру в Сино")).toBe("buy");
    expect(clientStatedDirection("Ищу квартиру 2 комнаты")).toBe("buy");
    expect(clientStatedDirection("Мехоҳам хона харам")).toBe("buy");
    expect(clientStatedDirection("Харидор ҳастам")).toBe("buy");
  });

  it("«хариду фурӯш» — название нашего занятия, а не направление клиента", () => {
    // Оборот зажигал ОБА сигнала, а два сигнала значат «не назвал ничего».
    expect(clientStatedDirection("Хариду фурӯши хона")).toBeNull();
    // «Харидор» говорит и продавец: «найдите покупателя» — это продажа.
    expect(clientStatedDirection("Хонаи фурӯшӣ дорам, харидор ёбед")).toBe("sell");
  });

  /**
   * ЖИВОЙ ГОЛОС ПО-000431, 22.09.2026: «Харидор» узнан выше, но продавец сказал
   * УСЕЧЁННОЕ «харидо» (без конечного «р») — прежнее исключение `(?!ор)` его не
   * ловило: «харид» + «о» + конец слова проходило мимо проверки на «ор» и
   * засчитывалось как «клиент сам хочет купить», хотя рядом стояло однозначное
   * «фуруши» (для продажи).
   */
  it("«харидо» (усечённое «харидор») — тоже покупатель-третье лицо, а не заявление о покупке", () => {
    expect(
      clientStatedDirection(
        "Салом алекум хонаи фуруши дорем коробка, ягон харидо дошба бошен ёрдам кунен реклама кунен"
      )
    ).toBe("sell");
    // Обычные формы покупки по-прежнему покупка.
    expect(clientStatedDirection("Хонаро харидам, шукр")).toBe("buy");
    expect(clientStatedDirection("Хонаро харидан мехоҳам")).toBe("buy");
  });

  /**
   * СИММЕТРИЧНО (правило «нашёл баг — почини весь класс»): «фурушанда»
   * (продавец) и «фурӯшгоҳ» (магазин) — тоже существительные о действующем
   * лице/месте, а не заявление клиента о продаже.
   */
  it("«фурушанда»/«фурӯшгоҳ» сами по себе не заявляют направление", () => {
    expect(clientStatedDirection("Ман фурушанда ҳастам, харидор лозим аст")).toBeNull();
    expect(clientStatedDirection("Дар фурӯшгоҳ кор мекунам")).toBeNull();
  });

  it("направление по-прежнему НЕ выдумывается там, где клиент его не называл", () => {
    expect(clientStatedDirection("Хонаи 2-хонага, 51 метр, ошёнаи 1")).toBeNull();
    expect(clientStatedDirection("Салом, кор ҳаст?")).toBeNull();
    // Оба направления сразу — решать за человека не дело кода.
    expect(clientStatedDirection("Куплю квартиру, чтобы потом продать старую")).toBeNull();
  });

  it("«оби гарм» — это горячая вода, а не райцентр Гарм", () => {
    expect(detectOutsideCoverage("Ремонташ нав, оби гарм ҳаст, 2-хонага")).toBeNull();
    // Само место по-прежнему узнаётся.
    expect(detectOutsideCoverage("Ман дар Гарм зиндагӣ мекунам")?.place.toLowerCase()).toBe("гарм");
    expect(detectOutsideCoverage("Хона дар Рашт")?.place.toLowerCase()).toBe("рашт");
  });

  it("«сто тысяч» — это сумма, а не автосервис СТО", () => {
    expect(detectOutOfScopeAsset("Куплю квартиру за сто тысяч долларов")).toBeNull();
    expect(detectOutOfScopeAsset("Продаю СТО с оборудованием")?.asset.toLowerCase()).toBe("сто");
  });

  it("«евро» в цене не засчитывается как состояние ремонта", () => {
    expect(extractSellerFacts("Нархаш 50 000 евро").condition).toBeUndefined();
    expect(extractSellerFacts("Нархаш 50 000 евро").price).toBe(true);
    // Сам ремонт по-прежнему узнаётся, в том числе таджикской формой.
    expect(extractSellerFacts("евроремонт").condition).toBe(true);
    expect(extractSellerFacts("евро таъмир шудааст").condition).toBe(true);
  });

  it("«уехал 910001044» — это номер, а не сумма в условных единицах", () => {
    // `у.е.` без правой границы совпадало с началом «уехал», и номер рядом
    // переставал разбираться строгим путём.
    // Номер приводится к международному виду — важно, что он вообще найден.
    expect(extractVolunteeredPhone("уехал 910001044")).toBe("+992910001044");
    // «у.е.» как единица по-прежнему читается денежным окружением.
    expect(extractVolunteeredPhone("отдам за 30 у.е. 910001044")).toBeNull();
  });
});

/**
 * ВТОРОЙ ЗАХОД, 22.09.2026 — тот же класс, ещё девять правил в шести файлах.
 *
 * Найдено сплошным чтением кода по просьбе владельца («ищи ошибки как дотошный
 * тестировщик»). Каждое правило ниже было написано и не срабатывало ни на одной
 * живой форме слова; проверено прогоном до правки. Девятое — зеркальный случай:
 * `\W` означает «всё, кроме латиницы», то есть ВСЮ кириллицу, и правило,
 * наоборот, срабатывало слишком широко.
 */
describe("границы слова в кириллице: второй заход 22.09.2026", () => {
  it("«планирую продать» — это продавец, а не реклама площадки", () => {
    // Было `планиру\w+`: `\w+` требует латинскую букву после кириллической
    // основы, значит альтернатива была мертва целиком, а продавец рисковал
    // получить молчание без карточки.
    expect(detectAgencyPitch("Планирую продать квартиру через ваше агентство")).toBeNull();
    expect(detectAgencyPitch("планирую выставить дом")).toBeNull();
  });

  it("«квартираи мекобам» — таджикский покупатель, а не реклама", () => {
    expect(detectAgencyPitch("Салом, квартираи мекобам дар маркази шахр")).toBeNull();
  });

  it("«регистрация на сайте» читается как предложение площадки", () => {
    // Было `регистрац\w* на (сайт|платформ)` — совпадала только форма без
    // окончания, «регистрац на сайт», которой в живом тексте не бывает.
    const v = detectAgencyPitch(
      "Здравствуйте! Приглашаем агентства: регистрация на сайте бесплатная, тариф для агентств"
    );
    expect(v).not.toBeNull();
  });

  it("«ваше объявление» читается как обращение к агентству", () => {
    const v = detectAgencyPitch(
      "Для риелторов: разместите ваши объявления у нас, подписка на месяц и премиум-доступ"
    );
    expect(v).not.toBeNull();
  });

  it("«свою квартиру продаю» — это продавец", () => {
    // Было `свою\s+кварт\w*\s+прода` — с окончанием «квартиру» не совпадало.
    expect(clientStatedDirection("свою квартиру продаю срочно")).toBe("sell");
    expect(clientStatedDirection("моя квартира на продажу")).toBe("sell");
  });

  it("«кондиционеры монтаж» читается как предложение услуги", () => {
    // Было `кондиционер\w*\s+(насб|монтаж|устанавлива)`.
    // «бригада» — второй признак: профессия одна, без него, вердикта не даёт
    // намеренно (см. doc-comment у TRADE).
    const v = detectServiceOffer("Кондиционеры монтаж, бригада опытная, работаем по городу");
    expect(v).not.toBeNull();
  });

  it("«номатон чи?» читается как вопрос бота об имени", () => {
    // Было `чи\b` — после кириллической «и» границы \b не существует вовсе.
    expect(ASKED_FOR_NAME.test("Ростӣ, номатон чи?")).toBe(true);
    // Форма с ӣ работала и раньше — не должна сломаться.
    expect(ASKED_FOR_NAME.test("Номатон чӣ?")).toBe(true);
  });

  it("«договорились, в 5» доходит до разбора договорённости о показе", () => {
    // Было `\bв\s?\d{1,2}\b` — перед кириллической «в» границы \b не бывает,
    // и реплика без слова «завтра» и без времени с двоеточием отсеивалась.
    expect(SHOWING_HINT_RE.test("Договорились, в 5")).toBe(true);
    expect(SHOWING_HINT_RE.test("подъеду в 17")).toBe(true);
    // «Ливан» и «Иван» не должны давать ложного «в» с числом рядом.
    expect(SHOWING_HINT_RE.test("Иванов 12")).toBe(false);
  });

  it("«ok, а сколько стоит» — это вопрос клиента, а не вежливость", () => {
    // Было `ok\W*` в списке вежливостей: `\W` — это вся кириллица, поэтому
    // вопрос целиком признавался вежливостью и выпадал из обучения манере.
    expect(isUsableClientQuestion("ok, а сколько стоит")).toBe(true);
    // Голая вежливость по-прежнему отсеивается.
    expect(isUsableClientQuestion("ok")).toBe(false);
    expect(isUsableClientQuestion("рахмат!")).toBe(false);
  });
});
