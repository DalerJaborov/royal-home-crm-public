/**
 * ОДНА БАЗА НА КАЖДЫЙ ПРОЦЕСС VITEST (12.09.2026).
 *
 * ЗАЧЕМ. Прогон тестов API был последовательным по своей сути: 484 файла в
 * ОДНОМ процессе, `fileParallelism: false`. Не от лени — все файлы делили одну
 * базу, а часть сценариев глобальна: распределение лидов выбирает агента среди
 * ВСЕХ активных, отказной поток передаёт клиента сильнейшему, лимиты читают
 * singleton-строку настроек, уборка задевает чужие внешние ключи. Стоило
 * пустить файлы параллельно — и агент соседнего файла перехватывал лид, а тест
 * падал «через раз». Замер 12.09 в CI: 658 секунд весь шаг, из них 520 именно
 * тесты; замер на машине владельца — 810 секунд.
 *
 * Ни второй раннер, ни лишние ядра тут не помогали: узкое место было не в
 * железе, а в том, что прогон нельзя было распараллелить.
 *
 * ЧТО СДЕЛАНО. Каждый процесс vitest получает СВОЮ базу. Глобальные выборки
 * снова честны — «все активные агенты» это все агенты одного процесса, — и
 * прогон можно разложить на несколько процессов, ничего в тестах не переписывая.
 *
 * Базы делаются не миграциями (минуты каждая), а копией шаблона:
 * `CREATE DATABASE ... TEMPLATE <база из DATABASE_URL>` копирует файлы на
 * уровне каталога за секунду. Приём взят из `scripts/agent-stand.mjs`, где он
 * уже экономит агентам по три минуты на стенд.
 *
 * ПОЧЕМУ ШАБЛОН — ИМЕННО БАЗА ИЗ `DATABASE_URL`, А НЕ СВЕЖИЕ МИГРАЦИИ. Та база
 * уже приведена в нужное состояние тем, кто запускает прогон: в CI это шаг
 * `prisma migrate deploy`, локально — `scripts/agent-stand.mjs up`. Повторять
 * миграции здесь значит завести ВТОРОЙ источник правды о состоянии схемы,
 * который однажды разъедется с первым и даст «у меня зелено, в CI красно».
 * Сама база-шаблон при этом остаётся нетронутой: тесты в неё не пишут, они
 * работают только со своими копиями — это же и делает прогон безопасным для
 * базы разработчика.
 *
 * ГДЕ ЖИВЁТ САМА ПАРАЛЛЕЛЬНОСТЬ — В `runParallel.ts`, А НЕ ЗДЕСЬ, И ЭТО
 * ИЗМЕРЕННОЕ РЕШЕНИЕ. Первым делом был испробован очевидный путь:
 * `fileParallelism: true` и несколько процессов внутри одного vitest. Он
 * ОКАЗАЛСЯ МЕДЛЕННЕЕ последовательного. Причина в том, что при `isolate: true`
 * (а без неё нельзя — файлы делят замоканные модули, проверено 12.08.2026)
 * vitest отдаёт каждый файл ОТДЕЛЬНОЙ задачей, а tinypool убивает и
 * пересоздаёт процесс после каждой задачи: 484 запуска Node и 484 холодных
 * старта своей среды вместо одного. Замер 12.09 на машине владельца: 17 файлов
 * за 2 минуты (≈7 с на файл) против 1,67 с на файл у последовательного
 * прогона — то есть четырёхкратная параллельность ушла целиком на
 * пересоздание процессов и дала ноль.
 *
 * Поэтому параллельность вынесена НАРУЖУ: `runParallel.ts` поднимает N
 * независимых процессов vitest, каждый со своей долей файлов (`--shard`), с
 * `singleFork` (все свои файлы — в одном процессе, ни одного пересоздания) и
 * со своей базой. Внутри процесса всё ровно как было; параллельность только
 * между процессами.
 *
 * ВЫКЛЮЧАТЕЛЬ. `VITEST_DB_PARALLEL=0` возвращает прежнее поведение целиком:
 * один процесс, база прямо из `DATABASE_URL`, без копий. Это путь отступления
 * и способ воспроизвести старое падение один в один.
 */
import { availableParallelism, freemem } from "node:os";

/** `true` в CI (GitHub Actions выставляет `CI=true`). */
export const isCI = process.env.CI === "true" || process.env.CI === "1";

/**
 * Своя база у процесса включена по умолчанию; `VITEST_DB_PARALLEL=0` (или
 * `false`) возвращает работу прямо с базой из `DATABASE_URL`, как было.
 */
export function isParallelDbEnabled(): boolean {
  const raw = process.env.VITEST_DB_PARALLEL;
  return !(raw === "0" || raw === "false");
}

/**
 * Сколько процессов vitest поднимает `runParallel.ts`, столько и баз.
 *
 * Умолчания подобраны под две реальные машины:
 *  - CI: раннер на VPS урезан до 2 ядер из 4 и 3 ГБ памяти (см. ci.yml). Тесты
 *    в основном ЖДУТ базу, а не считают, поэтому процессов имеет смысл больше,
 *    чем ядер, — но не настолько, чтобы упереться в память.
 *  - машина владельца: 6 ядер, 12 потоков. Половина потоков — потолок из
 *    правила «не душить машину»: рядом живут dev-серверы и они первыми падают
 *    при перегрузке.
 *  - облачная сессия claude.ai: 4 ядра, 15 ГБ. «Половина ядер» давала 2
 *    процесса и полный прогон ~1030 с; 4 процесса — ~700 с, ноль падений на
 *    двух полных прогонах (24.09.2026). Тесты ждут базу, а не считают, поэтому
 *    4 процесса на 4 ядрах не душат машину. Память: 4 × PROVEN_CAP_MB = 6 ГБ.
 *    На машине владельца ничего не меняется: там и раньше выходило 4.
 *  - СВОБОДНАЯ ПАМЯТЬ (25.09.2026): на машине владельца (16 ГБ, рядом
 *    несколько сессий Claude Code и два dev-сервера) 4 процесса не влезли —
 *    два воркера убиты по нехватке памяти при зелёных тестах. Поэтому число
 *    ещё и делится по свободной памяти в момент запуска: процессу нужно
 *    ~1,5 ГБ (PER_WORKER_BYTES — потолок кучи плюс нативная память Prisma и
 *    сам vitest). Не хватает даже на один — всё равно один: медленно, но
 *    прогон идёт, а не отказывается.
 *
 * Явный `VITEST_DB_WORKERS` главнее всего этого.
 */
export const PER_WORKER_BYTES = 1.5 * 1024 ** 3;
const MAX_WORKERS = 4;

export type WorkerPlan = { count: number; reason: string };

const gb = (bytes: number) => (bytes / 1024 ** 3).toFixed(1).replace(".", ",");

/** Чистая арифметика — отдельно от ОС, чтобы её можно было проверить тестом. */
export function planWorkers(input: { explicit?: string; cpus: number; freeBytes: number }): WorkerPlan {
  const explicit = Number(input.explicit);
  if (input.explicit !== undefined && input.explicit !== "" && Number.isInteger(explicit) && explicit >= 1) {
    return { count: explicit, reason: `задано VITEST_DB_WORKERS=${explicit}` };
  }
  const cpus = Math.max(1, input.cpus);
  const byMemory = Math.max(1, Math.floor(input.freeBytes / PER_WORKER_BYTES));
  const count = Math.max(1, Math.min(MAX_WORKERS, cpus, byMemory));
  const limits = [
    count === MAX_WORKERS ? `потолок ${MAX_WORKERS}` : null,
    count === cpus ? "ядра" : null,
    count === byMemory ? "память" : null,
  ].filter(Boolean);
  return {
    count,
    reason: `ядер ${cpus}, свободно ${gb(input.freeBytes)} ГБ (по ${gb(PER_WORKER_BYTES)} ГБ на процесс) — ограничило: ${limits.join(", ")}`,
  };
}

export function resolveWorkerPlan(): WorkerPlan {
  return planWorkers({
    explicit: process.env.VITEST_DB_WORKERS,
    cpus: availableParallelism(),
    freeBytes: freemem(),
  });
}

export function resolveWorkerCount(): number {
  return resolveWorkerPlan().count;
}

/**
 * Потолок кучи, проверенный замером 11.09.2026 на полном прогоне в один
 * процесс: с ним 465 файлов доходят до конца, с 2048 МБ прогон обрывался на
 * 174, без потолка — на 127. Выше не поднимаем нигде.
 */
const PROVEN_CAP_MB = 1536;

/**
 * Потолок кучи НА ОДИН процесс, в мегабайтах.
 *
 * Смысл потолка прежний (см. историю в `vitest.config.ts`): без него V8 идёт к
 * своим ~4 ГБ, и процесс убивают снаружи молча — прогон обрывается на середине
 * с кодом 1 при нуле упавших тестов. С потолком то же самое становится честным
 * «JavaScript heap out of memory» с именем файла.
 *
 * НИЗКИЙ потолок здесь безопаснее высокого, а не наоборот: замеры 11.09.2026
 * дали обратную зависимость — без потолка прогон обрывался на 127 файле из 465,
 * с 2048 МБ на 174, с 1536 МБ доходил до конца. Причина в нативной памяти
 * движка Prisma: она освобождается только когда сборщик доберётся до
 * JS-обёртки, а чем ниже потолок, тем чаще он это делает.
 *
 * Отсюда правило: потолок ОДНОГО процесса = проверенные 1536 МБ, делённые на
 * число процессов. Доказанная точка одна (484 файла ↔ 1536 МБ), и она задаёт
 * не абсолютное число, а соотношение «сколько файлов процесс держит»: при
 * четырёх процессах файлов у каждого вчетверо меньше, значит и потолок ему
 * нужен вчетверо ниже. Один процесс на все файлы (`test:seq`, прямой
 * `npx vitest run`) получает ровно прежние 1536.
 *
 * Нижняя граница 512 МБ — чтобы честное «heap out of memory» не наступало
 * раньше настоящей нехватки.
 *
 * Что бывает, если дать больше: 12.09.2026 при четырёх процессах по 1024 МБ
 * шард умер на 26 файле из 121 с «Worker exited unexpectedly» — без имени
 * файла, без записи в журнал, процесс просто убили снаружи. Формула выше даёт
 * в том же случае 384→512 МБ, и это не скупость, а та самая обратная
 * зависимость: чем ниже потолок, тем чаще сборщик добирается до нативной
 * памяти Prisma.
 *
 * `VITEST_HEAP_MB` задаёт потолок одного процесса напрямую, в обход всей этой
 * арифметики.
 */
export function resolveHeapMbPerWorker(workers: number): number {
  const explicit = Number(process.env.VITEST_HEAP_MB);
  if (Number.isInteger(explicit) && explicit > 0) return explicit;
  /**
   * НИЖНЯЯ ГРАНИЦА 768, А НЕ 512 (12.09.2026). На 512 третий из четырёх
   * процессов умер на 44 файле из 120 с безымянным «Worker exited
   * unexpectedly»: делить бюджет строго пропорционально нельзя, потому что
   * нативная память клиента Prisma от числа файлов почти не зависит, а
   * освобождается только после сборщика. 768 доказано проходит весь список.
   */
  return Math.max(768, Math.floor(PROVEN_CAP_MB / Math.max(1, workers)));
}

type ParsedUrl = { url: URL; database: string };

function parse(rawUrl: string): ParsedUrl {
  const url = new URL(rawUrl);
  const database = decodeURIComponent(url.pathname.replace(/^\//, ""));
  if (!database) throw new Error(`DATABASE_URL без имени базы: ${redact(rawUrl)}`);
  return { url, database };
}

/** Адрес в журнале и в ошибках — без пароля. */
export function redact(rawUrl: string): string {
  try {
    const url = new URL(rawUrl);
    if (url.password) url.password = "***";
    return url.toString();
  } catch {
    return "<неразбираемый DATABASE_URL>";
  }
}

/** Имя базы из `DATABASE_URL` — она же шаблон для копий. */
export function templateDatabaseName(rawUrl: string): string {
  return parse(rawUrl).database;
}

/**
 * Имя базы процесса. 63 символа — предел идентификатора в Postgres, поэтому
 * длинное имя шаблона обрезается: суффикс важнее хвоста имени.
 */
export function workerDatabaseName(rawUrl: string, index: number): string {
  const suffix = `_w${index}`;
  const base = parse(rawUrl).database;
  return base.slice(0, 63 - suffix.length) + suffix;
}

/**
 * `DATABASE_URL` процесса: тот же сервер и те же параметры, другая база.
 *
 * ПЛЮС ЯВНЫЙ ПОТОЛОК ПУЛА, И ЭТО НЕ УКРАШЕНИЕ. Prisma по умолчанию берёт
 * `ядра * 2 + 1` соединений на клиента: на машине владельца (12 потоков) это
 * 25. Пока процесс был один, 25 из ста укладывались с запасом. Четыре процесса
 * это ровно 100 — то есть `max_connections` Postgres, и первый же лишний
 * коннект (а `src/db.ts` берёт ВТОРОЙ на чтение «до» при правке статуса) даёт
 * «too many clients already» в случайном файле. Такое падение выглядит как
 * поломка продукта и уводит поиск совсем не туда.
 *
 * Десяти хватает: внутри процесса файлы идут по одному, параллелизм живёт
 * между процессами. Уже заданный в адресе `connection_limit` уважаем — значит
 * его поставили осознанно.
 */
export function workerDatabaseUrl(rawUrl: string, index: number): string {
  const { url } = parse(rawUrl);
  url.pathname = `/${encodeURIComponent(workerDatabaseName(rawUrl, index))}`;
  if (!url.searchParams.has("connection_limit")) {
    url.searchParams.set("connection_limit", process.env.VITEST_DB_CONNECTION_LIMIT ?? "10");
  }
  return url.toString();
}

/**
 * Служебное подключение для DDL. `CREATE DATABASE` нельзя выполнить, будучи
 * подключённым к создаваемой или копируемой базе, поэтому все команды идут
 * через системную `postgres`.
 */
export function maintenanceUrl(rawUrl: string): string {
  const { url } = parse(rawUrl);
  url.pathname = "/postgres";
  // `?schema=public` и прочие параметры Prisma к системной базе отношения не
  // имеют и только мешают: чистим строку запроса целиком.
  url.search = "";
  return url.toString();
}

/** Кавычки для идентификатора: имя базы приходит из окружения, не из кода. */
export function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

/**
 * Номер процесса. Его выдаёт `runParallel.ts` через `VITEST_DB_INDEX`; при
 * прямом `npx vitest run` переменной нет и процесс работает с базой №1.
 */
export function currentWorkerIndex(): number {
  const n = Number(process.env.VITEST_DB_INDEX);
  return Number.isInteger(n) && n >= 1 ? n : 1;
}
