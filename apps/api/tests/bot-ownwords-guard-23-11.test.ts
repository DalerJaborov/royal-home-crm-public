import { describe, expect, it } from "vitest";
import { checkComposedReply, composeOperatorReply } from "../src/ai/operator/compose.js";
import type { LeadOnlyIntentModel } from "../src/ai/leadOnlyIntent.js";

/**
 * «Бот пишет своими словами» — проверка ответа модели (ai/operator/compose.ts::checkComposedReply). Случаи — из прогона 23.11.2026
 * на 47 живых переписках прода (тестовый ключ, без отправки): ответы модели дословно, слова клиента сокращены, номеров нет.
 */

const ASK_ROLE_RU = "Вы хотите купить или продать недвижимость?";
const OFFER_CALL_TG = "Инро аниқ агенти мо мегӯяд. Агар хоҳед, агенти мо занг мезанад, ҳамаашро мегӯяд ва нишон медиҳад.";

describe("плохие ответы модели, которые прежняя проверка пропускала", () => {
  it("«не сможем помочь» вместо вопроса о роли: шаг потерян, выдуман отказ", () => {
    // Клиент: «У меня нет недвижимости».
    expect(checkComposedReply("Понятно, в таком случае мы не сможем вам помочь.", ASK_ROLE_RU, "ru")).toBe("question_dropped");
  });

  it("«Поняла вас… обращайтесь» вместо вопроса о роли и в женском роде", () => {
    // Клиент: «Не. Рахмат».
    expect(checkComposedReply("Поняла вас, спасибо. Если передумаете, обращайтесь.", ASK_ROLE_RU, "ru")).toBe("question_dropped");
  });

  it("предложение звонка («агар хоҳед») превращено в обещание звонка без номера и без заявки", () => {
    // Instagram, номера нет: «...нохияй фирдавси кадом тараф».
    expect(checkComposedReply("Ваалайкум ассалом. Маълумоти дақиқро агенти мо ба шумо мегӯяд. Агент занг зада, ҳамаашро шарҳ медиҳад ва нишон медиҳад.",
      `Ваалайкум ассалом! Ҷои дақиқашро агенти мо мегӯяд. Агар хоҳед, агенти мо занг мезанад, ҳамаашро мегӯяд ва нишон медиҳад.`, "tg")).toBe("condition");
    // WhatsApp: «нархои хона чанд квадраташ».
    expect(checkComposedReply("Инро агенти мо дақиқ мегӯяд. Агент занг зада, ҳамаашро мефаҳмонад ва нишон медиҳад.", OFFER_CALL_TG, "tg")).toBe("condition");
  });

  it("новое действие агента «меомӯзад» (изучит) и обещание звонка", () => {
    // Клиент прислал ссылку на чужой ролик.
    const reply = "Ин маълумотро агенти мо меомӯзад. Ба шумо занг мезанад ва ҳамаашро шарҳ медиҳад.";
    expect(checkComposedReply(reply, OFFER_CALL_TG, "tg")).not.toBeNull();
    expect(checkComposedReply("Ин маълумотро агенти мо меомӯзад. Агар хоҳед, занг мезанад.", OFFER_CALL_TG, "tg")).toBe("promise");
  });

  it("второй прогон: просьба номера пропала, аренда, приезд агента", () => {
    // Instagram, номера нет: «Я не в Таджикистане».
    expect(checkComposedReply("Эту информацию сообщит агент. Если хотите, он позвонит и все подробно расскажет.",
      "Это точно скажет агент. Напишите, пожалуйста, ваш номер телефона, агент позвонит, всё подробно расскажет и покажет.", "ru")).toBe("phone_ask_dropped");
    expect(checkComposedReply("Ҷои дақиқашро агенти мо мегӯяд. Агар хоҳед, агенти мо рақаматонро гирифта, занг мезанад ва ҳамаашро мефаҳмонад.",
      "Ҷои дақиқашро агенти мо мегӯяд. Рақами телефонатонро нависед, агент занг зада, ҳамаашро мегӯяд ва нишон медиҳад.", "tg")).toBe("phone_ask_dropped");
    expect(checkComposedReply("Ҷои дақиқашро агенти мо мегӯяд. Рақаматонро фиристед, агент занг зада ҳамаашро нишон медиҳад.",
      "Ҷои дақиқашро агенти мо мегӯяд. Рақами телефонатонро нависед, агент занг зада, ҳамаашро мегӯяд ва нишон медиҳад.", "tg")).toBeNull();
    // «Дом на ... 11 этаж 240кв».
    expect(checkComposedReply("Уточните, пожалуйста, вы хотите продать этот дом или сдать его в аренду?",
      "Подскажите, пожалуйста: вы покупаете или продаёте?", "ru")).toBe("topic");
    expect(checkComposedReply("Ташаккур, акс ва видеоро агент худаш омада мегирад.", "Ташаккур, акс ва видеоро агент худаш мегирад.", "tg")).toBe("promise");
  });

  it("отказ и женский род ловятся и сами по себе", () => {
    expect(checkComposedReply("Передал агенту, к сожалению, это не наш объект.", "Передал агенту.", "ru")).toBe("refusal");
    expect(checkComposedReply("Мо наметавонем ёрӣ диҳем.", "Ба агент расондам.", "tg")).toBe("refusal");
    expect(checkComposedReply("Поняла, передаю агенту.", "Передаю агенту.", "ru")).toBe("persona");
    // Отказ, который есть в готовой фразе (аренда), — можно.
    expect(checkComposedReply("Мо танҳо бо хариду фурӯш машғулем, бо иҷора кор намекунем.", "Мо бо иҷора кор намекунем, танҳо хариду фурӯш.", "tg")).toBeNull();
  });

  it("не длиннее двух предложений (или готовой фразы с приветствием)", () => {
    expect(checkComposedReply("Ваш вопрос передал агенту. Он уже в курсе дела. Спасибо вам за обращение.", "Передал агенту.", "ru")).toBe("sentences");
    expect(checkComposedReply("Спасибо! Ваш вопрос передал агенту. Он уже в курсе дела.", "Передал агенту.", "ru")).toBeNull();
    expect(checkComposedReply("Ваалейкум ассалом. Поможем с продажей, комиссия 2%. Расскажите, что продаёте и в каком районе.",
      "Ваалейкум ассалом! Поможем продать, комиссия агентства 2%. Напишите, пожалуйста, что продаёте и в каком районе, и расскажем подробнее.", "ru")).toBeNull();
  });

  it("дословный повтор своей прошлой реплики в этой переписке не уходит", () => {
    const said = "Благодарю за информацию. Подскажите, вы планируете покупку или продажу недвижимости?";
    expect(checkComposedReply(said, "Спасибо, получил. Вы хотите купить или продать недвижимость?", "ru", [said])).toBe("repeat");
    expect(checkComposedReply(said, "Спасибо, получил. Вы хотите купить или продать недвижимость?", "ru", ["Здравствуйте!"])).toBeNull();
  });
});

describe("годные ответы, которые прежняя проверка отбрасывала (ложные срабатывания)", () => {
  it("«Пришлите номер» — просьба к клиенту, а не обещание «пришлём»", () => {
    expect(checkComposedReply("Пришлите, пожалуйста, ваш номер телефона. Наш специалист свяжется с вами для оценки и обсуждения всех деталей.",
      "Напишите, пожалуйста, ваш номер телефона, агент позвонит, оценит и всё обсудит.", "ru")).toBeNull();
    expect(checkComposedReply("Мы пришлём вам подборку.", "Передал агенту.", "ru")).not.toBeNull();
  });

  it("«бо Шумо» с большой буквы — вежливость, а не новое имя", () => {
    expect(checkComposedReply("Мо дар фурӯши хона кӯмак мекунем, комиссияи агентӣ 2% аст. Маълумотро ба агент мерасонам ва ӯ ба зудӣ бо Шумо тамос мегирад.",
      "Дар фурӯш кӯмак мекунем, комиссияи агентӣ 2%. Ташаккур, ба агент мерасонам, ӯ ба зудӣ занг мезанад, то он вақт метавонед дар бораи хона гӯед: ноҳия, чанд ҳуҷра ва нарх.",
      "tg")).toBeNull();
    expect(checkComposedReply("Передал агенту Фарходу.", "Передал агенту.", "ru")).toBe("name");
  });

  it("«нархи» при «нарх» в готовой фразе — то же понятие", () => {
    expect(checkComposedReply("Дар фурӯш ёрӣ медиҳем, комиссияи агентӣ 2%. Ба агент мерасонам, ӯ зуд тамос мегирад, то он вақт метавонед дар бораи ноҳия, шумораи ҳуҷраҳо ва нархи хона нависед.",
      "Дар фурӯш кӯмак мекунем, комиссияи агентӣ 2%. Ташаккур, ба агент мерасонам, ӯ ба зудӣ занг мезанад, то он вақт метавонед дар бораи хона гӯед: ноҳия, чанд ҳуҷра ва нарх.",
      "tg")).toBeNull();
  });

  it("«показать» при «покажет» в готовой фразе; «может позвонить» сохраняет условие", () => {
    expect(checkComposedReply("Агент может позвонить вам и всё подробно рассказать и показать. Это самый точный способ получить информацию.",
      "Это точно скажет агент. Если хотите, агент позвонит, всё подробно расскажет и покажет.", "ru")).toBeNull();    expect(checkComposedReply("Агент назовет вам точный адрес. При необходимости он свяжется с вами и подробно все расскажет.",
      "Здравствуйте! Точное место расскажет агент. Если хотите, агент позвонит, всё подробно расскажет и покажет.", "ru")).toBeNull();
  });
});

describe("compose отдаёт прошлые реплики бота в проверку", () => {
  it("модель повторила прошлую реплику дословно — уходит готовая фраза", async () => {
    const said = "Благодарю за информацию. Подскажите, вы планируете покупку или продажу недвижимости?";
    const model: LeadOnlyIntentModel = async () => ({ reply: said });
    const result = await composeOperatorReply({ steps: [{ key: "media_received", vars: {}, variant: 0 }],
      template: "Спасибо, получил. Вы хотите купить или продать недвижимость?", language: "ru", current: "",
      recent: [{ role: "user", text: "[вложение]" }, { role: "assistant", text: said }], model });
    expect(result).toMatchObject({ source: "template", rejected: "repeat" });
  });
});
