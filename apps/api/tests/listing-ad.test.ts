/**
 * Частное объявление под нашим постом (24.09.2026, жалоба владельца со снимком
 * из Instagram). Отсечка скрывает комментарий без модели — поэтому здесь важнее
 * всего вторая половина: кого она НЕ задевает. Ложное срабатывание прячет живого
 * покупателя, и он уходит молча.
 */
describe("detectListingAd — узнаёт объявление", () => {
  it("живой случай saf8308: без глагола «продаю», таджикский, «58квадрат», «Нарх 580. Хазор сомон»", () => {
    const text =
      "Хона дорем да Маладёжний Орентир Цирк пеши магазини дастрас Хона каробка перегародкош кардаги то под обой " +
      "корхои электрикиш мантажш тамом шидаги хаст ичозати ремонт зиндаги дорад мардум 2 сол шид зиндаги доранд " +
      "Хона 58квадрат мебощад.  2 тиреза ва  хардуи хонахош балкон дорад да 15 этаж доми 19 этажа. Нарх 580. " +
      "Хазор сомон номер 980001010 занг занед ватсапам хаст нависен .....";
    const verdict = detectListingAd(text);
    expect(verdict?.phones).toEqual(["+992980001010"]);
    expect(verdict?.reason).toContain("цена");
  });

  it.each([
    "Продаю 2-комнатную квартиру в Сино, 60 м2, цена 55000$, звоните +992 918 12 34 56",
    "Мефурӯшам хонаи 3 хонагӣ, 9 ошёна, нархаш 700 ҳазор сомонӣ. Тел 900112233",
    "Мефурушам хонаи 3 хонаги, 9 ошена, нархаш 700 хазор. Тел 900112233",
    "Сдаю квартиру 2 комнаты, 3000 сомони в месяц, 918123456",
  ])("%s", (text) => {
    expect(detectListingAd(text)).not.toBeNull();
  });
});

describe("detectListingAd — не задевает живых людей", () => {
  it.each([
    // Вопрос про НАШ объект с номером — самый дорогой промах.
    "Нархаш чанд? 900123456 занг занед",
    "2 хонагӣ дар 10 этаж? 900123456",
    // Покупатель с бюджетом и номером — похож по всем признакам, кроме глагола.
    "Нужна двушка до 500 тысяч, звоните 918123456",
    "Хона лозим 2 хонагӣ то 400 ҳазор, 918123456",
    "Мехарам хона 60 квадрат то 500 хазор сомон, 918123456",
    // Продавец спрашивает НАС — ему отвечают, а не прячут.
    "Хочу продать свою квартиру через вас, как условия? 918123456",
    // Объявление без номера решает модель: звонить некуда, прятать кодом незачем.
    "Продаю квартиру 60 м2, 15 этаж, цена 55000$",
    "Класс! 🔥",
  ])("%s", (text) => {
    expect(detectListingAd(text)).toBeNull();
  });
});

/**
 * Слова-признаки трёх случаев владельца (24.09.2026): мат удалить, агентство
 * удалить, собственнику написать. Ошибка в любую сторону дорогая: удалённый
 * собственник — потерянный продавец, пропущенный мат висит у всех на виду.
 */
describe("detectHate — мат и брань удаляются, похожие слова живут", () => {
  it.each(["Иди нахуй", "пиздец цены", "сука дорого", "ебаный развод", "Бля", "кусат", "падарналат", "модаратро", "сагбача", "чалаб"])(
    "удаляется: %s",
    (text) => expect(detectHate(text)).not.toBeNull()
  );
  it.each([
    "Художник снимал?",
    "Требую ответа",
    "Кусок земли продаёте?",
    "Киро чанд?",
    "Модари ман мехоҳад",
    "Страхуйте квартиру",
    "Кирпичный дом?",
    "мудрое решение",
    // Критика по делу — не мат: на неё отвечают вежливо (решение владельца).
    "Мошенники, обманули меня",
    "Дорого!",
  ])("остаётся: %s", (text) => expect(detectHate(text)).toBeNull());
});

describe("detectAgencyAd — агентство отличается от собственника", () => {
  it.each([
    "Агентство недвижимости Сомон, большой выбор квартир, звоните 918123456",
    "Риелтор, подберём квартиру в любом районе @rieltor_dsh",
    "Агентии амволи ғайриманқул, вариантҳои зиёд, 900112233",
  ])("агентство: %s", (text) => expect(detectAgencyAd(text)).not.toBeNull());
  it.each([
    // Собственник сам отгораживается от агентств — это наш будущий продавец.
    "Продаю сам, собственник, агентствам не беспокоить 918123456",
    "Какое агентство лучше?",
    "Хона дорем, нарх 580 хазор, 58 квадрат, 980001010",
  ])("не агентство: %s", (text) => expect(detectAgencyAd(text)).toBeNull());
});

describe("looksTajik — на каком языке писать собственнику", () => {
  it("таджикский и русский комментарии различаются", () => {
    expect(looksTajik("Хона дорем да Маладёжний Нарх 580")).toBe(true);
    expect(looksTajik("Салом, нархаш чанд?")).toBe(true);
    expect(looksTajik("Продаю квартиру, звоните")).toBe(false);
    expect(looksTajik("Сколько стоит?")).toBe(false);
  });
});
