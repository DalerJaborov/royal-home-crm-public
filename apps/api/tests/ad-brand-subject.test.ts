import { describe, expect, it } from "vitest";
import { looksLikeBrandAd } from "../src/lib/ads/adSubject.js";

/**
 * Подписи взяты из живого кабинета агентства (сверка 21.08.2026). Тест сторожит
 * границу, из-за которой список «без объекта» никогда не пустел: реклама услуг
 * Royal Home лежала в нём вместе с квартирами, которые действительно ждут
 * привязки, и отличить одно от другого глазами было нельзя.
 */
describe("реклама агентства и реклама квартиры", () => {
  const propertyPosts = [
    "🏛 Продаётся квартира:\n✅Район: Сино\n✅Адрес: 102мкр Казокон\n✅Тип недвижимости: Новостройка",
    "🏛 Продаётся квартира:\n✅Район: Шохмансур\n✅Адрес: Пайкар «Голубой Экран»",
    "Фурӯши манзил\nСуроға: кӯчаи Рӯдакӣ 45",
  ];
  const brandPosts = [
    "⭐ Ба самти дуруст қадам гузоред — Бо Royal Home соҳиби хонаи орзуҳои худ шавед!",
    "Мехоҳед амволи худро зудтар ва бо нархи дуруст фурӯшед? Ба мо муроҷиат кунед",
    "В Royal Home есть большая база клиентов, которые прямо сейчас ищут однокомнатные",
    "Royal.home.tj",
    // «манзил» — это «жильё», а не «адрес»: без разбора слова эта подпись
    // читалась как объявление о конкретной квартире.
    "Фурӯши манзилро ба Royal Home бовар кунед.🏡 Шумо вакти худро сарфа кунед",
  ];

  it("публикация с предложением и адресом считается объектной", () => {
    for (const caption of propertyPosts) {
      expect(looksLikeBrandAd(caption), caption.slice(0, 40)).toBe(false);
    }
  });

  it("публикация об услугах агентства объекта не ждёт", () => {
    for (const caption of brandPosts) {
      expect(looksLikeBrandAd(caption), caption.slice(0, 40)).toBe(true);
    }
  });

  it("без подписи судить не о чем — объявление идёт человеку как есть", () => {
    expect(looksLikeBrandAd(null)).toBe(false);
    expect(looksLikeBrandAd("   ")).toBe(false);
  });
});
