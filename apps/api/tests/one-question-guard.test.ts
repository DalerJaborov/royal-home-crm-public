import { describe, expect, it } from "vitest";
import {
  collapseToOneQuestion,
  countSentenceQuestions,
  enforceOneQuestionPerBubble,
} from "../src/ai/oneQuestionGuard.js";

/**
 * СТРОГО ОДИН ВОПРОС В ОДНОМ СООБЩЕНИИ (разбор находок судьи 30.08.2026,
 * BotAuditFinding: 25 находок типа repetition и ещё несколько tone/other прямо
 * называют причиной «два вопроса в одной реплике»). См. ai/oneQuestionGuard.ts.
 */

describe("countSentenceQuestions — считает только настоящие вопросы", () => {
  it("один вопрос — единица", () => {
    expect(countSentenceQuestions("Хонаи чандҳуҷрагӣ мекобед?")).toBe(1);
  });

  it("два вопроса подряд — двойка (живой случай судьи)", () => {
    expect(countSentenceQuestions("Ба Шумо чӣ гуна кӯмак карда метавонам? Хона мехаред ё мефурӯшед?")).toBe(2);
  });

  it("«?» внутри ссылки вопросом не считается", () => {
    expect(countSentenceQuestions("Тафсилот: https://royalhome.tj/listing/9?ref=ig")).toBe(0);
  });

  it("вопрос перед ссылкой — считается, ссылка после — нет", () => {
    expect(countSentenceQuestions("Ин вариант зӯр аст? Дар royalhome.tj/listing/9?ref=ig")).toBe(1);
  });
});

describe("collapseToOneQuestion — убирает лишний вопрос, а не всё после него", () => {
  it("меньше двух вопросов — текст не трогаем", () => {
    const text = "Дар кадом тарафи шаҳр хона мекобед?";
    expect(collapseToOneQuestion(text)).toBe(text);
  });

  it("два вопроса — остаётся только первый", () => {
    expect(collapseToOneQuestion("Хонаи чандҳуҷрагӣ мекобед? Дар кадом тараф?")).toBe(
      "Хонаи чандҳуҷрагӣ мекобед?"
    );
  });

  /**
   * ГЛАВНАЯ ПОЛОМКА, НАЙДЕННАЯ 20.09.2026 (docs/bot-razbor-20-09.md, класс 4 п. 4):
   * до этой правки текст резался по первому «?» целиком, и ответ на заданный вопрос
   * молча терялся вместе с лишним вопросом — цена, район, площадь, ссылка.
   */
  it("факты МЕЖДУ вопросами остаются: цена и район не теряются", () => {
    expect(
      collapseToOneQuestion("Ин хона ба шумо мефорад? Нархаш 41 000 доллар, Сино. Буҷети шумо чанд аст?")
    ).toBe("Ин хона ба шумо мефорад? Нархаш 41 000 доллар, Сино.");
  });

  it("ссылка на объект между вопросами остаётся", () => {
    const out = collapseToOneQuestion(
      "Ин вариант мефорад? Инҷо бинед: https://royalhome.tj/listing/9\nКадом ваќт бинем?"
    );
    expect(out).toContain("royalhome.tj/listing/9");
    expect(out).not.toContain("Кадом ваќт бинем");
  });

  it("три вопроса — остаётся первый, факты между вторым и третьим целы", () => {
    expect(collapseToOneQuestion("Салом, кӯмак кунам? Чандҳонагӣ? Дар база 12 вариант аст. Кай занг занам?")).toBe(
      "Салом, кӯмак кунам? Дар база 12 вариант аст."
    );
  });

  it("кусок без границы предложения был целиком вопросом — уходит целиком", () => {
    expect(collapseToOneQuestion("Шумо чунин хона мекобед? Чандхонага лозим аст?")).toBe(
      "Шумо чунин хона мекобед?"
    );
  });

  it("хвост после последнего вопроса вопросом не является и остаётся", () => {
    // Раньше отрезался и он. Это был не вопрос, а обычный текст модели, и терять
    // его незачем — правило написано против лишнего ВОПРОСА.
    expect(collapseToOneQuestion("Шумо чунин хона мекобед? Чандхонага лозим аст? Хуб, ташаккур.")).toBe(
      "Шумо чунин хона мекобед? Хуб, ташаккур."
    );
  });

  it("точка внутри числа границей предложения не считается", () => {
    expect(collapseToOneQuestion("Мефорад? Масоҳат 54.5 метр аст. Буҷет чанд?")).toBe(
      "Мефорад? Масоҳат 54.5 метр аст."
    );
  });
});

describe("enforceOneQuestionPerBubble — применяется ко всем пузырям хода", () => {
  it("режет каждый пузырь с двумя вопросами по отдельности", () => {
    expect(
      enforceOneQuestionPerBubble([
        "Ба Шумо чӣ гуна кӯмак карда метавонам? Хона мехаред ё мефурӯшед?",
        "Дар кадом тарафи шаҳр?",
      ])
    ).toEqual(["Ба Шумо чӣ гуна кӯмак карда метавонам?", "Дар кадом тарафи шаҳр?"]);
  });

  it("приём объекта у продавца — исключение, текст не трогаем", () => {
    const bubbles = ["Напишите одним сообщением: комнаты, площадь, район? Этаж? Цена?"];
    expect(enforceOneQuestionPerBubble(bubbles, true)).toEqual(bubbles);
  });

  it("пустой ход остаётся пустым", () => {
    expect(enforceOneQuestionPerBubble([])).toEqual([]);
  });
});
