/**
 * Эмодзи в подписи стоит в НАЧАЛЕ фразы, а не в хвосте (решение владельца
 * 20.09.2026). Промт модели об этом просит, но промт — просьба, а не гарантия,
 * поэтому порядок наводится кодом; здесь проверяется именно код.
 */
import { describe, it, expect } from "vitest";
import { moveTrailingEmojiToStart } from "../src/ai/reelsCaptionAi.js";

describe("moveTrailingEmojiToStart", () => {
  it("переносит эмодзи из конца фразы в начало", () => {
    expect(moveTrailingEmojiToStart("Чистый холст для вашего интерьера 🎨")).toBe(
      "🎨 Чистый холст для вашего интерьера"
    );
  });

  it("не трогает фразу, где эмодзи уже в начале", () => {
    expect(moveTrailingEmojiToStart("🔑 Пишите в директ")).toBe("🔑 Пишите в директ");
  });

  it("правит каждую строку отдельно", () => {
    expect(moveTrailingEmojiToStart("Первая строка 🏠\nВторая строка 📲")).toBe(
      "🏠 Первая строка\n📲 Вторая строка"
    );
  });

  it("не ломает фразу без эмодзи", () => {
    expect(moveTrailingEmojiToStart("Просто текст без картинок")).toBe("Просто текст без картинок");
  });

  it("составной эмодзи с модификатором переносится целиком", () => {
    expect(moveTrailingEmojiToStart("Звоните прямо сейчас 👍🏽")).toBe("👍🏽 Звоните прямо сейчас");
  });

  it("строку из одного эмодзи оставляет как есть", () => {
    expect(moveTrailingEmojiToStart("🔥")).toBe("🔥");
  });
});
