import { describe, it, expect } from "vitest";
import { detectPhoneAsk } from "../src/lib/agentPhoneAskDetector.js";

/**
 * Регрессионные тесты детектора «агент спросил номер телефона» (требование 11 аудита 02.09.2026).
 *
 * Проверяем только функцию detectPhoneAsk — чистый regex без побочных эффектов.
 * Интеграция (push, logSystemError, дедупликация) тестируется отдельно через
 * e2e или моки, здесь же важно, что паттерны ловят нужное и не ловят лишнее.
 */
describe("detectPhoneAsk", () => {
  // ─── Должно сработать ──────────────────────────────────────────────────────

  it("ловит прямую просьбу «напишите ваш номер»", () => {
    expect(detectPhoneAsk("Напишите ваш номер, пожалуйста")).not.toBeNull();
  });

  it("ловит вопрос «какой у вас номер?»", () => {
    expect(detectPhoneAsk("Какой у вас номер телефона?")).not.toBeNull();
  });

  it("ловит «оставьте телефон»", () => {
    expect(detectPhoneAsk("Оставьте телефон для связи")).not.toBeNull();
  });

  it("ловит «скиньте номерок» (разговорный вариант)", () => {
    expect(detectPhoneAsk("Скиньте номерок, я перезвоню")).not.toBeNull();
  });

  it("ловит «позвоните мне на»", () => {
    expect(detectPhoneAsk("Позвоните мне на этот номер")).not.toBeNull();
  });

  it("ловит «можете дать номер»", () => {
    expect(detectPhoneAsk("Можете дать ваш номер?")).not.toBeNull();
  });

  it("ловит таджикский вариант «рақаматонро нависед»", () => {
    expect(detectPhoneAsk("Лутфан рақаматонро нависед")).not.toBeNull();
  });

  it("ловит «ваш телефон?» в конце фразы", () => {
    expect(detectPhoneAsk("А какой ваш телефон?")).not.toBeNull();
  });

  // ─── НЕ должно сработать ───────────────────────────────────────────────────

  it("не ловит обычное сообщение о показе", () => {
    expect(detectPhoneAsk("Завтра покажу вам квартиру в центре")).toBeNull();
  });

  it("не ловит упоминание цены", () => {
    expect(detectPhoneAsk("Цена 500 000 сомони, торг уместен")).toBeNull();
  });

  it("не ловит «мой номер» (агент называет свой, а не просит чужой)", () => {
    expect(detectPhoneAsk("Мой номер указан в карточке")).toBeNull();
  });

  it("не ловит «номер объекта»", () => {
    expect(detectPhoneAsk("Номер объекта RH-12345, посмотрите")).toBeNull();
  });

  it("не ловит пустую строку", () => {
    expect(detectPhoneAsk("")).toBeNull();
  });

  it("не ловит слишком короткий текст", () => {
    expect(detectPhoneAsk("Ок")).toBeNull();
  });

  it("не ловит приветствие", () => {
    expect(detectPhoneAsk("Здравствуйте! Как ваши дела?")).toBeNull();
  });

  it("не ловит «перезвоните на следующей неделе» (бытовая фраза, не номер)", () => {
    expect(detectPhoneAsk("Перезвоните на следующей неделе, будут новые варианты")).toBeNull();
    expect(detectPhoneAsk("Позвоните на этой неделе попозже")).toBeNull();
  });

  it("ловит «перезвоните на +992…» (агент уводит в личный номер)", () => {
    expect(detectPhoneAsk("Перезвоните на +992 90 123 45 67")).not.toBeNull();
  });
});