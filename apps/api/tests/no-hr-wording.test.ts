import { describe, expect, it } from "vitest";
import { SCENARIO_JOB } from "../src/ai/leadQualifier.js";

/**
 * СЛОВО «HR» И ОБЕЩАНИЕ ЗВОНКА КАНДИДАТУ.
 *
 * Владелец 20.09.2026, дословно: «не надо использовать слово HR, что вам
 * перезвонит и все такое. Просто сказать, что ваша заявка будет рассмотрена».
 *
 * Проверка стоит на САМОМ ТЕКСТЕ ПРАВИЛ, а не на ответе модели, и вот почему.
 * Обычно в этом проекте запрет закрывается гвардом над готовым ответом («промт —
 * просьба, а не гарантия», ai/bannedWordsGuard.ts). Здесь такого гварда нет:
 * у «HR» нет безопасной механической замены — вырезать слово из «HR ба шумо
 * занг мезанад» значит оставить обещание звонка без подлежащего, а заменить его
 * на «роҳбарият» — сохранить ровно то обещание, которое владелец и запретил.
 * Запрещена вся ФРАЗА, а не слово, и надёжно вырезать фразу регуляркой нельзя
 * (тот же разбор, что у «пешниҳод» в bannedWordsGuard.ts).
 *
 * Поэтому стережём источник: пока запрета нет в тексте правил, модель будет
 * писать «HR перезвонит» — она это и делала. Проверка ловит возврат слова в
 * правила при любой следующей правке блока.
 */
describe("Кандидату не обещают звонок и не говорят «HR»", () => {
  /**
   * Проверяются ПРЕЖНИЕ ФОРМУЛИРОВКИ, а не слова «HR» и «перезвонит» вообще:
   * сам запрет ниже эти слова называет по имени («ни „HR“, ни „перезвонят“»),
   * и поиск по слову краснел бы на тексте самого запрета.
   */
  it("прежние формулировки со словом «HR» из правил убраны", () => {
    expect(SCENARIO_JOB).not.toContain("HR перезвонит");
    expect(SCENARIO_JOB).not.toContain("HR ба шумо занг мезанад");
    expect(SCENARIO_JOB).not.toContain("масъули қабули кормандон занг");
  });

  it("в конце разговора кандидату не обещают, что с ним свяжутся", () => {
    expect(SCENARIO_JOB).not.toContain("передашь руководству и с ним свяжутся");
    expect(SCENARIO_JOB).toContain("заявка принята");
  });

  it("правила прямо называют запрет, а не просто молчат о нём", () => {
    // Без явного запрета модель возвращается к привычной формулировке сама:
    // отсутствие слова в тексте правил её ни от чего не удерживает.
    expect(SCENARIO_JOB).toContain("НИ СЛОВА «HR»");
  });
});
