/**
 * Обращения по полу запрещены владельцем полностью. В промте запрет стоит трижды,
 * включая поимённый список слов, — и 01.08.2026 бот всё равно написал в Instagram
 * «Фаҳмо, апаи Фарида». Промт это просьба; здесь — вычёркивание.
 *
 * Отдельно стережём кириллицу: `\b` в JavaScript определён через [A-Za-z0-9_] и с
 * кириллицей не работает вовсе. В этом репозитории так молча умерли уже два правила.
 */
describe("обращения по полу вычёркиваются из ответа", () => {
  it("«апаи Имя» — ровно тот случай, что ушёл клиенту", () => {
    expect(stripGenderedAddress("Фаҳмо, апаи Фарида.")).toBe("Фаҳмо.");
  });

  it("«акаи Имя» — то же самое в мужском роде", () => {
    expect(stripGenderedAddress("Салом, акаи Искандар! Чӣ хел хона мекобед?")).toBe(
      "Салом! Чӣ хел хона мекобед?"
    );
  });

  it("«акаҷон» и «апаҷон» — самая частая форма", () => {
    expect(stripGenderedAddress("Хуб акаҷон, фаҳмидам")).toBe("Хуб, фаҳмидам");
    expect(stripGenderedAddress("Апаҷон, вариант ҳаст")).toBe("Вариант ҳаст");
  });

  it("обращение в начале и в конце фразы", () => {
    expect(stripGenderedAddress("апаи Нигина, ин вариант зӯр аст")).toBe("Ин вариант зӯр аст");
    expect(stripGenderedAddress("Ин вариант зӯр аст, акаҷон")).toBe("Ин вариант зӯр аст");
  });

  it("обычный текст не трогаем", () => {
    const text = "Хуб, пагоҳ соати 18 мунтазир мешавем. Нархаш 1 460 000 сомонӣ.";
    expect(stripGenderedAddress(text)).toBe(text);
  });

  it("похожие слова не режем: «акаи мо» это не обращение", () => {
    // «акаи мо» — «наш брат», обычное существительное. Обращением приставка считается
    // только в конце фразы или перед знаком; перед другим словом её не трогаем.
    // До 16.08.2026 правило было шире и превращало фразу в «Ин мо».
    expect(stripGenderedAddress("Ана расмҳояш, нигоҳ кунед.")).toBe("Ана расмҳояш, нигоҳ кунед.");
    expect(stripGenderedAddress("Ин акаи мо")).toBe("Ин акаи мо");
    expect(stripGenderedAddress("Хонаи хола дар Сино")).toBe("Хонаи хола дар Сино");
  });

  /**
   * 16.08.2026. Хвост слова стоял как `\w*`, а `\w` в JavaScript — это [A-Za-z0-9_]:
   * на кириллице он не ловит ничего. «акаҷон» вырезалось, «акаҷонам» — нет. Третье
   * правило этого репозитория, умершее от `\w`/`\b` на кириллице.
   */
  it("обращение с таджикским суффиксом («акаҷонам», «апаҷони»)", () => {
    expect(stripGenderedAddress("Ин зӯр аст, акаҷонам")).toBe("Ин зӯр аст");
    expect(stripGenderedAddress("Ассалом, акаҷони азиз")).toBe("Ассалом, азиз");
  });

  /**
   * Промт запрещал «любые другие слова, выдающие пол», а фильтр знал два корня из
   * одиннадцати. Всё остальное держалось на просьбе к модели — то есть не держалось.
   */
  it("родственные обращения, кроме «ака»/«апа»", () => {
    expect(stripGenderedAddress("Хуб, додарҷон")).toBe("Хуб");
    expect(stripGenderedAddress("Хоҳарам, ин хона хуб аст")).toBe("Ин хона хуб аст");
    expect(stripGenderedAddress("Рахмат, амак")).toBe("Рахмат");
    expect(stripGenderedAddress("Хуб, хола")).toBe("Хуб");
  });

  it("то же самое латиницей", () => {
    // Промт велит отвечать кириллицей, но правило «никогда» на просьбе не держится.
    expect(stripGenderedAddress("Rahmat akajon")).toBe("Rahmat");
    expect(stripGenderedAddress("Salom apajon")).toBe("Salom");
  });
});

