import { describe, expect, it } from "vitest";
import { stripBannedWords } from "../src/ai/bannedWordsGuard.js";

/**
 * СЛОВА, ЗАПРЕЩЁННЫЕ В <language_and_slang> (ai/leadQualifier.ts, AGENCY_VOICE),
 * НО ВСЁ РАВНО ПРОСКОЧИВШИЕ В ЖИВЫХ НАХОДКАХ СУДЬИ 30.08.2026 (BotAuditFinding,
 * тип tone): «лутфан» и «мутахассис». См. ai/bannedWordsGuard.ts — файл нарочно
 * не покрывает весь список правил языка, только эти два безопасных случая.
 */

describe("stripBannedWords — «лутфан» вырезается", () => {
  it("вырезается вместе с повисшей запятой перед ним", () => {
    expect(stripBannedWords("Рақаматонро нависед, лутфан")).toBe("Рақаматонро нависед");
  });

  it("в начале реплики вырезается вместе с запятой после", () => {
    expect(stripBannedWords("Лутфан, рақами худро нависед")).toBe("Рақами худро нависед");
  });

  it("не трогает текст без запрещённых слов", () => {
    const text = "Хонаи дуҳонагӣ дар Сино, нархаш 320 000 сомонӣ";
    expect(stripBannedWords(text)).toBe(text);
  });
});

describe("stripBannedWords — «мутахассис» заменяется на «агент»", () => {
  it("живая находка судьи: изафет переносится на замену", () => {
    expect(stripBannedWords("Мутахассиси мо ба шумо занг мезанад")).toBe("Агенти мо ба шумо занг мезанад");
  });

  it("замена сохраняет соседние знаки препинания", () => {
    expect(stripBannedWords("Ба мутахассис муроҷиат кунед.")).toBe("Ба агент муроҷиат кунед.");
  });
});

describe("stripBannedWords — «пешниҳод» намеренно не трогается", () => {
  it("существительное «предложение» не искажается (боевой случай reply-guards.test.ts)", () => {
    // «Пешниҳод» запрещён правилами ТОЛЬКО в обороте «пешниҳод намудан»
    // (канцелярское «предлагать/представлять»), а не как слово вообще — оно же
    // означает обычное «предложение» («пешниҳоди ҳамкорӣ» — «предложение о
    // сотрудничестве»). Различить два значения регуляркой нельзя, поэтому файл
    // сознательно его не трогает (см. шапку bannedWordsGuard.ts).
    const text = "Чи шуд бо пешниҳоди ҳамкорӣ?";
    expect(stripBannedWords(text)).toBe(text);
  });
});
