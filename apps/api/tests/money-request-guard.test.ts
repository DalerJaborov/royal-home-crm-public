import { describe, expect, it } from "vitest";
import { looksLikeMoneyRequest } from "../src/ai/moneyRequestGuard.js";

/**
 * ПРОСЬБА О ДЕНЬГАХ (владелец 21.08.2026, живой случай: женщина попросила в
 * директе помочь деньгами). Полное молчание собирается из этого признака в
 * webhooks.ts — здесь проверяется только сам признак.
 */
describe("просьба о деньгах", () => {
  it.each([
    ["русский, прямая просьба", "помогите мне деньгами, очень нужно"],
    ["русский, материальная помощь", "нужна материальная помощь, дети голодают"],
    ["русский, долг", "дайте в долг тысячу сомони, отдам через неделю"],
    ["русский, перевод", "переведите мне денег на карту пожалуйста"],
    ["русский, милостыня", "подайте, кто чем может"],
    ["таджикский, маблағ", "маблағ кӯмак кунед, лутфан"],
    ["таджикский, садақа", "садақа диҳед барои Худо"],
    ["таджикский, қарз", "қарз диҳед, ба ман сахт лозим"],
  ])("%s", (_label, text) => {
    expect(looksLikeMoneyRequest(text)).toBe(true);
  });

  it("пусто — не просьба", () => {
    expect(looksLikeMoneyRequest("")).toBe(false);
    expect(looksLikeMoneyRequest("   ")).toBe(false);
  });

  it.each([
    ["покупатель про рассрочку", "у меня сейчас туго с деньгами, можно в рассрочку купить квартиру?"],
    ["обычный разговор о квартире", "Салом, 2-хонагӣ дар Сино ҳаст? Нархаш чанд?"],
    ["продавец про ипотеку", "подскажите, а через ипотеку можно оформить эту квартиру"],
  ])("амнистия по нашей теме: %s", (_label, text) => {
    expect(looksLikeMoneyRequest(text)).toBe(false);
  });
});
