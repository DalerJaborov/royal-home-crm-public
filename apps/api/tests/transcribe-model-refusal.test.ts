import { describe, expect, it } from "vitest";
import { looksLikeModelRefusal } from "../src/ai/transcribe.js";

/**
 * Ответ модели «расшифровывать нечего» не должен попадать в карточку клиента как
 * содержание разговора.
 *
 * Живой случай 13.08.2026: агент не снял трубку, запись состояла из одних гудков,
 * Gemini ответил «Пожалуйста, предоставьте голосовое сообщение или аудиозапись, так
 * как файл для расшифровки не был прикреплён» — и этот текст сохранился как
 * расшифровка звонка, ушёл в разбор качества («запись отсутствует») и в предложение
 * по карточке.
 *
 * Вторая половина проверки не менее важна первой: настоящая речь клиента, где
 * встречаются те же слова, должна оставаться расшифровкой. Потерять живой разговор
 * страшнее, чем пропустить одну служебную фразу.
 */
describe("отказ модели вместо расшифровки", () => {
  it("узнаёт ответ, из-за которого всё началось", () => {
    expect(
      looksLikeModelRefusal(
        "Пожалуйста, предоставьте голосовое сообщение или аудиозапись, так как файл для расшифровки не был прикреплен."
      )
    ).toBe(true);
  });

  it("узнаёт другие формулировки того же самого", () => {
    const refusals = [
      "Файл не был прикреплен, поэтому расшифровка невозможна.",
      "Загрузите аудиозапись, и я расшифрую её.",
      "Извините, я не могу расшифровать эту запись.",
      "I'm sorry, I cannot transcribe this audio.",
      "No audio file was provided.",
    ];
    for (const text of refusals) expect(looksLikeModelRefusal(text), text).toBe(true);
  });

  it("не трогает настоящую речь", () => {
    const speech = [
      "Ало, салом алейкум. Ҳа, ман дар бораи хонаи семоҷа занг задам.",
      "Алло, да, я по объявлению звоню. Пожалуйста, скажите, квартира ещё продаётся?",
      "Пожалуйста, отправьте мне фотографии квартиры в вотсап.",
      "",
    ];
    for (const text of speech) expect(looksLikeModelRefusal(text), text).toBe(false);
  });

  /**
   * Длинный текст — это уже разговор, даже если внутри попалась похожая фраза.
   * Порог намеренно щедрый: мета-ответ модели всегда короткий.
   */
  it("длинную расшифровку не выбрасывает, даже если внутри похожие слова", () => {
    const long =
      "Пожалуйста, предоставьте аудиозапись. " +
      "Клиент рассказывает про квартиру в Сино, три комнаты, ремонт свежий, цена договорная. ".repeat(4);
    expect(long.length).toBeGreaterThan(300);
    expect(looksLikeModelRefusal(long)).toBe(false);
  });
});
