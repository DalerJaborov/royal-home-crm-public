import { describe, expect, it } from "vitest";
import { SALES_PLAYBOOK } from "../src/ai/salesPlaybook.js";

/**
 * Условия работы агентства в промте бота.
 *
 * Эти факты получены от владельца и стоят дороже любого кода: ошибка здесь — это не
 * упавший экран, а клиент, которому пообещали то, чего нет. Тесты стерегут ровно те
 * места, где бот может соврать уверенно и правдоподобно.
 */

describe("торг", () => {
  it("торг есть, но размер назвать нельзя", () => {
    // Владелец: «конечно же всегда есть скидка, но сколько — сказать не можем».
    expect(SALES_PLAYBOOK).toContain("Торг есть ВСЕГДА");
    expect(SALES_PLAYBOOK).toContain("Никогда не называй процент");
  });

  it("запрет распространяется и на «примерно»", () => {
    // Иначе модель обойдёт запрет вежливой оговоркой и всё равно назовёт цифру.
    expect(SALES_PLAYBOOK).toContain("даже примерную");
  });
});

describe("рассрочка и ипотека", () => {
  it("сказано прямо, что их нет", () => {
    expect(SALES_PLAYBOOK).toContain("Их НЕТ");
  });

  it("отдельно запрещено верить собственному сайту", () => {
    // Самая опасная ловушка: на royalhome.tj написано про ипотеку и рассрочку, но
    // это планы, а не условия. Бот увидел бы текст сайта и наобещал.
    expect(SALES_PLAYBOOK).toContain("на нашем сайте написано");
    expect(SALES_PLAYBOOK).toContain("планы на будущее");
  });
});

describe("комиссия", () => {
  it("два процента платит продавец, покупатель не платит", () => {
    expect(SALES_PLAYBOOK).toContain("платит их ПРОДАВЕЦ");
    expect(SALES_PLAYBOOK).toContain("С покупателя мы не берём ничего");
  });

  it("с ПОКУПАТЕЛЕМ тему комиссии поднимать запрещено", () => {
    // Владелец поправил: в Таджикистане покупатель и не думает, что должен платить
    // риелтору. Сказав «а с вас мы ничего не берём», бот посеял бы сомнение, которого
    // не было («а разве где-то берут?»). Это ответ на невысказанное возражение.
    expect(SALES_PLAYBOOK).toContain("НЕ ПОДНИМАЙ ВООБЩЕ");
    expect(SALES_PLAYBOOK).toContain("посеешь мысль, которой у него не было");
  });

  it("с ПРОДАВЦОМ отвечать прямо и сразу", () => {
    // Он платит и обязательно спросит; уклончивость про цену читается как «накрутят».
    expect(SALES_PLAYBOOK).toContain("отвечай прямо и сразу");
    expect(SALES_PLAYBOOK).toContain("только когда квартира продана");
  });

  it("редкая схема «по проценту с обоих» в промт не попала", () => {
    // Владелец про неё сказал: «это редкость и исключение, не стоит писать».
    expect(SALES_PLAYBOOK).not.toContain("1 процент");
    expect(SALES_PLAYBOOK).not.toContain("по проценту");
  });
});

describe("цель разговора", () => {
  it("цель — показ, а не номер телефона", () => {
    expect(SALES_PLAYBOOK).toContain("НЕ номер телефона");
    expect(SALES_PLAYBOOK).toContain("Цель — ПОКАЗ");
  });

  it("запрещено отвечать общими фразами при наличии данных", () => {
    expect(SALES_PLAYBOOK).toContain("НИКОГДА не отвечай общей фразой");
  });

  it("запрещено давить срочностью", () => {
    // В Душанбе жильё покупают раз в жизни; на давление реагируют уходом.
    expect(SALES_PLAYBOOK).toContain("НЕ ДАВИ");
  });

  it("цифры только из карточки объекта", () => {
    expect(SALES_PLAYBOOK).toContain("НЕ ВЫДУМЫВАЙ");
  });
});

describe("география и документы", () => {
  it("работаем только по Душанбе", () => {
    expect(SALES_PLAYBOOK).toContain("Только Душанбе");
  });

  it("проверку документов берём на себя", () => {
    expect(SALES_PLAYBOOK).toContain("нотариус, МБТИ");
  });
});

describe("приёмы закрытия на показ", () => {
  it("выбор из двух вариантов вместо открытого вопроса", () => {
    // «Когда вам удобно?» заставляет человека придумывать время — он откладывает.
    expect(SALES_PLAYBOOK).toContain("ПРЕДЛАГАЙ ВЫБОР ИЗ ДВУХ");
  });

  it("резюме перед закрытием", () => {
    expect(SALES_PLAYBOOK).toContain("РЕЗЮМИРУЙ ПЕРЕД ЗАКРЫТИЕМ");
  });

  it("в каждом сообщении есть следующий шаг", () => {
    // Сообщение, заканчивающееся точкой, заканчивает и разговор.
    expect(SALES_PLAYBOOK).toContain("СЛЕДУЮЩИЙ ШАГ");
  });
});

describe("местные особенности Душанбе", () => {
  it("пятничный намаз учитывается при назначении показа", () => {
    expect(SALES_PLAYBOOK).toContain("ВРЕМЯ НАМАЗА");
  });

  it("жильё выбирает семья, а не один человек", () => {
    expect(SALES_PLAYBOOK).toContain("ВЫБИРАЕТ СЕМЬЯ");
  });

  it("про кредит и ипотеку не спрашивать — покупают за наличные", () => {
    expect(SALES_PLAYBOOK).toContain("ЗА НАЛИЧНЫЕ");
  });

  it("про доход спрашивать запрещено, про бюджет — нужно", () => {
    // Вопрос про зарплату звучит как проверка платёжеспособности.
    expect(SALES_PLAYBOOK).toContain("НЕ СПРАШИВАЙ ПРО ДОХОД");
  });
});

describe("кем бот себя называет", () => {
  it("в правилах продаж нет обещаний быть живым человеком", () => {
    // Владелец решил: бот называет себя консультантом Royal Home, не клянётся,
    // что он человек, и не признаётся, что он программа.
    expect(SALES_PLAYBOOK).not.toContain("живой человек");
    expect(SALES_PLAYBOOK).not.toContain("живой одам");
  });
});
