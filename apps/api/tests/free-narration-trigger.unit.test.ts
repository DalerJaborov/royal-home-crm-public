import { describe, expect, it } from "vitest";
import { detectFreeNarrationLang } from "@royal-home/shared";
import { parseFreeNarrationTrigger } from "../src/telegram/assistantFreeNarration.js";

/**
 * «ОЗВУЧЬ ТЕКСТ» В ШАБНАМ (16.11.2026): распознавание просьбы. Главное — ложные срабатывания:
 * «озвучь сроки по ОБ-12» это вопрос помощнику, а не текст для озвучки.
 */
describe("просьба «озвучь текст»: что срабатывает", () => {
  it.each([
    ["озвучь: Добро пожаловать в Royal Home", "Добро пожаловать в Royal Home"],
    ["Озвучь:\nПервая строка\nВторая строка", "Первая строка\nВторая строка"],
    ["озвучь\nДобрый день, квартира свободна", "Добрый день, квартира свободна"],
    ["озвучь текст Добро пожаловать в Royal Home", "Добро пожаловать в Royal Home"],
    ["озвучь текст: ОБ-12, три комнаты", "ОБ-12, три комнаты"],
    ["озвучь дословно: привет, друзья", "привет, друзья"],
    ["озвучь слово в слово\nпривет", "привет"],
    ["Шабнам, озвучь текст: привет", "привет"],
    ["озвучь, пожалуйста: привет", "привет"],
    ["озвучьте этот текст: здравствуйте", "здравствуйте"],
    ["овоз кун: Хуш омадед ба Royal Home", "Хуш омадед ба Royal Home"],
    ["Овоз деҳ:\nСалом алейкум", "Салом алейкум"],
    ["хонда деҳ матн: ин хона фурӯхта мешавад", "ин хона фурӯхта мешавад"],
    ["матнро овоз кун: салом", "салом"],
    ["овозонӣ кун: салом", "салом"],
    ["хонда дех айнан Салом ба ҳама", "Салом ба ҳама"],
    ["озвучь это: ещё текст", "ещё текст"],
    ["озвучь: ответ клиенту будет завтра", "ответ клиенту будет завтра"],
    ["озвучь текст Квартира в центре свободна с понедельника", "Квартира в центре свободна с понедельника"],
  ])("«%s»", (input, text) => {
    expect(parseFreeNarrationTrigger(input)).toEqual({ kind: "text", text });
  });

  it("явная просьба без текста: спросим текст", () => {
    for (const input of ["озвучь:", "озвучь текст", "озвучь дословно", "озвучь текст:", "овоз кун:", "хонда деҳ матнро", "матнро овоз кунед", "ин матнро овоз кун"]) {
      expect(parseFreeNarrationTrigger(input), input).toEqual({ kind: "ask" });
    }
  });

  it("голое «озвучь» годится только ответом на текст сотрудника", () => {
    for (const input of ["озвучь", "Озвучь!", "озвучь это", "овоз кун"]) {
      expect(parseFreeNarrationTrigger(input), input).toEqual({ kind: "bare" });
    }
  });
});

describe("просьба «озвучь текст»: что НЕ срабатывает (вопросы помощнику)", () => {
  it.each([
    "озвучь сроки по ОБ-12",
    "озвучь, сколько стоит ОБ-12?",
    "озвучь ответ",
    "озвучь последний ответ",
    "озвучьте мне ответ",
    "озвучка объекта ОБ-12 готова?",
    "озвучить текст объекта 12 голосом",
    "озвучь дословно последний ответ",
    "озвучь текст объявления ОБ-12",
    "озвучь текст ответа",
    "озвучь слово в слово ответ про ОБ-12",
    "Расскажи про озвучь: что это",
    "покажи объект 12 и озвучь: цену",
    "сколько знаков в озвучке за сегодня",
    "овоз кардан мумкин аст?",
    "",
  ])("«%s»", (input) => {
    expect(parseFreeNarrationTrigger(input)).toBeNull();
  });
});

describe("язык текста", () => {
  it("таджикские буквы дают tg, обычная кириллица ru, остальное без подсказки", () => {
    expect(detectFreeNarrationLang("Хуш омадед, хонаи нав дар ноҳияи Сино")).toBe("tg");
    expect(detectFreeNarrationLang("Добро пожаловать, квартира в Сино")).toBe("ru");
    expect(detectFreeNarrationLang("Welcome to Royal Home")).toBeNull();
    expect(detectFreeNarrationLang("12345 !!!")).toBeNull();
  });
});
