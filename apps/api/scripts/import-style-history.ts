import "../src/loadEnv.js";
import { importStyleFromHistory } from "../src/ai/styleLearning.js";

/**
 * РАЗОВЫЙ ИМПОРТ СТИЛЯ ИЗ ПРОШЛЫХ ПЕРЕПИСОК (просьба владельца 22.08.2026:
 * «просканировать все диалоги в инстаграме и выучить стиль общения»).
 *
 * Проходит по уже накопленным перепискам и вытаскивает пары «сообщение клиента →
 * следующий РУЧНОЙ ответ живого сотрудника». Ответы бота не берутся никогда: на
 * них он закрепил бы собственные ошибки, а учиться он должен у людей.
 *
 * Запускать можно сколько угодно раз: дубли гасит уникальность в базе, так что
 * повторный прогон просто добавит то, что появилось с прошлого раза.
 *
 * Запуск из apps/api (именно оттуда — иначе dotenv не найдёт .env и упадёт на
 * DATABASE_URL, та же грабля, что у тестов):
 *   npx tsx scripts/import-style-history.ts
 *   npx tsx scripts/import-style-history.ts 2000   // сколько диалогов просмотреть
 */
const limit = Number(process.argv[2]) || 500;

const { imported, scanned } = await importStyleFromHistory(limit);
console.log(`Просмотрено диалогов: ${scanned}`);
console.log(`Добавлено образцов стиля: ${imported}`);
console.log(
  imported === 0
    ? "Ноль — это нормально, если сотрудники ещё не отвечали вручную или всё уже импортировано раньше."
    : "Готово. Бот начнёт перенимать манеру этих ответов со следующего разговора."
);
process.exit(0);
