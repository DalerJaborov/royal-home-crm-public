import type { Currency, PropertyCondition, PropertyType } from "./enums.js";

/**
 * Черновик карточки ОБЪЕКТА со слов ПРОДАВЦА (задача K, план
 * docs/audit-02-09-2026/19-plan-03-09-evening.md) — «ИИ копит информацию по всем
 * каналам касания с продавцом... к моменту открытия формы создания объекта черновик
 * уже заполнен».
 *
 * Тот же принцип, что и у CardFillSuggestion (cardFill.ts, заполнение карточки
 * КЛИЕНТА), только источник — продавец, а поля — параметры ЕГО ОБЪЕКТА, а не
 * требования покупателя. Ничего не сохраняется само: сервер только читает
 * переписку/звонки и возвращает предложение, агент проверяет и правит поля в форме
 * создания объекта, сохраняет обычным POST /properties.
 */
export interface PropertyDraftSuggestion {
  /** chat — собрано из переписки; call — участвовали расшифровки звонков (надёжнее
   *  переписки, см. тот же принцип в CardFillSuggestion.source); none — продавец не
   *  писал и не звонил, либо сказать было нечего — форма открывается пустой. */
  source: "chat" | "call" | "none";
  type: PropertyType | null;
  rooms: number | null;
  areaSqm: number | null;
  floor: number | null;
  condition: PropertyCondition | null;
  price: number | null;
  currency: Currency | null;
  districtId: string | null;
  districtName: string | null;
  /** Ориентир/адрес со слов продавца («напротив кинотеатра Зебунисо», ЖК, улица). */
  address: string | null;
  /** До 3 коротких цитат продавца, на которых держится предложение — агент проверяет
   *  глазами, прежде чем сохранить (пометка «заполнено ИИ, проверьте» в форме). */
  evidence: string[];
  /** ИИ не ответил (нет ключа, таймаут) — форма открывается пустой, без подсказок. */
  aiUnavailable: boolean;
  /**
   * Подсказка НЕ выдана нарочно, потому что по переписке нельзя понять, о КАКОЙ
   * из квартир продавца идёт речь (19.09.2026, разбор перемешанных описаний двух
   * объектов одного продавца). Все поля при этом null — пустая форма честнее
   * смеси фактов двух разных квартир. Текст показывается агенту в форме.
   */
  ambiguityReason: AmbiguityReason | null;
  /** Сколько объектов этого продавца уже заведено в CRM (без удалённых) — то же
   *  число, что видит агент в карточке продавца; нужно для текста предупреждения. */
  existingObjectsCount: number;
}

/** Почему подсказка не выдана. SEVERAL_IN_CHAT — в переписке описано больше одного
 *  объекта; ALREADY_HAS_OBJECTS — у продавца уже есть объекты в CRM, и разобрать,
 *  где в переписке новый, а где уже заведённый, нечем. */
export type AmbiguityReason = "SEVERAL_IN_CHAT" | "ALREADY_HAS_OBJECTS";
