/**
 * Реестр прав доступа CRM — единственный источник истины и для сервера, и для
 * веб-клиента. До него роль проверялась строковым сравнением в ~66 файлах, из-за
 * чего нельзя было открыть один раздел одному сотруднику, не открыв его всей роли.
 *
 * Модель: роль — это ПРЕСЕТ прав (набор галочек по умолчанию), а директор может
 * поверх пресета что угодно добавить или отнять конкретному человеку.
 * Итог = (пресет роли ∪ granted) \ revoked.
 *
 * ВАЖНО, о чём легко забыть при добавлении новой возможности:
 *   1. Новое право добавляется СЮДА и сразу проставляется в ROLE_PRESETS — иначе
 *      оно не появится ни у кого, включая админа.
 *   2. Право обязано проверяться на сервере (requirePermission). Скрытая в
 *      интерфейсе кнопка — это косметика, а не защита: запрос к API руками уйдёт.
 *   3. directorOnly-права нельзя выдать галочкой ни при каких условиях — см.
 *      resolvePermissions. Это защита от повышения прав самому себе.
 */

export interface PermissionDef {
  id: string;
  /** Подпись в интерфейсе — короткая, языком директора, а не разработчика. */
  label: string;
  group: PermissionGroupId;
  /** Уточнение под подписью: что именно откроется/закроется. */
  hint?: string;
  /**
   * Право уровня владельца компании. Не входит ни в один пресет кроме DIRECTOR,
   * не показывается в списке галочек и молча отбрасывается, даже если кто-то
   * подложит его в granted напрямую через API.
   */
  directorOnly?: true;
  /**
   * Право оставлено в реестре только ради обратной совместимости с уже
   * выданными granted/revoked (Agent.permissions) — новые назначения через
   * галочку скрыты (см. ASSIGNABLE_PERMISSIONS). Инфраструктура для будущих
   * подобных переходов (пример: properties.viewAll → viewOwners/editForeign,
   * удалено в слое 4 08.09.2026 после backfill на проде).
   */
  deprecated?: true;
}

