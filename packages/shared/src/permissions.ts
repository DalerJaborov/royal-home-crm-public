export interface PermissionOverrides {
  granted: PermissionId[];
  revoked: PermissionId[];
}

export const EMPTY_OVERRIDES: PermissionOverrides = { granted: [], revoked: [] };

let warnedUnknownPermissionIds = false;

/**
 * Список id прав из старого клиента/записи. Неизвестный id (право
 * переименовали/убрали релизом, например снятый в слое 4 08.09.2026
 * `properties.viewAll`) тихо отбрасывается, а не 400-ит весь запрос —
 * старый фронтенд не должен получать ошибку сохранения из-за одной
 * устаревшей галочки в теле запроса. Предупреждение в лог — один раз за
 * процесс, чтобы не заспамить при повторных запросах с тем же мусором.
 */
const permissionIdListSchema = z
  .array(z.string())
  .max(PERMISSIONS.length)
  .transform((list) => {
    const known: PermissionId[] = [];
    const unknown: string[] = [];
    for (const id of list) {
      if (isPermissionId(id)) known.push(id);
      else unknown.push(id);
    }
    if (unknown.length > 0 && !warnedUnknownPermissionIds) {
      warnedUnknownPermissionIds = true;
      console.warn(`[permissions] Отброшены неизвестные id прав: ${unknown.join(", ")}`);
    }
    return known;
  });

/**
 * Схема персональных надстроек. Валидируется и на входе API, и при чтении из БД:
 * список прав может устареть после релиза (право переименовали/убрали) —
 * неизвестный идентификатор отбрасывается мягко (см. permissionIdListSchema),
 * а не роняет запрос.
 */
export const permissionOverridesSchema = z.object({
  granted: permissionIdListSchema.default([]),
  revoked: permissionIdListSchema.default([]),
});

/** Разбирает JSON-колонку Agent.permissions, отбрасывая мусор и снятые с учёта права. */
export function parsePermissionOverrides(raw: unknown): PermissionOverrides {
  if (!raw || typeof raw !== "object") return EMPTY_OVERRIDES;
  const source = raw as { granted?: unknown; revoked?: unknown };
  const clean = (list: unknown): PermissionId[] =>
    Array.isArray(list) ? (list.filter((v): v is PermissionId => typeof v === "string" && isPermissionId(v))) : [];
  return { granted: clean(source.granted), revoked: clean(source.revoked) };
}

/**
 * Итоговый набор прав сотрудника.
 *
 * Директор — владелец: получает всё и не может быть урезан, иначе компанию можно
 * запереть снаружи (в том числе случайно, сняв себе галочку «раздавать права»).
 * Для всех остальных владельческие права вычёркиваются последними — это делает
 * невозможным повышение до директора через granted, даже если запись в БД
 * подделана в обход API.
 */
export function resolvePermissions(role: Role, overrides?: PermissionOverrides | null): Set<PermissionId> {
  if (role === "DIRECTOR") {
    return new Set<PermissionId>(PERMISSION_IDS);
  }

  const effective = new Set<PermissionId>(ROLE_PRESETS[role] ?? []);
  for (const id of overrides?.granted ?? []) effective.add(id);
  for (const id of overrides?.revoked ?? []) effective.delete(id);
  for (const id of DIRECTOR_ONLY_PERMISSIONS) effective.delete(id);
  return effective;
}

/**
 * Нормализует надстройки перед записью: убирает владельческие права, снимает
 * противоречия (право одновременно в granted и revoked) и не хранит то, что и так
 * совпадает с пресетом роли — иначе после смены роли сотрудник тащил бы за собой
 * невидимый хвост старых галочек.
 */
export function normalizeOverrides(role: Role, overrides: PermissionOverrides): PermissionOverrides {
  const preset = new Set<PermissionId>(ROLE_PRESETS[role] ?? []);
  const assignable = new Set<PermissionId>(ASSIGNABLE_PERMISSIONS);
  const revoked = overrides.revoked.filter((id) => assignable.has(id) && preset.has(id));
  const revokedSet = new Set(revoked);
  const granted = overrides.granted.filter((id) => assignable.has(id) && !preset.has(id) && !revokedSet.has(id));
  return { granted: [...new Set(granted)], revoked: [...new Set(revoked)] };
}

/** Готовая «матрица галочек» для экрана настройки прав. */
export function describePermissions(role: Role, overrides?: PermissionOverrides | null) {
  const effective = resolvePermissions(role, overrides);
  const preset = new Set<PermissionId>(role === "DIRECTOR" ? PERMISSION_IDS : (ROLE_PRESETS[role] ?? []));
  return PERMISSIONS.filter((p) => !("directorOnly" in p) && !("deprecated" in p)).map((p) => ({
    ...p,
    enabled: effective.has(p.id),
    /** true — значение отличается от того, что даёт роль по умолчанию. */
    overridden: effective.has(p.id) !== preset.has(p.id),
  }));
}

