export type TelephonyOptionField = keyof typeof TELEPHONY_OPTIONS;

/** Название значения поля словами; неизвестное значение остаётся как есть (чтобы сообщение не потеряло факт). */
export function telephonyOptionTitle(field: TelephonyOptionField, value: string): string {
  const found = (TELEPHONY_OPTIONS[field] as readonly TelephonyOption[]).find((o) => o.value === value);
  return found ? found.title : value;
}
