/**
 * «НЕ СВЯЗЫВАЛИСЬ» — ОДНО ПРАВИЛО НА ВСЮ CRM (17.11.2026, жалоба РОП Нозы).
 *
 * Счётчик показывает клиентов, с которыми сотрудники НИ РАЗУ не связывались. Клиент,
 * с которым связались хотя бы раз, сюда не попадает никогда, сколько бы дней ни прошло.
 *
 * СВЯЗЬ — это любое действие живого сотрудника в сторону клиента:
 *   • звонок сотрудника с любым исходом, в том числе «не ответил» и сброшенный, пока
 *     у клиента звонил телефон (не считается только «агент сам не снял трубку» —
 *     до клиента вызов не дошёл);
 *   • состоявшийся разговор по телефону, в том числе входящий;
 *   • сообщение, написанное сотрудником (из CRM или прямо в мессенджере);
 *   • встреча или показ, записанные сотрудником;
 *   • отметка «агент пытался связаться» (Client.lastAgentAttemptAt).
 * Ответы бота, заметки, задачи и пропущенный входящий связью НЕ считаются.
 *
 * ПОЧЕМУ ТАК (было до 17.11): «без контакта» значило «больше суток не было разговора
 * или сообщения от самого клиента». Агент, который звонит клиенту каждый день, а тот не
 * берёт трубку, оставался «без контакта» навсегда: на проде 17.11 так висело 248
 * клиентов, и у 240 из них звонки сотрудников были. Ноза: «Это контакты, с которыми мы
 * на связи. Мы же не можем с ними ежедневно быть на связи».
 *
 * Выборка на сервере — apps/api/src/lib/noContact.ts (noContactWhere); подписи — здесь.
 */

