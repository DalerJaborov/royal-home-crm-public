/** Граница давности для других правил, которые считают паузу в контакте (рассылка
 *  «вернуть клиента», пауза бота): контакт раньше этого момента уже не свежий. */
export function noContactCutoff(now: Date, days: number): Date {
  return new Date(now.getTime() - days * 24 * 60 * 60 * 1000);
}

type When = Date | string | null | undefined;

export interface ClientContactFacts {
  createdAt: Date | string;
  /** Последнее сообщение САМОГО клиента в любом чате (агенту или боту). */
  lastClientMessageAt?: When;
  /** Последний звонок, где клиент реально разговаривал (TALKED / длительность > 0). */
  lastTalkedCallAt?: When;
}

const ms = (d: When): number | null => (d ? new Date(d).getTime() : null);

/** Момент последнего разговора или сообщения самого клиента; null — не было ни разу.
 *  Нужен паузе бота (lib/conversationState.ts), к счётчику «не связывались» отношения не имеет. */
export function lastRealContactTime(f: ClientContactFacts): Date | null {
  const t = Math.max(ms(f.lastClientMessageAt) ?? -Infinity, ms(f.lastTalkedCallAt) ?? -Infinity);
  return Number.isFinite(t) ? new Date(t) : null;
}

/** Цвет плитки: красный — только когда есть кого показать. */
export function noContactTileTone(count: number): "crit" | "calm" {
  return count > 0 ? "crit" : "calm";
}
