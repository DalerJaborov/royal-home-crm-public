/**
 * ТЕМА ВОЗРАЖЕНИЯ «ЦЕНА» — один словарь на сервер (диагноз) и экран («Голос рынка», 03.10.2026).
 *
 * Классификации тем в данных голоса рынка нет: сервер отдаёт частотные тексты как
 * есть (комментарии, вопросы собственнику, возражения из звонков). Единственное
 * структурное поле — причина отказа клиента `EXPENSIVE`. Всё остальное узнаётся
 * по словам, и словарь живёт ТОЛЬКО здесь: не копировать его в экран и в тесты.
 *
 * Что считается «возражением о цене»: дорого, завышена, торг, скидка, уступка,
 * рассрочка, «арзонтар» и аналоги на таджикском (кириллица и латиница).
 * Нейтральные «цена?», «нарх чанд?» сюда НЕ входят — это вопрос, а не возражение.
 * Ошибка в сторону «не узнали» дешевле ложного диагноза: слова подобраны узко.
 */

// Границы слов — через \p{L}: \b в JS не знает кириллицу.
const PRICE_OBJECTION_WORDS = [
  // русский
  "дорого",
  "дороговат\\p{L}*",
  "дорогов\\p{L}*",
  "завышен\\p{L}*",
  "переоценен\\p{L}*",
  "высокая\\s+цена",
  "цена\\s+высок\\p{L}*",
  "скидк\\p{L}*",
  "торг",
  "торга",
  "торгу",
  "торге",
  "торгом",
  "торговаться",
  "поторговаться",
  "торгуемся",
  "поторгуемся",
  "уступ\\p{L}*",
  "уступит\\p{L}*",
  "снизит\\p{L}*\\s+цен\\p{L}*",
  "рассрочк\\p{L}*",
  // таджикский (кириллица)
  "қимат\\p{L}*",
  "кимат\\p{L}*",
  "гарон",
  "арзон\\p{L}*",
  "тахфиф\\p{L}*",
  "савдо",
  // таджикский / узбекский (латиница)
  "qimat\\p{L}*",
  "arzon\\p{L}*",
  "tahfif\\p{L}*",
  "savdo",
];

// Взгляд назад (?<!…) не используется нарочно: файл грузится и в браузер, а iOS до 16.4
// такой синтаксис не разбирает — упал бы весь бандл, а не одна проверка.
const PRICE_OBJECTION_RE = new RegExp(`(?:^|[^\\p{L}])(?:${PRICE_OBJECTION_WORDS.join("|")})(?!\\p{L})`, "iu");

/** Текст — возражение или вопрос про цену, торг, скидку или рассрочку. */
export function isPriceObjectionText(text: string): boolean {
  return PRICE_OBJECTION_RE.test(text);
}

/** Причина отказа клиента из карточки (Client.refusalReason), которая значит «цена». */
export const PRICE_REFUSAL_REASON = "EXPENSIVE";
