/**
 * АДРЕС БЕЗ АДРЕСА (21.11.2026, объект №213: в карточке «улица», и монтажёр с
 * подписью получили «Адрес: улица»). Одно слово-заготовка — не адрес: в тексты для
 * людей (подпись, задание монтажёру, обложка, сторис) такой адрес не выводится, а
 * мастер объекта просит написать его полностью. Одно правило для всех мест.
 */
const GENERIC_ADDRESS_WORDS = new Set([
  "улица", "ул", "кӯча", "куча", "кӯчаи", "кучаи", "проспект", "пр", "пр-т", "шоҳроҳ", "мкр", "микрорайон",
  "район", "ноҳия", "ноҳияи", "дом", "хона", "адрес", "суроға", "нет", "не", "не знаю", "неизвестно", "уточнить", "уточняется",
]);

/** Адрес, который можно показать человеку; null — пусто или только слово-заготовка («улица», «ул.», «-»). */
export function meaningfulPropertyAddress(raw: string | null | undefined): string | null {
  const address = (raw ?? "").trim();
  const bare = address.toLocaleLowerCase("ru").replace(/[\s.,:;!?«»"'()\-–—_/\\]+/gu, " ").trim();
  if (!bare || bare.length < 2 || GENERIC_ADDRESS_WORDS.has(bare)) return null;
  return address;
}
