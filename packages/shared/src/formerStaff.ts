/**
 * БЫВШИЕ СОТРУДНИКИ НЕ ВИДНЫ КАК ЖИВЫЕ ЛЮДИ (владелец 10–11.11.2026: «Мы бы не
 * хотели видеть бывших сотрудников вообще… Да давай всех скрой»).
 *
 * Бывший — `Agent.isActive = false` (отключён или «удалён»: удаление тоже
 * отключает и переименовывает телефон, запись остаётся). Данные НЕ стираются:
 * в истории (кто создал, кто звонил, журнал) имя остаётся как было.
 *
 * Правило одно на обе стороны: любой СПИСОК сотрудников (справочник, выпадающие
 * выборы, «Команда», рейтинги, помощник в Telegram) по умолчанию отдаёт только
 * работающих. Директор (agents.manage) может попросить бывших параметром
 * `includeFormer=1` — только чтобы вернуть ошибочно отключённого.
 */
export const INCLUDE_FORMER_STAFF_PARAM = "includeFormer" as const;

/** Работает ли человек сейчас — единственная граница «живой / бывший». */
export function isCurrentStaff(agent: { isActive: boolean }): boolean {
  return agent.isActive === true;
}

/** Значение параметра запроса «показать бывших» (строгое: только "1" или "true"). */
export function wantsFormerStaff(value: unknown): boolean {
  return value === "1" || value === "true";
}
