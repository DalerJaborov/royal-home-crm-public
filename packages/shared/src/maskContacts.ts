/**
 * Скрытие телефонов в исходящих сообщениях агента клиенту.
 *
 * Зачем: именно так уходят клиенты. Агент даёт свой личный номер, разговор
 * переезжает в его WhatsApp, и сделка проходит мимо агентства. Маска работает
 * на текст, который уходит клиенту, поэтому лежит в общем пакете: сервер
 * заменяет перед отправкой, браузер тем же правилом предупреждает агента ДО
 * нажатия «Отправить». Два разных правила разошлись бы, и предупреждение
 * начало бы врать.
 *
 * Чего эта маска НЕ делает: не трогает входящие сообщения клиента. Пока телефон
 * клиента открыт в его карточке (до появления SIP-транка), скрывать тот же номер
 * в переписке бессмысленно — он виден строкой выше.
 *
 * Границы намеренно узкие. Замазать клиенту цену хуже, чем пропустить номер:
 * агент решит, что CRM сломана, и уйдёт писать из личного телефона — то есть
 * ровно туда, откуда маска его и уводит. Поэтому ловим только то, что похоже на
 * телефон однозначно:
 *
 *  - международный формат с плюсом: +992 XX XXX XXXX, +7 XXX XXX XX XX и любой
 *    другой код страны;
 *  - местные 9 цифр — длина мобильного в Таджикистане, с любыми разделителями.
 *
 * Более короткие последовательности без кода страны не ловим сознательно: от
 * цены, площади и номера объекта они не отличаются ничем. Ссылки и почту не
 * трогаем по решению владельца.
 */

/** Чем заменяем найденный номер — видно, что скрыто намеренно, а не потерялось. */
/** Чем заменяется номер в ТЕКСТЕ сообщения. Экспортируется, потому что веб рисует
 *  на этом месте кнопку «Позвонить» (владелец 07.09.2026: «маскировку не убирай, просто
 *  вместо некрасивого *** пусть будет кнопка позвонить») — и обе стороны обязаны
 *  понимать маску одинаково, иначе кнопка перестанет появляться от одной правки здесь. */
export const MESSAGE_PHONE_MASK = "****";
const MASK = MESSAGE_PHONE_MASK;

/**
 * Чем закрыт телефон в КАРТОЧКЕ клиента для сотрудника без права clients.viewPhone
 * (`+992•••••18`, см. apps/api/src/lib/clientPhone.ts). Другая маска и другой смысл,
 * чем у MASK выше: та прячет номер в тексте сообщения, эта — в данных карточки.
 *
 * Лежит в общем пакете, потому что закрытый номер нужно УЗНАВАТЬ с обеих сторон.
 * Пока узнавать было нечем, форма «Изменить клиента» подставляла маску в поле
 * телефона как обычное значение: агент не мог сохранить карточку вовсе — проверка
 * требовала девять цифр, а в маске их пять (жалоба владельца 10.08.2026). Хуже
 * того, серверная схема принимала любую строку длиннее пяти знаков — пройди
 * проверку, и маска затёрла бы настоящий номер в базе.
 */
export const CLIENT_PHONE_MASK_CHAR = "•";

/** Это закрытый маской номер, а не набранный человеком. */
export function isMaskedClientPhone(phone: string): boolean {
  return phone.includes(CLIENT_PHONE_MASK_CHAR);
}

/**
 * Международный номер: плюс, код страны, дальше 6–14 цифр с разделителями.
 * Разделители — пробел, дефис, скобки, точка: живой человек пишет как угодно.
 */
const INTERNATIONAL = /\+\d[\d\s().-]{6,18}\d/g;

/**
 * Местные 9 цифр (мобильный Таджикистана) с любыми разделителями между ними.
 * Границы «не цифра до» / (?!\d) не дают откусить середину длинного числа: у цены
 * «1234567890» девять цифр внутри есть, но телефоном она не является.
 *
 * Левая граница — поглощаемая группа (^|\D), а НЕ взгляд назад: файл грузится и
 * в браузер, а Safari до 16.4 lookbehind не знает и падает SyntaxError на разборе
 * всего модуля — CRM не открывается вовсе (19.10.2026, Safari на MacBook).
 */
const LOCAL_NINE = /(^|\D)((?:\d[\s().-]?){8}\d)(?!\d)/g;

/** Похоже ли, что рядом с числом стоит валюта: тогда это цена, а не телефон. */
const CURRENCY_NEAR = /(сомон|somon|tjs|руб|usd|доллар|долл|\$|€|₽)/i;

/**
 * Ссылки и адреса почты вырезаются из разбора целиком.
 *
 * Это не косметика: отправлять клиенту ссылки на объекты — основной смысл чата,
 * а в ссылке запросто окажется девятизначный идентификатор. Маска превратила бы
 * его в «****», и ссылка перестала бы открываться. Почту не трогаем по решению
 * владельца, а заодно это защищает адреса вида agent12345678@… от той же беды.
 *
 * Одна группа захвата — важна: String.split с ней оставляет сами разделители в
 * массиве (на нечётных позициях), и мы точно знаем, что маскировать нельзя.
 */
const SKIP_SEGMENTS = /((?:https?:\/\/|www\.)\S+|[^\s@]+@[^\s@]+\.[^\s@]+)/gi;

/** Ровно 9 цифр после вычистки разделителей — длина мобильного. */
function digitsOnly(value: string): string {
  return value.replace(/\D/g, "");
}

/**
 * Заменяет телефоны в тексте на «****».
 * Возвращает и результат, и признак срабатывания — по нему интерфейс показывает
 * агенту предупреждение, а роут пишет в историю то, что клиент реально получил.
 */
export function maskPhones(text: string): { text: string; masked: boolean } {
  let masked = false;

  const maskSegment = (segment: string): string => {
    const withoutInternational = segment.replace(INTERNATIONAL, (match) => {
      // Код страны + слишком мало цифр — скорее диапазон вроде «+7 лет», не номер.
      if (digitsOnly(match).length < 7) return match;
      masked = true;
      return MASK;
    });

    return withoutInternational.replace(LOCAL_NINE, (full, lead: string, match: string, at: number, whole: string) => {
      if (digitsOnly(match).length !== 9) return full;
      const offset = at + lead.length;
      // Цена «900 000 000 сомони» тоже даёт девять цифр — если валюта стоит рядом,
      // это деньги. Смотрим 12 символов до и после совпадения.
      const around =
        whole.slice(Math.max(0, offset - 12), offset) + whole.slice(offset + match.length, offset + match.length + 12);
      if (CURRENCY_NEAR.test(around)) return full;
      masked = true;
      return lead + MASK;
    });
  };

  // Нечётные позиции — сами ссылки и адреса почты, их отдаём как есть.
  const result = text
    .split(SKIP_SEGMENTS)
    .map((part, i) => (i % 2 === 1 ? part : maskSegment(part)))
    .join("");

  return { text: result, masked };
}

/**
 * Номер, зашитый В ССЫЛКУ или схему: wa.me/992…, api.whatsapp.com/send?phone=992…,
 * t.me/+992…, tel:+992…. maskPhones такие сегменты целиком пропускает (SKIP_SEGMENTS,
 * решение владельца для ИСХОДЯЩИХ: ссылки на объекты нельзя ломать), поэтому для
 * ЧИТАТЕЛЯ без права на номер их закрывает эта маска (аудит Codex 04.10.2026,
 * ACCESS-02). Узкая намеренно: прячутся только цифры номера (7+) именно в этих
 * четырёх видах, прочие ссылки (на объекты, сайт, t.me/канал) остаются рабочими.
 *
 * Группа 1 — префикс, который остаётся как есть; группа 2 — цифры номера. Цифры не
 * должны переходить в буквы (`(?![\w])`): у приглашения t.me/+12345678abc цифры —
 * кусок хеша, а не номер.
 */
const PHONE_IN_LINK =
  /((?:wa\.me\/|(?:api|web)\.whatsapp\.com\/send\/?\?(?:[^\s#]*&)?phone=|whatsapp:\/\/send\?(?:[^\s#]*&)?phone=|(?:t|telegram)\.me\/\+|tel:)\+?)(\d[\d\s().-]{5,}\d)(?![\w])/gi;

/**
 * То же, что maskPhones, но для читателя без права видеть номер клиента
 * (clients.viewPhone): дополнительно закрывает номер внутри телефонных ссылок.
 * Исходящий maskPhones не меняется — он должен пропускать ссылки.
 */
export function maskPhonesForReader(text: string): { text: string; masked: boolean } {
  let linkMasked = false;
  const withoutLinkPhones = text.replace(PHONE_IN_LINK, (match, prefix: string, digits: string) => {
    if (digitsOnly(digits).length < 7) return match;
    linkMasked = true;
    return `${prefix}${MASK}`;
  });
  const result = maskPhones(withoutLinkPhones);
  return { text: result.text, masked: result.masked || linkMasked };
}

/** Есть ли в тексте то, что будет скрыто — для предупреждения перед отправкой. */
export function hasMaskablePhone(text: string): boolean {
  return maskPhones(text).masked;
}
