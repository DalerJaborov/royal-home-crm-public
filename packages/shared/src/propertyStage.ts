/**
 * Состояние этапа конвейера подготовки объекта — общее для сервера и значка в
 * интерфейсе.
 *
 * Считает его сервер (apps/api/src/lib/propertyPipeline.ts): просрочка зависит от
 * сроков в Настройках, и своя копия правила в интерфейсе однажды покрасила бы
 * список и карточку по-разному.
 *
 * Тип был объявлен дважды, и веб-копия ослабила `owner` до обычной строки — то
 * есть подпись ответственного могла молча не найтись в справочнике, и вместо роли
 * человек увидел бы сырой код. Здесь `owner` снова закрытый список.
 */
/**
 * Минимум фото объекта, снятых агентом на месте — меньше этого числа карточка
 * не может покинуть подготовку (владелец 19.09.2026: снижено с 6 до 1, остальные
 * фото добавляются по желанию агента).
 *
 * Живёт здесь, а не только на сервере: экран одобрения материалов считал
 * достаточным одно фото и включал кнопку «Одобрить», а сервер отвечал 409. Модератор
 * жал живую кнопку и получал отказ — правило обязано быть одним на оба конца.
 */
export const MIN_PROPERTY_PHOTOS = 1;

export interface PropertyStageState {
  /** Объект ещё готовится, а не выставлен. */
  inPipeline: boolean;
  /** Роль, отвечающая за этот этап. null — объект уже ведёт назначенный агент. */
  owner: "MARKETING" | "EDITOR" | "AGENT" | null;
  /** Сколько дней объект стоит в этом состоянии (целое, вниз). */
  daysInStage: number;
  /** Срок этапа в днях. null — у состояния срока нет вовсе. */
  limitDays: number | null;
  /** Просрочен. У состояний вне конвейера — всегда false. */
  overdue: boolean;
}
