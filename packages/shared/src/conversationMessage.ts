/**
 * Реплика переписки с клиентом — общая форма для сервера и браузера.
 *
 * До 10.08.2026 одно и то же было описано шесть раз: `PresentedMessage`/
 * `PresentedAttachment` в lib/messageAttachments.ts, `ConversationMessage`/
 * `MessageAttachment` в веб-типах и четыре локальных `StoredMessage` (cardFill,
 * cron, lostConversations, conversations) — причём один из четырёх уже знал про
 * поле `at`, а три остальных нет.
 *
 * Так и расходятся копии: место, где реплики только читают, не замечает нового
 * поля, а место, где их пишут, — уже пишет. Компилятор молчит, потому что каждая
 * копия сама по себе верна.
 */

/**
 * Кто на самом деле написал реплику со стороны компании (role="assistant").
 *
 * До 12.08.2026 такого поля не было вовсе: и ответ ИИ, и ручной ответ агента
 * (кнопка «Ответить» в инбоксе, форма в карточке клиента), и служебная рассылка
 * CRM (просьба подтвердить показ, пересланный ответ на вопрос собственнику)
 * писались в одну и ту же реплику `{role: "assistant"}`, и интерфейс показывал
 * под каждой из них одну и ту же подпись «Royal Home» с иконкой бота — руководитель
 * не мог отличить, ответил бот или конкретный сотрудник. Найдено владельцем
 * 12.08.2026: «всегда указывать, кто отвечает — бот или какой оператор».
 *
 * Реплики без этого поля (записанные раньше) трактуются как ответ бота — это и
 * было подавляющим большинством случаев до появления самого поля.
 */
export type MessageSender =
  | { kind: "bot" }
  /** Автоматическая рассылка самой CRM — не ИИ и не человек: просьба подтвердить
   *  показ, напоминание, пересланный ответ на вопрос собственнику. */
  | { kind: "system" }
  | { kind: "agent"; agentId: string; agentName: string }
  /**
   * Ответ РУКАМИ ИЗ САМОГО МЕССЕНДЖЕРА, мимо CRM (17.08.2026).
   *
   * Кто именно писал — неизвестно и узнать невозможно: Meta в эхо-сообщении
   * называет только аккаунт страницы, а не сотрудника, который держал телефон.
   * Отдельный вид, а не «agent» с выдуманным именем и не «system»: подписать
   * такую реплику конкретным сотрудником значило бы соврать, а «CRM» — сказать,
   * что это автоматическая рассылка, хотя писал живой человек.
   *
   * Такие реплики раньше не сохранялись вовсе (эхо отбрасывалось целиком), и в
   * переписке CRM их не было — агент не знал, что клиенту уже отвечали.
   */
  | { kind: "manual" };

/**
 * Вложение в реплике: то, что клиент прислал в переписку.
 *
 * «video» и «file» добавлены 16.08.2026. До этого дня видео и документы вообще не
 * сохранялись: их отдавали Gemini на описание и выбрасывали. В переписке от
 * рум-тура оставалась одна пометка, посмотреть его было нельзя ни агенту, ни
 * руководителю — а это самое ценное, что присылает продавец.
 */
export interface MessageAttachment {
  kind: "image" | "audio" | "video" | "file";
  mime: string;
  /**
   * Имя файла для `GET /attachments/:name`; null — у смотрящего нет права
   * `messages.viewAttachments`. Само вложение лежит в закрытом хранилище.
   */
  file: string | null;
  /**
   * Готовый адрес внутри `/uploads` — есть только у фотографий объекта, которые
   * отправил сам бот. Правом не закрыт: это наш каталог, те же снимки открыты на
   * сайте и в карточке объекта, а агент должен знать, что клиенту уже показывали.
   */
  url?: string;
  /**
   * Файл в R2 удалён уборкой по сроку хранения (см. lib/outgoingMediaCleanup.ts,
   * 18.08.2026) — ISO-дата удаления. Ставится ТОЛЬКО на исходящие фото/видео
   * оператора (`url` из `chat-media/...`): у Meta своя копия уже есть, а наша в R2
   * занимала место сервера сверх согласованного срока. Сама реплика и её текст в
   * истории остаются — стирается только файл, чтобы UI показал понятную пометку
   * вместо битой ссылки/404 (см. routes/mediaProxy.ts → 410).
   */
  expiredAt?: string;
}

/**
 * Реплика в том виде, в каком она лежит в БД и уходит в браузер.
 *
 * `attachments` есть только там, где клиент прислал фото или голосовое; у старой
 * переписки поля нет вовсе. `at` появилось 01.08.2026 — у реплик, записанных
 * раньше, его тоже нет, и по нему считается разрыв во времени между сообщениями
 * (ai/conversationTime.ts).
 */
export interface ConversationMessage {
  role: "user" | "assistant";
  content: string;
  attachments?: MessageAttachment[];
  at?: string;
  /** Только у role="assistant". Отсутствует — старая запись или сбой сериализации,
   *  трактуется как ответ бота (см. MessageSender). */
  by?: MessageSender;
  /**
   * Идентификатор реплики у Meta (mid). Появился 16.08.2026 вместе с цитированием.
   *
   * У реплики клиента это mid его сообщения, у нашей — mid отправленного нами.
   * Нужен ровно затем, чтобы `replyToMid` было на что указывать: без него цитата
   * не находит, что цитировать.
   */
  mid?: string;
  /** Реплика клиента записана системой вместо хода бота (бот намеренно промолчал,
   *  а номер оформили). Повтор зависших диалогов такие реплики пропускает — см.
   *  ai/shared.ts в apps/api и lib/stuckConversations.ts. */
  silentCapture?: boolean;
  /**
   * Второй идентификатор — только у нашего ответа. Бот отвечает двумя короткими
   * сообщениями, а в переписке CRM они лежат ОДНОЙ репликой; клиент же может нажать
   * «ответить» на любое из двух. Без второго идентификатора цитата на второй пузырь
   * не нашла бы, к чему относится, и не нарисовалась бы вовсе.
   */
  mid2?: string;
  /**
   * На какую реплику отвечает эта — по ней в переписке рисуется цитата.
   *
   * Два случая, и оба настоящие:
   *  1) клиент нажал «ответить» на конкретное сообщение (Meta присылает reply_to.mid) —
   *     без цитаты короткое «да» или «подходит» повисает в воздухе;
   *  2) наш ответ пришёл с задержкой (окно ожидания + время модели), и человек за
   *     это время написал ещё раз. Тогда ответ бота стоит НЕ под тем сообщением,
   *     на которое отвечает, и руководитель читает диалог неверно.
   *
   * Указывает на реплику, которой в ленте может уже не быть (лента обрезана до 40) —
   * тогда цитата просто не рисуется.
   */
  replyToMid?: string;
  /** Present only in the grouped CRM timeline; points back to the underlying
   * conversation for source-aware translation, quoting, feedback and replies. */
  sourceConversationId?: string;
  /** Original zero-based array position inside sourceConversationId's history. */
  sourceMessageIndex?: number;
  /** Per-message channel badge in a grouped timeline. Null when origin is hidden. */
  sourceChannel?: string | null;
  /**
   * Статус доставки НАШЕГО сообщения у клиента (18.08.2026, только WhatsApp —
   * Instagram/Messenger такого не присылают). Отсутствует — статус ещё не
   * пришёл, или сообщение не отслеживается (не WhatsApp, либо нет `mid`).
   */
  deliveryStatus?: "sent" | "delivered" | "read" | "failed";
  /**
   * Запасные номера, которые клиент назвал в этой реплике и которых не было среди
   * уже известных номеров его карточки — зашифрованы, показывать их в браузере не
   * нужно (сам текст реплики в `content` уже замаскирован «*»), поле присутствует
   * только затем, чтобы фронт не отбрасывал его молча при пересборке типа.
   * Требование владельца 04.09.2026 — тот же приём, что у звонков
   * (Interaction.mentionedPhonesEncrypted, lib/telephony/callPhoneMasking.ts).
   */
  mentionedPhonesEncrypted?: string[];
  /**
   * Русский перевод — только у role="user", когда реплика на таджикском и
   * сотрудник нажал «Показать перевод» (POST /conversations/:id/translate).
   * Тот же приём, что у Interaction.transcriptRu для звонков: оригинал не
   * подменяется, перевод лежит рядом. Отсутствует — либо ещё не запрашивали,
   * либо сервер решил, что перевод не нужен (реплика и так по-русски).
   */
  translatedRu?: string;
  /**
   * Оценка ОТВЕТА БОТА прямо в чате (17.09.2026, POST /conversations/:id/reply-feedback).
   * Только у role="assistant" с `by.kind === "bot"`. Живёт в самой реплике —
   * повторная оценка обновляет это поле, а не плодит записи (идемпотентность),
   * и состояние переживает перезагрузку страницы без отдельного запроса.
   */
  feedback?: {
    verdict: "good" | "bad";
    note?: string;
    by: string;
    at: string;
    /** BotLesson.id — у verdict="bad" (правило создаётся всегда, активно оно или
     *  ждёт ночного разбора, см. lib/botLessons.ts). Храним, чтобы повторный клик
     *  ОБНОВЛЯЛ ту же запись, а не плодил новые, и чтобы смена вердикта знала, что
     *  выключить. */
    lessonId?: string;
    /** StyleExample.id — у verdict="good". Та же причина, что у lessonId выше. */
    styleExampleId?: string;
  };
}
