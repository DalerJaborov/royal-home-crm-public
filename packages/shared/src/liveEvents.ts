import { z } from "zod";

/**
 * ЖИВЫЕ СОБЫТИЯ СЕРВЕР→БРАУЗЕР (12.09.2026).
 *
 * До этого «живость» в CRM держалась только на опросе по таймеру: общий
 * `refetchInterval: 25_000` в queryClient плюс 56 точечных переопределений по
 * экранам. Владелец: «живые данные без перезагрузки». Опрос остаётся ЗАПАСНЫМ
 * путём — поток может не дойти (прокси режет, вкладка спала, сеть моргнула), —
 * но горячие места переводятся на поток, а их таймер растягивается.
 *
 * ⚠️ В ПОТОК НЕ КЛАДЁТСЯ СОДЕРЖИМОЕ. Ни телефонов, ни текстов сообщений, ни
 * имён. Только идентификаторы и признаки: браузер получает «в диалоге X новое
 * сообщение» и перезапрашивает данные обычным роутом, где права проверяются как
 * всегда. Иначе поток стал бы вторым, непроверенным каналом выдачи данных —
 * ровно тот класс дыр, который в этом репозитории уже ловили («защита
 * подключена не во всех каналах»).
 *
 * Контракт живёт здесь, а не в apps/api: одни и те же имена событий разбирает
 * сервер (адресация) и браузер (инвалидация ключей TanStack Query).
 */

/** Типы событий. Расширяется добавлением строки — сервер и клиент увидят обе. */
export const LIVE_EVENT_TYPES = [
  /** Новый лид ждёт принятия (предложен агенту/агентам). */
  "lead.pending",
  /** Лид принят — предложение погасло у всех, кому его показывали. */
  "lead.accepted",
  /** Новое сообщение в диалоге (входящее от клиента, от бота или от агента). */
  "message.new",
  /** Диалог изменился: статус, назначенный агент, непрочитанные. */
  "conversation.updated",
  /** Сделка изменилась (в первую очередь стадия). */
  "deal.updated",
  /** Снимок пульта пересчитан. */
  "pult.snapshot",
  /** Создано уведомление. */
  "notification.new",
  /**
   * Звонок изменился: входящий появился, был принят/пропущен, разобран.
   *
   * ОДНО событие на весь телефонный экран, а не три: журнал входящих, лента
   * звонков и счётчики читаются с одних и тех же строк, и разделять их значило
   * бы публиковать три события на каждый звонок ради одной и той же выборки.
   */
  "call.updated",
  /**
   * Клиент изменился так, что это видно ЧУЖИМ экранам: сменился исполнитель,
   * статус, клиент вернулся в работу, отказался или ушёл в отложенные.
   *
   * Мелкие правки карточки (комментарий, бюджет) сюда НЕ публикуются: их видит
   * тот же человек, который их и сделал, а его экран обновляет мутация.
   */
  "client.updated",
  /** Объект создан, изменён, опубликован/снят или отправлен в корзину. */
  "property.updated",
  /**
   * Заявка на рассмотрение изменилась: удаление клиента, удаление объекта,
   * спор о количестве объектов — создана, одобрена или отклонена.
   *
   * Три механизма под одним типом намеренно: у них один и тот же зритель
   * (надзор) и один и тот же экран, а различать их по типу события пришлось бы
   * только затем, чтобы погасить те же ключи.
   */
  "request.updated",
] as const;

export type LiveEventType = (typeof LIVE_EVENT_TYPES)[number];

/**
 * Полезная нагрузка события: ТОЛЬКО идентификаторы и короткие признаки.
 *
 * `passthrough` намеренно НЕ используется — схема закрытая, и это защита, а не
 * строгость ради строгости: случайно переданный в publish объект клиента
 * (с телефоном) будет обрезан здесь, а не уедет в браузер.
 */
export const liveEventPayloadSchema = z
  .object({
    leadId: z.string().min(1).max(64).optional(),
    clientId: z.string().min(1).max(64).optional(),
    conversationId: z.string().min(1).max(64).optional(),
    messageId: z.string().min(1).max(64).optional(),
    dealId: z.string().min(1).max(64).optional(),
    notificationId: z.string().min(1).max(64).optional(),
    /** Идентификатор звонка (входящего либо взаимодействия-звонка). */
    callId: z.string().min(1).max(64).optional(),
    /** Идентификатор объекта. */
    propertyId: z.string().min(1).max(64).optional(),
    /** Идентификатор заявки на рассмотрение (удаление, спор о количестве). */
    requestId: z.string().min(1).max(64).optional(),
    /** Канал диалога (TELEGRAM/WHATSAPP/...) — по нему фронт решает, что гасить. */
    channel: z.string().min(1).max(32).optional(),
    /** Направление сообщения: входящее от клиента или наше. */
    direction: z.enum(["IN", "OUT"]).optional(),
    /** Новая стадия сделки / новый статус — короткий признак, не текст. */
    stage: z.string().min(1).max(64).optional(),
    /** Кто вызвал изменение: чтобы автор не дёргал свой же экран лишний раз. */
    actorId: z.string().min(1).max(64).optional(),
  })
  .strict();

export type LiveEventPayload = z.infer<typeof liveEventPayloadSchema>;

/**
 * Адресация. Событие отдаётся подписчику, если выполнено ХОТЬ ОДНО условие:
 *  - его id есть в `agentIds`;
 *  - его роль есть в `roles`;
 *  - оба списка пусты (широковещательное — только для того, что и так видно
 *    всем: пересчёт снимка пульта).
 *
 * Права при этом НЕ подменяются: адресация лишь решает, кому СТОИТ перезапросить
 * данные. Сами данные приходят обычным роутом со своей проверкой прав.
 */
export const liveEventSchema = z.object({
  /** Монотонный номер строки-исходника: по нему клиент отбрасывает повторы. */
  id: z.number().int().nonnegative(),
  type: z.enum(LIVE_EVENT_TYPES),
  at: z.string().datetime(),
  payload: liveEventPayloadSchema,
});

export type LiveEvent = z.infer<typeof liveEventSchema>;

/** То, что кладут в шину (id и at проставляет сама шина). */
export interface LiveEventInput {
  type: LiveEventType;
  payload: LiveEventPayload;
  /** Персональные получатели; пусто вместе с roles — широковещательное. */
  agentIds?: string[];
  /** Получатели по роли (строки Role из enums.ts). */
  roles?: string[];
}
