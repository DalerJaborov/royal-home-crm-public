const KNOWN: ReadonlySet<string> = new Set(PUSH_KINDS.map((k) => k.key));

export function isPushKind(value: unknown): value is PushKind {
  return typeof value === "string" && KNOWN.has(value);
}

export interface PushPayload {
  /**
   * true — служебный сигнал «закрой уведомление с этим tag», не новое уведомление.
   * Нужен, когда лид ушёл от агента, пока он ещё не принял/отклонил его: без
   * этого на телефоне продолжает висеть пуш про заявку, которой уже нет — агент
   * тратит время, открывая карточку, которая давно не его (владелец 19.08.2026).
   * Тело/заголовок в этом случае не используются, но остаются обязательными
   * полями интерфейса — проще игнорировать два лишних значения на сервере,
   * чем городить второй тип ради одного поля.
   */
  close?: boolean;
  title: string;
  body: string;
  /**
   * Вид уведомления — для отбора по личным настройкам сотрудника. На устройство
   * не уезжает: отбор происходит на сервере, до отправки.
   *
   * Не задан — уведомление уходит ВСЕГДА. Это сознательно: служебные сигналы
   * (невозвращённый ключ, сбой интеграции, эскалация руководству) не должны
   * молча выключаться заодно с чем-то, что человек отключал совсем про другое.
   */
  kind?: PushKind;
  /**
   * СОБЫТИЕ РЕАЛЬНОГО ВРЕМЕНИ — тихие часы на него не действуют (владелец
   * 12.09.2026: «ночью запрещено слать пуши всем пользователям, только в начале
   * рабочего дня»).
   *
   * Ставится ТОЛЬКО там, где уведомление имеет смысл ровно в эту минуту и
   * бесполезно через час: телефон звонит прямо сейчас. Всё остальное — сводки,
   * лиды, задачи, сообщения, алармы — ночью не уходит (см.
   * apps/api/src/lib/pushQuietHours.ts): часть откладывается до 08:00, часть
   * отбрасывается, но запись в ленте уведомлений остаётся всегда.
   *
   * Не «важность»: у аларма руководителю уровень URGENT, и он всё равно ждёт
   * утра. Реальное время — про то, что событие проходит мимо, а не про то, что
   * оно значимое.
   */
  realtime?: boolean;
  /**
   * Важность для ЛЕНТЫ (владелец 09.09.2026, раздел «Срочное»). На устройство не
   * уезжает — шторка телефона про уровни ничего не знает.
   *
   * Поле живёт здесь, а не только в createNotification, по невесёлой причине:
   * sendPushToAgent(s) ПИШЕТ ТУ ЖЕ СТРОКУ ЛЕНТЫ вторым проходом, с тем же tag.
   * Без уровня в payload этот второй проход пересчитал бы важность из kind и
   * затёр бы явно выставленный URGENT — раздел «Срочное» тихо остался бы пустым,
   * хотя каждый аларм по отдельности выглядел бы правильным.
   *
   * Не задано — выводится из kind (см. notificationLevelOf).
   */
  level?: NotificationLevel;
  /** Относительный путь, куда вести при клике по уведомлению. */
  url?: string;
  /** Уведомления с одинаковым tag схлопываются в одно на устройстве — не заваливаем агента дублями. */
  tag?: string;
  /**
   * Кнопки в шторке. Safari (iPhone, в том числе установленная PWA) поле
   * игнорирует — там уведомление остаётся обычным, и нажатие открывает карточку.
   * Ничего дополнительно для этого делать не нужно, и отдельной ветки кода iPhone
   * не требует.
   */
  actions?: { action: PushActionKind; title: string }[];
  /**
   * Одноразовый маркер действия. У service worker нет JWT — он не часть
   * приложения и не видит localStorage вкладки, — поэтому право на ОДНО действие
   * приезжает в самом уведомлении. В базе лежит только SHA-256 от маркера,
   * маркер одноразовый, привязан к паре «агент + клиент» и живёт минуты из
   * Настроек. Предельный ущерб при утечке — приём или отклонение одного лида.
   */
  actionToken?: string;
  /**
   * Аватар клиента, который написал — «крутая фича» по просьбе владельца 19.08.2026:
   * агент должен ориентироваться по клиентам с одного взгляда на шторку, не открывая
   * карточку. Два вида значения, в порядке предпочтения, ОБА — короткий путь
   * `/uploads/...`, никогда base64:
   *
   *  · `/uploads/avatars/...` — настоящее фото профиля, если его удалось забрать
   *    (Instagram/Messenger отдают, WhatsApp Cloud API — нет, см. lib/clientAvatar.ts)
   *    и скачать локально; временные подписанные ссылки Meta сюда не попадают никогда;
   *  · `/uploads/avatars-fallback/...` — нарисованный кружок с тоном по имени и значком
   *    «покупатель/продавец» (lib/clientAvatarFallback.ts), заранее отрисован в PNG и
   *    лежит файлом. Фото есть далеко не у всех, и без этого большинство уведомлений
   *    выглядело одной иконкой приложения — то есть аватар не работал ровно там, ради
   *    чего заводился.
   *
   * Именно PNG, а не SVG: декодер картинок уведомлений в Chromium SVG не читает.
   *
   * До 25.08.2026 запасной вариант ехал прямо в теле как `data:image/png;base64,...` —
   * это раздувало payload push-уведомления (Apple/FCM режут его на ~4096 байт) и роняло
   * доставку кодами 413/400. Оба варианта теперь — путь, а не встроенные байты, так что
   * само уведомление отдельно скачивает картинку, и лимит тела push тут ни при чём.
   *
   * Не задан — service worker покажет иконку приложения. С 19.08.2026 это редкий
   * последний рубеж (отказ отрисовки), а не обычный случай.
   */
  avatarUrl?: string;
}

/** Ответ на выполнение действия из шторки — из него service worker делает уведомление-итог. */
export interface PushActionResult {
  ok: boolean;
  /** Готовый текст для человека: service worker не должен ничего сочинять сам. */
  message: string;
  /** Куда вести при клике по уведомлению-итогу. */
  url?: string;
}
