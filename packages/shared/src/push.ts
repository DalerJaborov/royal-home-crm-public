/**
 * Payload push-уведомления — ОДНО описание на сервер и на service worker.
 *
 * До 11.08.2026 тип был написан дважды: в `apps/api/src/push.ts` и копией в
 * `apps/web/src/sw.ts`. Синхронизировались руками, и это работало ровно до тех
 * пор, пока в уведомление не понадобилось вложить кнопки: расхождение в таком
 * поле не ломает сборку, а молча превращает кнопку в её отсутствие.
 */

/** Действие в самом уведомлении. Значения зашиты: их знает и сервер, и service worker. */
export type PushActionKind = "lead-accept" | "lead-decline";

/**
 * Вид уведомления — по нему сотрудник отключает то, что ему не нужно.
 *
 * До 11.08.2026 уведомления были «всё или ничего» на устройство: агент, которого
 * раздражал поток сообщений клиентов, отключал заодно и новые лиды — то есть
 * ровно то, ради чего push и заводился.
 *
 * Список нарочно короткий. Настройка на каждый повод («напоминание за 40 минут»
 * отдельно от «за 2 часа») — это экран, который никто не откроет; разделять надо
 * то, что человек и правда хочет разделить.
 */
export type PushKind =
  /** Новые лиды, передачи, освобождение места. */
  | "lead"
  /** Клиент написал в мессенджер. */
  | "message"
  /** Показы и встречи: напоминания, подтверждения, неявки. */
  | "showing"
  /** Задачи, сводка на завтра, просрочки. */
  | "task"
  /** Изменения Royal Score. */
  | "score"
  /** Контроль руководителя: разбор проблемных мест, куда уходят клиенты. */
  | "oversight"
  /** Сделка закрыта — салют команде (владелец 03.09.2026). Всегда включено: не
   *  в PUSH_KINDS ниже (без переключателя в Настройках) — выключать чужую
   *  радость никто не должен захотеть, а поводов немного, чтобы раздражать. */
  | "celebration"
  /** Гео-подбор (12.09.2026, docs/geo-match-plan-12-09.md блок D7): появившийся
   *  или подешевевший объект подошёл ждущему покупателю. До этой правки такие
   *  пуши уходили БЕЗ kind — значит неотключаемы, писались в ленту как «other»
   *  и без иконки (ломающее изменение поведения: теперь их можно приглушить
   *  через pushMuted — владелец предупреждён, усталость от уведомлений убивает
   *  функцию быстрее, чем её отсутствие). */
  | "look"
  /** «Объект загорелся» (24.09.2026): объект агента резко набрал просмотры на
   *  сайте — самое время позвонить тем, кто им интересовался. */
  | "hot";

/**
 * ЧЕТЫРЕ УРОВНЯ УВЕДОМЛЕНИЙ — ПО СУТИ ДЕЛА, А НЕ ПО ГРОМКОСТИ
 * (владелец 09.09.2026, переделано 12.09.2026).
 *
 * ПЕРВАЯ ПОПЫТКА БЫЛА НЕ О ТОМ. 10.09 здесь стояла шкала срочности — Срочное /
 * Важное / Обычное / К сведению. Владелец же описывал деление по ТИПУ дела, и
 * первым назвал «ждёт моего одобрения», объяснив почему: «они блокируют работу
 * людей». Шкала громкости на этот вопрос не отвечает: заявка на удаление не
 * «срочная», она просто ничья, пока её не решили, и человек на той стороне стоит.
 *
 * Дословно по разговору:
 *   1. ЖДЁТ РЕШЕНИЯ  — заявки на удаление, фото и видео на проверку, изменение
 *      количества объектов. Первыми, потому что блокируют работу других.
 *   2. КРИТИЧНОЕ     — обход CRM, объект не добавлен, заявлено N — сделано M,
 *      жалоба клиента.
 *   3. ИНСАЙТЫ       — агент что-то сказал не так, советы системы.
 *   4. ПРОЧЕЕ        — счета, реклама, финансы.
 *
 * ЭТО НЕ ТОЛЬКО ЭКРАН ВЛАДЕЛЬЦА. Лента общая, и у агента первый уровень читается
 * ровно так же: новый лид ждёт ЕГО решения и точно так же держит человека на той
 * стороне, пока он не принял. Одна шкала на всех честнее двух разных.
 *
 * Уровень отключению не подлежит — в отличие от вида (PushKind), который человек
 * настраивает под себя.
 */
export const NOTIFICATION_LEVELS = ["APPROVAL", "CRITICAL", "INSIGHT", "OTHER"] as const;
export type NotificationLevel = (typeof NOTIFICATION_LEVELS)[number];

export const NOTIFICATION_LEVEL_LABELS: Record<NotificationLevel, string> = {
  APPROVAL: "Ждёт решения",
  CRITICAL: "Критичное",
  INSIGHT: "Инсайты",
  OTHER: "Прочее",
};

/** Подпись под заголовком раздела — чтобы человек понимал, почему строка здесь. */
export const NOTIFICATION_LEVEL_HINTS: Record<NotificationLevel, string> = {
  APPROVAL: "Пока не решите, работа других стоит",
  CRITICAL: "Теряем клиента или деньги",
  INSIGHT: "Что подсказала система",
  OTHER: "К сведению",
};

/**
 * Уровень по умолчанию — ПО ВИДУ УВЕДОМЛЕНИЯ.
 *
 * Иначе уровень пришлось бы дописать в сотню мест вызова разом, и до тех пор всё
 * лежало бы в «Прочем»: три верхних раздела существовали бы пустыми, то есть их
 * бы не было. Вызывающий код указывает уровень явно только там, где умолчание
 * врёт (алармы, заявки на одобрение, разборы ИИ).
 *
 * `lead` — APPROVAL не «потому что важно», а потому что лид буквально ждёт
 * решения агента и до него клиент остаётся без ответа.
 */
export const DEFAULT_LEVEL_BY_KIND: Record<PushKind, NotificationLevel> = {
  lead: "APPROVAL",
  message: "OTHER",
  showing: "OTHER",
  task: "OTHER",
  score: "OTHER",
  oversight: "CRITICAL",
  // Салют команде за закрытую сделку — именно «прочее»: радость, а не работа.
  celebration: "OTHER",
  // Подходящий объект появился/подешевел — рабочая наводка, не блокирует
  // ничью работу и не критично: тот же уровень, что у сообщения и показа.
  look: "OTHER",
  // «Загорелся» — подсказка системы, ничью работу не блокирует.
  hot: "INSIGHT",
};

export function isNotificationLevel(value: unknown): value is NotificationLevel {
  return typeof value === "string" && (NOTIFICATION_LEVELS as readonly string[]).includes(value);
}

/** Уровень уведомления: явно заданный, иначе по виду, иначе «Прочее». */
export function notificationLevelOf(kind: string | null | undefined, explicit?: unknown): NotificationLevel {
  if (isNotificationLevel(explicit)) return explicit;
  if (isPushKind(kind)) return DEFAULT_LEVEL_BY_KIND[kind];
  return "OTHER";
}

