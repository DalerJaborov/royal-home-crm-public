import { z } from "zod";
import { PROPERTY_TYPES } from "./enums.js";

/**
 * Разбор входящего звонка — контракт того, ЧЕМ обращение оказалось.
 *
 * ЭТО БОЛЬШЕ НЕ РАБОЧЕЕ МЕСТО ЧЕЛОВЕКА (решение владельца 18.08.2026): роль
 * оператора входящих и окно разбора удалены целиком, звонок разбирает сама CRM по
 * расшифровке разговора (apps/api/src/lib/telephony/autoLeadFromCall.ts →
 * qualifyIncomingCall). Схема осталась ровно потому, что она и есть описание
 * результата разбора: автоматика заполняет те же поля и проверяется теми же
 * правилами, что заполнял оператор.
 *
 * Тип живёт в общем пакете, потому что этими же полями размечен ответ модели, а
 * пара «сервер + модель» с двумя копиями одного контракта расходится молча.
 */

/**
 * Итог разбора. Всё, кроме типа обращения, необязательно НАМЕРЕННО: разговор
 * обрывается, человек не всё рассказывает, и записанное наполовину лучше не
 * записанного вовсе.
 */
export const qualifyIncomingCallSchema = z.object({
  /**
   * Кем оказался звонящий — единственное обязательное поле.
   *
   * IRRELEVANT — «не по делу»: курьер, реклама, ошиблись номером. Это НЕ то же
   * самое, что OTHER: аренда, работа и коммерция — настоящие обращения, их смотрит
   * руководство в «Прочих обращениях», и карточка там нужна. У «не по делу»
   * карточки быть не должно вовсе — иначе раздел «Прочие обращения» за месяц
   * превращается в список курьеров, и его перестают открывать.
   */
  kind: z.enum(["BUYER", "SELLER", "OTHER", "IRRELEVANT"]),
  /** Настоящее имя вместо заглушки «Входящий +992…». */
  fullName: z.string().trim().min(2).max(120).optional(),
  /** Что человек хочет — своими словами из разговора. */
  requirementsNotes: z.string().trim().max(2000).optional(),
  budgetMin: z.number().int().min(0).max(100_000_000).optional(),
  budgetMax: z.number().int().min(0).max(100_000_000).optional(),
  desiredDistrictId: z.guid().optional(),
  desiredRooms: z.number().int().min(1).max(20).optional(),
  /// Тип объекта — его человек называет мимоходом, и заполняет это поле
  /// автоматический разбор разговора (см. api/src/lib/telephony/autoLeadFromCall.ts).
  desiredType: z.enum(PROPERTY_TYPES).optional(),
  /// Объект, о котором зашла речь — адрес/ЖК/номер/ссылка как услышал разбор
  /// (Пачка 1 п.4, 11.09.2026). Сопоставление со справочником делает
  /// resolveCallPropertyHint, не модель — здесь просто сырая строка.
  propertyHint: z.string().trim().min(2).max(200).optional(),
});

export type QualifyIncomingCallInput = z.infer<typeof qualifyIncomingCallSchema>;

export interface QualifyIncomingCallResult {
  /** null — звонок помечен «не по делу»: карточки у него больше нет. */
  clientId: string | null;
  clientShortId: number | null;
  /** Кому ушёл лид. null — распределение выключено, режим «Вручную», либо тип
   *  «Другое»/«Не по делу»: такие обращения агентам не раздаются вовсе. */
  assignedAgentName: string | null;
  /** Карточка, заведённая этим звонком, удалена как ненужная. */
  clientRemoved?: boolean;
}

/**
 * Сколько секунд днём звонит оператор, прежде чем трубку возьмёт консультант
 * (режим «если оператор не взял»). Константа с 01.11.2026 (значение прода), раньше —
 * Settings.liveVoiceInboundWaitSeconds. Одно место на сервер (станция получает
 * его через lib/telephony/failoverSync.ts) и экран (подпись к режиму).
 */
export const LIVE_VOICE_INBOUND_WAIT_SECONDS = 30;
