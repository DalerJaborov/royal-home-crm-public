/**
 * ГЕО-ТЕКСТ — ОДНО ПРАВИЛО ДЛЯ СЕРВЕРА И САЙТА (перенесено из
 * apps/api/src/lib/geoNormalize.ts 29.09.2026). Сайт сверяет район из разбора
 * касания с той же точностью, что сервер: «Шоҳмансур» и «Шохмансур», «Sino» и
 * «Сино» — один район. Две копии разъехались бы молча (CLAUDE.md, «Одно правило —
 * одно место»), поэтому функции живут здесь, а сервер их переизлучает.
 */

/**
 * НОРМАЛИЗАЦИЯ ГЕО-ТЕКСТА — единая функция для словаря синонимов (12.09.2026,
 * docs/geo-match-plan-12-09.md, блок B, дополнение владельца).
 *
 * И импорт (`apps/api/prisma/scripts/import-geo.ts`, генерирует варианты в GeoAlias.normalized)
 * и поиск (`apps/api/src/lib/geoResolve.ts`, ищет по тому же полю) ОБЯЗАНЫ звать эту функцию,
 * а не свою копию — иначе написание разъедется молча, ровно как уже разъехались
 * площадь и этаж в двух копиях фильтра подбора (план, раздел D4).
 *
 * Что делает: нижний регистр, `ё`→`е`, пунктуация и кавычки — в пробел,
 * пробелы схлопываются и обрезаются. Раскладка и транслитерация НЕ решаются
 * здесь — это другая задача (см. lib/searchTokens.ts для похожего, но не
 * тождественного прецедента: там раскладка и порядок слов, здесь только
 * форма написания одного и того же слова).
 */
export function normalizeGeoText(input: string): string {
  return input
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[«»"'`.,;:!?()/\\_+№]/g, " ")
    .replace(/-/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * ТАДЖИКСКИЕ БУКВЫ К РУССКИМ БЛИЗНЕЦАМ (20.09.2026).
 *
 * Одно и то же место пишут и «Роҳат», и «Рохат»; и «Деҳотӣ», и «Дехоти». В
 * купленном слое города оба написания встречаются вперемешку: русское — в
 * «Названии», таджикское — в «Названии (тадж.)» и в синонимах. Без свёртки бот
 * не узнаёт место, если клиент написал его не той раскладкой, а именно так
 * клиенты и пишут.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ЧАСТЬ `normalizeGeoText`. Та формирует
 * `GeoAlias.normalized`, и её результат ЛЕЖИТ В БАЗЕ, записанный импортом слоя.
 * Поменяй её — и сохранённые строки разойдутся с вычисляемыми, пока слой не
 * переимпортируют: поиск начнёт молча промахиваться. Поэтому свёртка
 * применяется В ПАМЯТИ к обеим сторонам сравнения (`ai/geoMentions.ts`,
 * `ai/folkPlaces.ts`) и ничего в базе не меняет.
 */
const TAJIK_FOLD: Record<string, string> = { "ғ": "г", "ӣ": "и", "қ": "к", "ӯ": "у", "ҳ": "х", "ҷ": "ч" };

export function foldTajikLetters(input: string): string {
  // «дж» (русское написание «Джавонон») и «ҷ/j» (таджикское «Ҷавонон», латинское
  // «Javonon») — одна буква; без этого 98 улиц и 2 105 домов справочника не
  // совпадали между написаниями (аудит 02.10.2026).
  return input.replace(/[ғӣқӯҳҷ]/g, (c) => TAJIK_FOLD[c] ?? c).replace(/дж/g, "ч");
}

/**
 * ЛАТИНИЦА В КИРИЛЛИЦУ — одно место для поиска (`lib/searchTokens.ts`) и для
 * сравнения мест (`geoMatchKey`). Слово пишут латиницей («Rudaki», «Sino»,
 * «Shohmansur»). Диграфы идут первыми — иначе «sh» разобралось бы как «с» + «х».
 * Спорные буквы (c, q, w, x) не трогаем: пусть вариант лучше не найдёт ничего,
 * чем найдёт чужое. Ждёт строку в нижнем регистре; не-латиница проходит как есть.
 */
const TRANSLIT_PAIRS: Array<[string, string]> = [
  ["dzh", "ҷ"], ["shch", "щ"], ["sh", "ш"], ["ch", "ч"], ["zh", "ж"], ["kh", "х"], ["ts", "ц"],
  ["yo", "ё"], ["yu", "ю"], ["ya", "я"],
  ["a", "а"], ["b", "б"], ["v", "в"], ["g", "г"], ["d", "д"], ["e", "е"], ["z", "з"],
  ["i", "и"], ["j", "ҷ"], ["y", "й"], ["k", "к"], ["l", "л"], ["m", "м"], ["n", "н"],
  ["o", "о"], ["p", "п"], ["r", "р"], ["s", "с"], ["t", "т"], ["u", "у"], ["f", "ф"],
  ["h", "ҳ"],
];

export function transliterateLatin(value: string): string {
  if (!/[a-z]/.test(value)) return value;
  let rest = value;
  let out = "";
  outer: while (rest.length > 0) {
    for (const [latin, cyrillic] of TRANSLIT_PAIRS) {
      if (rest.startsWith(latin)) {
        out += cyrillic;
        rest = rest.slice(latin.length);
        continue outer;
      }
    }
    out += rest[0];
    rest = rest.slice(1);
  }
  return out;
}

/** Нормализация для сравнения в памяти: та же форма записи, латиница в
 *  кириллицу (29.09.2026: «Shohmansur», «Dodo» — клиент пишет и так) и
 *  свёрнутые таджикские буквы. Обе стороны сравнения обязаны звать именно её. */
export function geoMatchKey(input: string): string {
  // Латиница — ДО normalizeGeoText: «yo» даёт «ё», а оно обязано стать «е», как у
  // кириллического написания («хиёбони» и «khiyoboni» — один ключ «хиебони»).
  return foldTajikLetters(normalizeGeoText(transliterateLatin(input.toLowerCase())));
}
