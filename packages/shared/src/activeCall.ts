/**
 * Живой звонок — то, что видит агент на экране вызова.
 *
 * Здесь описан КОНТРАКТ ОТВЕТА `GET /me/active-call`, а не внутреннее состояние
 * звонка: у сервера в памяти лежит больше (внутренний номер агента, телефон
 * клиента, id записи в хронологии), и наружу это не уходит — телефон клиента
 * агенту закрыт (см. lib/clientPhone.ts).
 *
 * Пока тип был объявлен дважды — в apps/api/src/lib/telephony/callTracker.ts и в
 * apps/web/src/hooks/useActiveCall.ts — копии успели разъехаться составом полей, и
 * ничто не мешало серверу перестать слать поле, которое экран продолжает читать:
 * компилятор в этой паре молчит, а замечает такое живой агент посреди разговора.
 */

/** Стадия звонка. Меняется событиями самой АТС (см. ariEvents.ts). */
export type CallState =
  /** Станция звонит самому агенту — на мобильный или софтфон. */
  | "ringing_agent"
  /** Агент снял трубку, станция набирает клиента. */
  | "ringing_client"
  /** Клиент ответил — идёт разговор. */
  | "talking"
  /** Звонок завершён по любой причине. */
  | "ended";

export interface ActiveCallView {
  channelId: string;
  clientId: string;
  /** Короткий номер карточки — по нему открывается клиент. */
  clientShortId: number;
  clientName: string;
  /** Номер, на который станция звонит самому сотруднику: если вызов ушёл не туда,
   *  это видно сразу, а не из журнала станции. */
  dialingTo: string;
  state: CallState;
  /** ISO-строки: JSON дат не знает, а на экране они и нужны как время. */
  startedAt: string;
  answeredAt: string | null;
  /** Секунды разговора считает сервер — у телефона в кармане агента и у браузера
   *  время расходится, а спорить о длительности разговора никому не полезно. */
  talkSeconds: number;
  /** Итог завершённого звонка: «Поговорили 1:12» или «Клиент не ответил». */
  outcome: string | null;
  /**
   * Агент сам нажал «Отменить», и разговор так и не начался (см. cancelledByAgent
   * в callTracker.ts). Нужно отдельным полем — иначе экран звонка кладёт отмену в
   * ту же корзину, что и «клиент не взял трубку», и текст под ней врёт: якобы
   * клиент не ответил, хотя решение принял агент.
   */
  cancelled: boolean;
  /**
   * Дошёл ли вызов до телефона клиента (см. clientRang в callTracker.ts) — нужно
   * экрану звонка, чтобы честно написать, осталась ли отмена в истории карточки:
   * если телефон клиента не звонил, запись в хронологии не заводится вовсе.
   */
  clientRang: boolean;
}

/**
 * Короче этого разговор не разбирается — и это ОКОНЧАТЕЛЬНО, а не «ещё готовится».
 *
 * Порог живёт в общем пакете, потому что нужен обеим сторонам: сервер по нему решает,
 * звать ли модель (ai/callAnalysis.ts), а раздел «Звонки» — что написать в строке.
 * Пока константа была только на сервере, интерфейс писал «Разбор ещё готовится» на
 * разговоре, разбора которого не будет никогда: владелец 10.08.2026 справедливо
 * решил, что расшифровка сломалась, и полез искать поломку там, где её нет.
 *
 * Восемьдесят знаков, а не двести, как было: «Договорились, приеду сегодня в шесть»
 * — это двадцать секунд разговора и главное событие сделки. Двести знаков выкидывали
 * из разбора ровно такие звонки (у владельца выпали оба коротких: 0:18 и 0:21).
 */
export const MIN_ANALYZED_TRANSCRIPT_CHARS = 80;

/**
 * Стадии конвейера «запись → расшифровка → карточка», пока он ещё не закончил.
 *
 * ЗАЧЕМ. До 15.08.2026 человек видел одну и ту же строку «Разговор ещё готовится»
 * от момента отбоя до готового разбора — минуту это, три минуты или пятнадцать
 * (длинный разговор режется на части и переводится), с экрана было не понять.
 * Владелец: «человек не должен просто сидеть и ждать секунды, пока это всё
 * расшифровывается» — не про скорость самого конвейера, а про то, что происходящее
 * нужно ВИДЕТЬ. Список стадий живёт в общем пакете по тому же принципу, что и
 * порог выше: сервер пишет ровно эти строки в Interaction.transcriptionStage
 * (валидируя, как suggestedOutcome у CallAnalysis — колонка обычная строка, а не
 * тип БД, чтобы новую стадию можно было завести без миграции), интерфейс подписывает
 * их по-русски и снимает поллингом, пока стадия не станет пустой.
 *
 * Пустая стадия (null) означает «сейчас конвейер этим разговором не занят» — то есть
 * либо ещё не начинал (запись только что кладётся на станцию), либо уже закончил
 * (транскрипт/разбор на месте), либо сорвался и ждёт своей очереди повтора
 * (см. lib/telephony/callRecordings.ts, runTranscriptionRetries). Различать «ещё не
 * начал» и «уже закончил» стадия не обязана — это делают уже существующие признаки
 * hasRecording/transcript/analysis.
 */
export const CALL_TRANSCRIPTION_STAGES = [
  /** Ищем файл записи в каталоге станции — сама станция ничего не сообщает,
   *  поиск идёт с паузами и может занять до полуминуты (см. findRecording). */
  "SEARCHING",
  /** Файл найден, но расшифровывается другой разговор раньше этого — конвейер
   *  строго последовательный (общий ключ Gemini на всё агентство), и без этой
   *  стадии второй подряд звонок выглядел бы так, будто про него забыли. */
  "QUEUED",
  /** Идёт сама расшифровка. У длинного разговора несколько частей —
   *  transcriptionProgress несёт долю готовых (0–100). */
  "TRANSCRIBING",
  /** Расшифровка готова, переводим на русский (если разговор был по-таджикски). */
  "TRANSLATING",
  /** Считаем разбор качества: шаги, возражения, совет агенту. */
  "ANALYZING",
] as const;
export type CallTranscriptionStage = (typeof CALL_TRANSCRIPTION_STAGES)[number];

export function isCallTranscriptionStage(value: unknown): value is CallTranscriptionStage {
  return typeof value === "string" && (CALL_TRANSCRIPTION_STAGES as readonly string[]).includes(value);
}

