/**
 * У объекта вписана ссылка на ролик РУКАМИ — значит, ролик когда-то вышел, даже если
 * список сетей `publishedChannels` пуст (07.10.2026, ОБ-000082).
 *
 * Старые объекты выкладывали вручную до конвейера автопубликации: `publishedChannels`
 * у них пуст, а единственный след — адрес в поле `instagramUrl`. Ссылка на сам
 * Instagram уже превращается в канал INSTAGRAM (миграция 05.10.2026 и запись при
 * правке карточки), а вот `t.me/...`, YouTube, TikTok и любой другой адрес в этом
 * поле — нет: правило владельца 13.08.2026 нарочно не считает их Instagram, и канал
 * им выдумывать нельзя (записанный TELEGRAM заставил бы публикацию пропустить
 * Telegram, а снять тот пост CRM нечем — id сообщения не сохранён).
 *
 * Но карточка и сервер читали только список сетей и считали такой объект «ни разу не
 * бывшим у монтажёра»: блок «Ролик и соцсети» сворачивался до одних историй, а сервер
 * на «Вернуть монтажёру» отвечал «Объект ещё не был у монтажёра». Одно правило здесь —
 * чтобы карточка и сервер не разошлись.
 */
export function hasManualVideoLink(instagramUrl: string | null | undefined): boolean {
  return !!instagramUrl && instagramUrl.trim().length > 0;
}

/**
 * У объекта УЖЕ был этап ролика — по любому из следов, а не только по списку сетей
 * (07.10.2026, решение владельца: «чтобы во всех объектах, старых и новых, были все
 * кнопки»). Следы: готовый ролик, отметка сети, ссылка, вписанная руками, или сам статус —
 * объект в продаже (AVAILABLE/RESERVED) не мог выйти из конвейера мимо ролика, а старые,
 * заведённые до конвейера, не хранят ни сетей, ни файла. Объект ещё в конвейере
 * (фото, видео, монтаж) следов не имеет — там «Вернуть монтажёру» не к месту.
 * Одно правило и для карточки, и для сервера.
 */
export function hasVideoHistory(property: {
  status?: string | null;
  instagramUrl?: string | null;
  publishedChannels?: readonly string[] | null;
  videoHandoffFinalPath?: string | null;
}): boolean {
  return (
    !!property.videoHandoffFinalPath ||
    (property.publishedChannels?.length ?? 0) > 0 ||
    hasManualVideoLink(property.instagramUrl) ||
    property.status === "AVAILABLE" ||
    property.status === "RESERVED"
  );
}
