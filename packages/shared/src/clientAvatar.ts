/**
 * ЗАПАСНОЙ АВАТАР КЛИЕНТА — ОДНО ОПИСАНИЕ ВИДА НА CRM И НА ПУШ.
 *
 * Настоящее фото профиля (`Client.avatarUrl`) забирается из Instagram/Messenger/Telegram
 * (см. apps/api/src/lib/clientAvatar.ts) и всегда главнее. Но у WhatsApp фото нет вовсе
 * (Cloud API его не отдаёт), у нового клиента оно ещё не скачано, а у заведённого руками
 * его не будет никогда. Раньше в этих случаях агент видел серый кружок или ничего —
 * то есть большинство клиентов выглядели одинаково.
 *
 * Просьба владельца 19.08.2026 дословно: «хочу визуально сделать всё понятным» — по
 * аватару должно быть видно, кто это, без открывания карточки.
 *
 * ЗНАЧОК «ПОКУПАТЕЛЬ/ПРОДАВЕЦ» (домик/ключ) БЫЛ ТРЕТЬИМ СЛОЕМ ЗДЕСЬ — УБРАН
 * ЦЕЛИКОМ 21.09.2026 (решение владельца: агенты путают клиентов, у которых
 * значок совпадает, а роль в разговоре другая; тип виден текстом там, где
 * нужен — вкладки/фильтры, а не значком на аватаре). Historically описывался
 * как «домик покупателю, ключ продавцу» — если вид снова понадобится, контуры
 * значков можно найти в истории git (`git log -p -- packages/shared/src/clientAvatar.ts`),
 * заново их не рисовать.
 *
 * Вид собран из двух слоёв, каждый со своим источником правды:
 *  1. КРУЖОК С ФИГУРКОЙ ЧЕЛОВЕКА (lucide `User`, одна и та же на всех), цвет —
 *     детерминированно по хэшу имени (палитра ниже). Никакого Math.random: один и тот
 *     же клиент обязан выглядеть одинаково в списке, в карточке, в чате и в шторке
 *     уведомлений на телефоне.
 *
 *     Двух отвергнутых редакций стоит держать в голове, чтобы не пойти по кругу:
 *     инициалы (владелец: не то) и собственноручно нарисованные силуэты с полом в
 *     форме — каре, разная ширина плеч (владелец, увидев их на экране: чужеродно
 *     рядом с остальными значками CRM). Итог: значок берём у lucide, различаем
 *     клиентов цветом.
 *
 *     Практическое следствие: ни буквы, ни форма фигурки больше не различают двух
 *     клиентов — всю работу делает цвет, поэтому палитра ниже расширена до восьми
 *     тонов, чтобы совпадения в одном списке были реже.
 *  2. ПОЛ, угаданный по имени, — ТОЛЬКО цветом тонкого кольца вокруг кружка, форма
 *     фигурки от него не зависит. Единственный НЕточный слой, поэтому:
 *     · словарь ниже маленький и правится без миграции — в базе пол не хранится;
 *     · имя не нашлось — кольца просто нет, и это выглядит как задумано, а не как
 *       пропавшая картинка; «не нашли» НИКОГДА не означает «значит, мужчина»;
 *     · дальше аватара догадка не уходит: ни поля в форме, ни фильтра, ни отчёта.
 *       Это украшение, а не данные, и product-у про пол клиента знать нечего.
 *
 * Модуль лежит в shared намеренно: apps/web рисует это React-ом с Tailwind, apps/api —
 * строкой SVG для картинки в пуше. Два разных способа рисовать, но палитра, инициалы,
 * хэш, словарь и контуры значков обязаны совпадать до символа, иначе один и тот же
 * клиент в CRM и в шторке телефона выглядел бы двумя разными людьми.
 */

/* ────────────────────────────── палитра ────────────────────────────── */

/** Тон аватара: пастельная подложка + насыщенный текст того же оттенка. */
export interface ClientAvatarTone {
  /** Заливка кружка. */
  bg: string;
  /** Цвет фигурки. */
  fg: string;
}

/**
 * Восемь тонов — ровно столько, чтобы соседние строки списка почти не повторялись,
 * но палитра осталась спокойной: это фон под именем, а не набор маркеров. Восемь, а не
 * шесть, потому что одинаковая для всех фигурка (в отличие от отвергнутых инициалов)
 * двух разных клиентов не различает — вся работа по различению легла на цвет.
 *
 * Значения заданы явными hex, а НЕ токенами темы (`--c-*`), и это осознанно: те же
 * цвета выводит сервер в PNG для шторки уведомлений, где никаких CSS-переменных нет.
 * Пара «бледная подложка + тёмный текст» читается и на светлой, и на тёмной теме —
 * кружок везде остаётся собственной плашкой, а не подкрашивается фоном страницы.
 */
export const CLIENT_AVATAR_TONES: readonly ClientAvatarTone[] = [
  { bg: "#e3e9fd", fg: "#33499b" }, // индиго
  { bg: "#fde3ec", fg: "#a33560" }, // роза
  { bg: "#dcf0fb", fg: "#16628c" }, // небо
  { bg: "#ddf3e4", fg: "#2b6b44" }, // зелень
  { bg: "#fdeed6", fg: "#8c5a1a" }, // янтарь
  { bg: "#ece2fb", fg: "#5a3a99" }, // фиалка
  { bg: "#d9f0ef", fg: "#1b6b66" }, // бирюза
  { bg: "#fae3df", fg: "#9c4436" }, // терракота
] as const;

/**
 * Устойчивый выбор тона по строке. Хэш простой (31-й полином) — от него нужна не
 * криптостойкость, а воспроизводимость: одно имя обязано давать один цвет всегда и
 * везде, включая другой процесс на другой машине.
 *
 * Сеем ИМЕНЕМ, а не id: имя видно человеку, и «Далер всегда синий» — это то, за что
 * глаз цепляется в списке. По id цвет был бы столь же стабильным, но бессмысленным.
 */
export function clientAvatarTone(seed: string | null | undefined): ClientAvatarTone {
  const s = (seed ?? "").trim() || "?";
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) % 100003;
  return CLIENT_AVATAR_TONES[h % CLIENT_AVATAR_TONES.length]!;
}

