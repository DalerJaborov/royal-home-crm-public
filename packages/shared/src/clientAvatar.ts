const GENDER_BY_NAME: ReadonlyMap<string, GuessedGender> = new Map([
  ...MALE_NAMES.map((n) => [n, "male"] as const),
  ...FEMALE_NAMES.map((n) => [n, "female"] as const),
]);

/**
 * Пол по ПЕРВОМУ слову имени. Не нашли — `null`, и это нормальный, ожидаемый ответ:
 * фамилия вперёд, латиница, «Клиент из Instagram», прозвище — всё сюда попадает.
 *
 * Никаких эвристик по окончанию («-ов мужчина, -ова женщина»): на именах вроде
 * «Лола», «Наврузова» и на любом нерусском написании они врут, а ошибиться в поле
 * человека неприятнее, чем не показать украшение.
 */
export function guessGenderFromName(fullName: string | null | undefined): GuessedGender | null {
  const first = (fullName ?? "").trim().split(/\s+/)[0];
  if (!first) return null;
  const key = first.toLowerCase().replace(/ё/g, "е");
  return GENDER_BY_NAME.get(key) ?? null;
}

