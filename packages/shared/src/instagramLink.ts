/**
 * Ведёт ли ссылка на сам Instagram.
 *
 * Проверка нарочно по началу строки: `instagram.com.чужойсайт.ru` начинается с тех
 * же букв, но нашей публикацией не является.
 */
export function isInstagramLink(url: string | undefined | null): url is string {
  if (!url) return false;
  return /^https?:\/\/(?:www\.)?instagram\.com\//i.test(url.trim());
}

/**
 * Условие того же правила для запроса в базу — для мест, где перебрать объекты в
 * памяти нельзя (очередь монтажёра листает каталог постранично).
 *
 * Слабее `isInstagramLink`: проверяет вхождение подстроки, а не начало адреса,
 * поэтому `https://чужойсайт.ru/instagram.com/x` для базы сойдёт за нашу ссылку.
 * Для ФИЛЬТРА это допустимо — он показывает рабочую очередь, а не пускает объект в
 * продажу. Решения принимает `isInstagramLink`, и подделать их так нельзя.
 */
export const INSTAGRAM_LINK_CONTAINS = "instagram.com/";

/**
 * Извлекает shortcode из ссылки на публикацию Instagram и возвращает
 * нормализованный URL: https://www.instagram.com/<тип>/<CODE>/.
 *
 * Поддерживает форматы: /reel/, /reels/, /p/, /tv/ — с www или без,
 * с query-параметрами (?igsh=...) и без. Возвращает null, если строка
 * не содержит распознаваемого shortcode.
 *
 * Тип публикации СОХРАНЯЕТСЯ (/reels/ → /reel/, остальное как есть):
 * до 03.09.2026 всё переписывалось в /reel/, а фото-пост или карусель по
 * адресу /reel/<код>/ Instagram открывать не обязан — клиент получал бы
 * в директ битую ссылку. Чистятся только домен, www и query.
 *
 * Используется в Zod-схемах (трансформация входа) и в backfill-скрипте
 * для приведения ссылок к единому каноническому виду.
 */
const SHORTCODE_RE = /instagram\.com\/(reel|reels|p|tv)\/([A-Za-z0-9_-]+)/i;

export function normalizeInstagramUrl(url: string | undefined | null): string | null {
  if (!url) return null;
  const match = url.trim().match(SHORTCODE_RE);
  if (!match) return null;
  const type = match[1].toLowerCase() === "reels" ? "reel" : match[1].toLowerCase();
  return `https://www.instagram.com/${type}/${match[2]}/`;
}

/**
 * Валидатор для Zod: принимает только строки, из которых удаётся извлечь
 * shortcode Instagram. Сообщение об ошибке — на русском, как и все остальные
 * сообщения схем в этом проекте.
 */
export function isValidInstagramPostUrl(url: string): boolean {
  return SHORTCODE_RE.test(url.trim());
}
