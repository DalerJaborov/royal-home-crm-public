export type PultModuleId = (typeof PULT_MODULES)[number]["id"];

const PULT_MODULE_ID_SET: ReadonlySet<string> = new Set(PULT_MODULES.map((m) => m.id));

export function isPultModuleId(value: string): value is PultModuleId {
  return PULT_MODULE_ID_SET.has(value);
}

export const pultModulePatchSchema = z.object({ enabled: z.boolean() });
export type PultModulePatch = z.infer<typeof pultModulePatchSchema>;

/** Строка ответа GET /dashboard/modules. */
export interface PultModuleState extends PultModuleDef {
  id: PultModuleId;
  enabled: boolean;
  updatedAt: string | null;
  updatedBy: { id: string; fullName: string } | null;
}
