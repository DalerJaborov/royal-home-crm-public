/**
 * Реестр выключаемых модулей пульта директора (docs/pult-direktora-audit-02-09-2026.md §4).
 *
 * Требование владельца (02.09.2026): любую часть пульта можно выключить из настроек,
 * и выключенная часть не должна ничего считать на сервере и не тратить токены ИИ.
 * Поэтому модуль — не «спрятать плитку», а «не строить секцию и не запускать тик».
 *
 * Три рода модулей:
 *  - section — секция экрана /mission-control: выключена → ключ ОТСУТСТВУЕТ в ответе
 *    агрегатора и не вычисляется; фронт рисует только присутствующие ключи;
 *  - ai — фоновое задание или запрос к модели, тратящий токены: выключен → крон-тик
 *    пропускается с отметкой в пульсе, роут отвечает 409;
 *  - preference — чистая настройка клиента, ничего не строит и не тратит токены на
 *    сервере (пример — «sound»: тихий сигнал пульта). Хранится в том же реестре и
 *    том же тумблере «Настроить пульт», чтобы не заводить отдельный механизм
 *    настроек ради одного булева флага, но НЕ участвует в gating mission-control:
 *    сервер не строит по её id никакой секции ответа.
 *
 * Тумблер плитки НАРОЧНО не гасит ночные задания ИИ (в аудите §4 они были привязаны к
 * плиткам): оценка клиентов и разбор звонков нужны и другим разделам CRM, а не только
 * пульту — гасить их через плитку было бы неожиданным побочным действием. У каждого
 * задания свой честный тумблер с подписью «тратит токены».
 */
export type PultModuleKind = "section" | "ai" | "preference";

export interface PultModuleDef {
  id: string;
  kind: PultModuleKind;
  label: string;
  /** Что происходит ПРИ ВКЛЮЧЁННОМ модуле (правило подписи тумблера от 11.08.2026). */
  onHint: string;
  /** Что происходит ПРИ ВЫКЛЮЧЕННОМ модуле. */
  offHint: string;
}

