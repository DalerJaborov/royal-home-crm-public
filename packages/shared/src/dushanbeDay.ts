/**
 * ГРАНИЦА СУТОК ПО ДУШАНБЕ: ОДНО ПРАВИЛО — ОДНО МЕСТО.
 *
 * `dushanbeDayKey` был написан дважды и РАЗНЫМИ способами: на сервере через
 * сдвиг времени и `toISOString`, на сайте через `toLocaleDateString("en-CA")`.
 * Ответы сходятся — проверено перебором 200 000 моментов, и сходятся они
 * потому, что в Таджикистане нет перевода часов, сдвиг всегда ровно +5. Но это
 * два независимых куска кода под одним именем: правку одного второй не узнает.
 *
 * Цена расхождения — весь суточный учёт: дневной бюджет ИИ, суточные сводки,
 * «за сегодня» в отчётах. Ошибка в границе суток не падает и не краснеет, она
 * просто показывает не то число, и обнаруживают её по несходящимся итогам.
 *
 * Про часовой пояс в этом проекте есть отдельное правило (CLAUDE.md): границы
 * суток и месяцев — никогда через `setHours`, контейнер живёт в UTC.
 */

/** Душанбе — UTC+5 круглый год, перевода часов в Таджикистане нет. */
export const DUSHANBE_OFFSET_MS = 5 * 60 * 60 * 1000;

/**
 * Ключ суток по Душанбе в виде «ГГГГ-ММ-ДД».
 *
 * Формат выбран не случайно: такая строка сравнивается и сортируется как
 * обычный текст, без разбора в дату, — поэтому годится и в ключ агрегата, и в
 * `groupBy`, и в имя счётчика.
 */
export function dushanbeDayKey(value: Date | string | number = new Date()): string {
  const at = value instanceof Date ? value : new Date(value);
  return new Date(at.getTime() + DUSHANBE_OFFSET_MS).toISOString().slice(0, 10);
}

/**
 * Час по Душанбе, 0-23. Был написан дважды (сервер — сдвигом времени в
 * статистике роликов, сайт — через Intl в пульте директора); сторож
 * `audit:rules` нашёл двойника 24.09.2026, правило переехало сюда.
 */
export function dushanbeHour(value: Date | string | number = new Date()): number {
  const at = value instanceof Date ? value : new Date(value);
  return new Date(at.getTime() + DUSHANBE_OFFSET_MS).getUTCHours();
}
