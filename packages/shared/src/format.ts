import type { ClientKind, PropertyType } from "./enums.js";

/** Короткое название типа для авто-заголовка объекта (не путать с PROPERTY_TYPE_LABELS). */
const TYPE_TITLE_WORD: Record<PropertyType, string> = {
  APARTMENT: "Квартира",
  HOUSE: "Дом",
  COMMERCIAL: "Коммерция",
  LAND: "Участок",
};

/**
 * Собирает название объекта из его параметров — единый формат для CRM и сайта,
 * чтобы заголовки были одинаковыми и не вводились руками. Примеры:
 *   квартира с комнатами → «2-комн · Рудаки»
 *   квартира без комнат   → «Квартира · Рудаки»
 *   дом/коммерция/участок → «Дом · Рудаки»
 * Без района — просто «2-комн» / «Дом».
 */
export function buildPropertyTitle(input: {
  type: PropertyType;
  rooms?: number | null;
  districtName?: string | null;
}): string {
  const head =
    input.type === "APARTMENT" && input.rooms ? `${input.rooms}-комн` : TYPE_TITLE_WORD[input.type];
  const district = input.districtName?.trim();
  return district ? `${head} · ${district}` : head;
}

/**
 * ПРЕФИКС НОМЕРА КАРТОЧКИ — ПО ТЕКУЩЕМУ ТИПУ КЛИЕНТА (владелец 30.08.2026:
 * «у клиентов должно быть КЛ, у продавцов ПР и так далее, чтобы везде
 * соответствовало»). 31.08.2026 владелец поправил себя: изначальная жалоба
 * (docs/razbor-zhaloby-admina-31-08-2026.md) просила «ПК» (покупатель) для
 * этого типа — переименовано с «КЛ» на «ПК» тем же днём
 * (docs/pk-vs-kl-labeling-analysis-31-08-2026.md).
 *
 * Счётчик при этом остаётся СКВОЗНЫМ (один Client.shortId на всех): в нумерации
 * каждого префикса будут пропуски — ПК-000227 и ПР-000229 без ПР-000228 — и это
 * ожидаемо, а не ошибка. Отдельные счётчики на тип означали бы, что номер
 * перестаёт быть уникальным ключом карточки и меняется при смене типа, а тип
 * меняется на живых карточках (см. services/leads/intake.ts, повторное
 * обращение). Здесь меняется только буквенная приставка.
 */
const CLIENT_KIND_PREFIX: Record<ClientKind, string> = {
  BUYER: "ПК",
  SELLER: "ПР",
  OTHER: "ПО",
};

/** Подписи типа клиента — один словарь на веб и на тексты уведомлений API. */
export const CLIENT_KIND_LABELS: Record<ClientKind, string> = {
  BUYER: "Покупатель",
  SELLER: "Продавец",
  OTHER: "Прочее обращение",
};

/**
 * Подпись типа клиента С УЧЁТОМ dualIntent (владелец 06.09.2026, разбор слепых
 * зон п.4) — «Продавец и покупатель» вместо одиночного «Продавец»/«Покупатель»,
 * когда у клиента есть обе стороны одновременно (kind остаётся текущей активной
 * стороной, dualIntent — просто отметка «есть и вторая тоже», см. Client.dualIntent
 * в schema.prisma). OTHER не роль — dualIntent для него не показываем.
 */
export function clientKindLabel(client: { kind?: ClientKind | null; dualIntent?: boolean | null }): string {
  const base = client.kind ? CLIENT_KIND_LABELS[client.kind] : "";
  if (!client.dualIntent || client.kind === "OTHER" || !client.kind) return base;
  return "Продавец и покупатель";
}

/**
 * Человекочитаемый номер карточки — «ПК-000042».
 * Источник — числовой Client.shortId/Property.shortId (он же в URL, /clients/1042),
 * здесь он только форматируется для показа человеку.
 */
export function formatShortCode(prefix: string, shortId: number): string {
  return `${prefix}-${String(shortId).padStart(6, "0")}`;
}

/**
 * Номер карточки клиента. `kind` не необязателен «для удобства»: у части
 * фронтовых типов он объявлен опциональным (apps/web/src/types.ts, Client.kind),
 * и там, где тип не пришёл, честнее показать прежний «ПК», чем упасть. Везде, где
 * тип под рукой есть, его ОБЯЗАТЕЛЬНО передавать — иначе продавец снова начнёт
 * показываться как «ПК».
 */
export function formatClientCode(shortId: number, kind?: ClientKind | null): string {
  return formatShortCode((kind && CLIENT_KIND_PREFIX[kind]) || "ПК", shortId);
}

/** Номер карточки объекта — «ОБ-000042». От типа клиента не зависит. */
export function formatPropertyCode(shortId: number): string {
  return formatShortCode("ОБ", shortId);
}

/**
 * Все префиксы номеров — и кириллицей, и латиницей той же раскладки.
 * «кл»/«kl» остаются рядом с новым «пк»/«pk» намеренно: до 31.08.2026 номер
 * покупателя показывался как «КЛ-000042» (переименовано в «ПК», см.
 * CLIENT_KIND_PREFIX выше и docs/pk-vs-kl-labeling-analysis-31-08-2026.md) —
 * старые скопированные/сохранённые номера с «КЛ-» должны продолжать находиться
 * поиском, а не тихо возвращать 0 результатов. Новые номера ВСЕГДА генерируются
 * с «ПК» (formatClientCode выше) — «кл» здесь только для разбора уже введённого.
 */
// Номер в том виде, в каком его печатает интерфейс и диктуют агенты (05.10.2026):
// «ОБ-000088», «№88», «ОБ №88», «#88», «ОБ- 88», «ОБ—88». Раньше разбирались только
// префикс и один дефис/пробел, и «№88» искался как слово.
const SHORT_CODE_PREFIX_RE = /^(?:(?:кл|пк|пр|по|об|kl|pk|pr|po|ob)[\s.\-–—]*)?[№#]?\s*/i;

/**
 * ИМЯ КЛИЕНТА С РОЛЬЮ ВПЕРЕДИ — «Покупатель Далер», «Продавец Пиров Махмуд»
 * (владелец 30.08.2026: «кто попадает в CRM — перед именем должно быть написано
 * Покупатель или Продавец, а далее его имя, если известно»).
 *
 * Одна функция на весь проект: и веб, и тексты уведомлений API. До неё роль была
 * подписана ровно на двух экранах из пятнадцати, и то отдельной колонкой.
 *
 * ГЛАВНАЯ ЛОВУШКА — РОЛЬ ДВАЖДЫ. У части карточек имени нет вовсе, и вместо него
 * в базе лежит заглушка, которую CRM сама и придумала: «Покупатель №1234»,
 * «Продавец №1234», «Входящий ***67», «Входящий +992…», «Клиент Instagram».
 * Наивная склейка давала бы «Покупатель Покупатель №1234» — ровно то, на чём уже
 * спотыкались вслух в телефонии (lib/telephony/whisperText.ts). Заглушку узнаём
 * по первому слову и заменяем её текущей ролью: роль берётся из `kind`, потому
 * что тип карточки меняется при повторном обращении, а заглушка в имени остаётся
 * от первого.
 *
 * Тип неизвестен — роль не выдумываем и возвращаем имя как есть: «Покупатель»
 * там, где карточка может оказаться продавцом, хуже, чем отсутствие подписи.
 */
const STUB_NAME_HEAD =
  /^(прочее обращение|обращение|покупатель|продавец|клиент|входящий|входящая|входящее|неизвестный|неизвестно|харидор|фурӯшанда|unknown|no ?name)(?=$|[^\p{L}])/iu;

/**
 * Роль ПЕРЕД ИМЕНЕМ — отдельно от CLIENT_KIND_LABELS: колонкой и плашкой «прочее
 * обращение» читается верно, а перед именем («Прочее обращение Фаррух») — нет.
 * Для OTHER берём нейтральное «Клиент»: не покупатель и не продавец, но человек.
 */
const CLIENT_NAME_ROLE: Record<ClientKind, string> = {
  BUYER: "Покупатель",
  SELLER: "Продавец",
  OTHER: "Клиент",
};

export function formatClientName(client: {
  kind?: ClientKind | null;
  fullName?: string | null;
  /** См. clientKindLabel выше и Client.dualIntent в schema.prisma. */
  dualIntent?: boolean | null;
}): string {
  const role =
    client.dualIntent && client.kind && client.kind !== "OTHER"
      ? "Продавец и покупатель"
      : client.kind
        ? CLIENT_NAME_ROLE[client.kind]
        : null;
  const name = (client.fullName ?? "").trim();
  if (!role) return name;
  if (!name) return role;

  const stub = STUB_NAME_HEAD.exec(name);
  if (!stub) return `${role} ${name}`;

  // Хвост заглушки — единственное, что в ней различает карточки: «№1234», «***67»,
  // «Instagram». Он и остаётся после роли; ничего больше с ним не делаем — ставить
  // хвост в скобки нельзя: настоящее имя тоже может начинаться со слова «Продавец»
  // («Продавец приёмки», живой пример из тестовых данных), и такое имя от такой
  // обработки разъезжалось бы.
  const tail = name.slice(stub[0].length).replace(/^[\s.,:;—–-]+/, "").trim();
  return tail ? `${role} ${tail}` : role;
}

/**
 * Разбирает поисковый запрос как НОМЕР карточки — «ПК-000042», «ПР-000042»,
 * «ПО-000042», «ОБ-000042», «42».
 *
 * ТЗ «Путь покупателя», п. 2: номер должен работать «в карточке; в поиске; в
 * списках; в истории». Форматирование (formatClientCode) живёт прямо над этим
 * разбором, в одном файле: префиксы обязаны совпадать между тем, что показываем,
 * и тем, что ищем, — иначе введённый глазами номер карточки не находится.
 *
 * Возвращает null, если это не номер: тогда поиск работает как раньше, по ФИО и
 * телефону. Префикс не проверяем на «ПК vs ОБ» — клиентов и объекты ищут разные
 * маршруты, и «ОБ-7», введённый в поиске клиентов, разумнее понять как номер 7,
 * чем не найти ничего.
 *
 * Латиница здесь не про английский интерфейс, а про раскладку: номер часто
 * набирают, не переключив клавиатуру, и «PR-000227» обязан искаться так же, как
 * «ПР-000227».
 */
export function parseShortCode(query: string): number | null {
  const cleaned = query.trim().replace(SHORT_CODE_PREFIX_RE, "");
  if (!/^\d{1,9}$/.test(cleaned)) return null;
  const n = Number(cleaned);
  return Number.isSafeInteger(n) && n > 0 ? n : null;
}

/** Склонение русских существительных по числу: pluralizeRu(0, ["задача","задачи","задач"]) → "задач". */
export function pluralizeRu(n: number, [one, few, many]: [string, string, string]) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
